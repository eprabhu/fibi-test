DELIMITER $$
CREATE  PROCEDURE `MIGRATE_AREA_RANK_FOR_NULL`()
BEGIN
    DECLARE LS_MODULE_ID DECIMAL(20,2);
    DECLARE DONE INT DEFAULT FALSE;
     DECLARE CUR_AWARD_AREA_OF_RESEARCH CURSOR FOR SELECT DISTINCT `AWARD_ID` FROM award_research_areas WHERE RESEARCH_RANK IS NULL;
     DECLARE CUR_PROPOSAL_AREA_OF_RESEARCH CURSOR FOR SELECT DISTINCT `PROPOSAL_ID` FROM eps_proposal_resrch_areas WHERE RESEARCH_RANK IS NULL;
     DECLARE CUR_IP_AREA_OF_RESEARCH CURSOR FOR SELECT DISTINCT `PROPOSAL_ID` FROM proposal_resrch_areas WHERE RESEARCH_RANK IS NULL;
    DECLARE CONTINUE HANDLER FOR NOT FOUND
    SET DONE = TRUE;
    OPEN CUR_AWARD_AREA_OF_RESEARCH;
    LOOP_AWARD: LOOP
        FETCH CUR_AWARD_AREA_OF_RESEARCH INTO LS_MODULE_ID;
        IF DONE THEN
            LEAVE LOOP_AWARD;
        END IF;
        update award_research_areas t1
        inner join (select ROW_NUMBER() OVER(ORDER BY UPDATE_TIMESTAMP ASC) AS New_RANK, RESRCH_AREA_ID from award_research_areas where `AWARD_ID` = LS_MODULE_ID) t2
        on t1.RESRCH_AREA_ID = t2.RESRCH_AREA_ID
        set t1.RESEARCH_RANK = t2.new_rank
        where t1.`AWARD_ID` = LS_MODULE_ID;
    END LOOP;
    CLOSE CUR_AWARD_AREA_OF_RESEARCH;
    SET DONE = FALSE;
    OPEN CUR_PROPOSAL_AREA_OF_RESEARCH;
    LOOP_PROPOSAL: LOOP
        FETCH CUR_PROPOSAL_AREA_OF_RESEARCH INTO LS_MODULE_ID;
        IF DONE THEN
            LEAVE LOOP_PROPOSAL;
        END IF;
        update eps_proposal_resrch_areas t1
        inner join (select ROW_NUMBER() OVER(ORDER BY UPDATE_TIMESTAMP ASC) AS New_RANK, RESRCH_AREA_ID from eps_proposal_resrch_areas where `PROPOSAL_ID` = LS_MODULE_ID) t2
        on t1.RESRCH_AREA_ID = t2.RESRCH_AREA_ID
        set t1.RESEARCH_RANK = t2.new_rank
        where t1.`PROPOSAL_ID` = LS_MODULE_ID;
    END LOOP;
    CLOSE CUR_PROPOSAL_AREA_OF_RESEARCH;
    SET DONE = FALSE;
    OPEN CUR_IP_AREA_OF_RESEARCH;
    LOOP_IP: LOOP
        FETCH CUR_IP_AREA_OF_RESEARCH INTO LS_MODULE_ID;
        IF DONE THEN
            LEAVE LOOP_IP;
        END IF;
        update proposal_resrch_areas t1
        inner join (select ROW_NUMBER() OVER(ORDER BY UPDATE_TIMESTAMP ASC) AS New_RANK, RESRCH_AREA_ID from proposal_resrch_areas where `PROPOSAL_ID` = LS_MODULE_ID) t2
        on t1.RESRCH_AREA_ID = t2.RESRCH_AREA_ID
        set t1.RESEARCH_RANK = t2.new_rank
        where t1.`PROPOSAL_ID` = LS_MODULE_ID;
    END LOOP;
    CLOSE CUR_IP_AREA_OF_RESEARCH;
END
$$
DELIMITER ;
