CREATE PROCEDURE `MERGE_AWD_MASTER_SUB_CONTRACT`(
AV_AWARD_ID 			DECIMAL(22,0),
AV_AWARD_NUMBER			VARCHAR(12),
AV_SEQUENCE_NUMBER		INT(4),
AV_VARIATION_TYPE_CODE	VARCHAR(3),
AV_UPDATE_USER			VARCHAR(60)
)
BEGIN
DECLARE LS_ERROR_MSG	VARCHAR(1000);
DECLARE LS_TABLE_NAME	VARCHAR(30);
DECLARE LI_FLAG			INT;
DECLARE LI_NEXT_VAL	INT(10);
DECLARE LI_MASTER_AWARD_ID	DECIMAL(22,0);
DECLARE LI_TOTAL_AWARD_APPROVED_SUBAWARDS INT(10);
DECLARE LI_AWARD_APPROVED_SUBAWARD_ID	DECIMAL(22,0);
DECLARE LI_AWARD_ID	DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER	VARCHAR(12);
DECLARE LI_SEQUENCE_NUMBER	INT(8);
DECLARE LS_ORGANIZATION_ID	VARCHAR(20);
DECLARE LI_AMOUNT	DECIMAL(12,2);
DECLARE LD_UPDATE_TIMESTAMP	DATETIME;
DECLARE LS_UPDATE_USER	VARCHAR(60);
DECLARE LS_DOCUMENT_UPDATE_USER			VARCHAR(60);
DECLARE LS_DOCUMENT_UPDATE_TIMESTAMP	DATETIME;
		BEGIN
				DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
				BEGIN
					GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
					 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
					SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
					SELECT @full_error INTO LS_ERROR_MSG;
					INSERT INTO AWARD_ERROR_LOG(AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, ERROR_MESSAGE, PROCEDURE_NAME, TABLE_NAME,SECTION_CODE,VARIATION_TYPE_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
					VALUES(AV_AWARD_ID,AV_AWARD_NUMBER,AV_SEQUENCE_NUMBER,LS_ERROR_MSG,'MERGE_AWD_MASTER_SUB_CONTRACT',LS_TABLE_NAME,112,AV_VARIATION_TYPE_CODE,UTC_TIMESTAMP(),AV_UPDATE_USER);
					COMMIT;
				END;
				SET SQL_SAFE_UPDATES = 0;
				SET LS_TABLE_NAME = 'AWARD_APPROVED_SUBAWARDS';
				SELECT COUNT(1) INTO LI_FLAG
				FROM AWARD
				WHERE AWARD_NUMBER = AV_AWARD_NUMBER
				AND SEQUENCE_NUMBER = 0;
				IF LI_FLAG > 0 THEN
					SELECT AWARD_ID INTO LI_MASTER_AWARD_ID
					FROM AWARD
					WHERE AWARD_NUMBER = AV_AWARD_NUMBER
					AND SEQUENCE_NUMBER = 0;
				END IF;
				SELECT COUNT(*) INTO LI_TOTAL_AWARD_APPROVED_SUBAWARDS
				FROM AWARD_APPROVED_SUBAWARDS
				WHERE AWARD_ID = AV_AWARD_ID;
				SELECT IFNULL(MAX(NEXT_VAL),0) INTO LI_NEXT_VAL FROM AWARD_APPROVED_SUBAWARD_ID_GENERATOR;
				UPDATE AWARD_APPROVED_SUBAWARD_ID_GENERATOR SET NEXT_VAL = LI_NEXT_VAL + LI_TOTAL_AWARD_APPROVED_SUBAWARDS + 1;
				COMMIT;
				BEGIN
					DECLARE DONE1 INT DEFAULT FALSE;
					DECLARE CUR_AWARD_APPROVED_SUBAWARDS CURSOR FOR
					SELECT AWARD_APPROVED_SUBAWARD_ID,
					AWARD_ID,
					AWARD_NUMBER,
					SEQUENCE_NUMBER,
					ORGANIZATION_ID,
					AMOUNT,
					UPDATE_TIMESTAMP,
					UPDATE_USER
					FROM AWARD_APPROVED_SUBAWARDS
					WHERE AWARD_ID = AV_AWARD_ID;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
					OPEN CUR_AWARD_APPROVED_SUBAWARDS;
					INSERT_AWARD_APPROVED_SUBAWARDS_LOOP: LOOP
					FETCH CUR_AWARD_APPROVED_SUBAWARDS INTO
					LI_AWARD_APPROVED_SUBAWARD_ID,
					LI_AWARD_ID,
					LS_AWARD_NUMBER,
					LI_SEQUENCE_NUMBER,
					LS_ORGANIZATION_ID,
					LI_AMOUNT,
					LD_UPDATE_TIMESTAMP,
					LS_UPDATE_USER;
					IF DONE1 THEN
						LEAVE INSERT_AWARD_APPROVED_SUBAWARDS_LOOP;
					END IF;
						SET LI_NEXT_VAL = LI_NEXT_VAL+1;
						INSERT INTO AWARD_APPROVED_SUBAWARDS
						(AWARD_APPROVED_SUBAWARD_ID,
						AWARD_ID,
						AWARD_NUMBER,
						SEQUENCE_NUMBER,
						ORGANIZATION_ID,
						AMOUNT,
						UPDATE_TIMESTAMP,
						UPDATE_USER)
						VALUES
						(LI_NEXT_VAL,
						LI_MASTER_AWARD_ID,
						LS_AWARD_NUMBER,
						0,
						LS_ORGANIZATION_ID,
						LI_AMOUNT,
						LD_UPDATE_TIMESTAMP,
						LS_UPDATE_USER);
					END LOOP;
					CLOSE CUR_AWARD_APPROVED_SUBAWARDS;
				END;
		END;
END
$$
DELIMITER ;
