CREATE FUNCTION `FN_CHK_IS_PROPOSAL_PI`(
AV_PROPOSAL_ID    int(10),
AV_PERSON_ID 	  VARCHAR(40)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_FLAG INT;
	SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROPOSAL_PERSONS
	WHERE PROPOSAL_ID = AV_PROPOSAL_ID
	AND PERSON_ID = AV_PERSON_ID
	AND PI_FLAG = 'Y';
	IF LI_FLAG > 0 THEN
		RETURN 'TRUE';
	ELSE
		SELECT COUNT(1) INTO LI_FLAG FROM PERSON_ROLES
		WHERE PERSON_ID = AV_PERSON_ID
		AND ROLE_ID IN(100,110);
		IF LI_FLAG > 0 THEN
			RETURN 'TRUE';
		END IF;
	END IF;
	RETURN 'FALSE';
END
$$
DELIMITER ;
