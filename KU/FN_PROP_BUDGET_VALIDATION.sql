CREATE FUNCTION `FN_PROP_BUDGET_VALIDATION`(
AV_PROPOSAL_ID	int(10)
) RETURNS varchar(20) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_BUDGET_HEADER_ID int(11);
DECLARE LS_COUNT int(11);
DECLARE LS_FLAG int(11);
DECLARE LI_CUTOFF decimal(10,2);
DECLARE LI_TOTAL_DIRECT_COST decimal(10,2);
DECLARE LI_TOTAL_INDIRECT_COST decimal(10,2);
SELECT COUNT(*) INTO LS_COUNT
FROM BUDGET_HEADER WHERE PROPOSAL_ID = AV_PROPOSAL_ID;
IF LS_COUNT = 0 THEN
		RETURN 'FALSE';
END IF;
SELECT BUDGET_HEADER_ID  INTO LI_BUDGET_HEADER_ID
FROM BUDGET_HEADER
WHERE PROPOSAL_ID = AV_PROPOSAL_ID AND  FINAL_VERSION_FLAG = 'Y';
IF LI_BUDGET_HEADER_ID IS NULL THEN
	SELECT COUNT(*)  INTO LS_COUNT
	FROM BUDGET_HEADER
	WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID AND IS_LATEST_VERSION = 'Y';
    IF LS_COUNT = 0 THEN
		RETURN 'FALSE';
    END IF;
END IF;
SELECT COUNT(*)  INTO LS_COUNT
FROM BUDGET_HEADER
WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID AND IS_AUTO_CALC = 'N';
IF LS_COUNT = 0 THEN
		RETURN 'FALSE';
ELSE
		SELECT (CASE WHEN GRANT_TYPE_CODE = 2 THEN  CAST('0.3' AS DECIMAL(10,2))
					  ELSE CAST('0.3' AS DECIMAL(10,2)) END)
		INTO LI_CUTOFF
		FROM EPS_PROPOSAL WHERE PROPOSAL_ID = AV_PROPOSAL_ID;
		SELECT TOTAL_DIRECT_COST,TOTAL_INDIRECT_COST INTO LI_TOTAL_DIRECT_COST,LI_TOTAL_INDIRECT_COST
		FROM BUDGET_HEADER WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID;
		IF ((LI_TOTAL_DIRECT_COST*LI_CUTOFF) <= LI_TOTAL_INDIRECT_COST) THEN
				RETURN 'TRUE';
		ELSE
				RETURN 'FALSE';
		END IF;
END IF;
END
$$
DELIMITER ;
