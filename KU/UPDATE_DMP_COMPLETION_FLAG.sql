DELIMITER $$
CREATE PROCEDURE `UPDATE_DMP_COMPLETION_FLAG`(
AV_QUESTIONNAIRE_ID 	INT,
AV_SUBMODULE_CODE 	INT
)
BEGIN
DECLARE LI_QUESTIONNAIRE_ANS_HEADER_ID 	INT(12);
DECLARE LS_MODULE_ITEM_KEY 				VARCHAR(20);
DECLARE LI_QUESTION_ID					INT(12);
DECLARE LI_FLAG 						INT(3);
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_CONDITION_FLAG VARCHAR(1000);
DECLARE LS_ERROR_MSG VARCHAR(1000);
DECLARE EXIT HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			SELECT IFNULL(MAX(ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM TEMP_DMP_ERROR_LOG;
			INSERT INTO TEMP_DMP_ERROR_LOG(ERROR_LOG_ID,ERROR_MESSAGE,PROCEDURE_NAME,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_ERROR_MSG,'UPDATE_DMP_COMPLETION_FLAG',NOW(),'quickstart');
			COMMIT;
		END;
	BEGIN
			DECLARE DONE1 INT DEFAULT FALSE;
			DECLARE CUR_QUEST_ANSWER_HEADER CURSOR FOR
			SELECT
				T1.QUESTIONNAIRE_ANS_HEADER_ID,
				T1.MODULE_ITEM_KEY
			FROM QUEST_ANSWER_HEADER T1
			WHERE T1.QUESTIONNAIRE_ID = AV_QUESTIONNAIRE_ID
			AND T1.MODULE_ITEM_CODE = 1
			AND T1.MODULE_SUB_ITEM_CODE = AV_SUBMODULE_CODE;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
			OPEN CUR_QUEST_ANSWER_HEADER;
			A_LOOP: LOOP
			FETCH CUR_QUEST_ANSWER_HEADER INTO
			LI_QUESTIONNAIRE_ANS_HEADER_ID,
			LS_MODULE_ITEM_KEY;
			IF DONE1 THEN
				LEAVE A_LOOP;
			END IF;
			SET LS_CONDITION_FLAG = 'FALSE';
						BEGIN
							DECLARE DONE2 INT DEFAULT FALSE;
							DECLARE CUR_QUEST_QUESTION CURSOR FOR
							SELECT QUESTION_ID  from QUEST_QUESTION WHERE QUESTIONNAIRE_ID = AV_QUESTIONNAIRE_ID AND PARENT_QUESTION_ID IS NULL;
							DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
							OPEN CUR_QUEST_QUESTION;
							B_LOOP: LOOP
							FETCH CUR_QUEST_QUESTION INTO
							LI_QUESTION_ID;
							IF DONE2 THEN
								LEAVE B_LOOP;
							END IF;
							CALL QUESTION_ANSWER_CHECK(LI_QUESTIONNAIRE_ANS_HEADER_ID, LI_QUESTION_ID, AV_QUESTIONNAIRE_ID, @EXPR_RESULT);
														SET LS_CONDITION_FLAG = @EXPR_RESULT;
							IF LS_CONDITION_FLAG = 'FALSE' THEN
								LEAVE B_LOOP;
							END IF;
							END LOOP;
							CLOSE CUR_QUEST_QUESTION;
						END;
			 INSERT INTO QUESTIONNAIRE_ISSUE_DEBUG (`ANSWER_HEADER`, `FLAG`) VALUES (LI_QUESTIONNAIRE_ANS_HEADER_ID, LS_CONDITION_FLAG);
			END LOOP;
			CLOSE CUR_QUEST_ANSWER_HEADER;
	END;
END
$$
DELIMITER ;
