CREATE FUNCTION `FN_NARRATIVE_TYPE_RULE`(
AV_PROPOSAL_ID              INT(10)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT INT;
SET  LI_COUNT = 0;
SELECT   COUNT(*)
INTO    LI_COUNT
FROM    EPS_PROPOSAL_ATTACHMENTS
WHERE   PROPOSAL_ID = AV_PROPOSAL_ID
AND     ATTACHMNT_TYPE_CODE = 2 ;
IF LI_COUNT > 0 THEN
	RETURN 'TRUE';
ELSE
	RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
