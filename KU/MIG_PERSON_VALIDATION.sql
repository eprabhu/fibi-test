DELIMITER $$
CREATE  PROCEDURE `MIG_PERSON_VALIDATION`(AV_TYPE VARCHAR(20))
BEGIN
    DECLARE NOT_FOUND INT DEFAULT 0;
    DECLARE LS_QUERY LONGTEXT;
    DECLARE LS_ERROR_MSG VARCHAR(4000);
    DECLARE SEL_BFR_OLD CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_PERSON_MATRIX MP
		SET MP.BEFORE_OLD_PERSON_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.PERSON_ID
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.PERSON_ID IN (SELECT OLD_PERSON_ID FROM MIG_PERSON_DETAILS);'
	)
	FROM MIG_PERSON_MATRIX;
	DECLARE SEL_BFR_NEW CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_PERSON_MATRIX MP
		SET MP.BEFORE_NEW_PERSON_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.NEW_PERSON_ID
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.NEW_PERSON_ID IN (SELECT NEW_PERSON_ID FROM MIG_PERSON_DETAILS);'
	)
	FROM MIG_PERSON_MATRIX;
	DECLARE SEL_AFT_OLD CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_PERSON_MATRIX MP
		SET MP.AFTER_OLD_PERSON_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.PERSON_ID
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.PERSON_ID IN (SELECT OLD_PERSON_ID FROM MIG_PERSON_DETAILS);'
	)
	FROM MIG_PERSON_MATRIX;
	DECLARE SEL_AFT_NEW CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_PERSON_MATRIX MP
		SET MP.AFTER_NEW_PERSON_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.NEW_PERSON_ID
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.NEW_PERSON_ID IN (SELECT NEW_PERSON_ID FROM MIG_PERSON_DETAILS);'
	)
	FROM MIG_PERSON_MATRIX;
	    DECLARE EXIT HANDLER FOR SQLEXCEPTION
			BEGIN
				GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
				SELECT @full_error INTO LS_ERROR_MSG;
                SELECT 'ERROR' AS VALIDATION_STATUS,LS_ERROR_MSG AS VALIDATION_MESSEGE;
			END;
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET NOT_FOUND = 1;
SET SQL_SAFE_UPDATES = 0;
SET FOREIGN_KEY_CHECKS = 0;
IF AV_TYPE = 'BEFORE' THEN
SET SESSION group_concat_max_len = 4294967295;
SELECT GROUP_CONCAT(
    'SELECT DISTINCT ''', T.TABLE_NAME, ''' AS TABLE_NAME, ''', C.COLUMN_NAME, ''' AS COLUMN_NAME, ',
    C.COLUMN_NAME,' AS PERSON_ID
    FROM ', T.TABLE_NAME,'
     WHERE ', C.COLUMN_NAME, ' IS NOT NULL GROUP BY ',C.COLUMN_NAME
    SEPARATOR ' UNION ALL '
) INTO LS_QUERY
FROM INFORMATION_SCHEMA.COLUMNS C
INNER JOIN INFORMATION_SCHEMA.TABLES T
    ON T.TABLE_NAME = C.TABLE_NAME
    AND T.TABLE_SCHEMA = C.TABLE_SCHEMA
WHERE T.TABLE_SCHEMA = (SELECT DATABASE())
  AND T.TABLE_TYPE = 'BASE TABLE'
  AND (C.COLUMN_NAME LIKE '%PERSON_ID%'
  OR C.COLUMN_NAME = 'SUBMIT_USER_ID'
  OR C.COLUMN_NAME = 'DELEGATED_BY'
  OR C.COLUMN_NAME = 'DELEGATED_TO'
  OR C.COLUMN_NAME = 'RECIPIENT_ID'
  OR C.COLUMN_NAME = 'USER_ID'
  OR C.COLUMN_NAME = 'REVIEW_REQUESTOR_ID'
  OR C.COLUMN_NAME = 'WORKFLOW_START_PERSON'
  OR C.COLUMN_NAME = 'WORKFLOW_END_PERSON'
  OR C.COLUMN_NAME = 'MEMBER_ID'
  OR C.COLUMN_NAME = 'TARGET_VALUE'
  OR C.COLUMN_NAME = 'STUDENT_ID'
  OR C.COLUMN_NAME = 'AWARD_PI_ID'
  OR C.COLUMN_NAME = 'UPDATED_BY'
  OR C.COLUMN_NAME = 'TEMPLATE_OWNER_PERSON_ID'
  )
  AND C.COLUMN_NAME <> 'COI_WITH_PERSON_ID'
  AND C.COLUMN_NAME <> 'BUDGET_PERSON_ID'
  AND C.COLUMN_NAME <> 'AWARD_PERSON_ID'
  AND C.COLUMN_NAME <> 'PROPOSAL_PERSON_ID'
  AND C.COLUMN_NAME <> 'PROTOCOL_PERSON_ID'
  AND T.TABLE_NAME NOT LIKE '%bkp%'
  AND T.TABLE_NAME NOT LIKE 'bkp%'
  AND T.TABLE_NAME NOT LIKE '%bkp'
  AND T.TABLE_NAME NOT LIKE '%backup'
  AND T.TABLE_NAME NOT LIKE '%bkup'
  AND T.TABLE_NAME NOT LIKE 'tmp_%'
  AND T.TABLE_NAME NOT LIKE 'TEMP_%'
  AND T.TABLE_NAME <> 'PERSON_test'
  AND T.TABLE_NAME <> 'PERSON'
  AND T.TABLE_NAME <> 'bck_person_null_homeunit-v1'
  AND T.TABLE_NAME <> 'person_role_rt'
  AND T.TABLE_NAME <> 'temp_error_log'
  AND T.TABLE_NAME <> 'mig_person_matrix'
   AND T.TABLE_NAME <> 'MIG_PERSON_DETAILS'
  AND C.COLUMN_NAME <> 'USER_MESSAGE'
  AND EXISTS (
  SELECT 1
  FROM INFORMATION_SCHEMA.TABLES
  WHERE TABLE_SCHEMA = (SELECT DATABASE())
  AND TABLE_ROWS > 0
  AND TABLE_NAME = T.TABLE_NAME
  );
SELECT CONCAT(' INSERT INTO MIG_PERSON_MATRIX(TABLE_NAMES,COLUMN_NAMES,PERSON_ID) SELECT * FROM(
SELECT ''QUEST_ANSWER_HEADER'' AS TABLE_NAME, ''MODULE_SUB_ITEM_KEY'' AS COLUMN_NAME, MODULE_SUB_ITEM_KEY AS PERSON_ID
FROM QUEST_ANSWER_HEADER
WHERE MODULE_ITEM_CODE = 3 AND MODULE_SUB_ITEM_CODE = 3 AND MODULE_SUB_ITEM_KEY IS NOT NULL  GROUP BY MODULE_SUB_ITEM_KEY
 UNION ALL
SELECT ''NOTIFICATION_LOG'' AS TABLE_NAME, ''MODULE_ITEM_KEY'' AS COLUMN_NAME, MODULE_ITEM_KEY AS PERSON_ID
FROM NOTIFICATION_LOG
WHERE module_code = 6 AND MODULE_ITEM_KEY IS NOT NULL  GROUP BY MODULE_ITEM_KEY
 UNION ALL
',LS_QUERY,' )T WHERE T.PERSON_ID IS NOT NULL AND T.PERSON_ID IN (SELECT PERSON_ID FROM PERSON WHERE STATUS = ''A'') AND T.PERSON_ID NOT IN (SELECT ROLODEX_ID FROM ROLODEX)') INTO LS_QUERY;
TRUNCATE TABLE MIG_PERSON_MATRIX;
SET @QUERY_STATEMENT = LS_QUERY;
PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
EXECUTE EXECUTABLE_STAEMENT;
UPDATE MIG_PERSON_MATRIX MP
JOIN MIG_PERSON_DETAILS MD ON MP.PERSON_ID = MD.OLD_PERSON_ID
SET MP.NEW_PERSON_ID = MD.NEW_PERSON_ID;
SET LS_QUERY = '';
                            OPEN SEL_BFR_OLD;
                             SEL_BFR_OLD: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_BFR_OLD INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_BFR_OLD;
                            END IF;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
                            END LOOP;
                            CLOSE SEL_BFR_OLD;
SET LS_QUERY = '';
                            OPEN SEL_BFR_NEW;
                             SEL_BFR_NEW: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_BFR_NEW INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_BFR_NEW;
                            END IF;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
                            END LOOP;
                            CLOSE SEL_BFR_NEW;
ELSEIF AV_TYPE = 'AFTER' THEN
SET LS_QUERY = '';
                            OPEN SEL_AFT_OLD;
                             SEL_AFT_OLD: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_AFT_OLD INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_AFT_OLD;
                            END IF;
								SET SQL_SAFE_UPDATES = 0;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
								SET SQL_SAFE_UPDATES = 1;
                            END LOOP;
                            CLOSE SEL_AFT_OLD;
SET LS_QUERY = '';
                            OPEN SEL_AFT_NEW;
                             SEL_AFT_NEW: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_AFT_NEW INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_AFT_NEW;
                            END IF;
							SET SQL_SAFE_UPDATES = 0;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
							SET SQL_SAFE_UPDATES = 1;
                            END LOOP;
                            CLOSE SEL_AFT_NEW;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE MIG_PERSON_MATRIX
		SET MIGRATION_STATUS =
			CASE
				WHEN BEFORE_OLD_PERSON_CNT <> (AFTER_NEW_PERSON_CNT - BEFORE_NEW_PERSON_CNT) THEN 'FAILED'
				ELSE 'SUCCESS'
			END
		WHERE (MIGRATION_STATUS = 'SUCCESS' OR MIGRATION_STATUS = 'ERROR');
		SET SQL_SAFE_UPDATES = 1;
END IF;
SET SQL_SAFE_UPDATES = 1;
SET FOREIGN_KEY_CHECKS = 1;
SELECT 'SUCCESS' AS VALIDATION_STATUS,LS_ERROR_MSG AS VALIDATION_MESSEGE;
END
$$
DELIMITER ;
