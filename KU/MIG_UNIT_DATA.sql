CREATE DEFINER=`ku_rms_user`@`%` PROCEDURE `MIG_UNIT_DATA`(IN AV_TYPE VARCHAR(10))
BEGIN
    DECLARE NOT_FOUND INT DEFAULT 0;
    DECLARE LS_QUERY LONGTEXT;
    DECLARE LS_ERROR_MSG VARCHAR(4000) DEFAULT NULL;
    DECLARE LS_TABLE_NAMES VARCHAR(255);
	DECLARE LS_COLUMN_NAMES VARCHAR(255);
	DECLARE LS_COLUMN_NAMES_DATA VARCHAR(255);
	DECLARE LS_OLD_PERSON_ID VARCHAR(255);
	DECLARE LS_NEW_PERSON_ID VARCHAR(255);
    DECLARE SEL_UPDATE CURSOR FOR
    SELECT CONCAT(
    'UPDATE ', TABLE_NAMES, ' AG SET AG.', COLUMN_NAMES, ' = (SELECT NEW_UNIT_NUMBER FROM MIG_UNIT_DETAILS WHERE UNIT_NUMBER = AG.', COLUMN_NAMES, ')
    WHERE AG.', COLUMN_NAMES, ' IN (SELECT UNIT_NUMBER FROM MIG_UNIT_DETAILS);'
		) AS UPDATE_QUERY,TABLE_NAMES,COLUMN_NAMES
	FROM MIG_UNIT_MATRIX WHERE (MIGRATION_STATUS IS NULL OR MIGRATION_STATUS = 'FAILED' OR MIGRATION_STATUS = 'ERROR')
	AND NEW_UNIT_NUMBER IS NOT NULL
	GROUP BY TABLE_NAMES, COLUMN_NAMES;
    DECLARE SEL_REVERT CURSOR FOR
    SELECT CONCAT(
    'UPDATE ', TABLE_NAMES, ' AG SET AG.', COLUMN_NAMES, ' = (SELECT UNIT_NUMBER FROM MIG_UNIT_DETAILS WHERE NEW_UNIT_NUMBER = AG.', COLUMN_NAMES, ')
    WHERE AG.', COLUMN_NAMES, ' IN (SELECT NEW_UNIT_NUMBER FROM MIG_UNIT_DETAILS);'
		) AS UPDATE_QUERY,TABLE_NAMES,COLUMN_NAMES
	FROM MIG_UNIT_MATRIX WHERE (MIGRATION_STATUS = 'SUCCESS')
	AND NEW_UNIT_NUMBER IS NOT NULL
	GROUP BY TABLE_NAMES, COLUMN_NAMES;
	DECLARE SEL_TAB_DATA CURSOR FOR
	SELECT COLUMN_NAMES,UNIT_NUMBER,NEW_UNIT_NUMBER FROM MIG_UNIT_MATRIX WHERE TABLE_NAMES = 'PROP_DETAILS_TAB';
    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS CONDITION 1
            @sqlstate = RETURNED_SQLSTATE,
            @errno = MYSQL_ERRNO,
            @msg = MESSAGE_TEXT;
        SET LS_ERROR_MSG = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
        SET SQL_SAFE_UPDATES = 0;
        UPDATE MIG_UNIT_MATRIX SET MIGRATION_STATUS = 'ERROR' WHERE TABLE_NAMES = LS_TABLE_NAMES AND COLUMN_NAMES = LS_COLUMN_NAMES AND NEW_UNIT_NUMBER IS NOT NULL;
        SET SQL_SAFE_UPDATES = 1;
        SELECT 'ERROR' AS MIGRATION_STATUS, LS_ERROR_MSG AS ERROR_MSG;
    END;
    DECLARE CONTINUE HANDLER FOR NOT FOUND SET NOT_FOUND = 1;
SET SQL_SAFE_UPDATES = 0;
SET FOREIGN_KEY_CHECKS = 0;
DELETE FROM UNIT WHERE UNIT_NUMBER IN('22401','22349','22347','22375','28571','22421','22420','22318','22392','22411','22389','27952','33537');
    IF AV_TYPE = 'UPDATE' THEN
    SET SESSION group_concat_max_len = 4294967295;
        OPEN SEL_UPDATE;
        UPDATE_LOOP: LOOP
            FETCH SEL_UPDATE INTO LS_QUERY,LS_TABLE_NAMES,LS_COLUMN_NAMES;
            IF NOT_FOUND = 1 THEN
                LEAVE UPDATE_LOOP;
            END IF;
           IF LOWER(LS_TABLE_NAMES) = 'prop_details_tab' THEN
			SET LS_QUERY = NULL;
			        OPEN SEL_TAB_DATA;
					SEL_TAB_DATA: LOOP
					SET NOT_FOUND = 0;
					FETCH SEL_TAB_DATA INTO LS_COLUMN_NAMES_DATA,LS_OLD_PERSON_ID,LS_NEW_PERSON_ID;
					IF NOT_FOUND = 1 THEN
						LEAVE SEL_TAB_DATA;
					END IF;
					SET LS_QUERY = CONCAT(' UPDATE PROP_DETAILS_TAB SET ',LS_COLUMN_NAMES_DATA,' = ''',LS_NEW_PERSON_ID,''' WHERE ',LS_COLUMN_NAMES_DATA,' = ''',LS_OLD_PERSON_ID,''';');
					SET SQL_SAFE_UPDATES = 0;
					SET FOREIGN_KEY_CHECKS = 0;
					SET @QUERY_STATEMENT = LS_QUERY;
					PREPARE EXECUTABLE_STATEMENT FROM @QUERY_STATEMENT;
					EXECUTE EXECUTABLE_STATEMENT;
					DEALLOCATE PREPARE EXECUTABLE_STATEMENT;
					COMMIT;
					UPDATE MIG_UNIT_MATRIX SET MIGRATION_STATUS = 'SUCCESS' WHERE TABLE_NAMES = LS_TABLE_NAMES AND COLUMN_NAMES = LS_COLUMN_NAMES AND NEW_UNIT_NUMBER IS NOT NULL;
					SET FOREIGN_KEY_CHECKS = 1;
					SET SQL_SAFE_UPDATES = 1;
					END LOOP;
					CLOSE SEL_TAB_DATA;
			ELSE
			SET SQL_SAFE_UPDATES = 0;
			SET FOREIGN_KEY_CHECKS = 0;
            SET @QUERY_STATEMENT = LS_QUERY;
            PREPARE EXECUTABLE_STATEMENT FROM @QUERY_STATEMENT;
            EXECUTE EXECUTABLE_STATEMENT;
            DEALLOCATE PREPARE EXECUTABLE_STATEMENT;
            SET SQL_SAFE_UPDATES = 0;
            UPDATE MIG_UNIT_MATRIX SET MIGRATION_STATUS = 'SUCCESS' WHERE TABLE_NAMES = LS_TABLE_NAMES AND COLUMN_NAMES = LS_COLUMN_NAMES AND NEW_UNIT_NUMBER IS NOT NULL;
        END IF;
        END LOOP;
        CLOSE SEL_UPDATE;
		SET SQL_SAFE_UPDATES = 0;
			UPDATE AGREEMENT_HEADER T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE AWARD_PERSONS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE EPS_PROPOSAL_PERSONS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE FEED_AWARD_DETAILS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE GRANT_CALL_ELIGIBLE_DEPARTMENT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE INSTITUTE_RATES T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNITNAME = T2.NEW_UNIT_NAME;
			UPDATE PROPOSAL_PERSONS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE AWARD_MASTER_DATASET_RT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.LEAD_UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE AWARD_MASTER_DATASET_RT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.PI_HOME_UNIT_NUMBER
			SET T1.PI_HOME_UNIT = T2.NEW_UNIT_NAME;
			UPDATE AWARD_MASTER_DATASET_RT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.KEY_PERSON_DEPARTMENT_NUMBER
			SET T1.KEY_PERSON_DEPARTMENT = T2.NEW_UNIT_NAME;
			UPDATE EPS_PROPOSAL T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.HOME_UNIT_NUMBER
			SET T1.HOME_UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE PROPOSAL T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.HOME_UNIT_NUMBER
			SET T1.HOME_UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE CUSTOM_DATA T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NAME = T1.DESCRIPTION
			SET T1.DESCRIPTION = T2.NEW_UNIT_NAME;
			UPDATE GRANT_CALL_HEADER T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.HOME_UNIT_NUMBER
			SET T1.HOME_UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE PROP_AWD_DETAILS_TAB T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.AWARD_LEAD_UNIT_NUMBER
			SET T1.AWARD_LEAD_UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE PROP_DETAILS_TAB T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.LEAD_UNIT_NUMBER
			SET T1.LEAD_UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE SR_HEADER_HISTORY T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE SR_HEADER_HISTORY T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = T1.PREV_UNIT_NUMBER
			SET T1.PREV_UNIT_NAME = T2.NEW_UNIT_NAME;
			UPDATE PROP_DETAILS_TAB T1
			INNER JOIN GRANT_CALL_HEADER GCH ON GCH.HOME_UNIT_NAME =  T1.GRANT_CALL_HOME_UNIT_NAME
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.NEW_UNIT_NUMBER = GCH.HOME_UNIT_NAME
			SET T1.GRANT_CALL_HOME_UNIT_NAME = T2.NEW_UNIT_NAME;
			SET FOREIGN_KEY_CHECKS = 0;
			UPDATE UNIT U
			INNER JOIN MIG_UNIT_DETAILS MIU ON MIU.UNIT_NUMBER = U.UNIT_NUMBER
			SET U.UNIT_NUMBER= MIU.NEW_UNIT_NUMBER;
            UPDATE UNIT U
			INNER JOIN MIG_UNIT_DETAILS MIU ON MIU.NEW_UNIT_NUMBER = U.UNIT_NUMBER
			SET U.UNIT_NAME = MIU.NEW_UNIT_NAME;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE PERSON P
		INNER JOIN MIG_PERSON_DETAILS MIP ON MIP.OLD_PERSON_ID = P.SUPERVISOR_PERSON_ID
		SET P.SUPERVISOR_PERSON_ID = MIP.NEW_PERSON_ID;
		UPDATE PERSON P
		INNER JOIN MIG_PERSON_DETAILS MIP ON MIP.OLD_PERSON_ID = P.PERSON_ID
		SET P.PERSON_ID = MIP.NEW_PERSON_ID;
		CALL MIG_UNIT_VALIDATION('AFTER');
    ELSEIF AV_TYPE = 'REVERT' THEN
    SET SESSION group_concat_max_len = 4294967295;
        OPEN SEL_REVERT;
        REVERT_LOOP: LOOP
            FETCH SEL_REVERT INTO LS_QUERY,LS_TABLE_NAMES,LS_COLUMN_NAMES;
            IF NOT_FOUND = 1 THEN
                LEAVE REVERT_LOOP;
            END IF;
			SET SQL_SAFE_UPDATES = 0;
			SET FOREIGN_KEY_CHECKS = 0;
            SET @QUERY_STATEMENT = LS_QUERY;
            PREPARE EXECUTABLE_STATEMENT FROM @QUERY_STATEMENT;
            EXECUTE EXECUTABLE_STATEMENT;
            DEALLOCATE PREPARE EXECUTABLE_STATEMENT;
			SET SQL_SAFE_UPDATES = 0;
            UPDATE MIG_UNIT_MATRIX SET MIGRATION_STATUS = NULL WHERE TABLE_NAMES = LS_TABLE_NAMES AND COLUMN_NAMES = LS_COLUMN_NAMES AND NEW_UNIT_NUMBER IS NOT NULL;
        END LOOP;
        CLOSE SEL_REVERT;
		SET SQL_SAFE_UPDATES = 0;
			UPDATE AGREEMENT_HEADER T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE AWARD_PERSONS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE EPS_PROPOSAL_PERSONS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE FEED_AWARD_DETAILS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE GRANT_CALL_ELIGIBLE_DEPARTMENT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE INSTITUTE_RATES T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNITNAME = T2.UNIT_NAME;
			UPDATE PROPOSAL_PERSONS T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE AWARD_MASTER_DATASET_RT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.LEAD_UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE AWARD_MASTER_DATASET_RT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.PI_HOME_UNIT_NUMBER
			SET T1.PI_HOME_UNIT = T2.UNIT_NAME;
			UPDATE AWARD_MASTER_DATASET_RT T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.KEY_PERSON_DEPARTMENT_NUMBER
			SET T1.KEY_PERSON_DEPARTMENT = T2.UNIT_NAME;
			UPDATE EPS_PROPOSAL T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.HOME_UNIT_NUMBER
			SET T1.HOME_UNIT_NAME = T2.UNIT_NAME;
			UPDATE PROPOSAL T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.HOME_UNIT_NUMBER
			SET T1.HOME_UNIT_NAME = T2.UNIT_NAME;
			UPDATE CUSTOM_DATA T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NAME = T1.DESCRIPTION
			SET T1.DESCRIPTION = T2.UNIT_NAME;
			UPDATE GRANT_CALL_HEADER T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.HOME_UNIT_NUMBER
			SET T1.HOME_UNIT_NAME = T2.UNIT_NAME;
			UPDATE PROP_AWD_DETAILS_TAB T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.AWARD_LEAD_UNIT_NUMBER
			SET T1.AWARD_LEAD_UNIT_NAME = T2.UNIT_NAME;
			UPDATE PROP_DETAILS_TAB T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.LEAD_UNIT_NUMBER
			SET T1.LEAD_UNIT_NAME = T2.UNIT_NAME;
			UPDATE SR_HEADER_HISTORY T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.UNIT_NUMBER
			SET T1.UNIT_NAME = T2.UNIT_NAME;
			UPDATE SR_HEADER_HISTORY T1
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = T1.PREV_UNIT_NUMBER
			SET T1.PREV_UNIT_NAME = T2.UNIT_NAME;
			UPDATE PROP_DETAILS_TAB T1
			INNER JOIN GRANT_CALL_HEADER GCH ON GCH.HOME_UNIT_NAME =  T1.GRANT_CALL_HOME_UNIT_NAME
			INNER JOIN MIG_UNIT_DETAILS T2 ON T2.UNIT_NUMBER = GCH.HOME_UNIT_NAME
			SET T1.GRANT_CALL_HOME_UNIT_NAME = T2.UNIT_NAME;
			SET FOREIGN_KEY_CHECKS = 0;
			UPDATE UNIT U
			INNER JOIN MIG_UNIT_DETAILS MIU ON MIU.UNIT_NUMBER = U.PARENT_UNIT_NUMBER
			SET U.PARENT_UNIT_NUMBER= MIU.UNIT_NUMBER;
			UPDATE UNIT U
			INNER JOIN MIG_UNIT_DETAILS MIU ON MIU.UNIT_NUMBER = U.UNIT_NUMBER
			SET U.UNIT_NUMBER= MIU.UNIT_NUMBER,
			U.UNIT_NAME = MIU.UNIT_NAME;
		UPDATE PERSON P
		INNER JOIN MIG_PERSON_DETAILS MIP ON MIP.NEW_PERSON_ID = P.SUPERVISOR_PERSON_ID
		SET P.SUPERVISOR_PERSON_ID = MIP.OLD_PERSON_ID;
		UPDATE PERSON P
		INNER JOIN MIG_PERSON_DETAILS MIP ON MIP.NEW_PERSON_ID = P.PERSON_ID
		SET P.PERSON_ID = MIP.OLD_PERSON_ID;
        UPDATE MIG_UNIT_MATRIX SET AFTER_OLD_UNIT_CNT = 0,AFTER_NEW_UNIT_CNT = 0;
    END IF;
SET SQL_SAFE_UPDATES = 1;
SET FOREIGN_KEY_CHECKS = 1;
    SELECT 'SUCCESS' AS MIGRATION_STATUS, LS_ERROR_MSG AS ERROR_MSG;
END
