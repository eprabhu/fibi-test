CREATE DEFINER=`ku_rms_user`@`%` FUNCTION `FN_LEAD_UNIT_RULE`(
AV_PROPOSAL_ID    INT(10)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE  LI_COUNT	INT;
DECLARE LS_ROOT_UNIT VARCHAR(50);
SELECT VALUE INTO LS_ROOT_UNIT FROM PARAMETER WHERE PARAMETER_NAME = 'ROOT_UNIT';
SELECT 	COUNT(*)
INTO	LI_COUNT
FROM	EPS_PROPOSAL
WHERE	PROPOSAL_ID = AV_PROPOSAL_ID
AND	HOME_UNIT_NUMBER = LS_ROOT_UNIT;
IF LI_COUNT > 0 THEN
	RETURN 'TRUE';
ELSE
	RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
