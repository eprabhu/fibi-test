CREATE  FUNCTION `FN_CHK_GRANT_CODE_VALUE`(
AV_AWARD_ID DECIMAL(22,0)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE  	LS_BA_CODE VARCHAR(4);
DECLARE  	LS_LEAD_UNIT_NUMBER VARCHAR(50);
DECLARE  	LS_GRANT_CODE VARCHAR(4000);
DECLARE 	LI_FLAG INT;
SELECT LEAD_UNIT_NUMBER INTO LS_LEAD_UNIT_NUMBER FROM AWARD where AWARD_ID = AV_AWARD_ID;
	SELECT	BA_CODE	INTO	LS_BA_CODE
	FROM SAP_FEED_UNIT_MAPPING
	WHERE UNIT_NUMBER = LS_LEAD_UNIT_NUMBER;
SELECT COUNT(1) INTO LI_FLAG
FROM CUSTOM_DATA T1
WHERE T1.MODULE_ITEM_CODE = 1
AND T1.MODULE_SUB_ITEM_CODE = 0
AND T1.MODULE_SUB_ITEM_KEY = 0
AND T1.MODULE_ITEM_KEY = AV_AWARD_ID
AND T1.CUSTOM_DATA_ELEMENTS_ID = (	SELECT MAX(CUSTOM_DATA_ELEMENTS_ID) FROM CUSTOM_DATA_ELEMENTS
								WHERE CUSTOM_ELEMENT_NAME = 'GRANT CODE'
								AND IS_LATEST_VERSION = 'Y'
								AND IS_ACTIVE = 'Y'
									)
AND (T1.VALUE IS NOT NULL AND TRIM(T1.VALUE) <> '');
IF LI_FLAG > 0 THEN
	SELECT TRIM(VALUE) INTO LS_GRANT_CODE
	FROM CUSTOM_DATA T1
	WHERE T1.MODULE_ITEM_CODE = 1
AND T1.MODULE_SUB_ITEM_CODE = 0
AND T1.MODULE_SUB_ITEM_KEY = 0
AND T1.MODULE_ITEM_KEY = AV_AWARD_ID
AND T1.CUSTOM_DATA_ELEMENTS_ID = (	SELECT MAX(CUSTOM_DATA_ELEMENTS_ID) FROM CUSTOM_DATA_ELEMENTS
								WHERE CUSTOM_ELEMENT_NAME = 'GRANT CODE'
								AND IS_LATEST_VERSION = 'Y'
								AND IS_ACTIVE = 'Y'
									);
		SET LS_GRANT_CODE = LEFT(LS_GRANT_CODE,2);
		IF LS_BA_CODE = 'A630' AND LS_GRANT_CODE = 'RL' THEN
			RETURN 'TRUE';
		ELSEIF LS_BA_CODE = 'A640' AND LS_GRANT_CODE = 'RI' THEN
			RETURN 'TRUE';
		ELSEIF LS_BA_CODE = 'A650' AND LS_GRANT_CODE = 'RS' THEN
			RETURN 'TRUE';
		ELSEIF LS_BA_CODE  NOT IN('A630','A640','A650') AND LS_GRANT_CODE = 'RN' THEN
			RETURN 'TRUE';
		ELSE
			RETURN 'FALSE';
		END IF;
ELSE
	RETURN 'TRUE';
END IF;
END
$$
