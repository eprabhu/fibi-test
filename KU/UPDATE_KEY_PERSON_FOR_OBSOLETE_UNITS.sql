DELIMITER $$
CREATE  PROCEDURE `UPDATE_KEY_PERSON_FOR_OBSOLETE_UNITS`()
BEGIN
    DECLARE LS_MODULE_PERSON_ID DECIMAL(22, 0);
    DECLARE LS_MODULE_PERSON_UNIT_ID DECIMAL(22, 0);
    DECLARE LS_IS_LEAD_UNIT INT;
    DECLARE LS_IS_PI_PERSON INT;
    DECLARE LS_MIN_PERSON_UNIT_ID INT;
    DECLARE LS_COUNT_UNIT INT;
    DECLARE DONE INT DEFAULT FALSE;
    DECLARE CUR_AWARD_KEY_PERSONAL CURSOR FOR
        SELECT DISTINCT AWARD_PERSON_ID, AWARD_PERSON_UNIT_ID FROM TMP_UNT_MIG_AWARD_KEY_PERSONAL;
    DECLARE CUR_PROPOSAL_KEY_PERSONAL CURSOR FOR
        SELECT DISTINCT PROPOSAL_PERSON_ID, PROP_PERSON_UNIT_ID FROM TMP_UNT_MIG_PROPOSAL_KEY_PERSONAL;
    DECLARE CUR_IP_KEY_PERSONAL CURSOR FOR
        SELECT DISTINCT PROPOSAL_PERSON_ID, PROP_PERSON_UNIT_ID FROM TMP_UNT_MIG_IP_KEY_PERSONAL;
    DECLARE CONTINUE HANDLER FOR NOT FOUND
        SET DONE = TRUE;
    OPEN CUR_AWARD_KEY_PERSONAL;
    LOOP_AWARD: LOOP
        FETCH CUR_AWARD_KEY_PERSONAL INTO LS_MODULE_PERSON_ID, LS_MODULE_PERSON_UNIT_ID;
        IF DONE THEN
            LEAVE LOOP_AWARD;
        END IF;
        SET LS_COUNT_UNIT = 0;
        SELECT COUNT(DISTINCT sub2.UNIT_NUMBER)
        INTO LS_COUNT_UNIT
        FROM award_persons sub
        INNER JOIN award_person_unit sub2 ON sub.AWARD_PERSON_ID = sub2.AWARD_PERSON_ID
        INNER JOIN UNIT SUB_UNIT ON SUB_UNIT.UNIT_NUMBER = sub2.UNIT_NUMBER
        WHERE sub.AWARD_PERSON_ID = LS_MODULE_PERSON_ID;
        IF LS_COUNT_UNIT = 1 THEN
            UPDATE TMP_UNT_MIG_AWARD_KEY_PERSONAL
            SET STATUS = 'U'
            WHERE AWARD_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
        ELSEIF LS_COUNT_UNIT > 1 THEN
            SET LS_IS_LEAD_UNIT = 0;
            SET LS_MIN_PERSON_UNIT_ID = 0;
            SET LS_IS_PI_PERSON = 0;
            SELECT COUNT(*)
            INTO LS_IS_PI_PERSON
            FROM award_person_unit
            WHERE AWARD_PERSON_ID = LS_MODULE_PERSON_ID AND LEAD_UNIT_FLAG = 'Y';
            SELECT COUNT(LEAD_UNIT_FLAG)
            INTO LS_IS_LEAD_UNIT
            FROM award_person_unit
            WHERE AWARD_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID AND LEAD_UNIT_FLAG = 'Y';
            SELECT MIN(AWARD_PERSON_UNIT_ID)
            INTO LS_MIN_PERSON_UNIT_ID
            FROM award_person_unit
            WHERE AWARD_PERSON_ID = LS_MODULE_PERSON_ID;
            IF (LS_IS_PI_PERSON > 0 && LS_IS_LEAD_UNIT = 1) OR (LS_IS_PI_PERSON = 0 && LS_MIN_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID) THEN
                UPDATE TMP_UNT_MIG_AWARD_KEY_PERSONAL
                SET STATUS = 'U'
                WHERE AWARD_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
            ELSE
                UPDATE TMP_UNT_MIG_AWARD_KEY_PERSONAL
                SET STATUS = 'D'
                WHERE AWARD_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
            END IF;
        END IF;
    END LOOP;
    CLOSE CUR_AWARD_KEY_PERSONAL;
    SET DONE = FALSE;
    OPEN CUR_PROPOSAL_KEY_PERSONAL;
    LOOP_PROPOSAL: LOOP
        FETCH CUR_PROPOSAL_KEY_PERSONAL INTO LS_MODULE_PERSON_ID, LS_MODULE_PERSON_UNIT_ID;
        IF DONE THEN
            LEAVE LOOP_PROPOSAL;
        END IF;
        SET LS_COUNT_UNIT = 0;
        SELECT COUNT(DISTINCT sub2.UNIT_NUMBER)
        INTO LS_COUNT_UNIT
        FROM eps_proposal_persons sub
        INNER JOIN eps_prop_person_units sub2 ON sub.PROPOSAL_PERSON_ID = sub2.PROPOSAL_PERSON_ID
        INNER JOIN UNIT SUB_UNIT ON SUB_UNIT.UNIT_NUMBER = sub2.UNIT_NUMBER
        WHERE sub.PROPOSAL_PERSON_ID = LS_MODULE_PERSON_ID;
        IF LS_COUNT_UNIT = 1 THEN
            UPDATE TMP_UNT_MIG_PROPOSAL_KEY_PERSONAL
            SET STATUS = 'U'
            WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
        ELSEIF LS_COUNT_UNIT > 1 THEN
            SET LS_IS_LEAD_UNIT = 0;
            SET LS_MIN_PERSON_UNIT_ID = 0;
            SET LS_IS_PI_PERSON = 0;
            SELECT COUNT(*)
            INTO LS_IS_PI_PERSON
            FROM eps_prop_person_units
            WHERE PROPOSAL_PERSON_ID = LS_MODULE_PERSON_ID AND LEAD_UNIT_FLAG = 'Y';
            SELECT COUNT(LEAD_UNIT_FLAG)
            INTO LS_IS_LEAD_UNIT
            FROM eps_prop_person_units
            WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID AND LEAD_UNIT_FLAG = 'Y';
            SELECT MIN(PROP_PERSON_UNIT_ID)
            INTO LS_MIN_PERSON_UNIT_ID
            FROM eps_prop_person_units
            WHERE PROPOSAL_PERSON_ID = LS_MODULE_PERSON_ID;
            IF (LS_IS_PI_PERSON > 0 && LS_IS_LEAD_UNIT = 1) OR (LS_IS_PI_PERSON = 0 && LS_MIN_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID) THEN
                UPDATE TMP_UNT_MIG_PROPOSAL_KEY_PERSONAL
                SET STATUS = 'U'
                WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
            ELSE
                UPDATE TMP_UNT_MIG_PROPOSAL_KEY_PERSONAL
                SET STATUS = 'D'
                WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
            END IF;
        END IF;
    END LOOP;
    CLOSE CUR_PROPOSAL_KEY_PERSONAL;
    SET DONE = FALSE;
    OPEN CUR_IP_KEY_PERSONAL;
    LOOP_IP: LOOP
        FETCH CUR_IP_KEY_PERSONAL INTO LS_MODULE_PERSON_ID, LS_MODULE_PERSON_UNIT_ID;
        IF DONE THEN
            LEAVE LOOP_IP;
        END IF;
        SET LS_COUNT_UNIT = 0;
        SELECT COUNT(DISTINCT sub2.UNIT_NUMBER)
        INTO LS_COUNT_UNIT
        FROM proposal_persons sub
        INNER JOIN prop_person_units sub2 ON sub.PROPOSAL_PERSON_ID = sub2.PROPOSAL_PERSON_ID
        INNER JOIN UNIT SUB_UNIT ON SUB_UNIT.UNIT_NUMBER = sub2.UNIT_NUMBER
        WHERE sub.PROPOSAL_PERSON_ID = LS_MODULE_PERSON_ID;
        IF LS_COUNT_UNIT = 1 THEN
            UPDATE TMP_UNT_MIG_IP_KEY_PERSONAL
            SET STATUS = 'U'
            WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
        ELSEIF LS_COUNT_UNIT > 1 THEN
            SET LS_IS_LEAD_UNIT = 0;
            SET LS_MIN_PERSON_UNIT_ID = 0;
            SET LS_IS_PI_PERSON = 0;
            SELECT COUNT(*)
            INTO LS_IS_PI_PERSON
            FROM prop_person_units
            WHERE PROPOSAL_PERSON_ID = LS_MODULE_PERSON_ID AND LEAD_UNIT_FLAG = 'Y';
            SELECT COUNT(LEAD_UNIT_FLAG)
            INTO LS_IS_LEAD_UNIT
            FROM prop_person_units
            WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID AND LEAD_UNIT_FLAG = 'Y';
            SELECT MIN(PROP_PERSON_UNIT_ID)
            INTO LS_MIN_PERSON_UNIT_ID
            FROM prop_person_units
            WHERE PROPOSAL_PERSON_ID = LS_MODULE_PERSON_ID;
            IF (LS_IS_PI_PERSON > 0 && LS_IS_LEAD_UNIT = 1) OR (LS_IS_PI_PERSON = 0 && LS_MIN_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID) THEN
                UPDATE TMP_UNT_MIG_IP_KEY_PERSONAL
                SET STATUS = 'U'
                WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
            ELSE
                UPDATE TMP_UNT_MIG_IP_KEY_PERSONAL
                SET STATUS = 'D'
                WHERE PROP_PERSON_UNIT_ID = LS_MODULE_PERSON_UNIT_ID;
            END IF;
        END IF;
    END LOOP;
    CLOSE CUR_IP_KEY_PERSONAL;
END
$$
DELIMITER ;
