DELIMITER $$
CREATE  PROCEDURE `GET_AWARD_KPI_DELETE`()
    DETERMINISTIC
BEGIN
DECLARE LI_AWARD_ID int(12);
DECLARE LS_KPI_TYPE_CODE int(11);
DECLARE LI_AWARD_KPI_ID int(11);
DECLARE LI_AWARD_KPI_ID2 int(11);
DECLARE LI_TARGET int(11);
DECLARE LI_KPI_CRITERIA_TYPE_CODE int(11);
DECLARE LI_AWARD_KPI_CRITERIA_ID int(11);
DECLARE LI_COUNT int(1);
DECLARE LS_DYN_SQL LONGTEXT;
BEGIN
	set LS_DYN_SQL = '';
	BEGIN
			DECLARE DONE1 INT DEFAULT FALSE;
			DECLARE CUR_KPI CURSOR FOR
				SELECT AWARD_ID, KPI_TYPE_CODE FROM AWARD_KPI GROUP BY AWARD_ID, KPI_TYPE_CODE HAVING COUNT(1) > 1;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
			OPEN CUR_KPI;
			INSERT_CUR_KPI_LOOP: LOOP
			FETCH CUR_KPI INTO
				LI_AWARD_ID,
				LS_KPI_TYPE_CODE;
			IF DONE1 THEN
				LEAVE INSERT_CUR_KPI_LOOP;
			END IF;
			BEGIN
				DECLARE DONE1 INT DEFAULT FALSE;
				DECLARE CUR_GRANT_ELIGIBILITY CURSOR FOR
					SELECT T1.AWARD_KPI_ID, T2.TARGET,T2.KPI_CRITERIA_TYPE_CODE, T2.AWARD_KPI_CRITERIA_ID  FROM AWARD_KPI T1
					INNER JOIN AWARD_KPI_CRITERIA T2 ON T1.AWARD_KPI_ID = T2.AWARD_KPI_ID
					WHERE T1.AWARD_ID = LI_AWARD_ID AND T1.KPI_TYPE_CODE = LS_KPI_TYPE_CODE
					and t1.award_kpi_id not in (select award_kpi_id from award_kpi_criteria where target is  null );
				DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
				OPEN CUR_GRANT_ELIGIBILITY;
				INSERT_CUR_GRANT_ELIGIBILITY_LOOP: LOOP
				FETCH CUR_GRANT_ELIGIBILITY INTO
					LI_AWARD_KPI_ID,
					LI_TARGET,
					LI_KPI_CRITERIA_TYPE_CODE,
					LI_AWARD_KPI_CRITERIA_ID;
				IF DONE1 THEN
					LEAVE INSERT_CUR_GRANT_ELIGIBILITY_LOOP;
				END IF;
                    SELECT count(1) into LI_COUNT FROM AWARD_KPI T1
						INNER JOIN AWARD_KPI_CRITERIA T2 ON T1.AWARD_KPI_ID = T2.AWARD_KPI_ID
						WHERE T1.KPI_TYPE_CODE = LS_KPI_TYPE_CODE AND T1.AWARD_ID = LI_AWARD_ID AND T1.AWARD_KPI_ID <> LI_AWARD_KPI_ID AND
						(T2.TARGET = LI_TARGET OR T2.TARGET IS NULL OR T2.TARGET =0) AND T2.KPI_CRITERIA_TYPE_CODE = LI_KPI_CRITERIA_TYPE_CODE;
					IF LI_COUNT > 0 THEN
						SELECT DISTINCT T1.AWARD_KPI_ID into LI_AWARD_KPI_ID2 FROM AWARD_KPI T1
						INNER JOIN AWARD_KPI_CRITERIA T2 ON T1.AWARD_KPI_ID = T2.AWARD_KPI_ID
						WHERE T1.KPI_TYPE_CODE = LS_KPI_TYPE_CODE AND T1.AWARD_ID = LI_AWARD_ID AND T1.AWARD_KPI_ID <> LI_AWARD_KPI_ID AND
						(T2.TARGET = LI_TARGET OR T2.TARGET IS NULL OR T2.TARGET =0) AND T2.KPI_CRITERIA_TYPE_CODE = LI_KPI_CRITERIA_TYPE_CODE;
						SET LS_DYN_SQL = CONCAT( LS_DYN_SQL,'TRUE');
					ELSE
						SET LS_DYN_SQL = CONCAT( LS_DYN_SQL,'FALSE');
					END IF;
				END LOOP;
				CLOSE CUR_GRANT_ELIGIBILITY;
				IF (SELECT count(1) FROM DUAL WHERE LS_DYN_SQL LIKE '%FALSE%') > 0 then
						SET LS_DYN_SQL = '';
					ELSE
						INSERT INTO TEMP_AWARD_KPI (AWARD_KPI_ID,sql_dyn,award_id,kpi_type_code) VALUES (LI_AWARD_KPI_ID2,LS_DYN_SQL,LI_AWARD_ID,LS_KPI_TYPE_CODE);
                        set LI_AWARD_KPI_ID2 = null;
				END IF;
			SET LS_DYN_SQL = '';
			END;
			END LOOP;
			CLOSE CUR_KPI;
	END;
end;
END
$$
DELIMITER ;
