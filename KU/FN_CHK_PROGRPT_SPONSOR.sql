DELIMITER $$
CREATE  FUNCTION `FN_CHK_PROGRPT_SPONSOR`(
AV_PROGRESS_REPORT_ID INT,
AV_SPONSOR_CODE VARCHAR(20)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT INT;
SELECT COUNT(*) INTO LI_COUNT FROM AWARD_PROGRESS_REPORT T1
INNER JOIN AWARD T2 ON T2.AWARD_ID = T1.AWARD_ID
WHERE UPPER(T2.SPONSOR_CODE) = UPPER(AV_SPONSOR_CODE) AND T1.PROGRESS_REPORT_ID = AV_PROGRESS_REPORT_ID;
IF LI_COUNT > 0 THEN
	RETURN 'TRUE';
ELSE
	RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
