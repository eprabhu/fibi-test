DELIMITER $$
CREATE DEFINER=`irshad`@`%` PROCEDURE `UPD_SPONSOR_PROPOSAL_DTLS`()
BEGIN
DECLARE LI_PROPOSAL_ID BIGINT(12);
DECLARE LS_SPONSOR_CODE VARCHAR(6);
DECLARE LS_GRANT_SPONSOR_CODE VARCHAR(6);
DECLARE LI_GRANT_HEADER_ID INT;
DECLARE LS_SPONSOR_NAME VARCHAR(200);
DECLARE DONE INT DEFAULT 0;
DECLARE DAT_CUR CURSOR FOR
SELECT p.PROPOSAL_ID,p.SPONSOR_code,gch.SPONSOR_code,gch.GRANT_HEADER_ID
FROM eps_proposal p,
(
SELECT GRANT_HEADER_ID ,SPONSOR_CODE
FROM grant_call_header
WHERE GRANT_TYPE_CODE
IN (SELECT GRANT_TYPE_CODE FROM grant_call_type
	WHERE GRANT_CALL_CATEGORY_CODE=1)) gch
WHERE gch.GRANT_HEADER_ID=p.GRANT_HEADER_ID
AND gch.SPONSOR_CODE <> p.SPONSOR_CODE;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET done = 1;
OPEN DAT_CUR;
L1: LOOP
FETCH DAT_CUR INTO LI_PROPOSAL_ID,LS_SPONSOR_CODE,LS_GRANT_SPONSOR_CODE,LI_GRANT_HEADER_ID;
IF done=1 THEN
		leave l1;
    END IF;
   SELECT SPONSOR_NAME INTO LS_SPONSOR_NAME FROM SPONSOR S WHERE S.SPONSOR_CODE=LS_GRANT_SPONSOR_CODE;
   UPDATE EPS_PROPOSAL P
   SET SPONSOR_NAME=LS_SPONSOR_NAME,
   SPONSOR_CODE=LS_GRANT_SPONSOR_CODE
   WHERE P.PROPOSAL_ID=LI_PROPOSAL_ID;
END LOOP l1;
CLOSE DAT_CUR;
SET LI_PROPOSAL_ID= NULL ;
SET LS_SPONSOR_CODE= NULL;
SET LS_GRANT_SPONSOR_CODE= NULL;
SET LI_GRANT_HEADER_ID= NULL;
BEGIN
DECLARE DONE1 INT DEFAULT 0;
DECLARE IP_CUR CURSOR FOR
SELECT p.PROPOSAL_ID,p.SPONSOR_code,gch.SPONSOR_code,gch.GRANT_HEADER_ID
FROM proposal p,
(
SELECT GRANT_HEADER_ID ,SPONSOR_CODE
FROM grant_call_header
WHERE GRANT_TYPE_CODE
IN (SELECT GRANT_TYPE_CODE FROM grant_call_type
	WHERE GRANT_CALL_CATEGORY_CODE=1)) gch
WHERE gch.GRANT_HEADER_ID=p.GRANT_HEADER_ID
AND gch.SPONSOR_CODE <> p.SPONSOR_CODE;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET done1 = 1;
OPEN IP_CUR;
L2: LOOP
FETCH IP_CUR INTO LI_PROPOSAL_ID,LS_SPONSOR_CODE,LS_GRANT_SPONSOR_CODE,LI_GRANT_HEADER_ID;
IF done1=1 THEN
		leave l2;
    END IF;
   SELECT SPONSOR_NAME INTO LS_SPONSOR_NAME FROM SPONSOR S WHERE S.SPONSOR_CODE=LS_GRANT_SPONSOR_CODE;
   UPDATE PROPOSAL P
   SET SPONSOR_NAME=LS_SPONSOR_NAME,
   SPONSOR_CODE=LS_GRANT_SPONSOR_CODE
   WHERE P.PROPOSAL_ID=LI_PROPOSAL_ID;
END LOOP l2;
CLOSE IP_CUR;
END;
SET LI_PROPOSAL_ID= NULL ;
SET LS_SPONSOR_CODE= NULL;
SET LS_GRANT_SPONSOR_CODE= NULL;
SET LI_GRANT_HEADER_ID= NULL;
BEGIN
DECLARE DONE2 INT DEFAULT 0;
DECLARE LI_AWARD_ID BIGINT(12);
DECLARE AWD_CUR CURSOR FOR
SELECT A.AWARD_ID,A.SPONSOR_code,gch.SPONSOR_code,gch.GRANT_HEADER_ID
FROM award a,
(
SELECT GRANT_HEADER_ID ,SPONSOR_CODE
FROM grant_call_header
WHERE GRANT_TYPE_CODE
IN (SELECT GRANT_TYPE_CODE FROM grant_call_type
	WHERE GRANT_CALL_CATEGORY_CODE=1)) gch
WHERE gch.GRANT_HEADER_ID=a.GRANT_HEADER_ID
AND gch.SPONSOR_CODE <> a.SPONSOR_CODE;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = 1;
OPEN AWD_CUR;
L3: LOOP
FETCH AWD_CUR INTO LI_AWARD_ID,LS_SPONSOR_CODE,LS_GRANT_SPONSOR_CODE,LI_GRANT_HEADER_ID;
IF DONE2=1 THEN
		leave l3;
    END IF;
 SELECT SPONSOR_NAME INTO LS_SPONSOR_NAME FROM SPONSOR S WHERE S.SPONSOR_CODE=LS_GRANT_SPONSOR_CODE;
  UPDATE award A
   SET
   A.SPONSOR_CODE=LS_GRANT_SPONSOR_CODE
   WHERE A.AWARD_ID=LI_AWARD_ID;
END LOOP l3;
CLOSE AWD_CUR;
END;
END
$$
DELIMITER ;
