DELIMITER $$
CREATE PROCEDURE `DELETE_MANPOWER_WORKDAY_RESOURCE`()
BEGIN
DECLARE LS_LOG_NEEDED VARCHAR(3);
SELECT CONFIGURATION_VALUE INTO LS_LOG_NEEDED FROM manpower_configuration_data WHERE CONFIGURATION_KEY = 'IS_MANPOWER_WORKDAY_LOG_NEEDED';
IF LS_LOG_NEEDED = 'Y' THEN
    INSERT INTO WORKDAY_RESOURCE_LOG (`WBS_NUMBER`, `COST_ALLOCATION`, `CHARGE_START_DATE`, `CHARGE_END_DATE`, `PERSON_ID`, `ACTION_TYPE`, `UPDATE_USER`, `UPDATE_TIMESTAMP`)
	(SELECT `WBS_NUMBER`, `COST_ALLOCATION`, `CHARGE_START_DATE`, `CHARGE_END_DATE`, `PERSON_ID`,
	CASE WHEN `WBS_NUMBER` IS NULL AND `COST_ALLOCATION` IS NULL AND `CHARGE_END_DATE` IS NULL
	   THEN 'DELETE_WORKDAY_RESCIND'
	   ELSE 'DELETE_WORKDAY_RESOURCE'
	END, 'willsmith', now() FROM DELETE_WORKDAY_RESOURCE);
END IF;
SET SQL_SAFE_UPDATES = 0;
DELETE FROM MANPOWER_WORKDAY_RESOURCE WHERE (`WBS_NUMBER`, `COST_ALLOCATION`, `CHARGE_START_DATE`, `CHARGE_END_DATE`, `PERSON_ID`)
IN (SELECT `WBS_NUMBER`, `COST_ALLOCATION`, `CHARGE_START_DATE`, `CHARGE_END_DATE`, `PERSON_ID` FROM DELETE_WORKDAY_RESOURCE WHERE
`WBS_NUMBER` IS NOT NULL AND `COST_ALLOCATION` IS NOT NULL AND `CHARGE_END_DATE` IS NOT NULL);
DELETE FROM MANPOWER_WORKDAY_RESOURCE WHERE (`CHARGE_START_DATE`, `PERSON_ID`)
IN (SELECT `CHARGE_START_DATE`, `PERSON_ID` FROM DELETE_WORKDAY_RESOURCE WHERE `WBS_NUMBER` IS NULL AND `COST_ALLOCATION` IS NULL AND `CHARGE_END_DATE` IS NULL);
TRUNCATE DELETE_WORKDAY_RESOURCE;
SET SQL_SAFE_UPDATES = 1;
END
$$
DELIMITER ;
