CREATE  PROCEDURE `UPD_MISSING_ORGANIZATIONS`()
    DETERMINISTIC
BEGIN
DECLARE NEXT_ORG_ID VARCHAR(20);
DECLARE LS_MISSING_ORG VARCHAR(200);
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE MISSING_ORG_CURSOR CURSOR FOR
SELECT ORGANIZATION
FROM ROLODEX WHERE ORGANIZATION NOT IN (SELECT ORGANIZATION_NAME FROM ORGANIZATION WHERE ORGANIZATION_NAME IS NOT NULL)
AND ORGANIZATION NOT IN (SELECT ORGANIZATION_ID FROM ORGANIZATION);
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN MISSING_ORG_CURSOR;
		MISSING_ORG_CURSOR_LOOP : LOOP
		FETCH MISSING_ORG_CURSOR INTO LS_MISSING_ORG;
		IF DONE1 THEN
		LEAVE MISSING_ORG_CURSOR_LOOP;
		END IF;
		SELECT ifnull(MAX(ORGANIZATION_ID),0) INTO NEXT_ORG_ID FROM ORGANIZATION;
		SET NEXT_ORG_ID = LPAD(NEXT_ORG_ID+1,6,0);
		Insert into ORGANIZATION (
		ORGANIZATION_ID,
		ORGANIZATION_NAME,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		IS_ACTIVE)
		VALUES (
		NEXT_ORG_ID,
		LS_MISSING_ORG,
		UTC_TIMESTAMP(),
		'quickstart',
		'Y');
		END LOOP;
		CLOSE MISSING_ORG_CURSOR;
		UPDATE ROLODEX R INNER JOIN ORGANIZATION O ON R.ORGANIZATION = O.ORGANIZATION_NAME
		SET R.ORGANIZATION = O.ORGANIZATION_ID
		WHERE R.ORGANIZATION NOT IN (SELECT ORGANIZATION_ID FROM ORGANIZATION);
END
$$
DELIMITER ;
