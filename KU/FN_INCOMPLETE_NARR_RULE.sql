CREATE  FUNCTION `FN_INCOMPLETE_NARR_RULE`(
AV_PROPOSAL_ID    INT(10)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE  LI_COUNT INT;
SELECT COUNT(*)
INTO   LI_COUNT
FROM   EPS_PROPOSAL_ATTACHMENTS N
WHERE  N.PROPOSAL_ID = AV_PROPOSAL_ID
AND    N.NARRATIVE_STATUS_CODE = 'I';
IF LI_COUNT > 0 THEN
	RETURN 'FALSE';
ELSE
	RETURN 'TRUE';
END IF;
END
$$
DELIMITER ;
