CREATE  FUNCTION `FN_CHCK_AWARD_INTERNAL_EXTERNAL`(AV_PROGRESS_REPORT_ID decimal(22,0)) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
	DECLARE LI_GRANT_TYPE_CODE INT;
	SELECT t2.GRANT_TYPE_CODE INTO LI_GRANT_TYPE_CODE FROM AWARD t1 JOIN activity_type t2 ON t1.ACTIVITY_TYPE_CODE = t2.ACTIVITY_TYPE_CODE WHERE
    AWARD_ID = (SELECT AWARD_ID FROM AWARD_PROGRESS_REPORT WHERE PROGRESS_REPORT_ID = AV_PROGRESS_REPORT_ID);
	IF LI_GRANT_TYPE_CODE = 1 THEN
		RETURN 'TRUE';
	ELSE
		RETURN 'FALSE';
	END IF;
END
$$
DELIMITER ;
