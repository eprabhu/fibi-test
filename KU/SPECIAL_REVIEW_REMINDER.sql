CREATE PROCEDURE `SPECIAL_REVIEW_REMINDER`( AV_DAYS INT )
BEGIN
SELECT 0 AS SUB_MODULE_ITEM_KEY, T1.AWARD_ID AS MODULE_ITEM_KEY, 1 AS MODULE_CODE,
0 AS SUB_MODULE_CODE, T2.DESCRIPTION
FROM AWARD_SPECIAL_REVIEW T1
INNER JOIN SPECIAL_REVIEW T2 ON T1.SPECIAL_REVIEW_CODE = T2.SPECIAL_REVIEW_CODE INNER JOIN AWARD T3 on T3.AWARD_ID = T1.AWARD_ID WHERE T3.AWARD_SEQUENCE_STATUS = 'ACTIVE'AND T3.STATUS_CODE NOT IN (5,14)
AND date(T1.EXPIRATION_DATE) = date(DATE_ADD(utc_timestamp(),INTERVAL AV_DAYS DAY));
END
$$
DELIMITER ;
