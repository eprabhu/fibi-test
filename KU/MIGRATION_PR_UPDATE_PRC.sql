CREATE PROCEDURE `MIGRATION_PR_UPDATE_PRC`()
BEGIN
DECLARE LI_AWARD_ID  DECIMAL(22,0);
DECLARE LI_REPORT_TRACKING_ID INT;
DECLARE LI_LEGACY_REPORT INT;
DECLARE LI_AWARD_REPORT_TERMS_ID INT;
DECLARE LI_AWARD_REPORT_TRACKING_ID INT ;
DECLARE LI_COUNT INT;
DECLARE DONE INT DEFAULT FALSE;
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE LI_NEW_AWARD_REPORT_TERMS_ID INT;
DECLARE CUR_REPORT_TERMS_ID CURSOR FOR
						select AR.AWARD_REPORT_TERMS_ID from AWARD_REPORT_TERMS AR
						where Ar.REPORT_CLASS_CODE IN (1 , 2)
						and exists (select 1 from AWARD_REPORT_TRACKING ART
										where ART.AWARD_REPORT_TERMS_ID = AR.AWARD_REPORT_TERMS_ID
										and ART.DUE_DATE < '2022-01-01 00:00:00'
										AND  (ART.PROGRESS_REPORT_ID IS NULL
										OR (ART.PROGRESS_REPORT_ID IS NOT NULL
										AND  EXISTS (SELECT 1 FROM AWARD_REPORT_TRACKING_FILE ARTF
													WHERE ARTF.AWARD_REPORT_TRACKING_ID = ART.AWARD_REPORT_TRACKING_ID)
											))
									);
DECLARE CUR_REPORT_TRACKING_ID CURSOR FOR
						(select  ART.AWARD_REPORT_TRACKING_ID
							from AWARD_REPORT_TRACKING ART
							where ART.AWARD_REPORT_TERMS_ID = LI_AWARD_REPORT_TERMS_ID
							AND ART.DUE_DATE < '2022-01-01 00:00:00'
							AND  (ART.PROGRESS_REPORT_ID IS NULL
								OR (ART.PROGRESS_REPORT_ID IS NOT NULL
									AND  EXISTS (SELECT 1 FROM AWARD_REPORT_TRACKING_FILE ARTF
													WHERE ARTF.AWARD_REPORT_TRACKING_ID = ART.AWARD_REPORT_TRACKING_ID)
									))
												);
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = TRUE  ;
BEGIN
		OPEN CUR_REPORT_TERMS_ID;
		REPORT_TERMS_ID_LOOP: LOOP
		FETCH CUR_REPORT_TERMS_ID INTO LI_AWARD_REPORT_TERMS_ID;
		IF DONE THEN
			LEAVE REPORT_TERMS_ID_LOOP;
		END IF;
		set LI_COUNT=0;
		SELECT  COUNT(*) INTO LI_COUNT
		FROM AWARD_REPORT_TRACKING ART
		JOIN AWARD_REPORT_TERMS AR ON ART.AWARD_REPORT_TERMS_ID = AR.AWARD_REPORT_TERMS_ID
		WHERE  AR.AWARD_REPORT_TERMS_ID = LI_AWARD_REPORT_TERMS_ID
        AND AR.REPORT_CLASS_CODE IN (1 , 2)
		and( ART.DUE_DATE > '2022-01-01 00:00:00'
			OR (ART.DUE_DATE < '2022-01-01 00:00:00'
			AND ART.PROGRESS_REPORT_ID IS NOT NULL
			AND NOT EXISTS (SELECT 1 FROM AWARD_REPORT_TRACKING_FILE ARTF
						WHERE ARTF.AWARD_REPORT_TRACKING_ID = ART.AWARD_REPORT_TRACKING_ID)
		));
		IF LI_COUNT = 0  THEN
				UPDATE AWARD_REPORT_TERMS
				SET REPORT_CLASS_CODE = 19
				WHERE AWARD_REPORT_TERMS_ID = LI_AWARD_REPORT_TERMS_ID;
		ELSE
					set LI_NEW_AWARD_REPORT_TERMS_ID = 0;
					INSERT INTO AWARD_REPORT_TERMS
					(AWARD_ID,
						AWARD_NUMBER,
						SEQUENCE_NUMBER,
						REPORT_CLASS_CODE,
						REPORT_CODE,
						FREQUENCY_CODE,
						FREQUENCY_BASE_CODE,
						OSP_DISTRIBUTION_CODE,
						DUE_DATE,
						UPDATE_TIMESTAMP,
						UPDATE_USER,
						BASE_DATE )
					(SELECT
						AWARD_ID,
						AWARD_NUMBER,
						SEQUENCE_NUMBER,
						19,
						REPORT_CODE,
						FREQUENCY_CODE,
						FREQUENCY_BASE_CODE,
						OSP_DISTRIBUTION_CODE,
						DUE_DATE,
						UPDATE_TIMESTAMP,
						UPDATE_USER,
						BASE_DATE
					FROM AWARD_REPORT_TERMS
					WHERE AWARD_REPORT_TERMS_ID=LI_AWARD_REPORT_TERMS_ID);
				SET @AWARD_REPORT_TERMS_ID = last_insert_id();
		BEGIN
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE  ;
						set DONE1 = FALSE;
						OPEN CUR_REPORT_TRACKING_ID;
						REPORT_TRACK_ID_LOOP: LOOP
						FETCH CUR_REPORT_TRACKING_ID INTO LI_AWARD_REPORT_TRACKING_ID;
						IF DONE1 THEN
							LEAVE REPORT_TRACK_ID_LOOP;
						END IF;
								UPDATE AWARD_REPORT_TRACKING_FILE
								SET AWARD_REPORT_TERMS_ID = @AWARD_REPORT_TERMS_ID
								WHERE AWARD_REPORT_TERMS_ID = LI_AWARD_REPORT_TERMS_ID
								AND AWARD_REPORT_TRACKING_ID = LI_AWARD_REPORT_TRACKING_ID ;
								UPDATE AWARD_REPORT_TRACKING ART
								SET ART.AWARD_REPORT_TERMS_ID = @AWARD_REPORT_TERMS_ID
								WHERE ART.AWARD_REPORT_TERMS_ID = LI_AWARD_REPORT_TERMS_ID
								AND ART.AWARD_REPORT_TRACKING_ID = LI_AWARD_REPORT_TRACKING_ID;
				   END LOOP REPORT_TRACK_ID_LOOP;
				   CLOSE CUR_REPORT_TRACKING_ID;
				   set LI_AWARD_REPORT_TRACKING_ID = null;
				END ;
		END IF;
       END LOOP REPORT_TERMS_ID_LOOP;
	   CLOSE CUR_REPORT_TERMS_ID;
	   set LI_AWARD_REPORT_TERMS_ID = null;
    END ;
   END
$$
DELIMITER ;
