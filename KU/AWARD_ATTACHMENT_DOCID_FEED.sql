DELIMITER $$
CREATE  PROCEDURE `AWARD_ATTACHMENT_DOCID_FEED`()
BEGIN
declare LI_DOCUMENT_ID	int(11);
declare LI_AWARD_ID decimal(22,0);
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE LI_AWARD_ATTACHMENT_ID decimal(12,0);
DECLARE EXP_CURSOR CURSOR FOR
SELECT DISTINCT AWARD_ID FROM AWARD_ATTACHMENT;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
SET LI_DOCUMENT_ID = 0;
OPEN EXP_CURSOR;
EXP_CURSOR_LOOP : LOOP
        FETCH EXP_CURSOR INTO  LI_AWARD_ID;
		IF DONE1 THEN
			LEAVE EXP_CURSOR_LOOP;
		END IF;
		SET LI_DOCUMENT_ID = 0;
		BEGIN
        	DECLARE DONE2 INT DEFAULT FALSE;
			DECLARE EXP_CURSOR1 CURSOR FOR
			SELECT AWARD_ATTACHMENT_ID,AWARD_ID FROM AWARD_ATTACHMENT WHERE AWARD_ID = LI_AWARD_ID;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
			OPEN EXP_CURSOR1;
			EXP_CURSOR_LOOP1 : LOOP
					FETCH EXP_CURSOR1 INTO  LI_AWARD_ATTACHMENT_ID,LI_AWARD_ID ;
					IF DONE2 THEN
						LEAVE EXP_CURSOR_LOOP1;
					END IF;
					SET LI_DOCUMENT_ID = LI_DOCUMENT_ID + 1;
					UPDATE AWARD_ATTACHMENT SET DOCUMENT_ID = LI_DOCUMENT_ID WHERE AWARD_ATTACHMENT_ID = LI_AWARD_ATTACHMENT_ID;
			END LOOP;
			CLOSE EXP_CURSOR1;
		END;
END LOOP;
CLOSE EXP_CURSOR;
END
$$
DELIMITER ;
