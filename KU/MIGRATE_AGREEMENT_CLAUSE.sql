DELIMITER $$
CREATE  PROCEDURE `MIGRATE_AGREEMENT_CLAUSE`()
BEGIN
DECLARE AGREEMENT_TYPE_DONE, GROUP_DONE BOOLEAN DEFAULT FALSE;
DECLARE LS_AGREEMENT_TYPE_CODE VARCHAR(3);
DECLARE LS_CLAUSES_GROUP_CODE INT;
DECLARE LS_CLAUSES_GROUP_CODE_EXISTS INT DEFAULT 0;
DECLARE LS_COMBINATION_EXISTS INT DEFAULT 0;
DECLARE AGREEMENT_TYPE_CURSOR CURSOR FOR SELECT AGREEMENT_TYPE_CODE FROM  AGREEMENT_TYPE;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET AGREEMENT_TYPE_DONE = TRUE;
OPEN AGREEMENT_TYPE_CURSOR;
AGREEMENT_TYPE_LOOP: LOOP
FETCH FROM AGREEMENT_TYPE_CURSOR INTO LS_AGREEMENT_TYPE_CODE;
	SELECT count(*) into LS_CLAUSES_GROUP_CODE_EXISTS FROM clauses_group where date(UPDATE_TIMESTAMP) = date(now());
    IF LS_CLAUSES_GROUP_CODE_EXISTS = 0 OR AGREEMENT_TYPE_DONE THEN
    CLOSE AGREEMENT_TYPE_CURSOR;
    LEAVE AGREEMENT_TYPE_LOOP;
    END IF;
    BLOCK2: BEGIN
    DECLARE GROUP_CURSOR CURSOR FOR SELECT CLAUSES_GROUP_CODE FROM clauses_group where date(UPDATE_TIMESTAMP) = date(now());
    DECLARE CONTINUE HANDLER FOR NOT FOUND SET GROUP_DONE = TRUE;
    OPEN GROUP_CURSOR;
    GROUP_CURSOR_lOOP: LOOP
    FETCH FROM GROUP_CURSOR INTO LS_CLAUSES_GROUP_CODE;
        SET LS_COMBINATION_EXISTS = 0;
        select COUNT(*) INTO LS_COMBINATION_EXISTS from agreemnt_type_clauses_mapping WHERE AGREEMENT_TYPE_CODE = LS_AGREEMENT_TYPE_CODE AND CLAUSES_GROUP_CODE = LS_CLAUSES_GROUP_CODE;
        IF LS_COMBINATION_EXISTS > 0 THEN
            set AGREEMENT_TYPE_DONE = false;
            CLOSE GROUP_CURSOR;
            LEAVE GROUP_CURSOR_lOOP;
        END IF;
        insert into agreemnt_type_clauses_mapping(AGREEMENT_TYPE_CODE, CLAUSES_GROUP_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
            values(LS_AGREEMENT_TYPE_CODE, LS_CLAUSES_GROUP_CODE, NOW(), 'akantony');
		select COUNT(*) INTO LS_COMBINATION_EXISTS from clauses WHERE CLAUSES_GROUP_CODE = LS_CLAUSES_GROUP_CODE;
        IF LS_COMBINATION_EXISTS = 0 THEN
            insert into clauses (CLAUSES_CODE, DESCRIPTION, UPDATE_TIMESTAMP, UPDATE_USER, CLAUSES_GROUP_CODE) values ((SELECT T.ID FROM (SELECT ifnull(MAX(CLAUSES_CODE), 0) + 1 AS ID FROM clauses) AS T), 'To be Defined', now(), 'akantony', LS_CLAUSES_GROUP_CODE);
        END IF;
    END LOOP GROUP_CURSOR_lOOP;
    END BLOCK2;
END LOOP AGREEMENT_TYPE_LOOP;
END
$$
DELIMITER ;
