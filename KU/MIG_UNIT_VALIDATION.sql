CREATE DEFINER=`ku_rms_user`@`%` PROCEDURE `MIG_UNIT_VALIDATION`(AV_TYPE VARCHAR(20))
BEGIN
    DECLARE NOT_FOUND INT DEFAULT 0;
    DECLARE LS_QUERY LONGTEXT;
    DECLARE LS_ERROR_MSG VARCHAR(4000);
    DECLARE SEL_BFR_OLD CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_UNIT_MATRIX MP
		SET MP.BEFORE_OLD_UNIT_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.UNIT_NUMBER
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM MIG_UNIT_DETAILS);'
	)
	FROM MIG_UNIT_MATRIX WHERE NEW_UNIT_NUMBER IS NOT NULL;
	DECLARE SEL_BFR_NEW CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_UNIT_MATRIX MP
		SET MP.BEFORE_NEW_UNIT_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.NEW_UNIT_NUMBER
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.NEW_UNIT_NUMBER IN (SELECT NEW_UNIT_NUMBER FROM MIG_UNIT_DETAILS);'
	)
	FROM MIG_UNIT_MATRIX WHERE NEW_UNIT_NUMBER IS NOT NULL;
	DECLARE SEL_AFT_OLD CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_UNIT_MATRIX MP
		SET MP.AFTER_OLD_UNIT_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.UNIT_NUMBER
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM MIG_UNIT_DETAILS);'
	)
	FROM MIG_UNIT_MATRIX WHERE NEW_UNIT_NUMBER IS NOT NULL;
	DECLARE SEL_AFT_NEW CURSOR FOR
	SELECT DISTINCT CONCAT(
		'UPDATE MIG_UNIT_MATRIX MP
		SET MP.AFTER_NEW_UNIT_CNT = (
			SELECT COUNT(1) FROM ',TABLE_NAMES,' AG
			WHERE AG.',COLUMN_NAMES,' = MP.NEW_UNIT_NUMBER
			)
		WHERE TABLE_NAMES = ''',TABLE_NAMES,'''
		AND COLUMN_NAMES = ''',COLUMN_NAMES,'''
		AND MP.NEW_UNIT_NUMBER IN (SELECT NEW_UNIT_NUMBER FROM MIG_UNIT_DETAILS);'
	)
	FROM MIG_UNIT_MATRIX WHERE NEW_UNIT_NUMBER IS NOT NULL;
	    DECLARE EXIT HANDLER FOR SQLEXCEPTION
			BEGIN
				GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
				SELECT @full_error INTO LS_ERROR_MSG;
                SELECT 'ERROR' AS VALIDATION_STATUS,LS_ERROR_MSG AS VALIDATION_MESSEGE;
			END;
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET NOT_FOUND = 1;
SET SQL_SAFE_UPDATES = 0;
SET FOREIGN_KEY_CHECKS = 0;
IF AV_TYPE = 'BEFORE' THEN
SET SESSION group_concat_max_len = 4294967295;
SELECT GROUP_CONCAT(
    'SELECT DISTINCT ''', T.TABLE_NAME, ''' AS TABLE_NAME, ''', C.COLUMN_NAME, ''' AS COLUMN_NAME, ',
    C.COLUMN_NAME,' AS UNIT_NUMBER
    FROM ', T.TABLE_NAME,'
     WHERE ', C.COLUMN_NAME, ' IS NOT NULL GROUP BY ',C.COLUMN_NAME
    SEPARATOR ' UNION ALL '
) INTO LS_QUERY
FROM INFORMATION_SCHEMA.COLUMNS C
INNER JOIN INFORMATION_SCHEMA.TABLES T
    ON T.TABLE_NAME = C.TABLE_NAME
    AND T.TABLE_SCHEMA = C.TABLE_SCHEMA
WHERE
    T.TABLE_SCHEMA = (SELECT DATABASE())
        AND T.TABLE_TYPE = 'BASE TABLE'
        AND (C.COLUMN_NAME LIKE '%UNIT_NUMBER%'
        OR C.COLUMN_NAME = 'OWNED_BY_UNIT'
        OR C.COLUMN_NAME LIKE '%LEAD_UNIT%'
        OR C.COLUMN_NAME = 'HOME_UNIT'
		OR C.COLUMN_NAME = 'RVALUE'
		OR C.COLUMN_NAME = 'KEY_PERSON_DEPARTMENT_NUMBER'
		OR C.COLUMN_NAME = 'HOME_UNIT_NUMBER'
		OR C.COLUMN_NAME = 'FUNDING_SOURCE'
		OR C.COLUMN_NAME = 'VALUE'
		OR C.COLUMN_NAME = 'UNIT_NUMBER'
        )
        AND T.TABLE_NAME NOT LIKE '%bkp%'
        AND T.TABLE_NAME NOT LIKE 'bkp%'
        AND T.TABLE_NAME NOT LIKE '%bkp'
        AND T.TABLE_NAME NOT LIKE '%backup'
        AND T.TABLE_NAME NOT LIKE '%bkup'
        AND T.TABLE_NAME <> 'UNIT'
		AND T.TABLE_NAME <>'mitkc_unit_with_children'
		AND T.TABLE_NAME <> 'unit_level'
        AND T.TABLE_NAME <> 'unit_with_children'
        AND T.TABLE_NAME <> 'unit_tmp'
        AND T.TABLE_NAME <> 'tmp_unt_mig_proposal_key_personal'
        AND C.COLUMN_NAME <> 'AWARD_PERSON_UNIT_ID'
        AND C.COLUMN_NAME <> 'AWARD_LEAD_UNIT_NAME'
        AND C.COLUMN_NAME <> 'LEAD_UNIT_NAME'
        AND C.COLUMN_NAME <> 'LEAD_UNIT_FLAG'
        AND C.COLUMN_NAME <> 'PROP_PERSON_UNIT_ID'
		AND T.TABLE_NAME <> 'person_role_rt'
        AND T.TABLE_NAME NOT LIKE  'tmp_unt_%'
        AND T.TABLE_NAME NOT LIKE  'temp_%'
        AND T.TABLE_NAME <> 'MIG_UNIT_DETAILS'
        AND T.TABLE_NAME <> 'MIG_UNIT_MATRIX'
        AND T.TABLE_NAME <> 'MIG_UNIT_BACKUP'
        AND T.TABLE_NAME <> 'mig_person_details'
        AND EXISTS( SELECT
            1
        FROM
            INFORMATION_SCHEMA.TABLES
        WHERE
            TABLE_SCHEMA = (SELECT DATABASE())
                AND TABLE_ROWS > 0
                AND TABLE_NAME = T.TABLE_NAME);
SELECT CONCAT(' INSERT INTO MIG_UNIT_MATRIX(TABLE_NAMES,COLUMN_NAMES,UNIT_NUMBER) SELECT * FROM(',LS_QUERY,' )T WHERE T.UNIT_NUMBER IS NOT NULL AND T.UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM UNIT WHERE ACTIVE_FLAG = ''Y'') AND T.UNIT_NUMBER <> \'\'; ') INTO LS_QUERY;
TRUNCATE TABLE MIG_UNIT_MATRIX;
SET @QUERY_STATEMENT = LS_QUERY;
PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
EXECUTE EXECUTABLE_STAEMENT;
UPDATE MIG_UNIT_MATRIX MP
JOIN MIG_UNIT_DETAILS MD ON MP.UNIT_NUMBER = MD.UNIT_NUMBER
SET MP.NEW_UNIT_NUMBER = MD.NEW_UNIT_NUMBER;
SET LS_QUERY = '';
                            OPEN SEL_BFR_OLD;
                             SEL_BFR_OLD: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_BFR_OLD INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_BFR_OLD;
                            END IF;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
                            END LOOP;
                            CLOSE SEL_BFR_OLD;
SET LS_QUERY = '';
                            OPEN SEL_BFR_NEW;
                             SEL_BFR_NEW: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_BFR_NEW INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_BFR_NEW;
                            END IF;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
                            END LOOP;
                            CLOSE SEL_BFR_NEW;
ELSEIF AV_TYPE = 'AFTER' THEN
SET LS_QUERY = '';
                            OPEN SEL_AFT_OLD;
                             SEL_AFT_OLD: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_AFT_OLD INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_AFT_OLD;
                            END IF;
								SET SQL_SAFE_UPDATES = 0;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
								SET SQL_SAFE_UPDATES = 1;
                            END LOOP;
                            CLOSE SEL_AFT_OLD;
SET LS_QUERY = '';
                            OPEN SEL_AFT_NEW;
                             SEL_AFT_NEW: LOOP
							 SET  NOT_FOUND = 0;
                             FETCH SEL_AFT_NEW INTO LS_QUERY;
                            IF NOT_FOUND = 1 THEN
                                LEAVE SEL_AFT_NEW;
                            END IF;
							SET SQL_SAFE_UPDATES = 0;
								SET @QUERY_STATEMENT = LS_QUERY;
								PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
								EXECUTE EXECUTABLE_STAEMENT;
								SET SQL_SAFE_UPDATES = 1;
                            END LOOP;
                            CLOSE SEL_AFT_NEW;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE MIG_UNIT_MATRIX
		SET MIGRATION_STATUS =
			CASE
				WHEN BEFORE_OLD_UNIT_CNT <> (AFTER_NEW_UNIT_CNT-BEFORE_NEW_UNIT_CNT) THEN 'FAILED'
				ELSE 'SUCCESS'
			END
		WHERE (MIGRATION_STATUS = 'SUCCESS' OR MIGRATION_STATUS = 'ERROR');
		SET SQL_SAFE_UPDATES = 1;
END IF;
SET SQL_SAFE_UPDATES = 1;
SET FOREIGN_KEY_CHECKS = 1;
SELECT 'SUCCESS' AS VALIDATION_STATUS,LS_ERROR_MSG AS VALIDATION_MESSEGE;
END
$$
DELIMITER ;
