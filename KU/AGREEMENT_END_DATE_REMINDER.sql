DELIMITER $$
CREATE PROCEDURE `AGREEMENT_END_DATE_REMINDER`( AV_DAYS INT )
BEGIN
	SELECT 0 AS SUB_MODULE_ITEM_KEY, AGREEMENT_REQUEST_ID AS MODULE_ITEM_KEY, 13 AS MODULE_CODE, 0 AS SUB_MODULE_CODE, END_DATE as END_DATE FROM AGREEMENT_HEADER
	WHERE AGREEMENT_STATUS_CODE IN (1,2,3,5,6,7)
	AND DATE(END_DATE) = DATE(DATE_ADD(utc_timestamp(),INTERVAL AV_DAYS DAY));
END
$$
DELIMITER ;
