CREATE FUNCTION `FN_NOTIFY_COMPLIANCE_MNGR`(
AV_PROPOSAL_ID    int(10)
  ) RETURNS varchar(20) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT INT;
	SELECT count(*) INTO LI_COUNT
	FROM QUEST_USAGE T1
	INNER JOIN QUEST_QUESTION T2 ON T1.QUESTIONNAIRE_ID = T2.QUESTIONNAIRE_ID
	INNER JOIN QUEST_ANSWER_HEADER T3 ON T2.QUESTIONNAIRE_ID = T3.QUESTIONNAIRE_ID
	INNER JOIN QUEST_ANSWER T4 ON T3.QUESTIONNAIRE_ANS_HEADER_ID = T4.QUESTIONNAIRE_ANS_HEADER_ID
							   AND T4.QUESTION_ID = T2.QUESTION_ID
	WHERE T1.MODULE_ITEM_CODE = 3
	AND T1.MODULE_SUB_ITEM_CODE = 0
	AND T3.MODULE_ITEM_KEY = AV_PROPOSAL_ID
	AND T1.QUESTIONNAIRE_ID = 1002
	AND T2.QUESTION_ID IN(1057,1059,1061)
	AND T4.ANSWER = 'Yes';
IF LI_COUNT >0 THEN
		RETURN 'TRUE';
ELSE
        RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
