DELIMITER $$
CREATE PROCEDURE `MIGRATION_ATTACHMENT_FEED_FULL_LATEST`(AV_TYPE INT)
BEGIN DECLARE LS_PROJECT_ID VARCHAR(50);
DECLARE LS_PROJECT_TYPE VARCHAR(10);
DECLARE LS_ATTACHMENT_TYPE VARCHAR(50);
DECLARE LS_FILE_NAME VARCHAR(500);
DECLARE LS_MIME_TYPE VARCHAR(100);
DECLARE LS_FILE_DATA LONGBLOB;
DECLARE LS_NUM INT;
DECLARE LS_TYPE_CODE_C INT;
DECLARE LI_AWARD_ATTACHMENT_ID DECIMAL(12, 0);
DECLARE LI_AWARD_ID DECIMAL(22, 0);
DECLARE LS_AWARD_NUMBER VARCHAR(20);
DECLARE LS_TYPE_CODE VARCHAR(3);
DECLARE UNIQUE_ID VARCHAR(36);
DECLARE LS_ATTACHMENT_ID INT(10);
DECLARE LI_DOCUMENT_ID INT(11);
DECLARE LS_MSG TEXT;
DECLARE LS_ERROR VARCHAR(2000);
DECLARE LI_COUNT INT;
DECLARE LS_LEGACY_PROJECT_ID VARCHAR(100);
DECLARE LS_FILE_TYPE VARCHAR(50);
begin DECLARE DONE1 INT DEFAULT FALSE;
DECLARE AWARD_CURSOR CURSOR FOR
SELECT
  A.PROJECT_ID,
  A.PROJECT_TYPE,
  A.ATTACHMENT_TYPE,
  A.FILE_NAME,
  A.MIME_TYPE,
  B.AWARD_ID,
  B.AWARD_NUMBER,
  A.DATA
FROM
  TEMP_ATTACHMENT_MIGRATION A
  LEFT JOIN AWARD B ON UPPER(
    TRIM(A.PROJECT_ID)
  ) = UPPER(
    TRIM(B.ACCOUNT_NUMBER)
  )
WHERE
  UPPER(
    TRIM(A.PROJECT_TYPE)
  ) = 'AWARD' AND  B.SEQUENCE_NUMBER = 1 and A.ATTACHMENT_ID in (174912,175101,175444,176053,176065,176066);
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION BEGIN GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
@errno = MYSQL_ERRNO,
@msg = MESSAGE_TEXT;
SET
  @full_error = CONCAT(
    "ERROR ", @errno, " (", @sqlstate,
    "): ", @msg
  );
SELECT
  @full_error INTO LS_ERROR;
INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(
  LEGACY_PROJECT_ID, LEGACY_WBS_NUMBER,
  ERROR_TYPE, FILE_NAME, ERROR_MESSAGE,
  VALIDATION_TYPE, FILE_TYPE
)
VALUES
  (
    NULL,
    LS_PROJECT_ID,
    'Exception',
    TRIM(LS_FILE_NAME),
    LS_ERROR,
    'During Migration',
    LS_FILE_TYPE
  );
END;
DECLARE CONTINUE HANDLER FOR NOT FOUND
SET
  DONE1 = TRUE;
OPEN AWARD_CURSOR;
AWARD_CURSOR_LOOP : LOOP FETCH AWARD_CURSOR INTO LS_PROJECT_ID,
LS_PROJECT_TYPE,
LS_ATTACHMENT_TYPE,
LS_FILE_NAME,
LS_MIME_TYPE,
LI_AWARD_ID,
LS_AWARD_NUMBER,
LS_FILE_DATA;
IF DONE1 THEN LEAVE AWARD_CURSOR_LOOP;
END IF;
set
  LS_FILE_TYPE = null;
SET
  LS_TYPE_CODE = NULL;
IF (
  IFNULL(
    TRIM(LS_FILE_DATA),
    ''
  ) = ''
) THEN INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(
  LEGACY_PROJECT_ID, LEGACY_WBS_NUMBER,
  ERROR_TYPE, FILE_NAME, ERROR_MESSAGE,
  VALIDATION_TYPE, FILE_TYPE
)
VALUES
  (
    NULL,
    ls_project_id,
    'Validation',
    TRIM(LS_FILE_NAME),
    CONCAT('Attachment is empty'),
    'Before Migration',
    LS_FILE_TYPE
  );
COMMIT;
ITERATE AWARD_CURSOR_LOOP;
END IF;
if (
  IFNULL(
    TRIM(LI_AWARD_ID),
    ''
  ) = ''
) THEN INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(
  LEGACY_PROJECT_ID, LEGACY_WBS_NUMBER,
  ERROR_TYPE, FILE_NAME, ERROR_MESSAGE,
  VALIDATION_TYPE, FILE_TYPE
)
VALUES
  (
    NULL,
    ls_project_id,
    'Validation',
    TRIM(LS_FILE_NAME),
    CONCAT(
      'Project id is missing in the Migration Award file provided'
    ),
    'During Migration',
    LS_FILE_TYPE
  );
COMMIT;
ITERATE AWARD_CURSOR_LOOP;
END IF;
SELECT
  COUNT(*) INTO LI_COUNT
FROM
  AWARD
WHERE
  AWARD_ID = LI_AWARD_ID;
IF LI_COUNT = 0 THEN INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(
  LEGACY_PROJECT_ID, LEGACY_WBS_NUMBER,
  ERROR_TYPE, FILE_NAME, ERROR_MESSAGE,
  VALIDATION_TYPE, FILE_TYPE
)
VALUES
  (
    NULL,
    ls_project_id,
    'Validation',
    TRIM(LS_FILE_NAME),
    CONCAT(
      'Award is missing in the Award table'
    ),
    'During Migration',
    LS_FILE_TYPE
  );
COMMIT;
ITERATE AWARD_CURSOR_LOOP;
END IF;
SELECT
  IFNULL(CAMPUS, 'NA') INTO LS_FILE_TYPE
FROM
  AWARD T1
  LEFT JOIN UNIT T2 ON T1.LEAD_UNIT_NUMBER = T2.UNIT_NUMBER
WHERE
  T1.AWARD_ID = LI_AWARD_ID;
SELECT
  COUNT(*) INTO LI_COUNT
FROM
  AWARD_ATTACHMENT_TYPE
WHERE
  UPPER(
    TRIM(DESCRIPTION)
  ) = UPPER(
    TRIM(LS_ATTACHMENT_TYPE)
  );
IF LI_COUNT > 0 THEN
SELECT
  TYPE_CODE INTO LS_TYPE_CODE
FROM
  AWARD_ATTACHMENT_TYPE
WHERE
  UPPER(
    TRIM(DESCRIPTION)
  ) = UPPER(
    TRIM(LS_ATTACHMENT_TYPE)
  );
ELSE INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(
  LEGACY_PROJECT_ID, LEGACY_WBS_NUMBER,
  ERROR_TYPE, FILE_NAME, ERROR_MESSAGE,
  VALIDATION_TYPE, FILE_TYPE
)
VALUES
  (
    NULL,
    ls_project_id,
    'Validation',
    TRIM(LS_FILE_NAME),
    CONCAT(
      'Award Attachment type"',
      TRIM(LS_ATTACHMENT_TYPE),
      '" is missing in the file provided'
    ),
    'During Migration',
    LS_FILE_TYPE
  );
COMMIT;
ITERATE AWARD_CURSOR_LOOP;
END IF;
if UPPER(
  TRIM(LS_PROJECT_TYPE)
) = 'AWARD' then
SELECT
  IFNULL(
    MAX(AWARD_ATTACHMENT_ID),
    0
  )+ 1 INTO LI_AWARD_ATTACHMENT_ID
FROM
  AWARD_ATTACHMENT;
SELECT
  UUID() INTO UNIQUE_ID
FROM
  DUAL;
INSERT INTO AWARD_ATTACHMENT (
  AWARD_ATTACHMENT_ID, AWARD_ID, AWARD_NUMBER,
  SEQUENCE_NUMBER, TYPE_CODE, DESCRIPTION,
  DOCUMENT_STATUS_CODE, UPDATE_TIMESTAMP,
  UPDATE_USER, FILE_DATA_ID, FILE_NAME,
  MIME_TYPE, NARRATIVE_STATUS_CODE,
  VERSION_NUMBER,DOCUMENT_ID
)
values
  (
    LI_AWARD_ATTACHMENT_ID, LI_AWARD_ID,
    LS_AWARD_NUMBER, 1, LS_TYPE_CODE,
    NULL, 1, NOW(), 'quickstart', UNIQUE_ID,
    LS_FILE_NAME, LS_MIME_TYPE, 'C',
    1,(ifnull((SELECT MAX(t2.DOCUMENT_ID) FROM AWARD_ATTACHMENT t2 WHERE t2.AWARD_ID= LI_AWARD_ID)+1,1))
  );
INSERT INTO FILE_DATA
VALUES
  (UNIQUE_ID, LS_FILE_DATA);
COMMIT;
end if;
END LOOP;
CLOSE AWARD_CURSOR;
UPDATE
  AWARD_ATTACHMENT_ID_GENERATOR
SET
  NEXT_VAL = (
    SELECT
      IFNULL(
        MAX(AWARD_ATTACHMENT_ID),
        0
      ) + 1
    FROM
      AWARD_ATTACHMENT
  );
COMMIT;
END;
END
$$
DELIMITER ;
