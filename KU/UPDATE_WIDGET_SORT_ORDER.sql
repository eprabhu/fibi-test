CREATE DEFINER=`irshad`@`%` PROCEDURE `UPDATE_WIDGET_SORT_ORDER`(AV_INPT INT)
BEGIN
	DECLARE LI_UL_CNT INT;
	DECLARE LI_TOTAL_CNT INT;
	DECLARE LS_PERSON_ID VARCHAR(40);
	DECLARE LI_SORT_ORDER INT;
	DECLARE LI_MAX_SEL_ID INT;
	DECLARE DONE BOOLEAN;
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE WIDGET_PERSON_CUR CURSOR FOR
		SELECT P.PERSON_ID
		  FROM PERSON P
		 WHERE STATUS = 'A'
		   AND NOT EXISTS ( SELECT 1
							 FROM USER_SELECTED_WIDGET USW
							WHERE USW.PERSON_ID = P.PERSON_ID
							  AND USW.WIDGET_ID = 9
							  AND USW.SORT_ORDER = 1);
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = TRUE;
	SET autocommit = 0;
	TRUNCATE TABLE WIDGET_AUDIT_TAB;
	OPEN WIDGET_PERSON_CUR;
	p_loop: LOOP
	BEGIN
		DECLARE EXIT HANDLER FOR SQLEXCEPTION
			BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			ROLLBACK;
			INSERT INTO WIDGET_AUDIT_TAB
				(PERSON_ID,STATUS,MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LS_PERSON_ID,'Error',SUBSTR(LS_ERROR,1,1000),CURRENT_TIMESTAMP,'akantony');
			COMMIT;
			SET DONE = TRUE;
		END;
		SET DONE = FALSE;
		SET LI_UL_CNT = 0;
		SET LI_SORT_ORDER = NULL;
		FETCH WIDGET_PERSON_CUR INTO LS_PERSON_ID;
		IF DONE = TRUE THEN
		   LEAVE p_loop;
		END IF;
		SELECT COUNT(*)
		  INTO LI_UL_CNT
		  FROM USER_SELECTED_WIDGET USW
		WHERE USW.PERSON_ID = LS_PERSON_ID
		  AND USW.WIDGET_ID = 9;
		IF LI_UL_CNT > 0 THEN
			SELECT SORT_ORDER
			  INTO LI_SORT_ORDER
			  FROM USER_SELECTED_WIDGET USW
			WHERE USW.PERSON_ID = LS_PERSON_ID
			  AND USW.WIDGET_ID = 9;
			UPDATE USER_SELECTED_WIDGET
			SET SORT_ORDER = SORT_ORDER + 1,UPDATE_USER='akantony',UPDATE_TIMESTAMP = CURRENT_TIMESTAMP
			WHERE PERSON_ID = LS_PERSON_ID
			AND WIDGET_ID <> 9
			AND SORT_ORDER < LI_SORT_ORDER;
			UPDATE USER_SELECTED_WIDGET
			SET SORT_ORDER = 1 ,UPDATE_USER='akantony',UPDATE_TIMESTAMP = CURRENT_TIMESTAMP
			WHERE PERSON_ID = LS_PERSON_ID
			AND WIDGET_ID = 9;
		ELSE
			SET LI_TOTAL_CNT = 0;
			SET LI_MAX_SEL_ID = 0;
			 SELECT COUNT(*)
			  INTO LI_TOTAL_CNT
			  FROM USER_SELECTED_WIDGET USW
			WHERE USW.PERSON_ID = LS_PERSON_ID;
			 SELECT IFNULL(MAX(SELECTED_WIDGET_ID),0) + 1
			  INTO LI_MAX_SEL_ID
			  FROM USER_SELECTED_WIDGET USW;
			IF LI_TOTAL_CNT > 0 THEN
			  UPDATE USER_SELECTED_WIDGET
				SET SORT_ORDER = SORT_ORDER + 1,UPDATE_USER='akantony',UPDATE_TIMESTAMP = CURRENT_TIMESTAMP
			  WHERE PERSON_ID = LS_PERSON_ID ;
			END IF;
			INSERT INTO USER_SELECTED_WIDGET (
						SELECTED_WIDGET_ID,
						WIDGET_ID,
						SORT_ORDER,
						PERSON_ID,
						UPDATE_TIMESTAMP,
						UPDATE_USER)
				VALUES (LI_MAX_SEL_ID,
						9,
						1,
						LS_PERSON_ID,
						CURRENT_TIMESTAMP,
						'akantony'
						);
		END IF;
		IF DONE = FALSE THEN
			INSERT INTO WIDGET_AUDIT_TAB
				(PERSON_ID,STATUS, MESSAGE ,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LS_PERSON_ID,'Success','Updated Successfully',CURRENT_TIMESTAMP,'akantony');
		END IF;
	END;
	COMMIT;
    END LOOP;
	SET autocommit = 1;
END
$$
DELIMITER ;
