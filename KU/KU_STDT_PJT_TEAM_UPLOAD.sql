DELIMITER $$
CREATE DEFINER=`irshad`@`%` PROCEDURE `KU_STDT_PJT_TEAM_UPLOAD`(AV_TYPE INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_AWD_ID INT;
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LS_STUDENT_ID VARCHAR(40);
DECLARE LS_STUDENT_NAME VARCHAR(255);
DECLARE LS_ROLE VARCHAR(100);
DECLARE LI_PERCENTAGE DECIMAL(5,2);
DECLARE LS_START_DATE DATETIME;
DECLARE LS_END_DATE DATETIME;
DECLARE LI_PROJ_TEAM_ID_DEST INT;
DECLARE DONE BOOLEAN;
DECLARE LS_ERROR VARCHAR(2000);
DECLARE LS_ERR_FLG VARCHAR(1);
DECLARE CUR_INPT CURSOR FOR
SELECT DETAIL_RECORD_ID,AWARD_ID ,AWARD_NUMBER,SEQUENCE_NUMBER,STUDENT_ID, STUDENT_NAME, ROLE, PERCENTAGE_CHARGED,STR_TO_DATE(START_DATE,'%d-%M-%y'), STR_TO_DATE(END_DATE,'%d-%M-%y')
  FROM KU_STUDENT_PROJECT_TEAM_DTLS
WHERE STATUS IS NULL;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = TRUE;
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
	 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
	SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
	SELECT @full_error INTO LS_ERROR;
	UPDATE KU_STUDENT_PROJECT_TEAM_DTLS
	SET STATUS = 'ERROR',
		ERROR_MESSAGE = (LS_ERROR)
	WHERE DETAIL_RECORD_ID  = LI_RECORD_ID;
	INSERT INTO KU_STUDENT_PROJECT_TEAM_ERRLOG
			(DETAIL_RECORD_ID,ERROR_MESSAGE)
	VALUES( DETAIL_RECORD_ID,LS_ERROR);
	SET LS_ERR_FLG ='Y';
END;
 BEGIN
	OPEN CUR_INPT;
	inpt_loop: LOOP
		SET DONE = FALSE;
		FETCH CUR_INPT INTO LI_RECORD_ID,LI_AWD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,LS_STUDENT_ID,LS_STUDENT_NAME,LS_ROLE,LI_PERCENTAGE,LS_START_DATE,LS_END_DATE;
		IF DONE = TRUE THEN
		   LEAVE inpt_loop;
		END IF;
		SET LS_ERR_FLG ='N';
		INSERT INTO AWARD_PROJECT_TEAM (
						  AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, PERSON_ID, FULL_NAME, PROJECT_ROLE, NON_EMPLOYEE_FLAG, PERCENTAGE_CHARGED, START_DATE, END_DATE, IS_ACTIVE, UPDATE_TIMESTAMP, UPDATE_USER)
			VALUES (LI_AWD_ID ,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,LS_STUDENT_ID, LS_STUDENT_NAME, LS_ROLE, 'N',LI_PERCENTAGE,LS_START_DATE, LS_END_DATE,'Y',
					CURRENT_TIMESTAMP, 'quickstart');
		SELECT LAST_INSERT_ID() INTO LI_PROJ_TEAM_ID_DEST;
		IF LS_ERR_FLG = 'N' THEN
			UPDATE KU_STUDENT_PROJECT_TEAM_DTLS
			  SET STATUS = 'SUCCESS', AWARD_PROJECT_TEAM_ID = LI_PROJ_TEAM_ID_DEST
			WHERE  DETAIL_RECORD_ID = LI_RECORD_ID;
		END IF;
	END LOOP;
	CLOSE CUR_INPT;
 END;
 SELECT 'Upload Complete';
END
$$
DELIMITER ;
