DELIMITER $$
CREATE PROCEDURE `AWARD_DMP_COMPLETE_DTLS`()
BEGIN
DECLARE DONE INT DEFAULT FALSE;
DECLARE LS_MODULE_ITEM_KEY  VARCHAR(200);
DECLARE CUR_AWARD_DTLS CURSOR FOR
SELECT distinct(T1.MODULE_ITEM_KEY )
                        FROM QUEST_ANSWER_HEADER T1
                       INNER JOIN QUEST_HEADER T2 ON T1.QUESTIONNAIRE_ID = T2.QUESTIONNAIRE_ID
                        WHERE T1.MODULE_ITEM_CODE = 1
                        AND T1.MODULE_SUB_ITEM_CODE = 3
                        AND T2.QUESTIONNAIRE_NUMBER = 1204
                       AND T2.IS_FINAL = 'Y';
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = TRUE;
OPEN CUR_AWARD_DTLS;
A_LOOP: LOOP
FETCH CUR_AWARD_DTLS INTO
LS_MODULE_ITEM_KEY;
 IF DONE THEN
               LEAVE A_LOOP;
END IF;
SELECT FN_CHK_AWARD_DMP_COMPLETE(LS_MODULE_ITEM_KEY) INTO @RESULT;
INSERT INTO `award_dmp_com_flag_dtls`
(`award_id`,
`complete_flag`
)
VALUES
(
LS_MODULE_ITEM_KEY,
@RESULT);
END LOOP A_LOOP;
CLOSE CUR_AWARD_DTLS;
END
$$
DELIMITER ;
