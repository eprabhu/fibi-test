CREATE  PROCEDURE `MIGRATION_EXTERNAL_REVIEWER_ACADEMIC2`(
av_id int
)
BEGIN
DECLARE LI_ID INT;
DECLARE LI_MIGRATED_EXTERNAL_REVIEWER_ID INT;
DECLARE LS_Academic_Area_1	varchar(500) DEFAULT NULL;
DECLARE LS_ACADEMIC_AREA_CODE_1 varchar(3);
DECLARE LS_Academic_Area_2	varchar(500) DEFAULT NULL;
DECLARE LS_ACADEMIC_AREA_CODE_2 varchar(3);
DECLARE LS_ERROR_FLAG VARCHAR(1) DEFAULT 'N';
DECLARE LS_ERROR_MSG varchar(1000);
DECLARE LI_COUNT INT;
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		INSERT INTO MIGRATION_EXT_REVIEWER_ERROR_LOG ( STAGE_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_ID,'EXCEPTION','ACADEMIC_AREA',LS_ERROR_MSG,'PREVALIDATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT ID,
				 Migrated_ext_reviewer_id,
                 Academic_Area_1,
				 Academic_Area_2
		FROM stage_external_reviewer
		 where validation_status = 'SUCCESS';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO	LI_ID
								,LI_MIGRATED_EXTERNAL_REVIEWER_ID
								, LS_Academic_Area_1
								,LS_Academic_Area_2	;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
        set LS_ERROR_FLAG = 'N';
		SET LI_COUNT = NULL;
		IF LS_Academic_Area_1 IS NOT NULL THEN
			SELECT COUNT(*) INTO LI_COUNT FROM EXT_REVIEWER_ACADEMIC_AREA
			WHERE UPPER(TRIM(replace(DESCRIPTION,'\n',''))) = UPPER(TRIM(replace(LS_Academic_Area_1,'\n','')));
				IF LI_COUNT != 1 THEN
					INSERT INTO MIGRATION_EXT_REVIEWER_ERROR_LOG ( STAGE_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALUE,VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
					VALUES(LI_ID,'EXCEPTION','EXTERNAL_REVIEWER','Invalid AcademicArea 1',trim(LS_Academic_Area_1),'PREVALIDATION',NOW(),'quickstart');
					COMMIT;
					set LS_ERROR_FLAG = 'Y';
				ELSE
				SELECT ACADEMIC_AREA_CODE INTO LS_ACADEMIC_AREA_CODE_1 FROM EXT_REVIEWER_ACADEMIC_AREA
			    WHERE UPPER(TRIM(replace(DESCRIPTION,'\n',''))) = UPPER(TRIM(replace(LS_Academic_Area_1,'\n','')));
									SET LI_COUNT = NULL;
									IF LS_Academic_Area_2 IS NOT NULL THEN
										SELECT COUNT(*) INTO LI_COUNT FROM EXT_REVIEWER_ACADEMIC_SUB_AREA
										WHERE UPPER(TRIM(replace(DESCRIPTION,'\n',''))) = UPPER(TRIM(replace(LS_Academic_Area_2,'\n','')));
											IF LI_COUNT != 1 THEN
												INSERT INTO MIGRATION_EXT_REVIEWER_ERROR_LOG ( STAGE_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALUE,VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
												VALUES(LI_ID,'EXCEPTION','EXTERNAL_REVIEWER','Invalid Academic Area 2',trim(LS_Academic_Area_2),'PREVALIDATION',NOW(),'quickstart');
												COMMIT;
												set LS_ERROR_FLAG = 'Y';
											ELSE
													SET LI_COUNT = NULL;
													IF LS_Academic_Area_2 IS NOT NULL THEN
														SELECT COUNT(*) INTO LI_COUNT FROM EXT_REVIEWER_ACADEMIC_SUB_AREA
														WHERE UPPER(TRIM(replace(DESCRIPTION,'\n',''))) = UPPER(TRIM(replace(LS_Academic_Area_2,'\n','')))
														AND ACADEMIC_AREA_CODE = LS_ACADEMIC_AREA_CODE_1;
															IF LI_COUNT != 1 THEN
																INSERT INTO MIGRATION_EXT_REVIEWER_ERROR_LOG ( STAGE_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALUE,VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
																VALUES(LI_ID,'EXCEPTION','EXTERNAL_REVIEWER','Academic Area Secondary is not a subarea of Academic Area Primary',concat('Academic Area Primary: ',trim(LS_Academic_Area_1),' Academic Area Secondary: ' ,trim(LS_Academic_Area_2)),'PREVALIDATION',NOW(),'quickstart');
																COMMIT;
																set LS_ERROR_FLAG = 'Y';
															ELSE
														SELECT ACADEMIC_SUB_AREA_CODE INTO LS_ACADEMIC_AREA_CODE_2 FROM EXT_REVIEWER_ACADEMIC_SUB_AREA
														WHERE UPPER(TRIM(replace(DESCRIPTION,'\n',''))) = UPPER(TRIM(replace(LS_Academic_Area_2,'\n','')))
														AND ACADEMIC_AREA_CODE = LS_ACADEMIC_AREA_CODE_1;
														set sql_safe_updates = 0;
                                                        UPDATE EXTERNAL_REVIEWER set ACADEMIC_AREA_CODE_SECONDARY = LS_ACADEMIC_AREA_CODE_2 where EXTERNAL_REVIEWER_ID = LI_MIGRATED_EXTERNAL_REVIEWER_ID;
															END IF;
													END IF;
											END IF;
									END IF;
				END IF;
		END IF;
		IF LS_ERROR_FLAG = 'Y' THEN
			UPDATE stage_external_reviewer SET VALIDATION_STATUS = 'FAILED'  WHERE ID = LI_ID;
		END IF;
		set LI_MIGRATED_EXTERNAL_REVIEWER_ID = NULL;
		set LS_Academic_Area_1 = NULL;
		set LS_ACADEMIC_AREA_CODE_1 = NULL;
		set LS_Academic_Area_2 = NULL;
		set LS_ACADEMIC_AREA_CODE_2  = NULL;
	END loop;
END;
END;
END
$$
DELIMITER ;
