CREATE  PROCEDURE `CLAIM_SUBMIT_MANPOWER_DATA_UPDATE`(
AV_AWARD_NUMBER VARCHAR(12),
AV_CLAIM_ID VARCHAR(10),
AV_CLAIM_NUMBER VARCHAR(12),
AV_UPDATE_USER VARCHAR(60)
)
BEGIN
DECLARE LS_CLAIM_MANPOWER_EXISTS INT;
SET LS_CLAIM_MANPOWER_EXISTS = 0;
	IF AV_CLAIM_NUMBER LIKE 'R%' THEN
		SELECT COUNT(1) INTO LS_CLAIM_MANPOWER_EXISTS FROM CLAIM_MANPOWER WHERE CLAIM_ID = AV_CLAIM_ID;
		IF LS_CLAIM_MANPOWER_EXISTS > 0 THEN
			DELETE FROM CLAIM_MANPOWER WHERE CLAIM_ID = AV_CLAIM_ID AND MANPOWER_TYPE_CODE = 1 AND
			(WBS_NUMBER, PERSON_ID, POSITION_ID, CHARGE_START_DATE, CHARGE_END_DATE, WORKDAY_REFERENCE_ID) NOT IN (
			SELECT T1.BUDGET_REFERENCE_NUMBER, T2.PERSON_ID, T2.POSITION_ID, T2.CHARGE_START_DATE, T2.CHARGE_END_DATE, T2.WORKDAY_REFERENCE_ID FROM AWARD_MANPOWER T1 INNER JOIN MANPOWER_WORKDAY_RESOURCE T2 ON T1.BUDGET_REFERENCE_NUMBER = T2.WBS_NUMBER AND T1.AWARD_NUMBER = AV_AWARD_NUMBER);
			DELETE FROM CLAIM_MANPOWER WHERE CLAIM_ID = AV_CLAIM_ID AND MANPOWER_TYPE_CODE <> 1 AND RESOURCE_UNIQUE_ID NOT IN (
			SELECT RESOURCE_UNIQUE_ID FROM AWARD_MANPOWER T1 INNER JOIN AWARD_MANPOWER_RESOURCE T2 ON T1.AWARD_MANPOWER_ID = T2.AWARD_MANPOWER_ID AND T1.AWARD_NUMBER = AV_AWARD_NUMBER);
			UPDATE CLAIM_MANPOWER T1 INNER JOIN manpower_workday_resource T2 ON (T1.PERSON_ID = T2.PERSON_ID AND T2.POSITION_ID = T1.POSITION_ID AND
			T2.CHARGE_START_DATE = T1.CHARGE_START_DATE  AND T2.CHARGE_END_DATE = T1.CHARGE_END_DATE AND T2.WORKDAY_REFERENCE_ID = T1.WORKDAY_REFERENCE_ID)
			INNER JOIN AWARD T4 ON SUBSTRING_INDEX(T1.WBS_NUMBER,'EOM',1) = T4.ACCOUNT_NUMBER AND AWARD_SEQUENCE_STATUS = 'ACTIVE' AND T4.AWARD_NUMBER = AV_AWARD_NUMBER
			INNER JOIN AWARD_BUDGET_HEADER T5 ON T5.AWARD_ID = T4.AWARD_ID AND T5.VERSION_NUMBER = (select max(VERSION_NUMBER) from AWARD_BUDGET_HEADER where AWARD_ID = T4.AWARD_ID)
			INNER JOIN AWARD_BUDGET_DETAIL T6 ON T6.INTERNAL_ORDER_CODE = T1.WBS_NUMBER AND T6.BUDGET_HEADER_ID = T5.BUDGET_HEADER_ID
			SET T1.COST_ALLOCATION = T2.COST_ALLOCATION, T1.COMMITTED_COST = T2.COMMITTED_COST, T1.JOB_PROFILE_TYPE_CODE = T2.JOB_PROFILE_TYPE_CODE,
			T1.POSITION_STATUS_CODE = T2.POSITION_STATUS_CODE, T1.APPROVED_HEADCOUNT = T6.QUANTITY, T1.UPDATE_TIMESTAMP = UTC_TIMESTAMP(), T1.UPDATE_USER = AV_UPDATE_USER
			WHERE T1.CLAIM_ID = AV_CLAIM_ID AND (T1.COST_ALLOCATION <> T2.COST_ALLOCATION OR T1.JOB_PROFILE_TYPE_CODE <> T2.JOB_PROFILE_TYPE_CODE
			OR T1.POSITION_STATUS_CODE <> T2.POSITION_STATUS_CODE OR T1.COMMITTED_COST <> T2.COMMITTED_COST OR T1.APPROVED_HEADCOUNT <> T6.QUANTITY);
			UPDATE CLAIM_MANPOWER T1 INNER JOIN AWARD_MANPOWER_RESOURCE T2 ON T1.RESOURCE_UNIQUE_ID = T2.RESOURCE_UNIQUE_ID
			INNER JOIN AWARD_MANPOWER T4 ON T2.AWARD_MANPOWER_ID = T4.AWARD_MANPOWER_ID AND T4.SEQUENCE_NUMBER = 0 AND T4.AWARD_NUMBER = AV_AWARD_NUMBER
			INNER JOIN AWARD_BUDGET_HEADER T5 ON T5.AWARD_ID = T4.AWARD_ID AND T5.VERSION_NUMBER = (select max(VERSION_NUMBER) from AWARD_BUDGET_HEADER where AWARD_ID = T4.AWARD_ID)
			INNER JOIN AWARD_BUDGET_DETAIL T6 ON T6.INTERNAL_ORDER_CODE = T1.WBS_NUMBER AND T6.BUDGET_HEADER_ID = T5.BUDGET_HEADER_ID
			SET T1.COST_ALLOCATION = T2.COST_ALLOCATION, T1.COMMITTED_COST = T2.COMMITTED_COST, T1.JOB_PROFILE_TYPE_CODE = T2.JOB_PROFILE_TYPE_CODE,
			T1.POSITION_STATUS_CODE = T2.POSITION_STATUS_CODE, T1.APPROVED_HEADCOUNT = T6.QUANTITY, T1.UPDATE_TIMESTAMP = UTC_TIMESTAMP(), T1.UPDATE_USER = AV_UPDATE_USER
			WHERE T1.CLAIM_ID = AV_CLAIM_ID AND (T1.COST_ALLOCATION <> T2.COST_ALLOCATION OR T1.COMMITTED_COST <> T2.COMMITTED_COST OR T1.APPROVED_HEADCOUNT <> T6.QUANTITY);
		END IF;
		INSERT INTO `claim_manpower` (`CLAIM_ID`, `CLAIM_NUMBER`, `PERSON_ID`, `UPDATE_TIMESTAMP`, `UPDATE_USER`, `WBS_NUMBER`, `MANPOWER_TYPE_CODE`,
		`COST_ALLOCATION`, `CHARGE_START_DATE`, `CHARGE_END_DATE`, `COMMITTED_COST`, `POSITION_ID`, `WORKDAY_REFERENCE_ID`, `RESOURCE_UNIQUE_ID`,
		`JOB_PROFILE_TYPE_CODE`, `POSITION_STATUS_CODE`, `APPROVED_HEADCOUNT`)
		SELECT
				CLAIM_ID,
				CLAIM_NUMBER,
				t2_person_id,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				t1_budget_reference_number,
				t1_manpower_type_code,
				t2_cost_allocation,
				t2_charge_start_date,
				t2_charge_end_date,
				t2_committed_cost,
				t2_position_id,
				t2_workday_reference_id,
				t2_resource_unique_id,
				t2_job_profile_type_code,
				t2_position_status_code,
				t6_quantity
			FROM
				((SELECT DISTINCT
					AV_CLAIM_ID AS CLAIM_ID,
					AV_CLAIM_NUMBER AS CLAIM_NUMBER,
					T2.PERSON_ID AS t2_person_id,
					UTC_TIMESTAMP() AS UPDATE_TIMESTAMP,
					AV_UPDATE_USER AS UPDATE_USER,
					T1.BUDGET_REFERENCE_NUMBER AS t1_budget_reference_number,
					T1.MANPOWER_TYPE_CODE AS t1_manpower_type_code,
					T2.COST_ALLOCATION AS t2_cost_allocation,
					T2.CHARGE_START_DATE AS t2_charge_start_date,
					T2.CHARGE_END_DATE AS t2_charge_end_date,
					T2.COMMITTED_COST AS t2_committed_cost,
					T2.POSITION_ID AS t2_position_id,
					NULL AS t2_workday_reference_id,
					T2.RESOURCE_UNIQUE_ID AS t2_resource_unique_id,
					T2.JOB_PROFILE_TYPE_CODE AS t2_job_profile_type_code,
					T2.POSITION_STATUS_CODE AS t2_position_status_code,
					T6.QUANTITY AS t6_quantity
				FROM
					AWARD_MANPOWER T1
				INNER JOIN
					AWARD_MANPOWER_RESOURCE T2
						ON T1.AWARD_MANPOWER_ID = T2.AWARD_MANPOWER_ID AND T2.PERSON_ID NOT IN ('999999999100')
				INNER JOIN
					AWARD_BUDGET_HEADER T5
						ON T5.AWARD_ID = T1.AWARD_ID
						AND T5.VERSION_NUMBER = (
							SELECT
								max(AWARD_BUDGET_HEADER.VERSION_NUMBER)
						FROM
							AWARD_BUDGET_HEADER
						WHERE
							AWARD_BUDGET_HEADER.AWARD_ID = T1.AWARD_ID
					)
				INNER JOIN
					AWARD_BUDGET_DETAIL T6
						ON T6.INTERNAL_ORDER_CODE = T1.BUDGET_REFERENCE_NUMBER
						AND T6.BUDGET_HEADER_ID = T5.BUDGET_HEADER_ID
				WHERE
					T1.AWARD_NUMBER = AV_AWARD_NUMBER
					AND T1.SEQUENCE_NUMBER = 0
					AND T1.MANPOWER_TYPE_CODE = 2
					AND NOT EXISTS (
						SELECT
							CLAIM_ID,
							CLAIM_NUMBER,
							CLAIM_MANPOWER.PERSON_ID,
							CLAIM_MANPOWER.UPDATE_TIMESTAMP,
							CLAIM_MANPOWER.UPDATE_USER,
							WBS_NUMBER,
							CLAIM_MANPOWER.MANPOWER_TYPE_CODE,
							CLAIM_MANPOWER.COST_ALLOCATION,
							CLAIM_MANPOWER.CHARGE_START_DATE,
							CLAIM_MANPOWER.CHARGE_END_DATE,
							CLAIM_MANPOWER.COMMITTED_COST,
							CLAIM_MANPOWER.POSITION_ID,
							WORKDAY_REFERENCE_ID,
							RESOURCE_UNIQUE_ID,
							CLAIM_MANPOWER.JOB_PROFILE_TYPE_CODE,
							CLAIM_MANPOWER.POSITION_STATUS_CODE,
							CLAIM_MANPOWER.APPROVED_HEADCOUNT
						FROM
							CLAIM_MANPOWER
						WHERE
							CLAIM_ID = AV_CLAIM_ID
							AND T1.BUDGET_REFERENCE_NUMBER = WBS_NUMBER
							AND T2.RESOURCE_UNIQUE_ID = RESOURCE_UNIQUE_ID
					)
				)
			UNION
			DISTINCT (SELECT
				AV_CLAIM_ID AS CLAIM_ID,
				AV_CLAIM_NUMBER as CLAIM_NUMBER,
				T2.PERSON_ID AS t2_person_id,
				UTC_TIMESTAMP() as UPDATE_TIMESTAMP,
				AV_UPDATE_USER as UPDATE_USER,
				T1.BUDGET_REFERENCE_NUMBER AS t1_budget_reference_number,
				T1.MANPOWER_TYPE_CODE AS t1_manpower_type_code,
				T2.COST_ALLOCATION AS t2_cost_allocation,
				T2.CHARGE_START_DATE AS t2_charge_start_date,
				T2.CHARGE_END_DATE AS t2_charge_end_date,
				T2.COMMITTED_COST AS t2_committed_cost,
				T2.POSITION_ID AS t2_position_id,
				T2.WORKDAY_REFERENCE_ID AS t2_workday_reference_id,
				NULL AS t2_resource_unique_id,
				T2.JOB_PROFILE_TYPE_CODE AS t2_job_profile_type_code,
				T2.POSITION_STATUS_CODE AS t2_position_status_code,
				T6.QUANTITY AS t6_quantity
			FROM
				AWARD_MANPOWER T1
			INNER JOIN
				MANPOWER_WORKDAY_RESOURCE  T2
					ON T1.BUDGET_REFERENCE_NUMBER = T2.WBS_NUMBER AND T2.PERSON_ID NOT IN ('999999999100')
			INNER JOIN
				AWARD_BUDGET_HEADER T5
					ON T5.AWARD_ID = T1.AWARD_ID
					AND T5.VERSION_NUMBER = (SELECT
						max(AWARD_BUDGET_HEADER.VERSION_NUMBER)
				FROM
					AWARD_BUDGET_HEADER
				WHERE
					AWARD_BUDGET_HEADER.AWARD_ID = T1.AWARD_ID)
			INNER JOIN
				AWARD_BUDGET_DETAIL T6
					ON T6.INTERNAL_ORDER_CODE = T1.BUDGET_REFERENCE_NUMBER
					AND T6.BUDGET_HEADER_ID = T5.BUDGET_HEADER_ID
			WHERE
				T1.AWARD_NUMBER = AV_AWARD_NUMBER
				AND T1.SEQUENCE_NUMBER = 0
				AND T1.MANPOWER_TYPE_CODE = 1
				AND NOT EXISTS (SELECT
					CLAIM_ID,
					CLAIM_NUMBER,
					CLAIM_MANPOWER.PERSON_ID,
					CLAIM_MANPOWER.UPDATE_TIMESTAMP,
					CLAIM_MANPOWER.UPDATE_USER,
					WBS_NUMBER,
					CLAIM_MANPOWER.MANPOWER_TYPE_CODE,
					CLAIM_MANPOWER.COST_ALLOCATION,
					CLAIM_MANPOWER.CHARGE_START_DATE,
					CLAIM_MANPOWER.CHARGE_END_DATE,
					CLAIM_MANPOWER.COMMITTED_COST,
					CLAIM_MANPOWER.POSITION_ID,
					WORKDAY_REFERENCE_ID,
					RESOURCE_UNIQUE_ID,
					CLAIM_MANPOWER.JOB_PROFILE_TYPE_CODE,
					CLAIM_MANPOWER.POSITION_STATUS_CODE,
					CLAIM_MANPOWER.APPROVED_HEADCOUNT
				FROM
					CLAIM_MANPOWER
				WHERE
					CLAIM_ID = AV_CLAIM_ID
					AND T1.BUDGET_REFERENCE_NUMBER = WBS_NUMBER
					AND (CLAIM_MANPOWER.PERSON_ID = T2.PERSON_ID
					AND T2.POSITION_ID = CLAIM_MANPOWER.POSITION_ID
					AND T2.CHARGE_START_DATE = CLAIM_MANPOWER.CHARGE_START_DATE
					AND T2.CHARGE_END_DATE = CLAIM_MANPOWER.CHARGE_END_DATE
					AND T2.WORKDAY_REFERENCE_ID = WORKDAY_REFERENCE_ID)))
			) AS MANPOWER_DETAILS;
	END IF;
END
$$
DELIMITER ;
