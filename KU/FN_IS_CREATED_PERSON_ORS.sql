CREATE  FUNCTION `FN_IS_CREATED_PERSON_ORS`(
AV_PROPOSAL_ID    	 VARCHAR(20)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_CREATE_USER  VARCHAR(50);
DECLARE LS_COUNT  int(3);
DECLARE LS_PERSON_ID  VARCHAR(50);
SELECT CREATE_USER
INTO LS_CREATE_USER
FROM EPS_PROPOSAL
WHERE PROPOSAL_ID = AV_PROPOSAL_ID;
SELECT COUNT(*)
INTO LS_COUNT
FROM PERSON
WHERE USER_NAME = LS_CREATE_USER;
IF LS_COUNT = 1 THEN
SELECT PERSON_ID
INTO LS_PERSON_ID
FROM PERSON
WHERE USER_NAME = LS_CREATE_USER;
END IF;
SELECT COUNT(*)
INTO LS_COUNT
FROM PERSON_ROLES
WHERE PERSON_ID = LS_PERSON_ID AND ROLE_ID = 42;
IF (LS_COUNT > 0 ) THEN
	RETURN 'TRUE';
ELSE
	RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
