CREATE DEFINER=`ku_rms_user`@`%` FUNCTION `FN_GET_UNIT_HIERARCHY_LEVEL`(AV_UNIT_NUMBER  VARCHAR(50)) RETURNS int
    DETERMINISTIC
BEGIN
 DECLARE LVL INT;
 DECLARE LS_UNIT_NUMBER VARCHAR(50);
 DECLARE LS_ROOT_UNIT VARCHAR(50);
 SELECT VALUE INTO LS_ROOT_UNIT FROM PARAMETER WHERE PARAMETER_NAME = 'ROOT_UNIT';
  SELECT AV_UNIT_NUMBER INTO LS_UNIT_NUMBER FROM DUAL;
 SET LVL = 1;
   REPEAT
       SET LVL = LVL + 1;
		SELECT PARENT_UNIT_NUMBER INTO LS_UNIT_NUMBER
        FROM UNIT
        WHERE UNIT_NUMBER = LS_UNIT_NUMBER;
      UNTIL  LS_UNIT_NUMBER=LS_ROOT_UNIT OR LS_UNIT_NUMBER IS NULL END REPEAT;
   RETURN LVL;
END
$$
DELIMITER ;
