DELIMITER $$
CREATE PROCEDURE `UPD_AWARD_HISTORY`(
AV_ID	INT
)
BEGIN
DECLARE LS_ERROR_MSG		VARCHAR(1000);
DECLARE LS_TABLE_NAME		VARCHAR(30);
DECLARE LI_FLAG				INT;
DECLARE LI_AWARD_ID							DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER						VARCHAR(12);
DECLARE LI_MIN_SEQ							INT(4);
DECLARE LI_SEQUENCE_NUMBER					INT(4);
DECLARE LI_LAST_MERGED_AWARD_CREATON		DECIMAL(22,0);
DECLARE LI_AWARD_HISTORY_LOG_ID				INT(11);
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO AWARD_ERROR_LOG(AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, ERROR_MESSAGE, PROCEDURE_NAME, TABLE_NAME,SECTION_CODE,VARIATION_TYPE_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
			VALUES(LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,LS_ERROR_MSG,'UPD_AWARD_HISTORY',NULL,NULL,null,UTC_TIMESTAMP(),'quickstart');
			COMMIT;
		END;
		BEGIN
			DECLARE DONE1 INT DEFAULT FALSE;
			DECLARE CUR_AWARD_DATA CURSOR FOR
			SELECT
				DISTINCT AWARD_NUMBER
			FROM AWARD
			ORDER BY AWARD_NUMBER;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
			OPEN CUR_AWARD_DATA;
			INSERT_AWARD_LOOP: LOOP
			FETCH CUR_AWARD_DATA INTO
			LS_AWARD_NUMBER;
			IF DONE1 THEN
				LEAVE INSERT_AWARD_LOOP;
			END IF;
				BEGIN
					DECLARE DONE2 INT DEFAULT FALSE;
					DECLARE CUR_AWARD_DTLS CURSOR FOR
					SELECT
						AWARD_ID,
						SEQUENCE_NUMBER
					FROM AWARD
					WHERE AWARD_NUMBER = LS_AWARD_NUMBER
					AND AWARD_SEQUENCE_STATUS <> 'CANCELLED'
					AND SEQUENCE_NUMBER <> 1
					ORDER BY SEQUENCE_NUMBER;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
					OPEN CUR_AWARD_DTLS;
					INSERT_AWARD_DTL_LOOP: LOOP
					FETCH CUR_AWARD_DTLS INTO
					LI_AWARD_ID,
					LI_SEQUENCE_NUMBER;
					IF DONE2 THEN
						LEAVE INSERT_AWARD_DTL_LOOP;
					END IF;
							SELECT AWARD_ID
							INTO LI_LAST_MERGED_AWARD_CREATON
							FROM AWARD
							WHERE AWARD_NUMBER = LS_AWARD_NUMBER
							AND SEQUENCE_NUMBER IN(
													SELECT MAX(SEQUENCE_NUMBER) FROM AWARD
													WHERE AWARD_NUMBER = LS_AWARD_NUMBER
													AND AWARD_SEQUENCE_STATUS <> 'CANCELLED'
													AND SEQUENCE_NUMBER < LI_SEQUENCE_NUMBER
												 );
							SELECT IFNULL(MAX(AWARD_HISTORY_LOG_ID),0) + 1 INTO LI_AWARD_HISTORY_LOG_ID
							FROM AWARD_HISTORY_LOG;
							INSERT INTO AWARD_HISTORY_LOG(AWARD_HISTORY_LOG_ID, AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, LAST_MERGED_AWARD_CREATON, LAST_MERGED_AWARD_APPRVAL, UPDATE_TIMESTAMP, UPDATE_USER)
							VALUES(LI_AWARD_HISTORY_LOG_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,LI_LAST_MERGED_AWARD_CREATON,LI_LAST_MERGED_AWARD_CREATON,UTC_TIMESTAMP(),'quickstart');
							SET LI_LAST_MERGED_AWARD_CREATON = NULL;
					END LOOP;
					CLOSE CUR_AWARD_DTLS;
				END;
			END LOOP;
			CLOSE CUR_AWARD_DATA;
		END;
END
$$
DELIMITER ;
