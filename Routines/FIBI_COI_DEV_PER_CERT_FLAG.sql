DELIMITER $$
CREATE DEFINER=`fibi`@`%` FUNCTION `FIBI_COI_DEV_PER_CERT_FLAG`(
  AV_PROPOSAL_NUMBER VARCHAR(50),
  AV_PERSON_ID VARCHAR(50),
  AV_PROP_PERSON_ROLE_ID VARCHAR(10),
  AV_PERSON_PROJ_ROLE VARCHAR(100)
) RETURNS varchar(20) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
  DECLARE LS_IS_PERSON_CERTIFIED VARCHAR(1) DEFAULT NULL;
  DECLARE IS_CERTIFICATION_REQUIRED INT DEFAULT 0;
  IF AV_PERSON_ID IS NULL THEN
    RETURN 'NOT_REQUIRED';
  END IF;
  SET IS_CERTIFICATION_REQUIRED = FIBI_COI_DEV_PER_IS_CERT_REQ(AV_PROPOSAL_NUMBER, AV_PROP_PERSON_ROLE_ID, AV_PERSON_PROJ_ROLE);
  IF IS_CERTIFICATION_REQUIRED = 0 THEN
    RETURN 'NOT_REQUIRED';
  END IF;
  SELECT IS_PERSON_CERTIFIED INTO LS_IS_PERSON_CERTIFIED
  FROM EPS_PROPOSAL_PERSONS
  WHERE PROPOSAL_ID = AV_PROPOSAL_NUMBER
    AND PERSON_ID = AV_PERSON_ID
  LIMIT 1;
  IF LS_IS_PERSON_CERTIFIED = 'Y' THEN
    RETURN 'COMPLETED';
  ELSE
    RETURN 'INCOMPLETE';
  END IF;
END
$$
DELIMITER ;
