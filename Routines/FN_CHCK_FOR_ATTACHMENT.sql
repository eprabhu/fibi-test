DELIMITER $$
CREATE  FUNCTION `FN_CHCK_FOR_ATTACHMENT`(AV_PROPOSAL_ID VARCHAR(10)) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_COUNT INT;
SELECT COUNT(*) INTO LS_COUNT FROM eps_proposal_attachments WHERE PROPOSAL_ID = AV_PROPOSAL_ID;
IF LS_COUNT > 0 THEN
	RETURN 'TRUE';
ELSE
    RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
