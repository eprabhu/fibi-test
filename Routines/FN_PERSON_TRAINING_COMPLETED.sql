CREATE DEFINER=`fibi`@`%` FUNCTION `FN_PERSON_TRAINING_COMPLETED`(
AV_PERSON_ID varchar(40),
AV_PROPOSAL_ID int(11)
) RETURNS varchar(20) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
    DECLARE person_count1 INT;
	DECLARE person_count2 INT;
    DECLARE training_status varchar(20);
	SELECT COUNT(t1.PERSON_TRAINING_ID) INTO person_count1 FROM person_training t1 JOIN mylearning_training_code t2 ON (t1.TRAINING_CODE = t2.COEUS_TRAINING_CODE)
		WHERE ((t2.MYLEARNING_TRAINING_CODE ='350102' AND t1.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(),INTERVAL 5 YEAR)) OR
		(t2.MYLEARNING_TRAINING_CODE ='212113' AND t1.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(),INTERVAL 5 YEAR)) OR
		(t2.MYLEARNING_TRAINING_CODE ='2434084' AND t1.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(),INTERVAL 5 YEAR))) AND t1.PERSON_ID = AV_PERSON_ID;
	SELECT COUNT(t1.PERSON_TRAINING_ID) INTO person_count2 FROM person_training t1 JOIN mylearning_training_code t2 ON (t1.TRAINING_CODE = t2.COEUS_TRAINING_CODE)
		WHERE (t2.MYLEARNING_TRAINING_CODE = ('412863') AND t1.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(),INTERVAL 4 YEAR)) AND t1.PERSON_ID = AV_PERSON_ID;
	IF (person_count1 > 0 AND person_count2 > 0) then
		SET training_status = 'Completed';
    ELSE
		SET training_status = 'Pending';
	END IF;
    RETURN training_status;
END
$$
DELIMITER ;
