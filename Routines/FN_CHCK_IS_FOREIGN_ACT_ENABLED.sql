CREATE  FUNCTION `FN_CHCK_IS_FOREIGN_ACT_ENABLED`(
AV_PROPOSAL_ID VARCHAR(20)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_FLAG INT;
	SELECT COUNT(1) INTO LI_FLAG FROM CUSTOM_DATA
	WHERE CUSTOM_DATA_ELEMENTS_ID IN
    (select CUSTOM_DATA_ELEMENTS_ID FROM custom_data_elements
     WHERE COLUMN_LABEL = 'Foreign Activities')
	AND MODULE_ITEM_KEY = AV_PROPOSAL_ID
	AND MODULE_ITEM_CODE = 3;
	IF LI_FLAG > 0 THEN
        SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROPOSAL_SPECIAL_REVIEW
		WHERE SPECIAL_REVIEW_CODE = 16
		AND PROPOSAL_ID = AV_PROPOSAL_ID;
        IF LI_FLAG > 0 THEN
			RETURN 'TRUE';
		ELSE
           RETURN 'FALSE';
        END IF;
	END IF;
	RETURN 'TRUE';
END
$$
DELIMITER ;
