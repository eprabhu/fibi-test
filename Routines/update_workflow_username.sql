DELIMITER $$
CREATE  PROCEDURE `update_workflow_username`(av_type int)
BEGIN
DECLARE LS_USER_NAME VARCHAR(60);
DECLARE LI_APPROVAL_STOP_NUMBER INT(3);
DECLARE LI_WORKFLOW_ID INT(3);
DECLARE LI_APPROVER_NUMBER INT(3);
DECLARE LI_COUNT INT(3);
DECLARE LS_ERROR VARCHAR(2000);
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
	 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
	SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
	SELECT @full_error INTO LS_ERROR;
	INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
	VALUES(LI_WORKFLOW_ID,LI_APPROVAL_STOP_NUMBER,'Exception','update_workflow_username',CONCAT(LS_ERROR),NULL,NULL);
	COMMIT;
END;
BEGIN
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE WORKFLOW_ID_CURSOR CURSOR FOR
		SELECT DISTINCT WORKFLOW_ID
		FROM fibikki_prod.WORKFLOW_DETAIL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN WORKFLOW_ID_CURSOR;
		WORKFLOW_ID_CURSOR_LOOP : LOOP
				FETCH WORKFLOW_ID_CURSOR INTO LI_WORKFLOW_ID;
				IF DONE1 THEN
					LEAVE WORKFLOW_ID_CURSOR_LOOP;
				END IF;
				BEGIN
					DECLARE DONE2 INT DEFAULT FALSE;
					DECLARE APPROVAL_STOP_NUMBER_CURSOR CURSOR FOR
					SELECT DISTINCT APPROVAL_STOP_NUMBER
					FROM fibikki_prod.WORKFLOW_DETAIL WHERE WORKFLOW_ID = LI_WORKFLOW_ID
					ORDER BY APPROVAL_STOP_NUMBER;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
					OPEN APPROVAL_STOP_NUMBER_CURSOR;
					APPROVAL_STOP_NUMBER_CURSOR_LOOP : LOOP
							FETCH APPROVAL_STOP_NUMBER_CURSOR INTO LI_APPROVAL_STOP_NUMBER;
							IF DONE2 THEN
								LEAVE APPROVAL_STOP_NUMBER_CURSOR_LOOP;
							END IF;
									BEGIN
									DECLARE DONE3 INT DEFAULT FALSE;
									DECLARE APPROVER_NUMBER_CURSOR CURSOR FOR
									SELECT DISTINCT APPROVER_NUMBER
									FROM fibikki_prod.WORKFLOW_DETAIL
									WHERE WORKFLOW_ID = LI_WORKFLOW_ID AND APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
									ORDER BY APPROVER_NUMBER;
									DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE3 = TRUE;
									OPEN APPROVER_NUMBER_CURSOR;
										APPROVER_NUMBER_CURSOR_LOOP : LOOP
												FETCH APPROVER_NUMBER_CURSOR INTO LI_APPROVER_NUMBER;
												IF DONE3 THEN
													LEAVE APPROVER_NUMBER_CURSOR_LOOP;
												END IF;
												SELECT COUNT(*) INTO LI_COUNT
												FROM fibikki_prod.WORKFLOW_DETAIL
												WHERE WORKFLOW_ID = LI_WORKFLOW_ID
												AND APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
												AND APPROVER_NUMBER = LI_APPROVER_NUMBER
												AND APPROVAL_STATUS = 'A';
												IF LI_COUNT > 0 THEN
													SELECT T2.USER_NAME INTO LS_USER_NAME
													FROM fibikki_prod.WORKFLOW_DETAIL T1 LEFT JOIN fibikki_prod.PERSON T2 ON T1.APPROVER_PERSON_ID = T2.PERSON_ID
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T2.PERSON_ID IS NOT NULL
													AND T1.APPROVAL_STATUS = 'A';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.PRIMARY_APPROVER_FLAG = 'Y'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'A';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.PRIMARY_APPROVER_FLAG = 'N'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'O';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.UPDATE_USER = LS_USER_NAME
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS IN('A','O');
												END IF;
												SELECT COUNT(*) INTO LI_COUNT
												FROM fibikki_prod.WORKFLOW_DETAIL
												WHERE WORKFLOW_ID = LI_WORKFLOW_ID
												AND APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
												AND APPROVER_NUMBER = LI_APPROVER_NUMBER
												AND APPROVAL_STATUS = 'B';
												IF LI_COUNT > 0 THEN
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.PRIMARY_APPROVER_FLAG = 'Y'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'B';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.PRIMARY_APPROVER_FLAG = 'N'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'K';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.UPDATE_USER = 'collinsc'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS IN('B','K');
												END IF;
												SELECT COUNT(*) INTO LI_COUNT
												FROM fibikki_prod.WORKFLOW_DETAIL T1
												WHERE WORKFLOW_ID = LI_WORKFLOW_ID
												AND APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
												AND APPROVER_NUMBER = LI_APPROVER_NUMBER
												AND APPROVAL_STATUS = 'R';
												IF LI_COUNT > 0 THEN
													SELECT T2.USER_NAME INTO LS_USER_NAME
													FROM fibikki_prod.WORKFLOW_DETAIL T1 LEFT JOIN fibikki_prod.PERSON T2 ON T1.APPROVER_PERSON_ID = T2.PERSON_ID
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T2.PERSON_ID IS NOT NULL
													AND T1.APPROVAL_STATUS = 'R';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.PRIMARY_APPROVER_FLAG = 'Y'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'R';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.PRIMARY_APPROVER_FLAG = 'N'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'J';
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.UPDATE_USER = LS_USER_NAME
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS IN('R','J');
												END IF;
												SELECT COUNT(*) INTO LI_COUNT
												FROM fibikki_prod.WORKFLOW_DETAIL T1
												WHERE WORKFLOW_ID = LI_WORKFLOW_ID
												AND APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
												AND APPROVER_NUMBER = LI_APPROVER_NUMBER
												AND APPROVAL_STATUS = 'RS';
												IF LI_COUNT > 0 THEN
													UPDATE  fibikki_prod.WORKFLOW_DETAIL T1
													SET T1.UPDATE_USER = 'collinsc'
													WHERE T1.WORKFLOW_ID = LI_WORKFLOW_ID
													AND T1.APPROVAL_STOP_NUMBER = LI_APPROVAL_STOP_NUMBER
													AND T1.APPROVER_NUMBER = LI_APPROVER_NUMBER
													AND T1.APPROVAL_STATUS = 'RS';
												END IF;
										END LOOP;
									CLOSE APPROVER_NUMBER_CURSOR;
									END;
							END LOOP;
					CLOSE APPROVAL_STOP_NUMBER_CURSOR;
				END;
		END LOOP;
		CLOSE WORKFLOW_ID_CURSOR;
END;
SELECT 1  AS RESULT;
END
$$
DELIMITER ;
