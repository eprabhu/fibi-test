DELIMITER $$
CREATE DEFINER=`fibi`@`%` PROCEDURE `inst_attchment_feed`(av_type int)
BEGIN
DECLARE LI_PROPOSAL_ID int(10);
DECLARE LI_PROP_ATTACHMENT_ID int(10);
declare LI_DOCUMENT_ID int(4);
BEGIN
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE EXP_CURSOR CURSOR FOR
SELECT DISTINCT PROPOSAL_ID
FROM fibikki_prod.PROPOSAL_ATTACHMENTS;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
SET LI_DOCUMENT_ID = 0;
OPEN EXP_CURSOR;
EXP_CURSOR_LOOP : LOOP
        FETCH EXP_CURSOR INTO  LI_PROPOSAL_ID;
		IF DONE2 THEN
			LEAVE EXP_CURSOR_LOOP;
		END IF;
		SET LI_DOCUMENT_ID = 0;
		BEGIN
        	DECLARE DONE3 INT DEFAULT FALSE;
			DECLARE EXP_CURSOR1 CURSOR FOR
			SELECT ATTACHMENT_ID
			FROM fibikki_prod.PROPOSAL_ATTACHMENTS
			WHERE PROPOSAL_ID = LI_PROPOSAL_ID;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE3 = TRUE;
			OPEN EXP_CURSOR1;
			EXP_CURSOR_LOOP1 : LOOP
					FETCH EXP_CURSOR1 INTO  LI_PROP_ATTACHMENT_ID;
					IF DONE3 THEN
						LEAVE EXP_CURSOR_LOOP1;
					END IF;
					SET LI_DOCUMENT_ID = LI_DOCUMENT_ID + 1;
					UPDATE fibikki_prod.PROPOSAL_ATTACHMENTS  SET DOCUMENT_ID = LI_DOCUMENT_ID WHERE ATTACHMENT_ID = LI_PROP_ATTACHMENT_ID;
			END LOOP;
			CLOSE EXP_CURSOR1;
		END;
END LOOP;
CLOSE EXP_CURSOR;
COMMIT;
END;
END
$$
DELIMITER ;
