DELIMITER $$
CREATE DEFINER=`fibi`@`%` FUNCTION `FN_CHK_ATTA_PROGRESS_REPORT`(
AV_AWARD_ID VARCHAR(10)) RETURNS varchar(6) CHARSET latin1
    DETERMINISTIC
BEGIN
DECLARE LS_COUNT INT;
SELECT COUNT(1) INTO LS_COUNT FROM AWARD_ATTACHMENT
WHERE AWARD_ID = AV_AWARD_ID
AND TYPE_CODE = 155;
IF LS_COUNT > 0 THEN
	RETURN 'TRUE';
ELSE
    RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
