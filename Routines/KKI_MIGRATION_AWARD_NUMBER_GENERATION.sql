DELIMITER $$
CREATE DEFINER=`fibi`@`%` PROCEDURE `KKI_MIGRATION_AWARD_NUMBER_GENERATION`(AV_TYPE INT)
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
		DECLARE LS_AWARD_NUMBER VARCHAR(12);
		DECLARE LI_AWARD_ID  DECIMAL(22,0);
		DECLARE LS_ACCOUNT_NUMBER VARCHAR(20);
		DECLARE LS_YEAR VARCHAR(10);
		DECLARE LI_CHILD_LEVEL INT;
		DECLARE LS_CHILD_ACCOUNT_NUMBER VARCHAR(20);
		DECLARE LS_CHILD_YEAR  VARCHAR(20);
		BEGIN
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWARD_CURSOR CURSOR FOR
		SELECT ACCOUNT_NUMBER,YEAR
		FROM MIGRATION_AWARD
		WHERE YEAR IS NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Exception','AWARD',LS_ERROR,'Before Migration',LS_FILE_TYPE);
			COMMIT;
		END;
		SELECT IFNULL(MAX(AWARD_ID),0)+1 INTO LI_AWARD_ID
		FROM AWARD;
		SELECT AWARD_NUMBER INTO LS_AWARD_NUMBER
		FROM AWARD_NEXTVALUE;
		OPEN MIGRATION_AWARD_CURSOR;
		MIGRATION_AWARD_CURSOR_LOOP : LOOP
				FETCH MIGRATION_AWARD_CURSOR INTO 	LS_ACCOUNT_NUMBER,
													LS_YEAR;
				IF DONE1 THEN
					LEAVE MIGRATION_AWARD_CURSOR_LOOP;
				END IF;
				SET LI_CHILD_LEVEL  = 1;
				SET LS_AWARD_NUMBER = LS_AWARD_NUMBER + 1;
				SET LI_AWARD_ID = LI_AWARD_ID +1;
				UPDATE MIGRATION_AWARD
				SET AWARD_NUMBER = CONCAT(LPAD(LS_AWARD_NUMBER, 6, "0"),'-00001'),
				AWARD_ID  = LI_AWARD_ID,
				SEQUENCE_NUMBER = 1
				WHERE ACCOUNT_NUMBER = LS_ACCOUNT_NUMBER;
				COMMIT;
				BEGIN
					DECLARE DONE2 INT DEFAULT FALSE;
					DECLARE MIGRATION_AWARD_CURSOR2 CURSOR FOR
					SELECT ACCOUNT_NUMBER,YEAR
					FROM MIGRATION_AWARD
					WHERE ACCOUNT_NUMBER LIKE   CONCAT(LS_ACCOUNT_NUMBER, '%')
					ORDER BY YEAR ASC;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
					OPEN MIGRATION_AWARD_CURSOR2;
					MIGRATION_AWARD_CURSOR_LOOP2 : LOOP
							FETCH MIGRATION_AWARD_CURSOR2 INTO 	LS_CHILD_ACCOUNT_NUMBER,LS_CHILD_YEAR;
							IF DONE2 THEN
								LEAVE MIGRATION_AWARD_CURSOR_LOOP2;
							END IF;
							IF LS_CHILD_YEAR IS NOT NULL THEN
								SET LI_CHILD_LEVEL  = LI_CHILD_LEVEL + 1;
								SET LI_AWARD_ID = LI_AWARD_ID +1;
								UPDATE MIGRATION_AWARD
								SET AWARD_NUMBER = CONCAT(LPAD(LS_AWARD_NUMBER, 6, "0"),'-',LPAD(LI_CHILD_LEVEL, 5, "0")),
								AWARD_ID  = LI_AWARD_ID,
								SEQUENCE_NUMBER = 1
								WHERE ACCOUNT_NUMBER = LS_CHILD_ACCOUNT_NUMBER;
								COMMIT;
							END IF;
					END LOOP;
					CLOSE MIGRATION_AWARD_CURSOR2;
				END;
		END LOOP;
		CLOSE MIGRATION_AWARD_CURSOR;
END;
UPDATE AWARD_NEXTVALUE SET AWARD_NUMBER = LS_AWARD_NUMBER +1 ;
UPDATE AWARD_ID_GENERATOR SET NEXT_VAL = LI_AWARD_ID+1;
END
$$
DELIMITER ;
