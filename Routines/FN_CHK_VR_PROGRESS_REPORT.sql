DELIMITER $$
CREATE  FUNCTION `FN_CHK_VR_PROGRESS_REPORT`(
AV_AWARD_ID DECIMAL(22,0)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_COUNT INT;
SET LS_COUNT = 0;
SELECT COUNT(*) INTO LS_COUNT
FROM AWARD
WHERE AWARD_ID = AV_AWARD_ID
AND AWARD_VARIATION_TYPE_CODE = '50';
	IF LS_COUNT > 0 THEN
		RETURN 'TRUE';
	ELSE
		RETURN 'FALSE';
	END IF;
END
$$
DELIMITER ;
