DELIMITER $$
CREATE DEFINER=`fibi`@`%` PROCEDURE `eps_attchment_feed`(av_type int)
BEGIN
declare ls_ATTACHMENT_ID int(11);
declare ls_ATTACHMENT longblob;
declare unique_id varchar(36);
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE LI_PROPOSAL_ID int(10);
DECLARE LI_PROP_ATTACHMENT_ID int(10);
declare LI_DOCUMENT_ID int(4);
DECLARE EXP_CURSOR CURSOR FOR
SELECT ATTACHMENT_ID,ATTACHMENT FROM kki_prod.fibi_proposal_attachments;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN EXP_CURSOR;
EXP_CURSOR_LOOP : LOOP
        FETCH EXP_CURSOR INTO  ls_ATTACHMENT_ID,ls_ATTACHMENT ;
        select uuid() into unique_id from dual;
		IF DONE1 THEN
			LEAVE EXP_CURSOR_LOOP;
		END IF;
		update fibikki_prod.EPS_PROPOSAL_ATTACHMENTS set FILE_DATA_ID = unique_id
        where ATTACHMENT_ID = ls_ATTACHMENT_ID;
        insert into fibikki_prod.FILE_DATA values(unique_id,ls_ATTACHMENT);
END LOOP;
commit;
CLOSE EXP_CURSOR;
BEGIN
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE EXP_CURSOR CURSOR FOR
SELECT DISTINCT PROPOSAL_ID
FROM fibikki_prod.EPS_PROPOSAL_ATTACHMENTS;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
SET LI_DOCUMENT_ID = 0;
OPEN EXP_CURSOR;
EXP_CURSOR_LOOP : LOOP
        FETCH EXP_CURSOR INTO  LI_PROPOSAL_ID;
		IF DONE2 THEN
			LEAVE EXP_CURSOR_LOOP;
		END IF;
		SET LI_DOCUMENT_ID = 0;
		BEGIN
        	DECLARE DONE3 INT DEFAULT FALSE;
			DECLARE EXP_CURSOR1 CURSOR FOR
			SELECT ATTACHMENT_ID
			FROM fibikki_prod.EPS_PROPOSAL_ATTACHMENTS
			WHERE PROPOSAL_ID = LI_PROPOSAL_ID;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE3 = TRUE;
			OPEN EXP_CURSOR1;
			EXP_CURSOR_LOOP1 : LOOP
					FETCH EXP_CURSOR1 INTO  LI_PROP_ATTACHMENT_ID;
					IF DONE3 THEN
						LEAVE EXP_CURSOR_LOOP1;
					END IF;
					SET LI_DOCUMENT_ID = LI_DOCUMENT_ID + 1;
					UPDATE fibikki_prod.EPS_PROPOSAL_ATTACHMENTS  SET DOCUMENT_ID = LI_DOCUMENT_ID WHERE ATTACHMENT_ID = LI_PROP_ATTACHMENT_ID;
			END LOOP;
			CLOSE EXP_CURSOR1;
		END;
END LOOP;
CLOSE EXP_CURSOR;
COMMIT;
END;
END
$$
DELIMITER ;
