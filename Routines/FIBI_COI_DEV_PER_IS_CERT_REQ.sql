CREATE  FUNCTION `FIBI_COI_DEV_PER_IS_CERT_REQ`(
  AV_PROPOSAL_NUMBER VARCHAR(50),
  AV_PROP_PERSON_ROLE_ID VARCHAR(10),
  AV_PERSON_PROJ_ROLE VARCHAR(100)
) RETURNS int
    DETERMINISTIC
BEGIN
  DECLARE IS_CERTIFICATION_REQUIRED INT DEFAULT 0;
  DECLARE LI_COUNT INT DEFAULT 0;
  IF AV_PROP_PERSON_ROLE_ID IN ('3','4','5','1','6') THEN
    RETURN 1;
  END IF;
  IF AV_PROP_PERSON_ROLE_ID IN('2','7') AND AV_PERSON_PROJ_ROLE IN ('Other Significant Contributor', 'Subaward Investigator', 'Consultant') THEN
    RETURN 0;
  END IF;
  SELECT COUNT(E.PROPOSAL_ID) INTO LI_COUNT
  FROM EPS_PROPOSAL E
  LEFT JOIN SPONSOR_DISCLOSURE_REQUIREMENTS S
    ON (E.SPONSOR_CODE = S.SPONSOR_CODE OR E.PRIME_SPONSOR_CODE = S.SPONSOR_CODE)
  WHERE E.PROPOSAL_ID = AV_PROPOSAL_NUMBER
    AND S.KEY_PERSON_DISCL_REQUIREMENT = 'ALL';
  IF LI_COUNT > 1 THEN
    RETURN 1;
  END IF;
  SELECT COUNT(E.PROPOSAL_ID) INTO LI_COUNT
  FROM EPS_PROPOSAL E
  LEFT JOIN SPONSOR_DISCLOSURE_REQUIREMENTS S
    ON (E.SPONSOR_CODE = S.SPONSOR_CODE OR E.PRIME_SPONSOR_CODE = S.SPONSOR_CODE)
  WHERE E.PROPOSAL_ID = AV_PROPOSAL_NUMBER
    AND S.KEY_PERSON_DISCL_REQUIREMENT = 'PI-COI';
  IF LI_COUNT > 1 AND AV_PROP_PERSON_ROLE_ID IN ('1','6','3','4') THEN
    RETURN 1;
  END IF;
  RETURN 0;
END
$$
DELIMITER ;
