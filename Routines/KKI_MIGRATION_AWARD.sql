DELIMITER $$
CREATE DEFINER=`fibi`@`%` PROCEDURE `KKI_MIGRATION_AWARD`(AV_TYPE INT)
BEGIN
DECLARE LI_MA_MIGRATION_AWARD_ID	INT(11);
DECLARE LS_LEGACY_PROJECT_ID	VARCHAR(100);
DECLARE LS_LEGACY_WBS_NUMBER	VARCHAR(100);
DECLARE LS_MA_GRANT_CODE	VARCHAR(50);
DECLARE LS_MA_ACCOUNT_NUMBER	VARCHAR(100);
DECLARE LI_MA_GRANT_HEADER_ID	VARCHAR(10);
DECLARE LS_MA_LEAD_UNIT_NUMBER	VARCHAR(8);
DECLARE LS_MA_LEAD_UNIT_NAME	VARCHAR(8);
DECLARE LS_MA_ACCOUNT_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_ACTIVITY_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_STATUS_DESC	VARCHAR(200);
DECLARE LS_MA_SPONSOR_CODE	VARCHAR(6);
DECLARE LS_MA_PRIME_SPONSOR_CODE	VARCHAR(6);
DECLARE LD_MA_START_DATE	VARCHAR(10);
DECLARE LD_MA_END_DATE	VARCHAR(10);
DECLARE LS_MA_SUB_LEAD_UNIT_CODE	VARCHAR(8);
DECLARE RESEARCH_AREA_DESC	VARCHAR(200);
DECLARE PI_PERSON_ID	VARCHAR(20);
DECLARE LS_MA_RIE_DOMAIN	VARCHAR(200);
DECLARE LS_STEM_NON_STEM	VARCHAR(10);
DECLARE LS_DISPLAY_AT_ACAD_PROFILE	VARCHAR(3);
DECLARE LS_RESEARCH_AREA_DESC VARCHAR(200);
DECLARE LS_PI_PERSON_ID VARCHAR(40);
DECLARE LS_TITLE VARCHAR(2000);
DECLARE LI_COUNT INT;
DECLARE LS_FILE_TYPE VARCHAR(50);
DECLARE LS_PI_ROLODEX_ID VARCHAR(20);
DECLARE LI_FLAG INT;
DECLARE LI_APPROVED_BUDGET VARCHAR(20);
DECLARE LS_SPONSOR_AWARD_NUMBER VARCHAR(100);
DECLARE LS_ACCOUNT_NUMBER  VARCHAR(100);
DECLARE LI_IP_ID  INT(11);
DECLARE LS_PI_USER_NAME VARCHAR(100);
DECLARE LS_PI_EMPLOYEE_TYPE VARCHAR(100);
DECLARE LS_UNIT_NAME VARCHAR(100);
DECLARE LD_AWARD_NOTICE_DATE VARCHAR(100);
DECLARE LS_SPONSOR_NAME VARCHAR(100);
DECLARE LS_PRIME_SPONSOR_NAME VARCHAR(100);
DECLARE LS_CFDA VARCHAR(100);
DECLARE LS_MANAGER VARCHAR(100);
DECLARE LI_SEQUENCE_NUMBER INT(3);
DECLARE LS_UNIT_NUMBER VARCHAR(100);
declare LS_WORKFLOW_AWARD_STATUS_CODE varchar(10);
DECLARE LI_AWARD_ID  DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LS_AWARD_TYPE_CODE VARCHAR(3);
DECLARE LS_ACTIVITY_TYPE_CODE VARCHAR(3);
DECLARE LS_ACCOUNT_TYPE_CODE  VARCHAR(3);
DECLARE LS_STATUS_CODE   VARCHAR(3);
DECLARE LI_AWARD_FUNDING_PROPOSAL_ID  INT(11);
DECLARE LS_CAMPUS VARCHAR(50);
DECLARE LS_FULL_NAME VARCHAR(90);
DECLARE LS_EMAIL_ADDRESS	varchar(255);
DECLARE LI_AWARD_PERSON_ID INT(11);
DECLARE LS_HOME_UNIT VARCHAR(8);
DECLARE LI_AWARD_PERSON_UNIT_ID DECIMAL(22,0);
DECLARE LI_AWARD_PERSON_ROLE_ID     INT(11);
DECLARE LS_PERSON_ROLE_ROLODEX_ID VARCHAR(40);
DECLARE LS_PERSON_ROLE_PERSON_ID VARCHAR(40);
DECLARE LS_AWARD_NOTICE_DATE VARCHAR(10);
DECLARE LS_AWARD_SEQUENCE_STATUS VARCHAR(50);
declare LI_AWARD_SPONSOR_CONTACT_ID  INT(11);
DECLARE LS_CONTACT_PERSON_ID VARCHAR(100);
DECLARE LS_CONTACT_FULL_NAME  VARCHAR(100);
DECLARE LS_CONTACT_PER_TITLE VARCHAR(100);
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWARD_CURSOR CURSOR FOR
		SELECT MA.MIGRATION_AWARD_ID,
		MA.ACCOUNT_NUMBER,
		MA.SPONSOR_AWARD_NUMBER,
		MA.ACCOUNT_TYPE_DESCRIPTION,
		MA.AWARD_TYPE_DESCRIPTION,
		MA.ACTIVITY_TYPE_DESCRIPTION,
		MA.AWARD_STATUS_DESCRIPTION,
		MA.TITLE,
		MA.START_DATE,
		MA.END_DATE,
        MA.INST_PROPOSAL,
		MA.PI_USER_NAME,
		MA.PI_EMPLOYEE_TYPE,
		MA.UNIT_NAME,
		MA.AWARD_NOTICE_DATE,
		MA.SPONSOR_NAME,
		MA.PRIME_SPONSOR_NAME,
		MA.CFDA,
		MA.MANAGER,
		MA.AWARD_NUMBER,
		MA.AWARD_ID,
		MA.SEQUENCE_NUMBER
		FROM MIGRATION_AWARD MA
        WHERE MA.ACCOUNT_NUMBER IS NOT NULL
		AND MA.AWARD_NUMBER IS NOT NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Exception','AWARD',LS_ERROR,'Before Migration',LS_FILE_TYPE);
			COMMIT;
		END;
		OPEN MIGRATION_AWARD_CURSOR;
		MIGRATION_AWARD_CURSOR_LOOP : LOOP
				FETCH MIGRATION_AWARD_CURSOR INTO 	LI_MA_MIGRATION_AWARD_ID,
													LS_ACCOUNT_NUMBER,
													LS_SPONSOR_AWARD_NUMBER,
													LS_MA_ACCOUNT_TYPE_DESC,
													LS_MA_AWARD_TYPE_DESC,
													LS_MA_ACTIVITY_TYPE_DESC,
													LS_MA_AWARD_STATUS_DESC,
													LS_TITLE,
													LD_MA_START_DATE,
													LD_MA_END_DATE,
													LI_IP_ID,
													LS_PI_USER_NAME,
													LS_PI_EMPLOYEE_TYPE,
													LS_UNIT_NAME,
													LD_AWARD_NOTICE_DATE,
													LS_SPONSOR_NAME,
													LS_PRIME_SPONSOR_NAME,
													LS_CFDA,
													LS_MANAGER,
													LS_AWARD_NUMBER,
													LI_AWARD_ID,
													LI_SEQUENCE_NUMBER;
				IF DONE1 THEN
					LEAVE MIGRATION_AWARD_CURSOR_LOOP;
				END IF;
				AWARD_LABEL :BEGIN
				SET LS_FILE_TYPE = NULL;
				SET LS_AWARD_TYPE_CODE = NULL;
				SET LS_ACTIVITY_TYPE_CODE = NULL;
				SET LS_ACCOUNT_TYPE_CODE = NULL;
				SET LS_STATUS_CODE = NULL;
				SET LS_AWARD_SEQUENCE_STATUS = NULL;
				SET LS_MA_SPONSOR_CODE = NULL;
				SET LS_MA_PRIME_SPONSOR_CODE = NULL;
				set LS_UNIT_NUMBER = NULL;
				SET LS_WORKFLOW_AWARD_STATUS_CODE = 3;
				IF (IFNULL(TRIM(LI_IP_ID),'') <> '') THEN
					SELECT COUNT(*) INTO LI_COUNT
					FROM PROPOSAL WHERE PROPOSAL_ID = LI_IP_ID;
					IF (LI_COUNT = 0) THEN
						SET LI_IP_ID = NULL;
					END IF;
				END IF;
				IF (  IFNULL(TRIM(LS_AWARD_NUMBER),'') = '' ) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (  IFNULL(TRIM(LS_ACCOUNT_NUMBER),'') = '' ) THEN
					LEAVE AWARD_LABEL;
				ELSE
                	SELECT COUNT(*) INTO LI_COUNT
					FROM MIGRATION_AWARD WHERE ACCOUNT_NUMBER = TRIM(LS_ACCOUNT_NUMBER);
                    IF LI_COUNT > 1 THEN
						LEAVE AWARD_LABEL;
					END IF;
				END IF;
				IF 	(IFNULL(TRIM(LS_MA_ACCOUNT_TYPE_DESC),'') <> '' AND UPPER(TRIM(LS_MA_ACCOUNT_TYPE_DESC)) NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM ACCOUNT_TYPE)) THEN
						LEAVE AWARD_LABEL;
				END IF;
				IF ( IFNULL(TRIM(LS_MA_ACTIVITY_TYPE_DESC),'') ='' ) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ( IFNULL(TRIM(LS_MA_ACTIVITY_TYPE_DESC),'') <> '' AND UPPER(TRIM(LS_MA_ACTIVITY_TYPE_DESC))  NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM ACTIVITY_TYPE)) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_MA_AWARD_STATUS_DESC),'') = '') THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ( (IFNULL(TRIM(LS_MA_AWARD_STATUS_DESC),'') <> '') AND (UPPER(TRIM(LS_MA_AWARD_STATUS_DESC))  NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM AWARD_STATUS))) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ( IFNULL(TRIM(LS_TITLE),'') ='' ) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ( LENGTH(IFNULL(TRIM(LS_TITLE),'')) >300 ) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_UNIT_NAME),'')= '') THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_UNIT_NAME),'') <>  '' AND UPPER(TRIM(LS_UNIT_NAME)) NOT IN (SELECT UPPER(TRIM(UNIT_NAME)) FROM UNIT)) THEN
					LEAVE AWARD_LABEL;
				ELSE
						SELECT UNIT_NUMBER INTO LS_UNIT_NUMBER
						FROM UNIT
						WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_UNIT_NAME));
				END IF;
				IF ( IFNULL(TRIM(LS_MA_AWARD_TYPE_DESC),'') <> '' AND  UPPER(TRIM(LS_MA_AWARD_TYPE_DESC))  NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM AWARD_TYPE)) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_SPONSOR_NAME),'')= '') THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_SPONSOR_NAME),'') <> '' AND UPPER(TRIM(LS_SPONSOR_NAME)) NOT IN(SELECT UPPER(TRIM(SPONSOR_NAME)) FROM SPONSOR)) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_PRIME_SPONSOR_NAME),'') <> ''  AND UPPER(TRIM(LS_PRIME_SPONSOR_NAME)) NOT IN(SELECT UPPER(TRIM(SPONSOR_NAME)) FROM SPONSOR)) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ( IFNULL(TRIM(LD_MA_START_DATE),'')  = '' OR STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') IS NULL ) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ( IFNULL(TRIM(LD_MA_END_DATE),'') = '' OR STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') IS NULL ) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (   IFNULL(TRIM(LD_AWARD_NOTICE_DATE),'') <> ''  AND STR_TO_DATE(LD_AWARD_NOTICE_DATE,'%d-%m-%Y') IS NULL ) THEN
					LEAVE AWARD_LABEL;
				END IF;
			    IF (  STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') IS NOT NULL AND TRIM(LD_MA_START_DATE) <> ''
				      AND STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') IS NOT NULL AND TRIM(LD_MA_END_DATE) <> ''
					  AND STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') > STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') )THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_PI_USER_NAME),'')= '')  THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'')= '') THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF (IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'')<> '' AND UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)) NOT IN ('EMPLOYEE','NON-EMPLOYEE')) THEN
					LEAVE AWARD_LABEL;
				END IF;
				IF ((IFNULL(TRIM(LS_PI_USER_NAME),'')) <> '' AND IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'') <> '' AND (IFNULL(UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)),'')) = 'EMPLOYEE' ) THEN
						SELECT COUNT(1) INTO LI_FLAG FROM PERSON
						WHERE UPPER(TRIM(USER_NAME))  = UPPER(TRIM(LS_PI_USER_NAME));
						IF LI_FLAG = 0 THEN
							LEAVE AWARD_LABEL;
						END IF;
				ELSE
					IF ((IFNULL(TRIM(LS_PI_USER_NAME),'')) <> '' AND IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'') <> '' AND (IFNULL(UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)),'')) = 'NON-EMPLOYEE' ) THEN
						SELECT COUNT(1) INTO LI_FLAG FROM ROLODEX
						WHERE UPPER(TRIM(FULL_NAME))  =UPPER(TRIM(LS_PI_USER_NAME));
						IF LI_FLAG = 0 THEN
							LEAVE AWARD_LABEL;
						END IF;
					END IF;
                END IF;
				IF ( IFNULL(TRIM(LS_SPONSOR_AWARD_NUMBER),'') <> '' AND LENGTH(IFNULL(TRIM(LS_SPONSOR_AWARD_NUMBER),'')) >70 ) THEN
					LEAVE AWARD_LABEL;
				END IF;
IF ( IFNULL(TRIM(LS_MA_AWARD_TYPE_DESC),'') <> '') THEN
				SELECT AWARD_TYPE_CODE INTO  LS_AWARD_TYPE_CODE
				FROM  AWARD_TYPE
				WHERE UPPER(TRIM(DESCRIPTION)) =   UPPER(TRIM(LS_MA_AWARD_TYPE_DESC));
END IF;
IF ( IFNULL(TRIM(LS_MA_ACTIVITY_TYPE_DESC),'') <> '') THEN
				SELECT ACTIVITY_TYPE_CODE INTO  LS_ACTIVITY_TYPE_CODE
				FROM  ACTIVITY_TYPE
				WHERE UPPER(TRIM(DESCRIPTION)) =   UPPER(TRIM(LS_MA_ACTIVITY_TYPE_DESC));
END IF;
IF ( IFNULL(TRIM(LS_MA_ACCOUNT_TYPE_DESC),'') <> '') THEN
				SELECT ACCOUNT_TYPE_CODE INTO  LS_ACCOUNT_TYPE_CODE
				FROM  ACCOUNT_TYPE
				WHERE UPPER(TRIM(DESCRIPTION)) =   UPPER(TRIM(LS_MA_ACCOUNT_TYPE_DESC));
END IF;
IF ( IFNULL(TRIM(LS_MA_AWARD_STATUS_DESC),'') <> '') THEN
				SELECT STATUS_CODE INTO  LS_STATUS_CODE
				FROM  AWARD_STATUS
				WHERE UPPER(TRIM(DESCRIPTION)) =   UPPER(TRIM(LS_MA_AWARD_STATUS_DESC));
				IF UPPER(TRIM(LS_MA_AWARD_STATUS_DESC)) = 'ACTIVE' THEN
					SET LS_AWARD_SEQUENCE_STATUS = 'ACTIVE';
				ELSEIF UPPER(TRIM(LS_MA_AWARD_STATUS_DESC)) = 'CLOSED' THEN
					SET LS_AWARD_SEQUENCE_STATUS = 'ARCHIVE';
				ELSEIF UPPER(TRIM(LS_MA_AWARD_STATUS_DESC)) = 'PENDING' THEN
					SET LS_AWARD_SEQUENCE_STATUS = 'PENDING';
				END IF;
END IF;
IF ( IFNULL(TRIM(LS_SPONSOR_NAME),'') <> '') THEN
				SELECT SPONSOR_CODE INTO  LS_MA_SPONSOR_CODE
				FROM  SPONSOR
				WHERE UPPER(TRIM(SPONSOR_NAME)) =   UPPER(TRIM(LS_SPONSOR_NAME))
                and ACTV_IND = 'Y';
END IF;
IF ( IFNULL(TRIM(LS_PRIME_SPONSOR_NAME),'') <> '') THEN
				SELECT SPONSOR_CODE INTO  LS_MA_PRIME_SPONSOR_CODE
				FROM  SPONSOR
				WHERE UPPER(TRIM(SPONSOR_NAME)) =   UPPER(TRIM(LS_PRIME_SPONSOR_NAME))
                and ACTV_IND = 'Y';
END IF;
			INSERT INTO AWARD( AWARD_ID,
									AWARD_NUMBER,
									SEQUENCE_NUMBER,
									ACCOUNT_NUMBER,
									LEAD_UNIT_NUMBER,
									TITLE,
									AWARD_TYPE_CODE,
									ACTIVITY_TYPE_CODE,
									ACCOUNT_TYPE_CODE,
									STATUS_CODE,
									SPONSOR_AWARD_NUMBER,
									SPONSOR_CODE,
									BEGIN_DATE,
									FINAL_EXPIRATION_DATE,
									PRIME_SPONSOR_CODE,
									AWARD_SEQUENCE_STATUS,
									UPDATE_TIMESTAMP,
									UPDATE_USER,
									IS_LATEST,
									CREATE_TIMESTAMP,
									CREATE_USER,
									WORKFLOW_AWARD_STATUS_CODE,
									AWARD_DOCUMENT_TYPE_CODE,
									CFDA_NUMBER,
									AWARD_EFFECTIVE_DATE
									)
									SELECT
									LI_AWARD_ID,
									LS_AWARD_NUMBER,
									LI_SEQUENCE_NUMBER,
									LS_ACCOUNT_NUMBER,
									TRIM(LS_UNIT_NUMBER),
									TRIM(LS_TITLE),
									LS_AWARD_TYPE_CODE,
									LS_ACTIVITY_TYPE_CODE,
									LS_ACCOUNT_TYPE_CODE,
									LS_STATUS_CODE,
									TRIM(LS_SPONSOR_AWARD_NUMBER),
									TRIM(LS_MA_SPONSOR_CODE),
									DATE_FORMAT(STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y'),'%Y-%m-%d'),
									DATE_FORMAT(STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y'),'%Y-%m-%d'),
									TRIM(LS_MA_PRIME_SPONSOR_CODE),
									LS_AWARD_SEQUENCE_STATUS,
									UTC_TIMESTAMP(),
									'quickstart',
									'Y',
									UTC_TIMESTAMP(),
									'quickstart',
									LS_WORKFLOW_AWARD_STATUS_CODE,
									1,
									LS_CFDA,
									DATE_FORMAT(STR_TO_DATE(LD_AWARD_NOTICE_DATE,'%d-%m-%Y'),'%Y-%m-%d') ;
IF (IFNULL(TRIM(LS_PI_USER_NAME),'') <> '' AND  UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)) = 'EMPLOYEE') THEN
	SELECT PERSON_ID,EMAIL_ADDRESS,FULL_NAME INTO LS_PI_PERSON_ID,LS_EMAIL_ADDRESS,LS_FULL_NAME
	FROM PERSON WHERE UPPER(TRIM(USER_NAME)) = UPPER(TRIM(LS_PI_USER_NAME));
ELSE
	SET LS_PI_PERSON_ID = NULL;
END IF;
IF (IFNULL(TRIM(LS_PI_USER_NAME),'') <> '' AND  UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)) = 'NON-EMPLOYEE') THEN
	SELECT ROLODEX_ID,EMAIL_ADDRESS,FULL_NAME INTO LS_PI_ROLODEX_ID,LS_EMAIL_ADDRESS,LS_FULL_NAME
	FROM ROLODEX WHERE UPPER(TRIM(FULL_NAME)) = UPPER(TRIM(LS_PI_USER_NAME));
ELSE
	SET LS_PI_ROLODEX_ID = NULL;
END IF;
SELECT IFNULL(MAX(AWARD_PERSON_ID),0)+1 INTO LI_AWARD_PERSON_ID
FROM AWARD_PERSONS;
INSERT INTO AWARD_PERSONS(AWARD_PERSON_ID,
							AWARD_ID,
							AWARD_NUMBER,
							SEQUENCE_NUMBER,
							PERSON_ID,
							ROLODEX_ID,
							FULL_NAME,
							PERCENTAGE_OF_EFFORT,
							PERSON_ROLE_ID,
							PI_FLAG,
							IS_MULTI_PI,
							UPDATE_TIMESTAMP,
							UPDATE_USER,
							EMAIL_ADDRESS)
				VALUES(LI_AWARD_PERSON_ID,
						LI_AWARD_ID,
						LS_AWARD_NUMBER,
						LI_SEQUENCE_NUMBER,
						TRIM(LS_PI_PERSON_ID),
						TRIM(LS_PI_ROLODEX_ID),
						LS_FULL_NAME,
						100,
						3,
						'Y',
						'N',
						UTC_TIMESTAMP(),
						'quickstart',
						LS_EMAIL_ADDRESS
				);
COMMIT;
SELECT IFNULL(MAX(AWARD_PERSON_UNIT_ID),0)+1 INTO LI_AWARD_PERSON_UNIT_ID
FROM AWARD_PERSON_UNIT;
				INSERT INTO AWARD_PERSON_UNIT(AWARD_PERSON_UNIT_ID,
												AWARD_PERSON_ID,
												AWARD_ID,
												AWARD_NUMBER,
												SEQUENCE_NUMBER,
												UNIT_NUMBER,
												LEAD_UNIT_FLAG,
												UPDATE_TIMESTAMP,
												UPDATE_USER)
				VALUES(LI_AWARD_PERSON_UNIT_ID,
						LI_AWARD_PERSON_ID,
						LI_AWARD_ID,
						LS_AWARD_NUMBER,
						LI_SEQUENCE_NUMBER,
						LS_UNIT_NUMBER,
						'Y',
						UTC_TIMESTAMP(),
						'quickstart'
				);
IF IFNULL(TRIM(LS_PI_PERSON_ID),'') <> '' THEN
			SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID
			FROM AWARD_PERSON_ROLES;
				INSERT INTO AWARD_PERSON_ROLES(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,TRIM(LS_PI_PERSON_ID),14,UTC_TIMESTAMP(),'quickstart');
				COMMIT;
			SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID
			FROM AWARD_PERSON_ROLES;
				INSERT INTO AWARD_PERSON_ROLES(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,TRIM(LS_PI_PERSON_ID),45,UTC_TIMESTAMP(),'quickstart');
				COMMIT;
			SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID
			FROM AWARD_PERSON_ROLES;
				INSERT INTO AWARD_PERSON_ROLES(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,TRIM(LS_PI_PERSON_ID),47,UTC_TIMESTAMP(),'quickstart');
				COMMIT;
			SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID
			FROM AWARD_PERSON_ROLES;
				INSERT INTO AWARD_PERSON_ROLES(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,TRIM(LS_PI_PERSON_ID),48,UTC_TIMESTAMP(),'quickstart');
				COMMIT;
END IF;
IF IFNULL(TRIM(LS_MANAGER),'') <> '' THEN
		SELECT PERSON_ID,FULL_NAME,PRIMARY_TITLE INTO LS_CONTACT_PERSON_ID,LS_CONTACT_FULL_NAME,LS_CONTACT_PER_TITLE
		FROM PERSON
		WHERE UPPER(TRIM(USER_NAME)) = UPPER(TRIM(LS_MANAGER));
		SELECT IFNULL(MAX(AWARD_SPONSOR_CONTACT_ID),0)+1 INTO LI_AWARD_SPONSOR_CONTACT_ID
		FROM AWARD_CONTACT;
		INSERT INTO AWARD_CONTACT(AWARD_SPONSOR_CONTACT_ID,
		AWARD_ID,
		AWARD_NUMBER,
		SEQUENCE_NUMBER,
		ROLODEX_ID,
		FULL_NAME,
		CONTACT_ROLE_CODE,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		CONTACT_TYPE_CODE,
		PERSON_ID,
		DESIGNATION)
		VALUES(LI_AWARD_SPONSOR_CONTACT_ID
		,LI_AWARD_ID,
		LS_AWARD_NUMBER,
		LI_SEQUENCE_NUMBER,
		NULL,
		LS_CONTACT_FULL_NAME,
		NULL,
		UTC_TIMESTAMP(),
		'quickstart',
		1,
		LS_CONTACT_PERSON_ID,
		LS_CONTACT_PER_TITLE
		);
		COMMIT;
END IF;
IF IFNULL(TRIM(LI_IP_ID),'') <> '' THEN
	SELECT IFNULL(MAX(AWARD_FUNDING_PROPOSAL_ID),0)+1 INTO LI_AWARD_FUNDING_PROPOSAL_ID
	FROM AWARD_FUNDING_PROPOSALS;
	INSERT INTO AWARD_FUNDING_PROPOSALS
	(
		AWARD_FUNDING_PROPOSAL_ID,
		AWARD_ID,
		PROPOSAL_ID,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		IS_ACTIVE
	)
	VALUES(
		LI_AWARD_FUNDING_PROPOSAL_ID,
		LI_AWARD_ID,
		LI_IP_ID,
		UTC_TIMESTAMP(),
		'quickstart',
