CREATE DEFINER=`fibi`@`%` FUNCTION `FN_CHCK_PROP_INCOMPLTE_ATCHMNT`(AV_PROPOSAL_ID    VARCHAR(10)) RETURNS varchar(8) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT INT(3);
SELECT COUNT(*) INTO LI_COUNT
FROM EPS_PROPOSAL_ATTACHMENTS
WHERE PROPOSAL_ID = AV_PROPOSAL_ID;
IF LI_COUNT = 0 THEN
	RETURN 'TRUE';
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM EPS_PROPOSAL_ATTACHMENTS
WHERE PROPOSAL_ID = AV_PROPOSAL_ID
AND NARRATIVE_STATUS_CODE = 'I';
IF LI_COUNT = 0 THEN
	RETURN 'TRUE';
else
	RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
