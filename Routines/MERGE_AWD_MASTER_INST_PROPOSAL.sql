DELIMITER $$
CREATE DEFINER=`fibi`@`%` PROCEDURE `MERGE_AWD_MASTER_INST_PROPOSAL`(
AV_AWARD_ID 			DECIMAL(22,0),
AV_AWARD_NUMBER			VARCHAR(12),
AV_SEQUENCE_NUMBER		INT(4),
AV_VARIATION_TYPE_CODE	VARCHAR(3),
AV_UPDATE_USER			VARCHAR(60)
)
BEGIN
DECLARE LS_ERROR_MSG	VARCHAR(1000);
DECLARE LS_TABLE_NAME	VARCHAR(30);
DECLARE LI_FLAG			INT;
DECLARE LI_NEXT_VAL	INT(10);
DECLARE LI_MASTER_AWARD_ID	DECIMAL(22,0);
DECLARE LI_TOTAL_AWARD_FUNDING_PROPOSALS INT(10);
DECLARE LI_AWARD_FUNDING_PROPOSAL_ID	decimal(22,0);
DECLARE LI_AWARD_ID	decimal(22,0);
DECLARE LI_PROPOSAL_ID	int(10);
DECLARE LD_UPDATE_TIMESTAMP	timestamp(6);
DECLARE LS_UPDATE_USER	varchar(60);
DECLARE LS_IS_ACTIVE	varchar(255);
DECLARE LS_DOCUMENT_UPDATE_USER			VARCHAR(60);
DECLARE LS_DOCUMENT_UPDATE_TIMESTAMP	DATETIME;
		BEGIN
				DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
				BEGIN
					GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
					 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
					SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
					SELECT @full_error INTO LS_ERROR_MSG;
					INSERT INTO AWARD_ERROR_LOG(AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, ERROR_MESSAGE, PROCEDURE_NAME, TABLE_NAME,SECTION_CODE,VARIATION_TYPE_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
					VALUES(AV_AWARD_ID,AV_AWARD_NUMBER,AV_SEQUENCE_NUMBER,LS_ERROR_MSG,'MERGE_AWD_MASTER_INST_PROPOSAL',LS_TABLE_NAME,117,AV_VARIATION_TYPE_CODE,UTC_TIMESTAMP(),AV_UPDATE_USER);
					COMMIT;
				END;
				SET SQL_SAFE_UPDATES = 0;
				SET LS_TABLE_NAME = 'AWARD_FUNDING_PROPOSALS';
				SELECT COUNT(1) INTO LI_FLAG
				FROM AWARD
				WHERE AWARD_NUMBER = AV_AWARD_NUMBER
				AND SEQUENCE_NUMBER = 0;
				IF LI_FLAG > 0 THEN
					SELECT AWARD_ID INTO LI_MASTER_AWARD_ID
					FROM AWARD
					WHERE AWARD_NUMBER = AV_AWARD_NUMBER
					AND SEQUENCE_NUMBER = 0;
				END IF;
				SELECT COUNT(*) INTO LI_TOTAL_AWARD_FUNDING_PROPOSALS
				FROM AWARD_FUNDING_PROPOSALS
				WHERE AWARD_ID = AV_AWARD_ID;
				SELECT IFNULL(MAX(NEXT_VAL),0) INTO LI_NEXT_VAL FROM AWARD_FUNDING_PROPOSAL_ID_GENERATOR;
				UPDATE AWARD_FUNDING_PROPOSAL_ID_GENERATOR SET NEXT_VAL = LI_NEXT_VAL + LI_TOTAL_AWARD_FUNDING_PROPOSALS  + 1;
				COMMIT;
				BEGIN
					DECLARE DONE1 INT DEFAULT FALSE;
					DECLARE CUR_AWARD_FUNDING_PROPOSALS CURSOR FOR
					SELECT AWARD_FUNDING_PROPOSAL_ID,
							AWARD_ID,
							PROPOSAL_ID,
							UPDATE_TIMESTAMP,
							UPDATE_USER,
							IS_ACTIVE
					FROM AWARD_FUNDING_PROPOSALS
					WHERE AWARD_ID = AV_AWARD_ID;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
					OPEN CUR_AWARD_FUNDING_PROPOSALS;
					INSERT_AWARD_FUNDING_PROPOSALS_LOOP: LOOP
					FETCH CUR_AWARD_FUNDING_PROPOSALS INTO
					LI_AWARD_FUNDING_PROPOSAL_ID,
					LI_AWARD_ID,
					LI_PROPOSAL_ID,
					LD_UPDATE_TIMESTAMP,
					LS_UPDATE_USER,
					LS_IS_ACTIVE;
					IF DONE1 THEN
						LEAVE INSERT_AWARD_FUNDING_PROPOSALS_LOOP;
					END IF;
						SET LI_NEXT_VAL = LI_NEXT_VAL+1;
						INSERT INTO AWARD_FUNDING_PROPOSALS
						(AWARD_FUNDING_PROPOSAL_ID,
							AWARD_ID,
							PROPOSAL_ID,
							UPDATE_TIMESTAMP,
							UPDATE_USER,
							IS_ACTIVE)
						VALUES
						(LI_NEXT_VAL,
						LI_MASTER_AWARD_ID,
						LI_PROPOSAL_ID,
						LD_UPDATE_TIMESTAMP,
						LS_UPDATE_USER,
						LS_IS_ACTIVE);
					END LOOP;
					CLOSE CUR_AWARD_FUNDING_PROPOSALS;
				END;
		END;
END
$$
DELIMITER ;
