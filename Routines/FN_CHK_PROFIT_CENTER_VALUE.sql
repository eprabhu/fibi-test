CREATE DEFINER=`fibi`@`%` FUNCTION `FN_CHK_PROFIT_CENTER_VALUE`(
AV_AWARD_ID DECIMAL(22,0)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE  	LS_BA_CODE VARCHAR(4);
DECLARE  	LS_LEAD_UNIT_NUMBER VARCHAR(8);
DECLARE  	LS_PROFIT_CENTER VARCHAR(4000);
DECLARE 	LI_FLAG INT;
SELECT LEAD_UNIT_NUMBER INTO LS_LEAD_UNIT_NUMBER FROM AWARD where AWARD_ID = AV_AWARD_ID;
	SELECT	BA_CODE	INTO LS_BA_CODE
	FROM SAP_FEED_UNIT_MAPPING
	WHERE UNIT_NUMBER = LS_LEAD_UNIT_NUMBER;
SELECT COUNT(*) INTO LI_FLAG
FROM CUSTOM_DATA T1
WHERE T1.MODULE_ITEM_CODE = 1
AND T1.MODULE_SUB_ITEM_CODE = 0
AND T1.MODULE_SUB_ITEM_KEY = 0
AND T1.MODULE_ITEM_KEY = AV_AWARD_ID
AND T1.CUSTOM_DATA_ELEMENTS_ID = (	SELECT MAX(CUSTOM_DATA_ELEMENTS_ID) FROM CUSTOM_DATA_ELEMENTS
								WHERE CUSTOM_ELEMENT_NAME = 'PROFIT CENTER'
								AND IS_LATEST_VERSION = 'Y'
								AND IS_ACTIVE = 'Y'
									)
AND (T1.VALUE IS NOT NULL AND TRIM(T1.VALUE) <> '');
IF (LI_FLAG > 0) THEN
SELECT COUNT(CUSTOM_DATA_ELEMENTS_ID) INTO LI_FLAG
FROM CUSTOM_DATA T1
WHERE T1.MODULE_ITEM_CODE = 1
AND T1.MODULE_SUB_ITEM_CODE = 0
AND T1.MODULE_SUB_ITEM_KEY = 0
AND T1.MODULE_ITEM_KEY = AV_AWARD_ID
AND TRIM(LS_BA_CODE) = TRIM(LEFT(VALUE,4))
AND T1.CUSTOM_DATA_ELEMENTS_ID = (	SELECT MAX(CUSTOM_DATA_ELEMENTS_ID) FROM CUSTOM_DATA_ELEMENTS
								WHERE CUSTOM_ELEMENT_NAME = 'PROFIT CENTER'
								AND IS_LATEST_VERSION = 'Y'
								AND IS_ACTIVE = 'Y'
									);
		IF (LI_FLAG>0) THEN
			RETURN 'TRUE';
		ELSE
			RETURN 'FALSE';
		END IF;
ELSE
	RETURN 'TRUE';
END IF;
END
$$
