DELIMITER $$
CREATE  PROCEDURE `GET_MANPWR_RSRCE_COST_ALLOCATN`(
AV_PERSON_ID VARCHAR(40),
AV_START_DATE DATETIME,
AV_END_DATE DATETIME,
AV_AWARD_NUMBER VARCHAR(20),
AV_IS_COST_ALLOCATION_VALIDATION VARCHAR(1)
)
BEGIN
IF AV_IS_COST_ALLOCATION_VALIDATION = 'Y' THEN
	SELECT T1.POSITION_ID,T1.COST_ALLOCATION,T1.AWARD_NUMBER,T3.ACCOUNT_NUMBER FROM AWARD_MANPOWER_RESOURCE T1
	INNER JOIN AWARD_MANPOWER T2 ON T2.AWARD_MANPOWER_ID = T1.AWARD_MANPOWER_ID
	INNER JOIN AWARD T3 ON T3.AWARD_ID = T2.AWARD_ID
	WHERE T3.AWARD_ID IN (SELECT AWARD_ID FROM AWARD WHERE (AWARD_NUMBER,SEQUENCE_NUMBER) IN
	(SELECT AWARD_NUMBER,MAX(SEQUENCE_NUMBER) FROM AWARD WHERE AWARD_NUMBER in (
	SELECT AWARD_NUMBER FROM AWARD_MANPOWER WHERE AWARD_NUMBER <> AV_AWARD_NUMBER
	) group by award_number))
	AND T1.PERSON_ID = AV_PERSON_ID AND T1.COST_ALLOCATION is not null
	AND (
	CASE
	WHEN T1.CHARGE_START_DATE IS NOT NULL AND T1.CHARGE_END_DATE IS NOT NULL
		THEN (AV_START_DATE BETWEEN T1.CHARGE_START_DATE AND T1.CHARGE_END_DATE)
			OR (AV_END_DATE BETWEEN T1.CHARGE_START_DATE AND T1.CHARGE_END_DATE)
			OR (T1.CHARGE_START_DATE BETWEEN AV_START_DATE AND AV_END_DATE )
			OR (T1.CHARGE_END_DATE BETWEEN AV_START_DATE AND AV_END_DATE)
	ELSE
		(AV_START_DATE BETWEEN T1.PLAN_START_DATE AND T1.PLAN_END_DATE)
		OR (AV_END_DATE BETWEEN T1.PLAN_START_DATE AND T1.PLAN_END_DATE)
		OR (T1.PLAN_START_DATE BETWEEN AV_START_DATE AND AV_END_DATE )
		OR (T1.PLAN_END_DATE BETWEEN AV_START_DATE AND AV_END_DATE)
	END
	);
ELSE
	SELECT T1.POSITION_ID,T1.COST_ALLOCATION,T1.AWARD_NUMBER,T3.ACCOUNT_NUMBER FROM AWARD_MANPOWER_RESOURCE T1
	INNER JOIN AWARD_MANPOWER T2 ON T2.AWARD_MANPOWER_ID = T1.AWARD_MANPOWER_ID
	INNER JOIN AWARD T3 ON T3.AWARD_ID = T2.AWARD_ID
	WHERE T3.AWARD_NUMBER <> AV_AWARD_NUMBER AND T1.PERSON_ID = AV_PERSON_ID AND POSITION_OWNED_BY_AWARD = 'Y'
	AND T3.AWARD_SEQUENCE_STATUS = 'ACTIVE' AND T3.FINAL_EXPIRATION_DATE < AV_END_DATE AND T1.COST_ALLOCATION is not null;
END IF;
END
$$
DELIMITER ;
