DELIMITER $$
CREATE DEFINER=`fibi`@`%` PROCEDURE `KKI_MIGRATION_PREVALIDATION_AWARD`(AV_TYPE INT)
BEGIN
DECLARE LI_MA_MIGRATION_AWARD_ID	INT(11);
DECLARE LS_LEGACY_PROJECT_ID	VARCHAR(100);
DECLARE LS_LEGACY_WBS_NUMBER	VARCHAR(100);
DECLARE LS_MA_GRANT_CODE	VARCHAR(50);
DECLARE LS_MA_ACCOUNT_NUMBER	VARCHAR(100);
DECLARE LI_MA_GRANT_HEADER_ID	VARCHAR(10);
DECLARE LS_MA_LEAD_UNIT_NUMBER	VARCHAR(8);
DECLARE LS_MA_LEAD_UNIT_NAME	VARCHAR(8);
DECLARE LS_MA_ACCOUNT_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_ACTIVITY_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_STATUS_DESC	VARCHAR(200);
DECLARE LS_MA_SPONSOR_CODE	VARCHAR(6);
DECLARE LS_MA_PRIME_SPONSOR_CODE	VARCHAR(6);
DECLARE LD_MA_START_DATE	VARCHAR(10);
DECLARE LD_MA_END_DATE	VARCHAR(10);
DECLARE LS_MA_SUB_LEAD_UNIT_CODE	VARCHAR(8);
DECLARE RESEARCH_AREA_DESC	VARCHAR(200);
DECLARE PI_PERSON_ID	VARCHAR(20);
DECLARE LS_MA_RIE_DOMAIN	VARCHAR(200);
DECLARE LS_STEM_NON_STEM	VARCHAR(10);
DECLARE LS_DISPLAY_AT_ACAD_PROFILE	VARCHAR(3);
DECLARE LS_RESEARCH_AREA_DESC VARCHAR(200);
DECLARE LS_PI_PERSON_ID VARCHAR(40);
DECLARE LS_TITLE VARCHAR(2000);
DECLARE LI_COUNT INT;
DECLARE LS_FILE_TYPE VARCHAR(50);
DECLARE LS_PI_ROLODEX_ID VARCHAR(20);
DECLARE LI_FLAG INT;
DECLARE LI_APPROVED_BUDGET VARCHAR(20);
DECLARE LS_SPONSOR_AWARD_NUMBER VARCHAR(100);
DECLARE LS_ACCOUNT_NUMBER  VARCHAR(100);
DECLARE LI_IP_ID  INT(11);
DECLARE LS_PI_USER_NAME VARCHAR(100);
DECLARE LS_PI_EMPLOYEE_TYPE VARCHAR(100);
DECLARE LS_UNIT_NAME VARCHAR(100);
DECLARE LD_AWARD_NOTICE_DATE VARCHAR(100);
DECLARE LS_SPONSOR_NAME VARCHAR(100);
DECLARE LS_PRIME_SPONSOR_NAME VARCHAR(100);
DECLARE LS_CFDA VARCHAR(100);
DECLARE LS_MANAGER VARCHAR(100);
DECLARE LS_AWARD_EFFECTIVE_DATE VARCHAR(10);
DECLARE LS_AWARD_NUMBER VARCHAR(10);
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWARD_CURSOR CURSOR FOR
		SELECT MA.MIGRATION_AWARD_ID,
		MA.ACCOUNT_NUMBER,
		MA.SPONSOR_AWARD_NUMBER,
		MA.ACCOUNT_TYPE_DESCRIPTION,
		MA.AWARD_TYPE_DESCRIPTION,
		MA.ACTIVITY_TYPE_DESCRIPTION,
		MA.AWARD_STATUS_DESCRIPTION,
		MA.TITLE,
		MA.START_DATE,
		MA.END_DATE,
        MA.INST_PROPOSAL,
		MA.PI_USER_NAME,
		MA.PI_EMPLOYEE_TYPE,
		MA.UNIT_NAME,
		MA.AWARD_NOTICE_DATE,
		MA.SPONSOR_NAME,
		MA.PRIME_SPONSOR_NAME,
		MA.CFDA,
		MA.MANAGER,
		MA.AWARD_NUMBER
		FROM MIGRATION_AWARD MA;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(LS_LEGACY_PROJECT_ID,LS_LEGACY_WBS_NUMBER,'Exception','AWARD',LS_ERROR,'Before Migration',LS_FILE_TYPE);
			COMMIT;
		END;
		OPEN MIGRATION_AWARD_CURSOR;
		MIGRATION_AWARD_CURSOR_LOOP : LOOP
				FETCH MIGRATION_AWARD_CURSOR INTO 	LI_MA_MIGRATION_AWARD_ID,
													LS_ACCOUNT_NUMBER,
													LS_SPONSOR_AWARD_NUMBER,
													LS_MA_ACCOUNT_TYPE_DESC,
													LS_MA_AWARD_TYPE_DESC,
													LS_MA_ACTIVITY_TYPE_DESC,
													LS_MA_AWARD_STATUS_DESC,
													LS_TITLE,
													LD_MA_START_DATE,
													LD_MA_END_DATE,
													LI_IP_ID,
													LS_PI_USER_NAME,
													LS_PI_EMPLOYEE_TYPE,
													LS_UNIT_NAME,
													LD_AWARD_NOTICE_DATE,
													LS_SPONSOR_NAME,
													LS_PRIME_SPONSOR_NAME,
													LS_CFDA,
													LS_MANAGER,
													LS_AWARD_NUMBER;
				IF DONE1 THEN
					LEAVE MIGRATION_AWARD_CURSOR_LOOP;
				END IF;
				SET LS_FILE_TYPE = NULL;
				IF (IFNULL(TRIM(LI_IP_ID),'') <> '') THEN
					SELECT COUNT(*) INTO LI_COUNT
					FROM PROPOSAL WHERE PROPOSAL_ID = LI_IP_ID;
					IF (LI_COUNT = 0) THEN
						INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
						VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Inst-Proposal id missing in the FIBI table'),'Before Migration',LS_FILE_TYPE);
						COMMIT;
					END IF;
				END IF;
				IF (  IFNULL(TRIM(LS_AWARD_NUMBER),'') = '' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award Number can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (  IFNULL(TRIM(LS_ACCOUNT_NUMBER),'') = '' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Account Number can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				ELSE
                	SELECT COUNT(*) INTO LI_COUNT
					FROM MIGRATION_AWARD WHERE ACCOUNT_NUMBER = TRIM(LS_ACCOUNT_NUMBER);
                    IF LI_COUNT > 1 THEN
						INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
						VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Account Number having more than one entry'),'Before Migration',LS_FILE_TYPE);
						COMMIT;
					END IF;
				END IF;
				IF 	(IFNULL(TRIM(LS_MA_ACCOUNT_TYPE_DESC),'') <> '' AND UPPER(TRIM(LS_MA_ACCOUNT_TYPE_DESC)) NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM ACCOUNT_TYPE)) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Account type "',TRIM(LS_MA_ACCOUNT_TYPE_DESC),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_MA_ACTIVITY_TYPE_DESC),'') ='' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Activity type can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_MA_ACTIVITY_TYPE_DESC),'') <> '' AND UPPER(TRIM(LS_MA_ACTIVITY_TYPE_DESC))  NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM ACTIVITY_TYPE)) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Activity type "',TRIM(LS_MA_ACTIVITY_TYPE_DESC),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_MA_AWARD_STATUS_DESC),'') = '') THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award status can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( (IFNULL(TRIM(LS_MA_AWARD_STATUS_DESC),'') <> '') AND (UPPER(TRIM(LS_MA_AWARD_STATUS_DESC))  NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM AWARD_STATUS))) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award status "',TRIM(LS_MA_AWARD_STATUS_DESC),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_TITLE),'') ='' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award title can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( LENGTH(IFNULL(TRIM(LS_TITLE),'')) >300 ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Warning','AWARD',CONCAT('Award title length shouldn''t exceed 300chara'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_UNIT_NAME),'')= '') THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award unit can''t be NULL '),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_UNIT_NAME),'') <>  '' AND UPPER(TRIM(LS_UNIT_NAME)) NOT IN (SELECT UPPER(TRIM(UNIT_NAME)) FROM UNIT)) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Unit "',TRIM(LS_UNIT_NAME),'" is missing in the unit master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_MA_AWARD_TYPE_DESC),'') <> '' AND  UPPER(TRIM(LS_MA_AWARD_TYPE_DESC))  NOT IN(SELECT UPPER(TRIM(DESCRIPTION)) FROM AWARD_TYPE)) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award type "',TRIM(LS_MA_AWARD_TYPE_DESC),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_SPONSOR_NAME),'')= '') THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Sponsor Name can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_SPONSOR_NAME),'') <> '' AND UPPER(TRIM(LS_SPONSOR_NAME)) NOT IN(SELECT UPPER(TRIM(SPONSOR_NAME)) FROM SPONSOR)) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Sponsor "',TRIM(LS_SPONSOR_NAME),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_PRIME_SPONSOR_NAME),'') <> ''  AND UPPER(TRIM(LS_PRIME_SPONSOR_NAME)) NOT IN(SELECT UPPER(TRIM(SPONSOR_NAME)) FROM SPONSOR)) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Prime Sponsor "',TRIM(LS_PRIME_SPONSOR_NAME),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LD_MA_START_DATE),'')  = '' OR STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') IS NULL ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award Start date can''t be NULL or Improper format'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LD_MA_END_DATE),'') = '' OR STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') IS NULL ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award End date can''t be NULL or Improper format'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LD_AWARD_NOTICE_DATE),'') <>'' and  STR_TO_DATE(LD_AWARD_NOTICE_DATE,'%d-%m-%Y') IS NULL ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award Notice date can''t be NULL or Improper format'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
			    IF (  STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') IS NOT NULL AND TRIM(LD_MA_START_DATE) <> ''
				      AND STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') IS NOT NULL AND TRIM(LD_MA_END_DATE) <> ''
					  AND STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') > STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') )THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Award Start date "',TRIM(LD_MA_START_DATE),'" should come before Award end date "',TRIM(LD_MA_END_DATE),'"'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_PI_USER_NAME),'')= '')  THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('PI person can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'')= '') THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Employee Type can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'')<> '' AND UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)) NOT IN ('EMPLOYEE','NON-EMPLOYEE')) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('Invalid Employee Type'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ((IFNULL(TRIM(LS_PI_USER_NAME),'')) <> '' AND IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'') <> '' AND (IFNULL(UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)),'')) = 'EMPLOYEE' ) THEN
						SELECT COUNT(1) INTO LI_FLAG FROM PERSON
						WHERE UPPER(TRIM(USER_NAME))  = UPPER(TRIM(LS_PI_USER_NAME));
						IF LI_FLAG = 0 THEN
							INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
							VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('PI person "',TRIM(LS_PI_USER_NAME),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
							COMMIT;
						END IF;
				ELSE
					IF ((IFNULL(TRIM(LS_PI_USER_NAME),'')) <> '' AND IFNULL(TRIM(LS_PI_EMPLOYEE_TYPE),'') <> '' AND (IFNULL(UPPER(TRIM(LS_PI_EMPLOYEE_TYPE)),'')) = 'NON-EMPLOYEE' ) THEN
						SELECT COUNT(1) INTO LI_FLAG FROM ROLODEX
						WHERE UPPER(TRIM(FULL_NAME))  =UPPER(TRIM(LS_PI_USER_NAME));
						IF LI_FLAG = 0 THEN
							INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
							VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD',CONCAT('PI ROLODEX person "',TRIM(LS_PI_ROLODEX_ID),'" is missing in the master data provided'),'Before Migration',LS_FILE_TYPE);
							COMMIT;
						END IF;
					END IF;
                END IF;
				IF ( IFNULL(TRIM(LS_SPONSOR_AWARD_NUMBER),'') <> '' AND LENGTH(IFNULL(TRIM(LS_SPONSOR_AWARD_NUMBER),'')) >70 ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Warning','AWARD',CONCAT('Sponsor award number length shouldn''t exceed 70chara'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
		END LOOP;
		CLOSE MIGRATION_AWARD_CURSOR;
END;
SELECT 1  AS RESULT;
END
$$
DELIMITER ;
