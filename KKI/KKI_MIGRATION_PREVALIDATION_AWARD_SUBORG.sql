DELIMITER $$
CREATE  PROCEDURE `KKI_MIGRATION_PREVALIDATION_AWARD_SUBORG`(AV_TYPE INT)
BEGIN
DECLARE LI_MA_MIGRATION_AWARD_ID	INT(11);
DECLARE LS_LEGACY_PROJECT_ID	VARCHAR(100);
DECLARE LS_LEGACY_WBS_NUMBER	VARCHAR(100);
DECLARE LS_MA_GRANT_CODE	VARCHAR(50);
DECLARE LS_MA_ACCOUNT_NUMBER	VARCHAR(100);
DECLARE LI_MA_GRANT_HEADER_ID	VARCHAR(10);
DECLARE LS_MA_LEAD_UNIT_NUMBER	VARCHAR(8);
DECLARE LS_MA_LEAD_UNIT_NAME	VARCHAR(8);
DECLARE LS_MA_ACCOUNT_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_ACTIVITY_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_STATUS_DESC	VARCHAR(200);
DECLARE LS_MA_SPONSOR_CODE	VARCHAR(6);
DECLARE LS_MA_PRIME_SPONSOR_CODE	VARCHAR(6);
DECLARE LD_MA_START_DATE	VARCHAR(10);
DECLARE LD_MA_END_DATE	VARCHAR(10);
DECLARE LS_MA_SUB_LEAD_UNIT_CODE	VARCHAR(8);
DECLARE RESEARCH_AREA_DESC	VARCHAR(200);
DECLARE PI_PERSON_ID	VARCHAR(20);
DECLARE LS_MA_RIE_DOMAIN	VARCHAR(200);
DECLARE LS_STEM_NON_STEM	VARCHAR(10);
DECLARE LS_DISPLAY_AT_ACAD_PROFILE	VARCHAR(3);
DECLARE LS_RESEARCH_AREA_DESC VARCHAR(200);
DECLARE LS_PI_PERSON_ID VARCHAR(40);
DECLARE LS_TITLE VARCHAR(2000);
DECLARE LI_COUNT INT;
DECLARE LS_FILE_TYPE VARCHAR(50);
DECLARE LS_PI_ROLODEX_ID VARCHAR(20);
DECLARE LI_FLAG INT;
DECLARE LI_APPROVED_BUDGET VARCHAR(20);
DECLARE LS_SPONSOR_AWARD_NUMBER VARCHAR(100);
DECLARE LS_ACCOUNT_NUMBER  VARCHAR(100);
DECLARE LI_IP_ID  INT(11);
DECLARE LS_PI_USER_NAME VARCHAR(100);
DECLARE LS_PI_EMPLOYEE_TYPE VARCHAR(100);
DECLARE LS_UNIT_NAME VARCHAR(100);
DECLARE LD_AWARD_NOTICE_DATE VARCHAR(100);
DECLARE LS_SPONSOR_NAME VARCHAR(100);
DECLARE LS_PRIME_SPONSOR_NAME VARCHAR(100);
DECLARE LS_CFDA VARCHAR(100);
DECLARE LS_MANAGER VARCHAR(100);
DECLARE LI_MIGRATION_AWARD_BUDGET_ID	INT(11);
DECLARE LS_YEAR	VARCHAR(100);
DECLARE LS_OBLIGATION_START_DATE	VARCHAR(12);
DECLARE LS_OBLIGATION_END_DATE	VARCHAR(12);
DECLARE LI_OBLIGATION_TOTAL_AMOUNT	DECIMAL(12,2);
DECLARE LS_AWARD_NUMBER	VARCHAR(12);
DECLARE LS_SUB_AWARD_ORGANIZATION VARCHAR(1000);
DECLARE LS_SUB_AWARD_ORGANIZATION_AMOUNT DECIMAL(12,2);
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWARD_SUBORG_CURSOR CURSOR FOR
		SELECT LEGACY_PROJECT_ID,
				LEGACY_WBS_NUMBER,
				AWARD_NUMBER,
				ACCOUNT_NUMBER,
				YEAR,
				SUB_AWARD_ORGANIZATION,
				SUB_AWARD_ORGANIZATION_AMOUNT,
				FILE_TYPE
		FROM KKI_MIGRATION_AWARD_SUBORG
        where YEAR is not null;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(LS_LEGACY_PROJECT_ID,LS_LEGACY_WBS_NUMBER,'Exception','AWARD_SUBORG',LS_ERROR,'Before Migration',LS_FILE_TYPE);
			COMMIT;
		END;
		OPEN MIGRATION_AWARD_SUBORG_CURSOR;
		MIGRATION_AWARD_SUBORG_CURSOR_LOOP : LOOP
				FETCH MIGRATION_AWARD_SUBORG_CURSOR INTO
													LS_LEGACY_PROJECT_ID,
													LS_LEGACY_WBS_NUMBER,
													LS_AWARD_NUMBER,
													LS_ACCOUNT_NUMBER,
													LS_YEAR,
													LS_SUB_AWARD_ORGANIZATION,
													LS_SUB_AWARD_ORGANIZATION_AMOUNT,
												    LS_FILE_TYPE;
				IF DONE1 THEN
					LEAVE MIGRATION_AWARD_SUBORG_CURSOR_LOOP;
				END IF;
				SET LS_FILE_TYPE = NULL;
				IF (  IFNULL(TRIM(LS_ACCOUNT_NUMBER),'') = '' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_SUBORG',CONCAT('Account Number can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				SELECT COUNT(*) INTO LI_COUNT
				FROM MIGRATION_AWARD WHERE UPPER(TRIM(ACCOUNT_NUMBER)) = UPPER(TRIM(LS_ACCOUNT_NUMBER)) ;
				IF LI_COUNT = 0 THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Account number unavailable in award file'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_SUB_AWARD_ORGANIZATION),'') = '' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_SUBORG',CONCAT('SubAward organization can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_SUB_AWARD_ORGANIZATION),'') <> '' AND IFNULL(TRIM(LS_SUB_AWARD_ORGANIZATION_AMOUNT),'') = ''  ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_SUBORG',CONCAT('SubAward organization amount can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_SUB_AWARD_ORGANIZATION),'') <> '' AND UPPER(TRIM(LS_SUB_AWARD_ORGANIZATION)) NOT IN (SELECT UPPER(TRIM(ORGANIZATION_NAME))
																														 FROM ORGANIZATION)  ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_SUBORG',CONCAT('Invalid SubAward organization '),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				SELECT COUNT(*) INTO LI_COUNT
				FROM MIGRATION_AWARD
				WHERE UPPER(TRIM(ACCOUNT_NUMBER)) = UPPER(TRIM(LS_ACCOUNT_NUMBER));
				IF LI_COUNT = 0 THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_SUBORG',CONCAT('Account Number missing in award file '),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
		END LOOP;
		CLOSE MIGRATION_AWARD_SUBORG_CURSOR;
END;
SELECT 1  AS RESULT;
END
$$
DELIMITER ;
