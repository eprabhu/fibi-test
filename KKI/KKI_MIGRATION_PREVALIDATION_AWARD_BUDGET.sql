DELIMITER $$
CREATE  PROCEDURE `KKI_MIGRATION_PREVALIDATION_AWARD_BUDGET`(AV_TYPE INT)
BEGIN
DECLARE LI_MA_MIGRATION_AWARD_ID	INT(11);
DECLARE LS_LEGACY_PROJECT_ID	VARCHAR(100);
DECLARE LS_LEGACY_WBS_NUMBER	VARCHAR(100);
DECLARE LS_MA_GRANT_CODE	VARCHAR(50);
DECLARE LS_MA_ACCOUNT_NUMBER	VARCHAR(100);
DECLARE LI_MA_GRANT_HEADER_ID	VARCHAR(10);
DECLARE LS_MA_LEAD_UNIT_NUMBER	VARCHAR(8);
DECLARE LS_MA_LEAD_UNIT_NAME	VARCHAR(8);
DECLARE LS_MA_ACCOUNT_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_ACTIVITY_TYPE_DESC	VARCHAR(200);
DECLARE LS_MA_AWARD_STATUS_DESC	VARCHAR(200);
DECLARE LS_MA_SPONSOR_CODE	VARCHAR(6);
DECLARE LS_MA_PRIME_SPONSOR_CODE	VARCHAR(6);
DECLARE LD_MA_START_DATE	VARCHAR(10);
DECLARE LD_MA_END_DATE	VARCHAR(10);
DECLARE LS_MA_SUB_LEAD_UNIT_CODE	VARCHAR(8);
DECLARE RESEARCH_AREA_DESC	VARCHAR(200);
DECLARE PI_PERSON_ID	VARCHAR(20);
DECLARE LS_MA_RIE_DOMAIN	VARCHAR(200);
DECLARE LS_STEM_NON_STEM	VARCHAR(10);
DECLARE LS_DISPLAY_AT_ACAD_PROFILE	VARCHAR(3);
DECLARE LS_RESEARCH_AREA_DESC VARCHAR(200);
DECLARE LS_PI_PERSON_ID VARCHAR(40);
DECLARE LS_TITLE VARCHAR(2000);
DECLARE LI_COUNT INT;
DECLARE LS_FILE_TYPE VARCHAR(50);
DECLARE LS_PI_ROLODEX_ID VARCHAR(20);
DECLARE LI_FLAG INT;
DECLARE LI_APPROVED_BUDGET VARCHAR(20);
DECLARE LS_SPONSOR_AWARD_NUMBER VARCHAR(100);
DECLARE LS_ACCOUNT_NUMBER  VARCHAR(100);
DECLARE LI_IP_ID  INT(11);
DECLARE LS_PI_USER_NAME VARCHAR(100);
DECLARE LS_PI_EMPLOYEE_TYPE VARCHAR(100);
DECLARE LS_UNIT_NAME VARCHAR(100);
DECLARE LD_AWARD_NOTICE_DATE VARCHAR(100);
DECLARE LS_SPONSOR_NAME VARCHAR(100);
DECLARE LS_PRIME_SPONSOR_NAME VARCHAR(100);
DECLARE LS_CFDA VARCHAR(100);
DECLARE LS_MANAGER VARCHAR(100);
DECLARE LI_MIGRATION_AWARD_BUDGET_ID	INT(11);
DECLARE LS_YEAR	VARCHAR(100);
DECLARE LS_OBLIGATION_START_DATE	VARCHAR(12);
DECLARE LS_OBLIGATION_END_DATE	VARCHAR(12);
DECLARE LI_OBLIGATION_TOTAL_AMOUNT	DECIMAL(12,2);
DECLARE LS_AWARD_NUMBER	VARCHAR(12);
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWARD_BUDGET_CURSOR CURSOR FOR
		SELECT MIGRATION_AWARD_BUDGET_ID,
				LEGACY_PROJECT_ID,
				LEGACY_WBS_NUMBER,
				AWARD_NUMBER,
				ACCOUNT_NUMBER,
				YEAR,
				OBLIGATION_START_DATE,
				OBLIGATION_END_DATE,
				OBLIGATION_TOTAL_AMOUNT,
				FILE_TYPE
		FROM KKI_MIGRATION_AWARD_BUDGET;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Exception','AWARD_BUDGET',LS_ERROR,'Before Migration',LS_FILE_TYPE);
			COMMIT;
		END;
		OPEN MIGRATION_AWARD_BUDGET_CURSOR;
		MIGRATION_AWARD_BUDGET_CURSOR_LOOP : LOOP
				FETCH MIGRATION_AWARD_BUDGET_CURSOR INTO 	LI_MIGRATION_AWARD_BUDGET_ID,
													LS_LEGACY_PROJECT_ID,
													LS_LEGACY_WBS_NUMBER,
													LS_AWARD_NUMBER,
													LS_ACCOUNT_NUMBER,
													LS_YEAR,
													LS_OBLIGATION_START_DATE,
													LS_OBLIGATION_END_DATE,
													LI_OBLIGATION_TOTAL_AMOUNT,
													LS_FILE_TYPE;
				IF DONE1 THEN
					LEAVE MIGRATION_AWARD_BUDGET_CURSOR_LOOP;
				END IF;
				SET LS_FILE_TYPE = NULL;
				IF (  IFNULL(TRIM(LS_ACCOUNT_NUMBER),'') = '' ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Account Number can''t be NULL'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
IF IFNULL(TRIM(LS_YEAR),'') <> '' THEN
				IF ( IFNULL(TRIM(LS_OBLIGATION_START_DATE),'')  = '' OR STR_TO_DATE(LS_OBLIGATION_START_DATE,'%d-%m-%Y') IS NULL ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Budget Start date can''t be NULL or Improper format'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF ( IFNULL(TRIM(LS_OBLIGATION_END_DATE),'') = '' OR STR_TO_DATE(LS_OBLIGATION_END_DATE,'%d-%m-%Y') IS NULL ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Budget End date can''t be NULL or Improper format'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
			    IF (  STR_TO_DATE(LS_OBLIGATION_START_DATE,'%d-%m-%Y') IS NOT NULL AND TRIM(LS_OBLIGATION_START_DATE) <> ''
				      AND STR_TO_DATE(LS_OBLIGATION_END_DATE,'%d-%m-%Y') IS NOT NULL AND TRIM(LS_OBLIGATION_END_DATE) <> ''
					  AND STR_TO_DATE(LS_OBLIGATION_START_DATE,'%d-%m-%Y') > STR_TO_DATE(LS_OBLIGATION_END_DATE,'%d-%m-%Y') )THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Budget Start date "',IFNULL(TRIM(LS_OBLIGATION_START_DATE),'NULL'),'" should come before Budget end date "',IFNULL(TRIM(LS_OBLIGATION_END_DATE),'NULL'),'"'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				SELECT COUNT(*) INTO LI_COUNT
				FROM MIGRATION_AWARD WHERE UPPER(TRIM(ACCOUNT_NUMBER)) = UPPER(TRIM(LS_ACCOUNT_NUMBER)) ;
				IF LI_COUNT = 1 THEN
					SELECT START_DATE,END_DATE  INTO LD_MA_START_DATE,LD_MA_END_DATE
					FROM MIGRATION_AWARD WHERE UPPER(TRIM(ACCOUNT_NUMBER)) = UPPER(TRIM(LS_ACCOUNT_NUMBER)) ;
				ELSE
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Award start - End date unavailable'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
				IF (IFNULL(TRIM(LS_OBLIGATION_START_DATE),'') = '' OR STR_TO_DATE(LS_OBLIGATION_START_DATE,'%d-%m-%Y') IS NULL
				   OR IFNULL(TRIM(LS_OBLIGATION_END_DATE),'') = '' OR STR_TO_DATE(LS_OBLIGATION_END_DATE,'%d-%m-%Y') IS NULL
				   OR IFNULL(TRIM(LD_MA_END_DATE),'') = '' OR STR_TO_DATE(LD_MA_END_DATE,'%d-%m-%Y') IS NULL
				   OR IFNULL(TRIM(LD_MA_START_DATE),'') = '' OR STR_TO_DATE(LD_MA_START_DATE,'%d-%m-%Y') IS NULL
				   ) THEN
					INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
					VALUES(LS_LEGACY_PROJECT_ID,LS_ACCOUNT_NUMBER,'Validation','AWARD_BUDGET',CONCAT('Award start date "',IFNULL(TRIM(LD_MA_START_DATE),'NULL'),'" should come before Budget Start date "',IFNULL(TRIM(LS_OBLIGATION_START_DATE),'NULL'),'"'),'Before Migration',LS_FILE_TYPE);
					COMMIT;
				END IF;
END IF;
		END LOOP;
		CLOSE MIGRATION_AWARD_BUDGET_CURSOR;
END;
SELECT 1  AS RESULT;
END
$$
DELIMITER ;
