CREATE  FUNCTION `FN_CHK_MODULE_REVIEWERS`(
AV_MODULE_ITEM_KEY    varchar(38),
AV_MODULE_CODE        VARCHAR(3)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_REVIEWER_STATUS_C INT;
DECLARE LI_REVIEWER_COUNT INT;
	SELECT COUNT(1) INTO LI_REVIEWER_COUNT FROM PRE_REVIEW
	WHERE MODULE_ITEM_CODE = AV_MODULE_CODE
	AND MODULE_SUB_ITEM_CODE = 0
	AND MODULE_ITEM_KEY = AV_MODULE_ITEM_KEY;
    IF LI_REVIEWER_COUNT = 0 THEN
		RETURN 'TRUE';
    END IF;
	SELECT COUNT(1) INTO LI_REVIEWER_STATUS_C
	FROM PRE_REVIEW
	WHERE MODULE_ITEM_CODE = AV_MODULE_CODE
	AND MODULE_SUB_ITEM_CODE = 0
	AND MODULE_ITEM_KEY = AV_MODULE_ITEM_KEY
	AND PRE_REVIEW_STATUS_CODE = 2;
	IF LI_REVIEWER_COUNT =  LI_REVIEWER_STATUS_C THEN
		RETURN 'TRUE';
	END IF;
	RETURN 'FALSE';
END
$$
DELIMITER ;
