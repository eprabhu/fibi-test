DELIMITER $$
CREATE  PROCEDURE `INSERT_INTO_BUDGET_DETAILS`(av_type int)
BEGIN
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE LS_BUDGET_HEADER_ID INT(11);
DECLARE  LS_BUDGET_DETAIL_ID INT(12);
DECLARE LS_BUDGET_PERIOD_ID INT(12);
DECLARE LS_BUDGET_PERIOD INT(11);
DECLARE LS_TOTAL_DIRECT_COST DECIMAL(10,2);
DECLARE LS_TOTAL_INDIRECT_COST DECIMAL(10,2);
DECLARE LS_SUBCONTRACT_COST DECIMAL(10,2);
DECLARE LS_UPDATE_USER VARCHAR(60);
DECLARE LD_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_COUNT INT;
DECLARE SEQ_BUDGET_DETAILS_ID  INT(12);
BEGIN
DECLARE BUDGET_HEADER_CURSOR CURSOR FOR
SELECT BUDGET_HEADER_ID FROM BUDGET_HEADER;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN BUDGET_HEADER_CURSOR;
BUDGET_HEADER_CURSOR_LOOP : LOOP
        FETCH BUDGET_HEADER_CURSOR INTO  LS_BUDGET_HEADER_ID ;
		IF DONE1 THEN
			LEAVE BUDGET_HEADER_CURSOR_LOOP;
		END IF;
        BEGIN
		DECLARE BUDGET_PERIOD_CURSOR CURSOR FOR
		SELECT BUDGET_PERIOD_ID,BUDGET_PERIOD,TOTAL_DIRECT_COST,TOTAL_INDIRECT_COST,SUBCONTRACT_COST,UPDATE_USER,UPDATE_TIMESTAMP
		FROM BUDGET_PERIOD
		WHERE BUDGET_HEADER_ID = LS_BUDGET_HEADER_ID;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
        OPEN BUDGET_PERIOD_CURSOR;
		BUDGET_PERIOD_CURSOR_LOOP : LOOP
				FETCH BUDGET_PERIOD_CURSOR INTO  LS_BUDGET_PERIOD_ID,LS_BUDGET_PERIOD,LS_TOTAL_DIRECT_COST,LS_TOTAL_INDIRECT_COST,LS_SUBCONTRACT_COST,LS_UPDATE_USER,LD_UPDATE_TIMESTAMP;
				IF DONE2 THEN
					LEAVE BUDGET_PERIOD_CURSOR_LOOP;
				END IF;
				select COUNT(BUDGET_DETAILS_ID) INTO LS_COUNT from BUDGET_DETAIL
				WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID ;
				if LS_COUNT  = 0 then
								select COUNT(BUDGET_DETAILS_ID) INTO LS_COUNT from BUDGET_DETAIL
								WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID AND COST_ELEMENT = '55480';
								IF LS_COUNT = 0 THEN
										SELECT (CASE WHEN MAX(BUDGET_DETAILS_ID) IS NULL THEN 1
												   ELSE MAX(BUDGET_DETAILS_ID)+1 END) INTO SEQ_BUDGET_DETAILS_ID
										FROM BUDGET_DETAIL;
									   INSERT INTO BUDGET_DETAIL(
										BUDGET_DETAILS_ID,
										BUDGET_PERIOD_ID,
										BUDGET_PERIOD,
										LINE_ITEM_NUMBER,
										BUDGET_CATEGORY_CODE,
										COST_ELEMENT,
										LINE_ITEM_COST,
										IS_SYSTEM_GENRTED_COST_ELEMENT,
										SYSTEM_GEN_COST_ELEMENT_TYPE,
										IS_APPLY_INFLATION_RATE,
										UPDATE_TIMESTAMP,
										UPDATE_USER,
										APPLY_IN_RATE_FLAG,
										SUBMIT_COST_SHARING_FLAG)
										VALUES(
										SEQ_BUDGET_DETAILS_ID,
										LS_BUDGET_PERIOD_ID,
										LS_BUDGET_PERIOD,
										2,
										19,
										'55480',
										LS_TOTAL_DIRECT_COST,
										'N',
										NULL,
										'Y',
										LD_UPDATE_TIMESTAMP,
										LS_UPDATE_USER,
										'N',
										'N'
										);
										commit;
								END IF;
								select COUNT(BUDGET_DETAILS_ID) INTO LS_COUNT from BUDGET_DETAIL
								WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID AND COST_ELEMENT = '420620';
								IF LS_COUNT = 0  AND LS_SUBCONTRACT_COST <> 0 THEN
										SELECT (CASE WHEN MAX(BUDGET_DETAILS_ID) IS NULL THEN 1
												   ELSE MAX(BUDGET_DETAILS_ID)+1 END) INTO SEQ_BUDGET_DETAILS_ID
										FROM BUDGET_DETAIL;
									   INSERT INTO BUDGET_DETAIL(
										BUDGET_DETAILS_ID,
										BUDGET_PERIOD_ID,
										BUDGET_PERIOD,
										LINE_ITEM_NUMBER,
										BUDGET_CATEGORY_CODE,
										COST_ELEMENT,
										LINE_ITEM_COST,
										IS_SYSTEM_GENRTED_COST_ELEMENT,
										SYSTEM_GEN_COST_ELEMENT_TYPE,
										IS_APPLY_INFLATION_RATE,
										UPDATE_TIMESTAMP,
										UPDATE_USER,
										APPLY_IN_RATE_FLAG,
										SUBMIT_COST_SHARING_FLAG)
										VALUES(
										SEQ_BUDGET_DETAILS_ID,
										LS_BUDGET_PERIOD_ID,
										LS_BUDGET_PERIOD,
										3,
										22,
										'420620',
										LS_SUBCONTRACT_COST,
										'N',
										NULL,
										'Y',
										LD_UPDATE_TIMESTAMP,
										LS_UPDATE_USER,
										'N',
										'N'
										);
										commit;
								END IF;
								select COUNT(BUDGET_DETAILS_ID) INTO LS_COUNT from BUDGET_DETAIL
								WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID AND COST_ELEMENT = '422121';
								IF LS_COUNT = 0 THEN
										SELECT (CASE WHEN MAX(BUDGET_DETAILS_ID) IS NULL THEN 1
												   ELSE MAX(BUDGET_DETAILS_ID)+1 END) INTO SEQ_BUDGET_DETAILS_ID
										FROM BUDGET_DETAIL;
									   INSERT INTO BUDGET_DETAIL(
										BUDGET_DETAILS_ID,
										BUDGET_PERIOD_ID,
										BUDGET_PERIOD,
										LINE_ITEM_NUMBER,
										BUDGET_CATEGORY_CODE,
										COST_ELEMENT,
										LINE_ITEM_COST,
										IS_SYSTEM_GENRTED_COST_ELEMENT,
										SYSTEM_GEN_COST_ELEMENT_TYPE,
										IS_APPLY_INFLATION_RATE,
										UPDATE_TIMESTAMP,
										UPDATE_USER,
										APPLY_IN_RATE_FLAG,
										SUBMIT_COST_SHARING_FLAG)
										VALUES(
										SEQ_BUDGET_DETAILS_ID,
										LS_BUDGET_PERIOD_ID,
										LS_BUDGET_PERIOD,
										1,
										600,
										'422121',
										LS_TOTAL_INDIRECT_COST,
										'Y',
										'BUDGET_OH_ON',
										'Y',
										LD_UPDATE_TIMESTAMP,
										LS_UPDATE_USER,
										'N',
										'N'
										);
										commit;
								END IF;
		  end if;
	   END LOOP;
	 CLOSE BUDGET_PERIOD_CURSOR;
	END;
	SET DONE2 = FALSE ;
END LOOP;
CLOSE BUDGET_HEADER_CURSOR;
END;
update budget_detail_id_generator set NEXT_VAL = (select MAX(BUDGET_DETAILS_ID)+1 from BUDGET_DETAIL );
END
$$
DELIMITER ;
