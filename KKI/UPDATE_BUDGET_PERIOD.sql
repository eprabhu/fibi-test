DELIMITER $$
CREATE  PROCEDURE `UPDATE_BUDGET_PERIOD`(av_type int)
BEGIN
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE LS_BUDGET_HEADER_ID INT(11);
DECLARE LS_BUDGET_DETAIL_ID INT(12);
DECLARE LS_BUDGET_PERIOD_ID INT(12);
DECLARE LI_LINE_ITEM_COST	decimal(10,2);
DECLARE LS_COUNT INT;
DECLARE LI_TOTAL_COST decimal(10,2);
DECLARE LI_DIRECT_LINE_ITEM_COST decimal(10,2);
DECLARE LI_INDIRECT_LINE_ITEM_COST decimal(10,2);
BEGIN
DECLARE BUDGET_HEADER_CURSOR CURSOR FOR
SELECT BUDGET_HEADER_ID FROM BUDGET_HEADER;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN BUDGET_HEADER_CURSOR;
BUDGET_HEADER_CURSOR_LOOP : LOOP
        FETCH BUDGET_HEADER_CURSOR INTO  LS_BUDGET_HEADER_ID ;
		IF DONE1 THEN
			LEAVE BUDGET_HEADER_CURSOR_LOOP;
		END IF;
        BEGIN
		DECLARE BUDGET_PERIOD_CURSOR CURSOR FOR
		SELECT BUDGET_PERIOD_ID
		FROM BUDGET_PERIOD
		WHERE BUDGET_HEADER_ID = LS_BUDGET_HEADER_ID;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
        OPEN BUDGET_PERIOD_CURSOR;
		BUDGET_PERIOD_CURSOR_LOOP : LOOP
				FETCH BUDGET_PERIOD_CURSOR INTO  LS_BUDGET_PERIOD_ID;
				IF DONE2 THEN
					LEAVE BUDGET_PERIOD_CURSOR_LOOP;
				END IF;
				select SUM(LINE_ITEM_COST) INTO LI_DIRECT_LINE_ITEM_COST from BUDGET_DETAIL
				WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID AND (SYSTEM_GEN_COST_ELEMENT_TYPE = 'BUDGET_FRINGE_ON' OR SYSTEM_GEN_COST_ELEMENT_TYPE is NULL) ;
				select SUM(LINE_ITEM_COST) INTO LI_INDIRECT_LINE_ITEM_COST from BUDGET_DETAIL
				WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID AND (SYSTEM_GEN_COST_ELEMENT_TYPE IN('BUDGET_RESEARCH_OH_ON','BUDGET_OH_ON')) ;
				SET LI_TOTAL_COST = LI_DIRECT_LINE_ITEM_COST + LI_INDIRECT_LINE_ITEM_COST;
				UPDATE BUDGET_PERIOD SET TOTAL_DIRECT_COST = LI_DIRECT_LINE_ITEM_COST WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID ;
				UPDATE BUDGET_PERIOD SET TOTAL_INDIRECT_COST = LI_INDIRECT_LINE_ITEM_COST WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID ;
				UPDATE BUDGET_PERIOD SET TOTAL_COST = LI_TOTAL_COST WHERE BUDGET_PERIOD_ID = LS_BUDGET_PERIOD_ID ;
				COMMIT;
	   END LOOP;
	 CLOSE BUDGET_PERIOD_CURSOR;
	END;
	SET DONE2 = FALSE ;
END LOOP;
CLOSE BUDGET_HEADER_CURSOR;
END;
END
$$
DELIMITER ;
