DELIMITER $$
CREATE  FUNCTION `FN_CHK_CHILD_AWARD`(
AV_AWARD_ID VARCHAR(12)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LI_FLAG INT;
SELECT COUNT(1) INTO LI_FLAG
FROM AWARD
WHERE AWARD_ID = AV_AWARD_ID;
IF LI_FLAG > 0 THEN
	SELECT AWARD_NUMBER INTO LS_AWARD_NUMBER
	FROM AWARD
	WHERE AWARD_ID = AV_AWARD_ID;
	IF SUBSTR(LS_AWARD_NUMBER,INSTR(LS_AWARD_NUMBER,'-')+1) <> '00001' THEN
		RETURN 'TRUE';
	ELSE
		RETURN 'FALSE';
	END IF;
END IF;
END
$$
DELIMITER ;
