CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_ORG_CONG_DIST_PREVAL`(DATA_PROPOSAL_NUMBER VARCHAR(8),DATA_SITE_NUMBER INT,FOR_AUDIT INT, OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_CONG_DISTRICT_SITE_NUMBER INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_CONG_DISTRICT VARCHAR(50);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'CONGDISTRICT';
END;
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_ORG_CONG_DISTRICT_CURSOR CURSOR FOR
		SELECT  MIGRATION_CONG_DIST_ID,
				CONG_DISTRICT
		FROM 	stage_eps_proposal_cong_district
		WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SITE_NUMBER = DATA_SITE_NUMBER;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'CONGDISTRICT','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_ORG_CONG_DISTRICT_CURSOR;
			MIGRATION_ORG_CONG_DISTRICT_CURSOR_LOOP :    LOOP
				FETCH MIGRATION_ORG_CONG_DISTRICT_CURSOR INTO     	LI_RECORD_ID,
																	LS_CONG_DISTRICT;
					IF DONE1 THEN
						LEAVE MIGRATION_ORG_CONG_DISTRICT_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','CONGDISTRICT',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					congressional_district WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_CONG_DISTRICT)) AND IS_ACTIVE = 'Y';
					IF LI_COUNT NOT IN (-1,1) THEN
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'CONGDISTRICT','VALIDATION',CONCAT('Invalid congressional district :', LS_CONG_DISTRICT),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						ELSEIF LI_COUNT > 1 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'CONGDISTRICT','VALIDATION',CONCAT('More than 1 Cong District is available in the lookup table congressional_district for the description :', LS_CONG_DISTRICT),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','CONGDISTRICT',LI_BATCH_ID,'after congressional district check',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
					END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						UPDATE stage_eps_proposal_cong_district
						SET VALIDATION_STATUS = 'VALID',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_CONG_DIST_ID = LI_RECORD_ID;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','CONGDISTRICT',LI_BATCH_ID,'after valid update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
						END IF;
					ELSE
						UPDATE stage_eps_proposal_cong_district
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_CONG_DIST_ID = LI_RECORD_ID;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','CONGDISTRICT',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
						END IF;
					END IF;
				IF FOR_AUDIT = 1 THEN
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','CONGDISTRICT',LI_BATCH_ID,'Validation end',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
				END IF;
			END LOOP MIGRATION_ORG_CONG_DISTRICT_CURSOR_LOOP;
			CLOSE MIGRATION_ORG_CONG_DISTRICT_CURSOR;
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','CONGDISTRICT',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
			END IF;
		END;
		SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM stage_eps_proposal_cong_district WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SITE_NUMBER = DATA_SITE_NUMBER;
		COMMIT;
END
$$
DELIMITER ;
