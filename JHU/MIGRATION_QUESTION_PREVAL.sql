DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATION_QUESTION_PREVAL`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUESTION_ID INT;
DECLARE LI_QUESTION_ID INT;
DECLARE LS_QUESTION VARCHAR(2000);
DECLARE LI_QUESTION_VERSION_NUMBER INT;
DECLARE LI_GROUP_TYPE_CODE SMALLINT;
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_STG_QUESTION_ID,'QUEST_QUESTION','VALIDATION',CONCAT(LS_ERROR_MSG),UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_QUESTION') AND ERROR_TYPE = 'VALIDATION';
			UPDATE stage_questions SET VALIDATION_STATUS = NULL where VALIDATION_STATUS = 'ERROR';
		SET SQL_SAFE_UPDATES = 1;
	END IF;
END;
BEGIN
SET SQL_SAFE_UPDATES = 0;
	DELETE FROM migration_qtn_execution_log;
	ALTER TABLE migration_qtn_execution_log AUTO_INCREMENT = 1;
SET SQL_SAFE_UPDATES = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_questions;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'QUEST_QUESTION';
	INSERT INTO migration_transtn_auditlog_header (BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
										VALUES 	(LI_BATCH_ID,'VALIDATION','QUEST_QUESTION',UTC_TIMESTAMP());
	INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution : QUEST_QUESTION ',UTC_TIMESTAMP());
END;
		BEGIN
		DECLARE DONE2 INT DEFAULT FALSE;
		DECLARE CUR_QUESTIONS CURSOR FOR
		select ID
				, QUESTION_ID
				, QUESTION
				, GROUP_TYPE_CODE
				, VERSION_NUMBER
		from stage_questions
        where validation_status is NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
		OPEN CUR_QUESTIONS;
		QUESTIONS_LOOP: LOOP
		FETCH CUR_QUESTIONS INTO LI_STG_QUESTION_ID
								, LI_QUESTION_ID
								, LS_QUESTION
								, LI_GROUP_TYPE_CODE
								, LI_QUESTION_VERSION_NUMBER;
		IF DONE2 THEN
			LEAVE QUESTIONS_LOOP;
		END IF;
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('VALIDATION','QUEST_QUESTION',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LI_QUESTION_ID);
					SET LS_DATA_ERROR_FLAG = 'N';
					IF LI_QUESTION_ID IS NULL THEN
						INSERT INTO migration_questionnaire_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_STG_QUESTION_ID,'QUEST_QUESTION','VALIDATION',CONCAT('Invalid question_id :  ', LI_QUESTION_ID),UTC_TIMESTAMP(),'JHU_ADMIN');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF trim(LS_QUESTION) IS NULL or trim(LS_QUESTION) = '' THEN
						INSERT INTO migration_questionnaire_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_STG_QUESTION_ID,'QUEST_QUESTION','VALIDATION',CONCAT('Invalid question :  ', LS_QUESTION),UTC_TIMESTAMP(),'JHU_ADMIN');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF LI_QUESTION_VERSION_NUMBER IS NULL THEN
						INSERT INTO migration_questionnaire_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_STG_QUESTION_ID,'QUEST_QUESTION','VALIDATION',CONCAT('Invalid version number :  ', LI_QUESTION_VERSION_NUMBER),UTC_TIMESTAMP(),'JHU_ADMIN');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
						IF LS_DATA_ERROR_FLAG = 'Y' THEN
							UPDATE stage_questions SET VALIDATION_STATUS = 'ERROR' where ID =  LI_STG_QUESTION_ID;
						ELSE
							UPDATE stage_questions SET VALIDATION_STATUS = 'VALID' where ID =  LI_STG_QUESTION_ID;
						END IF;
			IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Validated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Questionnaire Questions'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('VALIDATION','QUEST_QUESTION',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LI_QUESTION_ID);
					set LI_COUNT = NULL;
					set LI_STG_QUESTION_ID = NULL;
					set LI_QUESTION_ID = NULL;
					set LS_QUESTION = NULL;
					set LI_GROUP_TYPE_CODE = NULL;
					set LI_QUESTION_VERSION_NUMBER = NULL;
				END LOOP;
				CLOSE CUR_QUESTIONS;
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','QUEST_QUESTION',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),NULL);
			INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Validated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Questionnaire Questions'),UTC_TIMESTAMP()),('Validation completed successfully',UTC_TIMESTAMP());
			END;
END
$$
DELIMITER ;
