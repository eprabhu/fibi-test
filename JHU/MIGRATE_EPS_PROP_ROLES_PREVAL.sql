CREATE  PROCEDURE `MIGRATE_EPS_PROP_ROLES_PREVAL`(DATA_PROPOSAL_NUMBER VARCHAR(8), OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ROLE_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(8);
DECLARE LS_PROPOSAL_UPDATE_USER VARCHAR(8);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR CURSOR FOR
		SELECT  MIGRATION_PROPOSAL_PERSON_ROLE_ID,
				PROPOSAL_NUMBER,
				USER_ID,
				ROLE_ID,
				UPDATE_USER
		FROM 	stage_eps_proposal_person_roles
		WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'PERSONROLE','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR;
			MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR_LOOP :    LOOP
				FETCH MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR INTO     	LI_RECORD_ID,
																		LS_PROPOSAL_NUMBER,
																		LS_PERSON_ID,
																		LI_ROLE_ID,
																		LS_PROPOSAL_UPDATE_USER;
					IF DONE1 THEN
						LEAVE MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					SET LI_COUNT = -1;
					SELECT COUNT(*) INTO LI_COUNT FROM
					person   WHERE UPPER(USER_NAME) = UPPER(LS_PERSON_ID);
					IF LI_COUNT <> 1  THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'PERSONROLE','VALIDATION',IFNULL(CONCAT('Invalid person :', LS_PERSON_ID),'Person is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(*) INTO LI_COUNT FROM
					role  WHERE ROLE_ID = LI_ROLE_ID;
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'PERSONROLE','VALIDATION',IFNULL(CONCAT('Invalid role id :', LI_ROLE_ID),'Role Id is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(*) INTO LI_COUNT FROM
					person WHERE UPPER(USER_NAME) = UPPER(LS_PROPOSAL_UPDATE_USER);
						IF LI_COUNT <> 1 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'PERSONROLE','VALIDATION',CONCAT('Invalid user name :  ', LS_PROPOSAL_UPDATE_USER),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
				SET SQL_SAFE_UPDATES = 0;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
							UPDATE stage_eps_proposal_person_roles
							SET VALIDATION_STATUS = 'VALID',
							FIBI_IDENTIFIER = NULL
							WHERE MIGRATION_PROPOSAL_PERSON_ROLE_ID = LI_RECORD_ID;
					ELSE
						UPDATE stage_eps_proposal_person_roles
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROPOSAL_PERSON_ROLE_ID = LI_RECORD_ID;
					END IF;
				SET SQL_SAFE_UPDATES = 1;
			END LOOP MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR_LOOP;
			CLOSE MIGRATION_DEV_PROP_PERSON_ROLES_CURSOR;
		END;
		SELECT COUNT(*) INTO DATA_ERROR_COUNT FROM stage_eps_proposal_person_roles WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER;
		COMMIT;
END
$$
DELIMITER ;
