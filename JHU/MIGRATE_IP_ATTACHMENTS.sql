DELIMITER $$
CREATE  PROCEDURE `MIGRATE_IP_ATTACHMENTS`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LS_PROPOSAL_NUMBER varchar(8);
DECLARE LI_SEQUENCE_NUMBER TINYINT ;
DECLARE LI_ATTACHMENT_NUMBER TINYINT ;
DECLARE LS_ATTACHMENT_TITLE varchar(150);
DECLARE LI_ATTACHMENT_TYPE_CODE SMALLINT;
DECLARE LS_FILE_NAME varchar(2000);
DECLARE LS_MIME_TYPE varchar(100);
DECLARE LS_UPDATE_TIMESTAMP DATETIME ;
DECLARE LS_UPDATE_USER varchar(8);
DECLARE LS_DOC_UPDATE_USER varchar(8);
DECLARE LS_DOC_UPDATE_TIMESTAMP DATETIME ;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_CONTENT_DATA LONGBLOB;
DECLARE UNIQUE_ID VARCHAR(36);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_PROPOSAL_ID varchar(8);
DECLARE LI_PROPOSAL_ATT_ID INT;
DECLARE LI_ATTACHMENT_ID INT;
DECLARE LI_DOCUMENT_ID INT;
DECLARE LS_ERROR VARCHAR(2000);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_validation_matrix WHERE MODULE_NAME = 'INSTPROPATTACH';
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'INSTPROPATTACH' AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_proposal_attachments SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_proposal_special_review;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'INSTPROPATTACH';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','INSTPROPATTACH',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_PROP_ATTACHMENT_CURSOR CURSOR FOR
	SELECT      MIGRATION_PROP_ATTACH_ID,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				ATTACHMENT_NUMBER,
				ATTACHMENT_TITLE,
				ATTACHMENT_TYPE_CODE,
				FILE_NAME,
				MIME_TYPE,
				DOC_UPDATE_USER ,
				DOC_UPDATE_TIMESTAMP ,
				DOCUMENT,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM  STAGE_PROPOSAL_ATTACHMENTS
	WHERE		VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO MIGRATION_TRANSACTION_ERRORLOG
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'INSTPROPATTACH','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_PROP_ATTACHMENT_CURSOR;
	MIGRATION_PROP_ATTACHMENT_CURSOR_LOOP      : LOOP
	FETCH MIGRATION_PROP_ATTACHMENT_CURSOR       INTO   LI_RECORD_ID,
														LS_PROPOSAL_NUMBER,
														LI_SEQUENCE_NUMBER,
														LI_ATTACHMENT_NUMBER,
														LS_ATTACHMENT_TITLE,
														LI_ATTACHMENT_TYPE_CODE,
														LS_FILE_NAME,
														LS_MIME_TYPE,
														LS_DOC_UPDATE_USER,
														LS_DOC_UPDATE_TIMESTAMP,
														LS_CONTENT_DATA,
														LS_UPDATE_TIMESTAMP,
														LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_PROP_ATTACHMENT_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_ATTACHMENT_ID = -1;
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM PROPOSAL WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
	IF LI_COUNT = 0 THEN
			INSERT INTO MIGRATION_TRANSACTION_ERRORLOG
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'INSTPROPATTACH  ','MIGRATION',CONCAT('Invalid proposal number : ', LS_PROPOSAL_NUMBER,' and the sequence number : ',LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT PROPOSAL_ID INTO LI_PROPOSAL_ID FROM PROPOSAL WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'after IP check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	SELECT IFNULL(MAX(DOCUMENT_ID),0) + 1 INTO LI_DOCUMENT_ID
	FROM PROPOSAL_ATTACHMENTS WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'after document id logic',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(ATTACHMENT_ID),0) + 1 INTO LI_ATTACHMENT_ID
		FROM PROPOSAL_ATTACHMENTS;
		SELECT UUID() INTO UNIQUE_ID FROM DUAL;
		INSERT INTO PROPOSAL_ATTACHMENTS
		(
			ATTACHMENT_ID,
			PROPOSAL_ID,
			PROPOSAL_NUMBER,
			SEQUENCE_NUMBER,
			ATTACHMNT_TYPE_CODE,
			DESCRIPTION,
			FILE_NAME,
			MIME_TYPE,
			NARRATIVE_STATUS_CODE,
			VERSION_NUMBER,
			FILE_DATA_ID,
			DOCUMENT_STATUS_CODE,
			DOCUMENT_ID,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_ATTACHMENT_ID,
			LI_PROPOSAL_ID,
			LS_PROPOSAL_NUMBER,
			LI_SEQUENCE_NUMBER,
			LI_ATTACHMENT_TYPE_CODE,
			LS_ATTACHMENT_TITLE,
			LS_FILE_NAME,
			LS_MIME_TYPE,
			'C',
			1,
			UNIQUE_ID,
			1,
			LI_DOCUMENT_ID,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		INSERT INTO FILE_DATA (ID,DATA,MODULE_CODE,FILE_PATH,ORIGINAL_FILE_NAME,FILE_NAME,IS_ARCHIVED,UPDATE_TIMESTAMP,UPDATE_USER) VALUES(UNIQUE_ID,LS_CONTENT_DATA,2,NULL,NULL,LS_FILE_NAME,NULL,LS_UPDATE_TIMESTAMP,LS_UPDATE_USER);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'after blob insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE STAGE_PROPOSAL_ATTACHMENTS
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_ATTACHMENT_ID
		WHERE MIGRATION_PROP_ATTACH_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	ELSE
		UPDATE STAGE_PROPOSAL_ATTACHMENTS
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_PROP_ATTACH_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed processing of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	END LOOP MIGRATION_PROP_ATTACHMENT_CURSOR_LOOP;
	CLOSE MIGRATION_PROP_ATTACHMENT_CURSOR;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPATTACH',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL,NULL);
	END IF;
END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM SEQ_IP_ATTACH_ID_GNTR;
	IF LI_COUNT = 0 THEN
		INSERT INTO SEQ_IP_ATTACH_ID_GNTR  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(ATTACHMENT_ID),0) + 1  FROM PROPOSAL_ATTACHMENTS));
	ELSE
		UPDATE SEQ_IP_ATTACH_ID_GNTR   SET NEXT_VAL = (SELECT IFNULL(MAX(ATTACHMENT_ID),0) + 1  FROM PROPOSAL_ATTACHMENTS);
	END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	COMMIT;
END
$$
DELIMITER ;
