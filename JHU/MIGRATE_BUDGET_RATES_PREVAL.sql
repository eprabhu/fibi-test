CREATE  PROCEDURE `MIGRATE_BUDGET_RATES_PREVAL`(DATA_REFRESH_FLAG INT,DATA_PROPOSAL_NUMBER VARCHAR(8), DATA_VERSION_NUMBER INT,DATA_START_DATE DATETIME,DATA_END_DATE DATETIME, OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_RATE_TYPE_CODE INT;
DECLARE LI_RATE_CLASS_CODE INT;
DECLARE LI_ACTIVITY_TYPE INT;
DECLARE LI_VERSION_NUMBER INT;
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_START_DATE DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'EPSPROPRATE' AND ERROR_TYPE = 'VALIDATION' AND PARENT_ID IN
			(SELECT MIGRATION_PROP_RATE_ID FROM stage_eps_proposal_rates WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL  AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND VERSION_NUMBER = DATA_VERSION_NUMBER);
			UPDATE stage_eps_proposal_rates SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND VERSION_NUMBER = DATA_VERSION_NUMBER;
		SET SQL_SAFE_UPDATES = 1;
	END IF;
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
    DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_EPS_PROP_RATES_CURSOR CURSOR FOR
		SELECT  MIGRATION_PROP_RATE_ID,
				PROPOSAL_NUMBER,
				VERSION_NUMBER,
				RATE_CLASS_CODE,
				RATE_TYPE_CODE,
				START_DATE,
				ACTIVITY_TYPE_CODE,
				UPDATE_USER
		FROM 	stage_eps_proposal_rates
		WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND VERSION_NUMBER = DATA_VERSION_NUMBER;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
		OPEN MIGRATION_EPS_PROP_RATES_CURSOR;
		MIGRATION_EPS_PROP_RATES_CURSOR_LOOP    :  LOOP
		FETCH MIGRATION_EPS_PROP_RATES_CURSOR      INTO    	LI_RECORD_ID,
															LS_PROPOSAL_NUMBER,
															LI_VERSION_NUMBER,
															LI_RATE_CLASS_CODE,
															LI_RATE_TYPE_CODE,
															LS_START_DATE,
															LI_ACTIVITY_TYPE,
															LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_EPS_PROP_RATES_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	IF LI_ACTIVITY_TYPE IS NOT NULL AND LI_ACTIVITY_TYPE <> 0 THEN
		SELECT COUNT(*) INTO LI_COUNT FROM
		activity_type WHERE ACTIVITY_TYPE_CODE = LI_ACTIVITY_TYPE AND IS_ACTIVE = 'Y';
		IF LI_COUNT = 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION',IFNULL(CONCAT('Invalid activity type :', LI_ACTIVITY_TYPE),'Activity type is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
	END IF;
	SET LI_COUNT = -1;
	IF LI_RATE_TYPE_CODE IS NOT NULL AND LI_RATE_TYPE_CODE <> 0 THEN
		SELECT COUNT(*) INTO LI_COUNT FROM
		rate_type WHERE RATE_TYPE_CODE = LI_RATE_TYPE_CODE AND IS_ACTIVE = 'Y';
			IF LI_COUNT = 0 THEN
				INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION',CONCAT('Invalid rate type code : ',LI_RATE_TYPE_CODE),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
			END IF;
	END IF;
	SET LI_COUNT = -1;
	IF LI_RATE_CLASS_CODE IS NOT NULL AND LI_RATE_CLASS_CODE <> 0 THEN
		SELECT COUNT(*) INTO LI_COUNT FROM
		rate_class WHERE RATE_CLASS_CODE = LI_RATE_CLASS_CODE;
		IF LI_COUNT = 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION',CONCAT('Invalid rate class code : ',LI_RATE_CLASS_CODE),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
	END IF;
	IF LS_START_DATE IS NULL THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION','Start date is mandatory',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF LS_START_DATE IS NOT NULL AND LS_START_DATE >= DATA_START_DATE AND LS_START_DATE <= DATA_END_DATE THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION','Start date should be in between the budget dates',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(*) INTO LI_COUNT FROM
	person WHERE UPPER(USER_NAME) = UPPER(LS_UPDATE_USER);
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPRATE','VALIDATION',CONCAT('Invalid user name :  ', LS_UPDATE_USER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	SET SQL_SAFE_UPDATES = 0;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_eps_proposal_rates
		SET VALIDATION_STATUS = 'VALID',
		FIBI_IDENTIFIER = NULL
		WHERE MIGRATION_PROP_RATE_ID = LI_RECORD_ID;
	ELSE
		UPDATE stage_eps_proposal_rates
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = NULL
		WHERE MIGRATION_PROP_RATE_ID = LI_RECORD_ID;
	END IF;
	SET SQL_SAFE_UPDATES = 1;
	END LOOP MIGRATION_EPS_PROP_RATES_CURSOR_LOOP;
	CLOSE MIGRATION_EPS_PROP_RATES_CURSOR;
END;
SELECT COUNT(*) INTO DATA_ERROR_COUNT FROM stage_eps_proposal_rates WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND VERSION_NUMBER = DATA_VERSION_NUMBER;
COMMIT;
END
$$
DELIMITER ;
