CREATE  FUNCTION `FN_HAS_LINK_VALUE`(
  AV_SR_HEADER_ID   int(10)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT int;
DECLARE RETURN_STRING VARCHAR(5) DEFAULT 'FALSE';
DECLARE LI_MODULE_CODE int;
 SELECT module_code
 INTO LI_MODULE_CODE
 FROM sr_header s
 WHERE s.sr_header_id = AV_SR_HEADER_ID;
  IF LI_MODULE_CODE  in (1, 2, 3) THEN
	 SELECT COUNT(*)
	 INTO LI_COUNT
	 FROM sr_header s
	 WHERE s.sr_header_id = AV_SR_HEADER_ID
	 AND   s.module_item_key IS NOT NULL
	 AND   s.module_code IN (1, 2, 3);
ELSE
	SET LI_COUNT=1;
END IF;
IF LI_COUNT > 0 THEN
   SET RETURN_STRING = 'TRUE';
END IF;
RETURN RETURN_STRING;
END
$$
DELIMITER ;
