DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_PROP_NOTEPAD`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROPOSAL_COMMENT_ID INT;
DECLARE LI_COMMENT_TYPE_CODE INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_COMMENTS LONGTEXT;
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_validation_matrix WHERE MODULE_NAME = 'IPPROPNOTEPAD';
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'IPPROPNOTEPAD' AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_proposal_notepad SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_proposal_comments;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'IPPROPNOTEPAD';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','IPPROPNOTEPAD',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM comment_type WHERE UPPER(DESCRIPTION) = UPPER('General Comments(Notepad)') AND IS_ACTIVE = 'Y' AND MODULE_CODE = 2;
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'IPPROPNOTEPAD','MIGRATION',CONCAT('Invalid comment type : General Comments(Notepad)'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT COMMENT_TYPE_CODE INTO LI_COMMENT_TYPE_CODE FROM comment_type WHERE UPPER(DESCRIPTION) = UPPER('General Comments(Notepad)') AND IS_ACTIVE = 'Y' AND MODULE_CODE = 2;
	END IF;
END;
IF LS_DATA_ERROR_FLAG = 'N' THEN
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATE_PROP_NOTPD CURSOR FOR
	SELECT      MIGRATION_PROP_NOTEPAD_ID,
				PROPOSAL_NUMBER,
				COMMENTS,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM  stage_proposal_notepad  WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'IPPROPNOTEPAD','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATE_PROP_NOTPD;
	MIGRATE_PROP_NOTPD_LOOP      : 				LOOP
	FETCH MIGRATE_PROP_NOTPD       				INTO       		LI_RECORD_ID,
																LS_PROPOSAL_NUMBER,
																LS_COMMENTS,
																LS_UPDATE_TIMESTAMP,
																LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATE_PROP_NOTPD_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
	IF LI_COUNT = 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'IPPROPNOTEPAD','MIGRATION',CONCAT('Invalid proposal number : ', LS_PROPOSAL_NUMBER,' and the sequence number : ',LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_SEQUENCE_NUMBER FROM proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		IF LI_SEQUENCE_NUMBER = 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPNOTEPAD','MIGRATION',CONCAT('Invalid sequence number for the proposal : ', LS_PROPOSAL_NUMBER,' and the sequence number : ',LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		ELSE
			SELECT PROPOSAL_ID INTO LI_PROPOSAL_ID FROM proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
		END IF;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'after IP check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROPOSAL_COMMENT_ID),0) + 1 INTO LI_PROPOSAL_COMMENT_ID FROM proposal_comments;
		INSERT INTO   proposal_comments
		(
			PROPOSAL_COMMENT_ID,
			PROPOSAL_ID,
			PROPOSAL_NUMBER,
			SEQUENCE_NUMBER,
			COMMENT_TYPE_CODE,
			COMMENTS,
			IS_PRIVATE,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_PROPOSAL_COMMENT_ID,
			LI_PROPOSAL_ID,
			LS_PROPOSAL_NUMBER,
			LI_SEQUENCE_NUMBER,
			LI_COMMENT_TYPE_CODE,
			LS_COMMENTS,
			'N',
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_proposal_notepad
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_PROPOSAL_COMMENT_ID
		WHERE MIGRATION_PROP_NOTEPAD_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
	ELSE
		UPDATE stage_proposal_notepad
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_PROP_NOTEPAD_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed processing of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END LOOP MIGRATE_PROP_NOTPD_LOOP;
	CLOSE MIGRATE_PROP_NOTPD;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','IPPROPNOTEPAD',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM proposal_comment_id_generator;
	IF LI_COUNT = 0 THEN
	INSERT INTO proposal_comment_id_generator  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROPOSAL_COMMENT_ID),0) + 1  FROM proposal_comments));
	ELSE
	UPDATE proposal_comment_id_generator   SET NEXT_VAL = (SELECT IFNULL(MAX(PROPOSAL_COMMENT_ID),0) + 1  FROM proposal_comments);
	END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
END IF;
END
$$
DELIMITER ;
