DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PROP_YNQ`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_PROP_YNQ_ID int;
DECLARE LI_MIGRATED_QUESTION_ID int;
DECLARE LI_MIGRATED_QUESTION_NUMBER int;
DECLARE LI_MIGRATED_QUESTIONNAIRE_ID int;
DECLARE LI_MIGRATED_QUESTIONNAIRE_NUMBER INT;
DECLARE LI_MIGRATED_QUESTION_OPTION_ID INT;
DECLARE LI_MIGRATED_QUESTIONNAIRE_USAGE_ID INT;
DECLARE LS_QUESTION_ID varchar(4);
DECLARE LS_DESCRIPTION varchar(400) ;
DECLARE LS_QUESTION_TYPE char(1);
DECLARE LS_NO_OF_ANSWERS tinyint ;
DECLARE LS_STATUS char(1) ;
DECLARE LS_EFFECTIVE_DATE datetime ;
DECLARE LI_STG_PROP_EXP_YNQ_ID INT;
DECLARE LS_EXPLANATION longtext;
DECLARE LS_GROUP_NAME varchar(150);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(20);
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_PROP_YNQ_CREATED INT default 0;
DECLARE LI_PROP_PERS_YNQ_CREATED INT default 0;
DECLARE LS_DATA_ERROR_FLAG varchar(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
DECLARE LS_UPDATE_USER VARCHAR(60);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog (PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_STG_PROP_YNQ_ID,'PROP_YNQ','MIGRATION',LS_ERROR_MSG,UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('PROP_YNQ') AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_prop_ynq SET VALIDATION_STATUS = 'VALID' ,MIGRATED_QUESTIONNAIRE_ID = NULL, MIGRATED_QUESTION_ID = NULL WHERE VALIDATION_STATUS = 'ERROR' AND MIGRATED_QUESTION_ID = -1;
			UPDATE stage_prop_explanation_ynq SET VALIDATION_STATUS = 'VALID' WHERE VALIDATION_STATUS = 'ERROR';
		SET SQL_SAFE_UPDATES = 1;
	END IF;
END;
BEGIN
SET SQL_SAFE_UPDATES = 0;
	DELETE FROM migration_qtn_execution_log;
	ALTER TABLE migration_qtn_execution_log AUTO_INCREMENT = 1;
	SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_prop_ynq;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'PROP_YNQ';
	INSERT INTO migration_transtn_auditlog_header1 (BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME) VALUES (LI_BATCH_ID,'MIGRATION','PROP_YNQ',UTC_TIMESTAMP());
	INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution : PROP_YNQ ',UTC_TIMESTAMP());
END;
BEGIN
					select IFNULL(max(QUESTIONNAIRE_ID),0)+1 , IFNULL(max(QUESTIONNAIRE_NUMBER),0)+1
							into LI_MIGRATED_QUESTIONNAIRE_ID, LI_MIGRATED_QUESTIONNAIRE_NUMBER
					from quest_header;
					INSERT INTO quest_header(
									QUESTIONNAIRE_ID
									,QUEST_GROUP_TYPE_CODE
									,IS_FINAL
									,QUESTIONNAIRE_NUMBER
									,VERSION_NUMBER
									,QUESTIONNAIRE
									,DESCRIPTION
									,UPDATE_TIMESTAMP
									,UPDATE_USER
							)Values(
									LI_MIGRATED_QUESTIONNAIRE_ID
									,NULL
									,'Y'
									,LI_MIGRATED_QUESTIONNAIRE_NUMBER
									,1
									,'Proposal YNQ'
									,'YNQ Questions for proposal'
									, UTC_TIMESTAMP()
									,'JHU_ADMIN'
								);
					select IFNULL(max(QUESTIONNAIRE_USAGE_ID),0)+1 into LI_MIGRATED_QUESTIONNAIRE_USAGE_ID from quest_usage;
					INSERT INTO quest_usage(
								QUESTIONNAIRE_USAGE_ID
								,MODULE_ITEM_CODE
								,MODULE_SUB_ITEM_CODE
								,QUESTIONNAIRE_ID
								,QUESTIONNAIRE_LABEL
								,IS_MANDATORY
								,RULE_ID
								,UPDATE_TIMESTAMP
								,UPDATE_USER
								,SORT_ORDER
								,TRIGGER_POST_EVALUATION
							)VALUES(
								LI_MIGRATED_QUESTIONNAIRE_USAGE_ID
								,3
								,0
								,LI_MIGRATED_QUESTIONNAIRE_ID
								,'Proposal YNQ'
								,'Y'
								,NULL
								,date(UTC_TIMESTAMP())
								,'JHU_ADMIN'
								,1
								,NULL
								);
		BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_PROP_YNQ CURSOR FOR
		select SPY.ID
				,SPY.QUESTION_ID
				,SPY.DESCRIPTION
				,SPY.QUESTION_TYPE
				,SPY.NO_OF_ANSWERS
				,SPY.STATUS
				,SPY.GROUP_NAME
                ,SPY.UPDATE_USER
                ,SPY.UPDATE_TIMESTAMP
                ,SPEY.ID
				,SPEY.EXPLANATION
		from stage_prop_ynq SPY
		LEFT OUTER JOIN stage_prop_explanation_ynq SPEY ON SPY.QUESTION_ID = SPEY.QUESTION_ID
		where SPY.VALIDATION_STATUS = 'VALID'
		ORDER BY SPY.ID ASC;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_PROP_YNQ;
		PROP_YNQ_LOOP: LOOP
		FETCH CUR_PROP_YNQ INTO LI_STG_PROP_YNQ_ID
								,LS_QUESTION_ID
								,LS_DESCRIPTION
								,LS_QUESTION_TYPE
								,LS_NO_OF_ANSWERS
								,LS_STATUS
								,LS_GROUP_NAME
                                , LS_UPDATE_USER
                                , LS_UPDATE_TIMESTAMP
                                ,LI_STG_PROP_EXP_YNQ_ID
								,LS_EXPLANATION;
		IF DONE1 THEN
			LEAVE PROP_YNQ_LOOP;
		END IF;
				SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('MIGRATION','PROP_YNQ',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_QUESTION_ID);
					SET LS_DATA_ERROR_FLAG = 'N';
					select IFNULL(max(QUESTION_ID),0)+1  , IFNULL(max(QUESTION_NUMBER),0)+1
							into LI_MIGRATED_QUESTION_ID , LI_MIGRATED_QUESTION_NUMBER
					from quest_question;
					insert into quest_question(
									QUESTION_ID
									,QUESTION_NUMBER
									,QUESTION_VERSION_NUMBER
									,QUESTIONNAIRE_ID
									,SORT_ORDER
									,QUESTION
									,DESCRIPTION
									,PARENT_QUESTION_ID
									,HELP_LINK
									,ANSWER_TYPE
									,ANSWER_LENGTH
									,NO_OF_ANSWERS
									,LOOKUP_TYPE
									,LOOKUP_NAME
									,LOOKUP_FIELD
									,GROUP_NAME
									,GROUP_LABEL
									,HAS_CONDITION
									,UPDATE_TIMESTAMP
									,UPDATE_USER
							)VALUES(
									LI_MIGRATED_QUESTION_ID
									,LI_MIGRATED_QUESTION_NUMBER
									,1
									,LI_MIGRATED_QUESTIONNAIRE_ID
									,LI_STG_PROP_YNQ_ID
									,LS_DESCRIPTION
									,LS_EXPLANATION
									,NULL
									,NULL
									,'Y/N/NA'
									,NULL
									,1
									,NULL
									,NULL
									,NULL
									,'G0'
									,NULL
									,NULL
									,date(LS_UPDATE_TIMESTAMP)
									,LS_UPDATE_USER
									);
					select IFNULL(max(QUESTION_OPTION_ID),0)+1
					into LI_MIGRATED_QUESTION_OPTION_ID from quest_question_option;
					INSERT INTO quest_question_option(
								QUESTION_OPTION_ID
								, QUESTION_ID
								, OPTION_NUMBER
								, OPTION_LABEL
								, REQUIRE_EXPLANATION
								, EXPLANTION_LABEL
								, UPDATE_TIMESTAMP
								, UPDATE_USER
							)VALUES(
								LI_MIGRATED_QUESTION_OPTION_ID
								, LI_MIGRATED_QUESTION_ID
								,1
								,'Yes'
								,NULL
								,NULL
								,date(LS_UPDATE_TIMESTAMP)
									,LS_UPDATE_USER
                                    );
					INSERT INTO quest_question_option(
								QUESTION_OPTION_ID
								, QUESTION_ID
								, OPTION_NUMBER
								, OPTION_LABEL
								, REQUIRE_EXPLANATION
								, EXPLANTION_LABEL
								, UPDATE_TIMESTAMP
								, UPDATE_USER
							)VALUES(
								LI_MIGRATED_QUESTION_OPTION_ID+1
								, LI_MIGRATED_QUESTION_ID
								,2
								,'No'
								,NULL
								,NULL
								,date(LS_UPDATE_TIMESTAMP)
									,LS_UPDATE_USER
                                    );
					INSERT INTO quest_question_option(
								QUESTION_OPTION_ID
								, QUESTION_ID
								, OPTION_NUMBER
								, OPTION_LABEL
								, REQUIRE_EXPLANATION
								, EXPLANTION_LABEL
								, UPDATE_TIMESTAMP
								, UPDATE_USER
							)VALUES(
								LI_MIGRATED_QUESTION_OPTION_ID+2
								, LI_MIGRATED_QUESTION_ID
								,3
								,'N/A'
								,NULL
								,NULL
								,date(LS_UPDATE_TIMESTAMP)
									,LS_UPDATE_USER
                                    );
					UPDATE stage_prop_ynq SET MIGRATED_QUESTIONNAIRE_ID = LI_MIGRATED_QUESTIONNAIRE_ID
											, MIGRATED_QUESTION_ID = LI_MIGRATED_QUESTION_ID
											, VALIDATION_STATUS = 'SUCCESS' where ID =  LI_STG_PROP_YNQ_ID;
					UPDATE stage_prop_explanation_ynq SET
											  VALIDATION_STATUS = 'SUCCESS' where ID =  LI_STG_PROP_EXP_YNQ_ID;
					IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Migrated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Proposal YNQ Questions'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('MIGRATION','PROP_YNQ',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LS_Question_id);
		END LOOP;
		CLOSE CUR_PROP_YNQ;
		INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
												VALUES ('MIGRATION','PROP_YNQ',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),NULL);
				INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Migrated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Proposal YNQ Questions'),UTC_TIMESTAMP()),('Migration completed successfully',UTC_TIMESTAMP());
		set sql_safe_updates = 0;
		update quest_column_nextvalue set
							QUESTIONNAIRE_ID = (select IFNULL(max(QUESTIONNAIRE_ID),0)+1 from quest_header)
							,QUESTIONNAIRE_NUMBER = (select IFNULL(max(QUESTIONNAIRE_NUMBER),0)+1 from quest_header)
							,QUESTIONNAIRE_USAGE_ID = (select IFNULL(max(QUESTIONNAIRE_USAGE_ID),0)+1 from quest_usage)
							,QUESTION_ID = (select IFNULL(max(QUESTION_ID),0)+1 from quest_question)
							,QUESTION_NUMBER  = (select IFNULL(max(QUESTION_NUMBER),0)+1 from quest_question)
							,QUESTION_OPTION_ID = (select IFNULL(max(QUESTION_OPTION_ID),0)+1 from quest_question_option);
					SELECT COUNT(*) INTO LI_SOURCE_COUNT FROM stage_prop_ynq;
					SELECT COUNT(*) INTO LI_DESTINATION_COUNT FROM quest_question
											where question_id in (select migrated_question_id from stage_prop_ynq);
					IF LI_SOURCE_COUNT = LI_DESTINATION_COUNT THEN
						SET LS_MIGRATION_STATUS = 'SUCCESS';
					ELSE
						SET LS_MIGRATION_STATUS = 'ERROR';
					END IF;
					 INSERT INTO migration_validation_matrix (MODULE_NAME,DESTINATION_TYPE,SOURCE_NAME,DESTINATION_NAME,SOURCE_COUNT,DESTINATION_COUNT,MIGRATION_STATUS)
					 VALUES ('PROPOSAL_YNQ','FIBI','stage_prop_ynq','quest_question',LI_SOURCE_COUNT,LI_DESTINATION_COUNT,LS_MIGRATION_STATUS);
					call MIGRATION_EPS_PROP_YNQ(LI_MIGRATED_QUESTIONNAIRE_ID, DATA_REFRESH_FLAG);
					SET LS_DATA_ERROR_FLAG = 'N';
					set LI_STG_PROP_YNQ_ID = NULL;
					set LI_STG_PROP_EXP_YNQ_ID = NULL;
					set LI_MIGRATED_QUESTION_ID = NULL;
					set LI_MIGRATED_QUESTION_NUMBER = NULL;
					set LI_MIGRATED_QUESTIONNAIRE_NUMBER = NULL;
					set LI_MIGRATED_QUESTION_OPTION_ID = NULL;
					set LI_MIGRATED_QUESTIONNAIRE_USAGE_ID = NULL;
					set LS_QUESTION_ID = NULL;
					set LS_DESCRIPTION = NULL;
					set LS_QUESTION_TYPE = NULL;
					set LS_NO_OF_ANSWERS = NULL;
                    set LI_COUNT = NULL;
					set LS_STATUS = NULL;
					set LS_EFFECTIVE_DATE = NULL;
					set LS_EXPLANATION = NULL;
		END;
	END;
END
$$
DELIMITER ;
