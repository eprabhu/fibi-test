DELIMITER $$
CREATE  PROCEDURE `MIGRATION_QUEST_ANSWER_PREVAL`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUEST_ANSWER_ID INT;
DECLARE LS_QUESTIONNAIRE_COMPLETION_ID varchar(10);
DECLARE LI_QUESTION_ID INT;
DECLARE LS_ANSWER VARCHAR(2000);
DECLARE LI_QUESTION_VERSION_NUMBER INT;
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_STG_QUEST_ANSWER_ID,'QUEST_ANSWER','VALIDATION',CONCAT(LS_ERROR_MSG),UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_ANSWER') AND ERROR_TYPE = 'VALIDATION';
			UPDATE stage_quest_answer SET VALIDATION_STATUS = NULL where VALIDATION_STATUS = 'ERROR' and MIGRATION_QUEST_ANSWER_ID = NULL;
		SET SQL_SAFE_UPDATES = 1;
	END IF;
END;
BEGIN
SET SQL_SAFE_UPDATES = 0;
	DELETE FROM migration_qtn_execution_log;
	ALTER TABLE migration_qtn_execution_log AUTO_INCREMENT = 1;
SET SQL_SAFE_UPDATES = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_quest_answer;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'QUEST_ANSWER';
	INSERT INTO migration_transtn_auditlog_header1 (BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
										VALUES 	(LI_BATCH_ID,'VALIDATION','QUEST_ANSWER',UTC_TIMESTAMP());
	INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution : QUEST_ANSWER ',UTC_TIMESTAMP());
END;
		BEGIN
		DECLARE DONE7 INT DEFAULT FALSE;
		DECLARE CUR_QUEST_ANSWER CURSOR FOR
		select ID
				, QUESTIONNAIRE_COMPLETION_ID
				, QUESTION_ID
				, QUESTION_VERSION_NUMBER
				, ANSWER
		from stage_quest_answer
        where validation_status is NULL
        ORDER BY QUESTIONNAIRE_COMPLETION_ID;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE7 = TRUE;
		OPEN CUR_QUEST_ANSWER;
		QUEST_ANSWER_LOOP: LOOP
		FETCH CUR_QUEST_ANSWER INTO
									LI_STG_QUEST_ANSWER_ID
									, LS_QUESTIONNAIRE_COMPLETION_ID
									, LI_QUESTION_ID
									, LI_QUESTION_VERSION_NUMBER
									, LS_ANSWER;
		IF DONE7 THEN
			LEAVE QUEST_ANSWER_LOOP;
		END IF;
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('VALIDATION','QUEST_ANSWER',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LI_QUESTION_ID);
					SET LS_DATA_ERROR_FLAG = 'N';
					SELECT COUNT(*) INTO LI_COUNT FROM
					stage_questions WHERE QUESTION_ID = LI_QUESTION_ID
					AND VERSION_NUMBER = LI_QUESTION_VERSION_NUMBER
                    and validation_status in ('VALID');
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_questionnaire_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_STG_QUEST_ANSWER_ID,'QUEST_ANSWER','VALIDATION',CONCAT('Invalid Question  :  ',LI_QUESTION_ID , '  Version_number  : ',LI_QUESTION_VERSION_NUMBER ),UTC_TIMESTAMP(),'JHU_ADMIN');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					    SELECT COUNT(1) INTO LI_COUNT FROM
						stage_quest_answer_header
                        WHERE QUESTIONNAIRE_COMPLETION_ID = LS_QUESTIONNAIRE_COMPLETION_ID AND VALIDATION_STATUS = 'VALID';
						IF (LI_COUNT <> 1) THEN
							INSERT INTO migration_questionnaire_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_STG_QUEST_ANSWER_ID,'QUEST_ANSWER','VALIDATION',CONCAT('Invalid Questionnaire completion id:  ', LS_QUESTIONNAIRE_COMPLETION_ID),UTC_TIMESTAMP(),'JHU_ADMIN');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					IF (trim(LS_ANSWER) is NULL) THEN
						INSERT INTO migration_questionnaire_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_STG_QUEST_ANSWER_ID,'QUEST_ANSWER','VALIDATION',CONCAT('Answer is NULL for Question_id :',LI_QUESTION_ID,' Questionnaire_completion_id : ', LS_QUESTIONNAIRE_COMPLETION_ID) ,UTC_TIMESTAMP(),'JHU_ADMIN');
					END IF;
						IF LS_DATA_ERROR_FLAG = 'Y' THEN
							UPDATE stage_quest_answer SET VALIDATION_STATUS = 'ERROR' where ID =  LI_STG_QUEST_ANSWER_ID;
                            update stage_quest_answer_header set validation_status = 'ERROR' where QUESTIONNAIRE_COMPLETION_ID = LS_QUESTIONNAIRE_COMPLETION_ID;
						ELSE
							UPDATE stage_quest_answer SET VALIDATION_STATUS = 'VALID' where ID =  LI_STG_QUEST_ANSWER_ID;
						END IF;
				IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Validated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Questionnaire Answers'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('VALIDATION','QUEST_ANSWER',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LI_QUESTION_ID);
					SET LS_DATA_ERROR_FLAG = 'N';
					set LI_COUNT = NULL;
					set LI_STG_QUEST_ANSWER_ID = NULL;
					set LS_QUESTIONNAIRE_COMPLETION_ID = NULL;
					set LI_QUESTION_ID = NULL;
					set LI_QUESTION_VERSION_NUMBER = NULL;
					set LS_ANSWER = NULL;
				END LOOP;
				CLOSE CUR_QUEST_ANSWER;
				INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','QUEST_ANSWER',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),NULL);
			INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Validated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Questionnaire answer'),UTC_TIMESTAMP()),('Validation completed successfully',UTC_TIMESTAMP());
			END;
END
$$
DELIMITER ;
