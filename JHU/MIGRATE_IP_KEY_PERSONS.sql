DELIMITER $$
CREATE DEFINER=`jhufibi`@`%` PROCEDURE `MIGRATE_IP_KEY_PERSONS`(DATA_RECORD_ID INT,DATA_PROPOSAL_NUMBER VARCHAR(8),DATA_SEQUENCE_NUMBER INT,DATA_PROPOSAL_ID INT,DATA_KEY_PERSON_INDICATOR VARCHAR(2),FOR_AUDIT INT,DATA_SEQ_STATUS VARCHAR(20),OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_KP_RECORD_ID INT;
DECLARE LI_PROPOSAL_PERSON_ID INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_KP_SEQUENCE_NUMBER INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LI_MAX_SEQUENCE_NUMBER INT;
DECLARE LI_PROP_PERSON_ROLE_ID INT;
DECLARE LI_PROP_PERSON_KP_ROLE_ID INT;
DECLARE LS_PERCENTAGE_EFFORT DECIMAL(5, 2);
DECLARE LS_PERCENTAGE_OF_EFFORT DECIMAL(5,2);
DECLARE LS_ACADEMIC_YEAR_EFFORT DECIMAL(5,2);
DECLARE LS_CALENDAR_YEAR_EFFORT DECIMAL(5,2);
DECLARE LS_SUMMER_YEAR_EFFORT DECIMAL(5,2);
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_KP_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_KEY_PERSON_INDICATOR VARCHAR(2);
DECLARE LS_FULL_NAME VARCHAR(30);
DECLARE LS_PERSON_ID VARCHAR(40);
DECLARE LS_ROLODEX_ID VARCHAR(8);
DECLARE LS_PROJECT_ROLE VARCHAR(60);
DECLARE LS_NON_MIT_FLAG VARCHAR(1);
DECLARE LS_PI_FLAG VARCHAR(1);
DECLARE LS_MULTI_PI VARCHAR(255);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_DATA_VALID VARCHAR(1);
DECLARE LS_DATA_AVAILABLE_FLAG VARCHAR(1);
DECLARE LS_DELETED_DATA VARCHAR(1);
DECLARE LS_VALIDATION_STATUS VARCHAR(10);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LS_ERROR VARCHAR(2000);
DECLARE LI_BATCH_ID INT;
BEGIN
	SET LI_COUNT = -1;
	SET LS_DATA_ERROR_FLAG = 'N';
	SELECT COUNT(1) INTO LI_COUNT FROM eps_prop_person_role WHERE UPPER(DESCRIPTION) = UPPER('Key Study Person') AND IS_ACTIVE = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'INSTPROPKEYPERSON','MIGRATION',CONCAT('Invalid proposal role : Key Study Person'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT PROP_PERSON_ROLE_ID INTO LI_PROP_PERSON_KP_ROLE_ID FROM eps_prop_person_role WHERE UPPER(DESCRIPTION) = UPPER('Key Study Person') AND IS_ACTIVE = 'Y';
	END IF;
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'INSTPROPKEYPERSON';
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
END;
BEGIN
	SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_SEQUENCE_NUMBER FROM stage_proposal_key_persons
	WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= DATA_SEQUENCE_NUMBER AND VALIDATION_STATUS <> 'ERROR';
	IF LI_MAX_SEQUENCE_NUMBER = 0 THEN
		SET LS_DATA_AVAILABLE_FLAG = 'N';
	ELSE
		SET LS_DATA_AVAILABLE_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'fetch max sequence',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
	END IF;
END;
IF LS_DATA_AVAILABLE_FLAG = 'Y' AND LS_DATA_ERROR_FLAG = 'N' THEN
BEGIN
	DECLARE DONE2 INT DEFAULT FALSE;
	DECLARE MIGRATION_IP_KP_CURSOR CURSOR FOR
	SELECT       			MIGRATION_PROP_KEY_PERSON_ID,
							PROPOSAL_NUMBER,
							SEQUENCE_NUMBER,
							PERSON_ID,
							PERSON_NAME,
							PROJECT_ROLE,
							NON_MIT_PERSON_FLAG,
							PERCENTAGE_EFFORT,
							ACADEMIC_YEAR_EFFORT,
							SUMMER_YEAR_EFFORT,
							CALENDAR_YEAR_EFFORT,
							'N' AS PRINCIPAL_INVESTIGATOR_FLAG,
							'N' AS MULTI_PI_FLAG,
							UPDATE_TIMESTAMP,
							UPDATE_USER
	FROM  stage_proposal_key_persons  WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_SEQUENCE_NUMBER AND VALIDATION_STATUS <> 'ERROR';
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
				GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
				SELECT @full_error INTO LS_ERROR;
				UPDATE stage_proposal_key_persons
				SET VALIDATION_STATUS = 'ERROR'
				WHERE MIGRATION_PROP_KEY_PERSON_ID = LI_KP_RECORD_ID;
				INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_KP_RECORD_ID,'INSTPROPKEYPERSON','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
				SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_IP_KP_CURSOR;
	MIGRATION_IP_KP_CURSOR_LOOP :          		LOOP
	FETCH  MIGRATION_IP_KP_CURSOR          		INTO						LI_KP_RECORD_ID,
																			LS_KP_PROPOSAL_NUMBER,
																			LI_KP_SEQUENCE_NUMBER,
																			LS_PERSON_ID,
																			LS_FULL_NAME,
																			LS_PROJECT_ROLE,
																			LS_NON_MIT_FLAG,
																			LS_PERCENTAGE_EFFORT,
																			LS_ACADEMIC_YEAR_EFFORT,
																			LS_SUMMER_YEAR_EFFORT,
																			LS_CALENDAR_YEAR_EFFORT,
																			LS_PI_FLAG,
																			LS_MULTI_PI,
																			LS_UPDATE_TIMESTAMP,
																			LS_UPDATE_USER;
	IF DONE2 THEN
		LEAVE MIGRATION_IP_KP_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_PROPOSAL_PERSON_ID = -1;
	SET LS_DATA_VALID = 'Y';
	IF LS_PERCENTAGE_EFFORT IS NULL AND LS_ACADEMIC_YEAR_EFFORT IS NULL AND LS_CALENDAR_YEAR_EFFORT IS NULL AND LS_SUMMER_YEAR_EFFORT IS NULL THEN
		SET LS_PERCENTAGE_OF_EFFORT = NULL;
	ELSE
		SELECT GREATEST(IFNULL(LS_PERCENTAGE_EFFORT,0),IFNULL(LS_ACADEMIC_YEAR_EFFORT,0),IFNULL(LS_SUMMER_YEAR_EFFORT,0),IFNULL(LS_CALENDAR_YEAR_EFFORT,0)) INTO LS_PERCENTAGE_OF_EFFORT FROM DUAL;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'after percentage effort logic',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	IF LS_NON_MIT_FLAG = 'N' THEN
		SELECT COUNT(1) INTO LI_COUNT FROM proposal_persons WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = DATA_SEQUENCE_NUMBER AND PERSON_ID = LS_PERSON_ID;
	ELSE
		SELECT COUNT(1) INTO LI_COUNT FROM proposal_persons WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = DATA_SEQUENCE_NUMBER AND ROLODEX_ID = LS_PERSON_ID;
	END IF;
	IF LI_COUNT > 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_KP_RECORD_ID,'INSTPROPKEYPERSON','MIGRATION',IFNULL(CONCAT('Data already exists for the proposal number : ', DATA_PROPOSAL_NUMBER,' and the sequence number :',DATA_SEQUENCE_NUMBER,' and the person id',LS_PERSON_ID),CONCAT('Data already exists for the proposal number : ', LS_KP_PROPOSAL_NUMBER,' and the sequence number :',LI_KP_SEQUENCE_NUMBER,' and the rolodex id',LS_PERSON_ID)),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
		SET LS_DATA_VALID = 'N';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'after duplicate check',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROPOSAL_PERSON_ID),0) + 1 INTO LI_PROPOSAL_PERSON_ID
		FROM proposal_persons;
		INSERT INTO   proposal_persons
		(
			PROPOSAL_PERSON_ID,
			PROPOSAL_ID,
			PROPOSAL_NUMBER,
			SEQUENCE_NUMBER,
			DEPARTMENT,
			FULL_NAME,
			UNIT_NAME,
			UNIT_NUMBER,
			PERSON_ID,
			PROP_PERSON_ROLE_ID,
			ROLODEX_ID,
			PERCENTAGE_OF_EFFORT,
			EMAIL_ADDRESS,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			DESIGNATION,
			PI_FLAG,
			IS_MULTI_PI,
			PROJECT_ROLE
		)
		VALUES
		(
			LI_PROPOSAL_PERSON_ID,
			DATA_PROPOSAL_ID,
			DATA_PROPOSAL_NUMBER,
			DATA_SEQUENCE_NUMBER,
			NULL,
			LS_FULL_NAME,
			NULL,
			NULL,
			CASE WHEN LS_NON_MIT_FLAG = 'N' THEN LS_PERSON_ID ELSE NULL END,
			LI_PROP_PERSON_KP_ROLE_ID,
			CASE WHEN LS_NON_MIT_FLAG = 'Y' THEN LS_PERSON_ID ELSE NULL END,
			LS_PERCENTAGE_OF_EFFORT,
			NULL,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER,
			NULL,
			LS_PI_FLAG,
			LS_MULTI_PI,
			LS_PROJECT_ROLE
		);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SET LS_VALIDATION_STATUS = 'SUCCESS';
		SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
		SET LS_CHILD_ERROR = 'N';
		CALL MIGRATE_IP_KP_UNITS(LI_KP_RECORD_ID,LS_KP_PROPOSAL_NUMBER,LI_KP_SEQUENCE_NUMBER,DATA_SEQUENCE_NUMBER,LS_PERSON_ID,LI_PROPOSAL_PERSON_ID,DATA_PROPOSAL_ID,FOR_AUDIT,@kp_unit_error_count);
		IF @kp_unit_error_count > 0 THEN
			SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'PROP KP UNITS');
			SET LS_CHILD_ERROR = 'Y';
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'after child call',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
		END IF;
		IF LS_CHILD_ERROR = 'Y' THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_KP_RECORD_ID,'INSTPROPKEYPERSON','MIGRATION',IFNULL(CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',LS_KP_PROPOSAL_NUMBER,'and the person id : ',LS_PERSON_ID),CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',LS_KP_PROPOSAL_NUMBER,'and the rolodex id : ',LS_ROLODEX_ID)),UTC_TIMESTAMP(),'quickstart');
			SET LS_VALIDATION_STATUS  = 'ERROR';
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_proposal_key_persons
		SET VALIDATION_STATUS = LS_VALIDATION_STATUS,
		FIBI_IDENTIFIER = CASE  WHEN LS_VALIDATION_STATUS = 'ERROR' THEN -1 ELSE LI_PROPOSAL_PERSON_ID END
		WHERE MIGRATION_PROP_KEY_PERSON_ID = LI_KP_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'after update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
		END IF;
	ELSE
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT MIGRATION_PROP_KP_UNITS_ID,'INSTPROPKPUNITS','MIGRATION',CONCAT('Parent record failed for the proposal number : ', LS_KP_PROPOSAL_NUMBER,' and the sequence number : ',LI_KP_SEQUENCE_NUMBER,' and the person : ',LS_PERSON_ID),UTC_TIMESTAMP(),'quickstart' FROM stage_proposal_key_person_units WHERE PROPOSAL_NUMBER = LS_KP_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_KP_SEQUENCE_NUMBER AND PERSON_ID = LS_PERSON_ID;
		UPDATE stage_proposal_key_person_units
		SET VALIDATION_STATUS = CASE WHEN LS_DATA_VALID = 'Y' THEN 'ERROR' ELSE 'NOTVALID' END,
		FIBI_IDENTIFIER =  CASE WHEN LS_DATA_VALID = 'Y' THEN -1 ELSE NULL END
		WHERE PROPOSAL_NUMBER = LS_KP_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_KP_SEQUENCE_NUMBER AND PERSON_ID = LS_PERSON_ID;
		UPDATE stage_proposal_key_persons
		SET VALIDATION_STATUS =  CASE WHEN LS_DATA_VALID = 'Y' THEN 'ERROR' ELSE 'NOTVALID' END,
		FIBI_IDENTIFIER = CASE WHEN LS_DATA_VALID = 'Y' THEN -1 ELSE NULL END
		WHERE MIGRATION_PROP_KEY_PERSON_ID = LI_KP_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
		END IF;
	END IF;
	END LOOP MIGRATION_IP_KP_CURSOR_LOOP;
	CLOSE MIGRATION_IP_KP_CURSOR;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
	END IF;
END;
	SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM  stage_proposal_key_persons WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1 AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = DATA_SEQUENCE_NUMBER;
ELSE
	INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
	VALUES  (DATA_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT('There is no data available in the stage_proposal_key_persons table with the proposal number :  ',DATA_PROPOSAL_NUMBER,' and the sequence number : ',DATA_SEQUENCE_NUMBER,' with the indicator : ',DATA_KEY_PERSON_INDICATOR),UTC_TIMESTAMP(),'quickstart');
	IF DATA_SEQ_STATUS = 'ACTIVE' THEN
		SET DATA_ERROR_COUNT = 1;
	ELSE
		SET DATA_ERROR_COUNT = 0;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPKEYPERSON',LI_BATCH_ID,'data not available',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
	END IF;
END IF;
COMMIT;
END
$$
DELIMITER ;
