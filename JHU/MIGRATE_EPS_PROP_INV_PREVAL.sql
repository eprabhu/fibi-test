CREATE  PROCEDURE `MIGRATE_EPS_PROP_INV_PREVAL`(DATA_PROPOSAL_NUMBER VARCHAR(8),FOR_AUDIT INT, OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ROLODEX_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(9);
DECLARE LS_NON_MIT_FLAG VARCHAR(1);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'EPSKEYINVEST';
END;
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_DEV_PROP_INV_CURSOR CURSOR FOR
		SELECT  MIGRATION_INVESTIGATORS_ID,
				PROPOSAL_NUMBER,
				PERSON_ID,
				NON_MIT_PERSON_FLAG
		FROM  stage_eps_prop_investigators  WHERE
		VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
				INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_RECORD_ID,'EPSKEYINVEST','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
				SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_DEV_PROP_INV_CURSOR;
			MIGRATION_DEV_PROP_INV_CURSOR_LOOP :    LOOP
				FETCH MIGRATION_DEV_PROP_INV_CURSOR INTO     			LI_RECORD_ID,
																		LS_PROPOSAL_NUMBER,
																		LS_PERSON_ID,
																		LS_NON_MIT_FLAG;
					IF DONE1 THEN
						LEAVE MIGRATION_DEV_PROP_INV_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_NON_MIT_FLAG = 'N' THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						person   WHERE PERSON_ID = LS_PERSON_ID;
						IF LI_COUNT = 0  THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'EPSKEYINVEST','VALIDATION',IFNULL(CONCAT('Invalid person id :', LS_PERSON_ID),'Person Id is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'after person check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
						END IF;
					ELSE
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						rolodex   WHERE ROLODEX_ID = LS_PERSON_ID;
						IF LI_COUNT = 0  THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'EPSKEYINVEST','VALIDATION',IFNULL(CONCAT('Invalid rolodex id :', LS_PERSON_ID),'Person Id is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'after rolodex check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
						END IF;
					END IF;
					SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
					SET LS_CHILD_ERROR = 'N';
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
					IF LI_COUNT <> 0 THEN
						CALL MIGRATE_EPS_PROP_UNIT_PREVAL(LS_PROPOSAL_NUMBER,LS_PERSON_ID,FOR_AUDIT,@unit_data_error_count);
						IF @unit_data_error_count > 0 THEN
							SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE, 'EPS PROPOSAL INVESTIGATOR UNITS ');
							SET LS_CHILD_ERROR = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'child call end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_CHILD_ERROR = 'Y' THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'EPSKEYINVEST','VALIDATION',CONCAT('Error in the ',LS_CHILD_ERROR_MESSAGE, ' for the proposal number : ', LS_PROPOSAL_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						UPDATE stage_eps_prop_investigators
						SET VALIDATION_STATUS = 'VALID',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_INVESTIGATORS_ID = LI_RECORD_ID;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'after valid update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
						END IF;
					ELSE
						UPDATE stage_eps_prop_investigators
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_INVESTIGATORS_ID = LI_RECORD_ID;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
						END IF;
					END IF;
				IF FOR_AUDIT = 1 THEN
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'Validation end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
				END IF;
			END LOOP MIGRATION_DEV_PROP_INV_CURSOR_LOOP;
			CLOSE MIGRATION_DEV_PROP_INV_CURSOR;
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSKEYINVEST',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
			END IF;
		END;
		SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM stage_eps_prop_investigators WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER;
		COMMIT;
END
$$
DELIMITER ;
