CREATE DEFINER=`jhufibi`@`localhost` FUNCTION `FN_CHECK_PROPOSAL_BUDGET_STATUS`(
	AV_PROPOSAL_ID INT(11)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
	DECLARE LI_BUDGET_STATUS_CODE INT(2) DEFAULT 0;
    DECLARE LS_PARAM_ENABLED VARCHAR(1);
    DECLARE LS_IS_FINAL_BUDGET VARCHAR(1);
    SELECT VALUE INTO LS_PARAM_ENABLED FROM PARAMETER WHERE PARAMETER_NAME = 'ENABLE_PROPOSAL_BUDGET_VERSIONS';
    IF (LS_PARAM_ENABLED = 'N') THEN
		SELECT BUDGET_STATUS_CODE INTO LI_BUDGET_STATUS_CODE FROM BUDGET_HEADER WHERE PROPOSAL_ID = AV_PROPOSAL_ID AND IS_LATEST_VERSION = 'Y';
		IF (LI_BUDGET_STATUS_CODE = 3) THEN
		RETURN 'TRUE';
		ELSE
		RETURN 'FALSE';
		END IF;
    END IF;
END
$$
