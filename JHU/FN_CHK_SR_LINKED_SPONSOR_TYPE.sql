DELIMITER $$
CREATE  FUNCTION `FN_CHK_SR_LINKED_SPONSOR_TYPE`(
AV_SR_HEADER_ID INT,
AV_SPONSOR_TYPE varchar(6)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_FLAG INT;
DECLARE  LI_MODULE_CODE INT DEFAULT 0;
DECLARE  LI_MODULE_ITEM_ID INT DEFAULT 0;
BEGIN
	DECLARE CONTINUE HANDLER FOR NOT FOUND
	  SET LI_MODULE_ITEM_ID = 0;
      SELECT  MODULE_CODE,
                        MODULE_ITEM_ID
                        INTO
                        LI_MODULE_CODE,
                        LI_MODULE_ITEM_ID
                        FROM assoc_sr
                        WHERE SR_HEADER_ID = AV_SR_HEADER_ID ORDER BY UPDATE_TIMESTAMP ASC LIMIT 1;
END;
		IF LI_MODULE_ITEM_ID IS NULL OR LI_MODULE_ITEM_ID = 0 THEN
           RETURN 'FALSE';
	    END IF;
    IF LI_MODULE_CODE = 3 THEN
		SELECT COUNT(1) INTO LI_FLAG
		FROM EPS_PROPOSAL EP
		INNER JOIN SPONSOR SP ON SP.SPONSOR_CODE = EP.SPONSOR_CODE
		WHERE EP.PROPOSAL_ID = LI_MODULE_ITEM_ID AND SP.SPONSOR_TYPE_CODE = AV_SPONSOR_TYPE;
    ELSEIF LI_MODULE_CODE = 1 THEN
		SELECT COUNT(1) INTO LI_FLAG
		FROM AWARD AW
		INNER JOIN SPONSOR SP ON SP.SPONSOR_CODE = AW.SPONSOR_CODE
		WHERE AW.AWARD_ID = LI_MODULE_ITEM_ID
        AND AW.AWARD_SEQUENCE_STATUS = 'ACTIVE'
        AND SP.SPONSOR_TYPE_CODE = AV_SPONSOR_TYPE;
	ELSEIF LI_MODULE_CODE = 13 THEN
		SELECT COUNT(1) INTO LI_FLAG
		FROM AGREEMENT_SPONSOR AGS
		INNER JOIN SPONSOR SP ON SP.SPONSOR_CODE = AGS.SPONSOR_CODE
		WHERE AGS.AGREEMENT_REQUEST_ID = LI_MODULE_ITEM_ID AND SP.SPONSOR_TYPE_CODE = AV_SPONSOR_TYPE;
    ELSEIF LI_MODULE_CODE = 2 THEN
		SELECT COUNT(1) INTO LI_FLAG
		FROM PROPOSAL P
		INNER JOIN SPONSOR SP ON SP.SPONSOR_CODE = P.SPONSOR_CODE
		WHERE P.PROPOSAL_ID = LI_MODULE_ITEM_ID
		AND SP.PROPOSAL_SEQUENCE_STATUS = 'ACTIVE'
        AND SP.SPONSOR_TYPE_CODE = AV_SPONSOR_TYPE;
	END IF;
	IF LI_FLAG > 0 THEN
		RETURN 'TRUE';
	ELSE
		RETURN 'FALSE';
	END IF;
END
$$
DELIMITER ;
