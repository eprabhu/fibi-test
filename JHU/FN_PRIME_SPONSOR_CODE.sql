DELIMITER $$
CREATE  FUNCTION `FN_PRIME_SPONSOR_CODE`(
  AV_PROPOSAL_ID   int(10)
 ,PSC              varchar(6)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT int;
DECLARE RETURN_STRING VARCHAR(5) DEFAULT 'FALSE';
 SELECT COUNT(*)
 INTO LI_COUNT
 FROM eps_proposal p
 WHERE p.proposal_id=AV_PROPOSAL_ID
 AND   p.prime_sponsor_code = PSC;
IF LI_COUNT > 0 THEN
   SET RETURN_STRING = 'TRUE';
END IF;
RETURN RETURN_STRING;
END
$$
DELIMITER ;
