DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_EPS_PROP_PERDEG`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROPOSAL_PERSON_DEGREE_ID INT;
DECLARE LI_PROPOSAL_PERSON_ID INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(9);
DECLARE LS_DEGREE_CODE VARCHAR(10);
DECLARE LS_DEGREE VARCHAR(200);
DECLARE LS_FIELD_OF_STUDY VARCHAR(200);
DECLARE LS_SPECIALIZATION VARCHAR(200);
DECLARE LS_SCHOOL VARCHAR(200);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_GRADUATE_DATE DATETIME;
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_validation_matrix WHERE MODULE_NAME = 'PERSONDEGREE';
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'PERSONDEGREE' AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_eps_prop_person_degree SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_eps_prop_person_degree;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'PERSONDEGREE';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','PERSONDEGREE',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATE_PER_DEGREE CURSOR FOR
	SELECT      MIGRATION_PROP_DEGREE_ID,
				PROPOSAL_NUMBER,
				PERSON_ID,
				DEGREE_CODE,
				GRADUATION_DATE,
				DEGREE,
				FIELD_OF_STUDY,
				SPECIALIZATION,
				SCHOOL,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM  stage_eps_prop_person_degree  WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'PERSONDEGREE','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATE_PER_DEGREE;
	MIGRATE_PER_DEGREE_LOOP      : 				LOOP
	FETCH MIGRATE_PER_DEGREE       				INTO       		LI_RECORD_ID,
																LS_PROPOSAL_NUMBER,
																LS_PERSON_ID,
																LS_DEGREE_CODE,
																LS_GRADUATE_DATE,
																LS_DEGREE,
																LS_FIELD_OF_STUDY,
																LS_SPECIALIZATION,
																LS_SCHOOL,
																LS_UPDATE_TIMESTAMP,
																LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATE_PER_DEGREE_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SET LI_PROPOSAL_ID = -1;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	CALL JHU_FETCH_DEV_PROPOSAL_ID(LS_PROPOSAL_NUMBER,@proposal_id);
	IF @proposal_id = -1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'PERSONDEGREE','MIGRATION',CONCAT('Invalid proposal number : ', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SET LI_PROPOSAL_ID = @proposal_id;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'fetch proposal id',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM eps_proposal_persons WHERE PROPOSAL_ID = LI_PROPOSAL_ID AND PERSON_ID = LS_PERSON_ID;
	IF LI_COUNT <> 1 THEN
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM eps_proposal_persons WHERE PROPOSAL_ID = LI_PROPOSAL_ID AND ROLODEX_ID = LS_PERSON_ID;
		IF LI_COUNT <> 1 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'PERSONDEGREE','MIGRATION',CONCAT('Invalid proposal person with proposal number : ', LS_PROPOSAL_NUMBER,' and the person/rolodex id :',LS_PERSON_ID),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		ELSE
			SELECT PROPOSAL_PERSON_ID INTO LI_PROPOSAL_PERSON_ID FROM eps_proposal_persons WHERE PROPOSAL_ID = LI_PROPOSAL_ID AND ROLODEX_ID = LS_PERSON_ID;
		END IF;
	ELSE
		SELECT PROPOSAL_PERSON_ID INTO LI_PROPOSAL_PERSON_ID FROM eps_proposal_persons WHERE PROPOSAL_ID = LI_PROPOSAL_ID AND PERSON_ID = LS_PERSON_ID;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'fetch proposal person id',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER),('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'before insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		INSERT INTO   eps_proposal_person_degree
		(
			PROPOSAL_PERSON_ID,
			DEGREE_CODE,
			DEGREE,
			FIELD_OF_STUDY,
			SPECIALIZATION,
			SCHOOL,
			GRADUATION_DATE,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_PROPOSAL_PERSON_ID,
			LS_DEGREE_CODE,
			LS_DEGREE,
			LS_FIELD_OF_STUDY,
			LS_SPECIALIZATION,
			LS_SCHOOL,
			YEAR(LS_GRADUATE_DATE),
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT MAX(PROPOSAL_PERSON_DEGREE_ID) INTO LI_PROPOSAL_PERSON_DEGREE_ID FROM eps_proposal_person_degree;
		UPDATE stage_eps_prop_person_degree
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_PROPOSAL_PERSON_DEGREE_ID
		WHERE MIGRATION_PROP_DEGREE_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
	ELSE
		UPDATE stage_eps_prop_person_degree
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_PROP_DEGREE_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed processing of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END LOOP MIGRATE_PER_DEGREE_LOOP;
	CLOSE MIGRATE_PER_DEGREE;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','PERSONDEGREE',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
END;
	SET LI_COUNT = -1;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	COMMIT;
END
$$
DELIMITER ;
