DELIMITER $$
CREATE  PROCEDURE `MIGRATION_QUEST_ANS_HEADER`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUEST_ANS_HEADER_ID INT;
DECLARE LI_QUESTIONNAIRE_ID INT;
DECLARE LI_QUESTIONNAIRE_VERSION_NUMBER SMALLINt;
DECLARE LI_MIGRATED_QUESTIONNAIRE_ID INT;
DECLARE LS_MODULE_ITEM_KEY VARCHAR(8);
DECLARE LI_MIGRATED_QUEST_ANS_HEADER_ID INT;
DECLARE LS_QUESTIONNAIRE_COMPLETION_ID VARCHAR(10);
DECLARE LI_MIGRATION_QUEST_ANSWER_HEADER_ID int ;
DECLARE LI_MODULE_ITEM_CODE SMALLINT;
DECLARE LS_MODULE_SUB_ITEM_KEY VARCHAR(40);
DECLARE LI_MODULE_SUB_ITEM_CODE SMALLINT;
DECLARE LS_QUESTIONNAIRE_COMPLETED_FLAG varchar(1) ;
DECLARE LI_STG_QUEST_ANSWER_ID INT;
DECLARE LS_ANSWER VARCHAR(2000);
DECLARE LI_ANSWER_COUNT int;
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SUCCESS_QTNR INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_VALIDATION_STATUS varchar(10);
DECLARE LI_migrated_count INT;
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
DECLARE LS_UPDATE_USER VARCHAR(60);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (IFNULL(LI_STG_QUEST_ANS_HEADER_ID,0),'QUEST_ANS_HEADER','MIGRATION',LS_ERROR_MSG,UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_ANS_HEADER') AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_quest_answer_header SET VALIDATION_STATUS = 'VALID',MIGRATION_QUEST_ANSWER_HEADER_ID = NULL WHERE VALIDATION_STATUS = 'ERROR' and MIGRATION_QUEST_ANSWER_HEADER_ID = -1;
		SET SQL_SAFE_UPDATES = 1;
	END IF;
END;
BEGIN
SET SQL_SAFE_UPDATES = 0;
	DELETE FROM migration_qtn_execution_log;
	ALTER TABLE migration_qtn_execution_log AUTO_INCREMENT = 1;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'QUEST_ANS_HEADER';
	INSERT INTO migration_transtn_auditlog_header1 (BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
										VALUES 	(LI_BATCH_ID,'MIGRATION','QUEST_ANS_HEADER',UTC_TIMESTAMP());
	INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution : QUEST_ANS_HEADER ',UTC_TIMESTAMP());
END;
		BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_QUEST_ANS_HEADER CURSOR FOR
		select a.ID
				, a.MIGRATION_QUEST_ANSWER_HEADER_ID
				,a.MODULE_ITEM_CODE
				,a.MODULE_ITEM_KEY
				,a.MODULE_SUB_ITEM_CODE
				,a.MODULE_SUB_ITEM_KEY
				,a.QUESTIONNAIRE_ID
                ,a.QUESTIONNAIRE_VERSION_NUMBER
				,a.QUESTIONNAIRE_COMPLETED_FLAG
				,a.QUESTIONNAIRE_COMPLETION_ID
                ,(select MIGRATED_QUESTIONNAIRE_ID
							from stage_questionnaire
							where questionnaire_id = a.QUESTIONNAIRE_ID
							and version_number = a.QUESTIONNAIRE_VERSION_NUMBER
							and VALIDATION_STATUS = 'SUCCESS')
				,a.UPDATE_USER
                ,a.UPDATE_TIMESTAMP
		from stage_quest_answer_header a
        where exists(select count(1) from stage_questionnaire q
						where q.QUESTIONNAIRE_ID = a.QUESTIONNAIRE_ID
						and  q.VERSION_NUMBER = a.QUESTIONNAIRE_VERSION_NUMBER
						and  q.VALIDATION_STATUS = 'SUCCESS')
        and a.validation_status = 'VALID'
        ORDER BY  a.MODULE_ITEM_KEY ;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_QUEST_ANS_HEADER;
		QUEST_ANS_HEADER_LOOP: LOOP
		FETCH CUR_QUEST_ANS_HEADER INTO  LI_STG_QUEST_ANS_HEADER_ID
										, LI_MIGRATED_QUEST_ANS_HEADER_ID
										, LI_MODULE_ITEM_CODE
										, LS_MODULE_ITEM_KEY
										, LI_MODULE_SUB_ITEM_CODE
										, LS_MODULE_SUB_ITEM_KEY
										, LI_QUESTIONNAIRE_ID
                                        , LI_QUESTIONNAIRE_VERSION_NUMBER
										, LS_QUESTIONNAIRE_COMPLETED_FLAG
										, LS_QUESTIONNAIRE_COMPLETION_ID
                                        ,  LI_MIGRATED_QUESTIONNAIRE_ID
                                        , LS_UPDATE_USER
										, LS_UPDATE_TIMESTAMP;
		IF DONE1 THEN
			LEAVE QUEST_ANS_HEADER_LOOP;
		END IF;
            SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_quest_answer_header;
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,'Migration started',UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);*/
					CALL JHU_FETCH_DEV_PROPOSAL_ID(LS_MODULE_ITEM_KEY,@proposal_id);
					IF @proposal_id = -1 THEN
						INSERT INTO migration_questionnaire_errorlog(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_STG_QUEST_ANS_HEADER_ID,'QUEST_ANS_HEADER','MIGRATION',CONCAT('Invalid module item key :', LS_MODULE_ITEM_KEY),UTC_TIMESTAMP(),'JHU_ADMIN');
						UPDATE stage_quest_answer_header set MIGRATION_QUEST_ANSWER_HEADER_ID = -1, validation_status = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP() where ID = LI_STG_QUEST_ANS_HEADER_ID;
                        update  stage_quest_answer set MIGRATION_QUEST_ANSWER_ID = -1, VALIDATION_STATUS = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP()  where QUESTIONNAIRE_COMPLETION_ID = LS_QUESTIONNAIRE_COMPLETION_ID;
						   ITERATE QUEST_ANS_HEADER_LOOP;
					ELSE
						set LS_MODULE_ITEM_KEY = @proposal_id;
					END IF;
				IF LI_MODULE_SUB_ITEM_CODE = 6 THEN
						set LI_COUNT = -1;
						SELECT COUNT(*) INTO LI_COUNT FROM eps_proposal_persons
						WHERE proposal_id = LS_MODULE_ITEM_KEY
						and UPPER(PERSON_ID) = UPPER(LS_MODULE_SUB_ITEM_KEY);
                        IF LI_COUNT = 1 THEN
								SET SQL_SAFE_UPDATES =  0;
								update eps_proposal_persons set IS_PERSON_CERTIFIED = 'Y' where proposal_id = LS_MODULE_ITEM_KEY and PERSON_ID = LS_MODULE_SUB_ITEM_KEY	and LS_QUESTIONNAIRE_COMPLETED_FLAG = 'Y';
						END IF;
                    IF LI_COUNT <> 1 then
						set LI_COUNT = -1;
						SELECT COUNT(*) INTO LI_COUNT FROM eps_proposal_persons
						WHERE proposal_id = LS_MODULE_ITEM_KEY
						and UPPER(ROLODEX_ID) = UPPER(LS_MODULE_SUB_ITEM_KEY);
                        IF LI_COUNT = 1 THEN
								SET SQL_SAFE_UPDATES =  0;
								update eps_proposal_persons set IS_PERSON_CERTIFIED = 'Y' where proposal_id = LS_MODULE_ITEM_KEY and ROLODEX_ID = LS_MODULE_SUB_ITEM_KEY	and LS_QUESTIONNAIRE_COMPLETED_FLAG = 'Y';
						END IF;
								IF LI_COUNT <> 1 THEN
									INSERT INTO migration_questionnaire_errorlog (PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
									VALUES  (0 ,'QUEST_ANS_HEADER','MIGRATION',CONCAT('Invalid Proposal Person :  ', LS_MODULE_SUB_ITEM_KEY),UTC_TIMESTAMP(),'JHU_ADMIN');
									UPDATE stage_quest_answer_header set MIGRATION_QUEST_ANSWER_HEADER_ID = -1, validation_status = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP() where ID = LI_STG_QUEST_ANS_HEADER_ID;
									update  stage_quest_answer set MIGRATION_QUEST_ANSWER_ID = -1, VALIDATION_STATUS = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP()  where QUESTIONNAIRE_COMPLETION_ID = LS_QUESTIONNAIRE_COMPLETION_ID;
									ITERATE QUEST_ANS_HEADER_LOOP;
								END if;
					END IF;
                 END IF;
                              IF LI_MIGRATED_QUEST_ANS_HEADER_ID IS null or LI_MIGRATED_QUEST_ANS_HEADER_ID = -1 then
                                select IFNULL(MAX(QUESTIONNAIRE_ANS_HEADER_ID),0)+1 INTO LI_MIGRATED_QUEST_ANS_HEADER_ID
										from quest_answer_header;
							  END IF;
										INSERT INTO quest_answer_header(
																QUESTIONNAIRE_ANS_HEADER_ID
																, QUESTIONNAIRE_ID
																, MODULE_ITEM_CODE
																, MODULE_SUB_ITEM_CODE
																, MODULE_ITEM_KEY
																, MODULE_SUB_ITEM_KEY
																, QUESTIONNAIRE_COMPLETED_FLAG
																, UPDATE_TIMESTAMP
																, UPDATE_USER
														)VALUES(
																LI_MIGRATED_QUEST_ANS_HEADER_ID
																, LI_MIGRATED_QUESTIONNAIRE_ID
																, 3
																, case when LI_MODULE_SUB_ITEM_CODE = 6 then 3 else  0 end
																, LS_MODULE_ITEM_KEY
																,  case when LI_MODULE_SUB_ITEM_CODE = 6 then LS_MODULE_SUB_ITEM_KEY else  '' end
																, LS_QUESTIONNAIRE_COMPLETED_FLAG
																, LS_UPDATE_TIMESTAMP
																, LS_UPDATE_USER
															);
					UPDATE stage_quest_answer_header set MIGRATION_QUEST_ANSWER_HEADER_ID = LI_MIGRATED_QUEST_ANS_HEADER_ID where ID = LI_STG_QUEST_ANS_HEADER_ID;
                    /*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,'Insert into quest_answer_header completed ',UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);*/
                    CALL MIGRATION_QUEST_ANSWERS(LI_MIGRATED_QUEST_ANS_HEADER_ID,LI_QUESTIONNAIRE_ID,LI_QUESTIONNAIRE_VERSION_NUMBER, LS_QUESTIONNAIRE_COMPLETION_ID, DATA_REFRESH_FLAG);
                    /*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,'Insert into quest_answer completed ',UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);*/
					set LI_MIGRATED_COUNT = -1;
                    set LI_ANSWER_COUNT = -1;
                    select count(*) into LI_MIGRATED_COUNT from quest_answer where QUESTIONNAIRE_ANS_HEADER_ID = LI_MIGRATED_QUEST_ANS_HEADER_ID;
                    select count(*) into LI_ANSWER_COUNT from stage_quest_answer where  QUESTIONNAIRE_COMPLETION_ID = LS_QUESTIONNAIRE_COMPLETION_ID;
                    SET SQL_SAFE_UPDATES = 0;
                    IF LI_MIGRATED_COUNT = 0 then
						delete from quest_answer_header where QUESTIONNAIRE_ANS_HEADER_ID = LI_MIGRATED_QUEST_ANS_HEADER_ID;
						UPDATE stage_quest_answer_header set MIGRATION_QUEST_ANSWER_HEADER_ID = -1, validation_status  = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP()  where id = 	LI_STG_QUEST_ANS_HEADER_ID;
						update stage_quest_answer set MIGRATION_QUEST_ANSWER_ID = -1, validation_status = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP() where QUESTIONNAIRE_COMPLETION_ID = LS_QUESTIONNAIRE_COMPLETION_ID;
						/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,CONCAT('Roll back quest_header : ', LS_QUESTIONNAIRE_COMPLETION_ID),UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);*/
					elseif  LI_migrated_count <> LI_ANSWER_COUNT THEN
						UPDATE stage_quest_answer_header set MIGRATION_QUEST_ANSWER_HEADER_ID = LI_MIGRATED_QUEST_ANS_HEADER_ID, validation_status  = 'ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP()  where id = 	LI_STG_QUEST_ANS_HEADER_ID;
                        /*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,CONCAT('Out of ',LI_ANSWER_COUNT,' answers ', LI_migrated_count,' migrated'),UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);	*/
					elseif  LI_migrated_count = LI_ANSWER_COUNT THEN
                        UPDATE stage_quest_answer_header set MIGRATION_QUEST_ANSWER_HEADER_ID = LI_MIGRATED_QUEST_ANS_HEADER_ID, VALIDATION_STATUS = 'SUCCESS', UPDATE_TIMESTAMP = UTC_TIMESTAMP() where id = 	LI_STG_QUEST_ANS_HEADER_ID;
						/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,'All answers migrated',UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);	*/
                    END IF;
					IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Migrated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Questionnaire Answer Header'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LS_QUESTIONNAIRE_COMPLETION_ID);*/
										set LI_STG_QUEST_ANS_HEADER_ID = NULL;
										set LI_MODULE_ITEM_CODE = NULL;
										set LS_MODULE_ITEM_KEY = NULL;
										set LI_MODULE_SUB_ITEM_CODE = NULL;
										set LS_MODULE_SUB_ITEM_KEY = NULL;
										set LI_QUESTIONNAIRE_ID = NULL;
										set LS_QUESTIONNAIRE_COMPLETED_FLAG = NULL;
										set LS_QUESTIONNAIRE_COMPLETION_ID = NULL;
			END loop;
			CLOse CUR_QUEST_ANS_HEADER;
			END ;
			update quest_column_nextvalue set
                          QUESTIONNAIRE_ANS_HEADER_ID = (select IFNULL(MAX(QUESTIONNAIRE_ANS_HEADER_ID),0)+1 from quest_answer_header)
                         , QUESTIONNAIRE_ANSWER_ID = (select IFNULL(MAX(QUESTIONNAIRE_ANSWER_ID),0)+1 FROm quest_answer);
			/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANS_HEADER',LI_BATCH_ID,'Exit answer header cursor',UTC_TIMESTAMP(),NULL);*/
			INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Migrated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Questionnaire Answer Header'),UTC_TIMESTAMP()),('Migration of Answer Header completed successfully',UTC_TIMESTAMP());
set sql_safe_updates = 1;
END
$$
DELIMITER ;
