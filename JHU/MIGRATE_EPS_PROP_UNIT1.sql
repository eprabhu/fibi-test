CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_EPS_PROP_UNIT1`(FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROP_PERSON_UNIT_ID INT;
DECLARE LI_PROPOSAL_PERSON_ID INT;
DECLARE LI_PROP_PERSON_COUNT INT;
DECLARE LI_PROP_ROLODEX_COUNT INT;
DECLARE LI_PROP_PERSON_UNIT_IDCHECK INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(10);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UNIT_TYPE VARCHAR(20);
DECLARE LS_LEAD_UNIT_FLAG VARCHAR(1);
DECLARE LS_SOURCE_TYPE VARCHAR(20);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_DATA_DELETED VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_DEV_PROP_UNITS_CURSOR CURSOR FOR
	SELECT  MIGRATION_EPS_PROP_UNITS_ID,
		PROPOSAL_NUMBER,
		PERSON_ID,
		UNIT_NUMBER,
		LEAD_UNIT_FLAG,
		UPDATE_TIMESTAMP,
		UPDATE_USER
	FROM  stage_eps_prop_units WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'DEVPROPUNITS','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN   MIGRATION_DEV_PROP_UNITS_CURSOR;
	MIGRATION_DEV_PROP_UNITS_CURSOR_LOOP               :     LOOP
	FETCH MIGRATION_DEV_PROP_UNITS_CURSOR                    INTO       LI_RECORD_ID,
																		LS_PROPOSAL_NUMBER,
																		LS_PERSON_ID,
																		LS_UNIT_NUMBER,
																		LS_LEAD_UNIT_FLAG,
																		LS_UPDATE_TIMESTAMP,
																		LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_DEV_PROP_UNITS_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_PROP_PERSON_UNIT_ID = -1;
	SET LI_PROPOSAL_PERSON_ID = -1;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM eps_proposal_persons WHERE PROPOSAL_ID = LS_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
	IF LI_COUNT = 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'DEVPROPUNITS','MIGRATION',CONCAT('eps_proposal persons Data already exists proposal person id :  ', LS_PERSON_ID,' and the proposal number : ',LS_PROPOSAL_NUMBER,' and the unit number : ',LS_UNIT_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT PROPOSAL_PERSON_ID INTO LI_PROPOSAL_PERSON_ID FROM eps_proposal_persons WHERE PROPOSAL_ID = LS_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM eps_prop_person_units WHERE PROPOSAL_ID = LS_PROPOSAL_NUMBER AND PROPOSAL_PERSON_ID = LI_PROPOSAL_PERSON_ID AND UNIT_NUMBER = LS_UNIT_NUMBER;
	IF LI_COUNT = 1 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'DEVPROPUNITS','MIGRATION',CONCAT('Data already exists proposal person id :  ', LS_PERSON_ID,' and the proposal number : ',LS_PROPOSAL_NUMBER,' and the unit number : ',LS_UNIT_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPUNITS',LI_BATCH_ID,'before insert',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROP_PERSON_UNIT_ID),0) + 1 INTO LI_PROP_PERSON_UNIT_ID
		FROM eps_prop_person_units;
		INSERT INTO   eps_prop_person_units
		(
			PROP_PERSON_UNIT_ID,
			PROPOSAL_ID,
			PROPOSAL_PERSON_ID,
			LEAD_UNIT_FLAG,
			UNIT_NUMBER,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_PROP_PERSON_UNIT_ID,
			LS_PROPOSAL_NUMBER,
			LI_PROPOSAL_PERSON_ID,
			LS_LEAD_UNIT_FLAG,
			LS_UNIT_NUMBER,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
		UPDATE stage_eps_prop_units
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_PROP_PERSON_UNIT_ID
		WHERE MIGRATION_EPS_PROP_UNITS_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPUNITS',LI_BATCH_ID,'before update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
		END IF;
	ELSE
		UPDATE stage_eps_prop_units
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_EPS_PROP_UNITS_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPUNITS',LI_BATCH_ID,'error in the table',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
		END IF;
	END IF;
	END LOOP MIGRATION_DEV_PROP_UNITS_CURSOR_LOOP;
	CLOSE MIGRATION_DEV_PROP_UNITS_CURSOR;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPUNITS',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
END;
COMMIT;
END
$$
DELIMITER ;
