DELIMITER $$
CREATE DEFINER=`jhufibi`@`%` PROCEDURE `MIGRATE_IP_UNITS`(DATA_RECORD_ID INT,DATA_PROPOSAL_NUMBER VARCHAR(8),SOURCE_SEQUENCE_NUMBER INT,DEST_SEQUENCE_NUMBER INT,DATA_PERSON_ID VARCHAR(10),DATA_PROP_PERSON_ID INT,DATA_PROPOSAL_ID INT,FOR_AUDIT INT,DATA_SEQ_STATUS VARCHAR(20),OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROP_PERSON_UNIT_ID INT;
DECLARE LI_PROPOSAL_PERSON_ID INT;
DECLARE LI_PROP_PERSON_COUNT INT;
DECLARE LI_PROP_ROLODEX_COUNT INT;
DECLARE LI_PROP_PERSON_UNIT_IDCHECK INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LI_MAX_SEQUENCE_NUMBER INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(9);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UNIT_TYPE VARCHAR(20);
DECLARE LS_LEAD_UNIT_FLAG VARCHAR(1);
DECLARE LS_SOURCE_TYPE VARCHAR(20);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT1 INT;
DECLARE LI_SOURCE_COUNT2 INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_DATA_AVAILABLE_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'INSTPROPUNITS';
IF FOR_AUDIT = 1 THEN
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
END IF;
END;
BEGIN
	SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_SEQUENCE_NUMBER FROM stage_proposal_units
	WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= SOURCE_SEQUENCE_NUMBER AND VALIDATION_STATUS <> 'ERROR';
	IF LI_MAX_SEQUENCE_NUMBER = 0 THEN
		SET LS_DATA_AVAILABLE_FLAG = 'N';
	ELSE
		SET LS_DATA_AVAILABLE_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,CONCAT('data available flag',LS_DATA_AVAILABLE_FLAG),UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'fetch max sequence',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
END;
IF LS_DATA_AVAILABLE_FLAG = 'Y' THEN
IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'availability flag : Y',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
END IF;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_INST_PROP_UNITS_CURSOR CURSOR FOR
	SELECT  MIGRATION_PROP_UNITS_ID,
		PROPOSAL_NUMBER,
		SEQUENCE_NUMBER,
		PERSON_ID,
		UNIT_NUMBER,
		LEAD_UNIT_FLAG,
		UPDATE_TIMESTAMP,
		UPDATE_USER
	FROM  stage_proposal_units WHERE VALIDATION_STATUS <> 'ERROR' AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_SEQUENCE_NUMBER AND PERSON_ID = DATA_PERSON_ID;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'INSTPROPUNITS','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
		COMMIT;
	END;
	OPEN   MIGRATION_INST_PROP_UNITS_CURSOR;
	MIGRATION_INST_PROP_UNITS_CURSOR_LOOP               :    LOOP
	FETCH MIGRATION_INST_PROP_UNITS_CURSOR                   INTO       LI_RECORD_ID,
																		LS_PROPOSAL_NUMBER,
																		LI_SEQUENCE_NUMBER,
																		LS_PERSON_ID,
																		LS_UNIT_NUMBER,
																		LS_LEAD_UNIT_FLAG,
																		LS_UPDATE_TIMESTAMP,
																		LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_INST_PROP_UNITS_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_PROP_PERSON_UNIT_ID = -1;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM prop_person_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = DEST_SEQUENCE_NUMBER AND PROPOSAL_PERSON_ID = DATA_PROP_PERSON_ID AND UNIT_NUMBER = LS_UNIT_NUMBER;
	IF LI_COUNT = 1 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'INSTPROPUNITS','MIGRATION',CONCAT('Data already exists for the  proposal person id :  ', DATA_PERSON_ID,' and the proposal number : ',LS_PROPOSAL_NUMBER,' and the sequence number : ',DEST_SEQUENCE_NUMBER,' and the unit number : ',LS_UNIT_NUMBER),UTC_TIMESTAMP(),'quickstart');
			COMMIT;
			SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'duplicate check',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROP_PERSON_UNIT_ID),0) + 1 INTO LI_PROP_PERSON_UNIT_ID
		FROM prop_person_units;
		INSERT INTO   prop_person_units
		(
			PROP_PERSON_UNIT_ID,
			PROPOSAL_PERSON_ID,
			PROPOSAL_ID,
			PROPOSAL_NUMBER,
			SEQUENCE_NUMBER,
			LEAD_UNIT_FLAG,
			UNIT_NUMBER,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_PROP_PERSON_UNIT_ID,
			DATA_PROP_PERSON_ID,
			DATA_PROPOSAL_ID,
			LS_PROPOSAL_NUMBER,
			DEST_SEQUENCE_NUMBER,
			LS_LEAD_UNIT_FLAG,
			LS_UNIT_NUMBER,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_proposal_units
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_PROP_PERSON_UNIT_ID
		WHERE MIGRATION_PROP_UNITS_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
		END IF;
	ELSE
		UPDATE stage_proposal_units
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_PROP_UNITS_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
		END IF;
	END IF;
	END LOOP MIGRATION_INST_PROP_UNITS_CURSOR_LOOP;
	CLOSE MIGRATION_INST_PROP_UNITS_CURSOR;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
END;
	SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM  stage_proposal_units WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1 AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = SOURCE_SEQUENCE_NUMBER AND PERSON_ID = DATA_PERSON_ID;
ELSE
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'else case',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
	 INSERT INTO migration_transaction_errorlog
		 (PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
	 VALUES  (DATA_RECORD_ID,'INSTPROPINVEST','MIGRATION',CONCAT('There is no data available in the stage_proposal_units table with the proposal number :  ',DATA_PROPOSAL_NUMBER,' and the sequence number : ',SOURCE_SEQUENCE_NUMBER,' with the person : ',DATA_PERSON_ID),UTC_TIMESTAMP(),'quickstart');
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'before data error count set',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
	IF DATA_SEQ_STATUS = 'ACTIVE' THEN
		SET DATA_ERROR_COUNT = 1;
	ELSE
		SET DATA_ERROR_COUNT = 0;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,CONCAT('seq status : ',DATA_SEQ_STATUS),UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,CONCAT('data error count : ',DATA_ERROR_COUNT),UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','INSTPROPUNITS',LI_BATCH_ID,'data not available',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DEST_SEQUENCE_NUMBER);
	END IF;
END IF;
	COMMIT;
END
$$
DELIMITER ;
