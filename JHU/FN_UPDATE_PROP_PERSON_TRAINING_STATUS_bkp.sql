CREATE  FUNCTION `FN_UPDATE_PROP_PERSON_TRAINING_STATUS_bkp`(AV_PROPOSAL_ID INT) RETURNS int
    DETERMINISTIC
BEGIN
	DECLARE DONE INT DEFAULT 0;
	DECLARE AV_PROPOSAL_PERSON_ID INT;
    DECLARE AV_PERSON_ID VARCHAR(40);
    DECLARE TRAINING_STATUS VARCHAR(20);
    DECLARE TRAINING_CURSOR CURSOR FOR
    SELECT DISTINCT T1.PROPOSAL_PERSON_ID, T1.PERSON_ID, T1.PROPOSAL_ID
    FROM EPS_PROPOSAL_PERSONS T1
    JOIN EPS_PROPOSAL T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID
	WHERE T2.STATUS_CODE IN ('1','3','9') AND T1.PERSON_ID IS NOT NULL;
    DECLARE PROPOSAL_TRAINING_CURSOR CURSOR FOR
	SELECT DISTINCT T1.PROPOSAL_PERSON_ID, T1.PERSON_ID, T1.PROPOSAL_ID
	FROM EPS_PROPOSAL_PERSONS T1 JOIN EPS_PROPOSAL T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID
	WHERE T2.STATUS_CODE IN ('1','3','9') AND T1.PERSON_ID IS NOT NULL
	AND T2.PROPOSAL_ID = AV_PROPOSAL_ID;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = 1;
	IF (AV_PROPOSAL_ID = 0) THEN
		OPEN TRAINING_CURSOR;
			CURS_LOOP: LOOP
			FETCH TRAINING_CURSOR INTO AV_PROPOSAL_PERSON_ID, AV_PERSON_ID, AV_PROPOSAL_ID;
				IF DONE = 1 THEN
					LEAVE CURS_LOOP;
				END IF;
				SET TRAINING_STATUS = FN_PERSON_TRAINING_COMPLETED(AV_PERSON_ID, AV_PROPOSAL_ID);
				UPDATE EPS_PROPOSAL_PERSONS SET IS_TRAINING_COMPLETED = TRAINING_STATUS
				WHERE PROPOSAL_PERSON_ID = AV_PROPOSAL_PERSON_ID AND PERSON_ID = AV_PERSON_ID;
			END LOOP CURS_LOOP;
		CLOSE TRAINING_CURSOR;
	ELSE
		OPEN PROPOSAL_TRAINING_CURSOR;
			PROPOSAL_TRAINING_CURSOR_LOOP: LOOP
			FETCH PROPOSAL_TRAINING_CURSOR INTO AV_PROPOSAL_PERSON_ID, AV_PERSON_ID, AV_PROPOSAL_ID;
				IF DONE = 1 THEN
					LEAVE PROPOSAL_TRAINING_CURSOR_LOOP;
				END IF;
				SET TRAINING_STATUS = FN_PERSON_TRAINING_COMPLETED(AV_PERSON_ID, AV_PROPOSAL_ID);
				UPDATE EPS_PROPOSAL_PERSONS SET IS_TRAINING_COMPLETED = TRAINING_STATUS
				WHERE PROPOSAL_PERSON_ID = AV_PROPOSAL_PERSON_ID
				AND PERSON_ID = AV_PERSON_ID;
			END LOOP PROPOSAL_TRAINING_CURSOR_LOOP;
		CLOSE PROPOSAL_TRAINING_CURSOR;
	 END IF;
RETURN 1;
END
$$
