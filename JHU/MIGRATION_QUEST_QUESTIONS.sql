DELIMITER $$
CREATE  PROCEDURE `MIGRATION_QUEST_QUESTIONS`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUESTION_ID INT;
DECLARE LI_QUESTIONNAIRE_ID INT;
DECLARE LI_QUESTIONNAIRE_VERSION_NUMBER INT;
DECLARE LI_MIGRATED_QUESTIONNAIRE_ID INT;
DECLARE LI_MIGRATED_QUESTIONNAIRE_NUMBER INT;
DECLARE LI_MIGRATED_QUESTION_ID INT;
DECLARE LI_MIGRATED_PARENT_QUESTION_ID INT;
DECLARE LI_MIGRATED_QUESTION_NUMBER INT;
DECLARE LI_MIGRATED_QUESTION_CONDITION_ID INT;
DECLARE LI_MIGRATED_QUESTION_OPTION_ID INT;
DECLARE LI_STG_QUEST_QTN_ID INT;
DECLARE LI_QUESTION_ID INT;
DECLARE LI_QUESTION_NUMBER INT;
DECLARE LI_QUESTION_VERSION_NUMBER INT;
DECLARE LI_PARENT_QUESTION_NUMBER INT;
DECLARE LS_QUESTION_NUMBER INT;
DECLARE LS_CONDITION_FLAG VARCHAR(1);
DECLARE LS_CONDITION_VALUE VARCHAR(2000);
DECLARE LS_CONDITION VARCHAR(50);
DECLARE LI_SORT_ORDER INT;
DECLARE LS_QUESTION VARCHAR(2000);
DECLARE LI_MAX_ANSWERS tinyint;
DECLARE LS_GROUP_NAME varchar(10);
DECLARE LS_VALID_ANSWER varchar(20);
DECLARE LS_LOOKUP_NAME varchar(50);
DECLARE LS_ANSWER_DATA_TYPE varchar(30);
DECLARE LI_ANSWER_MAX_LENGTH smallint;
DECLARE LS_LOOKUP_GUI varchar(50);
DECLARE LI_DESCRIPTION_COUNT INT;
DECLARE LS_DESCRIPTION longtext;
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_quest_count INT;
DECLARE LI_migrated_count INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_VALIDATION_STATUS varchar(10);
DECLARE LI_CHILD_QUESTION_NUMBER INT;
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
DECLARE LI_CHILD_COUNT INT;
DECLARE LI_next_child_qtn INT;
declare li_max_id int;
DECLARE LI_QUEST_QUESTIONS_ID INT;
DECLARE LI_QUEST_QUESTION_NUMBER INT;
				DECLARE CONTINUE HANDLER FOR SQLEXCEPTION BEGIN GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET  @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg );
				SELECT @full_error INTO LS_ERROR_MSG;
				INSERT INTO migration_questionnaire_errorlog (PARENT_ID, SOURCE_TYPE, ERROR_TYPE, ERROR_MESSAGE, UPDATE_TIMESTAMP, UPDATE_USER)
				VALUES (IFNULL(LI_STG_QUEST_QTN_ID, 0),'QUEST_QUESTION', 'MIGRATION', CONCAT(LS_ERROR_MSG), UTC_TIMESTAMP(), 'JHU_ADMIN');
				END;
        BEGIN
			SET SQL_SAFE_UPDATES = 0;
			IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_QUESTION','QUEST_QUESTION_OPTION')  AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_quest_questions SET VALIDATION_STATUS = 'VALID' WHERE VALIDATION_STATUS = 'ERROR' AND MIGRATED_QUESTION_ID = -1 and MIGRATED_QUESTION_NUMBER = -1;
			END IF;
		END;
BEGIN
SET SQL_SAFE_UPDATES = 0;
DELETE FROM  migration_qtn_execution_log;
ALTER TABLE migration_qtn_execution_log AUTO_INCREMENT = 1;
SET SQL_SAFE_UPDATES = 1;
SELECT IFNULL(MAX(BATCH_ID), 0 ) + 1 INTO LI_BATCH_ID FROM  migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'QUEST_QUESTION';
INSERT INTO migration_transtn_auditlog_header1 (BATCH_ID, ACTION_TYPE, MODULE_NAME, EXECUTION_TIME) VALUES (LI_BATCH_ID, 'MIGRATION', 'QUEST_QUESTION', UTC_TIMESTAMP());
INSERT INTO migration_transtn_auditlog_header1 (BATCH_ID, ACTION_TYPE, MODULE_NAME, EXECUTION_TIME) VALUES (LI_BATCH_ID, 'MIGRATION', 'QUEST_QUESTION_OPTION', UTC_TIMESTAMP());
INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE, EXECUTION_TIME) VALUES ('Started execution : QUEST_QUESTIONNAIRE_QUESTION ', UTC_TIMESTAMP());
END;
BEGIN
DECLARE DONE_QUEST INT DEFAULT FALSE;
DECLARE CUR_QUEST CURSOR FOR
							select
							  Distinct questionnaire_id,
							  VERSION_NUMBER,
							  MIGRATED_QUESTIONNAIRE_ID
							from
							  stage_questionnaire
							where
							  validation_status = 'SUCCESS'
							Order by
							  questionnaire_id, VERSION_NUMBER;
DECLARE CONTINUE HANDLER FOR NOT FOUND
SET
  DONE_QUEST = TRUE;
OPEN CUR_QUEST;
QUEST_LOOP : LOOP
FETCH CUR_QUEST INTO LI_QUESTIONNAIRE_ID,
					LI_QUESTIONNAIRE_VERSION_NUMBER,
					LI_MIGRATED_QUESTIONNAIRE_ID;
IF DONE_QUEST THEN
	LEAVE QUEST_LOOP;
END IF;
BEGIN
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE QUEST_QUEST_CURSOR CURSOR FOR
 WITH RECURSIVE quest_questions_paths (id, question_number, path) AS (
													  SELECT
														id,
														question_number,
														CAST(
														  id AS CHAR(200)
														)
													  FROM
														stage_quest_questions
													  WHERE
														parent_id IS NULL
														and questionnaire_id = LI_QUESTIONNAIRE_ID
														AND QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER
													  UNION ALL
													  SELECT
														qu.id,
														qu.question_number,
														CONCAT(qp.path, ',', qu.id)
													  FROM
														quest_questions_paths AS qp
														JOIN stage_quest_questions AS qu ON qp.id = qu.parent_id
														and qu.questionnaire_id = LI_QUESTIONNAIRE_ID
														AND qu.questionnaire_version_number = LI_QUESTIONNAIRE_VERSION_NUMBER
													)
													SELECT
													  id,
													  question_number
													FROM
													  quest_questions_paths
													ORDER BY
													  path;
DECLARE CONTINUE HANDLER FOR NOT FOUND
SET
  DONE2 = TRUE;
OPEN QUEST_QUEST_CURSOR;
QUEST_QUEST_CURSOR_LOOP : LOOP
FETCH QUEST_QUEST_CURSOR INTO LI_QUEST_QUESTIONS_ID,
								LI_QUEST_QUESTION_NUMBER;
IF DONE2 THEN LEAVE QUEST_QUEST_CURSOR_LOOP;
END IF;
								call migration_question_option(
														LI_QUESTIONNAIRE_ID
                                                        , LI_QUESTIONNAIRE_VERSION_NUMBER
                                                        , LI_MIGRATED_QUESTIONNAIRE_ID
														, LI_QUEST_QUESTION_NUMBER);
END LOOP;
END;
 set li_count = -1;
    set li_migrated_count = -1;
	select count(*) into LI_COUNT from stage_quest_questions where questionnaire_id = LI_questionnaire_id and questionnaire_version_number = LI_QUESTIONNAIRE_VERSION_NUMBER;
	select count(*) into LI_migrated_count from quest_question  where QUESTIONNAIRE_id  = LI_MIGRATED_QUESTIONNAIRE_ID;
		IF LI_COUNT <> LI_migrated_count THEN
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
					VALUES  (IFNULL(LI_STG_QUEST_QTN_ID,0),'QUEST_QUESTION','MIGRATION',CONCAT('Question validation failed, Reverting Questionnaire: Questionnaire_id -  ', LI_QUESTIONNAIRE_ID, ' Version_number - ',LI_QUESTIONNAIRE_VERSION_NUMBER),UTC_TIMESTAMP(),'JHU_ADMIN');
            INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
					VALUES  (IFNULL(LI_STG_QUEST_QTN_ID,0),'QUEST_QUESTION','MIGRATION',CONCAT('STAGE_QUESTIONS: ', LI_COUNT),UTC_TIMESTAMP(),'JHU_ADMIN');
                    INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
					VALUES  (IFNULL(LI_STG_QUEST_QTN_ID,0),'QUEST_QUESTION','MIGRATION',CONCAT('MIGRATED_QUESTION : ', LI_MIGRATED_COUNT),UTC_TIMESTAMP(),'JHU_ADMIN');
		delete from quest_question_condition where question_id in (select question_id from quest_question where QUESTIONNAIRE_id  = LI_MIGRATED_QUESTIONNAIRE_ID);
		    delete from quest_question_option where question_id in (select question_id from quest_question where QUESTIONNAIRE_id  = LI_MIGRATED_QUESTIONNAIRE_ID);
            delete from quest_question  where QUESTIONNAIRE_id  = LI_MIGRATED_QUESTIONNAIRE_ID;
			delete from quest_usage where QUESTIONNAIRE_id  = LI_MIGRATED_QUESTIONNAIRE_ID;
			delete from quest_header where QUESTIONNAIRE_id  = LI_MIGRATED_QUESTIONNAIRE_ID;
			UPDATE stage_quest_questions SET VALIDATION_STATUS = 'ERROR', MIGRATED_QUESTION_ID = -1, MIGRATED_QUESTION_NUMBER = -1 where QUESTIONNAIRE_ID = LI_QUESTIONNAIRE_ID and QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
            UPDATE stage_quest_usage SET VALIDATION_STATUS = 'ERROR', MIGRATED_QUESTIONNAIRE_USAGE_ID = -1 where QUESTIONNAIRE_ID = LI_QUESTIONNAIRE_ID and VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
            update stage_questionnaire set VALIDATION_STATUS = 'ERROR', MIGRATED_QUESTIONNAIRE_ID = -1, MIGRATED_QUESTIONNAIRE_NUMBER = -1 where questionnaire_id = LI_QUESTIONNAIRE_ID and VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
            update stage_quest_answer_header set VALIDATION_STATUS = 'ERROR', MIGRATION_QUEST_ANSWER_HEADER_ID = -1 where questionnaire_id = LI_QUESTIONNAIRE_ID and QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
            update stage_quest_answer set MIGRATION_QUEST_ANSWER_ID = -1, validation_status = 'ERROR' where QUESTIONNAIRE_COMPLETION_ID in (select QUESTIONNAIRE_COMPLETION_ID from stage_quest_answer_header where questionnaire_id = LI_QUESTIONNAIRE_ID and QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER);
		END IF;
END LOOP;
CLOSE CUR_QUEST;
set LI_MIGRATED_QUESTIONNAIRE_ID = NULL;
set LI_QUESTIONNAIRE_ID = NULL;
set LI_QUESTIONNAIRE_VERSION_NUMBER = NULL;
INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE, MODULE_NAME, BATCH_ID, MESSAGE, EXECUTION_TIME, PARENT_NUMBER) VALUES ('MIGRATION', 'QUEST_QUESTION', LI_BATCH_ID, 'Exit cursor', UTC_TIMESTAMP(), NULL);
INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE, EXECUTION_TIME) VALUES (CONCAT('Migrated total records ( ', LI_TOTAL_DATA_COUNT, ' ) of Questionnaire'), UTC_TIMESTAMP()), ('Migration completed successfully', UTC_TIMESTAMP() );
		update quest_column_nextvalue set
		QUESTION_OPTION_ID = (select IFNULL(MAX(QUESTION_OPTION_ID),0)+1 from quest_question_option )
		, QUESTION_CONDITION_ID = (select IFNULL(MAX(QUESTION_CONDITION_ID),0)+1 from quest_question_condition )
		, QUESTION_ID = (select IFNULL(MAX(QUESTION_ID),0)+1 from quest_question )
		, QUESTION_NUMBER = (select IFNULL(MAX(QUESTION_NUMBER),0)+1 from quest_question );
END;
SET SQL_SAFE_UPDATES = 1;
END
$$
DELIMITER ;
