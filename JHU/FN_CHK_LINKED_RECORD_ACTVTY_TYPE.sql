CREATE  FUNCTION `FN_CHK_LINKED_RECORD_ACTVTY_TYPE`(
AV_SR_HEADER_ID INT,
AV_TYPE VARCHAR(10)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_FLAG INT;
DECLARE  LI_MODULE_CODE INT DEFAULT 0;
DECLARE  LI_MODULE_ITEM_ID INT DEFAULT 0;
BEGIN
		DECLARE CONTINUE HANDLER FOR NOT FOUND
			SET LI_MODULE_ITEM_ID = 0;
      SELECT  MODULE_CODE,
                        MODULE_ITEM_ID
                        INTO
                        LI_MODULE_CODE,
                        LI_MODULE_ITEM_ID
                        FROM assoc_sr
                        WHERE SR_HEADER_ID = AV_SR_HEADER_ID ORDER BY UPDATE_TIMESTAMP ASC LIMIT 1;
END;
		IF LI_MODULE_ITEM_ID IS NULL OR LI_MODULE_ITEM_ID = 0 THEN
           RETURN 'FALSE';
	    END IF;
    IF LI_MODULE_CODE = 3 THEN
		SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROPOSAL
		WHERE PROPOSAL_ID = LI_MODULE_ITEM_ID
		AND ACTIVITY_TYPE_CODE = AV_TYPE;
    ELSEIF LI_MODULE_CODE = 1 THEN
        SELECT COUNT(1) INTO LI_FLAG FROM AWARD
		WHERE AWARD_ID = LI_MODULE_ITEM_ID
		AND ACTIVITY_TYPE_CODE = AV_TYPE;
    ELSEIF LI_MODULE_CODE = 2 THEN
        SELECT COUNT(1) INTO LI_FLAG FROM PROPOSAL
		WHERE PROPOSAL_ID = LI_MODULE_ITEM_ID
		AND ACTIVITY_TYPE_CODE = AV_TYPE;
	END IF;
	IF LI_FLAG > 0 THEN
		RETURN 'TRUE';
	ELSE
		RETURN 'FALSE';
	END IF;
END
$$
DELIMITER ;
