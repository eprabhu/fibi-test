CREATE DEFINER=`jhufibi`@`%` FUNCTION `fn_sr_person_cert_not_completed`(
  AV_SR_HEADER_ID   INT
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
  DECLARE LI_COUNT INT DEFAULT 0;
  DECLARE YES_ANSWER VARCHAR(1) DEFAULT 'Y';
  DECLARE SINGLE_ANS VARCHAR(1) DEFAULT 'Y';
  DECLARE RETURN_STRING VARCHAR(6) DEFAULT 'FALSE';
  -- Optional handler for safety
  DECLARE CONTINUE HANDLER FOR NOT FOUND
    SET SINGLE_ANS = YES_ANSWER;
  -- Count how many distinct values exist
  SELECT COUNT(DISTINCT IS_PERSON_CERTIFIED)
  INTO LI_COUNT
  FROM SR_PERSONS
  WHERE SR_HEADER_ID = AV_SR_HEADER_ID
    AND ACTION_FLAG != 'IMPORTED_DELETED' AND ROLODEX_ID IS NULL ;
  IF LI_COUNT > 1 THEN
    SET RETURN_STRING = 'TRUE';
  ELSEIF LI_COUNT = 1 THEN
    SELECT DISTINCT IS_PERSON_CERTIFIED
    INTO SINGLE_ANS
    FROM SR_PERSONS
    WHERE SR_HEADER_ID = AV_SR_HEADER_ID
      AND ACTION_FLAG != 'IMPORTED_DELETED' AND ROLODEX_ID IS NULL
    LIMIT 1;
    IF SINGLE_ANS != YES_ANSWER THEN
      SET RETURN_STRING = 'TRUE';
    END IF;
  END IF;
  RETURN RETURN_STRING;
END
$$
DELIMITER ;
