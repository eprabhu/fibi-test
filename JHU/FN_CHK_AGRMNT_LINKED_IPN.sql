CREATE  FUNCTION `FN_CHK_AGRMNT_LINKED_IPN`(AV_AGREEMENT_ID INT) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_ANSWER VARCHAR(4);
DECLARE LI_COUNT INT;
 SELECT qa.ANSWER INTO LS_ANSWER FROM quest_answer_header qh inner join quest_answer qa
 on qh.QUESTIONNAIRE_ANS_HEADER_ID = qa.QUESTIONNAIRE_ANS_HEADER_ID
 inner join triage_header t on  t.TRIAGE_HEADER_ID = qh.MODULE_ITEM_KEY
 where qh.QUESTIONNAIRE_ID = 41 and qh.MODULE_SUB_ITEM_CODE = 999
 and qh.MODULE_ITEM_CODE = 13 and  t.MODULE_CODE = 13 and t.MODULE_ITEM_KEY = AV_AGREEMENT_ID
 and qa.QUESTION_ID = 256  ;
IF UPPER(TRIM(LS_ANSWER)) = UPPER(TRIM('No')) THEN
	 SELECT COUNT(1) INTO LI_COUNT FROM assoc_agreement WHERE AGREEMENT_ID = AV_AGREEMENT_ID
    AND MODULE_CODE = 2;
    IF LI_COUNT = 0 THEN
		RETURN 'TRUE';
	 ELSE
        RETURN 'FALSE';
	 END IF;
END IF;
RETURN 'FALSE';
END
$$
DELIMITER ;
