DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `CLAIM_REMINDER_NOTIFICATION_EXTERNAL`( AV_DAYS INT )
BEGIN
select 0 AS SUB_MODULE_ITEM_KEY, t1.AWARD_ID AS MODULE_ITEM_KEY, 1 AS MODULE_CODE,
0 AS SUB_MODULE_CODE
from claim t1
inner join award t2 on t1.AWARD_ID = t2.AWARD_ID
where t2.AWARD_SEQUENCE_STATUS = 'ACTIVE'
and date(DATE_ADD(t2.FINAL_EXPIRATION_DATE,INTERVAL AV_DAYS DAY)) = date(DATE_ADD(utc_timestamp(),INTERVAL 0 DAY))
and t1.CLAIM_ID = (select max(s1.CLAIM_ID) from claim s1 where s1.AWARD_NUMBER = t1.AWARD_NUMBER)
and t1.ACCOUNT_TYPE_CODE IN ('1','2','4','6','7')
and t1.CLAIM_STATUS_CODE <> 4;
END
$$
DELIMITER ;
