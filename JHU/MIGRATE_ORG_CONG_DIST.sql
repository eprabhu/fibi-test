CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_ORG_CONG_DIST`(DATA_PROPOSAL_NUMBER VARCHAR(8),DATA_SITE_NUMBER INT,DATA_ORGANIZATION_ID INT,FOR_AUDIT INT, OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROPOSAL_CONG_DISTRICT_ID INT;
DECLARE LI_EPS_PROP_ORGANIZATION_ID INT;
DECLARE LI_CONG_DISTRICT_CODE INT;
DECLARE LS_CONG_DISTRICT VARCHAR(50);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'CONGDISTRICT';
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_DEV_PROP_CONG_DIS_CURSOR CURSOR FOR
	SELECT      MIGRATION_CONG_DIST_ID,
				CONG_DISTRICT,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM  stage_eps_proposal_cong_district  WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SITE_NUMBER = DATA_SITE_NUMBER;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'CONGDISTRICT','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN  MIGRATION_DEV_PROP_CONG_DIS_CURSOR;
	MIGRATION_DEV_PROP_CONG_DIS_CURSOR_LOOP    :  LOOP
	FETCH MIGRATION_DEV_PROP_CONG_DIS_CURSOR      INTO      LI_RECORD_ID,
															LS_CONG_DISTRICT,
															LS_UPDATE_TIMESTAMP,
															LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_DEV_PROP_CONG_DIS_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SET LI_EPS_PROP_ORGANIZATION_ID = -1;
	SET LI_CONG_DISTRICT_CODE = -1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','CONGDISTRICT',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(*) INTO LI_COUNT FROM congressional_district WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_CONG_DISTRICT)) AND IS_ACTIVE = 'Y';
	IF LI_COUNT = 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'CONGDISTRICT','MIGRATION',CONCAT('Invalid congressional district : ', LS_CONG_DISTRICT),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT CONG_DISTRICT_CODE INTO LI_CONG_DISTRICT_CODE FROM congressional_district WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_CONG_DISTRICT)) AND IS_ACTIVE = 'Y';
	END IF ;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','CONGDISTRICT',LI_BATCH_ID,'before insert',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_PROPOSAL_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROPOSAL_CONG_DISTRICT_ID),0) + 1 INTO LI_PROPOSAL_CONG_DISTRICT_ID
		FROM eps_proposal_cong_district;
		INSERT INTO   eps_proposal_cong_district
		(
			PROPOSAL_CONG_DISTRICT_ID,
			PROPOSAL_ORGANIZATION_ID,
			CONG_DISTRICT_CODE,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_PROPOSAL_CONG_DISTRICT_ID,
			DATA_ORGANIZATION_ID,
			LI_CONG_DISTRICT_CODE,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_eps_proposal_cong_district
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_PROPOSAL_CONG_DISTRICT_ID
		WHERE MIGRATION_CONG_DIST_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','CONGDISTRICT',LI_BATCH_ID,'success update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_PROPOSAL_NUMBER);
		END IF;
	ELSE
		UPDATE stage_eps_proposal_cong_district
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_CONG_DIST_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','CONGDISTRICT',LI_BATCH_ID,'error update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_PROPOSAL_NUMBER);
		END IF;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','CONGDISTRICT',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SITE_NUMBER);
	END IF;
	END LOOP MIGRATION_DEV_PROP_CONG_DIS_CURSOR_LOOP;
	CLOSE MIGRATION_DEV_PROP_CONG_DIS_CURSOR;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','CONGDISTRICT',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_PROPOSAL_NUMBER);
	END IF;
END;
	SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM  stage_eps_proposal_cong_district WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1 AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SITE_NUMBER = DATA_SITE_NUMBER;
	COMMIT;
END
$$
DELIMITER ;
