DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_EPS_PROP_ORG`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROP_ORGANIZATION_ID INT;
DECLARE LI_ORGANIZATION_TYPE_CODE INT;
DECLARE LI_SITE_NUMBER INT;
DECLARE LI_ROLODEX_ID INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_LOCATION_NAME VARCHAR(60);
DECLARE LS_ORGANIZATION_ID VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_ORG_TYPE_DESC VARCHAR(200);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_VALIDATION_STATUS VARCHAR(10);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LS_DELETED_DATA VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_validation_matrix WHERE MODULE_NAME IN ('EPSORGANIZATION','CONGDISTRICT');
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE IN ('EPSORGANIZATION','CONGDISTRICT') AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_eps_proposal_organization SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
				UPDATE stage_eps_proposal_cong_district SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_eps_proposal_organization WHERE VALIDATION_STATUS = 'VALID';
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'EPSORGANIZATION';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','EPSORGANIZATION',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','CONGDISTRICT',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_EPS_PROP_ORGANIZATION_CURSOR CURSOR FOR
	SELECT      MIGRATION_SITE_ID,
				PROPOSAL_NUMBER,
				SITE_NUMBER,
				LOCATION_NAME,
				ORGANIZATION_ID,
				ROLODEX_ID,
				ORG_TYPE_DESCRIPTION,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM stage_eps_proposal_organization  WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSORGANIZATION','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN    MIGRATION_EPS_PROP_ORGANIZATION_CURSOR;
	MIGRATION_EPS_PROP_ORGANIZATION_CURSOR_LOOP         : LOOP
	FETCH MIGRATION_EPS_PROP_ORGANIZATION_CURSOR          INTO      LI_RECORD_ID,
																	LS_PROPOSAL_NUMBER,
																	LI_SITE_NUMBER,
																	LS_LOCATION_NAME,
																	LS_ORGANIZATION_ID,
																	LI_ROLODEX_ID,
																	LS_ORG_TYPE_DESC,
																	LS_UPDATE_TIMESTAMP,
																	LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_EPS_PROP_ORGANIZATION_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SET LI_PROP_ORGANIZATION_ID = -1;
	SET LI_PROPOSAL_ID = -1;
	SET LI_ORGANIZATION_TYPE_CODE = -1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
	END IF;
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	CALL JHU_FETCH_DEV_PROPOSAL_ID(LS_PROPOSAL_NUMBER,@proposal_id);
	IF @proposal_id = -1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSORGANIZATION','MIGRATION',CONCAT('Invalid proposal number : ', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SET LI_PROPOSAL_ID = @proposal_id;
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	organization_type WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ORG_TYPE_DESC)) AND IS_ACTIVE = 'Y';
	IF LI_COUNT = 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSORGANIZATION','MIGRATION',IFNULL(CONCAT('Invalid organization type :', LS_ORG_TYPE_DESC), 'Organization type code ia mandatory and cannot be NULL' ),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT ORGANIZATION_TYPE_CODE INTO LI_ORGANIZATION_TYPE_CODE FROM organization_type WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ORG_TYPE_DESC)) AND IS_ACTIVE = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'before insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROPOSAL_ORGANIZATION_ID),0) + 1 INTO LI_PROP_ORGANIZATION_ID
		FROM eps_proposal_organization;
		INSERT INTO   eps_proposal_organization
		(
			PROPOSAL_ORGANIZATION_ID,
			PROPOSAL_ID,
			LOCATION,
			ROLODEX_ID,
			ORGANIZATION_TYPE_CODE,
			ORGANIZATION_ID,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LI_PROP_ORGANIZATION_ID,
			LI_PROPOSAL_ID,
			LS_LOCATION_NAME,
			CASE WHEN LS_ORGANIZATION_ID IS NOT NULL THEN NULL ELSE LI_ROLODEX_ID END,
			LI_ORGANIZATION_TYPE_CODE,
			LS_ORGANIZATION_ID,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER
		);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SET LS_VALIDATION_STATUS = 'SUCCESS';
		SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
		SET LS_CHILD_ERROR = 'N';
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_proposal_cong_district WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SITE_NUMBER = LI_SITE_NUMBER;
		IF LI_COUNT > 0 THEN
			CALL MIGRATE_ORG_CONG_DIST(LS_PROPOSAL_NUMBER,LI_SITE_NUMBER,LI_PROP_ORGANIZATION_ID,FOR_AUDIT,@cong_dist_error_count);
			IF @cong_dist_error_count > 0 THEN
				SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'CONGRESSIONAL DISTRICT');
				SET LS_CHILD_ERROR = 'Y';
			END IF;
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'child procedure call end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
		END IF;
		IF LS_CHILD_ERROR  = 'Y' THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSORGANIZATION','MIGRATION',CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_VALIDATION_STATUS  = 'ERROR';
			DELETE FROM eps_proposal_cong_district WHERE PROPOSAL_CONG_DISTRICT_ID IN (SELECT FIBI_IDENTIFIER FROM stage_eps_proposal_cong_district WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SITE_NUMBER = LI_SITE_NUMBER AND VALIDATION_STATUS = 'SUCCESS');
			UPDATE stage_eps_proposal_cong_district SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SITE_NUMBER = LI_SITE_NUMBER AND VALIDATION_STATUS = 'SUCCESS';
			DELETE FROM eps_proposal_organization WHERE PROPOSAL_ORGANIZATION_ID = LI_PROP_ORGANIZATION_ID;
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'error in child table and reverting the migration',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
			END IF;
		END IF;
		UPDATE stage_eps_proposal_organization
		SET VALIDATION_STATUS = LS_VALIDATION_STATUS,
		FIBI_IDENTIFIER = CASE WHEN LS_VALIDATION_STATUS = 'ERROR' THEN -1 ELSE LI_PROP_ORGANIZATION_ID END
		WHERE MIGRATION_SITE_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
		END IF;
	ELSE
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT MIGRATION_CONG_DIST_ID,'CONGDISTRICT','MIGRATION',CONCAT('Parent record failed for the proposal number : ',LS_PROPOSAL_NUMBER,' and the site number : ',LI_SITE_NUMBER),UTC_TIMESTAMP(),'quickstart' FROM stage_eps_proposal_cong_district WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SITE_NUMBER = LI_SITE_NUMBER;
		UPDATE stage_eps_proposal_cong_district SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SITE_NUMBER = LI_SITE_NUMBER;
		UPDATE stage_eps_proposal_organization
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_SITE_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
		END IF;
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed processing of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SITE_NUMBER);
	END IF;
	END LOOP MIGRATION_EPS_PROP_ORGANIZATION_CURSOR_LOOP;
	CLOSE MIGRATION_EPS_PROP_ORGANIZATION_CURSOR;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','EPSORGANIZATION',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL,NULL);
	END IF;
END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM seq_eps_proposal_organization;
	IF LI_COUNT = 0 THEN
	INSERT INTO seq_eps_proposal_organization (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROPOSAL_ORGANIZATION_ID),0) + 1  FROM eps_proposal_organization));
	ELSE
	UPDATE seq_eps_proposal_organization SET NEXT_VAL = (SELECT IFNULL(MAX(PROPOSAL_ORGANIZATION_ID),0) + 1  FROM eps_proposal_organization);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(*) INTO LI_COUNT FROM seq_eps_proposal_cong_district;
	IF LI_COUNT = 0 THEN
	INSERT INTO seq_eps_proposal_cong_district  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROPOSAL_CONG_DISTRICT_ID),0) + 1  FROM eps_proposal_cong_district));
	ELSE
	UPDATE seq_eps_proposal_cong_district  SET NEXT_VAL = (SELECT IFNULL(MAX(PROPOSAL_CONG_DISTRICT_ID),0) + 1  FROM eps_proposal_cong_district);
	END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	COMMIT;
END
$$
DELIMITER ;
