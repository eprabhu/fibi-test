CREATE  PROCEDURE `MIGRATE_IP_SUBMISSION_DATE`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LS_SUBMISSION_USER VARCHAR(8);
DECLARE LS_SUBMISSION_DATE DATETIME;
DECLARE LS_CREATE_TIMESTAMP DATETIME;
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_FIBI_IDENTIFIER INT;
DECLARE LI_COUNT INT;
DECLARE LI_MIN_SEQUENCE_NUMBER INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_VALIDATION_STATUS VARCHAR(10);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LS_DELETED_DATA VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Start Execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_IP_PROP_CURSOR CURSOR FOR
	SELECT      MIGRATION_PROPOSAL_ID ,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				CREATE_TIMESTAMP,
				UPDATE_USER,
				CREATE_TIMESTAMP,
				UPDATE_USER,
				FIBI_IDENTIFIER
	FROM stage_proposal WHERE VALIDATION_STATUS = 'SUCCESS' AND FIBI_IDENTIFIER <> -1;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'IPSUBMISSION','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_IP_PROP_CURSOR;
	MIGRATION_IP_PROP_CURSOR_LOOP : 	  LOOP
	FETCH  MIGRATION_IP_PROP_CURSOR       INTO    		LI_RECORD_ID,
														LS_PROPOSAL_NUMBER,
														LI_SEQUENCE_NUMBER,
														LS_CREATE_TIMESTAMP,
														LS_UPDATE_USER,
														LS_SUBMISSION_DATE,
														LS_SUBMISSION_USER,
														LI_FIBI_IDENTIFIER;
	IF DONE1 THEN
		LEAVE MIGRATION_IP_PROP_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SET LI_MIN_SEQUENCE_NUMBER = -1;
		SELECT IFNULL(MIN(SEQUENCE_NUMBER),0) INTO LI_MIN_SEQUENCE_NUMBER FROM stage_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		IF LI_MIN_SEQUENCE_NUMBER > 0 THEN
			SELECT CREATE_TIMESTAMP, UPDATE_USER INTO LS_SUBMISSION_DATE, LS_SUBMISSION_USER FROM stage_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MIN_SEQUENCE_NUMBER;
		END IF;
		SET LI_COUNT = 0;
		SELECT COUNT(1) INTO LI_COUNT FROM proposal WHERE PROPOSAL_ID = LI_FIBI_IDENTIFIER;
		IF LI_COUNT = 0 THEN
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
		IF LS_DATA_ERROR_FLAG = 'N' THEN
			UPDATE proposal SET SUBMISSION_DATE = LS_SUBMISSION_DATE,
			SUBMIT_USER = LS_SUBMISSION_USER
			WHERE PROPOSAL_ID = LI_FIBI_IDENTIFIER;
		END IF;
	END LOOP MIGRATION_IP_PROP_CURSOR_LOOP;
	CLOSE MIGRATION_IP_PROP_CURSOR;
END;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	COMMIT;
END
$$
DELIMITER ;
