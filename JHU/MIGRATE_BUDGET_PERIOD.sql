DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_BUDGET_PERIOD`(DATA_PROPOSAL_NUMBER VARCHAR(8), DATA_VERSION_NUMBER INT,DATA_BUDGET_HEADER_ID INT,FOR_AUDIT INT, OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_BUDGET_PERIOD_ID INT;
DECLARE LI_BUDGET_PERIOD INT;
DECLARE LI_VERSION_NUMBER INT;
DECLARE LI_BUDGET_HEADER_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_COMMENTS LONGTEXT;
DECLARE LS_END_DATE DATETIME;
DECLARE LS_START_DATE DATETIME;
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_TOTAL_COST DECIMAL(12, 2);
DECLARE LS_TOTAL_DIRECT_COST DECIMAL(12, 2);
DECLARE LS_TOTAL_INDIRECT_COST DECIMAL(12, 2);
DECLARE LS_COST_SHARING_AMOUNT DECIMAL(12, 2);
DECLARE LS_UNDERRECOVERY_AMOUNT DECIMAL(12, 2);
DECLARE LS_TOTAL_COST_LIMIT DECIMAL(12, 2);
DECLARE LS_TOTAL_DIRECT_COST_LIMIT DECIMAL(12, 2);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'BUDGETPERIOD';
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_BUDGET_PERIOD_CURSOR CURSOR FOR
	SELECT      MIGRATION_BUDGET_PERIOD_ID,
				PROPOSAL_NUMBER,
				VERSION_NUMBER,
				BUDGET_PERIOD,
				START_DATE,
				END_DATE,
				TOTAL_COST,
				TOTAL_DIRECT_COST,
				TOTAL_INDIRECT_COST,
				COST_SHARING_AMOUNT,
				UNDERRECOVERY_AMOUNT,
				TOTAL_COST_LIMIT,
				COMMENTS,
				TOTAL_DIRECT_COST_LIMIT,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM  stage_budget_periods  WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND VERSION_NUMBER = DATA_VERSION_NUMBER;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGETPERIOD','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_BUDGET_PERIOD_CURSOR;
	MIGRATION_BUDGET_PERIOD_CURSOR_LOOP         : LOOP
	FETCH MIGRATION_BUDGET_PERIOD_CURSOR       	  INTO       	LI_RECORD_ID,
																LS_PROPOSAL_NUMBER,
																LI_VERSION_NUMBER,
																LI_BUDGET_PERIOD,
																LS_START_DATE,
																LS_END_DATE,
																LS_TOTAL_COST,
																LS_TOTAL_DIRECT_COST,
																LS_TOTAL_INDIRECT_COST,
																LS_COST_SHARING_AMOUNT,
																LS_UNDERRECOVERY_AMOUNT,
																LS_TOTAL_COST_LIMIT,
																LS_COMMENTS,
																LS_TOTAL_DIRECT_COST_LIMIT,
																LS_UPDATE_TIMESTAMP,
																LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_BUDGET_PERIOD_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','BUDGETPERIOD',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	SET LI_BUDGET_PERIOD_ID = -1;
	SET LI_COUNT = -1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','BUDGETPERIOD',LI_BATCH_ID,'before insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(BUDGET_PERIOD_ID),0) + 1 INTO LI_BUDGET_PERIOD_ID
		FROM budget_period;
		INSERT INTO  budget_period
		(
			BUDGET_PERIOD_ID,
			BUDGET_PERIOD,
			END_DATE,
			IS_OBLIGATED_PERIOD,
			MODULE_ITEM_CODE,
			MODULE_ITEM_KEY,
			PERIOD_LABEL,
			START_DATE,
			TOTAL_COST,
			TOTAL_DIRECT_COST,
			TOTAL_INDIRECT_COST,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			VERSION_NUMBER,
			BUDGET_HEADER_ID,
			SUBCONTRACT_COST,
			COST_SHARING_AMOUNT,
			UNDERRECOVERY_AMOUNT,
			TOTAL_COST_LIMIT,
			COMMENTS,
			TOTAL_DIRECT_COST_LIMIT
		)
		VALUES
		(
			LI_BUDGET_PERIOD_ID,
			LI_BUDGET_PERIOD,
			LS_END_DATE,
			NULL,
			NULL,
			NULL,
			NULL,
			LS_START_DATE,
			LS_TOTAL_COST,
			LS_TOTAL_DIRECT_COST,
			LS_TOTAL_INDIRECT_COST,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER,
			LI_VERSION_NUMBER,
			DATA_BUDGET_HEADER_ID,
			NULL,
			LS_COST_SHARING_AMOUNT,
			LS_UNDERRECOVERY_AMOUNT,
			LS_TOTAL_COST_LIMIT,
			LS_COMMENTS,
			LS_TOTAL_DIRECT_COST_LIMIT
		);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_budget_periods
		SET VALIDATION_STATUS = 'SUCCESS',
		FIBI_IDENTIFIER = LI_BUDGET_PERIOD_ID
		WHERE MIGRATION_BUDGET_PERIOD_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','BUDGETPERIOD',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	ELSE
		UPDATE stage_budget_periods
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_BUDGET_PERIOD_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','BUDGETPERIOD',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','BUDGETPERIOD',LI_BATCH_ID,'migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	END LOOP MIGRATION_BUDGET_PERIOD_CURSOR_LOOP;
	CLOSE MIGRATION_BUDGET_PERIOD_CURSOR;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','BUDGETPERIOD',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL,NULL);
	END IF;
END;
	SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM  stage_budget_periods WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1 AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND VERSION_NUMBER = DATA_VERSION_NUMBER;
	COMMIT;
END
$$
DELIMITER ;
