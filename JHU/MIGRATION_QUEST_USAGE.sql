DELIMITER $$
CREATE  PROCEDURE `MIGRATION_QUEST_USAGE`(AW_QUESTIONNAIRE_ID INT, AW_QUESTIONNAIRE_VERSION_NUMBER INT, AW_MIGRATED_QUESTIONNAIRE_ID INT, DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUESTIONNAIRE_ID INT;
DECLARE LI_QUESTIONNAIRE_ID INT;
DECLARE LI_QUESTIONNAIRE_VERSION_NUMBER INT;
DECLARE LI_MIGRATED_QUESTIONNAIRE_ID INT;
DECLARE LI_MIGRATED_QUESTIONNAIRE_USAGE_ID INT;
DECLARE LI_STG_QUEST_USAGE_ID INT;
DECLARE LI_MODULE_ITEM_CODE SMALLINT;
DECLARE LI_MODULE_SUB_ITEM_CODE SMALLINT;
DECLARE LS_QUESTIONNAIRE_LABEL varchar(50);
DECLARE LS_IS_MANDATORY varchar(1);
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_VALIDATION_STATUS varchar(10);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
DECLARE LS_UPDATE_USER VARCHAR(60);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (IFNULL(LI_STG_QUEST_USAGE_ID,0),'QUEST_USAGE','MIGRATION',LS_ERROR_MSG,UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_USAGE') AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_quest_usage SET VALIDATION_STATUS = 'VALID' , MIGRATED_QUESTIONNAIRE_USAGE_ID = NULL WHERE VALIDATION_STATUS = 'ERROR' AND MIGRATED_QUESTIONNAIRE_USAGE_ID = -1;
	END IF;
END;
BEGIN
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'QUEST_USAGE';
	INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution : QUEST_USAGE ',UTC_TIMESTAMP());
END;
		BEGIN
		DECLARE DONEUSAGE INT DEFAULT FALSE;
		DECLARE CUR_QUEST_USAGE CURSOR FOR
		select ID
				, QUESTIONNAIRE_ID
				, VERSION_NUMBER
				, MODULE_ITEM_CODE
				, MODULE_SUB_ITEM_CODE
				, QUESTIONNAIRE_LABEL
				, IS_MANDATORY
                , UPDATE_USER
                , UPDATE_TIMESTAMP
		from stage_quest_usage
		where QUESTIONNAIRE_ID = AW_QUESTIONNAIRE_ID
		and VERSION_NUMBER = AW_QUESTIONNAIRE_VERSION_NUMBER
        and validation_status = 'VALID';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONEUSAGE = TRUE;
		OPEN CUR_QUEST_USAGE;
		QUEST_USAGE_LOOP: LOOP
		FETCH CUR_QUEST_USAGE INTO LI_STG_QUEST_USAGE_ID
									, LI_QUESTIONNAIRE_ID
									, LI_QUESTIONNAIRE_VERSION_NUMBER
									, LI_MODULE_ITEM_CODE
									, LI_MODULE_SUB_ITEM_CODE
									, LS_QUESTIONNAIRE_LABEL
									, LS_IS_MANDATORY
									, LS_UPDATE_USER
									, LS_UPDATE_TIMESTAMP;
		IF DONEUSAGE THEN
			LEAVE QUEST_USAGE_LOOP;
		END IF;
				SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT
				FROM stage_quest_usage
				where QUESTIONNAIRE_ID = AW_QUESTIONNAIRE_ID
				and VERSION_NUMBER = AW_QUESTIONNAIRE_VERSION_NUMBER;
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('MIGRATION','QUEST_USAGE',LI_BATCH_ID,'Migration started',UTC_TIMESTAMP(),LI_QUESTIONNAIRE_ID);
								select IFNULL(MAX(QUESTIONNAIRE_USAGE_ID),0)+1 INTO LI_MIGRATED_QUESTIONNAIRE_USAGE_ID from quest_usage ;
								INSERT INTO quest_usage(
												 QUESTIONNAIRE_USAGE_ID
												,MODULE_ITEM_CODE
												,MODULE_SUB_ITEM_CODE
												,QUESTIONNAIRE_ID
												,QUESTIONNAIRE_LABEL
												,IS_MANDATORY
												,RULE_ID
												,UPDATE_TIMESTAMP
												,UPDATE_USER
												,SORT_ORDER
												,TRIGGER_POST_EVALUATION
										)VALUES(
												LI_MIGRATED_QUESTIONNAIRE_USAGE_ID
												, LI_MODULE_ITEM_CODE
												, CASE LI_MODULE_SUB_ITEM_CODE WHEN 6 THEN 3 ELSE LI_MODULE_SUB_ITEM_CODE END
												,AW_MIGRATED_QUESTIONNAIRE_ID
												,LS_QUESTIONNAIRE_LABEL
												,LS_IS_MANDATORY
												,NULL
												,date(LS_UPDATE_TIMESTAMP)
												,LS_UPDATE_USER
												,NULL
												,NULL
											);
						 UPDATE stage_quest_usage SET VALIDATION_STATUS = 'SUCCESS', MIGRATED_QUESTIONNAIRE_USAGE_ID = LI_MIGRATED_QUESTIONNAIRE_USAGE_ID where ID =  LI_STG_QUEST_USAGE_ID;
				IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Migrated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Questionnaire Usage'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('MIGRATION','QUEST_USAGE',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LI_QUESTIONNAIRE_ID);
					set LI_COUNT = NULL;
					set LI_MIGRATED_QUESTIONNAIRE_USAGE_ID = NULL;
					set LI_MIGRATED_QUESTIONNAIRE_ID = NULL;
					set LI_MODULE_ITEM_CODE = NULL;
					set LI_MODULE_SUB_ITEM_CODE = NULL;
					set LI_QUESTIONNAIRE_ID = NULL;
					set LI_QUESTIONNAIRE_VERSION_NUMBER = NULL;
					set LS_QUESTIONNAIRE_LABEL = NULL;
					set LS_IS_MANDATORY = NULL;
		END LOOP;
		CLOSE CUR_QUEST_USAGE;
		INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_USAGE',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),NULL);
			INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Migrated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Questionnaire usage'),UTC_TIMESTAMP()),('Migration completed successfully',UTC_TIMESTAMP());
	END;
END
$$
DELIMITER ;
