DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_AWARD_CUSTDATA_PREVAL`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LS_JHU_AWARD_NUMBER CHAR(10);
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LS_COLUMN_NAME VARCHAR(30);
DECLARE LS_COLUMN_VALUE VARCHAR(2000);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'AWRDCUSTOM' AND ERROR_TYPE = 'VALIDATION';
			UPDATE stage_award_custom_data SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'AWRDCUSTOM';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'VALIDATION','AWRDCUSTOM',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE  MIGRATE_AWARD_CUSTOM CURSOR FOR
	SELECT 		MIGRATION_AWARD_CUSTOM_DATA_ID,
				MIT_AWARD_NUMBER,
				SEQUENCE_NUMBER,
				COLUMN_NAME,
				COLUMN_VALUE
	FROM 	stage_award_custom_data  WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'AWRDCUSTOM','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATE_AWARD_CUSTOM;
	MIGRATE_AWARD_CUSTOM_LOOP		:		LOOP
	FETCH MIGRATE_AWARD_CUSTOM				INTO		LI_RECORD_ID,
														LS_JHU_AWARD_NUMBER,
														LI_SEQUENCE_NUMBER,
														LS_COLUMN_NAME,
														LS_COLUMN_VALUE;
	IF DONE1 THEN
		LEAVE MIGRATE_AWARD_CUSTOM_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	SET LS_AWARD_NUMBER = REPLACE(LS_JHU_AWARD_NUMBER,'-','-00');
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,CONCAT('Changed award number',LS_AWARD_NUMBER),UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER;
	IF LI_COUNT = 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'AWRDCUSTOM','VALIDATION',CONCAT('Invalid award number : ', LS_AWARD_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'after award check',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	END IF;
	IF LENGTH(LS_COLUMN_VALUE) > 4000 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'AWRDCUSTOM','VALIDATION',CONCAT('The length is more than the source data type size'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'after column value check',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM custom_data_elements WHERE UPPER(CUSTOM_ELEMENT_NAME) = UPPER(LS_COLUMN_NAME);
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'AWRDCUSTOM','VALIDATION',CONCAT('Invalid custom element :', LS_COLUMN_NAME),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'after custom data elements check',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'Before update',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	END IF;
		IF LS_DATA_ERROR_FLAG = 'N' THEN
			UPDATE stage_award_custom_data SET VALIDATION_STATUS = 'VALID', FIBI_IDENTIFIER = NULL WHERE MIGRATION_AWARD_CUSTOM_DATA_ID = LI_RECORD_ID;
		ELSE
			UPDATE stage_award_custom_data SET VALIDATION_STATUS = 'ERROR', FIBI_IDENTIFIER = NULL WHERE MIGRATION_AWARD_CUSTOM_DATA_ID = LI_RECORD_ID;
		END IF;
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'validation end',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
	END LOOP MIGRATE_AWARD_CUSTOM_LOOP;
	CLOSE MIGRATE_AWARD_CUSTOM;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','AWRDCUSTOM',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
END;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	SELECT 1 AS RESULT;
	COMMIT;
END
$$
DELIMITER ;
