DELIMITER $$
CREATE  PROCEDURE `MIGRATE_EPS_PROPOSAL_PREVAL`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ACTIVITY_TYPE_CODE INT;
DECLARE LI_STATUS_CODE INT;
DECLARE LI_TYPE_CODE INT;
DECLARE LS_AWARD_TYPE_CODE INT;
DECLARE LI_PI_COUNT INT;
DECLARE LI_GRANT_TYPE_CODE INT;
DECLARE LS_PROPOSAL_CREATE_USER VARCHAR(8);
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_CHK_START_DATE DATETIME;
DECLARE LS_CHK_END_DATE DATETIME;
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_SPONSOR_CODE VARCHAR(6);
DECLARE LS_TITLE VARCHAR(250);
DECLARE LS_PRIME_SPONSOR_CODE VARCHAR(6);
DECLARE LS_GRANT_CALL_TYPE VARCHAR(10);
DECLARE LS_PROPOSAL_STATUS VARCHAR(200);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE IN ('DEVPROPOSAL','EPSKEYINVEST','EPSKEYPERSON','DEVPROPUNITS','DEVPROPKPUNITS') AND ERROR_TYPE = 'VALIDATION';
			ALTER TABLE migration_transaction_errorlog AUTO_INCREMENT = 1;
			UPDATE stage_eps_proposal SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
			UPDATE stage_eps_prop_investigators SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
			UPDATE stage_eps_prop_key_persons SET VALIDATION_STATUS = NULL, FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
			UPDATE stage_eps_prop_units SET VALIDATION_STATUS = NULL, FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
			UPDATE stage_eps_prop_kp_units SET VALIDATION_STATUS = NULL, FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_eps_proposal;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'DEVPROPOSAL';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'VALIDATION','DEVPROPOSAL',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','DEVPROPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','DEVPROPKPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','EPSKEYINVEST',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','EPSKEYPERSON',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_DEV_PROPOSAL_CURSOR CURSOR FOR
		SELECT  MIGRATION_PROP_ID,
				PROPOSAL_NUMBER,
				PROPOSAL_TYPE_CODE,
				CREATION_STATUS_CODE,
				TITLE,
				SPONSOR_CODE,
				ACTIVITY_TYPE_CODE,
				REQUESTED_END_DATE_INITIAL,
				CREATE_USER,
				OWNED_BY_UNIT,
				REQUESTED_START_DATE_INITIAL,
				AWARD_TYPE_CODE,
				PRIME_SPONSOR_CODE,
				NOTICE_OF_OPPORTUNITY_CODE,
				DESCRIPTION
		FROM 	stage_eps_proposal
		WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_DEV_PROPOSAL_CURSOR;
			 MIGRATION_DEV_PROPOSAL_CURSOR_LOOP :   LOOP
				FETCH MIGRATION_DEV_PROPOSAL_CURSOR INTO     	LI_RECORD_ID,
																LS_PROPOSAL_NUMBER,
																LI_TYPE_CODE,
																LI_STATUS_CODE,
																LS_TITLE,
																LS_SPONSOR_CODE,
																LI_ACTIVITY_TYPE_CODE,
																LS_CHK_END_DATE,
																LS_PROPOSAL_CREATE_USER,
																LS_UNIT_NUMBER,
																LS_CHK_START_DATE,
																LS_AWARD_TYPE_CODE,
																LS_PRIME_SPONSOR_CODE,
																LI_GRANT_TYPE_CODE,
																LS_PROPOSAL_STATUS;
					IF DONE1 THEN
						LEAVE MIGRATION_DEV_PROPOSAL_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					SET LI_COUNT = -1;
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					SELECT COUNT(LS_PROPOSAL_NUMBER)  INTO LI_COUNT FROM DUAL  WHERE LS_PROPOSAL_NUMBER REGEXP '[^0-9]';
					IF LI_COUNT = 1  THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('The proposal number cannot be converted to integer :', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after int conversion',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM eps_proposal WHERE PROPOSAL_ID = LS_PROPOSAL_NUMBER;
					IF LI_COUNT <> 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Duplicate entry for the proposal number :', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after duplicate check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					eps_proposal_type WHERE TYPE_CODE = LI_TYPE_CODE AND IS_ACTIVE = 'Y';
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid type code :', LI_TYPE_CODE),'Proposal type is manadatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after proposal type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					eps_proposal_status WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROPOSAL_STATUS)) AND IS_ACTIVE = 'Y';
					IF LI_COUNT <> 1 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid status  :', LS_PROPOSAL_STATUS),'Proposal status is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after proposal status check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LI_GRANT_TYPE_CODE IS NOT NULL THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						grant_call_type WHERE GRANT_TYPE_CODE = LI_GRANT_TYPE_CODE AND IS_ACTIVE = 'Y';
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid grant type code : ',LI_GRANT_TYPE_CODE),'Grant type code is mandatory'),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after grant type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_TITLE IS NULL THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION','Proposal title is mandatory and cannot be NULL',UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after title check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_SPONSOR_CODE IS NOT NULL AND LS_SPONSOR_CODE <> '' THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						sponsor WHERE SPONSOR_CODE = LS_SPONSOR_CODE;
						IF LI_COUNT = 0  THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Invalid sponsor code :  ', LS_SPONSOR_CODE) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after sponsor check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_CHK_START_DATE IS NULL THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION','Start date is mandatory',UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after start date check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_CHK_END_DATE IS NULL THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION','End date is mandatory',UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after end date check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_CHK_END_DATE IS NOT NULL AND LS_CHK_START_DATE IS NOT NULL AND LS_CHK_END_DATE < LS_CHK_START_DATE  THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION','End date cannot be less than that of start date',UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after greater than check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND IS_ACTIVE = 'Y';
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid unit number :  ', LS_UNIT_NUMBER),'Lead unit is mandatory and cannot be NULL') ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after unit check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					activity_type WHERE ACTIVITY_TYPE_CODE = LI_ACTIVITY_TYPE_CODE AND IS_ACTIVE = 'Y';
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid activity code :', LI_ACTIVITY_TYPE_CODE),'Activity type is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after activity type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_PRIME_SPONSOR_CODE IS NOT NULL AND LS_PRIME_SPONSOR_CODE <> '' THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						sponsor WHERE SPONSOR_CODE = LS_PRIME_SPONSOR_CODE;
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Invalid prime sponsor code :  ', LS_PRIME_SPONSOR_CODE) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after prime sponsor check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_AWARD_TYPE_CODE IS NOT NULL THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						award_type  WHERE AWARD_TYPE_CODE = LS_AWARD_TYPE_CODE AND IS_ACTIVE = 'Y';
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Invalid award type code :  ', LS_AWARD_TYPE_CODE) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after award type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_PI_COUNT = -1;
					SELECT COUNT(1) INTO LI_PI_COUNT FROM
					stage_eps_prop_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND PRINCIPAL_INVESTIGATOR_FLAG = 'Y';
					IF LI_PI_COUNT <>  1 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Only one PI should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after PI check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					stage_eps_prop_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND LEAD_UNIT_FLAG = 'Y';
					IF LI_COUNT <> 1 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Only one lead unit should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after lead unit check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
					SET LS_CHILD_ERROR = 'N';
					 SET LI_COUNT = -1;
					 SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
					 IF LI_COUNT > 0 THEN
						CALL MIGRATE_EPS_PROP_INV_PREVAL(LS_PROPOSAL_NUMBER,FOR_AUDIT, @inv_data_error_count);
						IF @inv_data_error_count > 0 THEN
							SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE ,'INVESTIGATORS, ');
							SET LS_CHILD_ERROR = 'Y';
						END IF;
					 END IF;
					 IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after inv call end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					 SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_key_persons WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
					IF LI_COUNT > 0 THEN
						CALL MIGRATE_EPS_PROP_KP_PREVAL(LS_PROPOSAL_NUMBER,FOR_AUDIT, @kp_data_error_count);
						IF @kp_data_error_count > 0 THEN
							SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE, 'KEY PERSONS ');
							SET LS_CHILD_ERROR = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after key person call end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
					END IF;
					IF LS_CHILD_ERROR = 'Y' THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',CONCAT('Error in the ',LS_CHILD_ERROR_MESSAGE, ' for the proposal number : ', LS_PROPOSAL_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						UPDATE stage_eps_proposal
						SET VALIDATION_STATUS = 'VALID',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROP_ID = LI_RECORD_ID;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after valid update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
						END IF;
					ELSE
						UPDATE stage_eps_proposal
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROP_ID = LI_RECORD_ID;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
						END IF;
					END IF;
				IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed validation of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'Validation end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
			END LOOP MIGRATION_DEV_PROPOSAL_CURSOR_LOOP;
			CLOSE MIGRATION_DEV_PROPOSAL_CURSOR;
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','DEVPROPOSAL',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),NULL);
		END;
		INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
		SET SQL_SAFE_UPDATES = 1;
		SET FOREIGN_KEY_CHECKS = 1;
		SELECT 1 AS RESULT;
		COMMIT;
END
$$
DELIMITER ;
