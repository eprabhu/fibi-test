DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_IP_KP_UNITS_PREVAL`(DATA_PROPOSAL_NUMBER VARCHAR(8),DATA_SEQUENCE_NUMBER INT,DATA_PERSON_ID VARCHAR(10),FOR_AUDIT INT,OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(9);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'INSTPROPKPUNITS';
END;
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_INST_PROP_UNITS_CURSOR CURSOR FOR
		SELECT  MIGRATION_PROP_KP_UNITS_ID,
				UNIT_NUMBER
		FROM stage_proposal_key_person_units WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = DATA_SEQUENCE_NUMBER AND PERSON_ID = DATA_PERSON_ID;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'INSTPROPKPUNITS','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_INST_PROP_UNITS_CURSOR;
			MIGRATION_INST_PROP_UNITS_CURSOR_LOOP :    LOOP
				FETCH MIGRATION_INST_PROP_UNITS_CURSOR INTO     		LI_RECORD_ID,
																		LS_UNIT_NUMBER;
					IF DONE1 THEN
						LEAVE MIGRATION_INST_PROP_UNITS_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','INSTPROPKPUNITS',LI_BATCH_ID,'validation start',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND IS_ACTIVE = 'Y';
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'INSTPROPKPUNITS','VALIDATION',IFNULL(CONCAT('Invalid unit number :  ', LS_UNIT_NUMBER),'Lead unit is mandatory and cannot be NULL') ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','INSTPROPKPUNITS',LI_BATCH_ID,'after unit check',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
					END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						UPDATE stage_proposal_key_person_units
						SET VALIDATION_STATUS = 'VALID',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROP_KP_UNITS_ID = LI_RECORD_ID;
					ELSE
						UPDATE stage_proposal_key_person_units
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROP_KP_UNITS_ID = LI_RECORD_ID;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','INSTPROPKPUNITS',LI_BATCH_ID,'after update',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','INSTPROPKPUNITS',LI_BATCH_ID,'validation end',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
					END IF;
			END LOOP MIGRATION_INST_PROP_UNITS_CURSOR_LOOP;
			CLOSE MIGRATION_INST_PROP_UNITS_CURSOR;
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','INSTPROPKPUNITS',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER,DATA_SEQUENCE_NUMBER);
			END IF;
		END;
		SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM stage_proposal_key_person_units WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = DATA_SEQUENCE_NUMBER AND PERSON_ID = DATA_PERSON_ID;
		COMMIT;
END
$$
DELIMITER ;
