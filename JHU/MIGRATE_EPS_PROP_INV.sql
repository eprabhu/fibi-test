DELIMITER $$
CREATE  PROCEDURE `MIGRATE_EPS_PROP_INV`(DATA_PROPOSAL_NUMBER VARCHAR(8),DATA_PROPOSAL_ID INT,FOR_AUDIT INT,OUT DATA_ERROR_COUNT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROPOSAL_PERSON_ID INT;
DECLARE LI_PROP_PERSON_ROLE_ID INT;
DECLARE LI_PROP_PERSON_PI_ROLE_ID INT;
DECLARE LI_PROP_PERSON_COI_ROLE_ID INT;
DECLARE LI_PROP_PERSON_KP_ROLE_ID INT;
DECLARE LS_DEPARTMENT VARCHAR(90);
DECLARE LS_FULL_NAME VARCHAR(90);
DECLARE LS_UNIT_NAME VARCHAR(100);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_PERSON_ID VARCHAR(8);
DECLARE LS_ROLODEX_ID VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(60);
DECLARE LS_EMAIL_ADDRESS VARCHAR(255);
DECLARE LS_PI_FLAG VARCHAR(1);
DECLARE LS_DESIGNATION VARCHAR(255);
DECLARE LS_MULTI_PI VARCHAR(255);
DECLARE LS_NON_MIT_FLAG VARCHAR(1);
DECLARE LS_PROJECT_ROLE VARCHAR(60);
DECLARE LS_SOURCE_TYPE VARCHAR(20);
DECLARE LS_PERSON_TYPE VARCHAR(20);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_PERCENTAGE_EFFORT DECIMAL(5, 2);
DECLARE LS_PERCENTAGE_OF_EFFORT DECIMAL(5,2);
DECLARE LS_ACADEMIC_YEAR_EFFORT DECIMAL(5,2);
DECLARE LS_CALENDAR_YEAR_EFFORT DECIMAL(5,2);
DECLARE LS_SUMMER_YEAR_EFFORT DECIMAL(5,2);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT1 INT;
DECLARE LI_SOURCE_COUNT2 INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_DELETED_DATA VARCHAR(1);
DECLARE LS_VALIDATION_STATUS VARCHAR(10);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SET LI_COUNT = -1;
	SET LS_DATA_ERROR_FLAG = 'N';
	SELECT COUNT(*) INTO LI_COUNT FROM eps_prop_person_role WHERE UPPER(DESCRIPTION) = UPPER('Principal Investigator') AND IS_ACTIVE = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'EPSKEYINVEST','MIGRATION',CONCAT('Invalid proposal role : Principal Investigator'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT PROP_PERSON_ROLE_ID INTO LI_PROP_PERSON_PI_ROLE_ID FROM eps_prop_person_role WHERE UPPER(DESCRIPTION) = UPPER('Principal Investigator') AND IS_ACTIVE = 'Y';
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(*) INTO LI_COUNT FROM eps_prop_person_role WHERE UPPER(DESCRIPTION) = UPPER('Co-Investigator') AND IS_ACTIVE = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'EPSKEYINVEST','MIGRATION',CONCAT('Invalid proposal role : Co-Investigator'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT PROP_PERSON_ROLE_ID INTO LI_PROP_PERSON_COI_ROLE_ID FROM eps_prop_person_role WHERE UPPER(DESCRIPTION) = UPPER('Co-Investigator') AND IS_ACTIVE = 'Y';
	END IF;
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'EPSKEYINVEST';
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
END;
IF LS_DATA_ERROR_FLAG = 'N' THEN
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_DEV_PROP_INV_CURSOR CURSOR FOR
		SELECT  MIGRATION_INVESTIGATORS_ID,
				PERSON_ID,
				NON_MIT_PERSON_FLAG,
				PERSON_NAME,
				PERCENTAGE_EFFORT,
				ACADEMIC_YEAR_EFFORT,
				SUMMER_YEAR_EFFORT,
				CALENDAR_YEAR_EFFORT,
				PRINCIPAL_INVESTIGATOR_FLAG,
				MULTI_PI_FLAG,
				NULL AS PROJECT_ROLE,
				UPDATE_TIMESTAMP,
				UPDATE_USER
		FROM  stage_eps_prop_investigators 	WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSKEYINVEST','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_DEV_PROP_INV_CURSOR;
	MIGRATION_DEV_PROP_INV_CURSOR_LOOP :           		LOOP
	FETCH MIGRATION_DEV_PROP_INV_CURSOR            		INTO        LI_RECORD_ID,
																	LS_PERSON_ID,
																	LS_NON_MIT_FLAG,
																	LS_FULL_NAME,
																	LS_PERCENTAGE_EFFORT,
																	LS_ACADEMIC_YEAR_EFFORT,
																	LS_SUMMER_YEAR_EFFORT,
																	LS_CALENDAR_YEAR_EFFORT,
																	LS_PI_FLAG,
																	LS_MULTI_PI,
																	LS_PROJECT_ROLE,
																	LS_UPDATE_TIMESTAMP,
																	LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_DEV_PROP_INV_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LS_UNIT_NAME = NULL;
	SET LI_PROPOSAL_PERSON_ID = -1;
	SET LI_COUNT = -1;
	SET LS_UNIT_NUMBER = '0';
	SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_person WHERE
	PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
	IF LI_COUNT > 0 THEN
		SELECT DIRECTORY_DEPARTMENT,EMAIL_ADDRESS,PRIMARY_TITLE
		INTO LS_DEPARTMENT,LS_EMAIL_ADDRESS,LS_DESIGNATION FROM stage_eps_prop_person WHERE
		PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'fetch from osp$eps_prop_person',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
	END IF;
	IF LS_PI_FLAG = 'Y' THEN
		SET LI_PROP_PERSON_ROLE_ID = LI_PROP_PERSON_PI_ROLE_ID;
	ELSEIF LS_PI_FLAG = 'N' THEN
		SET LI_PROP_PERSON_ROLE_ID = LI_PROP_PERSON_COI_ROLE_ID;
	END IF;
	IF LS_PERCENTAGE_EFFORT IS NULL AND LS_ACADEMIC_YEAR_EFFORT IS NULL AND LS_CALENDAR_YEAR_EFFORT IS NULL AND LS_SUMMER_YEAR_EFFORT IS NULL THEN
		SET LS_PERCENTAGE_OF_EFFORT = NULL;
	ELSE
		SELECT GREATEST(IFNULL(LS_PERCENTAGE_EFFORT,0),IFNULL(LS_ACADEMIC_YEAR_EFFORT,0),IFNULL(LS_SUMMER_YEAR_EFFORT,0),IFNULL(LS_CALENDAR_YEAR_EFFORT,0)) INTO LS_PERCENTAGE_OF_EFFORT FROM DUAL;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'effort calculation',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
	END IF;
	IF LS_NON_MIT_FLAG = 'N' THEN
		SET LI_COUNT = -1;
		SELECT COUNT(*) INTO LI_COUNT FROM eps_proposal_persons WHERE PROPOSAL_ID = DATA_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
		IF LI_COUNT > 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSKEYINVEST','MIGRATION',CONCAT('Data already exist for the proposal number :  ',DATA_PROPOSAL_NUMBER, ' and the person id : ', LS_PERSON_ID),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
	ELSE
		SET LI_COUNT = -1;
		SELECT COUNT(*) INTO LI_COUNT FROM eps_proposal_persons WHERE PROPOSAL_ID = DATA_PROPOSAL_NUMBER AND ROLODEX_ID = LS_PERSON_ID;
		IF LI_COUNT > 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSKEYINVEST','MIGRATION',CONCAT('Data already exist for the proposal number :  ',DATA_PROPOSAL_NUMBER, ' and the rolodex id : ', LS_PERSON_ID),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'before insert',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROPOSAL_PERSON_ID),0) + 1 INTO LI_PROPOSAL_PERSON_ID
		FROM eps_proposal_persons;
		INSERT INTO  eps_proposal_persons
		(
			PROPOSAL_PERSON_ID,
			DEPARTMENT,
			FULL_NAME,
			UNIT_NAME,
			UNIT_NUMBER,
			PERSON_ID,
			PROP_PERSON_ROLE_ID,
			ROLODEX_ID,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			PROPOSAL_ID,
			PERCENTAGE_OF_EFFORT,
			EMAIL_ADDRESS,
			PI_FLAG,
			DESIGNATION,
			IS_MULTI_PI,
			PROJECT_ROLE,
			IS_TRAINING_COMPLETED
		)
		VALUES
		(
			LI_PROPOSAL_PERSON_ID,
			LS_DEPARTMENT,
			LS_FULL_NAME,
			NULL,
			NULL,
			CASE WHEN LS_NON_MIT_FLAG = 'N' THEN LS_PERSON_ID ELSE NULL END,
			LI_PROP_PERSON_ROLE_ID,
			CASE WHEN LS_NON_MIT_FLAG = 'Y' THEN LS_PERSON_ID ELSE NULL END,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER,
			DATA_PROPOSAL_NUMBER,
			LS_PERCENTAGE_OF_EFFORT,
			LS_EMAIL_ADDRESS,
			LS_PI_FLAG,
			LS_DESIGNATION,
			LS_MULTI_PI,
			LS_PROJECT_ROLE,
			(CASE WHEN LS_NON_MIT_FLAG = 'N' THEN 'Pending'
			WHEN LS_NON_MIT_FLAG = 'Y' THEN 'Not Applicable' ELSE NULL END)
		);
		SET LS_VALIDATION_STATUS = 'SUCCESS';
		SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
		SET LS_CHILD_ERROR = 'N';
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_units WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
		IF LI_COUNT > 0 THEN
			CALL MIGRATE_EPS_PROP_UNIT(DATA_PROPOSAL_NUMBER,DATA_PROPOSAL_ID,LS_PERSON_ID,LI_PROPOSAL_PERSON_ID,FOR_AUDIT,@prop_unit_error_count);
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'after child procedure call',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
			END IF;
			IF @prop_unit_error_count > 0 THEN
				SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'EPS PROP UNITS');
				SET LS_CHILD_ERROR = 'Y';
			END IF;
		END IF;
		IF LS_CHILD_ERROR = 'Y' THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSKEYINVEST','MIGRATION',IFNULL(CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',DATA_PROPOSAL_NUMBER,'and the person id : ',LS_PERSON_ID),CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',DATA_PROPOSAL_NUMBER,'and the rolodex id : ',LS_ROLODEX_ID)),UTC_TIMESTAMP(),'quickstart');
			SET LS_VALIDATION_STATUS  = 'ERROR';
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'child data error',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
			END IF;
		END IF;
		 UPDATE stage_eps_prop_investigators
		SET VALIDATION_STATUS = LS_VALIDATION_STATUS,
		 FIBI_IDENTIFIER = CASE  WHEN LS_VALIDATION_STATUS =  'ERROR' THEN -1 ELSE LI_PROPOSAL_PERSON_ID END
		WHERE MIGRATION_INVESTIGATORS_ID = LI_RECORD_ID;
	ELSE
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT MIGRATION_EPS_PROP_UNITS_ID,'DEVPROPUNITS','MIGRATION',CONCAT('Parent record failed for the proposal number : ',DATA_PROPOSAL_NUMBER,' and person : ',LS_PERSON_ID),UTC_TIMESTAMP(),'quickstart' FROM stage_eps_prop_units WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
		UPDATE stage_eps_prop_units SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID;
		UPDATE stage_eps_prop_investigators
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_INVESTIGATORS_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'error in investigator',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
		END IF;
	END IF;
	END LOOP MIGRATION_DEV_PROP_INV_CURSOR_LOOP;
	CLOSE MIGRATION_DEV_PROP_INV_CURSOR;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','EPSKEYINVEST',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),DATA_PROPOSAL_NUMBER);
END;
	SELECT COUNT(1) INTO DATA_ERROR_COUNT FROM  stage_eps_prop_investigators WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1 AND PROPOSAL_NUMBER = DATA_PROPOSAL_NUMBER;
ELSE
	SET DATA_ERROR_COUNT = 1;
END IF;
COMMIT;
END
$$
DELIMITER ;
