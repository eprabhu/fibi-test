DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_IP`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ACTIVITY_TYPE_CODE INT;
DECLARE LI_STATUS_CODE INT;
DECLARE LI_TYPE_CODE INT;
DECLARE LS_AWARD_TYPE_CODE INT;
DECLARE LI_GRANT_CALL_TYPE INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LI_MAX_SEQ_NUMBER INT;
DECLARE LI_MAX_LEAD_UNIT INT;
DECLARE LI_MAX_PI INT;
DECLARE LI_MIN_SEQ_NUMBER INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NAME VARCHAR(200);
DECLARE LS_SPONSOR_CODE VARCHAR(6);
DECLARE LS_TITLE VARCHAR(250);
DECLARE LS_PROPOSAL_UPDATE_USER VARCHAR(8);
DECLARE LS_PRIME_SPONSOR_CODE VARCHAR(6);
DECLARE LS_CDFA_NUMBER VARCHAR(100);
DECLARE LS_IS_SUBCONTRACT VARCHAR(1);
DECLARE LS_SPONSOR_PROPOSAL_NUMBER VARCHAR(100);
DECLARE LS_GRANT_CALL_TYPE VARCHAR(10);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_KEY_PERSON_INDICATOR VARCHAR(2);
DECLARE LS_PROPOSAL_STATUS VARCHAR(200);
DECLARE LS_PROP_SEQ_STATUS VARCHAR(20);
DECLARE LS_OPPORTUNITY VARCHAR(50);
DECLARE LS_SUBMISSION_USER VARCHAR(8);
DECLARE LS_CHANGE_STATUS VARCHAR(20);
DECLARE LS_SUBMISSION_DATE DATETIME;
DECLARE LS_CHK_START_DATE DATETIME;
DECLARE LS_CHK_END_DATE DATETIME;
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_CREATE_TIMESTAMP DATETIME;
DECLARE LS_SPONSOR_DEADLINE_DATE DATETIME;
DECLARE LS_TOTOAL_DIRECT_COST DECIMAL(12, 2);
DECLARE LS_TOTAL_INDIRECT_COST DECIMAL(12, 2);
DECLARE LS_TOTAL_COST DECIMAL(12, 2);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_SOURCE_COUNT1 INT;
DECLARE LI_SOURCE_COUNT2 INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_VALIDATION_STATUS VARCHAR(10);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LS_DELETED_DATA VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
SET SQL_SAFE_UPDATES = 0;
SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				-- DELETE FROM migration_validation_matrix WHERE MODULE_NAME IN ('IPPROPOSAL','INSTPROPKEYINVEST','INSTPROPKEYPERSON','INSTPROPKPUNITS','INSTPROPUNITS');
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE IN ('IPPROPOSAL','INSTPROPKEYINVEST','INSTPROPKEYPERSON','INSTPROPKPUNITS','INSTPROPUNITS') AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_proposal SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
				UPDATE stage_proposal_investigators SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
				UPDATE stage_proposal_key_persons SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
				UPDATE stage_proposal_key_person_units SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
				UPDATE stage_proposal_units SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_proposal;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'IPPROPOSAL';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','IPPROPOSAL',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','INSTPROPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','INSTPROPKPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','INSTPROPKEYINVEST',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','INSTPROPKEYPERSON',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_IP_PROPOSAL_CURSOR CURSOR FOR
	SELECT      MIGRATION_PROPOSAL_ID ,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				ACTIVITY_TYPE_CODE,
				CREATE_TIMESTAMP,
				UPDATE_USER,
				TITLE,
				REQUESTED_START_DATE_TOTAL,
				REQUESTED_END_DATE_TOTAL,
				SPONSOR_CODE,
				SPONSOR_PROPOSAL_NUMBER,
				PROPOSAL_TYPE_CODE,
				AWARD_TYPE_CODE,
				PRIME_SPONSOR_CODE,
				SUBCONTRACT_FLAG,
				CFDA_NUMBER,
				TOTAL_DIRECT_COST_TOTAL,
				TOTAL_INDIRECT_COST_TOTAL,
				DEADLINE_DATE,
				NOTICE_OF_OPPORTUNITY_CODE,
				KEY_PERSON_INDICATOR,
				DESCRIPTION,
				UPDATE_TIMESTAMP,
				OPPORTUNITY
	FROM stage_proposal WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_IP_PROPOSAL_CURSOR;
	MIGRATION_IP_PROPOSAL_CURSOR_LOOP : 	  LOOP
	FETCH  MIGRATION_IP_PROPOSAL_CURSOR       INTO    	LI_RECORD_ID,
														LS_PROPOSAL_NUMBER,
														LI_SEQUENCE_NUMBER,
														LI_ACTIVITY_TYPE_CODE,
														LS_CREATE_TIMESTAMP,
														LS_UPDATE_USER,
														LS_TITLE,
														LS_CHK_START_DATE,
														LS_CHK_END_DATE,
														LS_SPONSOR_CODE,
														LS_SPONSOR_PROPOSAL_NUMBER,
														LI_TYPE_CODE,
														LS_AWARD_TYPE_CODE,
														LS_PRIME_SPONSOR_CODE,
														LS_IS_SUBCONTRACT,
														LS_CDFA_NUMBER,
														LS_TOTOAL_DIRECT_COST,
														LS_TOTAL_INDIRECT_COST,
														LS_SPONSOR_DEADLINE_DATE,
														LI_GRANT_CALL_TYPE,
														LS_KEY_PERSON_INDICATOR,
														LS_PROPOSAL_STATUS,
														LS_UPDATE_TIMESTAMP,
														LS_OPPORTUNITY;
	IF DONE1 THEN
		LEAVE MIGRATION_IP_PROPOSAL_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_PROPOSAL_ID = -1;
	SET LI_COUNT = -1;
	SET LS_UNIT_NUMBER = NULL;
	SET LS_UNIT_NAME = NULL;
	SET LS_PROP_SEQ_STATUS = 'PENDING';
	SET LI_MAX_SEQ_NUMBER = -1;
	SET LI_MIN_SEQ_NUMBER = -1;
	SELECT IFNULL(MAX(SEQUENCE_NUMBER),0), IFNULL(MIN(SEQUENCE_NUMBER),0)  INTO LI_MAX_SEQ_NUMBER, LI_MIN_SEQ_NUMBER FROM stage_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
	IF LI_MAX_SEQ_NUMBER = LI_SEQUENCE_NUMBER THEN
		SET LS_PROP_SEQ_STATUS = 'ACTIVE';
	ELSE
		SET LS_PROP_SEQ_STATUS = 'ARCHIVE';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,CONCAT('seq  status : ',LS_PROP_SEQ_STATUS),UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	IF LI_MIN_SEQ_NUMBER > 0 THEN
		SELECT CREATE_TIMESTAMP, UPDATE_USER INTO LS_SUBMISSION_DATE, LS_SUBMISSION_USER FROM stage_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MIN_SEQ_NUMBER;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,CONCAT('Submission user and date logic of proposal : ', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	IF LS_PROP_SEQ_STATUS = 'ACTIVE' THEN
		SET LI_MAX_PI = -1;
			SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_PI FROM stage_proposal_investigators
			WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= LI_SEQUENCE_NUMBER;
		SELECT COUNT(1) INTO LI_COUNT FROM
		stage_proposal_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_PI AND PRINCIPAL_INVESTIGATOR_FLAG = 'Y' AND VALIDATION_STATUS <> 'ERROR';
		IF LI_COUNT <>  1 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT('Only one PI should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER,' and the sequence number : ', LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after IP check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
		SET LI_COUNT = -1;
		SET LI_MAX_LEAD_UNIT = -1;
		SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_LEAD_UNIT FROM stage_proposal_units
		WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= LI_SEQUENCE_NUMBER;
		SELECT COUNT(1) INTO LI_COUNT FROM stage_proposal_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_LEAD_UNIT AND LEAD_UNIT_FLAG = 'Y' AND VALIDATION_STATUS <> 'ERROR';
		IF LI_COUNT <> 1 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT('Only one lead unit should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER,' and the sequence number : ', LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		ELSEIF LI_COUNT =  1 THEN
			SELECT UNIT_NUMBER INTO LS_UNIT_NUMBER
			FROM stage_proposal_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_LEAD_UNIT AND LEAD_UNIT_FLAG = 'Y' AND VALIDATION_STATUS <> 'ERROR';
		END IF;
		IF LS_UNIT_NUMBER IS NOT NULL THEN
			SET LI_COUNT = -1;
			SELECT COUNT(1) INTO LI_COUNT FROM unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND IS_ACTIVE = 'Y';
			IF LI_COUNT <> 1 THEN
				INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT('Invalid unit number  :  ', LS_UNIT_NUMBER),UTC_TIMESTAMP(),'quickstart');
				SET LS_DATA_ERROR_FLAG = 'Y';
			ELSEIF LI_COUNT = 1 THEN
				SELECT unit_name INTO LS_UNIT_NAME FROM unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER;
			END IF;
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after lead unit check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	proposal_status WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROPOSAL_STATUS)) AND IS_ACTIVE = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog(
			PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',IFNULL(CONCAT('Invalid status  :', LS_PROPOSAL_STATUS),'Proposal status is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT STATUS_CODE INTO LI_STATUS_CODE FROM proposal_status WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROPOSAL_STATUS)) AND IS_ACTIVE = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after proposal status check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
	END IF;
	SET LS_TOTAL_COST = LS_TOTOAL_DIRECT_COST + LS_TOTAL_INDIRECT_COST;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(PROPOSAL_ID),0) + 1 INTO LI_PROPOSAL_ID
		FROM proposal;
		INSERT INTO proposal
		(
			PROPOSAL_ID,
			PROPOSAL_NUMBER,
			SEQUENCE_NUMBER,
			ABSTRACT_DESC,
			ACTIVITY_TYPE_CODE,
			CREATE_TIMESTAMP,
			CREATE_USER,
			DELIVERABLES,
			DETAILS,
			END_DATE,
			FUNDING_STRATEGY,
			HOME_UNIT_NAME,
			HOME_UNIT_NUMBER,
			IP_NUMBER,
			RESEARCH_AREA_DESC,
			SPONSOR_CODE,
			SPONSOR_PROPOSAL_NUMBER,
			START_DATE,
			STATUS_CODE,
			SUBMISSION_DATE,
			SUBMIT_USER,
			TITLE,
			TYPE_CODE,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			BUDGET_HEADER_ID,
			INTERNAL_DEADLINE_DATE,
			IS_SUBCONTRACT,
			IS_DOMESTIC_SITE,
			IS_MULTISITE_STUDY,
			GRANT_TYPE_CODE,
			GRANT_HEADER_ID,
			AWARD_TYPE_CODE,
			BASE_PROPOSAL_NUMBER,
			PROGRAM_ANNOUNCEMENT_NUMBER,
			PRIME_SPONSOR_CODE,
			CFDA_NUMBER,
			-- TOTAL_COST,
			-- TOTAL_DIRECT_COST,
			-- TOTAL_INDIRECT_COST,
			MULTI_DISCIPLINARY_DESC,
			SPONSOR_DEADLINE_DATE,
			EXTERNAL_FUNDING_AGENCY_ID,
			PROPOSAL_SEQUENCE_STATUS,
			CLUSTER_CODE,
			DURATION
		)
		VALUES
		(
			LI_PROPOSAL_ID,
			LS_PROPOSAL_NUMBER,
			LI_SEQUENCE_NUMBER,
			NULL,
			LI_ACTIVITY_TYPE_CODE,
			LS_CREATE_TIMESTAMP,
			LS_UPDATE_USER,
			NULL,
			NULL,
			LS_CHK_END_DATE,
			NULL,
			CONCAT(LS_UNIT_NUMBER, '-',LS_UNIT_NAME),
			LS_UNIT_NUMBER,
			NULL,
			NULL,
			LS_SPONSOR_CODE,
			LS_SPONSOR_PROPOSAL_NUMBER,
			LS_CHK_START_DATE,
			LI_STATUS_CODE,
			LS_SUBMISSION_DATE,
			LS_SUBMISSION_USER,
			LS_TITLE,
			LI_TYPE_CODE,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER,
			NULL,
			NULL,
			LS_IS_SUBCONTRACT,
			NULL,
			NULL,
			LI_GRANT_CALL_TYPE,
			NULL,
			LS_AWARD_TYPE_CODE,
			NULL,
			LS_OPPORTUNITY,
			LS_PRIME_SPONSOR_CODE,
			LS_CDFA_NUMBER,
			-- LS_TOTAL_COST,
			-- LS_TOTOAL_DIRECT_COST,
			-- LS_TOTAL_INDIRECT_COST,
			NULL,
			LS_SPONSOR_DEADLINE_DATE,
			NULL,
			LS_PROP_SEQ_STATUS,
			NULL,
			NULL
		);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		SET LS_VALIDATION_STATUS = 'SUCCESS';
		SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
		SET LS_CHILD_ERROR = 'N';
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'before chile proc call',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		CALL MIGRATE_IP_INV(LI_RECORD_ID,LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER,LI_PROPOSAL_ID,FOR_AUDIT,LS_PROP_SEQ_STATUS,@inv_error_count);
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after inv call',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
		IF LS_KEY_PERSON_INDICATOR IN ('P0','P1') THEN
			CALL MIGRATE_IP_KEY_PERSONS(LI_RECORD_ID,LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER,LI_PROPOSAL_ID,LS_KEY_PERSON_INDICATOR,FOR_AUDIT,LS_PROP_SEQ_STATUS,@kp_error_count);
			IF @kp_error_count > 0 THEN
				SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'KEY PERSONS,');
				SET LS_CHILD_ERROR = 'Y';
			END IF;
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after key person check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
			END IF;
		END IF;
		IF @inv_error_count > 0 THEN
			SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'INVESTIGATORS');
			SET LS_CHILD_ERROR = 'Y';
		END IF;
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after child procedure call',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		IF LS_CHILD_ERROR  = 'Y' THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',LS_PROPOSAL_NUMBER,' and the sequence number : ',LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_VALIDATION_STATUS  = 'ERROR';
				DELETE FROM prop_person_units WHERE PROP_PERSON_UNIT_ID IN
				(SELECT FIBI_IDENTIFIER FROM stage_proposal_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS'
				UNION
				SELECT FIBI_IDENTIFIER FROM stage_proposal_key_person_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS');
				UPDATE stage_proposal_units SET VALIDATION_STATUS = 'ERROR', FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS';
				UPDATE stage_proposal_key_person_units SET VALIDATION_STATUS = 'ERROR', FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS';
				DELETE FROM proposal_persons WHERE PROPOSAL_PERSON_ID IN
				(SELECT FIBI_IDENTIFIER FROM stage_proposal_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS' UNION
				SELECT FIBI_IDENTIFIER FROM stage_proposal_key_persons WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS');
				UPDATE stage_proposal_investigators SET VALIDATION_STATUS = 'ERROR', FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS';
				UPDATE stage_proposal_key_persons SET VALIDATION_STATUS = 'ERROR', FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER AND VALIDATION_STATUS = 'SUCCESS';
				DELETE FROM proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
				IF FOR_AUDIT = 1 THEN
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'child data error',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
				END IF;
		END IF;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_proposal
		SET VALIDATION_STATUS = LS_VALIDATION_STATUS,
		FIBI_IDENTIFIER = CASE WHEN LS_VALIDATION_STATUS = 'ERROR' THEN -1 ELSE LI_PROPOSAL_ID END
		WHERE MIGRATION_PROPOSAL_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPOSAL',LI_BATCH_ID,'after update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
	ELSE
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT MIGRATION_PROPOSAL_INVESTIGATORS_ID,'INSTPROPKEYINVEST','MIGRATION',CONCAT('Parent record failed for the proposal number : ',LS_PROPOSAL_NUMBER,' and the sequence number : ',LI_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart' FROM stage_proposal_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
