DELIMITER $$
CREATE DEFINER=`jhufibi`@`%` FUNCTION `fn_sr_need_assoc`(
  AV_SR_HEADER_ID   int
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
 DECLARE LI_COUNT int;
 DECLARE CATE_CODE int;
 DECLARE SR_CATE_CODE INT DEFAULT 20;
 DECLARE RETURN_STRING VARCHAR(5) DEFAULT 'FALSE';
 SELECT CATEGORY_CODE
 INTO CATE_CODE
 FROM SR_HEADER
 WHERE SR_HEADER_ID=AV_SR_HEADER_ID;
 IF CATE_CODE=SR_CATE_CODE THEN
 RETURN RETURN_STRING;
 ELSE
  SELECT COUNT(*)
  INTO   li_count
  FROM   assoc_sr
  WHERE  sr_header_id = AV_SR_HEADER_ID;
  IF LI_COUNT <= 0 THEN
   SET RETURN_STRING = 'TRUE';
  END IF;
  RETURN RETURN_STRING;
 END IF;
END
$$
DELIMITER ;
