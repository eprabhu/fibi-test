DELIMITER $$
CREATE  FUNCTION `FN_GET_SORT_VALUE`(AV_UNIT_NUMBER  varchar(8)) RETURNS varchar(255) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
    DECLARE LI_PARENT_UNIT_NUMBER VARCHAR(8) ;
	DECLARE LS_PARENT VARCHAR(3);
	DECLARE LS_SORT_VALUE VARCHAR(30);
	DECLARE LS_NEW_SORT_VALUE VARCHAR(30);
	DECLARE LI_COUNT , LI_COUNT_EXISTS INT;
	DECLARE LI_LIMIT INT DEFAULT 1;
		SELECT PARENT_UNIT_NUMBER INTO LI_PARENT_UNIT_NUMBER FROM UNIT WHERE UNIT_NUMBER = AV_UNIT_NUMBER;
		SELECT SORT_VALUE INTO LS_SORT_VALUE FROM JHU_UNIT WHERE UNIT_NUMBER = LI_PARENT_UNIT_NUMBER;
		SELECT COUNT(*) INTO LI_COUNT FROM UNIT WHERE PARENT_UNIT_NUMBER = LI_PARENT_UNIT_NUMBER and UNIT_NUMBER <= AV_UNIT_NUMBER;
		LOOP_LABEL:  LOOP
			SELECT SUBSTR(LS_SORT_VALUE,LI_LIMIT,3) INTO LS_PARENT FROM DUAL;
				IF 0-LS_PARENT < 0 THEN
					SET LI_LIMIT = LI_LIMIT +3;
				ELSE
					SET LS_NEW_SORT_VALUE = RPAD(CONCAT(SUBSTR(LS_SORT_VALUE,1,LI_LIMIT-1),LPAD(LI_COUNT,3,0)), 30, 0);
					return LS_NEW_SORT_VALUE;
					LEAVE LOOP_LABEL;
				END IF;
		END LOOP;
END
$$
DELIMITER ;
