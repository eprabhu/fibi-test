CREATE DEFINER=`jhufibi`@`%` PROCEDURE `MIGRATE_USER_ROLES`(REFRESH_FLAG INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ROLE_ID INT;
DECLARE LI_COUNT INT;
DECLARE LI_PERSON_ROLE_ID INT;
DECLARE LS_PERSON_ID VARCHAR(40);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_PARENT_UNIT_NUMBER VARCHAR(8);
DECLARE LS_USER_NAME VARCHAR(10);
DECLARE LS_DESCEND_FLAG VARCHAR(1);
DECLARE LS_UPDATE_USER VARCHAR(10);
DECLARE LS_CHILD_UNIT_NUMBER VARCHAR(1000);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_FALSE_PARENT VARCHAR(1);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_DATA_EXISTS VARCHAR(1);
DECLARE LS_ROLE_NOT_AVAIL_FLAG VARCHAR(1);
DECLARE LS_MIGRATION_ERROR_MESSAGE VARCHAR(500);
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
	IF REFRESH_FLAG = 1 THEN
		UPDATE stage_user_roles SET MIGRATION_STATUS = NULL , FIBI_IDENTIFIER = NULL WHERE MIGRATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'USERROLES' AND ERROR_TYPE = 'MIGRATION';
	END IF;
END;
BEGIN
	SET LI_COUNT = -1;
	SET LS_ROLE_NOT_AVAIL_FLAG = 'N';
	SELECT COUNT(1) INTO LI_COUNT FROM role WHERE TRIM(UPPER(ROLE_NAME)) = TRIM(UPPER('JHU Department Administrators')) AND STATUS_FLAG = 'Y';
	IF LI_COUNT = 1 THEN
		SELECT ROLE_ID INTO LI_ROLE_ID FROM role WHERE TRIM(UPPER(ROLE_NAME)) = TRIM(UPPER('JHU Department Administrators')) AND STATUS_FLAG = 'Y';
	ELSE
		SET LS_ROLE_NOT_AVAIL_FLAG = 'Y';
		INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Failed execution : Not a valid role',UTC_TIMESTAMP());
	END IF;
END;
IF LS_ROLE_NOT_AVAIL_FLAG = 'N' THEN
	BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE USER_ROLE_CURSOR CURSOR FOR
	SELECT 	ID,
			PERSON_ID,
			USER_ID,
			UNIT_NUMBER,
			DESCEND_FLAG,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			PARENT_UNIT_NUMBER
	FROM	stage_user_roles WHERE MIGRATION_STATUS IS NULL  AND FIBI_IDENTIFIER IS NULL and DESCEND_FLAG = 'N' ORDER BY ID;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'USERROLES','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN USER_ROLE_CURSOR;
	USER_ROLE_CURSOR_LOOP		:	LOOP
	FETCH USER_ROLE_CURSOR			INTO 	LI_RECORD_ID,
											LS_PERSON_ID,
											LS_USER_NAME,
											LS_UNIT_NUMBER,
											LS_DESCEND_FLAG,
											LS_UPDATE_TIMESTAMP,
											LS_UPDATE_USER,
											LS_PARENT_UNIT_NUMBER;
	IF DONE1 THEN
		LEAVE USER_ROLE_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_PERSON_ROLE_ID = -1;
	SET LS_DATA_EXISTS = 'Y';
	SET LS_CHILD_UNIT_NUMBER = NULL;
	SET LS_FALSE_PARENT = 'N';
	-- person check
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM person WHERE PERSON_ID = LS_PERSON_ID AND TRIM(UPPER(USER_NAME)) = TRIM(UPPER(LS_USER_NAME));
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'USERROLES','MIGRATION',IFNULL(CONCAT('Invalid person id : ',LS_PERSON_ID,' and the user name : ',LS_USER_NAME),'Person id/username is null'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	-- unit number check
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND ACTIVE_FLAG = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'USERROLES','MIGRATION',IFNULL(CONCAT('Invalid unit number : ',LS_UNIT_NUMBER),'Unit number is null'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT PARENT_UNIT_NUMBER INTO LS_PARENT_UNIT_NUMBER FROM unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND ACTIVE_FLAG = 'Y';
	END IF;
	-- unit number '000001, 00000001'
	IF LS_UNIT_NUMBER IN ('000001', '00000001') THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'USERROLES','MIGRATION','The department administrators should not set to the top level of the unit',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	-- person_roles check
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM person_roles WHERE PERSON_ID = LS_PERSON_ID AND UNIT_NUMBER = LS_UNIT_NUMBER AND ROLE_ID = LI_ROLE_ID;
	IF LI_COUNT > 0 THEN
		-- INSERT INTO migration_transaction_errorlog
			-- (PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		-- VALUES  (LI_RECORD_ID,'USERROLES','MIGRATION',IFNULL(CONCAT('Data already Exists for person id : ',LS_PERSON_ID,' and the unit number : ',LS_UNIT_NUMBER,' and role id :', LI_ROLE_ID),'The data is already is exists'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
		SET LS_DATA_EXISTS = 'Y';
	END IF;
	-- Person role RT TABLE
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM person_role_rt WHERE PERSON_ID = LS_PERSON_ID AND UNIT_NUMBER = LS_UNIT_NUMBER AND ROLE_ID = LI_ROLE_ID;
	IF LI_COUNT > 0 THEN
		SET LS_DATA_ERROR_FLAG = 'Y';
		SET LS_DATA_EXISTS = 'Y';
	END IF;
	-- Checking the unit is parent to any other unit
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM unit WHERE PARENT_UNIT_NUMBER = LS_UNIT_NUMBER;
	IF LI_COUNT = 0 THEN
		SET LS_FALSE_PARENT = 'Y';
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		INSERT INTO person_roles
		(
			PERSON_ID,
			ROLE_ID,
			UNIT_NUMBER,
			DESCEND_FLAG,
			UPDATE_TIMESTAMP,
			UPDATE_USER
		)
		VALUES
		(
			LS_PERSON_ID,
			LI_ROLE_ID,
			LS_UNIT_NUMBER,
			CASE WHEN LS_FALSE_PARENT = 'N' THEN LS_DESCEND_FLAG ELSE 'N' END,
			UTC_TIMESTAMP(),
			'tchitra1'
		);
		IF LS_DATA_ERROR_FLAG = 'N' THEN
			SELECT MAX(PERSON_ROLES_ID) INTO LI_PERSON_ROLE_ID FROM person_roles;
			UPDATE stage_user_roles SET MIGRATION_STATUS = 'SUCCESS',FIBI_IDENTIFIER = LI_PERSON_ROLE_ID WHERE ID = LI_RECORD_ID;
		END IF;
	ELSE
		IF LS_DATA_EXISTS = 'Y' THEN
			UPDATE stage_user_roles SET MIGRATION_STATUS = 'NOTVALID',FIBI_IDENTIFIER = -1 WHERE ID = LI_RECORD_ID;
		ELSE
			UPDATE stage_user_roles SET MIGRATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE ID = LI_RECORD_ID;
		END IF;
	END IF;
	END LOOP USER_ROLE_CURSOR_LOOP;
	CLOSE USER_ROLE_CURSOR;
	END;
END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Execution completed',UTC_TIMESTAMP());
    SET FOREIGN_KEY_CHECKS = 1;
    SET SQL_SAFE_UPDATES =  1;
    COMMIT;
END
$$
DELIMITER ;
