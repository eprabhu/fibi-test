DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_BUDGET_HEADER_PREVAL`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_RATE_TYPE_CODE INT;
DECLARE LI_RATE_CLASS_CODE INT;
DECLARE LI_UR_RATE_CLASS_CODE INT;
DECLARE LI_VERSION_NUMBER INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_FINAL_VERSION_FLAG VARCHAR(1);
DECLARE LS_IDC_BASE VARCHAR(10);
DECLARE LS_TOTAL_COST DECIMAL(12,2);
DECLARE LS_SUM_OF_COST DECIMAL(12,2);
DECLARE LS_DIRECT_TOTAL_COST DECIMAL(12,2);
DECLARE LS_INDIRECT_TOTAL_COST DECIMAL(12,2);
DECLARE LS_COST_SHARING_AMOUNT DECIMAL(12,2);
DECLARE LS_START_DATE DATETIME;
DECLARE LS_END_DATE DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE IN ('BUDGET','BUDGETPERIOD','EPSPROPRATE') AND ERROR_TYPE = 'VALIDATION';
			UPDATE stage_budget_header SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
			UPDATE stage_budget_periods SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_budget_header;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'BUDGET';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'VALIDATION','BUDGET',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','BUDGETPERIOD',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
    DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_BUDGET_HEADER_CURSOR CURSOR FOR
		SELECT  MIGRATION_BUDGET_ID,
				PROPOSAL_NUMBER,
				VERSION_NUMBER,
				START_DATE,
				END_DATE,
				TOTAL_COST,
				TOTAL_DIRECT_COST,
				TOTAL_INDIRECT_COST,
				COST_SHARING_AMOUNT,
				OH_RATE_CLASS_CODE,
				OH_RATE_TYPE_CODE,
				UR_RATE_CLASS_CODE,
				FINAL_VERSION_FLAG
		FROM 	stage_budget_header
		WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL AND FINAL_VERSION_FLAG = 'Y';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
		OPEN MIGRATION_BUDGET_HEADER_CURSOR;
		MIGRATION_BUDGET_HEADER_CURSOR_LOOP    : LOOP
		FETCH MIGRATION_BUDGET_HEADER_CURSOR     INTO    	LI_RECORD_ID,
															LS_PROPOSAL_NUMBER,
															LI_VERSION_NUMBER,
															LS_START_DATE,
															LS_END_DATE,
															LS_TOTAL_COST,
															LS_DIRECT_TOTAL_COST,
															LS_INDIRECT_TOTAL_COST,
															LS_COST_SHARING_AMOUNT,
															LI_RATE_CLASS_CODE,
															LI_RATE_TYPE_CODE,
															LI_UR_RATE_CLASS_CODE,
															LS_FINAL_VERSION_FLAG;
	IF DONE1 THEN
		LEAVE MIGRATION_BUDGET_HEADER_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	stage_eps_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VALIDATION_STATUS IN ('VALID','SUCCESS');
	IF LI_COUNT = 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',CONCAT('Invalid proposal number :', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after dev prop check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	IF LS_START_DATE IS NULL THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION','Start date is mandatory',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after start date',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	IF LS_END_DATE IS NULL THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION','End date is mandatory',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after end date',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	IF LS_START_DATE IS NOT NULL AND LS_END_DATE IS NOT NULL AND LS_END_DATE < LS_START_DATE THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION','End date should be greater than that of start date',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after greater than logic',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM
		rate_type WHERE RATE_TYPE_CODE = LI_RATE_TYPE_CODE AND IS_ACTIVE = 'Y';
		IF LI_COUNT = 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',IFNULL(CONCAT('Invalid rate type code : ',LI_RATE_TYPE_CODE),'Rate type is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after rate type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
		SET LI_COUNT = -1;
		IF LI_RATE_CLASS_CODE IS NOT NULL AND LI_RATE_CLASS_CODE <> 0 THEN
			SELECT COUNT(1) INTO LI_COUNT FROM
			rate_type WHERE RATE_CLASS_CODE = LI_RATE_CLASS_CODE AND IS_ACTIVE = 'Y';
			IF LI_COUNT = 0 THEN
				INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',CONCAT('Invalid rate class code : ',LI_RATE_CLASS_CODE),UTC_TIMESTAMP(),'quickstart');
				SET LS_DATA_ERROR_FLAG = 'Y';
			END IF;
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after rate class check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	SET LI_COUNT = -1;
	IF LI_UR_RATE_CLASS_CODE IS NOT NULL AND LI_UR_RATE_CLASS_CODE <> 0 THEN
		SELECT COUNT(1) INTO LI_COUNT FROM
		rate_type WHERE RATE_CLASS_CODE = LI_UR_RATE_CLASS_CODE AND IS_ACTIVE = 'Y';
		IF LI_COUNT = 0 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',CONCAT('Invalid rate class code : ',LI_UR_RATE_CLASS_CODE),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after UR rate class check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	SET LS_SUM_OF_COST = LS_DIRECT_TOTAL_COST + LS_INDIRECT_TOTAL_COST;
	IF LS_TOTAL_COST <> LS_SUM_OF_COST THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION','Total cost is not equal to the sum of direct cost and indirect cost',UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'total cost calculation',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
	SET LS_CHILD_ERROR = 'N';
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	stage_budget_periods WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VERSION_NUMBER = LI_VERSION_NUMBER;
	IF LI_COUNT > 0 THEN
		CALL MIGRATE_BUDGET_PERIOD_PREVAL(LS_PROPOSAL_NUMBER, LI_VERSION_NUMBER,LS_START_DATE,LS_END_DATE,FOR_AUDIT,@budget_period_error_count);
		IF @budget_period_error_count > 0 THEN
			SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE ,'BUDGET PERIOD, ');
			SET LS_CHILD_ERROR = 'Y';
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'child data call',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	ELSE
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',CONCAT('Invalid budget period with proposal number :  ',LS_PROPOSAL_NUMBER, ' and version number : ', LI_VERSION_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'invalid period check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	END IF;
	IF LS_CHILD_ERROR = 'Y' THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'BUDGET','VALIDATION',CONCAT('Error in the ',LS_CHILD_ERROR_MESSAGE, ' for the proposal number : ', LS_PROPOSAL_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_budget_header
		SET VALIDATION_STATUS = 'VALID',
		FIBI_IDENTIFIER = NULL
		WHERE MIGRATION_BUDGET_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after valid update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	ELSE
		UPDATE stage_budget_header
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = NULL
		WHERE MIGRATION_BUDGET_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
		END IF;
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed validation of ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'Validation end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_VERSION_NUMBER);
	END IF;
	END LOOP MIGRATION_BUDGET_HEADER_CURSOR_LOOP;
	CLOSE MIGRATION_BUDGET_HEADER_CURSOR;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','BUDGET',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL,NULL);
	END IF;
END;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	SELECT 1 AS RESULT;
	COMMIT;
END
$$
DELIMITER ;
