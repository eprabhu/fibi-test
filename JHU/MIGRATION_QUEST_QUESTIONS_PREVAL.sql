DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATION_QUEST_QUESTIONS_PREVAL`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUEST_QTN_ID INT;
DECLARE LI_QUESTIONNAIRE_ID int;
DECLARE LI_QUESTIONNAIRE_VERSION_NUMBER smallint;
DECLARE LI_QUESTION_ID int;
DECLARE LI_PARENT_QUESTION_NUMBER int;
DECLARE LI_QUESTION_VERSION_NUMBER int;
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_CONDITION_FLAG VARCHAR(2);
DECLARE LS_CONDITION_VALUE VARCHAR(2000);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_STG_QUEST_QTN_ID,'QUEST_QUESTIONNAIRE_QUESTION','VALIDATION',CONCAT(LS_ERROR_MSG),UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_QUESTIONNAIRE_QUESTION') AND ERROR_TYPE = 'VALIDATION';
			UPDATE stage_quest_questions SET VALIDATION_STATUS = NULL where  VALIDATION_STATUS = 'ERROR' and MIGRATED_QUESTION_ID = NULL;
			END IF;
END;
BEGIN
SET SQL_SAFE_UPDATES = 0;
	DELETE FROM migration_qtn_execution_log;
	ALTER TABLE migration_qtn_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_quest_questions;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'QUEST_QUESTIONNAIRE_QUESTION';
	INSERT INTO migration_transtn_auditlog_header1 (BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
										VALUES 	(LI_BATCH_ID,'VALIDATION','QUEST_QUESTIONNAIRE_QUESTION',UTC_TIMESTAMP());
	INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution : QUEST_QUESTIONNAIRE_QUESTION ',UTC_TIMESTAMP());
END;
		BEGIN
		DECLARE DONE4 INT DEFAULT FALSE;
		DECLARE CUR_quest_questions CURSOR FOR
		select ID
				, QUESTIONNAIRE_ID
				, QUESTIONNAIRE_VERSION_NUMBER
				, QUESTION_ID
				, PARENT_QUESTION_NUMBER
				, QUESTION_VERSION_NUMBER
				, CONDITION_FLAG
				, CONDITION_VALUE
		from stage_quest_questions
        where validation_status is NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE4 = TRUE;
		OPEN CUR_quest_questions;
		QUEST_QUESTION_LOOP: LOOP
		FETCH CUR_quest_questions INTO
						LI_STG_QUEST_QTN_ID
						, LI_QUESTIONNAIRE_ID
						, LI_QUESTIONNAIRE_VERSION_NUMBER
						, LI_QUESTION_ID
						, LI_PARENT_QUESTION_NUMBER
						, LI_QUESTION_VERSION_NUMBER
						, LS_CONDITION_FLAG
						, LS_CONDITION_VALUE;
		IF DONE4 THEN
			LEAVE QUEST_QUESTION_LOOP;
		END IF;
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('VALIDATION','QUEST_QUESTIONNAIRE_QUESTION',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LI_QUESTION_ID);
					SET LS_DATA_ERROR_FLAG = 'N';
					set LI_COUNT = -1;
                    SELECT COUNT(*) INTO LI_COUNT FROM
						stage_questions WHERE QUESTION_ID = LI_QUESTION_ID
                        AND VERSION_NUMBER = LI_QUESTION_VERSION_NUMBER
                        and validation_status = 'VALID';
							IF LI_COUNT = 0 THEN
								INSERT INTO migration_questionnaire_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_STG_QUEST_QTN_ID,'QUEST_QUESTIONNAIRE_QUESTION','VALIDATION',CONCAT('Invalid question id :  ', LI_QUESTION_ID, ' Version Number : ',LI_QUESTION_VERSION_NUMBER),UTC_TIMESTAMP(),'JHU_ADMIN');
								SET LS_DATA_ERROR_FLAG = 'Y';
							END IF;
					IF (trim(LI_PARENT_QUESTION_NUMBER) is not null and trim(LI_PARENT_QUESTION_NUMBER) != 0) then
						set LI_COUNT = -1;
						SELECT COUNT(*) INTO LI_COUNT FROM
						stage_quest_questions WHERE QUESTION_NUMBER = LI_PARENT_QUESTION_NUMBER
						and QUESTIONNAIRE_ID = LI_QUESTIONNAIRE_ID
						and QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
							IF LI_COUNT <> 1 THEN
								INSERT INTO migration_questionnaire_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_STG_QUEST_QTN_ID,'QUEST_QUESTIONNAIRE_QUESTION','VALIDATION',CONCAT('Invalid parent question id :  ', LI_PARENT_QUESTION_NUMBER),UTC_TIMESTAMP(),'JHU_ADMIN');
								SET LS_DATA_ERROR_FLAG = 'Y';
							END IF;
					END IF;
						IF LS_DATA_ERROR_FLAG = 'Y' THEN
							set sql_safe_updates = 0;
							UPDATE stage_quest_questions SET VALIDATION_STATUS = 'ERROR' where ID =  LI_STG_QUEST_QTN_ID;
                            UPDATE stage_quest_usage SET VALIDATION_STATUS = 'ERROR' where QUESTIONNAIRE_ID = LI_QUESTIONNAIRE_ID and VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
                            update stage_questionnaire set VALIDATION_STATUS = 'ERROR' where questionnaire_id = LI_QUESTIONNAIRE_ID and VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
                            update stage_quest_answer_header set VALIDATION_STATUS = 'ERROR' where QUESTIONNAIRE_ID  = LI_QUESTIONNAIRE_ID and QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER;
							update stage_quest_answer set validation_status = 'ERROR' where QUESTIONNAIRE_COMPLETION_ID in (select QUESTIONNAIRE_COMPLETION_ID from stage_quest_answer_header where QUESTIONNAIRE_ID  = LI_QUESTIONNAIRE_ID and QUESTIONNAIRE_VERSION_NUMBER = LI_QUESTIONNAIRE_VERSION_NUMBER);
						ELSE
							UPDATE stage_quest_questions SET VALIDATION_STATUS = 'VALID' where ID =  LI_STG_QUEST_QTN_ID;
						END IF;
					IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Validated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Questionnaire Questions'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('VALIDATION','QUEST_QUESTIONNAIRE_QUESTION',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LI_QUESTION_ID);
					set LI_COUNT = NULL;
					set LI_STG_QUEST_QTN_ID = NULL;
					set LI_PARENT_QUESTION_NUMBER = NULL;
					set LI_QUESTION_VERSION_NUMBER = NULL;
					set LI_QUESTION_ID = NULL;
				END LOOP;
				CLOSE CUR_quest_questions;
					INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','QUEST_QUESTIONNAIRE_QUESTION',LI_BATCH_ID,'Exit cursor',UTC_TIMESTAMP(),NULL);
			INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Validated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Questionnaire Questions'),UTC_TIMESTAMP()),('Validation completed successfully',UTC_TIMESTAMP());
			END;
		SET SQL_SAFE_UPDATES = 1;
		END
$$
DELIMITER ;
