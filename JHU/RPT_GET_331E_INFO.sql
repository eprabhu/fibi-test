CREATE DEFINER=`jhufibi`@`%` PROCEDURE `RPT_GET_331E_INFO`(REPORT_UNIT  VARCHAR(8))
BEGIN
SELECT DISTINCT
    CONCAT(PR.FULL_NAME, ' (', PR.USER_NAME, ')') AS FULL_NAME,
	date_format(CD.TRAINING_DATE,'%m/%d/%Y') COI_TRAINING_DATE,
    date_format(ED.TRAINING_DATE,'%m/%d/%Y')EFFORT_TRAINING_DATE,
    date_format(RS.TRAINING_DATE,'%m/%d/%Y') SECURITY_TRAINING_DATE,
    PR.EMAIL_ADDRESS,
    PR.HOME_UNIT,
    PR.DIRECTORY_TITLE,
    CASE
        WHEN IFNULL(PP_COUNT.CNT, 0) > 0 AND IFNULL(AWD_COUNT.CNT, 0) = 0 THEN 'PENDING'
        WHEN IFNULL(PP_COUNT.CNT, 0) = 0 AND IFNULL(AWD_COUNT.CNT, 0) > 0 THEN 'AWARDED'
        WHEN IFNULL(PP_COUNT.CNT, 0) > 0 AND IFNULL(AWD_COUNT.CNT, 0) > 0 THEN 'AWARDED AND PENDING'
        ELSE 'NONE'
    END AS PROJECT_TYPE,
    '331E' REPORT_NUMBER,
    'INVESTIGATOR TRAINING REPORT' REPORT_TITLE,
    REPORT_UNIT PARAMETER_ENTETRED_1,
    UTC_TIMESTAMP() RUN_TIME,
    @@HOSTNAME HOST_NAME
FROM
    PERSON PR
LEFT JOIN (
    SELECT
        CPR.PERSON_ID,
        MAX(CPRT.DATE_ACKNOWLEDGED) AS TRAINING_DATE
    FROM PERSON CPR
    JOIN PERSON_TRAINING CPRT ON CPR.PERSON_ID = CPRT.PERSON_ID
    WHERE CPRT.TRAINING_CODE = 4
    GROUP BY CPR.PERSON_ID
) CD ON PR.PERSON_ID = CD.PERSON_ID
LEFT JOIN (
    SELECT
        EPR.PERSON_ID,
        MAX(EPRT.DATE_ACKNOWLEDGED) AS TRAINING_DATE
    FROM PERSON EPR
    JOIN PERSON_TRAINING EPRT ON EPR.PERSON_ID = EPRT.PERSON_ID
    WHERE EPRT.TRAINING_CODE IN (20 , 21, 27)
    GROUP BY EPR.PERSON_ID
) ED ON PR.PERSON_ID = ED.PERSON_ID
LEFT JOIN (
    SELECT
        CPR.PERSON_ID,
        MAX(CPRT.DATE_ACKNOWLEDGED) AS TRAINING_DATE
    FROM PERSON CPR
    JOIN PERSON_TRAINING CPRT ON CPR.PERSON_ID = CPRT.PERSON_ID
    WHERE CPRT.TRAINING_CODE = 73
    GROUP BY CPR.PERSON_ID
) RS ON PR.PERSON_ID = RS.PERSON_ID
-- PROPOSAL (PENDING)
LEFT JOIN (
    SELECT
        IIPI1.PERSON_ID,
        COUNT(DISTINCT IIP1.PROPOSAL_ID) AS CNT,
        IIP1.HOME_UNIT_NUMBER
    FROM PROPOSAL IIP1
    JOIN PROPOSAL_PERSONS IIPI1
        ON IIP1.PROPOSAL_ID = IIPI1.PROPOSAL_ID
    WHERE IIP1.PROPOSAL_SEQUENCE_STATUS = 'ACTIVE'
      AND IIP1.STATUS_CODE = 1
      AND IIPI1.PROP_PERSON_ROLE_ID <> 2
    GROUP BY IIPI1.PERSON_ID, IIP1.HOME_UNIT_NUMBER
) PP_COUNT ON PP_COUNT.PERSON_ID = PR.PERSON_ID
-- AWARD (AWARDED)
LEFT JOIN (
    SELECT
        IAI1.PERSON_ID,
        COUNT(DISTINCT IA1.AWARD_ID) AS CNT,
        IA1.LEAD_UNIT_NUMBER
    FROM AWARD IA1
    JOIN AWARD_PERSONS IAI1
        ON IA1.AWARD_ID = IAI1.AWARD_ID
    WHERE IA1.AWARD_SEQUENCE_STATUS = 'ACTIVE'
    GROUP BY IAI1.PERSON_ID, IA1.LEAD_UNIT_NUMBER
) AWD_COUNT ON AWD_COUNT.PERSON_ID = PR.PERSON_ID
WHERE
    (
        FIND_IN_SET(PR.HOME_UNIT, FN_GET_TEMP_UNIT(REPORT_UNIT))
        OR FIND_IN_SET(PP_COUNT.HOME_UNIT_NUMBER, FN_GET_TEMP_UNIT(REPORT_UNIT))
        OR FIND_IN_SET(AWD_COUNT.LEAD_UNIT_NUMBER, FN_GET_TEMP_UNIT(REPORT_UNIT))
    )
    AND PR.USER_NAME IS NOT NULL
    AND (
        IFNULL(PP_COUNT.CNT, 0) > 0
        OR IFNULL(AWD_COUNT.CNT, 0) > 0
        OR (IFNULL(PP_COUNT.CNT, 0) = 0 AND IFNULL(AWD_COUNT.CNT, 0) = 0 AND PR.IS_FACULTY = 'Y')
    )
ORDER BY FULL_NAME;
END
$$
DELIMITER ;
