DELIMITER $$
CREATE DEFINER=`root`@`localhost` FUNCTION `FN_UPDATE_PROP_PERSON_TRAINING_STATUS`(AV_PROPOSAL_ID INT) RETURNS int
    DETERMINISTIC
BEGIN
SET SQL_SAFE_UPDATES = 0;
IF AV_PROPOSAL_ID = 0 THEN
     WITH TrainingStatus1 AS (
        SELECT DISTINCT PT.PERSON_ID
        FROM PERSON_TRAINING PT
        JOIN MYLEARNING_TRAINING_CODE MTC
          ON PT.TRAINING_CODE = MTC.COEUS_TRAINING_CODE
        WHERE MTC.COEUS_TRAINING_CODE = '20'
          AND PT.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(), INTERVAL 5 YEAR)
    ),
    TrainingStatus2 AS (
        SELECT DISTINCT PT.PERSON_ID
        FROM PERSON_TRAINING PT
        JOIN MYLEARNING_TRAINING_CODE MTC
          ON PT.TRAINING_CODE = MTC.COEUS_TRAINING_CODE
        WHERE MTC.COEUS_TRAINING_CODE = '4'
          AND PT.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(), INTERVAL 4 YEAR)
    )
     UPDATE EPS_PROPOSAL_PERSONS T1
    JOIN EPS_PROPOSAL T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID
    SET IS_TRAINING_COMPLETED = (
        CASE
            WHEN EXISTS (SELECT 1 FROM TrainingStatus1 TS1 WHERE TS1.PERSON_ID = T1.PERSON_ID)
             AND EXISTS (SELECT 1 FROM TrainingStatus2 TS2 WHERE TS2.PERSON_ID = T1.PERSON_ID)
            THEN 'Completed'
            ELSE 'Pending'
        END
    )
    WHERE T2.STATUS_CODE IN ('1', '3', '9')
      AND T1.PERSON_ID IS NOT NULL;
ELSE
     WITH TrainingStatus1 AS (
        SELECT DISTINCT PT.PERSON_ID
        FROM PERSON_TRAINING PT
        JOIN MYLEARNING_TRAINING_CODE MTC
          ON PT.TRAINING_CODE = MTC.COEUS_TRAINING_CODE
        WHERE MTC.COEUS_TRAINING_CODE = '20'
          AND PT.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(), INTERVAL 5 YEAR)
    ),
    TrainingStatus2 AS (
        SELECT DISTINCT PT.PERSON_ID
        FROM PERSON_TRAINING PT
        JOIN MYLEARNING_TRAINING_CODE MTC
          ON PT.TRAINING_CODE = MTC.COEUS_TRAINING_CODE
        WHERE MTC.COEUS_TRAINING_CODE = '4'
          AND PT.DATE_ACKNOWLEDGED >= DATE_SUB(NOW(), INTERVAL 4 YEAR)
    )
     UPDATE EPS_PROPOSAL_PERSONS T1
    JOIN EPS_PROPOSAL T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID
    SET IS_TRAINING_COMPLETED = (
        CASE
            WHEN EXISTS (SELECT 1 FROM TrainingStatus1 TS1 WHERE TS1.PERSON_ID = T1.PERSON_ID)
             AND EXISTS (SELECT 1 FROM TrainingStatus2 TS2 WHERE TS2.PERSON_ID = T1.PERSON_ID)
            THEN 'Completed'
            ELSE 'Pending'
        END
    )
    WHERE T2.STATUS_CODE IN ('1', '3', '9')
      AND T1.PERSON_ID IS NOT NULL
	  AND T2.PROPOSAL_ID = AV_PROPOSAL_ID;
END IF;
SET SQL_SAFE_UPDATES = 1;
    RETURN 1;
END
$$
DELIMITER ;
