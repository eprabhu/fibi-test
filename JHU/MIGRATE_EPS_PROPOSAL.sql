DELIMITER $$
CREATE  PROCEDURE `MIGRATE_EPS_PROPOSAL`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ACTIVITY_TYPE_CODE INT;
DECLARE LI_STATUS_CODE INT;
DECLARE LI_TYPE_CODE INT;
DECLARE LS_AWARD_TYPE_CODE INT;
DECLARE LI_GRANT_CALL_TYPE INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LS_PROPOSAL_CREATE_USER VARCHAR(8);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_IP_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NAME VARCHAR(200);
DECLARE LS_SPONSOR_CODE VARCHAR(6);
DECLARE LS_TITLE VARCHAR(250);
DECLARE LS_PROPOSAL_UPDATE_USER VARCHAR(8);
DECLARE LS_PRIME_SPONSOR_CODE VARCHAR(6);
DECLARE LS_BASE_PROPOSAL_NUMBER VARCHAR(20);
DECLARE LS_PROGRAM_ANNOUNCEMENT_NUMBER VARCHAR(50);
DECLARE LS_CDFA_NUMBER VARCHAR(100);
DECLARE LS_AWARD_NUMBER VARCHAR(255);
DECLARE LS_IS_SUBCONTRACT VARCHAR(1);
DECLARE LS_SPONSOR_PROPOSAL_NUMBER VARCHAR(100);
DECLARE LS_GRANT_CALL_TYPE VARCHAR(10);
DECLARE LS_PROPOSAL_STATUS VARCHAR(200);
DECLARE LS_CHK_START_DATE DATETIME;
DECLARE LS_CHK_END_DATE DATETIME;
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_CREATE_TIMESTAMP DATETIME;
DECLARE LS_SPONSOR_DEADLINE_DATE DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_SOURCE_COUNT1 INT;
DECLARE LI_SOURCE_COUNT2 INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_VALIDATION_STATUS VARCHAR(10);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LS_DELETED_DATA VARCHAR(1);
DECLARE LI_INSERT_ROW_COUNT INT;
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	IF DATA_REFRESH_FLAG = 1 THEN
			-- DELETE FROM migration_validation_matrix WHERE MODULE_NAME IN ('DEVPROPOSAL','EPSKEYINVEST','EPSKEYPERSON','DEVPROPUNITS','DEVPROPKPUNITS');
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE IN ('DEVPROPOSAL','EPSKEYINVEST','EPSKEYPERSON','DEVPROPUNITS','DEVPROPKPUNITS') AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_eps_proposal SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
			UPDATE stage_eps_prop_investigators SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
			UPDATE stage_eps_prop_key_persons SET VALIDATION_STATUS = 'VALID', FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
			UPDATE stage_eps_prop_units SET VALIDATION_STATUS = 'VALID', FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
			UPDATE stage_eps_prop_kp_units SET VALIDATION_STATUS = 'VALID', FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_eps_proposal;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'DEVPROPOSAL';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','DEVPROPOSAL',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','DEVPROPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','DEVPROPKPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','EPSKEYINVEST',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'MIGRATION','EPSKEYPERSON',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_EPS_PROPOSAL_CURSOR CURSOR FOR
	SELECT      MIGRATION_PROP_ID,
				PROPOSAL_NUMBER,
				ACTIVITY_TYPE_CODE,
				CREATE_TIMESTAMP,
				CREATE_USER,
				REQUESTED_END_DATE_INITIAL,
				OWNED_BY_UNIT,
				SPONSOR_CODE,
				SPONSOR_PROPOSAL_NUMBER,
				TITLE,
				REQUESTED_START_DATE_INITIAL,
				PROPOSAL_TYPE_CODE,
				SUBCONTRACT_FLAG,
				DEADLINE_DATE,
				AWARD_TYPE_CODE,
				BASE_PROPOSAL_NUMBER,
				PROGRAM_ANNOUNCEMENT_NUMBER,
				PRIME_SPONSOR_CODE,
				CFDA_NUMBER,
				CURRENT_AWARD_NUMBER,
				NOTICE_OF_OPPORTUNITY_CODE,
				DESCRIPTION,
				UPDATE_TIMESTAMP,
				UPDATE_USER
	FROM stage_eps_proposal WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'DEVPROPOSAL','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_EPS_PROPOSAL_CURSOR;
	MIGRATION_EPS_PROPOSAL_CURSOR_LOOP : 	   LOOP
	FETCH  MIGRATION_EPS_PROPOSAL_CURSOR       INTO    	LI_RECORD_ID,
														LS_PROPOSAL_NUMBER,
														LI_ACTIVITY_TYPE_CODE,
														LS_CREATE_TIMESTAMP,
														LS_PROPOSAL_CREATE_USER,
														LS_CHK_END_DATE,
														LS_UNIT_NUMBER,
														LS_SPONSOR_CODE,
														LS_SPONSOR_PROPOSAL_NUMBER,
														LS_TITLE,
														LS_CHK_START_DATE,
														LI_TYPE_CODE,
														LS_IS_SUBCONTRACT,
														LS_SPONSOR_DEADLINE_DATE,
														LS_AWARD_TYPE_CODE,
														LS_BASE_PROPOSAL_NUMBER,
														LS_PROGRAM_ANNOUNCEMENT_NUMBER,
														LS_PRIME_SPONSOR_CODE,
														LS_CDFA_NUMBER,
														LS_AWARD_NUMBER,
														LI_GRANT_CALL_TYPE,
														LS_PROPOSAL_STATUS,
														LS_UPDATE_TIMESTAMP,
														LS_UPDATE_USER;
	IF DONE1 THEN
		LEAVE MIGRATION_EPS_PROPOSAL_CURSOR_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LS_UNIT_NAME = NULL;
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	eps_proposal_status WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROPOSAL_STATUS)) AND IS_ACTIVE = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog(
			PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'DEVPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid status  :', LS_PROPOSAL_STATUS),'Proposal status is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT STATUS_CODE INTO LI_STATUS_CODE FROM eps_proposal_status WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROPOSAL_STATUS)) AND IS_ACTIVE = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'proposal status',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	stage_eps_prop_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND PRINCIPAL_INVESTIGATOR_FLAG = 'Y' AND VALIDATION_STATUS = 'VALID';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'DEVPROPOSAL','MIGRATION',CONCAT('Only one PI should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'PI check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM
	stage_eps_prop_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND LEAD_UNIT_FLAG = 'Y' AND VALIDATION_STATUS = 'VALID';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'DEVPROPOSAL','MIGRATION',CONCAT('Only one lead unit should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'Lead unit check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND IS_ACTIVE = 'Y';
	IF LI_COUNT =  0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'DEVPROPOSAL','MIGRATION',CONCAT('Invalid unit number :  ', LS_UNIT_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT unit_name INTO LS_UNIT_NAME FROM unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND IS_ACTIVE = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'Before master table insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SET LS_IP_NUMBER = NULL;
	SELECT COUNT(1) INTO LI_COUNT FROM stage_proposal_admin_details WHERE DEV_PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VALIDATION_STATUS <> 'ERROR';
	IF LI_COUNT > 0 THEN
		SELECT INST_PROPOSAL_NUMBER INTO LS_IP_NUMBER FROM stage_proposal_admin_details WHERE DEV_PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VALIDATION_STATUS <> 'ERROR' LIMIT 1;
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		INSERT INTO eps_proposal
		(
			PROPOSAL_ID,
			ABSTRACT_DESC,
			ACTIVITY_TYPE_CODE,
			CREATE_TIMESTAMP,
			CREATE_USER,
			DELIVERABLES,
			DETAILS,
			END_DATE,
			FUNDING_STRATEGY,
			GRANT_HEADER_ID,
			GRANT_TYPE_CODE,
			HOME_UNIT_NAME,
			HOME_UNIT_NUMBER,
			IP_NUMBER,
			RESEARCH_AREA_DESC,
			SPONSOR_CODE,
			SPONSOR_PROPOSAL_NUMBER,
			START_DATE,
			STATUS_CODE,
			SUBMISSION_DATE,
			SUBMIT_USER,
			TITLE,
			TYPE_CODE,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			BUDGET_HEADER_ID,
			INTERNAL_DEADLINE_DATE,
			IS_SUBCONTRACT,
			IS_DOMESTIC_SITE,
			IS_MULTISITE_STUDY,
			IS_ELIGIBLE_CRITERIA_MET,
			EXTERNAL_FUNDING_AGENCY_ID,
			SPONSOR_DEADLINE_DATE,
			MULTI_DISCIPLINARY_DESC,
			AWARD_TYPE_CODE,
			BASE_PROPOSAL_NUMBER,
			PROGRAM_ANNOUNCEMENT_NUMBER,
			PRIME_SPONSOR_CODE,
			CFDA_NUMBER,
			EVALUATION_RECOMMENDATION_CODE,
			APPLICATION_ID,
			CLUSTER_CODE,
			IS_ENDORSED_ONCE,
			PROPOSAL_RANK,
			DURATION,
			AWARD_NUMBER,
			DOCUMENT_STATUS_CODE
		)
		VALUES
		(
			LS_PROPOSAL_NUMBER,
			NULL,
			LI_ACTIVITY_TYPE_CODE,
			LS_CREATE_TIMESTAMP,
			LS_PROPOSAL_CREATE_USER,
			NULL,
			NULL,
			LS_CHK_END_DATE,
			NULL,
			NULL,
			LI_GRANT_CALL_TYPE,
			LS_UNIT_NAME,
			LS_UNIT_NUMBER,
			LS_IP_NUMBER,
			NULL,
			LS_SPONSOR_CODE,
			LS_SPONSOR_PROPOSAL_NUMBER,
			LS_CHK_START_DATE,
			LI_STATUS_CODE,
			NULL,
			NULL,
			LS_TITLE,
			LI_TYPE_CODE,
			LS_UPDATE_TIMESTAMP,
			LS_UPDATE_USER,
			NULL,
			NULL,
			LS_IS_SUBCONTRACT,
			NULL,
			NULL,
			NULL,
			NULL,
			LS_SPONSOR_DEADLINE_DATE,
			NULL,
			LS_AWARD_TYPE_CODE,
			LS_BASE_PROPOSAL_NUMBER,
			LS_PROGRAM_ANNOUNCEMENT_NUMBER,
			LS_PRIME_SPONSOR_CODE,
			LS_CDFA_NUMBER,
			NULL,
			LS_PROPOSAL_NUMBER,
			NULL,
			'N',
			NULL,
			NULL,
			LS_AWARD_NUMBER,
			1
		);
		SET LS_VALIDATION_STATUS = 'SUCCESS';
		SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
		SET LS_CHILD_ERROR = 'N';
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		IF LI_COUNT > 0 THEN
			CALL MIGRATE_EPS_PROP_INV(LS_PROPOSAL_NUMBER,0,FOR_AUDIT,@inv_error_count);
			IF @inv_error_count > 0 THEN
				SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'INVESTIGATORS,');
				SET LS_CHILD_ERROR = 'Y';
			END IF;
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'inv child call end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_key_persons WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		IF LI_COUNT > 0 THEN
			CALL MIGRATE_EPS_PROP_KP(LS_PROPOSAL_NUMBER,0,FOR_AUDIT,@kp_error_count);
			IF @kp_error_count > 0 THEN
				SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE,'KEY PERSONS,');
				SET LS_CHILD_ERROR = 'Y';
			END IF;
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'kp call end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
		IF LS_CHILD_ERROR  = 'Y' THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'DEVPROPOSAL','MIGRATION',CONCAT('Error in the ', LS_CHILD_ERROR_MESSAGE,' for the proposal number :',LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
			SET LS_VALIDATION_STATUS  = 'ERROR';
				DELETE FROM eps_prop_person_units WHERE PROP_PERSON_UNIT_ID IN
				(SELECT FIBI_IDENTIFIER FROM stage_eps_prop_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VALIDATION_STATUS = 'SUCCESS' UNION SELECT FIBI_IDENTIFIER FROM stage_eps_prop_kp_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER  AND VALIDATION_STATUS = 'SUCCESS');
				UPDATE stage_eps_prop_units SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE VALIDATION_STATUS = 'SUCCESS' AND PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
				UPDATE stage_eps_prop_kp_units SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE VALIDATION_STATUS = 'SUCCESS' AND PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
				DELETE FROM eps_proposal_persons WHERE PROPOSAL_PERSON_ID IN
				(SELECT FIBI_IDENTIFIER FROM stage_eps_prop_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VALIDATION_STATUS = 'SUCCESS' AND VALIDATION_STATUS = 'SUCCESS' UNION SELECT FIBI_IDENTIFIER FROM stage_eps_prop_key_persons WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER  AND VALIDATION_STATUS = 'SUCCESS');
				UPDATE stage_eps_prop_investigators SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE VALIDATION_STATUS = 'SUCCESS' AND PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
				UPDATE stage_eps_prop_key_persons SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE VALIDATION_STATUS = 'SUCCESS' AND PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
				DELETE FROM eps_proposal WHERE PROPOSAL_ID = LS_PROPOSAL_NUMBER;
				IF FOR_AUDIT = 1 THEN
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'error in child data. reverting the migration',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
				END IF;
		END IF;
		UPDATE stage_eps_proposal
		SET VALIDATION_STATUS = LS_VALIDATION_STATUS,
		FIBI_IDENTIFIER = CASE  WHEN LS_VALIDATION_STATUS = 'ERROR' THEN -1 ELSE LS_PROPOSAL_NUMBER END
		WHERE MIGRATION_PROP_ID = LI_RECORD_ID;
	ELSE
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT  MIGRATION_INVESTIGATORS_ID,'EPSKEYINVEST','MIGRATION',CONCAT('Parent record failed for proposal number :',LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart' FROM stage_eps_prop_investigators WHERE  PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		UPDATE stage_eps_prop_investigators SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT  MIGRATION_KEY_PERSON_ID,'EPSKEYPERSON','MIGRATION',CONCAT('Parent record failed for proposal number :',LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart' FROM stage_eps_prop_key_persons WHERE  PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		UPDATE stage_eps_prop_key_persons SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT  MIGRATION_EPS_PROP_UNITS_ID,'DEVPROPUNITS','MIGRATION',CONCAT('Parent record failed for proposal number :',LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart' FROM stage_eps_prop_units WHERE  PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		UPDATE stage_eps_prop_units SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		SELECT  MIGRATION_EPS_PROP_KP_UNIT_ID,'DEVPROPKPUNITS','MIGRATION',CONCAT('Parent record failed for proposal number :',LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart' FROM stage_eps_prop_kp_units WHERE  PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		UPDATE stage_eps_prop_kp_units SET VALIDATION_STATUS = 'ERROR',FIBI_IDENTIFIER = -1 WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
		UPDATE stage_eps_proposal
		SET VALIDATION_STATUS = 'ERROR',
		FIBI_IDENTIFIER = -1
		WHERE MIGRATION_PROP_ID = LI_RECORD_ID;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'error in master data. update error in the child table',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
		END IF;
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed processing of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END LOOP MIGRATION_EPS_PROPOSAL_CURSOR_LOOP;
	CLOSE MIGRATION_EPS_PROPOSAL_CURSOR;
	INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','DEVPROPOSAL',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM eps_proposal_id_generator;
	IF LI_COUNT = 0 THEN
		INSERT INTO eps_proposal_id_generator (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROPOSAL_ID),0)+1  FROM eps_proposal));
	ELSE
		UPDATE eps_proposal_id_generator SET NEXT_VAL = (SELECT IFNULL(MAX(PROPOSAL_ID),0)+1  FROM eps_proposal);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM eps_prop_person_id_generator;
	IF LI_COUNT = 0 THEN
		INSERT INTO eps_prop_person_id_generator (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROPOSAL_PERSON_ID),0)+1  FROM eps_proposal_persons));
	ELSE
		UPDATE eps_prop_person_id_generator SET NEXT_VAL = (SELECT IFNULL(MAX(PROPOSAL_PERSON_ID),0)+1  FROM eps_proposal_persons);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM eps_prop_person_unit_id_generator;
	IF LI_COUNT = 0 THEN
		INSERT INTO eps_prop_person_unit_id_generator  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROP_PERSON_UNIT_ID),0) + 1  FROM eps_prop_person_units));
	ELSE
