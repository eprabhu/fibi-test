DELIMITER $$
CREATE DEFINER=`jhufibi`@`%` PROCEDURE `MIGRATE_AWRD_SPL_REVIEW`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_SPECIAL_REVIEW_CODE INT;
DECLARE LI_APPROVAL_TYPE_CODE INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_AWRD_SPL_RVW_ID INT;
DECLARE LI_MAS_AWRD_SPL_RVW_ID INT;
DECLARE LI_MAX_SEQUENCE_NUMBER INT;
DECLARE LI_MASTER_AWARD_ID INT;
DECLARE LI_AWARD_ID INT;
DECLARE LI_SPECIAL_REVIEW_NUMBER INT;
DECLARE LS_PROTOCOL_NUMBER VARCHAR(20);
DECLARE LS_COMMENTS LONGTEXT;
DECLARE LS_APPLICATION_DATE DATETIME;
DECLARE LS_APPROVAL_DATE DATETIME;
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_JHU_AWARD_NUMBER CHAR(10);
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'AWRDSPLRVW' AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_award_special_review SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'AWRDSPLRVW';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','AWRDSPLRVW',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWRD_SPL_REVIEW_CURSOR CURSOR FOR
		SELECT  MIGRATION_AWARD_SPL_RVW_ID,
				MIT_AWARD_NUMBER,
				SEQUENCE_NUMBER,
				SPECIAL_REVIEW_CODE,
				APPROVAL_TYPE_CODE,
				PROTOCOL_NUMBER,
				APPLICATION_DATE,
				APPROVAL_DATE,
				COMMENTS,
				SPECIAL_REVIEW_NUMBER,
				UPDATE_TIMESTAMP,
				UPDATE_USER
		FROM 	stage_award_special_review
		WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'AWRDSPLRVW','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_AWRD_SPL_REVIEW_CURSOR;
			MIGRATION_AWRD_SPL_REVIEW_CURSOR_LOOP :    	LOOP
				FETCH MIGRATION_AWRD_SPL_REVIEW_CURSOR 	INTO     		LI_RECORD_ID,
																		LS_JHU_AWARD_NUMBER,
																		LI_SEQUENCE_NUMBER,
																		LI_SPECIAL_REVIEW_CODE,
																		LI_APPROVAL_TYPE_CODE,
																		LS_PROTOCOL_NUMBER,
																		LS_APPLICATION_DATE,
																		LS_APPROVAL_DATE,
																		LS_COMMENTS,
																		LI_SPECIAL_REVIEW_NUMBER,
																		LS_UPDATE_TIMESTAMP,
																		LS_UPDATE_USER;
					IF DONE1 THEN
						LEAVE MIGRATION_AWRD_SPL_REVIEW_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					SET LI_AWRD_SPL_RVW_ID = -1;
					SET LI_AWARD_ID = -1;
					SET LI_MASTER_AWARD_ID = -1;
					SET LI_MAS_AWRD_SPL_RVW_ID = -1;
					SET LI_MAX_SEQUENCE_NUMBER = -1;
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
					SET LS_AWARD_NUMBER = REPLACE(LS_JHU_AWARD_NUMBER,'-','-00');
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,CONCAT('Changed award number',LS_AWARD_NUMBER),UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					-- award number
					SELECT COUNT(1) INTO LI_COUNT FROM
					award WHERE AWARD_NUMBER = LS_AWARD_NUMBER;
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'AWRDSPLRVW','MIGRATION',CONCAT('Invalid award number :', LS_AWARD_NUMBER),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					ELSE
						SELECT IFNULL(MAX(SEQUENCE_NUMBER),-1) INTO LI_MAX_SEQUENCE_NUMBER FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER;
						IF LI_MAX_SEQUENCE_NUMBER <> -1 THEN
							SELECT AWARD_ID INTO LI_AWARD_ID FROM
							award WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = LI_MAX_SEQUENCE_NUMBER;
						ELSE
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'AWRDSPLRVW','MIGRATION',CONCAT('Invalid sequence number :', LI_MAX_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'after award check',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
					END IF;
					/*IF LS_DATA_ERROR_FLAG = 'N' THEN
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'Before insert',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
						END IF;
						SELECT IFNULL(MAX(AWARD_SPECIAL_REVIEW_ID),0) + 1 INTO LI_AWRD_SPL_RVW_ID FROM award_special_review;
						INSERT INTO award_special_review
						(
							AWARD_SPECIAL_REVIEW_ID,
							AWARD_ID,
							AWARD_NUMBER,
							SEQUENCE_NUMBER,
							SPECIAL_REVIEW_CODE,
							APPROVAL_TYPE_CODE,
							EXPIRATION_DATE,
							PROTOCOL_NUMBER,
							APPLICATION_DATE,
							APPROVAL_DATE,
							COMMENTS,
							UPDATE_USER,
							UPDATE_TIMESTAMP,
							SPECIAL_REVIEW_NUMBER
						)
						VALUES
						(
							LI_AWRD_SPL_RVW_ID,
							LI_AWARD_ID,
							LS_AWARD_NUMBER,
							LI_MAX_SEQUENCE_NUMBER,
							LI_SPECIAL_REVIEW_CODE,
							LI_APPROVAL_TYPE_CODE,
							NULL,
							LS_PROTOCOL_NUMBER,
							LS_APPLICATION_DATE,
							LS_APPROVAL_DATE,
							LS_COMMENTS,
							LS_UPDATE_USER,
							LS_UPDATE_TIMESTAMP,
							LI_SPECIAL_REVIEW_NUMBER
						);
					END IF;*/
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'master logic begin',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
						END IF;
							SET LI_COUNT = -1;
							SELECT COUNT(1) INTO LI_COUNT FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = 0;
							IF LI_COUNT = 0 THEN
								INSERT INTO migration_transaction_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_RECORD_ID,'AWRDSPLRVW','MIGRATION',CONCAT('Invalid master award data with award number :', LS_AWARD_NUMBER,' and the sequence number : 0'),UTC_TIMESTAMP(),'quickstart');
								SET LS_DATA_ERROR_FLAG = 'Y';
							ELSE
								SELECT AWARD_ID INTO LI_MASTER_AWARD_ID FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = 0;
							END IF;
							IF LS_DATA_ERROR_FLAG = 'N' THEN
								SELECT IFNULL(MAX(AWARD_SPECIAL_REVIEW_ID),0) + 1 INTO LI_MAS_AWRD_SPL_RVW_ID FROM award_special_review;
								INSERT INTO award_special_review
								(
									AWARD_SPECIAL_REVIEW_ID,
									AWARD_ID,
									AWARD_NUMBER,
									SEQUENCE_NUMBER,
									SPECIAL_REVIEW_CODE,
									APPROVAL_TYPE_CODE,
									EXPIRATION_DATE,
									PROTOCOL_NUMBER,
									APPLICATION_DATE,
									APPROVAL_DATE,
									COMMENTS,
									UPDATE_USER,
									UPDATE_TIMESTAMP,
									SPECIAL_REVIEW_NUMBER
								)
								VALUES
								(
									LI_MAS_AWRD_SPL_RVW_ID,
									LI_MASTER_AWARD_ID,
									LS_AWARD_NUMBER,
									0,
									LI_SPECIAL_REVIEW_CODE,
									LI_APPROVAL_TYPE_CODE,
									NULL,
									LS_PROTOCOL_NUMBER,
									LS_APPLICATION_DATE,
									LS_APPROVAL_DATE,
									LS_COMMENTS,
									LS_UPDATE_USER,
									LS_UPDATE_TIMESTAMP,
									LI_SPECIAL_REVIEW_NUMBER
								);
							END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'master logic end',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
						END IF;
					END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
							UPDATE stage_award_special_review
							SET VALIDATION_STATUS = 'SUCCESS',
							FIBI_IDENTIFIER = LI_MAS_AWRD_SPL_RVW_ID
							WHERE MIGRATION_AWARD_SPL_RVW_ID = LI_RECORD_ID;
					ELSE
						UPDATE stage_award_special_review
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = -1
						WHERE MIGRATION_AWARD_SPL_RVW_ID = LI_RECORD_ID;
					END IF;
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'Validation end',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
			END LOOP MIGRATION_AWRD_SPL_REVIEW_CURSOR_LOOP;
			CLOSE 	MIGRATION_AWRD_SPL_REVIEW_CURSOR;
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDSPLRVW',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
	END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM award_special_review_id_generator;
	IF LI_COUNT = 0 THEN
	INSERT INTO award_special_review_id_generator  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(AWARD_SPECIAL_REVIEW_ID ),0) + 1  FROM award_special_review));
	ELSE
	UPDATE award_special_review_id_generator   SET NEXT_VAL = (SELECT IFNULL(MAX(AWARD_SPECIAL_REVIEW_ID),0) + 1  FROM award_special_review);
	END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
		COMMIT;
END
$$
DELIMITER ;
