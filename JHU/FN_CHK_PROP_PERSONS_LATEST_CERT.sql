DELIMITER $$
CREATE  FUNCTION `FN_CHK_PROP_PERSONS_LATEST_CERT`(
AV_PROPOSAL_ID INT(10)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT INT;
DECLARE  LI_QUESTIONNAIRE_ID INT;
DECLARE LI_MODULE_CODE INT;
DECLARE LI_SUB_MODULE_CODE INT;
DECLARE LI_KEY_PERSON_COUNT INT;
DECLARE LI_CERT_PERSON_COUNT INT;
SET LI_COUNT = -1;
SELECT COUNT(1) INTO LI_COUNT FROM coeus_sub_module WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER('Proposal Person Certification'));
IF LI_COUNT = 1 THEN
	SELECT MODULE_CODE,SUB_MODULE_CODE INTO LI_MODULE_CODE,
    LI_SUB_MODULE_CODE FROM coeus_sub_module WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER('Proposal Person Certification'));
ELSE
	RETURN 'FALSE';
END IF;
SET LI_COUNT= -1;
SELECT COUNT(1) INTO LI_COUNT FROM quest_usage qu INNER JOIN quest_header qh ON qu.QUESTIONNAIRE_ID = qh.QUESTIONNAIRE_ID
WHERE qu.MODULE_ITEM_CODE = LI_MODULE_CODE AND qu.MODULE_SUB_ITEM_CODE = LI_SUB_MODULE_CODE AND qh.IS_FINAL = 'Y';
IF LI_COUNT = 1 THEN
	SELECT qh.QUESTIONNAIRE_ID INTO LI_QUESTIONNAIRE_ID FROM quest_usage qu INNER JOIN quest_header qh ON qu.QUESTIONNAIRE_ID = qh.QUESTIONNAIRE_ID
	WHERE qu.MODULE_ITEM_CODE = LI_MODULE_CODE AND qu.MODULE_SUB_ITEM_CODE = LI_SUB_MODULE_CODE AND qh.IS_FINAL = 'Y';
ELSE
	RETURN 'FALSE';
END IF;
SET LI_COUNT = -1;
SELECT count(1) INTO LI_COUNT FROM quest_answer_header WHERE
MODULE_ITEM_CODE = LI_MODULE_CODE AND MODULE_SUB_ITEM_CODE = LI_SUB_MODULE_CODE and MODULE_ITEM_KEY = AV_PROPOSAL_ID and
QUESTIONNAIRE_ID <> LI_QUESTIONNAIRE_ID;
	IF LI_COUNT = 0 THEN
		RETURN 'TRUE';
	ELSE
        SELECT COUNT(1) INTO LI_KEY_PERSON_COUNT FROM EPS_PROPOSAL_PERSONS T1
		INNER JOIN EPS_PROP_PERSON_ROLE T2 ON T1.PROP_PERSON_ROLE_ID = T2.PROP_PERSON_ROLE_ID AND T2.CERTIFICATION_REQUIRED = 'Y'
		WHERE T1.PROPOSAL_ID = AV_PROPOSAL_ID AND T1.PERSON_ID IS NOT NULL;
        SELECT count(1) INTO LI_CERT_PERSON_COUNT FROM quest_answer_header WHERE
		MODULE_ITEM_CODE = LI_MODULE_CODE AND MODULE_SUB_ITEM_CODE = LI_SUB_MODULE_CODE and MODULE_ITEM_KEY = AV_PROPOSAL_ID and
		QUESTIONNAIRE_ID = LI_QUESTIONNAIRE_ID AND MODULE_SUB_ITEM_KEY IS NOT NULL;
        IF LI_KEY_PERSON_COUNT = LI_CERT_PERSON_COUNT THEN
			RETURN 'TRUE';
        END IF;
		RETURN 'FALSE';
	END IF;
END
$$
DELIMITER ;
