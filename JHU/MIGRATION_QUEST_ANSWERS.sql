DELIMITER $$
CREATE  PROCEDURE `MIGRATION_QUEST_ANSWERS`(AW_MIGRATED_QUEST_ANS_HEADER_ID INT, AW_QUESTIONNAIRE_ID INT, AW_QUESTIONNAIRE_VERSION_NUMBER INT,AW_QUESTIONNAIRE_COMPLETION_ID VARCHAR(10), DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_STG_QUEST_ANS_HEADER_ID INT;
DECLARE LI_MODULE_ITEM_KEY INT;
DECLARE LI_MIGRATED_QUEST_ANS_HEADER_ID INT;
DECLARE LI_MIGRATED_QUESTION_ID INT;
DECLARE LI_MIGRATED_QUEST_ANS_ID INT;
DECLARE LI_STG_QUEST_ANSWER_ID INT;
DECLARE LI_QUESTION_ID INT;
DECLARE LI_QUESTION_NUMBER INT;
DECLARE LI_QUESTION_VERSION_NUMBER INT;
DECLARE LS_ANSWER VARCHAR(2000);
DECLARE LS_ERROR_MSG VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1) default 'N';
DECLARE LS_VALIDATION_STATUS varchar(10);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
DECLARE LI_DROP_DOWN_QTN  INT DEFAULT 0;
DECLARE LI_ANSWER_NUMBER  INT DEFAULT 0;
DECLARE LS_UPDATE_USER VARCHAR(60);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			INSERT INTO migration_questionnaire_errorlog
						(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_STG_QUEST_ANSWER_ID,'QUEST_ANSWER','MIGRATION',LS_ERROR_MSG,UTC_TIMESTAMP(),'JHU_ADMIN');
		END;
BEGIN
	IF DATA_REFRESH_FLAG = 1 THEN
		SET SQL_SAFE_UPDATES = 0;
			DELETE FROM migration_questionnaire_errorlog WHERE SOURCE_TYPE IN ('QUEST_ANSWER') AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_quest_answer SET VALIDATION_STATUS = 'VALID', MIGRATION_QUEST_ANSWER_ID = NULL WHERE VALIDATION_STATUS = 'ERROR' and MIGRATION_QUEST_ANSWER_ID = -1;
		SET SQL_SAFE_UPDATES = 1;
	END IF;
END;
BEGIN
set sql_safe_updates = 0;
	SELECT IFNULL(MAX(BATCH_ID),0) INTO LI_BATCH_ID FROM migration_transtn_auditlog_header1 WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'QUEST_ANSWER';
END;
		BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_QUEST_ANSWER CURSOR FOR
		select ID
				, QUESTION_ID
                , QUESTION_NUMBER
				, QUESTION_VERSION_NUMBER
				, ANSWER
                , UPDATE_USER
                , UPDATE_TIMESTAMP
		from stage_quest_answer
		WHERE QUESTIONNAIRE_COMPLETION_ID = AW_QUESTIONNAIRE_COMPLETION_ID
        Order by QUESTION_NUMBER;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_QUEST_ANSWER;
		QUEST_ANSWER_LOOP: LOOP
		FETCH CUR_QUEST_ANSWER INTO LI_STG_QUEST_ANSWER_ID
									, LI_QUESTION_ID
                                    , LI_QUESTION_NUMBER
									, LI_QUESTION_VERSION_NUMBER
									, LS_ANSWER
                                    , LS_UPDATE_USER
                                    , LS_UPDATE_TIMESTAMP;
		IF DONE1 THEN
			LEAVE QUEST_ANSWER_LOOP;
		END IF;
        SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_quest_answer WHERE QUESTIONNAIRE_COMPLETION_ID = AW_QUESTIONNAIRE_COMPLETION_ID;
				SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
							VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'Migration started',UTC_TIMESTAMP(),AW_QUESTIONNAIRE_COMPLETION_ID);*/
				/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'Line 102',UTC_TIMESTAMP(),LI_QUESTION_ID);	*/
                select COUNT(*) INTO LI_COUNT
				from stage_quest_questions
				where QUESTION_ID = LI_QUESTION_ID
                and QUESTION_NUMBER = LI_QUESTION_NUMBER
				and QUESTION_VERSION_NUMBER = LI_QUESTION_VERSION_NUMBER
                and QUESTIONNAIRE_ID = AW_QUESTIONNAIRE_ID
                and QUESTIONNAIRE_VERSION_NUMBER = AW_QUESTIONNAIRE_VERSION_NUMBER
				AND VALIDATION_STATUS = 'SUCCESS';
			IF LI_COUNT <> 1 THEN
				INSERT INTO migration_questionnaire_errorlog (PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_STG_QUEST_ANSWER_ID,'QUEST_ANSWER','MIGRATION',CONCAT('Invalid question id: ',LI_QUESTION_ID,' of Questionnaire: ',AW_QUESTIONNAIRE_ID ),UTC_TIMESTAMP(),'JHU_ADMIN');
                 UPDATE stage_quest_answer set MIGRATION_QUEST_ANSWER_ID = -1, VALIDATION_STATUS ='ERROR', UPDATE_TIMESTAMP = UTC_TIMESTAMP() where ID = LI_STG_QUEST_ANSWER_ID;
                 /*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'Line 115',UTC_TIMESTAMP(),LI_QUESTION_ID);*/
				ITERATE QUEST_ANSWER_LOOP;
			ELSE
								select MIGRATED_QUESTION_ID into LI_MIGRATED_QUESTION_ID
								from stage_quest_questions
								where QUESTION_ID = LI_QUESTION_ID
                                and QUESTION_NUMBER = LI_QUESTION_NUMBER
								and QUESTION_VERSION_NUMBER = LI_QUESTION_VERSION_NUMBER
                                and QUESTIONNAIRE_ID = AW_QUESTIONNAIRE_ID
                                and QUESTIONNAIRE_VERSION_NUMBER = AW_QUESTIONNAIRE_VERSION_NUMBER
                                and validation_status = 'SUCCESS';
                                select count(*) INTO LI_DROP_DOWN_QTN from quest_question where question_id = LI_MIGRATED_QUESTION_ID and LOOKUP_TYPE like 'ARG_VALUE_LOOKUP%';
                                IF LI_DROP_DOWN_QTN = 0 THEN
										SET LI_ANSWER_NUMBER = 1;
                                ELSE
										SET LI_ANSWER_NUMBER = 0;
                                END IF;
			END IF;
				/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'LINE 132',UTC_TIMESTAMP(),LI_QUESTION_ID);*/
				select IFNULL(MAX(QUESTIONNAIRE_ANSWER_ID),0)+1 INTO LI_MIGRATED_QUEST_ANS_ID FROm  quest_answer;
								INSERT INTO quest_answer(
													QUESTIONNAIRE_ANSWER_ID
													, QUESTIONNAIRE_ANS_HEADER_ID
													, QUESTION_ID
													, OPTION_NUMBER
													, ANSWER_NUMBER
													, ANSWER
													, ANSWER_LOOKUP_CODE
													, EXPLANATION
													, UPDATE_TIMESTAMP
													, UPDATE_USER
											)VALUES(
													LI_MIGRATED_QUEST_ANS_ID
													, AW_MIGRATED_QUEST_ANS_HEADER_ID
													, LI_MIGRATED_QUESTION_ID
													, NULL
													, 1
													, case LS_ANSWER when 'Y' then 'Yes' when 'N' then 'No' when 'X' then 'NA' else LS_ANSWER end
													, NULL
													, NULL
													, LS_UPDATE_TIMESTAMP
													, LS_UPDATE_USER
											);
				update stage_quest_answer set VALIDATION_STATUS= 'SUCCESS', MIGRATION_QUEST_ANSWER_ID = LI_MIGRATED_QUEST_ANS_ID, UPDATE_TIMESTAMP = UTC_TIMESTAMP() where ID = LI_STG_QUEST_ANSWER_ID;
					/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'LINE 162',UTC_TIMESTAMP(),LI_QUESTION_ID);*/
					IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
					IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
						INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
						VALUES (CONCAT('Migrated ',LI_TOTAL_PROCESSED_DATA_COUNT,' records of Questionnaire Answers'),UTC_TIMESTAMP());
						SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
					END IF;
				END IF ;
				/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER)
													VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'Completed execution ',UTC_TIMESTAMP(),LI_QUESTION_ID);*/
					set LI_COUNT = NULL;
					set LI_STG_QUEST_ANSWER_ID = NULL;
					set LI_QUESTION_ID = NULL;
					set LI_QUESTION_VERSION_NUMBER = NULL;
					set LS_ANSWER = NULL;
				END LOOP;
				CLOSE CUR_QUEST_ANSWER;
				/*INSERT INTO migration_transtn_auditlog_details1 (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','QUEST_ANSWER',LI_BATCH_ID,'Exit answer cursor',UTC_TIMESTAMP(),LI_QUESTION_ID);*/
			INSERT INTO migration_qtn_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME)
					VALUES (CONCAT('Migrated total records ( ', LI_TOTAL_DATA_COUNT,' ) of Questionnaire Answers'),UTC_TIMESTAMP()),('Migration completed successfully',UTC_TIMESTAMP());
			END;
		set sql_safe_updates = 1;
END
$$
DELIMITER ;
