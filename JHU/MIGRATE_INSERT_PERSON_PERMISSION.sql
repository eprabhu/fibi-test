DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_INSERT_PERSON_PERMISSION`()
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_PROP_PERMISSION_ID INT;
DECLARE LI_PERMISSION_ROLE_ID INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LI_COUNT INT;
DECLARE LS_PERSON_ID VARCHAR(40);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LS_DATA_AVAILABILITY VARCHAR(1);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	SET LS_DATA_AVAILABILITY = 'N';
	SET LI_COUNT = -1;
	SELECT COUNT(*) INTO LI_COUNT FROM role WHERE TRIM(UPPER(ROLE_NAME)) = TRIM(UPPER('Proposal Aggregator'));
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'PERSONROLE','MIGRATION',CONCAT('Invalid role : Proposal Aggregator'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_AVAILABILITY = 'Y';
	ELSE
		SELECT ROLE_ID INTO LI_PERMISSION_ROLE_ID FROM role WHERE TRIM(UPPER(ROLE_NAME)) = TRIM(UPPER('Proposal Aggregator'));
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
IF LS_DATA_AVAILABILITY = 'N' THEN
	BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE 	MIGRATION_EPS_PROP_PER_ROLE CURSOR FOR
		SELECT 		PROPOSAL_PERSON_ID,
					PERSON_ID,
					PROPOSAL_ID,
					UPDATE_TIMESTAMP,
					UPDATE_USER
		FROM eps_proposal_persons WHERE PERSON_ID IS NOT NULL AND PI_FLAG = 'Y';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
				GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
				SELECT @full_error INTO LS_ERROR;
				INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
				VALUES  (LI_RECORD_ID,'PERSONROLE','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
				SET LS_DATA_ERROR_FLAG = 'Y';
		END;
		OPEN MIGRATION_EPS_PROP_PER_ROLE;
		MIGRATION_EPS_PROP_PER_ROLE_LOOP      :   	LOOP
		FETCH MIGRATION_EPS_PROP_PER_ROLE 			INTO 		LI_RECORD_ID,
																LS_PERSON_ID,
																LI_PROPOSAL_ID,
																LS_UPDATE_TIMESTAMP,
																LS_UPDATE_USER;
			IF DONE1 THEN
				LEAVE MIGRATION_EPS_PROP_PER_ROLE_LOOP;
			END IF;
			SET LS_DATA_ERROR_FLAG = 'N';
			SET LI_PROP_PERMISSION_ID = -1;
			SET LI_COUNT = -1;
			SELECT COUNT(1) INTO LI_COUNT FROM eps_proposal_person_roles
			WHERE PROPOSAL_ID = LI_PROPOSAL_ID AND PERSON_ID = LS_PERSON_ID AND ROLE_ID = LI_PERMISSION_ROLE_ID;
			IF LI_COUNT > 0 THEN
				SET LS_DATA_ERROR_FLAG = 'Y';
			END IF;
			IF LS_DATA_ERROR_FLAG = 'N' THEN
				SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0) + 1 INTO LI_PROP_PERMISSION_ID
				FROM eps_proposal_person_roles;
				INSERT INTO  eps_proposal_person_roles
				(
					PROPOSAL_PERSON_ROLE_ID,
					PROPOSAL_ID,
					PERSON_ID,
					ROLE_ID,
					UPDATE_TIMESTAMP,
					UPDATE_USER
				)
				VALUES
				(
					LI_PROP_PERMISSION_ID,
					LI_PROPOSAL_ID,
					LS_PERSON_ID,
					LI_PERMISSION_ROLE_ID,
					LS_UPDATE_TIMESTAMP,
					LS_UPDATE_USER
				);
			END IF;
		END LOOP MIGRATION_EPS_PROP_PER_ROLE_LOOP;
		CLOSE  MIGRATION_EPS_PROP_PER_ROLE;
	END;
END IF;
SET LI_COUNT = -1;
SELECT COUNT(*) INTO LI_COUNT FROM eps_prop_person_role_id_generator;
IF LI_COUNT = 0 THEN
	INSERT INTO eps_prop_person_role_id_generator   (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0) + 1  FROM eps_proposal_person_roles));
ELSE
	UPDATE eps_prop_person_role_id_generator    SET NEXT_VAL = (SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0) + 1  FROM eps_proposal_person_roles);
END IF;
INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
SET SQL_SAFE_UPDATES = 1;
SET FOREIGN_KEY_CHECKS = 1;
COMMIT;
END
$$
DELIMITER ;
