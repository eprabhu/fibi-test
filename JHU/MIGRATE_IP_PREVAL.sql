DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_IP_PREVAL`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_ACTIVITY_TYPE_CODE INT;
DECLARE LI_STATUS_CODE INT;
DECLARE LI_TYPE_CODE INT;
DECLARE LS_AWARD_TYPE_CODE INT;
DECLARE LI_PI_COUNT INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_GRANT_TYPE_CODE INT;
DECLARE LI_MAX_SEQUENCE INT;
DECLARE LI_MAX_LEAD_UNIT INT;
DECLARE LI_MAX_PI INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_CHK_START_DATE DATETIME;
DECLARE LS_CHK_END_DATE DATETIME;
DECLARE LS_SPONSOR_CODE VARCHAR(6);
DECLARE LS_TITLE VARCHAR(250);
DECLARE LS_PRIME_SPONSOR_CODE VARCHAR(6);
DECLARE LS_GRANT_CALL_TYPE VARCHAR(10);
DECLARE LS_DEV_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_UNIT_NUMBER VARCHAR(8);
DECLARE LS_PROPOSAL_STATUS VARCHAR(200);
DECLARE LS_MAX_SEQUENCE_DATA VARCHAR(1);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_CHILD_ERROR_MESSAGE VARCHAR(500);
DECLARE LS_CHILD_ERROR VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE IN ('IPPROPOSAL','INSTPROPKEYINVEST','INSTPROPUNITS','INSTPROPKEYPERSON','INSTPROPKPUNITS') AND ERROR_TYPE = 'VALIDATION';
				UPDATE stage_proposal SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
				UPDATE stage_proposal_investigators SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
				UPDATE stage_proposal_units SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
				UPDATE stage_proposal_key_persons SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
				UPDATE stage_proposal_key_person_units SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_proposal;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'IPPROPOSAL';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'VALIDATION','IPPROPOSAL',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','INSTPROPKEYINVEST',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','INSTPROPUNITS',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','INSTPROPKEYPERSON',UTC_TIMESTAMP()),
				(LI_BATCH_ID,'VALIDATION','INSTPROPKPUNITS',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_INST_PROPOSAL_CURSOR CURSOR FOR
		SELECT  MIGRATION_PROPOSAL_ID,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				PROPOSAL_TYPE_CODE,
				STATUS_CODE,
				TITLE,
				SPONSOR_CODE,
				ACTIVITY_TYPE_CODE,
				REQUESTED_END_DATE_TOTAL,
				REQUESTED_START_DATE_TOTAL,
				AWARD_TYPE_CODE,
				PRIME_SPONSOR_CODE,
				NOTICE_OF_OPPORTUNITY_CODE,
				DESCRIPTION
		FROM 	stage_proposal
		WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_INST_PROPOSAL_CURSOR;
			 MIGRATION_INST_PROPOSAL_CURSOR_LOOP :   LOOP
				FETCH MIGRATION_INST_PROPOSAL_CURSOR INTO     	LI_RECORD_ID,
																LS_PROPOSAL_NUMBER,
																LI_SEQUENCE_NUMBER,
																LI_TYPE_CODE,
																LI_STATUS_CODE,
																LS_TITLE,
																LS_SPONSOR_CODE,
																LI_ACTIVITY_TYPE_CODE,
																LS_CHK_END_DATE,
																LS_CHK_START_DATE,
																LS_AWARD_TYPE_CODE,
																LS_PRIME_SPONSOR_CODE,
																LI_GRANT_TYPE_CODE,
																LS_PROPOSAL_STATUS;
					IF DONE1 THEN
						LEAVE MIGRATION_INST_PROPOSAL_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					SET LS_MAX_SEQUENCE_DATA = 'N';
					SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'Validation start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_SEQUENCE FROM stage_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER;
					IF LI_MAX_SEQUENCE = LI_SEQUENCE_NUMBER THEN
						SET LS_MAX_SEQUENCE_DATA = 'Y';
					ELSE
						SET LS_MAX_SEQUENCE_DATA = 'N';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'fetch max sequence',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					proposal_type  WHERE TYPE_CODE = LI_TYPE_CODE AND IS_ACTIVE = 'Y';
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid proposal type :', LI_TYPE_CODE),'Proposal type is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after proposal type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					proposal_status  WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROPOSAL_STATUS)) AND IS_ACTIVE = 'Y';
					IF LI_COUNT <> 1 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid proposal status :', LS_PROPOSAL_STATUS),'Proposal status is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after proposal status check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LI_GRANT_TYPE_CODE IS NOT NULL THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						grant_call_type WHERE GRANT_TYPE_CODE = LI_GRANT_TYPE_CODE AND IS_ACTIVE = 'Y';
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid grant type : ',LI_GRANT_TYPE_CODE),'Grant type code is mandatory'),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after grant type  check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LS_SPONSOR_CODE IS NOT NULL THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						sponsor WHERE SPONSOR_CODE = LS_SPONSOR_CODE;
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',CONCAT('Invalid sponsor code :  ', LS_SPONSOR_CODE) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after proposal sponsor check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LS_MAX_SEQUENCE_DATA = 'Y' THEN
						IF LS_TITLE IS NULL  THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION','Proposal title is mandatory and cannot be NULL',UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after proposal title check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
						IF LS_CHK_START_DATE IS NULL  THEN
								INSERT INTO migration_transaction_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION','Start date is mandatory for a proposal and cannot be NULL',UTC_TIMESTAMP(),'quickstart');
								SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after start date check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
						IF LS_CHK_END_DATE IS NULL  THEN
								INSERT INTO migration_transaction_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION','End date is mandatory for a proposal and cannot be NULL',UTC_TIMESTAMP(),'quickstart');
								SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after end date check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
						IF LS_CHK_END_DATE IS NOT NULL AND LS_CHK_START_DATE IS NOT NULL AND LS_CHK_END_DATE < LS_CHK_START_DATE  THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION','End date cannot be less than that of start date',UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after start and end date check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
						SET LI_MAX_LEAD_UNIT = -1;
						SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_LEAD_UNIT FROM stage_proposal_units
						WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= LI_SEQUENCE_NUMBER;
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM stage_proposal_units
						WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_LEAD_UNIT AND LEAD_UNIT_FLAG = 'Y';
						IF LI_COUNT = 1 THEN
							SELECT UNIT_NUMBER INTO LS_UNIT_NUMBER FROM
							stage_proposal_units WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_LEAD_UNIT AND LEAD_UNIT_FLAG = 'Y';
							SET LI_COUNT = -1;
							SELECT COUNT(1) INTO LI_COUNT FROM
							unit WHERE UNIT_NUMBER = LS_UNIT_NUMBER AND IS_ACTIVE = 'Y';
							IF LI_COUNT = 0 THEN
								INSERT INTO migration_transaction_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid unit number :  ', LS_UNIT_NUMBER),'Lead unit is mandatory and cannot be NULL') ,UTC_TIMESTAMP(),'quickstart');
								SET LS_DATA_ERROR_FLAG = 'Y';
							END IF;
						ELSE
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (
							LI_RECORD_ID,
							'IPPROPOSAL',
							'VALIDATION',
							CASE  WHEN LI_COUNT = 0 THEN 'Lead unit is mandatory and cannot be NULL' ELSE CONCAT('More than one lead unit is available for the proposal number : ',LS_PROPOSAL_NUMBER,' and the sequence number : ',LI_SEQUENCE_NUMBER) END,
							UTC_TIMESTAMP(),
							'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'lead unit check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
						SET LI_MAX_PI = -1;
						SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_PI FROM stage_proposal_investigators
						WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= LI_SEQUENCE_NUMBER;
						SET LI_PI_COUNT = -1;
						SELECT COUNT(1) INTO LI_PI_COUNT FROM
						stage_proposal_investigators WHERE
						PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_PI AND PRINCIPAL_INVESTIGATOR_FLAG = 'Y';
						IF LI_PI_COUNT <> 1 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',CONCAT('Only one PI should be present for the proposal with the proposal number :  ', LS_PROPOSAL_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after PI check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after max sequence check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM
					activity_type WHERE ACTIVITY_TYPE_CODE = LI_ACTIVITY_TYPE_CODE AND IS_ACTIVE = 'Y';
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',IFNULL(CONCAT('Invalid activity type  :', LI_ACTIVITY_TYPE_CODE),'Activity type is mandatory and cannot be NULL'),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'activity type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LS_PRIME_SPONSOR_CODE IS NOT NULL THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						sponsor WHERE SPONSOR_CODE = LS_PRIME_SPONSOR_CODE;
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',CONCAT('Invalid prime sponsor code:  ', LS_PRIME_SPONSOR_CODE) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after prime sponsor check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LS_AWARD_TYPE_CODE IS NOT NULL THEN
						SET LI_COUNT = -1;
						SELECT COUNT(1) INTO LI_COUNT FROM
						award_type  WHERE AWARD_TYPE_CODE = LS_AWARD_TYPE_CODE AND IS_ACTIVE = 'Y';
						IF LI_COUNT = 0 THEN
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',CONCAT('Invalid award type :  ', LS_AWARD_TYPE_CODE) ,UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after award type check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					SET LS_CHILD_ERROR_MESSAGE = 'CHILD TABLES : ';
					SET LS_CHILD_ERROR = 'N';
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM stage_proposal_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
					IF LI_COUNT > 0 THEN
						CALL MIGRATE_IP_INV_PREVAL(LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER,FOR_AUDIT,@inv_error_count);
					    IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,ifnull(concat(@inv_error_count,': @inv_error_count and LI_SEQUENCE_NUMBER: ', LI_SEQUENCE_NUMBER),'@inv_error_count is null'),UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
                        IF @inv_error_count > 0 THEN
							SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE ,'INVESTIGATORS, ');
							SET LS_CHILD_ERROR = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after INV call',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					SELECT COUNT(1) INTO LI_COUNT FROM stage_proposal_key_persons WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_SEQUENCE_NUMBER;
					IF LI_COUNT > 0 THEN
						CALL MIGRATE_IP_KEY_PERSONS_PREVAL(LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER,FOR_AUDIT,@kp_error_count);
						IF @kp_error_count > 0 THEN
							SET LS_CHILD_ERROR_MESSAGE = CONCAT(LS_CHILD_ERROR_MESSAGE, 'KEY PERSONS, ');
							SET LS_CHILD_ERROR = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after key person check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LS_CHILD_ERROR = 'Y' THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'IPPROPOSAL','VALIDATION',CONCAT('Error in the ',LS_CHILD_ERROR_MESSAGE, ' for the proposal number : ', LS_PROPOSAL_NUMBER,' and the sequence number : ', LI_SEQUENCE_NUMBER) ,UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						UPDATE stage_proposal
						SET VALIDATION_STATUS = 'VALID',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROPOSAL_ID  = LI_RECORD_ID;
					ELSE
						UPDATE stage_proposal
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = NULL
						WHERE MIGRATION_PROPOSAL_ID  = LI_RECORD_ID;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('VALIDATION','IPPROPOSAL',LI_BATCH_ID,'after update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
					END IF;
					IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
						IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
							INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed validation of ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
							SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
