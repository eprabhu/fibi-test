DELIMITER $$
CREATE DEFINER=`jhufibi`@`%` FUNCTION `FN_HAS_FON`(
  AV_PROPOSAL_ID   int(10)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT int;
DECLARE RETURN_STRING VARCHAR(5) DEFAULT 'FALSE';
 SELECT COUNT(*)
 INTO LI_COUNT
 FROM eps_proposal p
 WHERE p.PROPOSAL_ID=AV_PROPOSAL_ID
 AND  (p.program_announcement_number IS NOT NULL
 AND   LENGTH(TRIM(p.program_announcement_number)) > 0);
IF LI_COUNT > 0 THEN
   SET RETURN_STRING = 'TRUE';
END IF;
RETURN RETURN_STRING;
END
$$
DELIMITER ;
