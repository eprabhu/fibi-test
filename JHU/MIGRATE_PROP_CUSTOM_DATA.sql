DELIMITER $$
CREATE  PROCEDURE `MIGRATE_PROP_CUSTOM_DATA`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LI_CUSTOM_DATA_ID INT;
DECLARE LI_CUSTOM_DATA_ELEMENTS_ID INT;
DECLARE LI_COLUMN_ID INT;
DECLARE LI_COLUMN_VERSION_NUMBER INT;
DECLARE LI_MODULE_ITEM_CODE INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_PROPOSAL_ID INT;
DECLARE LI_IP_PROPOSAL_NUMBER INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_COLUMN_NAME VARCHAR(30);
DECLARE LS_COLUMN_VALUE VARCHAR(2000);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LI_PARENT_RECORD_ID INT;
DECLARE LI_MAX_SEQUENCE_NUMBER INT;
DECLARE LS_PARENT_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LI_PARENT_SEQ_NUMBER INT;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_PARENT_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LS_DATA_AVAILABLE_FLAG VARCHAR(1);
DECLARE LS_DATA_EXISTS VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
				DELETE FROM migration_validation_matrix WHERE MODULE_NAME = 'IPPROPCUSTOM';
				DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'IPPROPCUSTOM' AND ERROR_TYPE = 'MIGRATION';
				UPDATE stage_proposal_custom_data SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_proposal_custom_data;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'IPPROPCUSTOM';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','IPPROPCUSTOM',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM coeus_module WHERE UPPER(DESCRIPTION) = UPPER('Institute Proposal') AND IS_ACTIVE = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'IPPROPCUSTOM','MIGRATION',CONCAT('Invalid module item code : Institute Proposal'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT MODULE_CODE INTO LI_MODULE_ITEM_CODE FROM coeus_module WHERE UPPER(DESCRIPTION) = UPPER('Institute Proposal') AND IS_ACTIVE = 'Y';
	END IF;
END;
IF LS_DATA_ERROR_FLAG = 'N' THEN
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE MIGRATION_IP_CURSOR CURSOR FOR
	SELECT    	MIGRATION_PROPOSAL_ID,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				FIBI_IDENTIFIER
	FROM  stage_proposal  WHERE PROPOSAL_NUMBER IN (SELECT DISTINCT PROPOSAL_NUMBER FROM stage_proposal_custom_data WHERE VALIDATION_STATUS = 'VALID')
	AND VALIDATION_STATUS = 'SUCCESS' AND FIBI_IDENTIFIER IS NOT NULL AND FIBI_IDENTIFIER <> -1 ORDER BY PROPOSAL_NUMBER;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_PARENT_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATION_IP_CURSOR;
	MIGRATION_INST_PROPOSAL_CURSOR_LOOP       : LOOP
	FETCH MIGRATION_IP_CURSOR        			INTO        LI_PARENT_RECORD_ID,
															LS_PARENT_PROPOSAL_NUMBER,
															LI_PARENT_SEQ_NUMBER,
															LI_PROPOSAL_ID;
	IF DONE1 THEN
		LEAVE MIGRATION_INST_PROPOSAL_CURSOR_LOOP;
	END IF;
	SET LS_PARENT_DATA_ERROR_FLAG = 'N';
	SET LI_IP_PROPOSAL_NUMBER = -1;
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PARENT_PROPOSAL_NUMBER,LI_PARENT_SEQ_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM proposal WHERE PROPOSAL_ID = LI_PROPOSAL_ID;
	IF LI_COUNT = 0 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'IPPROPOSAL','MIGRATION',CONCAT('Invalid proposal number : ',LS_PARENT_PROPOSAL_NUMBER,' and the sequence number : ', LI_PARENT_SEQ_NUMBER,' in the proposal admin details'),UTC_TIMESTAMP(),'quickstart');
		SET LS_PARENT_DATA_ERROR_FLAG = 'Y';
		-- SELECT PROPOSAL_ID INTO LI_IP_PROPOSAL_NUMBER FROM proposal WHERE PROPOSAL_NUMBER = LS_PARENT_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_PARENT_SEQ_NUMBER;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'after IP check',UTC_TIMESTAMP(),LS_PARENT_PROPOSAL_NUMBER,LI_PARENT_SEQ_NUMBER);
	END IF;
	IF LS_PARENT_DATA_ERROR_FLAG = 'N' THEN
		SELECT IFNULL(MAX(SEQUENCE_NUMBER),0) INTO LI_MAX_SEQUENCE_NUMBER FROM stage_proposal_custom_data
		WHERE PROPOSAL_NUMBER = LS_PARENT_PROPOSAL_NUMBER AND SEQUENCE_NUMBER <= LI_PARENT_SEQ_NUMBER AND VALIDATION_STATUS <> 'ERROR';
		IF LI_MAX_SEQUENCE_NUMBER = 0 THEN
			SET LS_DATA_AVAILABLE_FLAG = 'N';
		ELSE
			SET LS_DATA_AVAILABLE_FLAG = 'Y';
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'fetch max sequence number',UTC_TIMESTAMP(),LS_PARENT_PROPOSAL_NUMBER,LI_PARENT_SEQ_NUMBER);
		END IF;
		IF LS_DATA_AVAILABLE_FLAG = 'Y' THEN
		BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_PROP_CUSTOM_DATA	CURSOR FOR
		SELECT     MIGRATION_PROP_CUSTOM_DATA_ID,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				COLUMN_NAME,
				COLUMN_VALUE,
				UPDATE_TIMESTAMP,
				UPDATE_USER
		FROM  stage_proposal_custom_data   WHERE PROPOSAL_NUMBER = LS_PARENT_PROPOSAL_NUMBER AND SEQUENCE_NUMBER = LI_MAX_SEQUENCE_NUMBER AND  VALIDATION_STATUS <> 'ERROR';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPCUSTOM','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
		OPEN MIGRATION_PROP_CUSTOM_DATA;
		MIGRATION_PROP_CUSTOM_DATA_LOOP      : 		LOOP
		FETCH MIGRATION_PROP_CUSTOM_DATA       		INTO       	LI_RECORD_ID,
																LS_PROPOSAL_NUMBER,
																LI_SEQUENCE_NUMBER,
																LS_COLUMN_NAME,
																LS_COLUMN_VALUE,
																LS_UPDATE_TIMESTAMP,
																LS_UPDATE_USER;
		IF DONE1 THEN
			LEAVE MIGRATION_PROP_CUSTOM_DATA_LOOP;
		END IF;
		SET LS_DATA_ERROR_FLAG = 'N';
		SET LI_CUSTOM_DATA_ID = -1;
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'Migration start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM custom_data_elements WHERE UPPER(TRIM(CUSTOM_ELEMENT_NAME)) = UPPER(TRIM(LS_COLUMN_NAME));
		IF LI_COUNT = 1 THEN
			SELECT CUSTOM_DATA_ELEMENTS_ID,COLUMN_ID,COLUMN_VERSION_NUMBER INTO LI_CUSTOM_DATA_ELEMENTS_ID,LI_COLUMN_ID,LI_COLUMN_VERSION_NUMBER
			FROM custom_data_elements WHERE UPPER(TRIM(CUSTOM_ELEMENT_NAME)) = UPPER(TRIM(LS_COLUMN_NAME));
		ELSE
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'IPPROPCUSTOM','MIGRATION',CONCAT('Invalid custom element : ', LS_COLUMN_NAME),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'after custom data elements check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
		-- Checking already exists or NOT
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM custom_data WHERE MODULE_ITEM_CODE = LI_MODULE_ITEM_CODE AND MODULE_ITEM_KEY = LI_PROPOSAL_ID AND CUSTOM_DATA_ELEMENTS_ID = LI_CUSTOM_DATA_ELEMENTS_ID;
		IF LI_COUNT <> 0 THEN
			--  INSERT INTO migration_transaction_errorlog
			-- 	 (PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			--  VALUES  (LI_RECORD_ID,'IPPROPCUSTOM','MIGRATION',CONCAT('Custom data already exists for the proposal  : ', LI_PROPOSAL_ID, ' for the element id : ', LI_CUSTOM_DATA_ELEMENTS_ID),UTC_TIMESTAMP(),'quickstart');
			 SET LS_DATA_ERROR_FLAG = 'Y';
			 SET LS_DATA_EXISTS = 'Y';
		END IF;
		IF LS_DATA_ERROR_FLAG = 'N' THEN
			SELECT IFNULL(MAX(CUSTOM_DATA_ID),0) + 1 INTO LI_CUSTOM_DATA_ID
			FROM custom_data;
			INSERT INTO   custom_data
			(
				CUSTOM_DATA_ID,
				CUSTOM_DATA_ELEMENTS_ID,
				MODULE_ITEM_CODE,
				MODULE_SUB_ITEM_CODE,
				MODULE_ITEM_KEY,
				MODULE_SUB_ITEM_KEY,
				VALUE,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				COLUMN_ID,
				COLUMN_VERSION_NUMBER,
				DESCRIPTION
			)
			VALUES
			(
				LI_CUSTOM_DATA_ID,
				LI_CUSTOM_DATA_ELEMENTS_ID,
				LI_MODULE_ITEM_CODE,
				0,
				LI_PROPOSAL_ID,
				0,
				LS_COLUMN_VALUE,
				LS_UPDATE_TIMESTAMP,
				LS_UPDATE_USER,
				LI_COLUMN_ID,
				LI_COLUMN_VERSION_NUMBER,
				NULL
			);
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
			END IF;
		END IF;
		IF LS_DATA_ERROR_FLAG = 'N' THEN
			UPDATE stage_proposal_custom_data
			SET VALIDATION_STATUS = 'SUCCESS',
			FIBI_IDENTIFIER = LI_CUSTOM_DATA_ID
			WHERE MIGRATION_PROP_CUSTOM_DATA_ID = LI_RECORD_ID;
			IF FOR_AUDIT = 1 THEN
				INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'after success update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
			END IF;
		ELSE
			IF LS_DATA_EXISTS = 'N' THEN
				UPDATE stage_proposal_custom_data
				SET VALIDATION_STATUS = 'ERROR',
				FIBI_IDENTIFIER = -1
				WHERE MIGRATION_PROP_CUSTOM_DATA_ID = LI_RECORD_ID;
				IF FOR_AUDIT = 1 THEN
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'after error update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
				END IF;
			END IF;
		END IF;
		IF FOR_AUDIT = 1 THEN
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'Migration end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER,LI_SEQUENCE_NUMBER);
		END IF;
		END LOOP MIGRATION_PROP_CUSTOM_DATA_LOOP;
		CLOSE MIGRATION_PROP_CUSTOM_DATA;
		END;
	END IF;
		END IF;
		IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
			IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
				INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed processing of  ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
				SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
			END IF;
		END IF ;
		END LOOP MIGRATION_INST_PROPOSAL_CURSOR_LOOP;
		CLOSE MIGRATION_IP_CURSOR;
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER,SEQUENCE_NUMBER) VALUES ('MIGRATION','IPPROPCUSTOM',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL,NULL);
END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM custom_data_id_generator;
	IF LI_COUNT = 0 THEN
	INSERT INTO custom_data_id_generator  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(CUSTOM_DATA_ID),0) + 1  FROM custom_data));
	ELSE
	UPDATE custom_data_id_generator   SET NEXT_VAL = (SELECT IFNULL(MAX(CUSTOM_DATA_ID),0) + 1  FROM custom_data);
	END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	COMMIT;
END IF;
END
$$
DELIMITER ;
