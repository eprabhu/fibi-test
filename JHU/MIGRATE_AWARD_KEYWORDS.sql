						END IF;
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						UPDATE stage_award_keywords
						SET VALIDATION_STATUS = 'SUCCESS',
						FIBI_IDENTIFIER = LI_MAS_KEYWORD_ID
						WHERE MIGRATION_AWARD_KEYWORD_ID = LI_RECORD_ID;
					ELSE
						UPDATE stage_award_keywords
						SET VALIDATION_STATUS = 'ERROR',
						FIBI_IDENTIFIER = -1
						WHERE MIGRATION_AWARD_KEYWORD_ID = LI_RECORD_ID;
					END IF;
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,'MIGRATION end',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
			END LOOP MIGRATION_AWRD_KEYWORD_CURSOR_LOOP;
			CLOSE MIGRATION_AWRD_KEYWORD_CURSOR;
			INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
	END;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM seq_award_research_area;
	IF LI_COUNT = 0 THEN
	INSERT INTO seq_award_research_area  (NEXT_VAL) VALUES ((SELECT IFNULL(MAX(RESRCH_AREA_ID ),0) + 1  FROM award_research_areas));
	ELSE
	UPDATE seq_award_research_area   SET NEXT_VAL = (SELECT IFNULL(MAX(RESRCH_AREA_ID),0) + 1  FROM award_research_areas);
	END IF;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
		COMMIT;
END IF;
END
