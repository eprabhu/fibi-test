DECLARE LI_RECORD_ID INT;
DECLARE LI_SEQUENCE_NUMBER INT;
DECLARE LI_KEYWORD_ID INT;
DECLARE LI_AWARD_ID INT;
DECLARE LI_MASTER_AWARD_ID INT;
DECLARE LI_MAX_SEQUENCE_NUMBER INT;
DECLARE LI_MAS_KEYWORD_ID INT;
DECLARE LI_RESEARCH_TYPE_CODE INT;
DECLARE LS_JHU_AWARD_NUMBER CHAR(10);
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LS_SCIENCE_CODE VARCHAR(15);
DECLARE LS_UPDATE_USER VARCHAR(8);
DECLARE LS_UPDATE_TIMESTAMP DATETIME;
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LI_SOURCE_COUNT INT;
DECLARE LI_DESTINATION_COUNT INT;
DECLARE LS_MIGRATION_STATUS VARCHAR(30);
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
		IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'AWRDKEYWORD' AND ERROR_TYPE = 'MIGRATION';
			UPDATE stage_award_keywords SET VALIDATION_STATUS = 'VALID',FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER = -1;
		END IF;
END;
BEGIN
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM research_type WHERE UPPER(DESCRIPTION) = UPPER('AreaÂ ofÂ Research') AND ACTIVE_FLAG = 'Y';
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (-100,'AWRDKEYWORD','MIGRATION',CONCAT('Invalid research type : AreaÂ ofÂ Research'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	ELSE
		SELECT RESRCH_TYPE_CODE INTO LI_RESEARCH_TYPE_CODE FROM research_type WHERE UPPER(DESCRIPTION) = UPPER('AreaÂ ofÂ Research') AND ACTIVE_FLAG = 'Y';
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
	SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'MIGRATION' AND MODULE_NAME = 'AWRDKEYWORD';
	INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'MIGRATION','AWRDKEYWORD',UTC_TIMESTAMP());
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
IF LS_DATA_ERROR_FLAG = 'N' THEN
BEGIN
		DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE MIGRATION_AWRD_KEYWORD_CURSOR CURSOR FOR
		SELECT  MIGRATION_AWARD_KEYWORD_ID,
				MIT_AWARD_NUMBER,
				SEQUENCE_NUMBER,
				SCIENCE_CODE,
				UPDATE_TIMESTAMP,
				UPDATE_USER
		FROM 	stage_award_keywords
		WHERE VALIDATION_STATUS = 'VALID' AND FIBI_IDENTIFIER IS NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR;
			INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'AWRDKEYWORD','MIGRATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END;
			OPEN MIGRATION_AWRD_KEYWORD_CURSOR;
			MIGRATION_AWRD_KEYWORD_CURSOR_LOOP :    	LOOP
				FETCH MIGRATION_AWRD_KEYWORD_CURSOR 	INTO     	LI_RECORD_ID,
																	LS_JHU_AWARD_NUMBER,
																	LI_SEQUENCE_NUMBER,
																	LS_SCIENCE_CODE,
																	LS_UPDATE_TIMESTAMP,
																	LS_UPDATE_USER;
					IF DONE1 THEN
						LEAVE MIGRATION_AWRD_KEYWORD_CURSOR_LOOP;
					END IF;
					SET LS_DATA_ERROR_FLAG = 'N';
					SET LI_KEYWORD_ID = -1;
					SET LI_AWARD_ID = -1;
					SET LI_MASTER_AWARD_ID = -1;
					SET LI_MAS_KEYWORD_ID = -1;
					SET LI_MAX_SEQUENCE_NUMBER = -1;
					INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,'MIGRATION start',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
					SET LS_AWARD_NUMBER = REPLACE(LS_JHU_AWARD_NUMBER,'-','-00');
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,CONCAT('Changed award number',LS_AWARD_NUMBER),UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
					END IF;
					SET LI_COUNT = -1;
					-- award number
					SELECT COUNT(1) INTO LI_COUNT FROM
					award WHERE AWARD_NUMBER = LS_AWARD_NUMBER;
					IF LI_COUNT = 0 THEN
						INSERT INTO migration_transaction_errorlog
							(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
						VALUES  (LI_RECORD_ID,'AWRDKEYWORD','MIGRATION',CONCAT('Invalid award number :', LS_AWARD_NUMBER),UTC_TIMESTAMP(),'quickstart');
						SET LS_DATA_ERROR_FLAG = 'Y';
					ELSE
						SELECT IFNULL(MAX(SEQUENCE_NUMBER),-1) INTO LI_MAX_SEQUENCE_NUMBER FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER;
						IF LI_MAX_SEQUENCE_NUMBER <> -1 THEN
							SELECT AWARD_ID INTO LI_AWARD_ID FROM
							award WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = LI_MAX_SEQUENCE_NUMBER;
						ELSE
							INSERT INTO migration_transaction_errorlog
								(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
							VALUES  (LI_RECORD_ID,'AWRDKEYWORD','MIGRATION',CONCAT('Invalid sequence number :', LI_MAX_SEQUENCE_NUMBER),UTC_TIMESTAMP(),'quickstart');
							SET LS_DATA_ERROR_FLAG = 'Y';
						END IF;
					END IF;
					IF FOR_AUDIT = 1 THEN
						INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,'after award check',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
					END IF;
					/*IF LS_DATA_ERROR_FLAG = 'N' THEN
						SELECT IFNULL(MAX(RESRCH_AREA_ID),0) + 1 INTO LI_KEYWORD_ID FROM award_research_areas;
						INSERT INTO award_research_areas
						(
							RESRCH_AREA_ID,
							RESRCH_TYPE_CODE,
							RESEARCH_AREA_CODE,
							RESEARCH_SUB_AREA_CODE,
							AWARD_ID,
							AWARD_NUMBER,
							SEQUENCE_NUMBER,
							UPDATE_TIMESTAMP,
							UPDATE_USER,
							CHALLENGE_AREA_CODE,
							CHALLENGE_SUBAREA_CODE,
							RESRCH_TYPE_AREA_CODE,
							RESRCH_TYPE_SUB_AREA_CODE
						)
						VALUES
						(
							LI_KEYWORD_ID,
							LI_RESEARCH_TYPE_CODE,
							NULL,
							NULL,
							LI_AWARD_ID,
							LS_AWARD_NUMBER,
							LI_MAX_SEQUENCE_NUMBER,
							LS_UPDATE_TIMESTAMP,
							LS_UPDATE_USER,
							NULL,
							NULL,
							LS_SCIENCE_CODE,
							NULL
						);
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,'after insert',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
						END IF;
					END IF;*/
					IF LS_DATA_ERROR_FLAG = 'N' THEN
						IF FOR_AUDIT = 1 THEN
							INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('MIGRATION','AWRDKEYWORD',LI_BATCH_ID,'master logic begin',UTC_TIMESTAMP(),LS_JHU_AWARD_NUMBER);
						END IF;
							SET LI_COUNT = -1;
							SELECT COUNT(1) INTO LI_COUNT FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = 0;
							IF LI_COUNT = 0 THEN
								INSERT INTO migration_transaction_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_RECORD_ID,'AWRDKEYWORD','MIGRATION',CONCAT('Invalid master award data with award number :', LS_AWARD_NUMBER,' and the sequence number : 0'),UTC_TIMESTAMP(),'quickstart');
								SET LS_DATA_ERROR_FLAG = 'Y';
							ELSE
								SELECT AWARD_ID INTO LI_MASTER_AWARD_ID FROM award WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = 0;
							END IF;
							SET LI_COUNT = -1;
							SELECT COUNT(1) INTO LI_COUNT FROM award_research_areas WHERE AWARD_ID = LI_MASTER_AWARD_ID AND RESRCH_TYPE_AREA_CODE = LS_SCIENCE_CODE;
							IF LI_COUNT > 0 THEN
								INSERT INTO migration_transaction_errorlog
									(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
								VALUES  (LI_RECORD_ID,'AWRDKEYWORD','MIGRATION',CONCAT('Data already exists for the award number :', LS_AWARD_NUMBER,' and the sequence number : 0',' and the science code : ',LS_SCIENCE_CODE),UTC_TIMESTAMP(),'quickstart');
								SET LS_DATA_ERROR_FLAG = 'Y';
							END IF;
							IF LS_DATA_ERROR_FLAG = 'N' THEN
								SELECT IFNULL(MAX(RESRCH_AREA_ID),0) + 1 INTO LI_MAS_KEYWORD_ID FROM award_research_areas;
								INSERT INTO award_research_areas
								(
									RESRCH_AREA_ID,
									RESRCH_TYPE_CODE,
									RESEARCH_AREA_CODE,
									RESEARCH_SUB_AREA_CODE,
									AWARD_ID,
									AWARD_NUMBER,
