DELIMITER $$
CREATE  PROCEDURE `MIGRATE_TEMPLATE_TERMS`(DATA_REFRESH_FLAG INT)
BEGIN
DECLARE LI_SPONSOR_TERM_ID INT;
DECLARE LI_SPONSOR_TERM_TYPE_CODE varchar(3);
DECLARE  LS_SPONSOR_TERM_TYPE varchar(200);
DECLARE LI_FUNDING_SCHEME_ID INT;
DECLARE LI_SPONSOR_TERM_CODE varchar(3);
DECLARE LS_SPONSOR_TERM varchar(200);
DECLARE LI_SPONSOR_TERM_REPORT_ID INT;
DECLARE LI_term_already_exist INT;
DECLARE LS_ERROR_MSG VARCHAR(4000);
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
				select LS_ERROR_MSG from dual;
            COMMIT;
		END;
		BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_TEMPLATE_TERM CURSOR FOR
		select SPONSOR_TERM_TYPE_CODE
				,SPONSOR_TERM_TYPE
                ,FUNDING_SCHEME_ID
                ,SPONSOR_TERM_CODE
                ,SPONSOR_TERM
		from stage_template_terms;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_TEMPLATE_TERM;
		TEMPLATE_TERM_LOOP: LOOP
		FETCH CUR_TEMPLATE_TERM INTO LI_SPONSOR_TERM_TYPE_CODE
									,LS_SPONSOR_TERM_TYPE
									,LI_FUNDING_SCHEME_ID
									,LI_SPONSOR_TERM_CODE
									,LS_SPONSOR_TERM;
		IF DONE1 THEN
			LEAVE TEMPLATE_TERM_LOOP;
		END IF;
            select count(*) into LI_term_already_exist from
            sponsor_term where SPONSOR_TERM_TYPE_CODE = LI_SPONSOR_TERM_TYPE_CODE
            and  SPONSOR_TERM_CODE  = LI_SPONSOR_TERM_CODE;
            IF LI_term_already_exist = 0 THEN
			select IFNULL(MAX(SPONSOR_TERM_ID),0)+1 into LI_SPONSOR_TERM_ID from sponsor_term;
			INSERT INTO SPONSOR_TERM (SPONSOR_TERM_ID
									, SPONSOR_TERM_TYPE_CODE
									, SPONSOR_TERM_CODE
									,  DESCRIPTION
									, UPDATE_TIMESTAMP
									, UPDATE_USER)
							values(LI_SPONSOR_TERM_ID
									, LI_SPONSOR_TERM_TYPE_CODE
									, LI_SPONSOR_TERM_CODE
									, LS_SPONSOR_TERM
									, UTC_TIMESTAMP()
									, 'JHU_ADMIN'
									);commit;
			select IFNULL(MAX(SPONSOR_TERM_REPORT_ID),0)+1 into LI_SPONSOR_TERM_REPORT_ID from SPONSOR_TERM_REPORT;
			INSERT INTO SPONSOR_TERM_REPORT (SPONSOR_TERM_REPORT_ID
											, FUNDING_SCHEME_ID
											, SPONSOR_TERM_ID
											, UPDATE_USER
											, UPDATE_TIMESTAMP)
									VALUES(LI_SPONSOR_TERM_REPORT_ID
											, LI_FUNDING_SCHEME_ID
											, LI_SPONSOR_TERM_ID
											, 'JHU_ADMIN'
											, UTC_TIMESTAMP()
											);commit;
		else
             select IFNULL(MAX(SPONSOR_TERM_REPORT_ID),0)+1 into LI_SPONSOR_TERM_REPORT_ID from SPONSOR_TERM_REPORT;
            select SPONSOR_TERM_ID into LI_SPONSOR_TERM_ID from
            sponsor_term where SPONSOR_TERM_TYPE_CODE = LI_SPONSOR_TERM_TYPE_CODE
            and  SPONSOR_TERM_CODE  = LI_SPONSOR_TERM_CODE;
			INSERT INTO SPONSOR_TERM_REPORT (SPONSOR_TERM_REPORT_ID
											, FUNDING_SCHEME_ID
											, SPONSOR_TERM_ID
											, UPDATE_USER
											, UPDATE_TIMESTAMP)
									VALUES(LI_SPONSOR_TERM_REPORT_ID
											, LI_FUNDING_SCHEME_ID
											, LI_SPONSOR_TERM_ID
											, 'JHU_ADMIN'
											, UTC_TIMESTAMP()
											);commit;
		END IF;
			SET SQL_SAFE_UPDATES = 0;
			set LI_SPONSOR_TERM_ID = NULL;
			set LI_SPONSOR_TERM_REPORT_ID = NULL;
				set LI_SPONSOR_TERM_TYPE_CODE = NULL;
				set LS_SPONSOR_TERM_TYPE = NULL;
                set LI_FUNDING_SCHEME_ID = NULL;
                set LI_SPONSOR_TERM_CODE = NULL;
                set LS_SPONSOR_TERM = NULL;
			SET SQL_SAFE_UPDATES = 1;
		END LOOP;
		CLOSE CUR_TEMPLATE_TERM;
		END;
END
$$
DELIMITER ;
