CREATE  FUNCTION `FN_HAS_INCOMPLETE_ATTACMENT`(
 AV_PROPOSAL_ID VARCHAR(6)
) RETURNS varchar(6) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT int;
DECLARE RETURN_STRING VARCHAR(5) DEFAULT 'FALSE';
 SELECT COUNT(*)
 INTO LI_COUNT
 FROM eps_proposal_attachments p
 WHERE p.PROPOSAL_ID=AV_PROPOSAL_ID
 AND   p.narrative_status_code = 'I'
 AND   p.document_status_code <> 2;
IF LI_COUNT > 0 THEN
   SET RETURN_STRING = 'TRUE';
END IF;
RETURN RETURN_STRING;
END
$$
DELIMITER ;
