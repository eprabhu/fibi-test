DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `MIGRATE_PER_CUSTOM_DATA_PREVAL`(DATA_REFRESH_FLAG INT,FOR_AUDIT INT)
BEGIN
DECLARE LI_RECORD_ID INT;
DECLARE LS_PROPOSAL_NUMBER VARCHAR(8);
DECLARE LS_COLUMN_NAME VARCHAR(30);
DECLARE LS_COLUMN_VALUE VARCHAR(2000);
DECLARE LS_PERSON_ID VARCHAR(9);
DECLARE LS_ERROR_MESSAGE VARCHAR(4000);
DECLARE LI_COUNT INT;
DECLARE LS_DATA_ERROR_FLAG VARCHAR(1);
DECLARE LI_BATCH_ID INT;
DECLARE LI_TOTAL_PROCESSED_DATA_COUNT INT DEFAULT 0;
DECLARE LI_TOTAL_DATA_COUNT INT DEFAULT 0;
BEGIN
	SET SQL_SAFE_UPDATES = 0;
	SET FOREIGN_KEY_CHECKS = 0;
	IF DATA_REFRESH_FLAG = 1 THEN
			DELETE FROM migration_transaction_errorlog WHERE SOURCE_TYPE = 'EPSPROPPERCUSTOM' AND ERROR_TYPE = 'VALIDATION';
			UPDATE stage_eps_prop_per_custom_data SET VALIDATION_STATUS = NULL,FIBI_IDENTIFIER = NULL WHERE VALIDATION_STATUS = 'ERROR' AND FIBI_IDENTIFIER IS NULL;
	END IF;
END;
BEGIN
	DELETE FROM migration_trans_execution_log;
	ALTER TABLE migration_trans_execution_log AUTO_INCREMENT = 1;
SELECT COUNT(1) INTO LI_TOTAL_DATA_COUNT FROM stage_eps_prop_per_custom_data;
SELECT IFNULL(MAX(BATCH_ID),0) + 1 INTO LI_BATCH_ID FROM migration_transtn_auditlog_header WHERE ACTION_TYPE = 'VALIDATION' AND MODULE_NAME = 'EPSPROPPERCUSTOM';
INSERT INTO migration_transtn_auditlog_header
		(BATCH_ID,ACTION_TYPE,MODULE_NAME,EXECUTION_TIME)
		VALUES 	(LI_BATCH_ID,'VALIDATION','EPSPROPPERCUSTOM',UTC_TIMESTAMP());
INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Started execution',UTC_TIMESTAMP());
END;
BEGIN
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE1 INT DEFAULT FALSE;
	DECLARE  MIGRATE_EPS_PROP_PER_CUSTOM CURSOR FOR
	SELECT 		MIGRATION_PROP_PER_CUSTOM_DATA_ID,
				PROPOSAL_NUMBER,
				PERSON_ID,
				COLUMN_NAME,
				COLUMN_VALUE
	FROM 	stage_eps_prop_per_custom_data  WHERE VALIDATION_STATUS IS NULL AND FIBI_IDENTIFIER IS NULL;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		INSERT INTO migration_transaction_errorlog
					(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPPERCUSTOM','VALIDATION',CONCAT(LS_ERROR),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END;
	OPEN MIGRATE_EPS_PROP_PER_CUSTOM;
	MIGRATE_EPS_PROP_PER_CUSTOM_LOOP		:	LOOP
	FETCH MIGRATE_EPS_PROP_PER_CUSTOM			INTO		LI_RECORD_ID,
															LS_PROPOSAL_NUMBER,
															LS_PERSON_ID,
															LS_COLUMN_NAME,
															LS_COLUMN_VALUE;
	IF DONE1 THEN
		LEAVE MIGRATE_EPS_PROP_PER_CUSTOM_LOOP;
	END IF;
	SET LS_DATA_ERROR_FLAG = 'N';
	SET LI_TOTAL_PROCESSED_DATA_COUNT = LI_TOTAL_PROCESSED_DATA_COUNT + 1;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'validation start',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_proposal WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND VALIDATION_STATUS IN ('VALID','SUCCESS');
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPPERCUSTOM','VALIDATION',CONCAT('Invalid proposal number :', LS_PROPOSAL_NUMBER),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'after dev prop check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM custom_data_elements WHERE UPPER(CUSTOM_ELEMENT_NAME) = UPPER(LS_COLUMN_NAME);
	IF LI_COUNT <> 1 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPPERCUSTOM','VALIDATION',CONCAT('Invalid custom element :', LS_COLUMN_NAME),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'after custom data elements check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	SET LI_COUNT = -1;
	SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_investigators WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID AND
	VALIDATION_STATUS IN ('VALID','SUCCESS');
	IF LI_COUNT <> 1 THEN
		SET LI_COUNT = -1;
		SELECT COUNT(1) INTO LI_COUNT FROM stage_eps_prop_key_persons WHERE PROPOSAL_NUMBER = LS_PROPOSAL_NUMBER AND PERSON_ID = LS_PERSON_ID AND
		VALIDATION_STATUS IN ('VALID','SUCCESS');
		IF LI_COUNT <> 1 THEN
			INSERT INTO migration_transaction_errorlog
				(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES  (LI_RECORD_ID,'EPSPROPPERCUSTOM','VALIDATION',CONCAT('Invalid proposal person with proposal number :', LS_PROPOSAL_NUMBER, ' and person id : ', LS_PERSON_ID),UTC_TIMESTAMP(),'quickstart');
			SET LS_DATA_ERROR_FLAG = 'Y';
		END IF;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'after proposal person check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	IF LENGTH(LS_COLUMN_VALUE) > 4000 THEN
		INSERT INTO migration_transaction_errorlog
			(PARENT_ID,SOURCE_TYPE,ERROR_TYPE,ERROR_MESSAGE,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES  (LI_RECORD_ID,'EPSPROPPERCUSTOM','VALIDATION',CONCAT('The length is more than the source data type size'),UTC_TIMESTAMP(),'quickstart');
		SET LS_DATA_ERROR_FLAG = 'Y';
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'after column value check',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	IF LS_DATA_ERROR_FLAG = 'N' THEN
		UPDATE stage_eps_prop_per_custom_data SET VALIDATION_STATUS = 'VALID', FIBI_IDENTIFIER = NULL WHERE MIGRATION_PROP_PER_CUSTOM_DATA_ID = LI_RECORD_ID;
	ELSE
		UPDATE stage_eps_prop_per_custom_data SET VALIDATION_STATUS = 'ERROR', FIBI_IDENTIFIER = NULL WHERE MIGRATION_PROP_PER_CUSTOM_DATA_ID = LI_RECORD_ID;
	END IF;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'after update',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	IF LI_TOTAL_PROCESSED_DATA_COUNT < LI_TOTAL_DATA_COUNT THEN
		IF LI_TOTAL_PROCESSED_DATA_COUNT = 10000 THEN
			INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES (CONCAT('Completed validation of ',LI_TOTAL_PROCESSED_DATA_COUNT,' records'),UTC_TIMESTAMP());
			SET LI_TOTAL_PROCESSED_DATA_COUNT = 0;
		END IF;
	END IF ;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'validation end',UTC_TIMESTAMP(),LS_PROPOSAL_NUMBER);
	END IF;
	END LOOP MIGRATE_EPS_PROP_PER_CUSTOM_LOOP;
	CLOSE MIGRATE_EPS_PROP_PER_CUSTOM;
	IF FOR_AUDIT = 1 THEN
		INSERT INTO migration_transtn_auditlog_details (ACTION_TYPE,MODULE_NAME,BATCH_ID,MESSAGE,EXECUTION_TIME,PARENT_NUMBER) VALUES ('VALIDATION','EPSPROPPERCUSTOM',LI_BATCH_ID,'exit cursor',UTC_TIMESTAMP(),NULL);
	END IF;
END;
	INSERT INTO migration_trans_execution_log (EXECUTION_MESSAGE,EXECUTION_TIME) VALUES ('Completed successfully',UTC_TIMESTAMP());
	SET SQL_SAFE_UPDATES = 1;
	SET FOREIGN_KEY_CHECKS = 1;
	SELECT 1 AS RESULT;
	COMMIT;
END
$$
DELIMITER ;
