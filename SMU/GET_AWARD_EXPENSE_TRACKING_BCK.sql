DELIMITER $$
CREATE  PROCEDURE `GET_AWARD_EXPENSE_TRACKING_BCK`(
av_award_number varchar(12),
av_account_number varchar(100)
)
    DETERMINISTIC
BEGIN
DECLARE LI_AWARD_ID INT;
SELECT AWARD_ID INTO LI_AWARD_ID FROM AWARD T1
WHERE T1.AWARD_NUMBER = AV_AWARD_NUMBER
AND T1.AWARD_SEQUENCE_STATUS = 'ACTIVE';
IF LI_AWARD_ID IS NOT NULL THEN
SELECT
S2.BUDGET_CATEGORY_CODE,
S2.BUDGET_CATEGORY,
S2.COST_ELEMENT,
S2.LINE_ITEM,
S2.IO_CODE,
S2.QUANTITY,
S2.ORIGINAL_APPROVED_BUDGET,
S2.LATEST_APPROVED_BUDGET,
S2.EXPENDITURE_TO_DATE,
ifnull(S2.LATEST_APPROVED_BUDGET,0)-ifnull(S2.EXPENDITURE_TO_DATE,0) as BALANCE,
ROUND((S2.EXPENDITURE_TO_DATE/S2.LATEST_APPROVED_BUDGET)*100,2) as UTILIZATION_RATE,
S2.BUDGET_CATEGORY_TYPE_CODE,
S2.SORT_ORDER,
S2.BUDGET_DETAILS_ID,
S2.UPDATE_TIMESTAMP,
S2.STUDENT_HRS_FLAG,
S2.IS_UNASSIGN_TRANSACTION
FROM
(SELECT
DISTINCT
T3.BUDGET_CATEGORY_CODE,
T6.description AS BUDGET_CATEGORY,
T3.COST_ELEMENT,
T7.DESCRIPTION AS LINE_ITEM,
T3.INTERNAL_ORDER_CODE AS IO_CODE,
T3.QUANTITY,
S1.LINE_ITEM_COST as ORIGINAL_APPROVED_BUDGET,
T3.LINE_ITEM_COST as LATEST_APPROVED_BUDGET,
CASE WHEN T6.BUDGET_CATEGORY_TYPE_CODE = 'P' AND T3.INTERNAL_ORDER_CODE IS NULL THEN
(
SELECT
SUM(E1.TOTAL_EXPENSE_AMOUNT)
FROM AWARD_BUDGET_PERSON_DETAIL BP1
INNER JOIN AWARD_EXPENSE_DETAILS E1 ON BP1.IO_CODE = E1.INTERNAL_ORDER_CODE
WHERE BP1.BUDGET_DETAILS_ID = T3.BUDGET_DETAILS_ID
AND T1.AWARD_NUMBER = E1.AWARD_NUMBER
AND T2.ACCOUNT_NUMBER = E1.ACCOUNT_NUMBER
)
else
T4.TOTAL_EXPENSE_AMOUNT
END AS EXPENDITURE_TO_DATE,
T6.BUDGET_CATEGORY_TYPE_CODE,
T6.SORT_ORDER,
T3.BUDGET_DETAILS_ID,
T2.LAST_SYNCH_TIMESTAMP as UPDATE_TIMESTAMP,
case when T7.COST_ELEMENT = '4' then 'Y'
else
'N'
end as STUDENT_HRS_FLAG,
'N' AS IS_UNASSIGN_TRANSACTION
FROM AWARD_BUDGET_HEADER T1
LEFT OUTER JOIN AWARD_EXPENSE_HEADER T2 ON T1.AWARD_NUMBER = T2.AWARD_NUMBER
LEFT OUTER JOIN AWARD_BUDGET_PERIOD P1 ON P1.BUDGET_HEADER_ID = T1.BUDGET_HEADER_ID
LEFT OUTER JOIN AWARD_BUDGET_DETAIL T3 ON T3.BUDGET_PERIOD_ID = P1.BUDGET_PERIOD_ID
LEFT OUTER JOIN AWARD_EXPENSE_DETAILS T4 ON T1.AWARD_NUMBER = T4.AWARD_NUMBER
AND T2.ACCOUNT_NUMBER = T4.ACCOUNT_NUMBER
AND T3.INTERNAL_ORDER_CODE = T4.INTERNAL_ORDER_CODE
LEFT OUTER JOIN (SELECT
P2.BUDGET_PERIOD_ID,
A3.COST_ELEMENT,
A3.LINE_ITEM_COST,
A2.BUDGET_HEADER_ID,
A3.INTERNAL_ORDER_CODE,
A3.LINE_ITEM_NUMBER
FROM award_budget_header A2
LEFT OUTER JOIN AWARD_BUDGET_PERIOD P2 ON P2.BUDGET_HEADER_ID = A2.BUDGET_HEADER_ID
LEFT OUTER JOIN AWARD_BUDGET_DETAIL A3 ON P2.BUDGET_PERIOD_ID = A3.BUDGET_PERIOD_ID
where A2.award_number = AV_AWARD_NUMBER
AND A2.SEQUENCE_NUMBER IN (SELECT MIN(AB1.SEQUENCE_NUMBER) FROM AWARD_BUDGET_HEADER AB1
WHERE AB1.AWARD_NUMBER = A2.AWARD_NUMBER)
AND P2.BUDGET_PERIOD_ID IN (SELECT MIN(BP2.BUDGET_PERIOD_ID) FROM AWARD_BUDGET_PERIOD BP2
WHERE BP2.BUDGET_HEADER_ID = P2.BUDGET_HEADER_ID)
and A3.BUDGET_CATEGORY_CODE<>600
) S1 ON S1.LINE_ITEM_NUMBER = T3.LINE_ITEM_NUMBER
AND S1.COST_ELEMENT = T3.COST_ELEMENT
INNER JOIN BUDGET_CATEGORY T6 ON T3.BUDGET_CATEGORY_CODE = T6.BUDGET_CATEGORY_CODE
LEFT OUTER JOIN COST_ELEMENT T7 ON T7.COST_ELEMENT = T3.COST_ELEMENT
WHERE T1.AWARD_ID = LI_AWARD_ID
AND T1.VERSION_NUMBER IN (SELECT MAX(AB1.VERSION_NUMBER) FROM AWARD_BUDGET_HEADER AB1
WHERE AB1.AWARD_ID = T1.AWARD_ID)
AND P1.BUDGET_PERIOD_ID IN (SELECT MIN(BP1.BUDGET_PERIOD_ID) FROM AWARD_BUDGET_PERIOD BP1
WHERE BP1.BUDGET_HEADER_ID = P1.BUDGET_HEADER_ID)
AND T3.BUDGET_CATEGORY_CODE<>600
) S2
union
SELECT
NULL AS BUDGET_CATEGORY_CODE,
NULL AS BUDGET_CATEGORY,
NULL AS COST_ELEMENT,
'Unassigned Transactions' AS LINE_ITEM,
NULL AS IO_CODE,
NULL AS QUANTITY,
NULL AS ORIGINAL_APPROVED_BUDGET,
NULL AS LATEST_APPROVED_BUDGET,
sum(T1.AMOUNT_IN_FMA_CURRENCY) as EXPENDITURE_TO_DATE,
NULL AS BALANCE,
NULL AS UTILIZATION_RATE,
'' AS BUDGET_CATEGORY_TYPE_CODE,
999 AS SORT_ORDER,
0 AS BUDGET_DETAILS_ID,
NULL as UPDATE_TIMESTAMP,
NULL as STUDENT_HRS_FLAG,
'Y' AS IS_UNASSIGN_TRANSACTION
FROM AWARD_EXPENSE_TRANSACTIONS T1
WHERE T1.AWARD_NUMBER=AV_AWARD_NUMBER
AND T1.ACCOUNT_NUMBER=AV_ACCOUNT_NUMBER
and (T1.INTERNAL_ORDER_CODE is null or T1.INTERNAL_ORDER_CODE ='')
and T1.ACTUAL_OR_COMMITTED_FLAG = 'A'
UNION
SELECT
NULL AS BUDGET_CATEGORY_CODE,
NULL AS BUDGET_CATEGORY,
NULL AS COST_ELEMENT,
'Unassigned Transactions' AS LINE_ITEM,
NULL AS IO_CODE,
NULL AS QUANTITY,
NULL AS ORIGINAL_APPROVED_BUDGET,
NULL AS LATEST_APPROVED_BUDGET,
sum(T1.AMOUNT_IN_FMA_CURRENCY) as EXPENDITURE_TO_DATE,
NULL AS BALANCE,
NULL AS UTILIZATION_RATE,
'' AS BUDGET_CATEGORY_TYPE_CODE,
999 AS SORT_ORDER,
0 AS BUDGET_DETAILS_ID,
NULL as UPDATE_TIMESTAMP,
NULL as STUDENT_HRS_FLAG,
'Y' AS IS_UNASSIGN_TRANSACTION
FROM AWARD_EXPENSE_TRANSACTIONS T1
WHERE T1.AWARD_NUMBER = AV_AWARD_NUMBER
AND T1.ACCOUNT_NUMBER = AV_ACCOUNT_NUMBER
AND T1.INTERNAL_ORDER_CODE IS NOT NULL
AND T1.INTERNAL_ORDER_CODE NOT IN (SELECT T2.INTERNAL_ORDER_CODE FROM AWARD_BUDGET_HEADER T1
INNER JOIN AWARD_BUDGET_DETAIL T2 ON T1.BUDGET_HEADER_ID = T2.BUDGET_HEADER_ID
WHERE AWARD_ID = LI_AWARD_ID
);
END IF;
END
