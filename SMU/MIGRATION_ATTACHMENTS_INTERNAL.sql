DELIMITER $$
CREATE  PROCEDURE `MIGRATION_ATTACHMENTS_INTERNAL`(AV_TYPE INT)
BEGIN
DECLARE LS_ERROR VARCHAR(2000);
DECLARE LS_LEGACY_PROJECT_ID VARCHAR(100);
DECLARE LS_PROJECT_ID   VARCHAR(255);
DECLARE LI_PROPOSAL_ID   INT;
DECLARE LS_PROJECT_TYPE VARCHAR(255);
DECLARE LS_PROJECT_ATTACHMENT_TYPE      VARCHAR(255);
DECLARE LS_PROJECT_FILE_NAME    VARCHAR(500);
DECLARE LS_PROJECT_MIME_TYPE    VARCHAR(255);
DECLARE LS_PROJECT_FILE_DATA    LONGBLOB;
DECLARE LI_PROJECT_ATTACHMENT_ID DECIMAL(12,0);
DECLARE LS_PROJECT_NUMBER VARCHAR(20);
DECLARE LI_PROJECT_COUNT INT;
DECLARE LI_ATT_TYPE_COUNT INT(11);
DECLARE LS_TYPE_CODE VARCHAR(3);
DECLARE LI_UNIQUE_ID VARCHAR(36);
DECLARE LI_DOCUMENT_ID  INT(11);
DECLARE LI_VERSION_AWARD_ID int;
DECLARE LI_MASTER_AWARD_ID int;
DECLARE LI_ATTACHMENT_ID int(11);
DECLARE LS_ERROR_FLAG VARCHAR(1);
begin
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE AWARD_CURSOR CURSOR FOR
SELECT ATTACHMENT_ID,PROJECT_ID,PROJECT_TYPE,ATTACHMENT_TYPE,FILE_NAME,MIME_TYPE,DATA
FROM migration_attachments_internal_00_17
where   validation_status in( 'VALID');
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
BEGIN
        GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
         @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
        SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
        SELECT @full_error INTO LS_ERROR;
        INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
        VALUES(LS_PROJECT_ID,'Exception','ATTACHMENT MIGRATION',LS_ERROR,'MIGRATION',LS_PROJECT_TYPE);
END;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN AWARD_CURSOR;
AWARD_CURSOR_LOOP : LOOP
        FETCH AWARD_CURSOR INTO
		LI_ATTACHMENT_ID,
		LS_PROJECT_ID,
		LS_PROJECT_TYPE,
		LS_PROJECT_ATTACHMENT_TYPE,
		LS_PROJECT_FILE_NAME,
		LS_PROJECT_MIME_TYPE,
		LS_PROJECT_FILE_DATA;
                IF DONE1 THEN
                        LEAVE AWARD_CURSOR_LOOP;
                END IF;
	set sql_safe_updates = 0;
		IF upper(trim(LS_PROJECT_TYPE)) = 'AWARD' THEN
				set  LS_PROJECT_ID = trim(substring(LS_PROJECT_ID,1,16));
				select  MASTER_AWARD_ID, AWARD_NUMBER
				into LI_MASTER_AWARD_ID,LS_PROJECT_NUMBER
				from MIGRATION_AWARD_INTERNAL_00_17
				WHERE PROJECT_ID = LS_PROJECT_ID;
				SELECT TYPE_CODE INTO LS_TYPE_CODE
				FROM AWARD_ATTACHMENT_TYPE
				WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_ATTACHMENT_TYPE));
                SELECT NEXT_VAL INTO LI_PROJECT_ATTACHMENT_ID FROM AWARD_ATTACHMENT_ID_GENERATOR;
                SELECT UUID() INTO LI_UNIQUE_ID FROM DUAL;
select IFNULL(max(DOCUMENT_ID),0)+1 into LI_DOCUMENT_ID from AWARD_ATTACHMENT where AWARD_ID = LI_MASTER_AWARD_ID;
                INSERT INTO AWARD_ATTACHMENT (
											AWARD_ATTACHMENT_ID,
											AWARD_ID,
											AWARD_NUMBER,
											SEQUENCE_NUMBER,
											TYPE_CODE,
											DESCRIPTION,
											DOCUMENT_STATUS_CODE,
											UPDATE_TIMESTAMP,
											UPDATE_USER,
											FILE_DATA_ID,
											FILE_NAME,
											MIME_TYPE,
											NARRATIVE_STATUS_CODE,
											VERSION_NUMBER,
                                            DOCUMENT_ID
								)values (
											LI_PROJECT_ATTACHMENT_ID,
											LI_MASTER_AWARD_ID,
											LS_PROJECT_NUMBER,
											1,
											LS_TYPE_CODE,
											NULL,
											1,
											NOW(),
											'quickstart',
											LI_UNIQUE_ID,
											LS_PROJECT_FILE_NAME,
											LS_PROJECT_MIME_TYPE,
											'C',
											1,
                                            LI_DOCUMENT_ID
							   );
                INSERT INTO FILE_DATA(ID,DATA) VALUES(LI_UNIQUE_ID,LS_PROJECT_FILE_DATA);
				UPDATE migration_attachments_internal_00_17 set validation_status = 'SUCCESS'
					where ATTACHMENT_ID = LI_ATTACHMENT_ID;
                COMMIT;
				UPDATE AWARD_ATTACHMENT_ID_GENERATOR SET NEXT_VAL = LI_PROJECT_ATTACHMENT_ID+1;
				COMMIT;
	elseif upper(trim(LS_PROJECT_TYPE)) = 'PROPOSAL' THEN
				SET  LS_PROJECT_ID = TRIM(LS_PROJECT_ID);
				select PROPOSAL_ID into LI_PROPOSAL_ID
				from MIGRATION_PROPOSAL_INTERNAL_00_17
				where APPLICATION_ID = LS_PROJECT_ID;
				SELECT ATTACHMNT_TYPE_CODE INTO LS_TYPE_CODE
				FROM eps_proposal_attach_type
				WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_ATTACHMENT_TYPE));
				SELECT NEXT_VAL INTO LI_PROJECT_ATTACHMENT_ID FROM eps_prop_attach_id_generator;
                SELECT UUID() INTO LI_UNIQUE_ID FROM DUAL;
select IFNULL(max(DOCUMENT_ID),0)+1 into LI_DOCUMENT_ID from EPS_PROPOSAL_ATTACHMENTS where PROPOSAL_ID = LI_PROPOSAL_ID;
                INSERT INTO EPS_PROPOSAL_ATTACHMENTS (
												ATTACHMENT_ID,
												PROPOSAL_ID,
												ATTACHMNT_TYPE_CODE,
												DESCRIPTION,
												DOCUMENT_STATUS_CODE,
												UPDATE_TIMESTAMP,
												UPDATE_USER,
												FILE_DATA_ID,
												FILE_NAME,
												MIME_TYPE,
												NARRATIVE_STATUS_CODE,
												VERSION_NUMBER,
                                                DOCUMENT_ID
										)values (
												LI_PROJECT_ATTACHMENT_ID,
												LI_PROPOSAL_ID,
												LS_TYPE_CODE,
												NULL,
												1,
												NOW(),
												'quickstart',
												LI_UNIQUE_ID,
												LS_PROJECT_FILE_NAME,
												LS_PROJECT_MIME_TYPE,
												'C',
												1,
                                                LI_DOCUMENT_ID
										);
                INSERT INTO FILE_DATA (ID, DATA)VALUES(LI_UNIQUE_ID,LS_PROJECT_FILE_DATA);
				UPDATE migration_attachments_internal_00_17 set validation_status = 'SUCCESS'
					where ATTACHMENT_ID = LI_ATTACHMENT_ID;
				COMMIT;
				UPDATE EPS_PROP_ATTACH_ID_GENERATOR SET NEXT_VAL = LI_PROJECT_ATTACHMENT_ID+1;
				COMMIT;
	end if;
		END LOOP;
		CLOSE AWARD_CURSOR;
END;
END
$$
DELIMITER ;
