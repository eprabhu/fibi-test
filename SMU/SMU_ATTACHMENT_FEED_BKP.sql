DELIMITER $$
CREATE  PROCEDURE `SMU_ATTACHMENT_FEED_BKP`(av_id int)
BEGIN
DECLARE LS_PROJECT_ID	VARCHAR(50);
DECLARE LS_PROJECT_TYPE	VARCHAR(10);
DECLARE LS_ATTACHMENT_TYPE	VARCHAR(50);
DECLARE LS_FILE_NAME	VARCHAR(500);
DECLARE LS_MIME_TYPE	VARCHAR(100);
DECLARE LS_FILE_DATA	LONGBLOB;
DECLARE LS_NUM	INT;
DECLARE LS_TYPE_CODE_C INT;
DECLARE LI_AWARD_ATTACHMENT_ID DECIMAL(12,0);
DECLARE LI_AWARD_ID DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER VARCHAR(20);
DECLARE LS_TYPE_CODE VARCHAR(3);
DECLARE UNIQUE_ID VARCHAR(36);
DECLARE LS_PROPOSAL_ID INT(10);
DECLARE LS_ATTACHMENT_ID  INT(10);
DECLARE LI_PROPOSAL_ATTACHMENT_ID   DECIMAL(12,0);
DECLARE LI_PROPOSAL_ID INT(10);
DECLARE LI_DOCUMENT_ID	INT(11);
DECLARE LS_MSG TEXT;
DECLARE LS_ERROR VARCHAR(2000);
DECLARE LI_COUNT INT;
DECLARE LS_APPLICATION_ID VARCHAR(255);
begin
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE AWARD_CURSOR CURSOR FOR
SELECT A.PROJECT_ID,A.PROJECT_TYPE,A.ATTACHMENT_TYPE,A.FILE_NAME,A.MIME_TYPE,
 B.AWARD_ID,B.AWARD_NUMBER,A.FILE_DATA
 FROM TEMP_ATTACHMENT_MIGRATION A LEFT JOIN MIGRATION_AWARD B ON UPPER(TRIM(A.PROJECT_ID)) = UPPER(TRIM(B.PROJECT_ID))
 WHERE A.PROJECT_TYPE = 'Award' AND B.PROJECT_ID NOT IN (258,193,267,266,265,263,260,161,8,
								280,209,208,201,200,163,261,431,419,294,292,285,210,204,310);
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
BEGIN
	GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
	 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
	SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
	SELECT @full_error INTO LS_ERROR;
	INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
	VALUES(ls_project_id,'Exception',TRIM(LS_FILE_NAME),LS_ERROR,'During Migration','Award');
END;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN AWARD_CURSOR;
AWARD_CURSOR_LOOP : LOOP
        FETCH AWARD_CURSOR INTO  LS_PROJECT_ID,LS_PROJECT_TYPE,LS_ATTACHMENT_TYPE,LS_FILE_NAME,LS_MIME_TYPE,LI_AWARD_ID,LS_AWARD_NUMBER,LS_FILE_DATA;
		IF DONE1 THEN
			LEAVE AWARD_CURSOR_LOOP;
		END IF;
		if (IFNULL(TRIM(LI_AWARD_ID),'') ='') THEN
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Project id is missing in the Migration Award file provided'),'During Migration','Award');
			COMMIT;
			ITERATE AWARD_CURSOR_LOOP;
		END IF;
		SELECT  COUNT(*) INTO LI_COUNT
		FROM AWARD WHERE AWARD_ID = LI_AWARD_ID;
		IF LI_COUNT = 0 THEN
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Award is missing in the Award table'),'During Migration','Award');
			COMMIT;
			ITERATE AWARD_CURSOR_LOOP;
		END IF;
		SELECT COUNT(*) INTO LI_COUNT
		FROM AWARD_ATTACHMENT_TYPE_BKP WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ATTACHMENT_TYPE));
		IF LI_COUNT > 0 THEN
			SELECT TYPE_CODE INTO LS_TYPE_CODE
			FROM AWARD_ATTACHMENT_TYPE_BKP
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ATTACHMENT_TYPE));
		ELSE
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Award Attachment type"',TRIM(LS_ATTACHMENT_TYPE),'" is missing in the file provided'),'During Migration','Award');
			COMMIT;
		    ITERATE AWARD_CURSOR_LOOP;
		END IF;
if LS_PROJECT_TYPE = 'Award' then
		SELECT IFNULL(MAX(AWARD_ATTACHMENT_ID),0)+1 INTO LI_AWARD_ATTACHMENT_ID FROM AWARD_ATTACHMENT;
		SELECT UUID() INTO UNIQUE_ID FROM DUAL;
		INSERT INTO AWARD_ATTACHMENT (
		AWARD_ATTACHMENT_ID,
		AWARD_ID,
		AWARD_NUMBER,
		SEQUENCE_NUMBER,
		TYPE_CODE,
		DESCRIPTION,
		DOCUMENT_STATUS_CODE,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		FILE_DATA_ID,
		FILE_NAME,
		MIME_TYPE,
		NARRATIVE_STATUS_CODE,
		VERSION_NUMBER)
		values (
		LI_AWARD_ATTACHMENT_ID,
		LI_AWARD_ID,
		LS_AWARD_NUMBER,
		1,
		LS_TYPE_CODE,
		NULL,
		1,
		NOW(),
		'quickstart',
		UNIQUE_ID,
		LS_FILE_NAME,
		LS_MIME_TYPE,
		'C',
		1
		);
		INSERT INTO FILE_DATA VALUES(UNIQUE_ID,LS_FILE_DATA);
end if;
END LOOP;
CLOSE AWARD_CURSOR;
UPDATE AWARD_ATTACHMENT_ID_GENERATOR SET NEXT_VAL = (SELECT IFNULL(MAX(AWARD_ATTACHMENT_ID),0)+1
																FROM AWARD_ATTACHMENT);
END;
BEGIN
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE EXP_CURSOR CURSOR FOR
SELECT DISTINCT AWARD_ID
FROM AWARD_ATTACHMENT
WHERE AWARD_ID IN(SELECT AWARD_ID FROM MIGRATION_AWARD WHERE PROJECT_ID NOT IN(258,193,267,266,265,263,260,161,8,
								280,209,208,201,200,163,261,431,419,294,292,285,210,204,310));
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
SET LI_DOCUMENT_ID = 0;
OPEN EXP_CURSOR;
EXP_CURSOR_LOOP : LOOP
        FETCH EXP_CURSOR INTO  LI_AWARD_ID;
		IF DONE2 THEN
			LEAVE EXP_CURSOR_LOOP;
		END IF;
		SET LI_DOCUMENT_ID = 0;
		BEGIN
        	DECLARE DONE3 INT DEFAULT FALSE;
			DECLARE EXP_CURSOR1 CURSOR FOR
			SELECT AWARD_ATTACHMENT_ID,AWARD_ID
			FROM AWARD_ATTACHMENT
			WHERE AWARD_ID = LI_AWARD_ID;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE3 = TRUE;
			OPEN EXP_CURSOR1;
			EXP_CURSOR_LOOP1 : LOOP
					FETCH EXP_CURSOR1 INTO  LI_AWARD_ATTACHMENT_ID,LI_AWARD_ID ;
					IF DONE3 THEN
						LEAVE EXP_CURSOR_LOOP1;
					END IF;
					SET LI_DOCUMENT_ID = LI_DOCUMENT_ID + 1;
					UPDATE AWARD_ATTACHMENT SET DOCUMENT_ID = LI_DOCUMENT_ID WHERE AWARD_ATTACHMENT_ID = LI_AWARD_ATTACHMENT_ID;
			END LOOP;
			CLOSE EXP_CURSOR1;
		END;
END LOOP;
CLOSE EXP_CURSOR;
COMMIT;
END;
begin
DECLARE DONE4 INT DEFAULT FALSE;
DECLARE PROPOSAL_CURSOR CURSOR FOR
SELECT A.PROJECT_ID,A.PROJECT_TYPE,A.ATTACHMENT_TYPE,A.FILE_NAME,A.MIME_TYPE,
A.FILE_DATA,B.APPLICATION_ID,B.PROPOSAL_ID
FROM TEMP_ATTACHMENT_MIGRATION A LEFT JOIN MIGRATION_PROPOSAL B ON UPPER(TRIM(A.PROJECT_ID)) = UPPER(TRIM(B.APPLICATION_ID))
WHERE A.PROJECT_TYPE = 'Proposal'
and B.APPLICATION_ID not in (212,186,178,166,164,146,125,114,108,104);
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE4 = TRUE;
OPEN PROPOSAL_CURSOR;
PROPOSAL_CURSOR_LOOP : LOOP
        FETCH PROPOSAL_CURSOR INTO  LS_PROJECT_ID,LS_PROJECT_TYPE,LS_ATTACHMENT_TYPE,LS_FILE_NAME,LS_MIME_TYPE,LS_FILE_DATA,LS_APPLICATION_ID,LS_PROPOSAL_ID;
		IF DONE4 THEN
			LEAVE PROPOSAL_CURSOR_LOOP;
		END IF;
		if (IFNULL(TRIM(LS_APPLICATION_ID),'') ='') THEN
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Project id is missing in the Migration Proposal file provided'),'During Migration','Proposal');
			COMMIT;
			ITERATE PROPOSAL_CURSOR_LOOP;
		END IF;
		if (IFNULL(TRIM(LS_PROPOSAL_ID),'') ='') THEN
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Proposal is missing in the Proposal table'),'During Migration','Proposal');
			COMMIT;
			ITERATE PROPOSAL_CURSOR_LOOP;
		END IF;
		SELECT  COUNT(*) INTO LI_COUNT
		FROM EPS_PROPOSAL WHERE PROPOSAL_ID = LS_PROPOSAL_ID;
		IF LI_COUNT = 0 THEN
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Proposal is missing in the Proposal table'),'During Migration','Proposal');
			COMMIT;
			ITERATE PROPOSAL_CURSOR_LOOP;
		END IF;
		SELECT COUNT(*) INTO LI_COUNT
		FROM EPS_PROPOSAL_ATTACH_TYPE_BKP WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ATTACHMENT_TYPE));
		IF LI_COUNT > 0 then
			SELECT ATTACHMNT_TYPE_CODE INTO LS_TYPE_CODE
			FROM EPS_PROPOSAL_ATTACH_TYPE_BKP WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ATTACHMENT_TYPE));
		ELSE
			INSERT INTO MIGRATION_ATTACHMENT_ERROR_LOG(LEGACY_PROJECT_ID,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
			VALUES(ls_project_id,'Validation',TRIM(LS_FILE_NAME),CONCAT('Proposal Attachment type"',TRIM(LS_ATTACHMENT_TYPE),'" is missing in the file provided'),'During Migration','Proposal');
			COMMIT;
			ITERATE PROPOSAL_CURSOR_LOOP;
		END IF;
if LS_PROJECT_TYPE = 'Proposal' then
		SELECT ifnull(MAX(ATTACHMENT_ID),0)+1 into LS_ATTACHMENT_ID from EPS_PROPOSAL_ATTACHMENTS;
		select uuid() into unique_id from dual;
		INSERT INTO EPS_PROPOSAL_ATTACHMENTS
		(ATTACHMENT_ID,
		ATTACHMNT_TYPE_CODE,
		DESCRIPTION,
		FILE_NAME,
		MIME_TYPE,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		PROPOSAL_ID,
		NARRATIVE_STATUS_CODE,
		VERSION_NUMBER,
		FILE_DATA_ID,
		DOCUMENT_STATUS_CODE
		)
		VALUES
		(
		LS_ATTACHMENT_ID,
		LS_TYPE_CODE,
		'Migrated',
		LS_FILE_NAME,
		LS_MIME_TYPE,
		NOW(),
		'quickstart',
		LS_PROPOSAL_ID,
		'C',
		1,
		unique_id,
		1
		);
		INSERT INTO FILE_DATA VALUES(UNIQUE_ID,LS_FILE_DATA);
end if;
END LOOP;
CLOSE PROPOSAL_CURSOR;
update EPS_PROP_ATTACH_ID_GENERATOR set next_val =  (SELECT (CASE WHEN MAX(ATTACHMENT_ID) IS NULL THEN 1
																		  ELSE MAX(ATTACHMENT_ID)+1 END)
															FROM EPS_PROPOSAL_ATTACHMENTS);
end;
BEGIN
DECLARE DONE2 INT DEFAULT FALSE;
DECLARE EXP_CURSOR CURSOR FOR
SELECT DISTINCT PROPOSAL_ID
FROM EPS_PROPOSAL_ATTACHMENTS
WHERE PROPOSAL_ID IN(SELECT PROPOSAL_ID FROM MIGRATION_PROPOSAL where APPLICATION_ID not in (212,186,178,166,164,146,125,114,108,104));
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
SET LI_DOCUMENT_ID = 0;
OPEN EXP_CURSOR;
EXP_CURSOR_LOOP : LOOP
        FETCH EXP_CURSOR INTO  LI_PROPOSAL_ID;
		IF DONE2 THEN
			LEAVE EXP_CURSOR_LOOP;
		END IF;
		SET LI_DOCUMENT_ID = 0;
		BEGIN
        	DECLARE DONE3 INT DEFAULT FALSE;
			DECLARE EXP_CURSOR1 CURSOR FOR
			SELECT ATTACHMENT_ID
			FROM EPS_PROPOSAL_ATTACHMENTS
			WHERE PROPOSAL_ID = LI_PROPOSAL_ID;
			DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE3 = TRUE;
			OPEN EXP_CURSOR1;
			EXP_CURSOR_LOOP1 : LOOP
					FETCH EXP_CURSOR1 INTO  LI_PROPOSAL_ATTACHMENT_ID ;
					IF DONE3 THEN
						LEAVE EXP_CURSOR_LOOP1;
					END IF;
					SET LI_DOCUMENT_ID = LI_DOCUMENT_ID + 1;
					UPDATE EPS_PROPOSAL_ATTACHMENTS SET DOCUMENT_ID = LI_DOCUMENT_ID WHERE ATTACHMENT_ID = LI_PROPOSAL_ATTACHMENT_ID;
			END LOOP;
			CLOSE EXP_CURSOR1;
		END;
END LOOP;
CLOSE EXP_CURSOR;
COMMIT;
END;
END
$$
DELIMITER ;
