DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PREVAL_PROPOSAL_PERSONS_INTERNAL`(
)
BEGIN
DECLARE LS_APPLICATION_ID 				VARCHAR(50);
DECLARE LS_PROJECT_TEAM_MEMBER_TYPE 	VARCHAR(50);
DECLARE LS_NT_LOGIN_ID 					VARCHAR(50);
DECLARE LS_PROJECT_TEAM_NAME 			VARCHAR(100);
DECLARE LS_PROJECT_TEAM_DESIGNATION 	VARCHAR(300);
DECLARE LS_SEQUENCE_PROJECT_TEAM 		VARCHAR(100);
DECLARE LS_PROJECT_TEAM_ROLE 			VARCHAR(100);
DECLARE LS_PROJECT_TEAM_PERCENT_EFFORT 	VARCHAR(10);
DECLARE LS_PROJECT_TEAM_DEPARTMENT 		VARCHAR(1000);
DECLARE LS_PROJECT_TEAM_ORGANISATION 	VARCHAR(1000);
DECLARE LS_PROJECT_TEAM_COUNTRY 		VARCHAR(100);
DECLARE LS_PROJECT_TEAM_CV 				VARCHAR(100);
DECLARE LS_PROJECT_TEAM_TRACK 			VARCHAR(100);
DECLARE LI_FLAG							INT;
DECLARE LI_ID						INT;
DECLARE LI_SEQ_ERROR_LOG_ID 			INT;
DECLARE LS_ERROR_MSG 					VARCHAR(1000);
DECLARE LI_MISSING_ID					INT;
DECLARE LS_ORAGANIZATION_ID				VARCHAR(10);
DECLARE LS_ERROR_FLAG VARCHAR(1);
DECLARE LI_ORGANIZATION_ID 	VARCHAR(8);
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_PERSON',LS_ERROR_MSG,'PRE_VALIDATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			ID,
			APPLICATION_ID,
			PROJECT_TEAM_MEMBER_TYPE,
			NT_LOGIN_ID,
			PROJECT_TEAM_NAME,
			PROJECT_TEAM_DESIGNATION,
			SEQUENCE_PROJECT_TEAM,
			PROJECT_TEAM_ROLE,
			PROJECT_TEAM_PERCENT_EFFORT,
			PROJECT_TEAM_DEPARTMENT,
			TRIM(PROJECT_TEAM_ORGANISATION),
			PROJECT_TEAM_COUNTRY,
			PROJECT_TEAM_CV,
			PROJECT_TEAM_TRACK,
			ORAGANIZATION_ID
		FROM MIGRATION_PROPOSAL_PERSONS_INTERNAL_00_17  where VALIDATION_STATUS is null
		and  APPLICATION_ID in (select APPLICATION_ID from migration_proposal_internal_00_17);
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
								LI_ID,
								LS_APPLICATION_ID,
								LS_PROJECT_TEAM_MEMBER_TYPE,
								LS_NT_LOGIN_ID,
								LS_PROJECT_TEAM_NAME,
								LS_PROJECT_TEAM_DESIGNATION,
								LS_SEQUENCE_PROJECT_TEAM,
								LS_PROJECT_TEAM_ROLE,
								LS_PROJECT_TEAM_PERCENT_EFFORT,
								LS_PROJECT_TEAM_DEPARTMENT,
								LS_PROJECT_TEAM_ORGANISATION,
								LS_PROJECT_TEAM_COUNTRY,
								LS_PROJECT_TEAM_CV,
								LS_PROJECT_TEAM_TRACK,
								LS_ORAGANIZATION_ID;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		set LS_ERROR_FLAG = 'N';
		SELECT COUNT(1) INTO LI_FLAG
		FROM MIGRATION_PROPOSAL_INTERNAL_00_17
		WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_APPLICATION_ID));
		IF LI_FLAG = 0 THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER,CAN_CREATE_PROPOSAL )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_PERSON','APPLICATION_ID DOES NOT EXIST',LS_APPLICATION_ID,'PREVALIDATION',NOW(),'quickstart','N');
			set LS_ERROR_FLAG = 'Y';
			COMMIT;
		END IF;
		IF LS_PROJECT_TEAM_MEMBER_TYPE = 'Non-SMU Employee' THEN
			SELECT COUNT(1) INTO LI_FLAG FROM ROLODEX
			WHERE UPPER(TRIM(FULL_NAME)) COLLATE utf8mb4_general_ci = UPPER(TRIM(LS_PROJECT_TEAM_NAME));
			IF LI_FLAG = 0 THEN
					SELECT COUNT(1) INTO LI_FLAG
					FROM MIGRATION_MISSING_PERSONS
					WHERE
					EMPLOYEE_TYPE = 'ROLODEX'
					AND UPPER(TRIM(FULL_NAME))  COLLATE utf8mb4_general_ci = UPPER(TRIM(LS_PROJECT_TEAM_NAME));
					IF LI_FLAG = 0 THEN
						SELECT IFNULL(MAX(ID),0)+1 INTO LI_MISSING_ID FROM MIGRATION_MISSING_PERSONS;
						INSERT INTO MIGRATION_MISSING_PERSONS
						(
						ID,ROLODEX_ID,FILE_TYPE, APPLICATION_ID, EMPLOYEE_TYPE, USER_NAME, FULL_NAME, PROJECT_TEAM_DESIGNATION, PROJECT_ROLE, PROJECT_TEAM_DEPARTMENT, PROJECT_TEAM_ORGANISATION, PROJECT_TEAM_COUNTRY,ORAGANIZATION_ID)
						VALUES(LI_MISSING_ID,IFNULL((select max(mmp.ROLODEX_ID)+1 from MIGRATION_MISSING_PERSONS mmp), (SELECT IFNULL(MAX(ROLODEX_ID),0)+1 FROM ROLODEX)),'PROPOSAL',LS_APPLICATION_ID,'ROLODEX',NULL,TRIM(LS_PROJECT_TEAM_NAME), LS_PROJECT_TEAM_DESIGNATION, LS_PROJECT_TEAM_ROLE, LS_PROJECT_TEAM_DEPARTMENT,LS_PROJECT_TEAM_ORGANISATION,LS_PROJECT_TEAM_COUNTRY,LS_ORAGANIZATION_ID);
						set LS_ERROR_FLAG = 'Y';
						COMMIT;
								-- organization_update
								IF LS_PROJECT_TEAM_ORGANISATION IS NOT NULL THEN
								SELECT COUNT(1) INTO LI_FLAG FROM organization
								WHERE UPPER(TRIM(ORGANIZATION_NAME)) = UPPER(TRIM(LS_PROJECT_TEAM_ORGANISATION));
									IF LI_FLAG = 0 THEN
										SELECT IFNULL(MAX(cast(organization_id as unsigned)),0)+1 INTO LI_ORGANIZATION_ID FROM organization;
										insert into organization (ORGANIZATION_ID, ORGANIZATION_NAME, UPDATE_TIMESTAMP, UPDATE_USER, IS_ACTIVE) values (cast(LI_ORGANIZATION_ID as char),LS_PROJECT_TEAM_ORGANISATION, UTC_TIMESTAMP(), 'quickstart', 'Y');
									END IF;
									SELECT ORGANIZATION_ID INTO LI_ORGANIZATION_ID FROM organization
									WHERE UPPER(TRIM(ORGANIZATION_NAME)) = UPPER(TRIM(LS_PROJECT_TEAM_ORGANISATION));
									UPDATE MIGRATION_MISSING_PERSONS set ORAGANIZATION_ID = LI_ORGANIZATION_ID where ID = LI_ID;
					END IF;
			END IF;
			END IF;
		ELSEIF LS_PROJECT_TEAM_MEMBER_TYPE = 'SMU Employee' THEN
			SELECT COUNT(1) INTO LI_FLAG FROM PERSON
			WHERE TRIM(UPPER(USER_NAME)) = TRIM(UPPER(LS_NT_LOGIN_ID));
			IF LI_FLAG = 0 THEN
					SELECT COUNT(1) INTO LI_FLAG
					FROM MIGRATION_MISSING_PERSONS
					WHERE EMPLOYEE_TYPE = 'PERSON'
					AND UPPER(TRIM(USER_NAME)) = UPPER(TRIM(LS_NT_LOGIN_ID));
					-- IF LI_FLAG = 0 THEN
						SELECT IFNULL(MAX(ID),0)+1 INTO LI_MISSING_ID FROM MIGRATION_MISSING_PERSONS;
						INSERT INTO MIGRATION_MISSING_PERSONS
						(
						ID,FILE_TYPE, APPLICATION_ID, EMPLOYEE_TYPE, USER_NAME, FULL_NAME, PROJECT_TEAM_DESIGNATION, PROJECT_ROLE, PROJECT_TEAM_DEPARTMENT, PROJECT_TEAM_ORGANISATION, PROJECT_TEAM_COUNTRY,ORAGANIZATION_ID)
						VALUES(LI_MISSING_ID,'PROPOSAL',LS_APPLICATION_ID,'PERSON',TRIM(LS_NT_LOGIN_ID),TRIM(LS_PROJECT_TEAM_NAME), LS_PROJECT_TEAM_DESIGNATION, LS_PROJECT_TEAM_ROLE, LS_PROJECT_TEAM_DEPARTMENT,LS_PROJECT_TEAM_ORGANISATION,LS_PROJECT_TEAM_COUNTRY,LS_ORAGANIZATION_ID);
						set LS_ERROR_FLAG = 'Y';
						COMMIT;
					-- END IF;
			END IF;
		END IF;
		IF LS_PROJECT_TEAM_ROLE IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROP_PERSON_ROLE
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_TEAM_ROLE));
			IF LI_FLAG = 0 THEN
					SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
					INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER
										   )
					VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_PERSON','PROPOSAL PERSON ROLE NOT EXIST',LS_PROJECT_TEAM_ROLE,'PREVALIDATION',NOW(),'quickstart');
					set LS_ERROR_FLAG = 'Y';
					COMMIT;
			END IF;
		ELSE
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER
								   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_PERSON','PROPOSAL PERSON ROLE IS NULL',LS_PROJECT_TEAM_ROLE,'PREVALIDATION',NOW(),'quickstart');
			set LS_ERROR_FLAG = 'Y';
			COMMIT;
	   END IF;
	IF LS_PROJECT_TEAM_MEMBER_TYPE = 'SMU Employee' THEN
		IF LS_PROJECT_TEAM_DEPARTMENT IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM UNIT
			WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROJECT_TEAM_DEPARTMENT));
			IF LI_FLAG = 0 THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE, VALIDATION_TYPE,UPDATE_TIMESTAMP, UPDATE_USER
									   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_PERSON','UNIT DOES NOT EXIST',CONCAT('PERSON NAME:',IFNULL(LS_PROJECT_TEAM_NAME,''),' UNIT NAME:',LS_PROJECT_TEAM_DEPARTMENT),'PREVALIDATION',NOW(),'quickstart');
				set LS_ERROR_FLAG = 'Y';
				COMMIT;
			END IF;
		ELSE
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE,VALIDATION_TYPE,UPDATE_TIMESTAMP, UPDATE_USER
									   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_PERSON','UNIT IS NULL',CONCAT('PERSON NAME:',IFNULL(LS_PROJECT_TEAM_NAME,''),' UNIT NAME:',IFNULL(LS_PROJECT_TEAM_DEPARTMENT,'')),'PREVALIDATION',NOW(),'quickstart');
				set LS_ERROR_FLAG = 'Y';
				COMMIT;
	  END IF;
	END IF;
		set sql_safe_updates = 0;
		IF LS_ERROR_FLAG = 'Y' then
			UPDATE MIGRATION_PROPOSAL_PERSONS_INTERNAL_00_17 set validation_status = 'ERROR' where ID = LI_ID;
			UPDATE MIGRATION_PROPOSAL_INTERNAL_00_17 set validation_status = 'ERROR' where APPLICATION_ID = LS_APPLICATION_ID;
		ELSE
			UPDATE MIGRATION_PROPOSAL_PERSONS_INTERNAL_00_17 set validation_status = 'VALID' where  ID = LI_ID;
			UPDATE MIGRATION_PROPOSAL_INTERNAL_00_17 set validation_status = 'VALID' where APPLICATION_ID = LS_APPLICATION_ID;
		END IF;
		END LOOP;
		CLOSE CUR_SEL_DATA;
	END;
		UPDATE MIGRATION_MISSING_PERSONS T1
		INNER JOIN ORGANIZATION T2 ON TRIM(UPPER(T1.PROJECT_TEAM_ORGANISATION))= TRIM(UPPER(T2.ORGANIZATION_NAME))
		SET T1.ORAGANIZATION_ID = T2.ORGANIZATION_ID
		WHERE T1.APPLICATION_ID IN (SELECT APPLICATION_ID FROM MIGRATION_PROPOSAL_INTERNAL_00_17 );
        update rolodex_id_generator set NEXT_VAL = (SELECT IFNULL(MAX(ROLODEX_ID),0)+1 FROM ROLODEX);
END;
END
$$
DELIMITER ;
