DELIMITER $$
CREATE  PROCEDURE `MERGE_AWD_MASTER_AWARD_KPI`(
AV_AWARD_ID 			DECIMAL(22,0),
AV_AWARD_NUMBER			VARCHAR(12),
AV_SEQUENCE_NUMBER		INT(4),
AV_VARIATION_TYPE_CODE	VARCHAR(3),
AV_UPDATE_USER			VARCHAR(60)
)
BEGIN
DECLARE LS_ERROR_MSG						VARCHAR(1000);
DECLARE LS_TABLE_NAME						VARCHAR(30);
DECLARE LI_FLAG								INT;
DECLARE LI_MASTER_AWARD_ID					DECIMAL(22,0);
DECLARE LI_MASTER_SEQ_NUMBER				INT(4);
DECLARE LI_AWARD_KPI_NEXT_VAL				BIGINT(20);
DECLARE LI_AWARD_KPI_CNT					INT(10);
DECLARE LI_AWARD_KPI_ID			INT(10);
DECLARE LS_KPI_TYPE_CODE		VARCHAR(3);
DECLARE LS_UPDATE_TIMESTAMP		DATETIME;
DECLARE LS_UPDATE_USER			VARCHAR(60);
DECLARE LI_AWARD_KPI_CRITERIA_ID	INT(10);
DECLARE LS_KPI_CRITERIA_TYPE_CODE	VARCHAR(3);
DECLARE LI_TARGET					INT(3);
DECLARE LI_AWARD_KPI_CRIT_NEXT_VAL	BIGINT(20);
DECLARE LI_AWARD_KPI_CRIT_CNT		INT(10);
DECLARE LS_DOCUMENT_UPDATE_USER			VARCHAR(60);
DECLARE LS_DOCUMENT_UPDATE_TIMESTAMP	DATETIME;
	BEGIN
			DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
			BEGIN
				GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
				SELECT @full_error INTO LS_ERROR_MSG;
				INSERT INTO AWARD_ERROR_LOG(AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, ERROR_MESSAGE, PROCEDURE_NAME, TABLE_NAME,SECTION_CODE,VARIATION_TYPE_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
				VALUES(AV_AWARD_ID,AV_AWARD_NUMBER,AV_SEQUENCE_NUMBER,LS_ERROR_MSG,'MERGE_AWD_MASTER_AWARD_KPI',LS_TABLE_NAME,122,AV_VARIATION_TYPE_CODE,UTC_TIMESTAMP(),AV_UPDATE_USER);
				COMMIT;
			END;
			SELECT COUNT(1) INTO LI_FLAG
			FROM AWARD
			WHERE AWARD_NUMBER = AV_AWARD_NUMBER
			AND SEQUENCE_NUMBER = 0;
			IF LI_FLAG > 0 THEN
				SELECT AWARD_ID,SEQUENCE_NUMBER
				INTO LI_MASTER_AWARD_ID,LI_MASTER_SEQ_NUMBER
				FROM AWARD
				WHERE AWARD_NUMBER = AV_AWARD_NUMBER
				AND SEQUENCE_NUMBER = 0;
			END IF;
			SELECT COUNT(1) INTO LI_AWARD_KPI_CNT
			FROM AWARD_KPI
			WHERE AWARD_ID = AV_AWARD_ID;
			SELECT COUNT(1) INTO  LI_AWARD_KPI_CRIT_CNT
			FROM AWARD_KPI_CRITERIA
			WHERE AWARD_KPI_ID IN(SELECT AWARD_KPI_ID FROM AWARD_KPI
								  WHERE AWARD_ID = AV_AWARD_ID
								  );
			SELECT IFNULL(MAX(NEXT_VAL),0) INTO LI_AWARD_KPI_NEXT_VAL
			FROM AWARD_KPI_ID_GENERATOR;
			SELECT IFNULL(MAX(NEXT_VAL),0) INTO LI_AWARD_KPI_CRIT_NEXT_VAL
			FROM AWARD_KPI_CRITERIA_ID_GENERATOR;
			UPDATE AWARD_KPI_ID_GENERATOR
			SET NEXT_VAL = LI_AWARD_KPI_NEXT_VAL + LI_AWARD_KPI_CNT + 1;
			UPDATE AWARD_KPI_CRITERIA_ID_GENERATOR
			SET NEXT_VAL = LI_AWARD_KPI_CRIT_NEXT_VAL + LI_AWARD_KPI_CRIT_CNT + 1;
			COMMIT;
			SET LS_TABLE_NAME = 'AWARD_KPI';
            BEGIN
				DECLARE DONE1 INT DEFAULT FALSE;
				DECLARE CUR_AWARD_KPI CURSOR FOR
				SELECT
					AWARD_KPI_ID,
					KPI_TYPE_CODE,
					UPDATE_TIMESTAMP,
					UPDATE_USER
				FROM AWARD_KPI
				WHERE AWARD_ID = AV_AWARD_ID;
				DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
				OPEN CUR_AWARD_KPI;
				INSERT_AWAD_KPI_LOOP: LOOP
				FETCH CUR_AWARD_KPI INTO
				LI_AWARD_KPI_ID,
				LS_KPI_TYPE_CODE,
				LS_UPDATE_TIMESTAMP,
				LS_UPDATE_USER;
				IF DONE1 THEN
					LEAVE INSERT_AWAD_KPI_LOOP;
				END IF;
				SET LI_AWARD_KPI_NEXT_VAL = LI_AWARD_KPI_NEXT_VAL + 1;
				INSERT INTO AWARD_KPI(
				AWARD_KPI_ID,
				AWARD_ID,
				AWARD_NUMBER,
				SEQUENCE_NUMBER,
				KPI_TYPE_CODE,
				UPDATE_TIMESTAMP,
				UPDATE_USER
				)
				VALUES
				(
				LI_AWARD_KPI_NEXT_VAL,
				LI_MASTER_AWARD_ID,
				AV_AWARD_NUMBER,
				LI_MASTER_SEQ_NUMBER,
				LS_KPI_TYPE_CODE,
				LS_UPDATE_TIMESTAMP,
				LS_UPDATE_USER
				);
				SET LS_TABLE_NAME = 'AWARD_KPI_CRITERIA';
				BEGIN
					DECLARE DONE2 INT DEFAULT FALSE;
					DECLARE CUR_AWARD_KPI_CRITERIA CURSOR FOR
					SELECT
						AWARD_KPI_CRITERIA_ID,
						KPI_CRITERIA_TYPE_CODE,
						TARGET,
						UPDATE_TIMESTAMP,
						UPDATE_USER
					FROM AWARD_KPI_CRITERIA
					WHERE AWARD_KPI_ID = LI_AWARD_KPI_ID;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
					OPEN CUR_AWARD_KPI_CRITERIA;
					INSERT_AWAD_KPI_CRIT_LOOP: LOOP
					FETCH CUR_AWARD_KPI_CRITERIA INTO
					LI_AWARD_KPI_CRITERIA_ID,
					LS_KPI_CRITERIA_TYPE_CODE,
					LI_TARGET,
					LS_UPDATE_TIMESTAMP,
					LS_UPDATE_USER;
					IF DONE2 THEN
						LEAVE INSERT_AWAD_KPI_CRIT_LOOP;
					END IF;
					SET LI_AWARD_KPI_CRIT_NEXT_VAL = LI_AWARD_KPI_CRIT_NEXT_VAL + 1;
					INSERT INTO AWARD_KPI_CRITERIA(
					AWARD_KPI_CRITERIA_ID,
					AWARD_KPI_ID,
					KPI_CRITERIA_TYPE_CODE,
					TARGET,
					UPDATE_TIMESTAMP,
					UPDATE_USER)
					VALUES
					(
					LI_AWARD_KPI_CRIT_NEXT_VAL,
					LI_AWARD_KPI_NEXT_VAL,
					LS_KPI_CRITERIA_TYPE_CODE,
					LI_TARGET,
					LS_UPDATE_TIMESTAMP,
					LS_UPDATE_USER
					);
					END LOOP;
					CLOSE CUR_AWARD_KPI_CRITERIA;
				END;
				END LOOP;
				CLOSE CUR_AWARD_KPI;
			END;
	END;
END
$$
DELIMITER ;
