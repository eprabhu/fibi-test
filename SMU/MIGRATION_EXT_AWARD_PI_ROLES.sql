DELIMITER $$
CREATE  PROCEDURE `MIGRATION_EXT_AWARD_PI_ROLES`(av_id int)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_ERROR_MSG 		VARCHAR(1000);
DECLARE LS_PERSON_ID 		VARCHAR(40);
DECLARE LI_LATEST_AWARD_ID			DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER		VARCHAR(12);
DECLARE LI_AWARD_PERSON_ROLE_ID	INT(12);
DECLARE LI_LATEST_SEQ INT(11);
DECLARE LI_SKIP_INSERT INT;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_AWARD_NUMBER,'EXCEPTION','PROJECT_ROLES',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
		AWARD_NUMBER,
		PERSON_ID
		FROM AWARD_PERSONS WHERE AWARD_ID IN (select award_id from migration_ext_award)
		AND PERSON_ROLE_ID = 3
		AND PERSON_ID IS NOT NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_AWARD_NUMBER,
		LS_PERSON_ID;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		SELECT MAX(SEQUENCE_NUMBER) INTO LI_LATEST_SEQ FROM AWARD WHERE AWARD_NUMBER = LS_AWARD_NUMBER;
		SELECT MAX(AWARD_ID) INTO LI_LATEST_AWARD_ID FROM AWARD WHERE AWARD_NUMBER = LS_AWARD_NUMBER AND SEQUENCE_NUMBER = LI_LATEST_SEQ;
		SELECT COUNT(*) INTO LI_SKIP_INSERT
				FROM AWARD_PERSON_ROLES
				WHERE AWARD_ID = LI_LATEST_AWARD_ID
						AND PERSON_ID = LS_PERSON_ID
						AND ROLE_ID IN (14); -- Create Variation Request
	IF LI_SKIP_INSERT < 1 THEN
		SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
		INSERT INTO AWARD_PERSON_ROLES
		(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES(LI_AWARD_PERSON_ROLE_ID,LI_LATEST_AWARD_ID,LS_AWARD_NUMBER,LI_LATEST_SEQ, LS_PERSON_ID,14,NOW(),'quickstart');
		COMMIT;
	end if;
	SELECT COUNT(*) INTO LI_SKIP_INSERT
				FROM AWARD_PERSON_ROLES
				WHERE AWARD_ID = LI_LATEST_AWARD_ID
						AND PERSON_ID = LS_PERSON_ID
						AND ROLE_ID IN (45); -- Create Projetc Closure
	IF LI_SKIP_INSERT < 1 THEN
		SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
		INSERT INTO AWARD_PERSON_ROLES
		(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES(LI_AWARD_PERSON_ROLE_ID,LI_LATEST_AWARD_ID,LS_AWARD_NUMBER,LI_LATEST_SEQ, LS_PERSON_ID,45,NOW(),'quickstart');
		COMMIT;
	end if;
	SELECT COUNT(*) INTO LI_SKIP_INSERT
				FROM AWARD_PERSON_ROLES
				WHERE AWARD_ID = LI_LATEST_AWARD_ID
						AND PERSON_ID = LS_PERSON_ID
						AND ROLE_ID IN (47); -- Modify Project Outcome
	IF LI_SKIP_INSERT < 1 THEN
		SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
		INSERT INTO AWARD_PERSON_ROLES
		(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES(LI_AWARD_PERSON_ROLE_ID,LI_LATEST_AWARD_ID,LS_AWARD_NUMBER,LI_LATEST_SEQ, LS_PERSON_ID,47,NOW(),'quickstart');
		COMMIT;
	end if;
	SELECT COUNT(*) INTO LI_SKIP_INSERT
				FROM AWARD_PERSON_ROLES
				WHERE AWARD_ID = LI_LATEST_AWARD_ID
						AND PERSON_ID = LS_PERSON_ID
						AND ROLE_ID IN (48); -- Withdraw Request
	IF LI_SKIP_INSERT < 1 THEN
		SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
		INSERT INTO AWARD_PERSON_ROLES
		(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES(LI_AWARD_PERSON_ROLE_ID,LI_LATEST_AWARD_ID,LS_AWARD_NUMBER,LI_LATEST_SEQ, LS_PERSON_ID,48,NOW(),'quickstart');
		COMMIT;
	end if;
	SELECT COUNT(*) INTO LI_SKIP_INSERT
				FROM AWARD_PERSON_ROLES
				WHERE AWARD_ID = LI_LATEST_AWARD_ID
						AND PERSON_ID = LS_PERSON_ID
						AND ROLE_ID IN (653); -- Principle Investigator
	IF LI_SKIP_INSERT < 1 THEN
		SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
		INSERT INTO AWARD_PERSON_ROLES
		(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
		VALUES(LI_AWARD_PERSON_ROLE_ID,LI_LATEST_AWARD_ID,LS_AWARD_NUMBER,LI_LATEST_SEQ, LS_PERSON_ID,653,NOW(),'quickstart');
		COMMIT;
	END IF;
		END LOOP;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE AWARD_PERSON_ROLE_ID_GENERATOR SET NEXT_VAL = (SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 FROM AWARD_PERSON_ROLES);
		COMMIT;
		CLOSE CUR_SEL_DATA;
	end;
END
$$
DELIMITER ;
