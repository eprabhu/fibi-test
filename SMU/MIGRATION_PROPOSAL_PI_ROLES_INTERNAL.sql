DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PROPOSAL_PI_ROLES_INTERNAL`(av_id int)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_ERROR_MSG 		VARCHAR(1000);
DECLARE LS_PERSON_ID 		VARCHAR(40);
DECLARE LI_PROPOSAL_ID		INT(10);
DECLARE LI_PROPOSAL_PERSON_ROLE_ID BIGINT(20);
DECLARE LI_PI_ROLE INT;
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LI_PROPOSAL_ID,'EXCEPTION','PROJECT_ROLES',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
		PERSON_ID,
		PROPOSAL_ID
		FROM EPS_PROPOSAL_PERSONS
		WHERE PROPOSAL_ID IN (SELECT PROPOSAL_ID FROM MIGRATION_PROPOSAL_INTERNAL_00_17 WHERE PROPOSAL_ID IS NOT NULL)
		AND PROP_PERSON_ROLE_ID = 3
		AND PERSON_ID IS NOT NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_PERSON_ID,
		LI_PROPOSAL_ID;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_PI_ROLE FROM EPS_PROPOSAL_PERSON_ROLES
		WHERE PROPOSAL_ID = LI_PROPOSAL_ID
		AND PERSON_ID = LS_PERSON_ID
		AND ROLE_ID = 14; -- Create Variation Request
		IF LI_PI_ROLE = 0 THEN
			SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0)+1 INTO LI_PROPOSAL_PERSON_ROLE_ID FROM EPS_PROPOSAL_PERSON_ROLES;
			INSERT INTO EPS_PROPOSAL_PERSON_ROLES
			(PROPOSAL_PERSON_ROLE_ID,PROPOSAL_ID,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_PROPOSAL_PERSON_ROLE_ID,LI_PROPOSAL_ID,LS_PERSON_ID,14,NOW(),'quickstart');
			commit;
		END IF;
		SELECT COUNT(1) INTO LI_PI_ROLE FROM EPS_PROPOSAL_PERSON_ROLES
		WHERE PROPOSAL_ID = LI_PROPOSAL_ID
		AND PERSON_ID = LS_PERSON_ID
		AND ROLE_ID = 45;  -- Create Projetc Closure
		IF LI_PI_ROLE = 0 THEN
			SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0)+1 INTO LI_PROPOSAL_PERSON_ROLE_ID FROM EPS_PROPOSAL_PERSON_ROLES;
			INSERT INTO EPS_PROPOSAL_PERSON_ROLES
			(PROPOSAL_PERSON_ROLE_ID,PROPOSAL_ID,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_PROPOSAL_PERSON_ROLE_ID,LI_PROPOSAL_ID,LS_PERSON_ID,45,NOW(),'quickstart');
			commit;
		END IF;
		SELECT COUNT(1) INTO LI_PI_ROLE FROM EPS_PROPOSAL_PERSON_ROLES
		WHERE PROPOSAL_ID = LI_PROPOSAL_ID
		AND PERSON_ID = LS_PERSON_ID
		AND ROLE_ID = 47; -- Modify Project Outcome
		IF LI_PI_ROLE = 0 THEN
			SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0)+1 INTO LI_PROPOSAL_PERSON_ROLE_ID FROM EPS_PROPOSAL_PERSON_ROLES;
			INSERT INTO EPS_PROPOSAL_PERSON_ROLES
			(PROPOSAL_PERSON_ROLE_ID,PROPOSAL_ID,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_PROPOSAL_PERSON_ROLE_ID,LI_PROPOSAL_ID,LS_PERSON_ID,47,NOW(),'quickstart');
			commit;
		END IF;
		SELECT COUNT(1) INTO LI_PI_ROLE FROM EPS_PROPOSAL_PERSON_ROLES
		WHERE PROPOSAL_ID = LI_PROPOSAL_ID
		AND PERSON_ID = LS_PERSON_ID
		AND ROLE_ID = 48;  -- Withdraw Request
		IF LI_PI_ROLE = 0 THEN
			SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0)+1 INTO LI_PROPOSAL_PERSON_ROLE_ID FROM EPS_PROPOSAL_PERSON_ROLES;
			INSERT INTO EPS_PROPOSAL_PERSON_ROLES
			(PROPOSAL_PERSON_ROLE_ID,PROPOSAL_ID,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_PROPOSAL_PERSON_ROLE_ID,LI_PROPOSAL_ID,LS_PERSON_ID,48,NOW(),'quickstart');
			commit;
		END IF;
		SELECT COUNT(1) INTO LI_PI_ROLE FROM EPS_PROPOSAL_PERSON_ROLES
		WHERE PROPOSAL_ID = LI_PROPOSAL_ID
		AND PERSON_ID = LS_PERSON_ID
		AND ROLE_ID = 653;  -- Principle Investigator
		IF LI_PI_ROLE = 0 THEN
			SELECT IFNULL(MAX(PROPOSAL_PERSON_ROLE_ID),0)+1 INTO LI_PROPOSAL_PERSON_ROLE_ID FROM EPS_PROPOSAL_PERSON_ROLES;
			INSERT INTO EPS_PROPOSAL_PERSON_ROLES
			(PROPOSAL_PERSON_ROLE_ID,PROPOSAL_ID,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_PROPOSAL_PERSON_ROLE_ID,LI_PROPOSAL_ID,LS_PERSON_ID,653,NOW(),'quickstart');
			commit;
		END IF;
		END LOOP;
		CLOSE CUR_SEL_DATA;
		END;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE EPS_PROP_PERSON_ROLE_ID_GENERATOR SET NEXT_VAL = (SELECT MAX(PROPOSAL_PERSON_ROLE_ID)+1 FROM EPS_PROPOSAL_PERSON_ROLES);
		COMMIT;
END
$$
DELIMITER ;
