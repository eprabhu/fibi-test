DELIMITER $$
CREATE  PROCEDURE `MIGRATION_POSTVAL_MATRIX_INTERNAL`(AV_TYPE INT)
BEGIN
DECLARE LI_SOURCE_COUNT          int;
DECLARE LI_DESTINATION_COUNT     int;
select count(distinct(NAME_OF_GRANT_CALL)) into LI_SOURCE_COUNT from MIGRATION_PROPOSAL_INTERNAL_00_17;
select count(distinct(NAME_OF_GRANT_CALL)) into LI_DESTINATION_COUNT from  MIGRATION_PROPOSAL_INTERNAL_00_17;
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('GRANT_CALL','TOTAL NUMBER OF DISTINCT GRANT CALLS',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_PROPOSAL_INTERNAL_00_17 ;
select count(*) into LI_DESTINATION_COUNT from EPS_PROPOSAL where APPLICATION_ID in (select APPLICATION_ID from MIGRATION_PROPOSAL_INTERNAL_00_17);
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROPOSAL','TOTAL NUMBER OF DISTINCT PROPOSALS',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
select COUNT(*) INTO LI_SOURCE_COUNT from MIGRATION_PROPOSAL_INTERNAL_00_17 where PROPOSAL_STATUS = 'Awarded';
select count(*) into LI_DESTINATION_COUNT from EPS_PROPOSAL where APPLICATION_ID in (select APPLICATION_ID from MIGRATION_PROPOSAL_INTERNAL_00_17)
and status_code in (SELECT STATUS_CODE FROM EPS_PROPOSAL_STATUS
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER('Awarded')));
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROPOSAL','TOTAL NUMBER OF DISTINCT PROPOSALS WITH PROPOSAL_STATUS ''Awarded''',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
select COUNT(*) INTO LI_SOURCE_COUNT from MIGRATION_PROPOSAL_INTERNAL_00_17 where PROPOSAL_STATUS = 'Unsuccessful';
select count(*) into LI_DESTINATION_COUNT from EPS_PROPOSAL where APPLICATION_ID in (select APPLICATION_ID from MIGRATION_PROPOSAL_INTERNAL_00_17)
and status_code in (SELECT STATUS_CODE FROM EPS_PROPOSAL_STATUS
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER('Unsuccessful')));
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROPOSAL','TOTAL NUMBER OF DISTINCT PROPOSALS WITH PROPOSAL_STATUS ''Unsuccessful''',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_PROPOSAL_PERSONS_INTERNAL_00_17 ;
select count(*) into LI_DESTINATION_COUNT from EPS_PROPOSAL_PERSONS
where proposal_id in (select proposal_id from EPS_PROPOSAL where APPLICATION_ID in (select APPLICATION_ID from MIGRATION_PROPOSAL_INTERNAL_00_17));
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROPOSAL_PERSON','TOTAL NUMBER OF DISTINCT PROPOSAL PERSONS ',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
select COUNT(*) INTO LI_SOURCE_COUNT from MIGRATION_PROPOSAL_PERSONS_INTERNAL_00_17 where UPPER(TRIM(PROJECT_TEAM_ROLE)) = UPPER('Principal Investigator');
select count(*) into LI_DESTINATION_COUNT  from EPS_PROPOSAL_PERSONS
where proposal_id in (select proposal_id from EPS_PROPOSAL where APPLICATION_ID in (select APPLICATION_ID from MIGRATION_PROPOSAL_INTERNAL_00_17))
and PI_FLAG = 'Y';
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROPOSAL_PERSON','TOTAL NUMBER OF DISTINCT PROPOSAL PI''s ',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_AWARD_INTERNAL_00_17 ;
select count(*) into LI_DESTINATION_COUNT from AWARD where award_id in (select version_award_id from MIGRATION_AWARD_INTERNAL_00_17);
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT','TOTAL NUMBER OF DISTINCT PROJECTS',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_AWARD_INTERNAL_00_17 where PROJECT_STATUS = 'Live';
select count(*) into LI_DESTINATION_COUNT from AWARD where award_id in (select version_award_id from MIGRATION_AWARD_INTERNAL_00_17)
and STATUS_CODE in (SELECT STATUS_CODE
				FROM AWARD_STATUS
				WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM('Live')));
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT','TOTAL NUMBER OF DISTINCT PROJECTS WITH AWARD_STATUS ''Live''',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_AWARD_INTERNAL_00_17 where PROJECT_STATUS = 'Terminated by SMU';
select count(*) into LI_DESTINATION_COUNT from AWARD where award_id in (select version_award_id from MIGRATION_AWARD_INTERNAL_00_17)
and STATUS_CODE in (SELECT STATUS_CODE
				FROM AWARD_STATUS
				WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM('Terminated by SMU')));
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT','TOTAL NUMBER OF DISTINCT PROJECTS WITH AWARD_STATUS ''Terminated by SMU''',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_AWARD_INTERNAL_00_17 where PROJECT_STATUS = 'Closed';
select count(*) into LI_DESTINATION_COUNT from AWARD where award_id in (select version_award_id from MIGRATION_AWARD_INTERNAL_00_17)
and STATUS_CODE in (SELECT STATUS_CODE
				FROM AWARD_STATUS
				WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM('Closed')));
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT','TOTAL NUMBER OF DISTINCT PROJECTS WITH AWARD_STATUS ''Closed''',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_DESTINATION_COUNT = LI_SOURCE_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
SELECT COUNT(*) INTO LI_SOURCE_COUNT
FROM  MIGRATION_AWARD_PERSONS_INTERNAL_00_17 ;
select count(*) into LI_DESTINATION_COUNT from AWARD_PERSONS
where award_id in (select award_id  from MIGRATION_AWARD_INTERNAL_00_17);
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT_PERSON','TOTAL NUMBER OF DISTINCT PROJECT PERSONS',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED') ,NULL);
COMMIT;
select count(*) into LI_SOURCE_COUNT from MIGRATION_AWARD_PERSONS_INTERNAL_00_17 where MEMBER_TYPE = 'SMU Employee';
select count(*) into LI_DESTINATION_COUNT from AWARD_PERSONS
where award_id in (select award_id  from MIGRATION_AWARD_INTERNAL_00_17)
and PERSON_ID is not null;
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT_PERSON','TOTAL NUMBER OF DISTINCT EMPLOYEES IN PROJECTS',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED') ,NULL);
COMMIT;
select count(*) into LI_SOURCE_COUNT from MIGRATION_AWARD_PERSONS_INTERNAL_00_17 where MEMBER_TYPE = 'Non-SMU Employee';
select count(*) into LI_DESTINATION_COUNT from AWARD_PERSONS
where award_id in (select award_id  from MIGRATION_AWARD_INTERNAL_00_17)
and ROLODEX_ID is not null;
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT_PERSON','TOTAL NUMBER OF DISTINCT NON_EMPLOYEES IN PROJECTS',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED') ,NULL);
COMMIT;
select round(sum(ORIGINAL_APPROVED_BUDGET))  into LI_SOURCE_COUNT from MIGRATION_AWARD_budget_INTERNAL_00_17;
select round(sum(TOTAL_COST))  into LI_DESTINATION_COUNT from award_budget_header where award_id in (select version_award_id from MIGRATION_AWARD_INTERNAL_00_17);
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT_BUDGET','TOTAL AWARD BUDGET COST',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
select count(*) into LI_SOURCE_COUNT  from PROPOSAL where grant_header_id in (select grant_header_id from MIGRATION_PROPOSAL_INTERNAL_00_17);
select count(*) into LI_DESTINATION_COUNT  from  MIGRATION_AWARD_INTERNAL_00_17;
INSERT INTO MIGRATION_TEST_MATRIX(MODULE,TEST_CASE,CRITERIA,SOURCE_COUNT,DESTINATION_COUNT,STATUS,FILE_TYPE)
VALUES('PROJECT_BUDGET','TOTAL NUMBER OF INSTITUTE PROPOSALS GENERATED',NULL,LI_SOURCE_COUNT,LI_DESTINATION_COUNT,IF(LI_SOURCE_COUNT = LI_DESTINATION_COUNT,'SUCCESS','FAILED'),NULL);
COMMIT;
END
$$
DELIMITER ;
