DELIMITER $$
CREATE  PROCEDURE `smu_update_awd_budget_person`()
BEGIN
DECLARE LI_FLAG					INT(5);
DECLARE LS_CODE 		CHAR(5) DEFAULT '00000';
DECLARE LS_MSG 			TEXT;
DECLARE LS_ERROR       	VARCHAR(1000);
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LI_BUDGET_HEADER_ID int(11);
DECLARE LI_BUDGET_PERSON_ID INT(11);
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT BUDGET_HEADER_ID FROM AWARD_BUDGET_HEADER;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
	OPEN CUR_SEL_DATA;
	INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LI_BUDGET_HEADER_ID;
	IF DONE1 THEN
		LEAVE INSERT_LOOP;
	END IF;
	SELECT COUNT(1) INTO LI_FLAG
	FROM AWARD_BUDGET_PERSONS
	WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID;
	IF LI_FLAG = 0 THEN
		SELECT IFNULL(MAX(BUDGET_PERSON_ID),0)+1 INTO LI_BUDGET_PERSON_ID
		FROM AWARD_BUDGET_PERSONS;
		INSERT INTO AWARD_BUDGET_PERSONS (
		BUDGET_PERSON_ID,
		APPOINTMENT_TYPE_CODE,
		BUDGET_HEADER_ID,
		CALCULATION_BASE,
		EFFECTIVE_DATE,
		JOB_CODE,
		NON_EMPLOYEE_FLAG,
		PERSON_ID,
		PERSON_NAME,
		ROLODEX_ID,
		SALARY_ANNIVERSARY_DATE,
		TBN_ID,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		PERSON_TYPE
		)
		VALUES(
		LI_BUDGET_PERSON_ID,
		NULL,
		LI_BUDGET_HEADER_ID,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		NULL,
		1,
		NOW(),
		'quickstart',
		'T'
		);
	END IF;
     update award_budget_person_id_generator set next_val = LI_BUDGET_PERSON_ID;
	END LOOP;
	CLOSE CUR_SEL_DATA;
	END;
END
$$
DELIMITER ;
