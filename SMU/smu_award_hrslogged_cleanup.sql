CREATE  PROCEDURE `smu_award_hrslogged_cleanup`()
BEGIN
DECLARE ls_award_number 	VARCHAR(20);
DECLARE ls_account_number 	VARCHAR(20);
DECLARE ls_fund_code        VARCHAR(100);
DECLARE ls_io_code          VARCHAR(50);
DECLARE DONE1 INT DEFAULT FALSE;
DECLARE LI_FLAG INT;
DECLARE INSERT_CURSOR CURSOR FOR
SELECT FUND_CODE,
IO_CODE
FROM AWARD_HOURS_LOG_RT;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
OPEN INSERT_CURSOR;
INSERT_CURSOR_LOOP : LOOP
        FETCH INSERT_CURSOR INTO ls_fund_code,ls_io_code;
		IF DONE1 THEN
			LEAVE INSERT_CURSOR_LOOP;
		END IF;
	IF ls_fund_code = '' THEN
		SET ls_fund_code = NULL;
	END IF;
	SELECT COUNT(1) INTO LI_FLAG FROM AWARD_HOURS_LOGGED
	WHERE IFNULL(trim(upper(ACCOUNT_NUMBER)),'0') = IFNULL(trim(upper(ls_fund_code)),'0');
	IF LI_FLAG > 0 THEN
		DELETE FROM AWARD_HOURS_LOGGED
		WHERE IFNULL(trim(upper(ACCOUNT_NUMBER)),'0') = IFNULL(trim(upper(ls_fund_code)),'0');
	END IF;
     SET LS_FUND_CODE = NULL;
	END LOOP;
CLOSE INSERT_CURSOR;
END
$$
DELIMITER ;
