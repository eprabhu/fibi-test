DELIMITER $$
CREATE  PROCEDURE `MERGE_AWD_SECTION_DISTRIBUTION`(
AV_AWARD_ID 			DECIMAL(22,0),
AV_AWARD_NUMBER			VARCHAR(12),
AV_SEQUENCE_NUMBER		INT(4),
AV_VARIATION_TYPE_CODE	VARCHAR(3),
AV_UPDATE_USER			VARCHAR(60)
)
BEGIN
DECLARE LS_ERROR_MSG						VARCHAR(1000);
DECLARE LS_TABLE_NAME						VARCHAR(30);
DECLARE LI_FLAG								INT;
DECLARE LI_MASTER_AWARD_ID					DECIMAL(22,0);
DECLARE LI_MASTER_SEQ_NUMBER				INT(4);
DECLARE LI_AWARD_DIST_NEXT_VAL			BIGINT(20);
DECLARE LI_AWARD_DIST_ST_CNT				INT(10);
DECLARE LS_BUDGET_PERIOD 			INT(11);
DECLARE	LS_COMMENT 					VARCHAR(4000);
DECLARE	LS_CREATE_TIMESTAMP 		DATETIME;
DECLARE	LS_CREATE_USER 				VARCHAR(60);
DECLARE	LS_END_DATE 				DATETIME;
DECLARE	LS_START_DATE 				DATETIME;
DECLARE	LS_TOTAL_DIRECT_COST		DECIMAL(12,2);
DECLARE	LS_TOTAL_INDIRECT_COST		DECIMAL(12,2);
DECLARE LS_UPDATE_TIMESTAMP	DATETIME;
DECLARE LS_UPDATE_USER		VARCHAR(60);
	BEGIN
			DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
			BEGIN
				GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
				 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
				SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
				SELECT @full_error INTO LS_ERROR_MSG;
				INSERT INTO AWARD_ERROR_LOG(AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, ERROR_MESSAGE, PROCEDURE_NAME, TABLE_NAME,SECTION_CODE,VARIATION_TYPE_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
				VALUES(AV_AWARD_ID,AV_AWARD_NUMBER,AV_SEQUENCE_NUMBER,LS_ERROR_MSG,'MERGE_AWD_SECTION_DISTRIBUTION',LS_TABLE_NAME,123,AV_VARIATION_TYPE_CODE,UTC_TIMESTAMP(),AV_UPDATE_USER);
				COMMIT;
			END;
			SELECT COUNT(1) INTO LI_FLAG
			FROM AWARD
			WHERE AWARD_NUMBER = AV_AWARD_NUMBER
			AND SEQUENCE_NUMBER = 0;
			IF LI_FLAG > 0 THEN
				SELECT AWARD_ID,SEQUENCE_NUMBER
				INTO LI_MASTER_AWARD_ID,LI_MASTER_SEQ_NUMBER
				FROM AWARD
				WHERE AWARD_NUMBER = AV_AWARD_NUMBER
				AND SEQUENCE_NUMBER = 0;
			END IF;
			DELETE FROM AWARD_AMT_FNA_DISTRIBUTION
			WHERE AWARD_ID = LI_MASTER_AWARD_ID;
			SELECT IFNULL(MAX(NEXT_VAL),0) INTO LI_AWARD_DIST_NEXT_VAL
			FROM SEQ_AWD_AMT_FNA_DSTN_ID_GNTR;
			SELECT COUNT(1) INTO LI_AWARD_DIST_ST_CNT
			FROM AWARD_AMT_FNA_DISTRIBUTION
			WHERE AWARD_ID = AV_AWARD_ID;
			UPDATE SEQ_AWD_AMT_FNA_DSTN_ID_GNTR
			SET NEXT_VAL = LI_AWARD_DIST_NEXT_VAL + LI_AWARD_DIST_ST_CNT + 1;
			COMMIT;
			SET LS_TABLE_NAME = 'AWARD_AMT_FNA_DISTRIBUTION';
            BEGIN
				DECLARE DONE1 INT DEFAULT FALSE;
				DECLARE CUR_AWARD_AMT_DIST_ST CURSOR FOR
				SELECT
					BUDGET_PERIOD,
					COMMENT,
					CREATE_TIMESTAMP,
					CREATE_USER,
					END_DATE,
					START_DATE,
					TOTAL_DIRECT_COST,
					TOTAL_INDIRECT_COST,
					UPDATE_TIMESTAMP,
					UPDATE_USER
				FROM AWARD_AMT_FNA_DISTRIBUTION
				WHERE AWARD_ID = AV_AWARD_ID;
				DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
				OPEN CUR_AWARD_AMT_DIST_ST;
				INSERT_CUR_AWARD_AMT_DIST_ST_LOOP: LOOP
				FETCH CUR_AWARD_AMT_DIST_ST INTO
					LS_BUDGET_PERIOD,
					LS_COMMENT,
					LS_CREATE_TIMESTAMP,
					LS_CREATE_USER,
					LS_END_DATE,
					LS_START_DATE,
					LS_TOTAL_DIRECT_COST,
					LS_TOTAL_INDIRECT_COST,
					LS_UPDATE_TIMESTAMP,
					LS_UPDATE_USER;
				IF DONE1 THEN
					LEAVE INSERT_CUR_AWARD_AMT_DIST_ST_LOOP;
				END IF;
				SET LI_AWARD_DIST_NEXT_VAL = LI_AWARD_DIST_NEXT_VAL + 1;
				INSERT INTO AWARD_AMT_FNA_DISTRIBUTION(
				FNA_DISTRIBUTION_ID,
				AWARD_ID,
				AWARD_NUMBER,
				SEQUENCE_NUMBER,
				BUDGET_PERIOD,
				COMMENT,
				CREATE_TIMESTAMP,
				CREATE_USER,
				END_DATE,
				START_DATE,
				TOTAL_DIRECT_COST,
				TOTAL_INDIRECT_COST,
				UPDATE_TIMESTAMP,
				UPDATE_USER
				)
				VALUES
				(
				LI_AWARD_DIST_NEXT_VAL,
				LI_MASTER_AWARD_ID,
				AV_AWARD_NUMBER,
				LI_MASTER_SEQ_NUMBER,
				LS_BUDGET_PERIOD,
				LS_COMMENT,
				LS_CREATE_TIMESTAMP,
				LS_CREATE_USER,
				LS_END_DATE,
				LS_START_DATE,
				LS_TOTAL_DIRECT_COST,
				LS_TOTAL_INDIRECT_COST,
				LS_UPDATE_TIMESTAMP,
				LS_UPDATE_USER
				);
				END LOOP;
				CLOSE CUR_AWARD_AMT_DIST_ST;
			END;
	END;
END
$$
DELIMITER ;
