DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PROPOSAL`(
av_id int
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_ERROR_MSG 		VARCHAR(1000);
DECLARE LS_SUBMISSION_DATE VARCHAR(20);
DECLARE LS_INTERNAL_DEADLINE_DATE VARCHAR(20);
DECLARE LS_PROPOSAL_STATUS VARCHAR(200);
DECLARE LS_APPLICATION_ID VARCHAR(50);
DECLARE LS_EXTERNAL_FUNDING_AGENCY_ID VARCHAR(50);
DECLARE LS_TITLE VARCHAR(2000);
DECLARE LS_ACTIVITY_TYPE VARCHAR(50);
DECLARE LS_DISCIPLINE_CLUSTER VARCHAR(200);
DECLARE LS_PROPOSAL_LEAD_UNIT VARCHAR(500);
DECLARE LS_PROPOSED_START_DATE VARCHAR(20);
DECLARE LS_PROPOSED_END_DATE VARCHAR(20);
DECLARE LS_PROJECT_DURATION VARCHAR(10);
DECLARE LS_KEYWORDS_OF_RESEARCH LONGTEXT;
DECLARE LS_GRANT_CALL_ID VARCHAR(10);
DECLARE LS_TYPE_OF_GRANT VARCHAR(200);
DECLARE LS_NAME_OF_GRANT_CALL VARCHAR(1000);
DECLARE LS_NAME_OF_FUNDING_AGENCY VARCHAR(500);
DECLARE LS_NAME_OF_FUNDING_SCHEME VARCHAR(500);
DECLARE LS_TYPE_OF_FUNDING_AGENCY VARCHAR(500);
DECLARE LS_GRANT_CALL_THEME LONGTEXT;
DECLARE LS_GRANT_CALL_CLOSING_DATE VARCHAR(20);
DECLARE LS_INTERNAL_SUBMISSION_DATE VARCHAR(20);
DECLARE LS_RESEARCH_AREA VARCHAR(500);
DECLARE LS_RESEARCH_SUB_AREA VARCHAR(500);
DECLARE LS_SOCIETAL_CHALLENGE_AREA VARCHAR(500);
DECLARE LS_SOCIETAL_CHALLENGE_SUB_AREA VARCHAR(500);
DECLARE LS_RESEARCH_AREA_DESC LONGTEXT;
DECLARE LS_MULTI_DISCIPLINARY_DESC LONGTEXT;
DECLARE LS_ABSTRACT_DESC LONGTEXT;
DECLARE LS_STRATEGY_FOR_EXTERNAL_FUNDING VARCHAR(200);
DECLARE LS_DETAILS_RESEARCH_PROPOSAL VARCHAR(500);
DECLARE LS_CONFIDENTIALITY VARCHAR(500);
DECLARE LS_CONFIDENTIALITY_REMARKS VARCHAR(500);
DECLARE LS_FULL_NAME VARCHAR(100);
DECLARE LS_SPONSOR_TYPE VARCHAR(200);
DECLARE LS_SPONSOR VARCHAR(200);
DECLARE LS_START_DATE VARCHAR(20);
DECLARE LS_END_DATE VARCHAR(20);
DECLARE LS_AMOUNT VARCHAR(20);
DECLARE LS_FUNDING_STATUS VARCHAR(200);
DECLARE LS_ETHICS_CONSIDERATION VARCHAR(1000);
DECLARE LI_PROPOSAL_ID 			INT;
DECLARE LI_FLAG 				INT;
DECLARE LS_ACTIVITY_TYPE_CODE 	VARCHAR(3);
DECLARE LS_HOME_UNIT_NUMBER 	VARCHAR(10);
DECLARE LS_HOME_UNIT_NAME		VARCHAR(500);
DECLARE LI_STATUS_CODE			INT;
DECLARE LS_CLUSTER_CODE			INT;
DECLARE LI_RESRCH_AREA_ID		INT;
DECLARE LS_RESEARCH_AREA_CODE 		VARCHAR(3);
DECLARE LS_RESEARCH_SUB_AREA_CODE	VARCHAR(3);
DECLARE LS_CHALLENGE_AREA_CODE 		VARCHAR(3);
DECLARE LS_CHALLENGE_SUBAREA_CODE 	VARCHAR(3);
DECLARE LI_SPONSOR_ID			INT;
DECLARE LS_SPONSOR_CODE			VARCHAR(20);
DECLARE LI_FUNDING_STATUS_CODE	INT;
DECLARE LS_SPONSOR_TYPE_CODE	VARCHAR(3);
DECLARE LI_GRANT_HEADER_ID		INT;
DECLARE LI_GRANT_TYPE_CODE INT;
DECLARE LS_GRANT_SPONSOR_CODE VARCHAR(6);
DECLARE LS_GRANT_CLOSING_DATE DATETIME;
DECLARE LS_SPONSOR_NAME		VARCHAR(200);
DECLARE LS_KEYWORD_LIST		VARCHAR(4000);
DECLARE LS_KEYWORD			VARCHAR(200);
DECLARE LI_KEYWORD_ID		INT;
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'EXCEPTION','PROPOSAL',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
		SUBMISSION_DATE,
		INTERNAL_DEADLINE_DATE,
		PROPOSAL_STATUS,
		APPLICATION_ID,
		EXTERNAL_FUNDING_AGENCY_ID,
		TITLE,
		ACTIVITY_TYPE,
		DISCIPLINE_CLUSTER,
		PROPOSAL_LEAD_UNIT,
		PROPOSED_START_DATE,
		PROPOSED_END_DATE,
		PROJECT_DURATION,
		KEYWORDS_OF_RESEARCH,
		GRANT_CALL_ID,
		TYPE_OF_GRANT,
		NAME_OF_GRANT_CALL,
		NAME_OF_FUNDING_AGENCY,
		NAME_OF_FUNDING_SCHEME,
		TYPE_OF_FUNDING_AGENCY,
		GRANT_CALL_THEME,
		GRANT_CALL_CLOSING_DATE,
		INTERNAL_SUBMISSION_DATE,
		RESEARCH_AREA,
		RESEARCH_SUB_AREA,
		SOCIETAL_CHALLENGE_AREA,
		SOCIETAL_CHALLENGE_SUB_AREA,
		RESEARCH_AREA_DESC,
		MULTI_DISCIPLINARY_DESC,
		ABSTRACT_DESC,
		STRATEGY_FOR_EXTERNAL_FUNDING,
		DETAILS_RESEARCH_PROPOSAL,
		CONFIDENTIALITY,
		CONFIDENTIALITY_REMARKS,
		FULL_NAME,
		SPONSOR_TYPE,
		SPONSOR_CODE,
		START_DATE,
		END_DATE,
		AMOUNT,
		FUNDING_STATUS,
		ETHICS_CONSIDERATION,
		GRANT_HEADER_ID
		FROM MIGRATION_PROPOSAL
		WHERE APPLICATION_ID NOT IN(212,186,178,166,164,146,125,114,108,104);
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_SUBMISSION_DATE,
		LS_INTERNAL_DEADLINE_DATE,
		LS_PROPOSAL_STATUS,
		LS_APPLICATION_ID,
		LS_EXTERNAL_FUNDING_AGENCY_ID,
		LS_TITLE,
		LS_ACTIVITY_TYPE,
		LS_DISCIPLINE_CLUSTER,
		LS_PROPOSAL_LEAD_UNIT,
		LS_PROPOSED_START_DATE,
		LS_PROPOSED_END_DATE,
		LS_PROJECT_DURATION,
		LS_KEYWORDS_OF_RESEARCH,
		LS_GRANT_CALL_ID,
		LS_TYPE_OF_GRANT,
		LS_NAME_OF_GRANT_CALL,
		LS_NAME_OF_FUNDING_AGENCY,
		LS_NAME_OF_FUNDING_SCHEME,
		LS_TYPE_OF_FUNDING_AGENCY,
		LS_GRANT_CALL_THEME,
		LS_GRANT_CALL_CLOSING_DATE,
		LS_INTERNAL_SUBMISSION_DATE,
		LS_RESEARCH_AREA,
		LS_RESEARCH_SUB_AREA,
		LS_SOCIETAL_CHALLENGE_AREA,
		LS_SOCIETAL_CHALLENGE_SUB_AREA,
		LS_RESEARCH_AREA_DESC,
		LS_MULTI_DISCIPLINARY_DESC,
		LS_ABSTRACT_DESC,
		LS_STRATEGY_FOR_EXTERNAL_FUNDING,
		LS_DETAILS_RESEARCH_PROPOSAL,
		LS_CONFIDENTIALITY,
		LS_CONFIDENTIALITY_REMARKS,
		LS_FULL_NAME,
		LS_SPONSOR_TYPE,
		LS_SPONSOR,
		LS_START_DATE,
		LS_END_DATE,
		LS_AMOUNT,
		LS_FUNDING_STATUS,
		LS_ETHICS_CONSIDERATION,
		LI_GRANT_HEADER_ID;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
        IF LS_ACTIVITY_TYPE IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM ACTIVITY_TYPE
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ACTIVITY_TYPE));
		IF LI_FLAG > 0 THEN
			SELECT ACTIVITY_TYPE_CODE INTO LS_ACTIVITY_TYPE_CODE
			FROM ACTIVITY_TYPE
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_ACTIVITY_TYPE));
		END IF;
	ELSE
		SET LS_ACTIVITY_TYPE_CODE = 10;
	 END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM UNIT
		WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROPOSAL_LEAD_UNIT));
		IF LI_FLAG > 0 THEN
			SELECT UNIT_NUMBER,UNIT_NAME INTO LS_HOME_UNIT_NUMBER,LS_HOME_UNIT_NAME
			FROM UNIT
			WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROPOSAL_LEAD_UNIT));
		ELSE
			ITERATE INSERT_LOOP;
		END IF;
		IF ( IFNULL(TRIM(LS_PROPOSED_START_DATE),'')  = '' OR STR_TO_DATE(LS_PROPOSED_START_DATE,'%d/%m/%Y') IS NULL ) THEN
				ITERATE INSERT_LOOP;
		END IF;
		IF ( IFNULL(TRIM(LS_PROPOSED_END_DATE),'') = '' OR STR_TO_DATE(LS_PROPOSED_END_DATE,'%d/%m/%Y') IS NULL ) THEN
				ITERATE INSERT_LOOP;
		END IF;
		IF (  STR_TO_DATE(LS_PROPOSED_START_DATE,'%d/%m/%Y') IS NOT NULL AND TRIM(LS_PROPOSED_START_DATE) <> ''
			  AND STR_TO_DATE(LS_PROPOSED_END_DATE,'%d/%m/%Y') IS NOT NULL AND TRIM(LS_PROPOSED_END_DATE) <> ''
			  AND STR_TO_DATE(LS_PROPOSED_START_DATE,'%d/%m/%Y') > STR_TO_DATE(LS_PROPOSED_END_DATE,'%d/%m/%Y') )THEN
			  ITERATE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROPOSAL_STATUS
		WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_PROPOSAL_STATUS));
		IF LI_FLAG > 0 THEN
			SELECT STATUS_CODE INTO LI_STATUS_CODE FROM EPS_PROPOSAL_STATUS
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_PROPOSAL_STATUS));
		END IF;
		IF LS_TITLE IS NULL OR LS_TITLE = '' THEN
			ITERATE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROP_DISCIPLINE_CLUSTER
		WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_DISCIPLINE_CLUSTER));
		IF LI_FLAG > 0 THEN
			SELECT CLUSTER_CODE INTO LS_CLUSTER_CODE FROM EPS_PROP_DISCIPLINE_CLUSTER
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_DISCIPLINE_CLUSTER));
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM
		GRANT_CALL_HEADER WHERE GRANT_HEADER_ID = LI_GRANT_HEADER_ID;
		IF LI_FLAG > 0 THEN
			SELECT T1.GRANT_TYPE_CODE,T1.SPONSOR_CODE,T1.NAME,T1.CLOSING_DATE,T2.SPONSOR_NAME
			INTO LI_GRANT_TYPE_CODE,LS_GRANT_SPONSOR_CODE,LS_NAME_OF_GRANT_CALL,
			LS_GRANT_CLOSING_DATE,LS_SPONSOR_NAME
			FROM GRANT_CALL_HEADER T1
			LEFT OUTER JOIN SPONSOR T2 ON T1.SPONSOR_CODE = T2.SPONSOR_CODE
			WHERE GRANT_HEADER_ID = LI_GRANT_HEADER_ID;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM MIGRATION_PROPOSAL_EXT
		WHERE APPLICATION_ID = LS_APPLICATION_ID;
		IF LI_FLAG > 0 THEN
			SELECT RESEARCH_ABSTRACT INTO LS_ABSTRACT_DESC
			FROM MIGRATION_PROPOSAL_EXT
			WHERE APPLICATION_ID = LS_APPLICATION_ID;
		END IF;
		-- SELECT IFNULL(MAX(PROPOSAL_ID),0)+1 INTO LI_PROPOSAL_ID FROM EPS_PROPOSAL;
		SELECT NEXT_VAL INTO LI_PROPOSAL_ID FROM EPS_PROPOSAL_ID_GENERATOR;
		INSERT INTO EPS_PROPOSAL(
		PROPOSAL_ID,
		ABSTRACT_DESC,
		ACTIVITY_TYPE_CODE,
		CREATE_TIMESTAMP,
		CREATE_USER,
		END_DATE,
		GRANT_HEADER_ID,
		GRANT_TYPE_CODE,
		HOME_UNIT_NAME,
		HOME_UNIT_NUMBER,
		RESEARCH_AREA_DESC,
		SPONSOR_CODE,
		SPONSOR_NAME,
		START_DATE,
		STATUS_CODE,
		SUBMISSION_DATE,
		TITLE,
		TYPE_CODE,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		INTERNAL_DEADLINE_DATE,
		SPONSOR_DEADLINE_DATE,
		APPLICATION_ID,
		CLUSTER_CODE,
		GRANT_CALL_NAME,
		GRANT_CALL_CLOSING_DATE,
		MULTI_DISCIPLINARY_DESC,
		EXTERNAL_FUNDING_AGENCY_ID,
		SUBMIT_USER
		)
		VALUES(
		LI_PROPOSAL_ID,
		LS_ABSTRACT_DESC,
		LS_ACTIVITY_TYPE_CODE,
		NOW(),
		'quickstart',
		STR_TO_DATE(LS_PROPOSED_END_DATE,'%d/%m/%Y'),
		LI_GRANT_HEADER_ID,
		LI_GRANT_TYPE_CODE,
		LS_HOME_UNIT_NAME,
		LS_HOME_UNIT_NUMBER,
		LS_RESEARCH_AREA_DESC,
		LS_GRANT_SPONSOR_CODE,
		LS_SPONSOR_NAME,
		STR_TO_DATE(LS_PROPOSED_START_DATE,'%d/%m/%Y'),
		LI_STATUS_CODE,
		STR_TO_DATE(LS_SUBMISSION_DATE,'%d/%m/%Y'),
		LS_TITLE,
		1,
		NOW(),
		'quickstart',
		STR_TO_DATE(LS_INTERNAL_DEADLINE_DATE,'%d/%m/%Y'),
		NULL,
		LS_APPLICATION_ID,
		LS_CLUSTER_CODE,
		LS_NAME_OF_GRANT_CALL,
		LS_GRANT_CLOSING_DATE,
		LS_MULTI_DISCIPLINARY_DESC,
		LS_EXTERNAL_FUNDING_AGENCY_ID,
		'quickstart'
		);
		IF LS_KEYWORDS_OF_RESEARCH IS NOT NULL THEN
			SET LS_KEYWORD_LIST = LS_KEYWORDS_OF_RESEARCH;
			WHILE LS_KEYWORD_LIST != '' DO
				SET LS_KEYWORD = SUBSTRING_INDEX(LS_KEYWORD_LIST, ';', 1);
				SELECT IFNULL(MAX(KEYWORD_ID),0)+1 INTO LI_KEYWORD_ID FROM EPS_PROPOSAL_KEYWORDS;
				INSERT INTO EPS_PROPOSAL_KEYWORDS(KEYWORD_ID, SCIENCE_KEYWORD_CODE, UPDATE_TIMESTAMP, UPDATE_USER, PROPOSAL_ID, KEYWORD)
				VALUES(LI_KEYWORD_ID,NULL,NOW(),'quickstart',LI_PROPOSAL_ID,LS_KEYWORD);
				IF LOCATE(';', LS_KEYWORD_LIST) > 0 THEN
					SET LS_KEYWORD_LIST = SUBSTRING(LS_KEYWORD_LIST, LOCATE(';', LS_KEYWORD_LIST) + 1);
			   ELSE
					SET LS_KEYWORD_LIST = '';
			   END IF;
			END WHILE;
		END IF;
			SELECT COUNT(1) INTO LI_FLAG FROM RESEARCH_AREAS
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_RESEARCH_AREA));
			IF LI_FLAG > 0 THEN
				SELECT RESEARCH_AREA_CODE INTO LS_RESEARCH_AREA_CODE FROM RESEARCH_AREAS
				WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_RESEARCH_AREA));
				SELECT COUNT(1) INTO LI_FLAG FROM RESEARCH_AREAS
				WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_RESEARCH_SUB_AREA));
				IF LI_FLAG > 0 THEN
					SELECT RESEARCH_AREA_CODE INTO LS_RESEARCH_SUB_AREA_CODE FROM RESEARCH_AREAS
					WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_RESEARCH_SUB_AREA));
				END IF;
				SELECT IFNULL(MAX(RESRCH_AREA_ID),0)+1 INTO LI_RESRCH_AREA_ID FROM EPS_PROPOSAL_RESRCH_AREAS;
				INSERT INTO EPS_PROPOSAL_RESRCH_AREAS
				(
				RESRCH_AREA_ID,
				EXCELLENCE_AREA_CODE,
				RESEARCH_AREA_CODE,
				RESRCH_TYPE_CODE,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				PROPOSAL_ID,
				RESEARCH_SUB_AREA_CODE,
				CHALLENGE_AREA_CODE,
				CHALLENGE_SUBAREA_CODE
				)
				VALUES
				(
				LI_RESRCH_AREA_ID,
				NULL,
				LS_RESEARCH_AREA_CODE,
				1,
				NOW(),
				'quickstart',
				LI_PROPOSAL_ID,
				LS_RESEARCH_SUB_AREA_CODE,
				NULL,
				NULL
				);
			END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM SOCIETAL_CHALLENGE_AREA
		WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_SOCIETAL_CHALLENGE_AREA));
		IF LI_FLAG > 0 THEN
			SELECT CHALLENGE_AREA_CODE INTO LS_CHALLENGE_AREA_CODE FROM SOCIETAL_CHALLENGE_AREA
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_SOCIETAL_CHALLENGE_AREA));
			SELECT COUNT(1) INTO LI_FLAG FROM SOCIETAL_CHALLENGE_SUBAREA
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_SOCIETAL_CHALLENGE_SUB_AREA));
			IF LI_FLAG > 0 THEN
				SELECT CHALLENGE_SUBAREA_CODE INTO LS_CHALLENGE_SUBAREA_CODE FROM SOCIETAL_CHALLENGE_SUBAREA
				WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_SOCIETAL_CHALLENGE_SUB_AREA));
			END IF;
			SELECT IFNULL(MAX(RESRCH_AREA_ID),0)+1 INTO LI_RESRCH_AREA_ID FROM EPS_PROPOSAL_RESRCH_AREAS;
			INSERT INTO EPS_PROPOSAL_RESRCH_AREAS
			(
			RESRCH_AREA_ID,
			EXCELLENCE_AREA_CODE,
			RESEARCH_AREA_CODE,
			RESRCH_TYPE_CODE,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			PROPOSAL_ID,
			RESEARCH_SUB_AREA_CODE,
			CHALLENGE_AREA_CODE,
			CHALLENGE_SUBAREA_CODE
			)
			VALUES
			(
			LI_RESRCH_AREA_ID,
			NULL,
			NULL,
			2,
			NOW(),
			'quickstart',
			LI_PROPOSAL_ID,
			NULL,
			LS_CHALLENGE_AREA_CODE,
			LS_CHALLENGE_SUBAREA_CODE
			);
		END IF;
			SELECT COUNT(1) INTO LI_FLAG FROM SPONSOR
			WHERE TRIM(UPPER(SPONSOR_NAME)) = TRIM(UPPER(LS_SPONSOR));
			IF LI_FLAG > 0 THEN
				SELECT SPONSOR_CODE INTO LS_SPONSOR_CODE FROM SPONSOR
				WHERE TRIM(UPPER(SPONSOR_NAME)) = TRIM(UPPER(LS_SPONSOR));
				SELECT COUNT(1) INTO LI_FLAG FROM PROPOSAL_FUNDING_STATUS
				WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_FUNDING_STATUS));
				IF LI_FLAG > 0 THEN
					SELECT FUNDING_STATUS_CODE INTO LI_FUNDING_STATUS_CODE FROM EPS_PROPOSAL_FUNDING_STATUS
					WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_FUNDING_STATUS));
				END IF;
				SELECT COUNT(1) INTO LI_FLAG FROM SPONSOR_TYPE
				WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_SPONSOR_TYPE));
				IF LI_FLAG > 0 THEN
					SELECT SPONSOR_TYPE_CODE INTO LS_SPONSOR_TYPE_CODE FROM SPONSOR_TYPE
					WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_SPONSOR_TYPE));
				END IF;
				SELECT IFNULL(MAX(SPONSOR_ID),0)+1 INTO LI_SPONSOR_ID FROM EPS_PROPOSAL_SPONSORS;
				INSERT INTO EPS_PROPOSAL_SPONSORS
				(
				SPONSOR_ID,
				AMOUNT,
				END_DATE,
				SPONSOR_CODE,
				START_DATE,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				PROPOSAL_ID,
				FULL_NAME,
				FUNDING_STATUS_CODE,
				SPONSOR_NAME,
				SPONSOR_TYPE_CODE
				)
				VALUES
				(LI_SPONSOR_ID,
				LS_AMOUNT,
				DATE_FORMAT(STR_TO_DATE(LS_END_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
				LS_SPONSOR_CODE,
				DATE_FORMAT(STR_TO_DATE(LS_START_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
				NOW(),
				'quickstart',
				LI_PROPOSAL_ID,
				LS_FULL_NAME,
				LI_FUNDING_STATUS_CODE,
				LS_SPONSOR,
				LS_SPONSOR_TYPE_CODE
				);
			END IF;
	UPDATE MIGRATION_PROPOSAL SET PROPOSAL_ID = LI_PROPOSAL_ID
	WHERE APPLICATION_ID = LS_APPLICATION_ID;
	UPDATE EPS_PROPOSAL_ID_GENERATOR SET NEXT_VAL = LI_PROPOSAL_ID+1;
	SET LS_SUBMISSION_DATE=NULL;
	SET LS_INTERNAL_DEADLINE_DATE=NULL;
	SET LS_PROPOSAL_STATUS=NULL;
	SET LS_APPLICATION_ID=NULL;
	SET LS_EXTERNAL_FUNDING_AGENCY_ID=NULL;
	SET LS_TITLE=NULL;
	SET LS_ACTIVITY_TYPE=NULL;
	SET LS_DISCIPLINE_CLUSTER=NULL;
	SET LS_PROPOSAL_LEAD_UNIT=NULL;
	SET LS_PROPOSED_START_DATE=NULL;
	SET LS_PROPOSED_END_DATE=NULL;
	SET LS_PROJECT_DURATION=NULL;
	SET LS_KEYWORDS_OF_RESEARCH=NULL;
	SET LS_GRANT_CALL_ID=NULL;
	SET LS_TYPE_OF_GRANT=NULL;
	SET LS_NAME_OF_GRANT_CALL=NULL;
	SET LS_NAME_OF_FUNDING_AGENCY=NULL;
	SET LS_NAME_OF_FUNDING_SCHEME=NULL;
	SET LS_TYPE_OF_FUNDING_AGENCY=NULL;
	SET LS_GRANT_CALL_THEME=NULL;
	SET LS_GRANT_CALL_CLOSING_DATE=NULL;
	SET LS_INTERNAL_SUBMISSION_DATE=NULL;
	SET LS_RESEARCH_AREA=NULL;
	SET LS_RESEARCH_SUB_AREA=NULL;
	SET LS_SOCIETAL_CHALLENGE_AREA=NULL;
	SET LS_SOCIETAL_CHALLENGE_SUB_AREA=NULL;
	SET LS_RESEARCH_AREA_DESC=NULL;
	SET LS_MULTI_DISCIPLINARY_DESC=NULL;
	SET LS_ABSTRACT_DESC=NULL;
	SET LS_STRATEGY_FOR_EXTERNAL_FUNDING=NULL;
	SET LS_DETAILS_RESEARCH_PROPOSAL=NULL;
	SET LS_CONFIDENTIALITY=NULL;
	SET LS_CONFIDENTIALITY_REMARKS=NULL;
	SET LS_FULL_NAME=NULL;
	SET LS_SPONSOR_TYPE=NULL;
	SET LS_SPONSOR=NULL;
	SET LS_START_DATE=NULL;
	SET LS_END_DATE=NULL;
	SET LS_AMOUNT=NULL;
	SET LS_FUNDING_STATUS=NULL;
	SET LS_ETHICS_CONSIDERATION=NULL;
	SET LI_PROPOSAL_ID=NULL;
	SET LI_FLAG=NULL;
	SET LS_ACTIVITY_TYPE_CODE=NULL;
	SET LS_HOME_UNIT_NUMBER=NULL;
	SET LS_HOME_UNIT_NAME=NULL;
	SET LI_STATUS_CODE=NULL;
	SET LS_CLUSTER_CODE=NULL;
	SET LI_RESRCH_AREA_ID=NULL;
	SET LS_RESEARCH_AREA_CODE=NULL;
	SET LS_RESEARCH_SUB_AREA_CODE=NULL;
	SET LS_CHALLENGE_AREA_CODE=NULL;
	SET LS_CHALLENGE_SUBAREA_CODE=NULL;
	SET LI_SPONSOR_ID=NULL;
	SET LS_SPONSOR_CODE=NULL;
	SET LI_FUNDING_STATUS_CODE=NULL;
	SET LS_SPONSOR_TYPE_CODE=NULL;
	SET LI_GRANT_HEADER_ID=NULL;
	SET LI_GRANT_TYPE_CODE =NULL;
	SET LS_GRANT_SPONSOR_CODE=NULL;
	SET LS_GRANT_CLOSING_DATE=NULL;
	SET LS_SPONSOR_NAME=NULL;
	SET LS_KEYWORD_LIST=NULL;
	SET LS_KEYWORD=NULL;
	SET LI_KEYWORD_ID=NULL;
	END LOOP;
	CLOSE CUR_SEL_DATA;
    END;
	COMMIT;
