DELIMITER $$
CREATE  FUNCTION `FN_TOTALCOST_GRATER_AVAIL_FUND`(
AV_AWARD_ID INT
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_FLAG 					INT;
DECLARE LI_TOTAL_COST 				DECIMAL(13,2);
DECLARE LI_AMOUNT_OBLIGATED_TO_DATE DECIMAL(13,2);
	SELECT COUNT(1) INTO LI_FLAG
	FROM AWARD_BUDGET_HEADER
	WHERE AWARD_ID = AV_AWARD_ID;
	IF LI_FLAG > 0 THEN
		SELECT T1.TOTAL_COST INTO LI_TOTAL_COST
		FROM AWARD_BUDGET_HEADER T1
		WHERE T1.AWARD_ID = AV_AWARD_ID
		AND T1.VERSION_NUMBER = ( SELECT MAX(T2.VERSION_NUMBER) FROM AWARD_BUDGET_HEADER T2
								  WHERE T1.AWARD_ID = T2.AWARD_ID);
		SELECT COUNT(*) INTO LI_FLAG
		FROM AWARD_AMOUNT_INFO T1
		WHERE T1.AWARD_ID = AV_AWARD_ID
		AND T1.AWARD_AMOUNT_INFO_ID = (	SELECT  MAX(T2.AWARD_AMOUNT_INFO_ID)
										FROM AWARD_AMOUNT_INFO T2
										WHERE T1.AWARD_ID = T2.AWARD_ID
									  );
	   IF LI_FLAG = 0 THEN
			RETURN 'TRUE';
	   END IF;
		SELECT AMOUNT_OBLIGATED_TO_DATE INTO LI_AMOUNT_OBLIGATED_TO_DATE
		FROM AWARD_AMOUNT_INFO T1
		WHERE T1.AWARD_ID = AV_AWARD_ID
		AND T1.AWARD_AMOUNT_INFO_ID = (	SELECT  MAX(T2.AWARD_AMOUNT_INFO_ID)
								FROM AWARD_AMOUNT_INFO T2
								WHERE T1.AWARD_ID = T2.AWARD_ID
							  );
		IF LI_TOTAL_COST > LI_AMOUNT_OBLIGATED_TO_DATE THEN
			RETURN 'FALSE';
		ELSE
			RETURN 'TRUE';
		END IF;
	ELSE
		RETURN 'TRUE';
	END IF;
END
$$
DELIMITER ;
