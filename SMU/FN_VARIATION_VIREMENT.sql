DELIMITER $$
CREATE  FUNCTION `FN_VARIATION_VIREMENT`(
AV_AWARD_ID INT
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_MAX_VERSION 		INT;
DECLARE LS_BUDGET_HEADER 	INT;
DECLARE LI_INCREASE_FLAG 	INT;
DECLARE LI_DECREASE_FLAG 	INT;
DECLARE LI_FLAG 			INT;
	SELECT COUNT(1) INTO LI_FLAG FROM AWARD T1
	inner join grant_call_header t2 on t1.GRANT_HEADER_ID = t2.GRANT_HEADER_ID
	WHERE T1.AWARD_ID = AV_AWARD_ID
	AND AWARD_VARIATION_TYPE_CODE in (4, 9, 10, 11, 12)
	AND T1.AWARD_DOCUMENT_TYPE_CODE = 3
	AND T2.FUNDING_SCHEME_ID IN(select FUNDING_SCHEME_ID from SPONSOR_FUNDING_SCHEME
						 where FUNDING_SCHEME_CODE = 11);
	IF LI_FLAG > 0 THEN
        SELECT BUDGET_HEADER_ID INTO LS_BUDGET_HEADER FROM AWARD_BUDGET_HEADER T3
        where T3.AWARD_ID = AV_AWARD_ID
        and T3.VERSION_NUMBER in (SELECT max(t2.VERSION_NUMBER)
									FROM AWARD_BUDGET_HEADER T2
                                    where t3.award_id = t2.award_id);
		SELECT sum(LINE_ITEM_COST) > sum(PREVIOUS_LINE_ITEM_COST) INTO LI_INCREASE_FLAG
		FROM AWARD_BUDGET_DETAIL T4 where T4.BUDGET_HEADER_ID = LS_BUDGET_HEADER
        and COST_ELEMENT = 25 group by COST_ELEMENT;
        SELECT sum(LINE_ITEM_COST) < sum(PREVIOUS_LINE_ITEM_COST) INTO LI_DECREASE_FLAG
		FROM AWARD_BUDGET_DETAIL T5 where T5.BUDGET_HEADER_ID = LS_BUDGET_HEADER
        and COST_ELEMENT = 41 group by COST_ELEMENT;
        IF LI_INCREASE_FLAG > 0 or LI_DECREASE_FLAG > 0 THEN
			RETURN 'FALSE';
		ELSE
			RETURN 'TRUE';
		END IF;
	END IF;
RETURN 'TRUE';
END
$$
DELIMITER ;
