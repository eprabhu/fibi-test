DELIMITER $$
CREATE  PROCEDURE `MIGRATION_GRANT_CALL_INTERNAL`(
av_id int
)
BEGIN
DECLARE LS_APPLICATION_ID VARCHAR(50);
DECLARE LS_GRANT_CALL_ID VARCHAR(10);
DECLARE LS_TYPE_OF_GRANT VARCHAR(200);
DECLARE LS_NAME_OF_GRANT_CALL VARCHAR(1000);
DECLARE LS_NAME_OF_FUNDING_AGENCY VARCHAR(500);
DECLARE LS_NAME_OF_FUNDING_SCHEME VARCHAR(4000);
DECLARE LS_TYPE_OF_FUNDING_AGENCY VARCHAR(500);
DECLARE LS_GRANT_CALL_THEME LONGTEXT;
DECLARE LS_GRANT_CALL_CLOSING_DATE VARCHAR(20);
DECLARE LS_INTERNAL_SUBMISSION_DATE VARCHAR(20);
DECLARE LI_GRANT_HEADER_ID INT;
DECLARE LI_FLAG	INT;
DECLARE LI_COUNT INT;
DECLARE LI_GRANT_TYPE_CODE		INT;
DECLARE LS_SPONSOR_CODE 		VARCHAR(6);
DECLARE LS_SPONSOR_TYPE_CODE	VARCHAR(3);
DECLARE LS_FUNDING_SCHEME_ID	INT(11);
DECLARE LS_ERROR_MSG	VARCHAR(1000);
DECLARE LI_SEQ_ERROR_LOG_ID	INT;
	BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'EXCEPTION','GRANT_CALL',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
		DISTINCT
		TYPE_OF_GRANT,
		NAME_OF_GRANT_CALL,
		NAME_OF_FUNDING_AGENCY,
		NAME_OF_FUNDING_SCHEME,
		TYPE_OF_FUNDING_AGENCY,
		GRANT_CALL_THEME,
		GRANT_CALL_CLOSING_DATE,
		INTERNAL_SUBMISSION_DATE
		FROM MIGRATION_PROPOSAL_INTERNAL_00_17 WHERE VALIDATION_STATUS = 'VALID';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_TYPE_OF_GRANT,
		LS_NAME_OF_GRANT_CALL,
		LS_NAME_OF_FUNDING_AGENCY,
		LS_NAME_OF_FUNDING_SCHEME,
		LS_TYPE_OF_FUNDING_AGENCY,
		LS_GRANT_CALL_THEME,
		LS_GRANT_CALL_CLOSING_DATE,
		LS_INTERNAL_SUBMISSION_DATE;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM GRANT_CALL_TYPE
		WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_TYPE_OF_GRANT));
		IF LI_FLAG > 0 THEN
			SELECT GRANT_TYPE_CODE INTO LI_GRANT_TYPE_CODE FROM GRANT_CALL_TYPE
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_TYPE_OF_GRANT));
		ELSE
				ITERATE INSERT_LOOP;
		END IF;
		IF LS_NAME_OF_GRANT_CALL IS NULL OR LS_NAME_OF_GRANT_CALL = '' THEN
			ITERATE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM SPONSOR
		WHERE TRIM(UPPER(SPONSOR_NAME)) = TRIM(UPPER(LS_NAME_OF_FUNDING_AGENCY));
		IF LI_FLAG > 0 THEN
			SELECT SPONSOR_CODE INTO LS_SPONSOR_CODE FROM SPONSOR
			WHERE TRIM(UPPER(SPONSOR_NAME)) = TRIM(UPPER(LS_NAME_OF_FUNDING_AGENCY));
			SELECT COUNT(1) INTO LI_FLAG FROM FUNDING_SCHEME
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_NAME_OF_FUNDING_SCHEME));
			IF LI_FLAG > 0 THEN
				SELECT COUNT(1) INTO LI_COUNT FROM SPONSOR_FUNDING_SCHEME
				WHERE SPONSOR_CODE = LS_SPONSOR_CODE
				AND FUNDING_SCHEME_CODE = (SELECT FUNDING_SCHEME_CODE FROM FUNDING_SCHEME
											WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_NAME_OF_FUNDING_SCHEME)));
							IF LI_COUNT > 0 THEN
								SELECT FUNDING_SCHEME_ID INTO LS_FUNDING_SCHEME_ID FROM SPONSOR_FUNDING_SCHEME
								WHERE SPONSOR_CODE = LS_SPONSOR_CODE
								AND FUNDING_SCHEME_CODE = (SELECT FUNDING_SCHEME_CODE FROM FUNDING_SCHEME
															WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_NAME_OF_FUNDING_SCHEME)));
							END IF;
			END IF;
		ELSE
			ITERATE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM SPONSOR_TYPE
		WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_TYPE_OF_FUNDING_AGENCY));
		IF LI_FLAG > 0 THEN
			SELECT SPONSOR_TYPE_CODE INTO LS_SPONSOR_TYPE_CODE FROM SPONSOR_TYPE
			WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_TYPE_OF_FUNDING_AGENCY));
		END IF;
		SELECT GRANT_HEADER_ID INTO LI_GRANT_HEADER_ID FROM MIGRATION_ID_GENERATOR;
		INSERT INTO GRANT_CALL_HEADER(
		GRANT_HEADER_ID,
		GRANT_TYPE_CODE,
		GRANT_STATUS_CODE,
		OPENING_DATE,
		CLOSING_DATE,
		NAME,
		DESCRIPTION,
		SPONSOR_CODE,
		SPONSOR_TYPE_CODE,
		FUNDING_SCHEME_ID,
		GRANT_THEME,
		CREATE_TIMESTAMP,
		CREATE_USER,
		INTERNAL_SUBMISSION_DEADLINE_DATE,
		IS_PUBLISHED,
		PUBLISH_TIMESTAMP,
		UPDATE_TIMESTAMP,
		UPDATE_USER
		)
		VALUES
		(
			LI_GRANT_HEADER_ID,
			LI_GRANT_TYPE_CODE,
			'3',
			NULL,
			DATE_FORMAT(STR_TO_DATE(LS_GRANT_CALL_CLOSING_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
			LS_NAME_OF_GRANT_CALL,
			LS_NAME_OF_GRANT_CALL,
			LS_SPONSOR_CODE,
			LS_SPONSOR_TYPE_CODE,
			LS_FUNDING_SCHEME_ID,
			LS_GRANT_CALL_THEME,
			NOW(),
			'quickstart',
			DATE_FORMAT(STR_TO_DATE(LS_INTERNAL_SUBMISSION_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
			'Y',
			NOW(),
			NOW(),
			'quickstart'
		);
		UPDATE MIGRATION_PROPOSAL_INTERNAL_00_17
		SET GRANT_HEADER_ID = LI_GRANT_HEADER_ID
		WHERE
		UPPER(TRIM(IFNULL(TYPE_OF_GRANT,'0'))) = UPPER(TRIM(IFNULL(LS_TYPE_OF_GRANT,'0')))
		AND UPPER(TRIM(IFNULL(NAME_OF_GRANT_CALL,'0'))) = UPPER(TRIM(IFNULL(LS_NAME_OF_GRANT_CALL,'0')))
		AND UPPER(TRIM(IFNULL(NAME_OF_FUNDING_AGENCY,'0'))) = UPPER(TRIM(IFNULL(LS_NAME_OF_FUNDING_AGENCY,'0')))
		AND UPPER(TRIM(IFNULL(NAME_OF_FUNDING_SCHEME,'0'))) = UPPER(TRIM(IFNULL(LS_NAME_OF_FUNDING_SCHEME,'0')))
		AND UPPER(TRIM(IFNULL(TYPE_OF_FUNDING_AGENCY,'0'))) = UPPER(TRIM(IFNULL(LS_TYPE_OF_FUNDING_AGENCY,'0')))
		AND UPPER(TRIM(IFNULL(GRANT_CALL_THEME,'0'))) = UPPER(TRIM(IFNULL(LS_GRANT_CALL_THEME,'0')))
		AND UPPER(TRIM(IFNULL(GRANT_CALL_CLOSING_DATE,'0'))) = UPPER(TRIM(IFNULL(LS_GRANT_CALL_CLOSING_DATE,'0')))
		AND UPPER(TRIM(IFNULL(INTERNAL_SUBMISSION_DATE,'0'))) = UPPER(TRIM(IFNULL(LS_INTERNAL_SUBMISSION_DATE,'0')));
		COMMIT;
		set sql_safe_updates = 0;
		UPDATE MIGRATION_ID_GENERATOR SET GRANT_HEADER_ID = LI_GRANT_HEADER_ID + 1;
		SET LS_APPLICATION_ID = NULL;
		SET LS_GRANT_CALL_ID = NULL;
		SET LS_TYPE_OF_GRANT = NULL;
		SET LS_NAME_OF_GRANT_CALL = NULL;
		SET LS_NAME_OF_FUNDING_AGENCY = NULL;
		SET LS_NAME_OF_FUNDING_SCHEME = NULL;
		SET LS_TYPE_OF_FUNDING_AGENCY = NULL;
		SET LS_GRANT_CALL_THEME = NULL;
		SET LS_GRANT_CALL_CLOSING_DATE = NULL;
		SET LS_INTERNAL_SUBMISSION_DATE = NULL;
		SET LI_GRANT_HEADER_ID = NULL;
		SET LI_FLAG = NULL;
		SET LI_COUNT = NULL;
		SET LI_GRANT_TYPE_CODE = NULL;
		SET LS_SPONSOR_CODE = NULL;
		SET LS_SPONSOR_TYPE_CODE = NULL;
		SET LS_FUNDING_SCHEME_ID = NULL;
		END LOOP;
		CLOSE CUR_SEL_DATA;
	END;
	END;
END
$$
DELIMITER ;
