			LI_SEQ_RESRCH_AREA_ID,
			LI_CHALLENGE_AREA_CODE,
			-- LI_EXCELLENCE_AREA_CODE,
			LI_PROPOSAL_ID,
			AV_INST_PROPOSAL_NUMBER,
			LS_RESEARCH_AREA_CODE,
			LI_RESRCH_TYPE_CODE,
			LI_SEQUENCE_NUMBER,
			NOW(),
			AV_UPDATE_USER
			);
		END LOOP;
		CLOSE CUR_PROP_RSRCH_AREA;
	END;
	BEGIN
		DECLARE DONE6 INT DEFAULT FALSE;
		DECLARE CUR_PROP_SPONSOR CURSOR FOR
		SELECT  AMOUNT,
				END_DATE,
				SPONSOR_CODE,
				START_DATE
		FROM EPS_PROPOSAL_SPONSORS
		WHERE PROPOSAL_ID = AV_DEV_PROPOSAL_ID;
