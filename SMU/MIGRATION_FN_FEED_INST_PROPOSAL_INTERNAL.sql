			(
				SPONSOR_ID,
				AMOUNT,
				END_DATE,
				PROPOSAL_ID,
				PROPOSAL_NUMBER,
				SEQUENCE_NUMBER,
				SPONSOR_CODE,
				START_DATE,
				UPDATE_TIMESTAMP,
				UPDATE_USER
			)
			VALUES
			(
			LI_SEQ_SPONSOR_ID,
			LI_AMOUNT,
			LO_END_DATE,
			LI_PROPOSAL_ID,
			AV_INST_PROPOSAL_NUMBER,
			LI_SEQUENCE_NUMBER,
			LS_SPONSOR_CODE,
			LO_START_DATE,
			NOW(),
			AV_UPDATE_USER
			);
