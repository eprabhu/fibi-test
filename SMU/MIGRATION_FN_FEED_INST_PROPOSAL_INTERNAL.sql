		CLOSE CUR_PROP_SPONSOR;
	END;
	BEGIN
		DECLARE DONE7 INT DEFAULT FALSE;
		DECLARE CUR_PROP_PROJECT CURSOR FOR
		SELECT
			PERSON_ID,
