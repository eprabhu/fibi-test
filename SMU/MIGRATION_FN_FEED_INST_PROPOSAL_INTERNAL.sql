		VALUES(LI_SEQ_ERROR_LOG_ID,AV_DEV_PROPOSAL_ID,'EXCEPTION','INSTITUTE_PROPOSAL',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
	END;
