DELIMITER $$
CREATE  PROCEDURE `MIGRATION_EXT_AWARD_PERSONS`(
av_id int
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID 			INT;
DECLARE LS_ERROR_MSG 					VARCHAR(1000);
DECLARE LS_PROJECT_ID					VARCHAR(255);
DECLARE LS_MEMBER_TYPE					VARCHAR(50);
DECLARE LS_NTLOGIN_ID					VARCHAR(50);
DECLARE LS_NAME							VARCHAR(100);
DECLARE LS_DESIGNATION					VARCHAR(500);
DECLARE LS_SEQUENCE_IN_PROJECT_TEAM		VARCHAR(10);
DECLARE LS_DEPARTMENT					VARCHAR(500);
DECLARE LS_ORGANISATION					VARCHAR(500);
DECLARE LS_COUNTRY_OF_ORGANISATION		VARCHAR(500);
DECLARE LS_PROJECT_ROLE 				VARCHAR(50);
DECLARE LS_PERCENTAGE_OF_EFFORT			VARCHAR(50);
DECLARE LI_FLAG							INT;
DECLARE LI_AWARD_PERSON_ID				DECIMAL(22,0);
DECLARE LI_AWARD_ID						DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER					VARCHAR(12);
DECLARE LS_PERSON_ID					VARCHAR(40);
DECLARE LS_FULL_NAME					VARCHAR(90);
DECLARE LS_EMAIL_ADDRESS				VARCHAR(200);
DECLARE LI_ROLODEX_ID					INT(10);
DECLARE LI_AWARD_PERSON_UNIT_ID			DECIMAL(22,0);
DECLARE LS_UNIT_NUMBER					VARCHAR(8);
DECLARE LI_PROP_PERSON_ROLE_ID			INT(12);
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'EXCEPTION','PROJECT_PERSON',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			PROJECT_ID,
			MEMBER_TYPE,
			NTLOGIN_ID,
			NAME,
			DESIGNATION,
			SEQUENCE_IN_PROJECT_TEAM,
			DEPARTMENT,
			ORGANISATION,
			COUNTRY_OF_ORGANISATION,
			PROJECT_ROLE,
			PERCENTAGE_OF_EFFORT
		FROM MIGRATION_EXT_AWARD_PERSONS
		order by PROJECT_ID,SEQUENCE_IN_PROJECT_TEAM;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_PROJECT_ID,
		LS_MEMBER_TYPE,
		LS_NTLOGIN_ID,
		LS_NAME,
		LS_DESIGNATION,
		LS_SEQUENCE_IN_PROJECT_TEAM,
		LS_DEPARTMENT,
		LS_ORGANISATION,
		LS_COUNTRY_OF_ORGANISATION,
		LS_PROJECT_ROLE,
		LS_PERCENTAGE_OF_EFFORT;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM MIGRATION_EXT_AWARD
		WHERE PROJECT_ID = LS_PROJECT_ID;
		IF LI_FLAG > 0 THEN
			SELECT AWARD_ID,AWARD_NUMBER
			INTO LI_AWARD_ID,LS_AWARD_NUMBER
			FROM MIGRATION_EXT_AWARD
			WHERE PROJECT_ID = LS_PROJECT_ID;
		END IF;
		IF LS_MEMBER_TYPE = 'SMU Employee' THEN
			SELECT COUNT(1) INTO LI_FLAG FROM PERSON
			WHERE TRIM(UPPER(USER_NAME)) = TRIM(UPPER(LS_NTLOGIN_ID));
			IF LI_FLAG > 0 THEN
				SELECT PERSON_ID,EMAIL_ADDRESS INTO LS_PERSON_ID,LS_EMAIL_ADDRESS FROM PERSON
				WHERE TRIM(UPPER(USER_NAME)) = TRIM(UPPER(LS_NTLOGIN_ID));
			END IF;
		ELSEIF LS_MEMBER_TYPE = 'Non-SMU Employee' THEN
			SELECT COUNT(1) INTO LI_FLAG FROM ROLODEX
			WHERE UPPER(TRIM(FULL_NAME)) COLLATE utf8mb4_general_ci = UPPER(TRIM(LS_NAME));
			IF LI_FLAG > 0 THEN
				SELECT ROLODEX_ID,EMAIL_ADDRESS INTO LI_ROLODEX_ID,LS_EMAIL_ADDRESS FROM ROLODEX
				WHERE UPPER(TRIM(FULL_NAME)) COLLATE utf8mb4_general_ci = UPPER(TRIM(LS_NAME));
			END IF;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROP_PERSON_ROLE
		WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_ROLE));
		IF LI_FLAG > 0 THEN
			SELECT PROP_PERSON_ROLE_ID INTO LI_PROP_PERSON_ROLE_ID FROM EPS_PROP_PERSON_ROLE
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_ROLE));
		ELSE
			ITERATE INSERT_LOOP;
		END IF;
		SELECT IFNULL(MAX(AWARD_PERSON_ID),0)+1 INTO LI_AWARD_PERSON_ID FROM AWARD_PERSONS;
		INSERT INTO AWARD_PERSONS(
		AWARD_PERSON_ID,
		AWARD_ID,
		AWARD_NUMBER,
		SEQUENCE_NUMBER,
		PERSON_ID,
		FULL_NAME,
		PERCENTAGE_OF_EFFORT,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		EMAIL_ADDRESS,
		ROLODEX_ID,
		PERSON_ROLE_ID,
		PI_FLAG,
		IS_MULTI_PI,
		DESIGNATION
		)
		VALUES
		(
		LI_AWARD_PERSON_ID,
		LI_AWARD_ID,
		LS_AWARD_NUMBER,
		1,
		CASE WHEN LS_MEMBER_TYPE = 'SMU Employee' THEN LS_PERSON_ID
		ELSE NULL END,
		TRIM(LS_NAME),
		CAST(LS_PERCENTAGE_OF_EFFORT AS DECIMAL(5,2)),
		NOW(),
		'quickstart',
		LS_EMAIL_ADDRESS,
		CASE WHEN LS_MEMBER_TYPE = 'Non-SMU Employee' THEN LI_ROLODEX_ID
		ELSE NULL END,
		LI_PROP_PERSON_ROLE_ID,
		CASE WHEN LI_PROP_PERSON_ROLE_ID = 3 THEN 'Y'
		ELSE
		'N'
		END,
		CASE WHEN LI_PROP_PERSON_ROLE_ID = 9 THEN 'Y'
		ELSE
		'N'
		END,
		LS_DESIGNATION
		);
	IF LS_MEMBER_TYPE = 'SMU Employee' THEN
		IF LS_DEPARTMENT IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM UNIT
			WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_DEPARTMENT));
			IF LI_FLAG > 0 THEN
				SELECT UNIT_NUMBER INTO LS_UNIT_NUMBER
				FROM UNIT
				WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_DEPARTMENT));
				SELECT IFNULL(MAX(AWARD_PERSON_UNIT_ID),0)+1 INTO LI_AWARD_PERSON_UNIT_ID
				FROM AWARD_PERSON_UNIT;
				INSERT INTO AWARD_PERSON_UNIT
				(
				AWARD_PERSON_UNIT_ID,
				AWARD_PERSON_ID,
				AWARD_ID,
				AWARD_NUMBER,
				SEQUENCE_NUMBER,
				UNIT_NUMBER,
				LEAD_UNIT_FLAG,
				UPDATE_TIMESTAMP,
				UPDATE_USER
				)
				VALUES
				(
				LI_AWARD_PERSON_UNIT_ID,
				LI_AWARD_PERSON_ID,
				LI_AWARD_ID,
				LS_AWARD_NUMBER,
				1,
				LS_UNIT_NUMBER,
				CASE WHEN LI_PROP_PERSON_ROLE_ID = 3 THEN 'Y'
				ELSE
				'N'
				END,
				NOW(),
				'quickstart'
				);
			END IF;
		 END IF;
	END IF;
		SET LI_AWARD_ID = NULL;
		SET LS_AWARD_NUMBER = NULL;
		SET LS_UNIT_NUMBER = NULL;
		SET LI_PROP_PERSON_ROLE_ID = NULL;
		SET LS_MEMBER_TYPE = NULL;
		SET LS_NAME = NULL;
		SET LS_PERCENTAGE_OF_EFFORT = NULL;
		SET LS_EMAIL_ADDRESS = NULL;
		SET LS_DESIGNATION = NULL;
		SET LI_ROLODEX_ID = NULL;
		SET LS_PERSON_ID = NULL;
		SET LS_PROJECT_ROLE = NULL;
		SET LS_NTLOGIN_ID = NULL;
		SET LS_PROJECT_ID = NULL;
		END LOOP;
		CLOSE CUR_SEL_DATA;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE AWARD_PERSON_ID_GENERATOR SET NEXT_VAL = LI_AWARD_PERSON_ID +1;
		UPDATE AWARD_PERSON_UNIT_ID_GENERATOR  SET NEXT_VAL = LI_AWARD_PERSON_UNIT_ID +1;
		COMMIT;
	END;
END;
END
$$
DELIMITER ;
