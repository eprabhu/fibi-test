DELIMITER $$
CREATE  PROCEDURE `GET_WIDGET_DATA_IN_DETAIL`(
AV_WIDGET VARCHAR(200),
AV_PERSON_ID VARCHAR(50),
AV_SEARCH VARCHAR(1000),
AV_UNIT_NUMBER VARCHAR(10)
)
BEGIN
DECLARE LS_DYN_SQL LONGTEXT;
DECLARE COL3 VARCHAR(20);
DECLARE LL_SPONSOR VARCHAR(4000);
IF AV_UNIT_NUMBER = '' THEN
	SET AV_UNIT_NUMBER = null ;
END IF;
IF AV_WIDGET = 'INPROGRESS_PROPOSALS' THEN
	SELECT T1.PROPOSAL_ID, T1.TITLE, T5.SPONSOR_NAME, ifnull(T2.TOTAL_COST,0.00) as TOTAL_COST, T4.FULL_NAME AS PI, T6.UNIT_NAME, T1.SPONSOR_DEADLINE_DATE
			FROM EPS_PROPOSAL T1 LEFT OUTER JOIN BUDGET_HEADER T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID AND T2.IS_LATEST_VERSION  = 'Y'
			LEFT OUTER JOIN EPS_PROPOSAL_PERSONS T4 ON T1.PROPOSAL_ID = T4.PROPOSAL_ID AND T4.PI_FLAG ='Y'
			LEFT OUTER JOIN SPONSOR T5 ON T1.SPONSOR_CODE = T5.SPONSOR_CODE INNER JOIN UNIT T6 ON  T1.HOME_UNIT_NUMBER= T6.UNIT_NUMBER
			WHERE T1.STATUS_CODE = 1 AND T1.DOCUMENT_STATUS_CODE <> '3' AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER) AND T1.PROPOSAL_ID IN (
			SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID UNION SELECT PROPOSAL_ID FROM EPS_PROPOSAL WHERE HOME_UNIT_NUMBER IN (
			SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL') AND PERSON_ID = AV_PERSON_ID) UNION
			SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSON_ROLES WHERE PERSON_ID = AV_PERSON_ID);
ELSEIF AV_WIDGET = 'APPROVAL_INPROGRESS_PROPOSALS' THEN
	SELECT T1.PROPOSAL_ID, T1.TITLE, T5.SPONSOR_NAME, ifnull(T2.TOTAL_COST,0.00) as TOTAL_COST, T4.FULL_NAME AS PI, T6.UNIT_NAME, T1.SPONSOR_DEADLINE_DATE,T9.APPROVER_PERSON_NAME
			FROM EPS_PROPOSAL T1 LEFT OUTER JOIN BUDGET_HEADER T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID AND T2.IS_FINAL_BUDGET = 'Y'
			INNER JOIN EPS_PROPOSAL_PERSONS T4 ON T1.PROPOSAL_ID = T4.PROPOSAL_ID AND T4.PI_FLAG ='Y'
			LEFT OUTER JOIN SPONSOR T5 ON T1.SPONSOR_CODE = T5.SPONSOR_CODE
			INNER JOIN UNIT T6 ON  T1.HOME_UNIT_NUMBER= T6.UNIT_NUMBER
			INNER JOIN (SELECT GROUP_CONCAT(T8.APPROVER_PERSON_NAME SEPARATOR ' | ') AS APPROVER_PERSON_NAME,
            T7.MODULE_ITEM_ID FROM WORKFLOW T7 INNER JOIN WORKFLOW_DETAIL T8 ON T8.WORKFLOW_ID= T7.WORKFLOW_ID
            WHERE IS_WORKFLOW_ACTIVE = 'Y' AND APPROVAL_STATUS='W' and PRIMARY_APPROVER_FLAG='Y' AND MODULE_CODE=3 GROUP BY T7.WORKFLOW_ID
            ) T9 ON T9.MODULE_ITEM_ID = T1.PROPOSAL_ID
			WHERE T1.STATUS_CODE = 2 AND T1.DOCUMENT_STATUS_CODE <> '3' AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER)
			AND T1.PROPOSAL_ID IN (SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID UNION SELECT PROPOSAL_ID FROM EPS_PROPOSAL
			WHERE HOME_UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL') AND PERSON_ID = AV_PERSON_ID)
			UNION SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSON_ROLES WHERE PERSON_ID = AV_PERSON_ID  UNION
			SELECT S1.MODULE_ITEM_ID FROM WORKFLOW S1 INNER JOIN WORKFLOW_DETAIL S2 ON S1.WORKFLOW_ID = S2.WORKFLOW_ID WHERE S1.IS_WORKFLOW_ACTIVE = 'Y'
			AND S2.APPROVER_PERSON_ID = AV_PERSON_ID AND S1.MODULE_CODE = 3);
ELSEIF AV_WIDGET = 'AWARDED_PROPOSALS' THEN
			SELECT T1.PROPOSAL_ID, T1.TITLE, T5.SPONSOR_NAME, T2.TOTAL_COST, T4.FULL_NAME AS PI, T6.UNIT_NAME, T1.SPONSOR_DEADLINE_DATE
				FROM EPS_PROPOSAL T1 LEFT OUTER JOIN BUDGET_HEADER T2 ON T1.PROPOSAL_ID = T2.PROPOSAL_ID AND T2.IS_FINAL_BUDGET = 'Y'
				LEFT OUTER JOIN EPS_PROPOSAL_PERSONS T4 ON T1.PROPOSAL_ID = T4.PROPOSAL_ID AND T4.PI_FLAG ='Y'
				INNER JOIN SPONSOR T5 ON T1.SPONSOR_CODE = T5.SPONSOR_CODE
				INNER JOIN UNIT T6 ON  T1.HOME_UNIT_NUMBER= T6.UNIT_NUMBER
				WHERE T1.STATUS_CODE = 11 AND T1.DOCUMENT_STATUS_CODE <> '3' AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER) AND T1.PROPOSAL_ID IN (
					SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID
					UNION
					   SELECT PROPOSAL_ID FROM EPS_PROPOSAL
					   WHERE HOME_UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL') AND PERSON_ID = AV_PERSON_ID)
					   UNION
					   SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSON_ROLES WHERE PERSON_ID = AV_PERSON_ID
					   UNION
					   SELECT PROPOSAL_ID FROM EPS_PROPOSAL
					   WHERE HOME_UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM UNIT_ADMINISTRATOR WHERE PERSON_ID = AV_PERSON_ID AND UNIT_ADMINISTRATOR_TYPE_CODE = 3));
ELSEIF AV_WIDGET = 'PROPOSAL_BY_SPONSOR_TYPE' THEN
			SELECT T1.PROPOSAL_ID, T1.TITLE, T2.SPONSOR_NAME, T4.DESCRIPTION AS PROPOSAL_TYPE, T3.FULL_NAME AS PI, T1.SUBMISSION_DATE FROM EPS_PROPOSAL T1
			INNER JOIN SPONSOR T2 ON T1.SPONSOR_CODE = T2.SPONSOR_CODE LEFT OUTER JOIN EPS_PROPOSAL_PERSONS T3 ON T1.PROPOSAL_ID = T3.PROPOSAL_ID AND T3.PI_FLAG ='Y'
			INNER JOIN EPS_PROPOSAL_TYPE T4 ON T1.TYPE_CODE = T4.TYPE_CODE WHERE T2.SPONSOR_TYPE_CODE = AV_SEARCH AND T1.DOCUMENT_STATUS_CODE <> '3'
			AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER) AND T1.PROPOSAL_ID IN (SELECT PROPOSAL_ID FROM EPS_PROPOSAL
			WHERE HOME_UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL')AND PERSON_ID = AV_PERSON_ID ) UNION
			SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID );
ELSEIF AV_WIDGET IN ('AWARD_BY_SPONSOR_TYPE', 'ACTIVE_AWARDS_BY_SPONSOR_TYPE') THEN
		if month(NOW()) >= '4' then
				SET COL3 = YEAR(NOW());
				else
				SET COL3 = YEAR(NOW()) - 1;
			END IF;
			SELECT DISTINCT AWARD_NUMBER,ACCOUNT_NUMBER,TITLE, SPONSOR_NAME, AWARD_ID, ANTICIPATED_TOTAL_AMOUNT, PI_NAME FROM
			       award_master_dataset_rt
			        WHERE AWARD_SEQUENCE_STATUS = 'ACTIVE'
			        AND (ifnull (FUND_CODE , 'R_RESFUND')) <> 'G_DESIGNAT'
                    AND AWARD_STATUS_CODE <> '3'
					AND BEGIN_DATE BETWEEN concat(COL3,"-04-01") AND concat(COL3+1,"-03-31")
			        AND ( AWARD_ID  IN
					(SELECT T1.AWARD_ID FROM AWARD_PERSON_ROLES T1
					INNER JOIN ROLE_RIGHTS T2 ON T1.ROLE_ID = T2.ROLE_ID
					INNER JOIN RIGHTS T3 ON T3.RIGHT_ID = T2.RIGHT_ID
					WHERE T1.PERSON_ID = AV_PERSON_ID AND T3.RIGHT_NAME = 'VIEW_AWARD')
			        OR LEAD_UNIT_NUMBER IN (
			        SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('VIEW_AWARD')
			        AND PERSON_ID = AV_PERSON_ID
			        ))
				AND SPONSOR_TYPE_CODE =AV_SEARCH;
ELSEIF AV_WIDGET = 'INPROGRESS_PROPOSALS_BY_SPONSOR' THEN
			SELECT T1.PROPOSAL_ID, T1.TITLE, T4.FULL_NAME AS PI, T1.TYPE_CODE, T5.DESCRIPTION AS PROPOSAL_TYPE, ifnull(T6.TOTAL_COST,'0.00')AS BUDGET, T1.SUBMISSION_DATE FROM EPS_PROPOSAL T1
			LEFT OUTER JOIN EPS_PROPOSAL_PERSONS T4 ON T1.PROPOSAL_ID = T4.PROPOSAL_ID AND  T4.PI_FLAG ='Y' INNER JOIN EPS_PROPOSAL_TYPE T5 ON T1.TYPE_CODE=T5.TYPE_CODE
			LEFT OUTER JOIN BUDGET_HEADER T6 ON T1.BUDGET_HEADER_ID = T6.BUDGET_HEADER_ID WHERE T1.STATUS_CODE = 1 AND T1.SPONSOR_CODE = AV_SEARCH
			AND T1.DOCUMENT_STATUS_CODE <> '3' AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER) AND T1.PROPOSAL_ID IN (SELECT PROPOSAL_ID FROM EPS_PROPOSAL WHERE HOME_UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL')
			AND PERSON_ID = AV_PERSON_ID)UNION SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID UNION
			SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSON_ROLES WHERE PERSON_ID = AV_PERSON_ID UNION SELECT S1.MODULE_ITEM_ID FROM WORKFLOW S1 INNER JOIN WORKFLOW_DETAIL S2 ON S1.WORKFLOW_ID = S2.WORKFLOW_ID
			WHERE S1.IS_WORKFLOW_ACTIVE = 'Y' AND S2.APPROVER_PERSON_ID = AV_PERSON_ID	AND S1.MODULE_CODE = 3);
ELSEIF AV_WIDGET = 'AWARDED_PROPOSALS_BY_SPONSOR' THEN
			SELECT T1.PROPOSAL_NUMBER, T1.TITLE, T4.FULL_NAME AS PI, T1.ACTIVITY_TYPE_CODE, T5.DESCRIPTION AS ACTIVITY_TYPE, T1.TYPE_CODE as PROPOSAL_TYPE_CODE,T6.DESCRIPTION AS PROPOSAL_TYPE,
			T1.SPONSOR_CODE, T1.PROPOSAL_ID FROM PROPOSAL T1 INNER JOIN SPONSOR T2 ON T1.SPONSOR_CODE = T2.SPONSOR_CODE LEFT OUTER JOIN PROPOSAL_PERSONS T4 ON T1.PROPOSAL_ID = T4.PROPOSAL_ID AND T4.PROP_PERSON_ROLE_ID = 3
			INNER JOIN ACTIVITY_TYPE T5 ON T1.ACTIVITY_TYPE_CODE = T5.ACTIVITY_TYPE_CODE INNER JOIN PROPOSAL_TYPE T6 ON T1.TYPE_CODE = T6.TYPE_CODE WHERE  T1.STATUS_CODE = 2
			AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER) AND T1.SPONSOR_CODE = AV_SEARCH AND T1.PROPOSAL_NUMBER IN (SELECT PROPOSAL_NUMBER FROM PROPOSAL WHERE HOME_UNIT_NUMBER IN
			(SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL') AND PERSON_ID = AV_PERSON_ID) UNION SELECT PROPOSAL_ID FROM
			PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID);
ELSEIF AV_WIDGET = 'AWARD_BY_SPONSOR' THEN
	if month(NOW()) >= '4' then
					SET COL3 = YEAR(NOW());
					else
					SET COL3 = YEAR(NOW()) - 1;
				END IF;
   set LS_DYN_SQL = concat('SELECT group_concat('''',SPONSOR_CODE,'''') INTO @SPONSOR_LIST FROM(
	SELECT SPONSOR_CODE FROM SPONSOR WHERE SPONSOR_GROUP IN (',AV_SEARCH,')
	union
	SELECT SPONSOR_CODE FROM SPONSOR WHERE SPONSOR_GROUP IS NULL AND SPONSOR_CODE IN (',AV_SEARCH,')) AS TAB');
	SET @QUERY_STATEMENT = LS_DYN_SQL;
	PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
	EXECUTE EXECUTABLE_STAEMENT ;
	SET LL_SPONSOR = @SPONSOR_LIST;
IF AV_UNIT_NUMBER is null then
SET AV_UNIT_NUMBER = '''NULL''';
END IF;
	IF LOCATE(',',AV_SEARCH) = 0 then
		SET LS_DYN_SQL = CONCAT('SELECT DISTINCT AWARD_NUMBER,ACCOUNT_NUMBER,TITLE, SPONSOR_NAME, AWARD_ID FROM
        award_master_dataset_rt
        WHERE AWARD_SEQUENCE_STATUS = ''ACTIVE''
		AND AWARD_STATUS_CODE <> ''3''
        AND (',AV_UNIT_NUMBER,' = ''NULL'' OR LEAD_UNIT_NUMBER = ',AV_UNIT_NUMBER,')
        AND (ifnull (FUND_CODE , ''R_RESFUND'')) <> ''G_DESIGNAT''
		AND BEGIN_DATE BETWEEN ''',COL3,'-04-01'' AND ''', COL3+1,'-03-31''
        AND (AWARD_NUMBER  IN
					(SELECT T1.AWARD_NUMBER FROM AWARD_PERSON_ROLES T1
					INNER JOIN ROLE_RIGHTS T2 ON T1.ROLE_ID = T2.ROLE_ID
					INNER JOIN RIGHTS T3 ON T3.RIGHT_ID = T2.RIGHT_ID
					WHERE T1.PERSON_ID = ''',AV_PERSON_ID, '''AND T3.RIGHT_NAME = ''VIEW_AWARD'')
        OR LEAD_UNIT_NUMBER IN (
        SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN (''VIEW_AWARD'')
        AND PERSON_ID =''',AV_PERSON_ID,'''))
        AND SPONSOR_CODE IN (',LL_SPONSOR,')');
	SET @QUERY_STATEMENT = LS_DYN_SQL;
	PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
	EXECUTE EXECUTABLE_STAEMENT;
	ELSE
	SET LS_DYN_SQL = CONCAT('SELECT DISTINCT AWARD_NUMBER,ACCOUNT_NUMBER,TITLE, SPONSOR_NAME, AWARD_ID FROM
        award_master_dataset_rt
        WHERE AWARD_SEQUENCE_STATUS = ''ACTIVE''
		AND AWARD_STATUS_CODE <> ''3''
        AND (',AV_UNIT_NUMBER,' = ''NULL'' OR LEAD_UNIT_NUMBER = ',AV_UNIT_NUMBER,')
        AND (ifnull (FUND_CODE , ''R_RESFUND'')) <> ''G_DESIGNAT''
		AND BEGIN_DATE BETWEEN ''',COL3,'-04-01'' AND ''', COL3+1,'-03-31''
        AND (AWARD_NUMBER  IN
					(SELECT T1.AWARD_NUMBER FROM AWARD_PERSON_ROLES T1
					INNER JOIN ROLE_RIGHTS T2 ON T1.ROLE_ID = T2.ROLE_ID
					INNER JOIN RIGHTS T3 ON T3.RIGHT_ID = T2.RIGHT_ID
					WHERE T1.PERSON_ID = ''',AV_PERSON_ID, '''AND T3.RIGHT_NAME = ''VIEW_AWARD'')
        OR LEAD_UNIT_NUMBER IN (
        SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN (''VIEW_AWARD'')
        AND PERSON_ID =''',AV_PERSON_ID,'''))
        AND SPONSOR_CODE NOT IN (',LL_SPONSOR,')');
	SET @QUERY_STATEMENT = LS_DYN_SQL;
	PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
	EXECUTE EXECUTABLE_STAEMENT;
    END IF;
ELSEIF AV_WIDGET = 'AWARD_BY_UTALIZATION' THEN
	IF AV_SEARCH = 'Low Utilisation' THEN
		SELECT DISTINCT AWARD_NUMBER , TITLE, UTILIZATION_RATE_WO_IRC
			FROM award_master_dataset_rt
				WHERE AWARD_SEQUENCE_STATUS = 'ACTIVE'
                AND AWARD_STATUS_CODE = '1'
				AND (
			AWARD_ID  IN
			(SELECT T1.AWARD_ID FROM AWARD_PERSON_ROLES T1
			INNER JOIN ROLE_RIGHTS T2 ON T1.ROLE_ID = T2.ROLE_ID
				INNER JOIN RIGHTS T3 ON T3.RIGHT_ID = T2.RIGHT_ID
				WHERE T1.PERSON_ID = AV_PERSON_ID AND T3.RIGHT_NAME = 'VIEW_AWARD')
				OR LEAD_UNIT_NUMBER IN (
				SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('VIEW_AWARD')AND PERSON_ID = AV_PERSON_ID)
				)
		AND FINAL_EXPIRATION_DATE >= utc_timestamp()
		AND (UTILIZATION_RATE_WO_IRC + 10) < ((DATEDIFF(UTC_TIMESTAMP(),BEGIN_DATE)+1)/(DATEDIFF(FINAL_EXPIRATION_DATE,BEGIN_DATE)+1))*100
		ORDER BY FINAL_EXPIRATION_DATE ASC;
	ELSEIF AV_SEARCH = 'High Utilisation' THEN
    SELECT DISTINCT AWARD_NUMBER , TITLE, UTILIZATION_RATE_WO_IRC
			FROM award_master_dataset_rt
				WHERE AWARD_SEQUENCE_STATUS = 'ACTIVE'
                AND AWARD_STATUS_CODE = '1'
				AND (
			AWARD_ID  IN
			(SELECT T1.AWARD_ID FROM AWARD_PERSON_ROLES T1
			INNER JOIN ROLE_RIGHTS T2 ON T1.ROLE_ID = T2.ROLE_ID
				INNER JOIN RIGHTS T3 ON T3.RIGHT_ID = T2.RIGHT_ID
				WHERE T1.PERSON_ID = AV_PERSON_ID AND T3.RIGHT_NAME = 'VIEW_AWARD')
				OR LEAD_UNIT_NUMBER IN (
				SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('VIEW_AWARD')AND PERSON_ID = AV_PERSON_ID)
				)
		AND FINAL_EXPIRATION_DATE >= utc_timestamp()
		AND (UTILIZATION_RATE_WO_IRC - 10) > ((DATEDIFF(UTC_TIMESTAMP(),BEGIN_DATE)+1)/(DATEDIFF(FINAL_EXPIRATION_DATE,BEGIN_DATE)+1)) *100
		ORDER BY FINAL_EXPIRATION_DATE ASC;
	ELSEIF AV_SEARCH = 'Acceptable Utilisation' THEN
		SELECT DISTINCT AWARD_NUMBER , TITLE, UTILIZATION_RATE_WO_IRC
			FROM award_master_dataset_rt
				WHERE AWARD_SEQUENCE_STATUS = 'ACTIVE'
                AND AWARD_STATUS_CODE = '1'
				AND (
			AWARD_ID  IN
			(SELECT T1.AWARD_ID FROM AWARD_PERSON_ROLES T1
			INNER JOIN ROLE_RIGHTS T2 ON T1.ROLE_ID = T2.ROLE_ID
				INNER JOIN RIGHTS T3 ON T3.RIGHT_ID = T2.RIGHT_ID
				WHERE T1.PERSON_ID = AV_PERSON_ID AND T3.RIGHT_NAME = 'VIEW_AWARD')
				OR LEAD_UNIT_NUMBER IN (
				SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('VIEW_AWARD')AND PERSON_ID = AV_PERSON_ID)
				)
		AND FINAL_EXPIRATION_DATE >= utc_timestamp()
		AND ((DATEDIFF(UTC_TIMESTAMP(),BEGIN_DATE)+1)/(DATEDIFF(FINAL_EXPIRATION_DATE,BEGIN_DATE)+1))*100 BETWEEN (UTILIZATION_RATE_WO_IRC - 10) AND (UTILIZATION_RATE_WO_IRC + 10)
		ORDER BY FINAL_EXPIRATION_DATE ASC;
	END IF;
ELSEIF AV_WIDGET = 'PENDING_PROPOSAL_BY_SPONSOR_TYPE' THEN
			SELECT T1.PROPOSAL_ID, T1.TITLE, T2.SPONSOR_NAME,IFNULL(T4.TOTAL_COST, '0.00'), T3.FULL_NAME  FROM EPS_PROPOSAL T1
			LEFT JOIN SPONSOR T2 ON T1.SPONSOR_CODE = T2.SPONSOR_CODE LEFT OUTER JOIN EPS_PROPOSAL_PERSONS T3 ON T1.PROPOSAL_ID = T3.PROPOSAL_ID AND T3.PI_FLAG ='Y'
			LEFT OUTER JOIN (SELECT IS_LATEST_VERSION ,TOTAL_COST, PROPOSAL_ID FROM BUDGET_HEADER WHERE IS_LATEST_VERSION = 'Y' GROUP BY BUDGET_HEADER_ID) T4 ON T1.PROPOSAL_ID = T4.PROPOSAL_ID
            WHERE T1.STATUS_CODE = 41 AND T2.SPONSOR_TYPE_CODE = AV_SEARCH AND (AV_UNIT_NUMBER is null OR T1.HOME_UNIT_NUMBER = AV_UNIT_NUMBER)
            AND  T1.PROPOSAL_ID IN (SELECT PROPOSAL_ID FROM EPS_PROPOSAL
			WHERE HOME_UNIT_NUMBER IN (SELECT UNIT_NUMBER FROM PERSON_ROLE_RT WHERE RIGHT_NAME IN ('MODIFY_PROPOSAL','VIEW_PROPOSAL','VIEW_ANY_PROPOSAL')AND PERSON_ID = AV_PERSON_ID ) UNION
			SELECT PROPOSAL_ID FROM EPS_PROPOSAL_PERSONS WHERE PERSON_ID = AV_PERSON_ID);
END IF;
END
$$
DELIMITER ;
