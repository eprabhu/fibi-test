DELIMITER $$
CREATE  PROCEDURE `SPECIAL_REVIEW_REMAINDER`( AV_DAYS INT )
BEGIN
	SELECT 0 AS SUB_MODULE_ITEM_KEY, T1.AWARD_ID AS MODULE_ITEM_KEY, 1 AS MODULE_CODE, 0 AS SUB_MODULE_CODE, T1.PROTOCOL_NUMBER, T1.APPLICATION_DATE, T1.APPROVAL_DATE, T1.EXPIRATION_DATE, T1.COMMENTS, T2.DESCRIPTION AS REVIEW_TYPE, T3.DESCRIPTION AS APPROVAL_STATUS FROM AWARD_SPECIAL_REVIEW T1
    INNER JOIN SPECIAL_REVIEW T2 ON T1.SPECIAL_REVIEW_CODE = T2.SPECIAL_REVIEW_CODE
    LEFT JOIN SP_REV_APPROVAL_TYPE T3 ON T1.APPROVAL_TYPE_CODE = T3.APPROVAL_TYPE_CODE
	WHERE date(T1.EXPIRATION_DATE) = date(DATE_ADD(utc_timestamp(),INTERVAL AV_DAYS DAY));
END
$$
DELIMITER ;
