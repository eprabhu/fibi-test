DELIMITER $$
CREATE  PROCEDURE `SMU_DATA_MASK_UPDATE_RLDX`(AV_ACTION INT)
BEGIN
	DECLARE LS_ERR_FLG VARCHAR(1);
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE BOOLEAN;
	DECLARE LS_TABLE_NAME VARCHAR(100);
	DECLARE LS_COL_NAME VARCHAR(100);
	DECLARE LS_ERR_TABLE_NAME VARCHAR(100);
	DECLARE LS_STAGE VARCHAR(50);
	-- ROLODEX
	DECLARE  CUR_RLDX_FN CURSOR FOR
		SELECT TABLE_NAME,COLUMN_NAME
		FROM SMU_DATA_MASK_TAB_DTLS
		WHERE PERSON_TYPE = 'RLDX'
		AND DATA_CATEGORY = 'FULL_NAME';
	DECLARE CUR_RLDX_FIRST CURSOR FOR
		SELECT TABLE_NAME,COLUMN_NAME
		FROM SMU_DATA_MASK_TAB_DTLS
		WHERE PERSON_TYPE = 'RLDX'
		AND DATA_CATEGORY = 'FIRST_NAME';
	DECLARE  CUR_RLDX_LAST CURSOR FOR
		SELECT TABLE_NAME,COLUMN_NAME
		FROM SMU_DATA_MASK_TAB_DTLS
		WHERE PERSON_TYPE = 'RLDX'
		AND DATA_CATEGORY = 'LAST_NAME';
	DECLARE  CUR_RLDX_EMAIL CURSOR FOR
		SELECT TABLE_NAME,COLUMN_NAME
		FROM SMU_DATA_MASK_TAB_DTLS
		WHERE PERSON_TYPE = 'RLDX'
		AND DATA_CATEGORY = 'EMAIL';
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = TRUE;
	DECLARE EXIT HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		ROLLBACK;
		INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS,ERR_TABLE_NAME,ERROR_MESSAGE)
		VALUES( LS_STAGE,'ERROR',LS_ERR_TABLE_NAME,LS_ERROR);
		COMMIT;
		SET LS_ERR_FLG ='Y';
		SELECT @stmt;
	END;
BEGIN
	 SET AUTOCOMMIT= 0;
	 SET SQL_SAFE_UPDATES= 0;
	 TRUNCATE TABLE SMU_DATA_MASK_AUDIT_LOG;
	 SET LS_ERR_FLG = 'N';
	 SET LS_STAGE = 'Updating Rldx Full Name details';
	 INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Started');
	OPEN CUR_RLDX_FN;
	rldx_fn_loop: LOOP
		SET DONE = FALSE;
		FETCH CUR_RLDX_FN INTO LS_TABLE_NAME, LS_COL_NAME;
		IF DONE = TRUE THEN
			LEAVE rldx_fn_loop;
		END IF;
		SET LS_ERR_TABLE_NAME = LS_TABLE_NAME;
		SET @stmt = CONCAT ('UPDATE ', LS_TABLE_NAME, ' a SET ',LS_COL_NAME, '  = (SELECT CONCAT (''Name of '',ROLODEX_ID) FROM ROLODEX R WHERE R.FULL_NAME = a.',LS_COL_NAME,' ORDER BY R.UPDATE_TIMESTAMP DESC LIMIT 1) WHERE ',LS_COL_NAME,
		' IS NOT NULL AND ', LS_COL_NAME,' <> ''SMU Admin'' AND EXISTS (SELECT 1 FROM ROLODEX WHERE FULL_NAME = a.',LS_COL_NAME,')');
		PREPARE LS_EXEC_STMT FROM  @stmt;
		EXECUTE  LS_EXEC_STMT;
		DEALLOCATE PREPARE LS_EXEC_STMT;
	END LOOP;
	CLOSE CUR_RLDX_FN;
	INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Completed');
		 SET LS_STAGE = 'Updating First Name details';
	 INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Started');
	OPEN CUR_RLDX_FIRST;
	rldx_first_loop: LOOP
		SET DONE = FALSE;
		FETCH CUR_RLDX_FIRST INTO LS_TABLE_NAME, LS_COL_NAME;
		IF DONE = TRUE THEN
			LEAVE rldx_first_loop;
		END IF;
		SET LS_ERR_TABLE_NAME = LS_TABLE_NAME;
		SET @stmt = CONCAT ('UPDATE ', LS_TABLE_NAME, ' a SET ',LS_COL_NAME, '  = ''Name of'' WHERE ',LS_COL_NAME,' IS NOT NULL AND ',LS_COL_NAME,' NOT IN (''SMU Admin'' ,'''')
		AND EXISTS (SELECT 1 FROM ROLODEX WHERE FIRST_NAME IS NOT NULL AND FIRST_NAME NOT IN (''SMU Admin'', '''') AND FIRST_NAME = a.',LS_COL_NAME,')');
		PREPARE LS_EXEC_STMT FROM  @stmt;
		EXECUTE  LS_EXEC_STMT;
		DEALLOCATE PREPARE LS_EXEC_STMT;
	END LOOP;
	CLOSE CUR_RLDX_FIRST;
	INSERT INTO SMU_DATA_MASK_AUDIT_LOG
			(STAGE,STATUS)
	VALUES( LS_STAGE,'Completed');
	SET LS_STAGE = 'Updating last name details';
	 INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Started');
	OPEN CUR_RLDX_LAST;
	rldx_last_loop: LOOP
		SET DONE = FALSE;
		FETCH CUR_RLDX_LAST INTO LS_TABLE_NAME, LS_COL_NAME;
		IF DONE = TRUE THEN
			LEAVE rldx_last_loop;
		END IF;
		SET LS_ERR_TABLE_NAME = LS_TABLE_NAME;
		SET @stmt = CONCAT ('UPDATE ', LS_TABLE_NAME, ' a SET ',LS_COL_NAME, '  = (SELECT ROLODEX_ID FROM ROLODEX R WHERE R.LAST_NAME = a.',LS_COL_NAME,' ORDER BY R.UPDATE_TIMESTAMP DESC LIMIT 1) WHERE ',LS_COL_NAME,
		' IS NOT NULL AND ', LS_COL_NAME, ' <> ''SMU Admin'' AND EXISTS (SELECT 1 FROM ROLODEX WHERE LAST_NAME = a.',LS_COL_NAME,')');
		PREPARE LS_EXEC_STMT FROM  @stmt;
		EXECUTE  LS_EXEC_STMT;
		DEALLOCATE PREPARE LS_EXEC_STMT;
	END LOOP;
	CLOSE CUR_RLDX_LAST;
	INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Completed');
	SET LS_STAGE = 'Updating email details';
	 INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Started');
	OPEN CUR_RLDX_EMAIL;
		rldx_email_loop: LOOP
			SET DONE = FALSE;
			FETCH CUR_RLDX_EMAIL INTO LS_TABLE_NAME, LS_COL_NAME;
			IF DONE = TRUE THEN
				LEAVE rldx_email_loop;
			END IF;
			SET LS_ERR_TABLE_NAME = LS_TABLE_NAME;
			SET @stmt = CONCAT ('UPDATE ', LS_TABLE_NAME, ' a SET ',LS_COL_NAME, '  = (SELECT CONCAT(ROLODEX_ID,''@smu1.edu.sg'') FROM ROLODEX R WHERE R.EMAIL_ADDRESS = a.',	LS_COL_NAME,
			' ORDER BY R.UPDATE_TIMESTAMP DESC LIMIT 1) WHERE EXISTS (SELECT 1 FROM ROLODEX WHERE EMAIL_ADDRESS = a.',LS_COL_NAME,')');
			PREPARE LS_EXEC_STMT FROM  @stmt;
			EXECUTE  LS_EXEC_STMT;
			DEALLOCATE PREPARE LS_EXEC_STMT;
	END LOOP;
	CLOSE CUR_RLDX_EMAIL;
	INSERT INTO SMU_DATA_MASK_AUDIT_LOG
			(STAGE,STATUS)
	VALUES( LS_STAGE,'Completed');
	IF LS_ERR_FLG = 'N' THEN
		-- ROLLBACK;
		INSERT INTO SMU_DATA_MASK_AUDIT_LOG
					(STAGE,STATUS)
		VALUES( LS_STAGE,'Update Rldx Procedure Completed');
		COMMIT;
	END IF;
END;
END
$$
DELIMITER ;
