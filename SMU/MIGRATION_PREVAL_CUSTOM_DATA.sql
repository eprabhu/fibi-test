DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PREVAL_CUSTOM_DATA`(AV_TYPE int)
BEGIN
DECLARE LS_LEGACY_PROJECT_ID    VARCHAR(100);
DECLARE LS_LEGACY_WBS_NUMBER    VARCHAR(100);
DECLARE LI_COUNT INT;
DECLARE LS_FILE_TYPE VARCHAR(50);
DECLARE LI_AWARD_ID   INT(22);
DECLARE LS_AWARD_NUMBER VARCHAR(12);
DECLARE LS_HOME_UNIT               VARCHAR(8);
DECLARE LS_PROJECT_ID VARCHAR(20);
DECLARE LS_TITLE VARCHAR(4000);
DECLARE LS_PROJECT_STATUS VARCHAR(200);
DECLARE LS_LEAD_UNIT VARCHAR(200);
DECLARE LS_CUST_SCHOOL_UNIVERSITY VARCHAR(200);
DECLARE LS_GRANTCALL_TYPE VARCHAR(200);
DECLARE LS_MODULE_TYPE VARCHAR(10);
BEGIN
DECLARE LS_ERROR VARCHAR(2000);
        DECLARE DONE1 INT DEFAULT FALSE;
DECLARE MIGRATION_CUSTOM_DATA_CURSOR CURSOR FOR
SELECT PROJECT_ID,
TITLE,
PROJECT_STATUS,
LEAD_UNIT,
CUST_SCHOOL_UNIVERSITY,
GRANTCALL_TYPE,
MODULE_TYPE
FROM MIGRATION_CUSTOM_DATA;
DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
BEGIN
GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
@errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
SELECT @full_error INTO LS_ERROR;
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Exception','CUSTOM_DATA',SUBSTR(LS_ERROR,1,999),'During Migration',NULL);
COMMIT;
END;
OPEN MIGRATION_CUSTOM_DATA_CURSOR;
MIGRATION_CUSTOM_DATA_CURSOR_LOOP : LOOP
FETCH MIGRATION_CUSTOM_DATA_CURSOR INTO LS_PROJECT_ID,
LS_TITLE,
LS_PROJECT_STATUS,
LS_LEAD_UNIT,
LS_CUST_SCHOOL_UNIVERSITY,
LS_GRANTCALL_TYPE,
LS_MODULE_TYPE;
IF DONE1 THEN
LEAVE MIGRATION_CUSTOM_DATA_CURSOR_LOOP;
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM CUSTOM_DATA_ELEMENTS
WHERE CUSTOM_ELEMENT_NAME ='School/University'
AND COLUMN_ID = (SELECT MAX(COLUMN_ID) FROM CUSTOM_DATA_ELEMENTS WHERE CUSTOM_ELEMENT_NAME = 'School/University');
IF LI_COUNT <> 1 THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('Award custom data is missing'),'Before Migration',NULL);
COMMIT;
LEAVE MIGRATION_CUSTOM_DATA_CURSOR_LOOP;
END IF;
IF LS_MODULE_TYPE = 'AWARD' THEN
IF (IFNULL(TRIM(LS_PROJECT_ID),'') = '' ) THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('Project id can''t be NULL'),'Before Migration',NULL);
COMMIT;
ITERATE MIGRATION_CUSTOM_DATA_CURSOR_LOOP;
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM MIGRATION_CUSTOM_DATA
WHERE PROJECT_ID = LS_PROJECT_ID
AND MODULE_TYPE ='AWARD' ;
IF LI_COUNT > 1 THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('More than one entry present in the provided file'),'Before Migration',NULL);
COMMIT;
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM AWARD
WHERE AWARD_NUMBER = LS_PROJECT_ID;
IF LI_COUNT = 0 THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('Award Number missing in FIBI'),'Before Migration',NULL);
COMMIT;
ELSE
SELECT COUNT(*) INTO LI_COUNT
FROM AWARD
WHERE AWARD_NUMBER = LS_PROJECT_ID
AND AWARD_SEQUENCE_STATUS = 'ACTIVE';
IF LI_COUNT = 0 THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('Active version of Award Number missing in FIBI'),'Before Migration',NULL);
COMMIT;
ELSEIF LI_COUNT = 1 THEN
SELECT AWARD_ID INTO LI_AWARD_ID
FROM AWARD
WHERE AWARD_NUMBER = LS_PROJECT_ID
AND AWARD_SEQUENCE_STATUS = 'ACTIVE';
ELSE
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('More than one Active version of Award in FIBI'),'Before Migration',NULL);
COMMIT;
END IF;
END IF;
ELSE
IF (IFNULL(TRIM(LS_PROJECT_ID),'') = '' ) THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('Project id can''t be NULL'),'Before Migration',NULL);
COMMIT;
ITERATE MIGRATION_CUSTOM_DATA_CURSOR_LOOP;
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM MIGRATION_CUSTOM_DATA
WHERE PROJECT_ID = LS_PROJECT_ID
AND MODULE_TYPE ='PROPOSAL' ;
IF LI_COUNT > 1 THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('More than one entry present in the provided file'),'Before Migration',NULL);
COMMIT;
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM EPS_PROPOSAL
WHERE APPLICATION_ID = LS_PROJECT_ID;
IF LI_COUNT = 0 THEN
INSERT INTO MIGRATION_ERROR_LOG(LEGACY_PROJECT_ID,LEGACY_WBS_NUMBER,ERROR_TYPE,FILE_NAME,ERROR_MESSAGE,VALIDATION_TYPE,FILE_TYPE)
VALUES(LS_PROJECT_ID,LS_MODULE_TYPE,'Validation','CUSTOM_DATA',CONCAT('Application id missing in FIBI'),'Before Migration',NULL);
COMMIT;
END IF;
END IF;
END LOOP;
CLOSE MIGRATION_CUSTOM_DATA_CURSOR;
END;
SELECT 'Prevalidation completed'  AS RESULT;
END
$$
DELIMITER ;
