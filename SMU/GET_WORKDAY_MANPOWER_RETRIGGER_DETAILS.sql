DELIMITER $$
CREATE  PROCEDURE `GET_WORKDAY_MANPOWER_RETRIGGER_DETAILS`(
AV_AWARD_NUMBER                  VARCHAR(20),
AV_POSITION_ID                   VARCHAR(200),
AV_PERSON_ID                     VARCHAR(20),
AV_WBS_NUMBER                    VARCHAR(200),
AV_START_DATE                    VARCHAR(200),
AV_END_DATE    			         VARCHAR(200),
AV_SORT_TYPE                     VARCHAR(500),
AV_PAGED                         INT(10),
AV_LIMIT                         INT(10),
AV_TYPE                          VARCHAR(1),
AV_TAB_TYPE                      VARCHAR(200),
AV_UNLIMITED                     BOOLEAN
)
BEGIN
DECLARE TAB_QUERY LONGTEXT;
DECLARE JOIN_CONDITION LONGTEXT;
DECLARE LS_DYN_SQL LONGTEXT;
DECLARE LS_FILTER_CONDITION LONGTEXT;
DECLARE LS_OFFSET_CONDITION VARCHAR(600);
DECLARE LS_OFFSET INT(11);
SET LS_OFFSET = (AV_LIMIT * AV_PAGED);
SET LS_FILTER_CONDITION ='';
SET LS_DYN_SQL ='';
SET JOIN_CONDITION = '';
IF AV_TYPE = 'A' THEN
		   IF AV_AWARD_NUMBER IS NOT NULL AND AV_AWARD_NUMBER <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.AWARD_NUMBER LIKE ''%',AV_AWARD_NUMBER,'%'' AND ');
			END IF;
           IF AV_POSITION_ID IS NOT NULL AND AV_POSITION_ID <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.POSITION_ID LIKE ''%',AV_POSITION_ID,'%'' AND ');
			END IF;
           IF AV_WBS_NUMBER IS NOT NULL AND AV_WBS_NUMBER <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.BUDGET_REFERENCE_NUMBER LIKE ''%',AV_WBS_NUMBER,'%'' AND ');
			END IF;
		   IF AV_PERSON_ID IS NOT NULL AND AV_PERSON_ID <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.PERSON_ID = ',AV_PERSON_ID,' AND ');
			END IF;
		    IF AV_START_DATE IS NOT NULL AND AV_START_DATE <> '' AND AV_END_DATE IS NOT NULL AND AV_END_DATE <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' DATE(T.INTERFACE_TIMESTAMP) BETWEEN DATE_FORMAT(''',AV_START_DATE,''',''%Y-%m-%d'') AND DATE_FORMAT(''',AV_END_DATE,''',''%Y-%m-%d'') AND ');
			END IF;
		   IF  AV_START_DATE <> '' AND AV_START_DATE IS NOT NULL  THEN
             SET LS_FILTER_CONDITION = CONCAT( LS_FILTER_CONDITION,' DATE(T.INTERFACE_TIMESTAMP ) >=   DATE_FORMAT(''',AV_START_DATE,''',''%Y-%m-%d'') AND ');
			END IF;
		   IF AV_END_DATE <> '' AND AV_END_DATE IS NOT NULL THEN
             SET LS_FILTER_CONDITION = CONCAT( LS_FILTER_CONDITION,' DATE(T.INTERFACE_TIMESTAMP ) <=   DATE_FORMAT(''',AV_END_DATE,''',''%Y-%m-%d'') AND ');
			END IF;
END IF;
IF AV_TAB_TYPE = 'AWARD_MANPOWER_RETRIGGER' THEN
			SET JOIN_CONDITION = CONCAT('SELECT T1.AWARD_ID,
											T1.WORKDAY_MANPOWER_INTERFACE_ID,
											T3.TITLE, T2.MESSAGE,
											T2.MESSAGE_TYPE,
											T1.INTERFACE_TYPE_CODE,
											T4.DESCRIPTION, T1.COMMENTS,
											T1.MANPOWER_USER_ACTION_CODE,
											T1.AWARD_NUMBER,
											T2.MANPOWER_LOG_ID,
                                            T1.INTERFACE_TIMESTAMP,
											T5.MANPOWER_USER_ACTION
											FROM WORKDAY_MANPOWER_INTERFACE T1
										INNER JOIN MANPOWER_LOG T2 on T2.WORKDAY_MANPOWER_INTERFACE_ID = T1.WORKDAY_MANPOWER_INTERFACE_ID
										INNER JOIN AWARD T3 on T3.AWARD_ID = T1.AWARD_ID
										INNER JOIN MANPOWER_INTERFACE_TYPE T4 on T4.INTERFACE_TYPE_CODE = T1.INTERFACE_TYPE_CODE
										LEFT JOIN MANPOWER_USER_ACTIONS T5 on T5.MANPOWER_USER_ACTION_CODE = T1.MANPOWER_USER_ACTION_CODE
										WHERE (T1.INTERFACE_STATUS_CODE IN (2,5) OR T1.MANPOWER_USER_ACTION_CODE IS NOT NULL) AND T1.INTERFACE_TYPE_CODE = 6');
ELSEIF AV_TAB_TYPE = 'POSITION_RETRIGGER' THEN
			SET JOIN_CONDITION = CONCAT('SELECT  T1.AWARD_NUMBER, T1.FULL_NAME, T1.POSITION_ID, T1.WORKDAY_MANPOWER_INTERFACE_ID, T1.BUDGET_REFERENCE_NUMBER, T1.INTERFACE_TYPE_CODE, T1.INTERFACE_TYPE,
											T1.INTERFACE_STATUS_CODE, T1.RESOURCE_UNIQUE_ID, CASE WHEN T1.CHARGE_START_DATE IS NULL THEN T1.PLAN_START_DATE ELSE T1.CHARGE_START_DATE END AS START_DATE ,
                                            CASE WHEN T1.CHARGE_END_DATE IS NULL THEN T1.PLAN_END_DATE ELSE T1.CHARGE_END_DATE END AS END_DATE, T1.JOB_PROFILE_TYPE,
											T1.MANPOWER_USER_ACTION, T1.INTERFACE_STATUS, T1.PERSON_ID, T1.COST_ALLOCATION, T1.INTERFACE_TIMESTAMP, T1.POSITION_STATUS, T1.COMMENTS, T1.MANPOWER_LOG_ID
											FROM (SELECT  T2.AWARD_NUMBER, T4.FULL_NAME, T4.POSITION_ID, T2.WORKDAY_MANPOWER_INTERFACE_ID, T5.BUDGET_REFERENCE_NUMBER, T2.INTERFACE_TYPE_CODE,
											T20.DESCRIPTION AS INTERFACE_TYPE, T2.INTERFACE_STATUS_CODE, T2.RESOURCE_UNIQUE_ID , T4.CHARGE_START_DATE, T4.CHARGE_END_DATE, T4.PLAN_START_DATE,
											T4.PLAN_END_DATE, T6.DESCRIPTION AS JOB_PROFILE_TYPE, T7.MANPOWER_USER_ACTION, T9.DESCRIPTION AS INTERFACE_STATUS, T4.PERSON_ID, T4.COST_ALLOCATION,
                                            T2.INTERFACE_TIMESTAMP, T8.DESCRIPTION AS POSITION_STATUS,  T2.COMMENTS, T3.MANPOWER_LOG_ID,
											ROW_NUMBER() OVER(PARTITION BY RESOURCE_UNIQUE_ID ORDER BY INTERFACE_STATUS_CODE )
											FROM WORKDAY_MANPOWER_INTERFACE T2
											INNER JOIN MANPOWER_LOG T3 ON T2.WORKDAY_MANPOWER_INTERFACE_ID = T3.WORKDAY_MANPOWER_INTERFACE_ID
											INNER JOIN AWARD_MANPOWER_RESOURCE T4 ON T4.AWARD_MANPOWER_RESOURCE_ID = T2.AWARD_MANPOWER_RESOURCE_ID
											INNER JOIN AWARD_MANPOWER T5 ON T5.AWARD_MANPOWER_ID = T4.AWARD_MANPOWER_ID
											LEFT OUTER JOIN MANPOWER_JOB_PROFILE_TYPE T6 ON T6.JOB_PROFILE_TYPE_CODE = T4.JOB_PROFILE_TYPE_CODE
											LEFT OUTER JOIN MANPOWER_USER_ACTIONS T7 ON T7.MANPOWER_USER_ACTION_CODE = T2.MANPOWER_USER_ACTION_CODE
											INNER JOIN MANPOWER_POSITION_STATUS T8 ON T8.POSITION_STATUS_CODE = T4.POSITION_STATUS_CODE
											INNER JOIN MANPOWER_INTERFACE_STATUS T9 ON T9.INTERFACE_STATUS_CODE = T2.INTERFACE_STATUS_CODE
											INNER JOIN MANPOWER_INTERFACE_TYPE T20 ON T20.INTERFACE_TYPE_CODE = T2.INTERFACE_TYPE_CODE
											WHERE ((T2.INTERFACE_STATUS_CODE = 2 OR T2.MANPOWER_USER_ACTION_CODE IS NOT NULL) AND ((T2.INTERFACE_TYPE_CODE = 3 AND T3.MESSAGE_TYPE = ''TECHNICAL_ERROR'') OR (T2.INTERFACE_TYPE_CODE IN (1, 14, 4, 8)))))T1 GROUP BY T1.RESOURCE_UNIQUE_ID');
ELSEIF AV_TAB_TYPE = 'COST_ALLOCATION_RETRIGGER' THEN
		  SET JOIN_CONDITION = CONCAT('SELECT  T1.AWARD_NUMBER, T1.FULL_NAME, T1.POSITION_ID, T1.WORKDAY_MANPOWER_INTERFACE_ID, T1.BUDGET_REFERENCE_NUMBER, T1.INTERFACE_TYPE_CODE, T1.INTERFACE_TYPE,
											T1.INTERFACE_STATUS_CODE, T1.RESOURCE_UNIQUE_ID, CASE WHEN T1.CHARGE_START_DATE IS NULL THEN T1.PLAN_START_DATE ELSE T1.CHARGE_START_DATE END AS START_DATE ,
                                            CASE WHEN T1.CHARGE_END_DATE IS NULL THEN T1.PLAN_END_DATE ELSE T1.CHARGE_END_DATE END AS END_DATE, T1.JOB_PROFILE_TYPE,
											T1.MANPOWER_USER_ACTION, T1.INTERFACE_STATUS, T1.PERSON_ID, T1.COST_ALLOCATION, T1.INTERFACE_TIMESTAMP, T1.POSITION_STATUS, T1.COMMENTS, T1.MANPOWER_LOG_ID
											FROM (SELECT  T2.AWARD_NUMBER, T4.FULL_NAME, T4.POSITION_ID, T2.WORKDAY_MANPOWER_INTERFACE_ID, T5.BUDGET_REFERENCE_NUMBER, T2.INTERFACE_TYPE_CODE,
											T20.DESCRIPTION AS INTERFACE_TYPE, T2.INTERFACE_STATUS_CODE, T2.RESOURCE_UNIQUE_ID , T4.CHARGE_START_DATE, T4.CHARGE_END_DATE, T4.PLAN_START_DATE,
											T4.PLAN_END_DATE, T6.DESCRIPTION AS JOB_PROFILE_TYPE, T7.MANPOWER_USER_ACTION, T9.DESCRIPTION AS INTERFACE_STATUS, T4.PERSON_ID, T4.COST_ALLOCATION,
                                            T2.INTERFACE_TIMESTAMP, T8.DESCRIPTION AS POSITION_STATUS,  T2.COMMENTS, T3.MANPOWER_LOG_ID,
											ROW_NUMBER() OVER(PARTITION BY RESOURCE_UNIQUE_ID ORDER BY INTERFACE_STATUS_CODE )
											FROM WORKDAY_MANPOWER_INTERFACE T2
											INNER JOIN MANPOWER_LOG T3 ON T2.WORKDAY_MANPOWER_INTERFACE_ID = T3.WORKDAY_MANPOWER_INTERFACE_ID
											INNER JOIN AWARD_MANPOWER_RESOURCE T4 ON T4.AWARD_MANPOWER_RESOURCE_ID = T2.AWARD_MANPOWER_RESOURCE_ID
											INNER JOIN AWARD_MANPOWER T5 ON T5.AWARD_MANPOWER_ID = T4.AWARD_MANPOWER_ID
											LEFT OUTER JOIN MANPOWER_JOB_PROFILE_TYPE T6 ON T6.JOB_PROFILE_TYPE_CODE = T4.JOB_PROFILE_TYPE_CODE
											LEFT OUTER JOIN MANPOWER_USER_ACTIONS T7 ON T7.MANPOWER_USER_ACTION_CODE = T2.MANPOWER_USER_ACTION_CODE
											INNER JOIN MANPOWER_POSITION_STATUS T8 ON T8.POSITION_STATUS_CODE = T4.POSITION_STATUS_CODE
											INNER JOIN MANPOWER_INTERFACE_STATUS T9 ON T9.INTERFACE_STATUS_CODE = T2.INTERFACE_STATUS_CODE
											INNER JOIN MANPOWER_INTERFACE_TYPE T20 ON T20.INTERFACE_TYPE_CODE = T2.INTERFACE_TYPE_CODE
											WHERE ((T2.INTERFACE_STATUS_CODE = 2 OR T2.MANPOWER_USER_ACTION_CODE IS NOT NULL) AND T2.INTERFACE_TYPE_CODE IN (2, 17)))T1 ');
END IF;
IF AV_SORT_TYPE IS NULL THEN
	SET AV_SORT_TYPE =  CONCAT(' ORDER BY T.INTERFACE_TIMESTAMP DESC ');
ELSE
    SET AV_SORT_TYPE = CONCAT(' ORDER BY ',AV_SORT_TYPE);
END IF;
IF AV_UNLIMITED = TRUE THEN
	SET LS_OFFSET_CONDITION = '';
ELSE
	SET LS_OFFSET_CONDITION = CONCAT(' LIMIT ',AV_LIMIT,' OFFSET ',LS_OFFSET);
END IF;
IF LS_FILTER_CONDITION <>'' THEN
SET LS_FILTER_CONDITION = CONCAT(' WHERE ',LS_FILTER_CONDITION);
SELECT TRIM(TRAILING 'AND ' FROM LS_FILTER_CONDITION) into LS_FILTER_CONDITION from dual;
END IF;
			SET LS_DYN_SQL =CONCAT('SELECT DISTINCT *  FROM('
											,JOIN_CONDITION,'
											)T' ,LS_FILTER_CONDITION, ' ',AV_SORT_TYPE,' ',LS_OFFSET_CONDITION );
SET @QUERY_STATEMENT = LS_DYN_SQL;
PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
EXECUTE EXECUTABLE_STAEMENT;
END
$$
DELIMITER ;
