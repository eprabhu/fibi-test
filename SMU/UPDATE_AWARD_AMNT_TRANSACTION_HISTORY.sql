DELIMITER $$
CREATE  PROCEDURE `UPDATE_AWARD_AMNT_TRANSACTION_HISTORY`(AV_ID INT)
BEGIN
DECLARE LS_ERROR_MSG	VARCHAR(1000);
DECLARE LS_TABLE_NAME	VARCHAR(30);
DECLARE LI_FLAG			INT;
DECLARE LI_AWARD_ID						DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER					VARCHAR(12);
DECLARE LI_SEQUENCE_NUMBER				INT;
DECLARE LI_TRANSACTION_ID 				DECIMAL(22,0);
DECLARE LI_TRNSCTN_HISTORY_ID			INT;
		BEGIN
				DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
				BEGIN
					GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
					 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
					SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
					SELECT @full_error INTO LS_ERROR_MSG;
					INSERT INTO AWARD_ERROR_LOG(AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER, ERROR_MESSAGE, PROCEDURE_NAME, TABLE_NAME,SECTION_CODE,VARIATION_TYPE_CODE, UPDATE_TIMESTAMP, UPDATE_USER)
					VALUES(LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER,LS_ERROR_MSG,'UPDATE_AWARD_AMNT_TRANSACTION_HISTORY',NULL,NULL,null,UTC_TIMESTAMP(),'quickstart');
					COMMIT;
				END;
				SET SQL_SAFE_UPDATES = 0;
				BEGIN
					DECLARE DONE1 INT DEFAULT FALSE;
					DECLARE CUR_AWARD_DATA CURSOR FOR
					SELECT AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER FROM AWARD
					WHERE SEQUENCE_NUMBER <> 0;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
					OPEN CUR_AWARD_DATA;
					INSERT_AWARD_LOOP: LOOP
					FETCH CUR_AWARD_DATA INTO
					LI_AWARD_ID,
					LS_AWARD_NUMBER,
					LI_SEQUENCE_NUMBER;
					IF DONE1 THEN
						LEAVE INSERT_AWARD_LOOP;
					END IF;
						SELECT COUNT(1) INTO LI_FLAG
						FROM AWARD_AMOUNT_INFO
						WHERE AWARD_AMOUNT_INFO_ID IN (SELECT MAX(AWARD_AMOUNT_INFO_ID)
													   FROM AWARD_AMOUNT_INFO
													   WHERE AWARD_NUMBER = LS_AWARD_NUMBER
													   AND SEQUENCE_NUMBER <= LI_SEQUENCE_NUMBER
													   );
						IF LI_FLAG > 0 THEN
							SELECT TRANSACTION_ID INTO LI_TRANSACTION_ID
							FROM AWARD_AMOUNT_INFO
							WHERE AWARD_AMOUNT_INFO_ID IN (SELECT MAX(AWARD_AMOUNT_INFO_ID)
														   FROM AWARD_AMOUNT_INFO
														   WHERE AWARD_NUMBER = LS_AWARD_NUMBER
														   AND SEQUENCE_NUMBER <= LI_SEQUENCE_NUMBER
														   );
							SELECT IFNULL(MAX(TRNSCTN_HISTORY_ID),0)+1 INTO LI_TRNSCTN_HISTORY_ID FROM AWARD_AMT_TRNSCTN_HISTORY;
							INSERT INTO AWARD_AMT_TRNSCTN_HISTORY(TRNSCTN_HISTORY_ID, TRANSACTION_ID, UPDATE_TIMESTAMP, UPDATE_USER, AWARD_ID, AWARD_NUMBER, SEQUENCE_NUMBER)
							VALUES(LI_TRNSCTN_HISTORY_ID,LI_TRANSACTION_ID,UTC_TIMESTAMP(),'quickstart',LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQUENCE_NUMBER);
						END IF;
					END LOOP;
					CLOSE CUR_AWARD_DATA;
				END;
		END;
END
$$
DELIMITER ;
