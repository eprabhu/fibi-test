DELIMITER $$
CREATE  PROCEDURE `get_award_expense_person_dtls`(
AV_BUDGET_DETAILS_ID INT,
AV_AWARD_NUMBER VARCHAR(12),
AV_ACCOUNT_NUMBER VARCHAR(100)
  )
    DETERMINISTIC
BEGIN
SELECT
	DISTINCT
	T3.BUDGET_CATEGORY_CODE,
	T6.DESCRIPTION AS BUDGET_CATEGORY,
	T3.COST_ELEMENT,
	T7.DESCRIPTION AS LINE_ITEM,
	BP1.IO_CODE AS IO_CODE,
	T3.QUANTITY,
	null AS ORIGINAL_APPROVED_BUDGET,
	BP1.SALARY_REQUESTED AS LATEST_APPROVED_BUDGET,
	case when BP1.IO_CODE is null then 0 else T4.TOTAL_EXPENSE_AMOUNT end AS EXPENDITURE_TO_DATE,
	IFNULL(BP1.SALARY_REQUESTED,0)-IFNULL(case when BP1.IO_CODE is null then 0 else T4.TOTAL_EXPENSE_AMOUNT end,0) AS BALANCE,
	ROUND((case when BP1.IO_CODE is null then 0 else T4.TOTAL_EXPENSE_AMOUNT end/BP1.SALARY_REQUESTED)*100,2) AS UTILIZATION_RATE,
	T6.BUDGET_CATEGORY_TYPE_CODE,
	T6.SORT_ORDER,
    T3.BUDGET_DETAILS_ID,
	CASE WHEN T7.COST_ELEMENT = '4' THEN 'Y'
		 ELSE
			'N'
	END AS STUDENT_HRS_FLAG,
    CASE WHEN T8.PERSON_TYPE = 'T' THEN
		T9.PERSON_NAME
    ELSE
		T8.PERSON_NAME
    END AS PERSON_NAME
FROM AWARD_BUDGET_DETAIL T3
LEFT OUTER JOIN AWARD_BUDGET_PERSON_DETAIL BP1 ON BP1.BUDGET_DETAILS_ID = T3.BUDGET_DETAILS_ID
LEFT OUTER JOIN AWARD_EXPENSE_DETAILS T4 ON IFNULL(BP1.IO_CODE,'0') = IFNULL(T4.INTERNAL_ORDER_CODE,'0')
AND T4.AWARD_NUMBER = AV_AWARD_NUMBER
AND T4.ACCOUNT_NUMBER = AV_ACCOUNT_NUMBER
INNER JOIN BUDGET_CATEGORY T6 ON T3.BUDGET_CATEGORY_CODE = T6.BUDGET_CATEGORY_CODE
LEFT OUTER JOIN COST_ELEMENT T7 ON T7.COST_ELEMENT = T3.COST_ELEMENT
LEFT OUTER JOIN AWARD_BUDGET_PERSONS T8 ON T8.BUDGET_PERSON_ID = BP1.BUDGET_PERSON_ID
LEFT OUTER JOIN TBN T9 ON T9.TBN_ID = T8.TBN_ID
WHERE T3.BUDGET_DETAILS_ID = AV_BUDGET_DETAILS_ID
AND T3.BUDGET_CATEGORY_CODE<>600;
END
$$
DELIMITER ;
