DELIMITER $$
CREATE  PROCEDURE `AWARD_INSERT_PI_ROLES`()
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_ERROR_MSG 		VARCHAR(1000);
DECLARE LS_PERSON_ID 		VARCHAR(40);
DECLARE LI_AWARD_ID			DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER		VARCHAR(12);
DECLARE LI_AWARD_PERSON_ROLE_ID	INT(12);
DECLARE LI_FLAG INT;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
		PERSON_ID,
		AWARD_ID,
		AWARD_NUMBER
		FROM AWARD_PERSONS WHERE PERSON_ROLE_ID = 3
		AND PERSON_ID IS NOT NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_PERSON_ID,
		LI_AWARD_ID,
		LS_AWARD_NUMBER;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM AWARD_PERSON_ROLES
		WHERE AWARD_ID = LI_AWARD_ID
		AND PERSON_ID = LS_PERSON_ID
		AND ROLE_ID = 653;
		IF LI_FLAG = 0 THEN
			SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
			INSERT INTO AWARD_PERSON_ROLES
			(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
			VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,1,LS_PERSON_ID,653,NOW(),'quickstart');
			commit;
		END IF;
		END LOOP;
		CLOSE CUR_SEL_DATA;
		UPDATE AWARD_PERSON_ROLE_ID_GENERATOR SET NEXT_VAL = (SELECT MAX(AWARD_PERSON_ROLE_ID)+1 FROM AWARD_PERSON_ROLES);
		END;
END
$$
DELIMITER ;
