DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PREVAL_AWARD`(
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID 		INT;
DECLARE LS_ERROR_MSG 				VARCHAR(1000);
DECLARE LS_PROJECT_ID 				VARCHAR(200);
DECLARE LS_PROJECT_TYPE 			VARCHAR(50);
DECLARE LS_PROJECT_STATUS 			VARCHAR(50);
DECLARE LS_PROJECT_TITLE 			VARCHAR(500);
DECLARE LS_PROJECT_START_DATE 		VARCHAR(50);
DECLARE LS_PROJECT_END_DATE 		VARCHAR(50);
DECLARE LS_PROJECT_DURATION 		VARCHAR(200);
DECLARE LS_PROJECT_LEAD_UNIT 		VARCHAR(600);
DECLARE LS_DATE_OF_AWARD 			VARCHAR(50);
DECLARE LS_PROJECT_FUND_CENTRE 		VARCHAR(200);
DECLARE LS_PROJECT_FUND_CODE 		VARCHAR(200);
DECLARE LI_FLAG						INT;
DECLARE LS_LINKED_NAME_OF_FUNDING_AGENCY	VARCHAR(200);
DECLARE LS_LINKED_TYPE_OF_FUNDING_AGENCY	VARCHAR(200);
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'EXCEPTION','PROJECT',LS_ERROR_MSG,'PRE_VALIDATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			PROJECT_ID,
			PROJECT_TYPE,
			PROJECT_STATUS,
			PROJECT_TITLE,
			PROJECT_START_DATE,
			PROJECT_END_DATE,
			PROJECT_DURATION,
			PROJECT_LEAD_UNIT,
			DATE_OF_AWARD,
			PROJECT_FUND_CENTRE,
			PROJECT_FUND_CODE,
			LINKED_NAME_OF_FUNDING_AGENCY,
			LINKED_TYPE_OF_FUNDING_AGENCY
		FROM MIGRATION_AWARD
		WHERE PROJECT_ID IN ('000334', '000335', '000455', '000440', '000002', '000067', '000133', '000064', '000220', '000164', '000125', '000108', '000008',
							'000089', '000310', '000399', '000431', '000327', '000440', '000409');
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_PROJECT_ID,
		LS_PROJECT_TYPE,
		LS_PROJECT_STATUS,
		LS_PROJECT_TITLE,
		LS_PROJECT_START_DATE,
		LS_PROJECT_END_DATE,
		LS_PROJECT_DURATION,
		LS_PROJECT_LEAD_UNIT,
		LS_DATE_OF_AWARD,
		LS_PROJECT_FUND_CENTRE,
		LS_PROJECT_FUND_CODE,
		LS_LINKED_NAME_OF_FUNDING_AGENCY,
		LS_LINKED_TYPE_OF_FUNDING_AGENCY;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		/*IF LS_PROJECT_TYPE = 'GRANT' THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM MIGRATION_PROPOSAL
			WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_PROJECT_ID));
			IF LI_FLAG = 0 THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT ID IS NOT IN PROPOSAL FILE',NULL,'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
			END IF;
		END IF;
		*/
		-- IF LS_PROJECT_TYPE = 'Direct Engagement' THEN
			IF LS_LINKED_NAME_OF_FUNDING_AGENCY IS NOT NULL THEN
				SELECT COUNT(1) INTO LI_FLAG
				FROM SPONSOR WHERE UPPER(TRIM(SPONSOR_NAME)) = UPPER(TRIM(LS_LINKED_NAME_OF_FUNDING_AGENCY));
				IF LI_FLAG = 0 THEN
					SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
					INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
													VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
												   )
					VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','NAME_OF_FUNDING_AGENCY DOES NOT EXIST',LS_LINKED_NAME_OF_FUNDING_AGENCY,'PREVALIDATION','N',NOW(),'quickstart');
					COMMIT;
				END IF;
			ELSE
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
					INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
													VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
												   )
					VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','NAME_OF_FUNDING_AGENCY IS NULL FOR PROJETCS',NULL,'PREVALIDATION','N',NOW(),'quickstart');
					COMMIT;
			END IF;
		-- END IF;
		IF LS_PROJECT_TITLE IS NULL OR LS_PROJECT_TITLE = '' THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
											VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
										   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','AWARD TITLE IS NULL',NULL,'PREVALIDATION','N',NOW(),'quickstart');
			COMMIT;
		END IF;
		IF LS_PROJECT_STATUS IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM AWARD_STATUS
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_STATUS));
			IF LI_FLAG = 0 THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT STATUS DOES NOT EXIST',LS_PROJECT_STATUS,'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
			END IF;
		ELSE
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT STATUS IS NULL',LS_PROJECT_STATUS,'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
		END IF;
		IF LS_PROJECT_LEAD_UNIT IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM UNIT
			WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROJECT_LEAD_UNIT));
			IF LI_FLAG = 0 THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT LEAD UNIT DOES NOT EXIST',LS_PROJECT_LEAD_UNIT,'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
			END IF;
		ELSE
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT LEAD UNIT IS NULL',LS_PROJECT_LEAD_UNIT,'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM AWARD_TYPE WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_TYPE));
		IF LI_FLAG = 0 THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
											VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
										   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT TYPE DOES NOT EXIST',LS_PROJECT_TYPE,'PREVALIDATION','Y',NOW(),'quickstart');
			COMMIT;
		END IF;
		IF ( IFNULL(TRIM(LS_PROJECT_START_DATE),'')  = '' OR STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y') IS NULL ) THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
											VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
										   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT',CONCAT('Project Start date can''t be NULL or Improper format'),LS_PROJECT_START_DATE,'PREVALIDATION','N',NOW(),'quickstart');
			COMMIT;
		END IF;
		IF ( IFNULL(TRIM(LS_PROJECT_END_DATE),'') = '' OR STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y') IS NULL ) THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
											VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
										   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT',CONCAT('Project End date can''t be NULL or Improper format'),LS_PROJECT_END_DATE,'PREVALIDATION','N',NOW(),'quickstart');
			COMMIT;
		END IF;
		IF (  STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y') IS NOT NULL AND TRIM(LS_PROJECT_START_DATE) <> ''
				      AND STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y') IS NOT NULL AND TRIM(LS_PROJECT_END_DATE) <> ''
					  AND STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y') > STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y') )THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
											VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
										   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT',CONCAT('Project Start date "',TRIM(LS_PROJECT_START_DATE),'" should come before Project end date "',TRIM(LS_PROJECT_END_DATE),'"'),CONCAT(LS_PROJECT_START_DATE,',',LS_PROJECT_END_DATE),'PREVALIDATION','N',NOW(),'quickstart');
			COMMIT;
		END IF;
		/*IF ( IFNULL(TRIM(LS_DATE_OF_AWARD),'') = '' OR STR_TO_DATE(LS_DATE_OF_AWARD,'%d/%m/%Y') IS NULL ) THEN
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
											VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
										   )
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT',CONCAT('Project Date Of award is NULL or Improper format'),LS_DATE_OF_AWARD,'PREVALIDATION','Y',NOW(),'quickstart');
			COMMIT;
		END IF;
		*/
		END LOOP;
		CLOSE CUR_SEL_DATA;
	END;
END;
END
$$
