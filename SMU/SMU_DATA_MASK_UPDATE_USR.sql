DELIMITER $$
CREATE  PROCEDURE `SMU_DATA_MASK_UPDATE_USR`(AV_ACTION INT)
BEGIN
	-- DECLARE LI_PERSON_ID VARCHAR(40);
	-- DECLARE LS_USR_NAME VARCHAR(60);
	-- DECLARE LS_USR_NEW  VARCHAR(60);
	DECLARE LS_ERR_FLG VARCHAR(1);
	DECLARE LS_ERROR VARCHAR(2000);
	DECLARE DONE BOOLEAN;
	DECLARE LS_TABLE_NAME VARCHAR(100);
	DECLARE LS_COL_NAME VARCHAR(100);
	-- DECLARE LS_ERR_RECORD_ID VARCHAR(40);
	DECLARE LS_ERR_TABLE_NAME VARCHAR(100);
	DECLARE LS_STAGE VARCHAR(50);
	/*DECLARE CUR_PERSON CURSOR FOR
	SELECT PERSON_ID,USER_NAME
	FROM PERSON WHERE FULL_NAME NOT IN ('SMU Admin');*/
	DECLARE  CUR_USR CURSOR FOR
		SELECT TABLE_NAME,COLUMN_NAME
		FROM SMU_DATA_MASK_TAB_DTLS
		WHERE PERSON_TYPE = 'PER'
		AND DATA_CATEGORY = 'USR';
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE = TRUE;
	DECLARE EXIT HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR;
		ROLLBACK;
		INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS,ERR_TABLE_NAME,ERROR_MESSAGE)
		VALUES( LS_STAGE,'ERROR',LS_ERR_TABLE_NAME,LS_ERROR);
		COMMIT;
		SET LS_ERR_FLG ='Y';
	END;
BEGIN
	 SET AUTOCOMMIT= 0;
	 SET SQL_SAFE_UPDATES= 0;
	 TRUNCATE TABLE SMU_DATA_MASK_AUDIT_LOG;
	 SET LS_ERR_FLG = 'N';
	 SET LS_STAGE = 'Updating usr details';
	 INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Started');
	OPEN CUR_USR;
		usr_loop: LOOP
			SET DONE = FALSE;
			FETCH CUR_USR INTO LS_TABLE_NAME, LS_COL_NAME;
			IF DONE = TRUE THEN
				LEAVE usr_loop;
			END IF;
			SET LS_ERR_TABLE_NAME = LS_TABLE_NAME;
			SET @stmt = CONCAT ('UPDATE ', LS_TABLE_NAME, ' a SET ',LS_COL_NAME, '  = (SELECT PERSON_ID FROM PERSON WHERE USER_NAME = a.',LS_COL_NAME,' ORDER BY STATUS LIMIT 1) WHERE ',LS_COL_NAME,' <> ''quickstart'' AND EXISTS (SELECT 1 FROM PERSON WHERE USER_NAME = a.',LS_COL_NAME,')');
			PREPARE LS_EXEC_STMT FROM  @stmt;
			EXECUTE  LS_EXEC_STMT;
			DEALLOCATE PREPARE LS_EXEC_STMT;
	END LOOP;
	CLOSE CUR_USR;
	INSERT INTO SMU_DATA_MASK_AUDIT_LOG
				(STAGE,STATUS)
	VALUES( LS_STAGE,'Completed');
	IF LS_ERR_FLG = 'N' THEN
		-- ROLLBACK;
		INSERT INTO SMU_DATA_MASK_AUDIT_LOG
					(STAGE,STATUS)
		VALUES( LS_STAGE,'Update usr Procedure Completed');
		COMMIT;
	END IF;
END;
END
$$
DELIMITER ;
