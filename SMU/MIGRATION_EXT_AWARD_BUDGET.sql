DELIMITER $$
CREATE  PROCEDURE `MIGRATION_EXT_AWARD_BUDGET`(av_id int
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID 			INT;
DECLARE LS_ERROR_MSG 					VARCHAR(1000);
DECLARE LI_FLAG 						INT;
DECLARE LS_PROJECT_ID 					VARCHAR(255);
DECLARE LS_FUND_CENTRE					VARCHAR(255);
DECLARE LS_FUND_CODE					VARCHAR(255);
DECLARE LS_BUDGET_CATEGORY				VARCHAR(50);
DECLARE LS_BUDGET_LINE_ITEM				VARCHAR(50);
DECLARE LS_QUANTITY						VARCHAR(50);
DECLARE LS_IO_CODE						VARCHAR(50);
DECLARE LS_ORIGINAL_APPROVED_BUDGET		VARCHAR(50);
DECLARE LS_CURRENT_APPROVED_BUDGET		VARCHAR(50);
DECLARE LS_EXPENDITURE_TO_DATE			VARCHAR(50);
DECLARE LS_AMOUNT_REMAIN_BAL			VARCHAR(50);
DECLARE LS_UTILIZATION_RATE				VARCHAR(50);
DECLARE LI_AWARD_AMOUNT_TRANSACTION_ID      DECIMAL(12,0);
DECLARE LS_TRANSACTION_ID                   VARCHAR(20);
DECLARE LI_AWARD_ID							DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER						VARCHAR(12);
DECLARE LI_AWARD_AMOUNT_INFO_ID				DECIMAL(22,0);
DECLARE LI_BUDGET_HEADER_ID					INT;
DECLARE LS_PROJECT_START_DATE 		DATETIME;
DECLARE LS_PROJECT_END_DATE 		DATETIME;
DECLARE LI_BUDGET_PERIOD_ID 		INT(12);
DECLARE LI_BUDGET_DETAILS_ID 		INT(12);
DECLARE LI_LINE_ITEM_NUMBER			INT(3);
DECLARE LS_BUDGET_CATEGORY_CODE 	VARCHAR(3);
DECLARE LS_COST_ELEMENT 			VARCHAR(500);
DECLARE LI_TOTAL_COST 				DECIMAL(13,2);
DECLARE LS_TOTAL_CASH				VARCHAR(50);
DECLARE LS_CASH						VARCHAR(50);
DECLARE LS_CONTRIBUTIONS			VARCHAR(50);
DECLARE LI_AWARD_COST_SHARE_ID		INT(12);
DECLARE LI_TOTAL_DIRECT_COST		DECIMAL(13,2);
DECLARE LI_DIRECT_COST				DECIMAL(13,2);
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'EXCEPTION','PROJECT_BUDGET',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
			COMMIT;
		END;
		BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			DISTINCT
			PROJECT_ID
		FROM MIGRATION_EXT_AWARD_BUDGET
		where PROJECT_ID IN (SELECT PROJECT_ID FROM MIGRATION_EXT_AWARD);
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP1: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_PROJECT_ID;
		IF DONE1 THEN
			LEAVE INSERT_LOOP1;
		END IF;
			SELECT COUNT(1) INTO LI_FLAG
			FROM MIGRATION_EXT_AWARD
			WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID));
			IF LI_FLAG = 0 THEN
				ITERATE INSERT_LOOP1;
			ELSE
				SELECT AWARD_ID,AWARD_NUMBER,
				DATE_FORMAT(STR_TO_DATE(PROJECT_START_DATE,'%d/%m/%Y'),'%Y-%m-%d 00:00:00'),
				DATE_FORMAT(STR_TO_DATE(PROJECT_END_DATE,'%d/%m/%Y'),'%Y-%m-%d 00:00:00'),
				CASH,CONTRIBUTIONS,TOTAL_CASH
				INTO LI_AWARD_ID,LS_AWARD_NUMBER,LS_PROJECT_START_DATE,LS_PROJECT_END_DATE,LS_CASH,LS_CONTRIBUTIONS,LS_TOTAL_CASH
				FROM MIGRATION_EXT_AWARD
				WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID));
			END IF;
			SELECT COUNT(1) INTO LI_FLAG
			FROM MIGRATION_EXT_AWARD_BUDGET
			WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID))
			AND FUND_CENTRE IS NOT NULL;
			IF LI_FLAG > 0 THEN
				SELECT FUND_CENTRE INTO LS_FUND_CENTRE
				FROM MIGRATION_EXT_AWARD_BUDGET
				WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID))
				AND FUND_CENTRE IS NOT NULL LIMIT 1;
			END IF;
			SELECT COUNT(1) INTO LI_FLAG
			FROM MIGRATION_EXT_AWARD_BUDGET
			WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID))
			AND FUND_CODE IS NOT NULL;
			IF LI_FLAG > 0 THEN
				SELECT FUND_CENTRE INTO LS_FUND_CODE
				FROM MIGRATION_EXT_AWARD_BUDGET
				WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID))
				AND FUND_CODE IS NOT NULL LIMIT 1;
				SET SQL_SAFE_UPDATES = 0;
				UPDATE AWARD SET ACCOUNT_NUMBER = LS_FUND_CODE
				WHERE AWARD_ID = LI_AWARD_ID;
			END IF;
				SELECT IFNULL(MAX(AWARD_AMOUNT_TRANSACTION_ID),0)+1 INTO LI_AWARD_AMOUNT_TRANSACTION_ID
				FROM AWARD_AMOUNT_TRANSACTION;
				SET LS_TRANSACTION_ID = CONCAT(DATE_FORMAT(NOW(),'%y%d%m'), SUBSTRING(DATE_FORMAT(NOW(2),'%h%m%s%f'),1,5),LI_AWARD_ID);
				INSERT INTO AWARD_AMOUNT_TRANSACTION
				(
				 AWARD_AMOUNT_TRANSACTION_ID,
				 AWARD_NUMBER,
				 TRANSACTION_ID,
				 TRANSACTION_TYPE_CODE,
				 COMMENTS,
				 SOURCE_AWARD_NUMBER,
				 DESTINATION_AWARD_NUMBER,
				 UPDATE_TIMESTAMP,
				 UPDATE_USER,
				 FUNDED_PROPOSAL_ID,
				 NOTICE_DATE
				)
				VALUES
				(
				LI_AWARD_AMOUNT_TRANSACTION_ID,
				LS_AWARD_NUMBER,
				LS_TRANSACTION_ID,
				17,
				'Migrated Award',
				'EXTERNAL',
				LS_AWARD_NUMBER,
				NOW(),
				'quickstart',
				NULL,
				NULL
				);
				COMMIT;
				SELECT IFNULL(MAX(AWARD_AMOUNT_INFO_ID),0)+1 INTO LI_AWARD_AMOUNT_INFO_ID
				FROM AWARD_AMOUNT_INFO;
				INSERT INTO AWARD_AMOUNT_INFO(
				AWARD_AMOUNT_INFO_ID,
				AWARD_ID,
				AWARD_NUMBER,
				SEQUENCE_NUMBER,
				TRANSACTION_ID,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				ANTICIPATED_CHANGE,
				ANTICIPATED_CHANGE_DIRECT,
				ANTICIPATED_CHANGE_INDIRECT,
				OBLIGATED_CHANGE,
				OBLIGATED_CHANGE_DIRECT,
				OBLIGATED_CHANGE_INDIRECT,
				ANTICIPATED_TOTAL_DIRECT,
				ANTICIPATED_TOTAL_INDIRECT,
				ANTICIPATED_TOTAL_AMOUNT,
				OBLIGATED_TOTAL_DIRECT,
				OBLIGATED_TOTAL_INDIRECT,
				AMOUNT_OBLIGATED_TO_DATE,
				ANT_DISTRIBUTABLE_AMOUNT,
				OBLI_DISTRIBUTABLE_AMOUNT,
				FINAL_EXPIRATION_DATE,
				CURRENT_FUND_EFFECTIVE_DATE,
				OBLIGATION_EXPIRATION_DATE,
				TOTAL_COST_IN_CURRENCY,
				CURRENCY_CODE
				)
				VALUES(
				LI_AWARD_AMOUNT_INFO_ID,
				LI_AWARD_ID,
				LS_AWARD_NUMBER,
				1,
				LS_TRANSACTION_ID,
				NOW(),
				'quickstart',
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				0,
				0,
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				0,
				0,
				0,
				0,
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				0,
				0,
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				LS_PROJECT_END_DATE,
				LS_PROJECT_START_DATE,
				LS_PROJECT_END_DATE,
				0,
				'SGD'
				);
				COMMIT;
			SET SQL_SAFE_UPDATES = 0;
			update AWARD_AMOUNT_INFO set OBLIGATION_EXPIRATION_DATE = DATE_FORMAT(STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y'),'%Y-%m-%d 00:00:00')
			where AWARD_ID = LI_AWARD_ID;
			SELECT IFNULL(MAX(BUDGET_HEADER_ID),0)+1 INTO LI_BUDGET_HEADER_ID FROM AWARD_BUDGET_HEADER;
			INSERT INTO AWARD_BUDGET_HEADER
			(
			BUDGET_HEADER_ID,
			BUDGET_STATUS_CODE,
			BUDGET_TYPE_CODE,
			CREATE_TIMESTAMP,
			CREATE_USER,
			CREATE_USER_NAME,
			END_DATE,
			IS_AUTO_CALC,
			OBLIGATED_CHANGE,
			OBLIGATED_TOTAL,
			ON_OFF_CAMPUS_FLAG,
			RATE_CLASS_CODE,
			RATE_TYPE_CODE,
			START_DATE,
			TOTAL_COST,
			TOTAL_DIRECT_COST,
			TOTAL_INDIRECT_COST,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			UPDATE_USER_NAME,
			VERSION_NUMBER,
			TOTAL_SUBCONTRACT_COST,
			AWARD_ID,
			AWARD_NUMBER,
			SEQUENCE_NUMBER,
			FUND_CENTRE,
			FUND_CODE,
			AWARD_BUDGET_STATUS_CODE,
			IS_LATEST_VERSION
			)
			VALUES
			(
			LI_BUDGET_HEADER_ID,
			3,
			1,
			NOW(),
			'quickstart',
			'quickstart',
			LS_PROJECT_END_DATE,
			'N',
			0,
			0,
			'N',
			1,
			1,
			LS_PROJECT_START_DATE,
			0,
			0,
			IFNULL(CAST(LS_CASH AS DECIMAL(13,2)),0),
			NOW(),
			'quickstart',
			'quickstart',
			1,
			0.00,
			LI_AWARD_ID,
			LS_AWARD_NUMBER,
			1,
			LS_FUND_CENTRE,
			LS_FUND_CODE,
			10,
			'Y'
			);
				SELECT IFNULL(MAX(BUDGET_PERIOD_ID),0)+1 INTO LI_BUDGET_PERIOD_ID
				FROM AWARD_BUDGET_PERIOD;
				INSERT INTO AWARD_BUDGET_PERIOD
				(
				BUDGET_PERIOD_ID,
				BUDGET_PERIOD,
				END_DATE,
				START_DATE,
				TOTAL_COST,
				TOTAL_DIRECT_COST,
				TOTAL_INDIRECT_COST,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				VERSION_NUMBER,
				BUDGET_HEADER_ID,
				SUBCONTRACT_COST,
				AWARD_NUMBER,
				DEV_PROPOSAL_ID,
				DEV_PROP_BUDGET_ID,
				DEV_PROP_BUDGET_PERIOD
				)
				VALUES
				(
				LI_BUDGET_PERIOD_ID,
				1,
				LS_PROJECT_END_DATE,
				LS_PROJECT_START_DATE,
				0,
				0,
				IFNULL(CAST(LS_CASH AS DECIMAL(13,2)),0),
				NOW(),
				'quickstart',
				1,
				LI_BUDGET_HEADER_ID,
				0,
				LS_AWARD_NUMBER,
				NULL,
				NULL,
				NULL
				);
			SET LI_LINE_ITEM_NUMBER = 0;
			IF LS_CASH IS NOT NULL THEN
						SELECT IFNULL(MAX(BUDGET_DETAILS_ID),0)+1 INTO LI_BUDGET_DETAILS_ID
						FROM AWARD_BUDGET_DETAIL;
						/*SET LI_TOTAL_COST = 0;
						SET LI_LINE_ITEM_NUMBER = LI_LINE_ITEM_NUMBER + 1;
						SET LI_TOTAL_COST =	LI_TOTAL_COST + IFNULL(CAST(LS_CASH AS DECIMAL(13,2)),0);
						*/
						SET LI_LINE_ITEM_NUMBER = LI_LINE_ITEM_NUMBER + 1;
						INSERT INTO AWARD_BUDGET_DETAIL
						(
						BUDGET_DETAILS_ID,
						BUDGET_HEADER_ID,
						BUDGET_PERIOD_ID,
						VERSION_NUMBER,
						BUDGET_PERIOD,
						LINE_ITEM_NUMBER,
						START_DATE,
						END_DATE,
						BUDGET_CATEGORY_CODE,
						COST_ELEMENT,
						LINE_ITEM_DESCRIPTION,
						LINE_ITEM_COST,
						PREVIOUS_LINE_ITEM_COST,
						IS_SYSTEM_GENRTED_COST_ELEMENT,
						ON_OFF_CAMPUS_FLAG,
						SYSTEM_GEN_COST_ELEMENT_TYPE,
						IS_APPLY_INFLATION_RATE,
						COST_SHARING_AMOUNT,
						COST_SHARING_PERCENT,
						UPDATE_TIMESTAMP,
						UPDATE_USER,
						AWARD_NUMBER,
						QUANTITY,
						INTERNAL_ORDER_CODE
						)
						VALUES
						(
						LI_BUDGET_DETAILS_ID,
						LI_BUDGET_HEADER_ID,
						LI_BUDGET_PERIOD_ID,
						1,
						1,
						LI_LINE_ITEM_NUMBER,
						LS_PROJECT_START_DATE,
						LS_PROJECT_END_DATE,
						600,
						28,
						NULL,
						IFNULL(CAST(LS_CASH AS DECIMAL(13,2)),0),
						NULL,
						'Y',
						'N',
						'BUDGET_OH_ON',
						'Y',
						0,
						NULL,
						NOW(),
						'quickstart',
						LS_AWARD_NUMBER,
						NULL,
						NULL
						);
			END IF;
			IF LS_CONTRIBUTIONS IS NOT NULL THEN
				SELECT IFNULL(MAX(AWARD_COST_SHARE_ID),0)+1 INTO  LI_AWARD_COST_SHARE_ID FROM AWARD_COST_SHARE;
				INSERT INTO AWARD_COST_SHARE
				(
				AWARD_COST_SHARE_ID,
				AWARD_ID,
				AWARD_NUMBER,
				SEQUENCE_NUMBER,
				PROJECT_PERIOD,
				COST_SHARE_PERCENTAGE,
				COST_SHARE_TYPE_CODE,
				SOURCE,
				COMMENTS,
				DESTINATION,
				COMMITMENT_AMOUNT,
				VERIFICATION_DATE,
				COST_SHARE_MET,
				UNIT_NUMBER,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				COST_SHARE_DISTRIBUTABLE
				)
				VALUES
				(
				LI_AWARD_COST_SHARE_ID,
				LI_AWARD_ID,
				LS_AWARD_NUMBER,
				1,
			    year(LS_PROJECT_START_DATE),
				NULL,
				1,
				NULL,
				NULL,
				NULL,
				IFNULL(CAST(LS_CONTRIBUTIONS AS DECIMAL(13,2)),0),
				NULL,
				0,
				NULL,
				NOW(),
				'quickstart',
				0
				);
			END IF;
			SET LI_TOTAL_DIRECT_COST = 0;
			BEGIN
				DECLARE DONE2 INT DEFAULT FALSE;
				DECLARE AWARD_BUDGET_DTL_CURSOR CURSOR FOR
				SELECT
				BUDGET_CATEGORY,
				BUDGET_LINE_ITEM,
				QUANTITY,
				trim(IO_CODE),
				ORIGINAL_APPROVED_BUDGET,
				CURRENT_APPROVED_BUDGET,
				EXPENDITURE_TO_DATE,
				AMOUNT_REMAIN_BAL,
				UTILIZATION_RATE
				FROM MIGRATION_EXT_AWARD_BUDGET
				WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID));
				DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE2 = TRUE;
				OPEN AWARD_BUDGET_DTL_CURSOR;
				INSERT_LOOP2: LOOP
				FETCH AWARD_BUDGET_DTL_CURSOR INTO
				LS_BUDGET_CATEGORY,
				LS_BUDGET_LINE_ITEM,
				LS_QUANTITY,
				LS_IO_CODE,
				LS_ORIGINAL_APPROVED_BUDGET,
				LS_CURRENT_APPROVED_BUDGET,
				LS_EXPENDITURE_TO_DATE,
				LS_AMOUNT_REMAIN_BAL,
				LS_UTILIZATION_RATE;
				IF DONE2 THEN
					LEAVE INSERT_LOOP2;
				END IF;
				SELECT COUNT(1) INTO LI_FLAG FROM BUDGET_CATEGORY
				WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_BUDGET_CATEGORY));
				IF LI_FLAG > 0 THEN
					SELECT BUDGET_CATEGORY_CODE INTO LS_BUDGET_CATEGORY_CODE FROM BUDGET_CATEGORY
					WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_BUDGET_CATEGORY));
					SELECT COUNT(1) INTO LI_FLAG FROM migration_cost_element_mapping
					WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_BUDGET_LINE_ITEM))
					AND BUDGET_CATEGORY_CODE = LS_BUDGET_CATEGORY_CODE;
					IF LI_FLAG > 0 THEN
						SELECT COST_ELEMENT INTO LS_COST_ELEMENT FROM migration_cost_element_mapping
						WHERE TRIM(UPPER(DESCRIPTION)) = TRIM(UPPER(LS_BUDGET_LINE_ITEM))
						AND BUDGET_CATEGORY_CODE = LS_BUDGET_CATEGORY_CODE;
						SELECT IFNULL(MAX(BUDGET_DETAILS_ID),0)+1 INTO LI_BUDGET_DETAILS_ID
						FROM AWARD_BUDGET_DETAIL;
						SET LI_LINE_ITEM_NUMBER = LI_LINE_ITEM_NUMBER + 1;
						/*SET LI_TOTAL_COST =	IFNULL(LI_TOTAL_COST,0) + IFNULL(CAST(LS_CURRENT_APPROVED_BUDGET AS DECIMAL(13,2)),0);
						SET LI_TOTAL_DIRECT_COST = IFNULL(LI_TOTAL_DIRECT_COST,0) + IFNULL(CAST(LS_CURRENT_APPROVED_BUDGET AS DECIMAL(13,2)),0);
						*/
						INSERT INTO AWARD_BUDGET_DETAIL
						(
						BUDGET_DETAILS_ID,
						BUDGET_HEADER_ID,
						BUDGET_PERIOD_ID,
						VERSION_NUMBER,
						BUDGET_PERIOD,
						LINE_ITEM_NUMBER,
						START_DATE,
						END_DATE,
						BUDGET_CATEGORY_CODE,
						COST_ELEMENT,
						LINE_ITEM_DESCRIPTION,
						LINE_ITEM_COST,
						PREVIOUS_LINE_ITEM_COST,
						IS_SYSTEM_GENRTED_COST_ELEMENT,
						ON_OFF_CAMPUS_FLAG,
						SYSTEM_GEN_COST_ELEMENT_TYPE,
						IS_APPLY_INFLATION_RATE,
						COST_SHARING_AMOUNT,
						COST_SHARING_PERCENT,
						UPDATE_TIMESTAMP,
						UPDATE_USER,
						AWARD_NUMBER,
						QUANTITY,
						INTERNAL_ORDER_CODE
						)
						VALUES
						(
						LI_BUDGET_DETAILS_ID,
						LI_BUDGET_HEADER_ID,
						LI_BUDGET_PERIOD_ID,
						1,
						1,
						LI_LINE_ITEM_NUMBER,
						LS_PROJECT_START_DATE,
						LS_PROJECT_END_DATE,
						LS_BUDGET_CATEGORY_CODE,
						LS_COST_ELEMENT,
						NULL,
						IFNULL(CAST(LS_CURRENT_APPROVED_BUDGET AS DECIMAL(13,2)),0),
						IFNULL(CAST(LS_ORIGINAL_APPROVED_BUDGET AS DECIMAL(13,2)),0),
						'N',
						'N',
						NULL,
						'Y',
						0,
						NULL,
						NOW(),
						'quickstart',
						LS_AWARD_NUMBER,
						LS_QUANTITY,
						LS_IO_CODE
						);
					ELSE
						SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
						INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE,
														VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
						VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT_BUDGET','COST ELEMENT DOES NOT EXISTS',concat(LS_BUDGET_LINE_ITEM,',category:',LS_BUDGET_CATEGORY_CODE),'CREATION',NOW(),'quickstart');
						COMMIT;
					END IF;
				END IF;
				/*UPDATE AWARD_BUDGET_HEADER
				SET TOTAL_COST = LI_TOTAL_COST,
				TOTAL_DIRECT_COST = LI_TOTAL_DIRECT_COST
				WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID;
				UPDATE AWARD_BUDGET_PERIOD
				SET
				TOTAL_COST = LI_TOTAL_COST,
				TOTAL_DIRECT_COST = LI_TOTAL_DIRECT_COST
				WHERE BUDGET_PERIOD_ID = LI_BUDGET_PERIOD_ID;
				*/
				SET LS_BUDGET_CATEGORY = NULL;
				SET LS_BUDGET_CATEGORY_CODE = NULL;
				SET LS_BUDGET_LINE_ITEM = NULL;
				SET LS_CURRENT_APPROVED_BUDGET = NULL;
				SET LS_QUANTITY = NULL;
				SET LS_COST_ELEMENT = NULL;
				END LOOP;
				CLOSE AWARD_BUDGET_DTL_CURSOR;
			END;
			SELECT SUM(LINE_ITEM_COST) INTO LI_DIRECT_COST  FROM AWARD_BUDGET_DETAIL
			WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID
			AND BUDGET_CATEGORY_CODE <> 600;
				SET SQL_SAFE_UPDATES = 0;
				UPDATE AWARD_BUDGET_HEADER
				SET TOTAL_DIRECT_COST = LI_DIRECT_COST
				WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID;
				UPDATE AWARD_BUDGET_PERIOD
				SET TOTAL_DIRECT_COST = LI_DIRECT_COST
				WHERE BUDGET_PERIOD_ID = LI_BUDGET_PERIOD_ID;
				COMMIT;
				UPDATE AWARD_BUDGET_HEADER
				SET TOTAL_COST = TOTAL_DIRECT_COST + TOTAL_INDIRECT_COST
				WHERE BUDGET_HEADER_ID = LI_BUDGET_HEADER_ID;
				UPDATE AWARD_BUDGET_PERIOD
				SET TOTAL_COST = TOTAL_DIRECT_COST + TOTAL_INDIRECT_COST
				WHERE BUDGET_PERIOD_ID = LI_BUDGET_PERIOD_ID;
			SET LI_AWARD_ID = NULL;
			SET LS_AWARD_NUMBER = NULL;
			SET LS_PROJECT_START_DATE = NULL;
			SET LS_PROJECT_END_DATE = NULL;
			SET LS_CASH = NULL;
			SET LS_CONTRIBUTIONS = NULL;
			SET LS_TOTAL_CASH = NULL;
			SET LS_PROJECT_ID = NULL;
			SET LS_FUND_CENTRE = NULL;
			SET LS_FUND_CODE = NULL;
			END LOOP;
			CLOSE CUR_SEL_DATA;
			SET SQL_SAFE_UPDATES = 0;
			UPDATE AWARD_BUDGET_PERIOD_ID_GENERATOR SET NEXT_VAL = (SELECT IFNULL(MAX(BUDGET_PERIOD_ID),0)+1 FROM AWARD_BUDGET_PERIOD);
