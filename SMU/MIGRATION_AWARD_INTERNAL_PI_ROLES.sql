DELIMITER $$
CREATE  PROCEDURE `MIGRATION_AWARD_INTERNAL_PI_ROLES`(av_id int)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_ERROR_MSG 		VARCHAR(1000);
DECLARE LS_PERSON_ID 		VARCHAR(40);
DECLARE LS_CURRENT_PERSON_ID 		VARCHAR(40);
DECLARE LI_AWARD_ID			DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER		VARCHAR(12);
DECLARE LI_AWARD_PERSON_ROLE_ID	INT(12);
declare LI_ROLES_EXIST int;
declare LI_SKIP int;
declare LI_SEQ_NUMBER int (11);
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
			SELECT
			IFNULL(MAX(MIGRATION_ERROR_LOG_ID), 0) + 1
			INTO LI_SEQ_ERROR_LOG_ID FROM
			MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_AWARD_NUMBER,'EXCEPTION','PROJECT_ROLES',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
		PERSON_ID,
		AWARD_NUMBER
		FROM AWARD_PERSONS WHERE AWARD_ID IN (SELECT AWARD_ID FROM MIGRATION_AWARD_INTERNAL WHERE AWARD_ID IS NOT NULL)
		AND PERSON_ROLE_ID = 3
		AND PERSON_ID IS NOT NULL;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_PERSON_ID,
		LS_AWARD_NUMBER;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
					BEGIN
					DECLARE DONE1 INT DEFAULT FALSE;
					DECLARE CUR_AWARD_ID CURSOR FOR
						SELECT  DISTINCT AWARD_ID, PERSON_ID, SEQUENCE_NUMBER
						FROM AWARD_PERSONS
						WHERE AWARD_NUMBER = LS_AWARD_NUMBER
						AND PI_FLAG = 'Y'
						AND	PERSON_ROLE_ID = 3
						AND PERSON_ID IS NOT NULL;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
					OPEN CUR_AWARD_ID;
					IN_LOOP: LOOP
					FETCH CUR_AWARD_ID INTO
										LI_AWARD_ID,
										LS_CURRENT_PERSON_ID,
										LI_SEQ_NUMBER;
					IF DONE1 THEN
					LEAVE IN_LOOP;
					END IF;
											SELECT COUNT(*) INTO LI_ROLES_EXIST
											FROM AWARD_PERSON_ROLES
											WHERE AWARD_ID = LI_AWARD_ID
											AND PERSON_ID = LS_PERSON_ID
											AND ROLE_ID IN (14); -- Create Variation Request
														IF LI_ROLES_EXIST < 1 THEN
														SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
														INSERT INTO AWARD_PERSON_ROLES
														(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
														VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQ_NUMBER, LS_PERSON_ID,14,NOW(),'quickstart');
														COMMIT;
														end if;
											SELECT  COUNT(*) INTO LI_ROLES_EXIST
											FROM AWARD_PERSON_ROLES
											WHERE AWARD_ID = LI_AWARD_ID
											AND PERSON_ID = LS_PERSON_ID
											AND ROLE_ID IN (45); -- Create Projetc Closure
														IF LI_ROLES_EXIST < 1 THEN
														SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
														INSERT INTO AWARD_PERSON_ROLES
														(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
														VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQ_NUMBER, LS_PERSON_ID,45,NOW(),'quickstart');
														COMMIT;
														end if;
											SELECT COUNT(*)INTO LI_ROLES_EXIST FROM
											AWARD_PERSON_ROLES WHERE AWARD_ID = LI_AWARD_ID
											AND PERSON_ID = LS_PERSON_ID
											AND ROLE_ID IN (47); -- Modify Project Outcome
														IF LI_ROLES_EXIST < 1 THEN
														SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
														INSERT INTO AWARD_PERSON_ROLES
														(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
														VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQ_NUMBER, LS_PERSON_ID,47,NOW(),'quickstart');
														COMMIT;
														end if;
											SELECT COUNT(*)INTO LI_ROLES_EXIST FROM AWARD_PERSON_ROLES
											WHERE AWARD_ID = LI_AWARD_ID
											AND PERSON_ID = LS_PERSON_ID
											AND ROLE_ID IN (48); -- Withdraw Request
														IF LI_ROLES_EXIST < 1 THEN
														SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
														INSERT INTO AWARD_PERSON_ROLES
														(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
														VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQ_NUMBER, LS_PERSON_ID,48,NOW(),'quickstart');
														COMMIT;
														end if;
									IF (LS_PERSON_ID = LS_CURRENT_PERSON_ID) THEN
											SELECT COUNT(*) INTO LI_ROLES_EXIST FROM AWARD_PERSON_ROLES
											WHERE AWARD_ID = LI_AWARD_ID
											AND PERSON_ID = LS_PERSON_ID
											AND ROLE_ID IN (653); -- Principle Investigator
														IF LI_ROLES_EXIST < 1 THEN
														SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
														INSERT INTO AWARD_PERSON_ROLES
														(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
														VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQ_NUMBER, LS_PERSON_ID,653,NOW(),'quickstart');
														COMMIT;
														END IF;
									ELSE
											SELECT COUNT(*) INTO LI_ROLES_EXIST FROM AWARD_PERSON_ROLES
											WHERE AWARD_ID = LI_AWARD_ID
											AND PERSON_ID = LS_CURRENT_PERSON_ID
											AND ROLE_ID IN (653); -- Principle Investigator
														IF LI_ROLES_EXIST < 1 THEN
														SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID),0)+1 INTO LI_AWARD_PERSON_ROLE_ID FROM AWARD_PERSON_ROLES;
														INSERT INTO AWARD_PERSON_ROLES
														(AWARD_PERSON_ROLE_ID,AWARD_ID,AWARD_NUMBER,SEQUENCE_NUMBER,PERSON_ID,ROLE_ID,UPDATE_TIMESTAMP,UPDATE_USER)
														VALUES(LI_AWARD_PERSON_ROLE_ID,LI_AWARD_ID,LS_AWARD_NUMBER,LI_SEQ_NUMBER, LS_CURRENT_PERSON_ID,653,NOW(),'quickstart');
														COMMIT;
														END IF;
								    END IF;
						set sql_safe_updates = 0;
						UPDATE AWARD_PERSON_ROLE_ID_GENERATOR SET NEXT_VAL = (SELECT IFNULL(MAX(AWARD_PERSON_ROLE_ID), 0) + 1 FROM AWARD_PERSON_ROLES);
						COMMIT;
						set sql_safe_updates = 1;
				end loop;
				CLOSE CUR_AWARD_ID;
				end;
		END LOOP;
		CLOSE CUR_SEL_DATA;
		end;
	end
$$
DELIMITER ;
