DELIMITER $$
CREATE  FUNCTION `FN_CHCK_OBLIGATD_AND_TOTAL_AMT`(AV_AWARD_ID VARCHAR(22)) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LI_COUNT INT;
DECLARE LS_TOTAL_COST decimal(13,2);
DECLARE LS_OBLI_DISTRIBUTABLE_AMOUNT decimal(13,2);
SELECT COUNT(*) INTO LI_COUNT
FROM AWARD
WHERE AWARD_ID = AV_AWARD_ID
AND AWARD_VARIATION_TYPE_CODE IN(4,9,10,12);
IF LI_COUNT = 0 THEN
	RETURN 'TRUE';
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM AWARD_BUDGET_HEADER
WHERE AWARD_ID = AV_AWARD_ID
AND VERSION_NUMBER = ( select max(VERSION_NUMBER) FROM AWARD_BUDGET_HEADER
						WHERE AWARD_ID = AV_AWARD_ID);
IF LI_COUNT = 1 THEN
	SELECT TOTAL_COST INTO  LS_TOTAL_COST
	FROM AWARD_BUDGET_HEADER
	WHERE AWARD_ID = AV_AWARD_ID
	AND VERSION_NUMBER = ( select max(VERSION_NUMBER) FROM AWARD_BUDGET_HEADER
						WHERE AWARD_ID = AV_AWARD_ID);
ELSE
	RETURN 'TRUE';
END IF;
SELECT COUNT(*) INTO LI_COUNT
FROM AWARD_AMOUNT_INFO
WHERE AWARD_ID = AV_AWARD_ID
AND AWARD_AMOUNT_INFO_ID = (SELECT  MAX(AWARD_AMOUNT_INFO_ID)
							FROM AWARD_AMOUNT_INFO
                            WHERE AWARD_ID = AV_AWARD_ID);
IF LI_COUNT = 1 THEN
	SELECT OBLI_DISTRIBUTABLE_AMOUNT INTO LS_OBLI_DISTRIBUTABLE_AMOUNT
	FROM AWARD_AMOUNT_INFO
	WHERE AWARD_ID = AV_AWARD_ID
	AND AWARD_AMOUNT_INFO_ID = (SELECT  MAX(AWARD_AMOUNT_INFO_ID)
								FROM AWARD_AMOUNT_INFO
								WHERE AWARD_ID = AV_AWARD_ID);
ELSE
	RETURN 'TRUE';
END IF;
IF (LS_OBLI_DISTRIBUTABLE_AMOUNT = LS_TOTAL_COST) THEN
	RETURN 'TRUE';
ELSE
	RETURN 'FALSE';
END IF;
END
$$
DELIMITER ;
