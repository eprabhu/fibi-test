DELIMITER $$
CREATE  FUNCTION `FN_FUNDCODE_FUNDCENTER_MODIFIED`(
AV_AWARD_ID INT
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
DECLARE LS_PREVIOUS_FUND_CODE 		varchar(100);
DECLARE LS_NEW_FUND_CODE 			varchar(100);
DECLARE LS_PREVIOUS_FUND_CENTER 	varchar(255);
DECLARE LS_NEW_FUND_CENTER 			varchar(255);
DECLARE LI_FLAG 					INT;
DECLARE LS_SEQUENCE_NUMBER INT;
	SELECT COUNT(1) INTO LI_FLAG FROM AWARD T1
	WHERE T1.AWARD_ID = AV_AWARD_ID
	AND AWARD_VARIATION_TYPE_CODE in (4, 9, 10, 11, 12)
	AND T1.AWARD_DOCUMENT_TYPE_CODE = 3;
	IF LI_FLAG > 0 THEN
		SELECT SEQUENCE_NUMBER INTO LS_SEQUENCE_NUMBER
		FROM AWARD where AWARD_ID = AV_AWARD_ID;
		SELECT ACCOUNT_NUMBER, FUND_CENTER INTO LS_NEW_FUND_CODE, LS_NEW_FUND_CENTER
        FROM AWARD T2 where T2.AWARD_ID = AV_AWARD_ID;
		SELECT ACCOUNT_NUMBER, FUND_CENTER
        INTO LS_PREVIOUS_FUND_CODE, LS_PREVIOUS_FUND_CENTER
        FROM AWARD T3 where T3.SEQUENCE_NUMBER = LS_SEQUENCE_NUMBER - 1
        and T3.AWARD_NUMBER = (SELECT AWARD_NUMBER
								FROM AWARD T4
								where T4.AWARD_ID = AV_AWARD_ID);
        IF IFNULL (LS_PREVIOUS_FUND_CODE, 0) <> IFNULL (LS_NEW_FUND_CODE, 0)
			OR
			IFNULL (LS_PREVIOUS_FUND_CENTER, 0) <> IFNULL (LS_NEW_FUND_CENTER, 0)
		THEN
			RETURN 'FALSE';
		ELSE
			RETURN 'TRUE';
		END IF;
	END IF;
RETURN 'TRUE';
END
$$
DELIMITER ;
