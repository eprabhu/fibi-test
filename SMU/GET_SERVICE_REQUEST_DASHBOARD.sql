CREATE  PROCEDURE `GET_SERVICE_REQUEST_DASHBOARD`(
AV_MODULE_ITEM_KEY     		VARCHAR(22),
AV_MODULE_CODE	            VARCHAR(3),
AV_SR_HEADER_ID	            VARCHAR(6),
AV_REQUEST_SUBJECT	        VARCHAR(1000),
AV_REQUEST_TYPE   	        VARCHAR(200),
AV_REQUEST_STATUS           VARCHAR(200),
AV_RESEARCH_PERSON_ID       VARCHAR(40),
AV_LEAD_UNIT_NUMBER   	    varchar(8),
AV_TITLE                    VARCHAR(200),
AV_PERSON_ID 			    VARCHAR(200),
AV_SORT_TYPE 			    VARCHAR(500),
AV_PAGED  				    INT(10),
AV_LIMIT				    INT(10),
AV_TAB_TYPE 				VARCHAR(30),
AV_UNLIMITED                BOOLEAN,
AV_TYPE                     VARCHAR(1),
AV_ROLE_ID						 VARCHAR(20)
)
BEGIN
DECLARE LS_DYN_SQL LONGTEXT;
DECLARE LS_FILTER_CONDITION LONGTEXT;
DECLARE LS_OFFSET_CONDITION VARCHAR(600);
DECLARE LS_OFFSET INT(11);
DECLARE TAB_QUERY LONGTEXT;
DECLARE JOIN_CONDITION LONGTEXT;
DECLARE SELECTED_FIELD_LIST LONGTEXT;
SET LS_OFFSET = (AV_LIMIT * AV_PAGED);
SET LS_FILTER_CONDITION ='';
SET LS_DYN_SQL ='';
SET JOIN_CONDITION = '';
SET SELECTED_FIELD_LIST= '';
IF AV_TYPE = 'A'   THEN
			IF AV_MODULE_ITEM_KEY IS NOT NULL AND AV_MODULE_ITEM_KEY <> '' THEN
			IF AV_MODULE_CODE = 1 THEN
				SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.MODULE_ITEM_KEY IN (SELECT AWARD_ID FROM AWARD
										WHERE AWARD_NUMBER IN (	SELECT AWARD_NUMBER FROM AWARD
																WHERE AWARD_ID =',AV_MODULE_ITEM_KEY,'))AND  T.MODULE_CODE = ''',AV_MODULE_CODE,''' AND ');
			ELSE
				SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.MODULE_ITEM_KEY LIKE ''%',AV_MODULE_ITEM_KEY,'%'' AND  T.MODULE_CODE = ''',AV_MODULE_CODE,''' AND ');
			END IF;
			END IF;
			IF AV_SR_HEADER_ID IS NOT NULL AND AV_SR_HEADER_ID <> '' THEN
			  SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.SR_HEADER_ID LIKE ''%',AV_SR_HEADER_ID,'%'' AND ');
			END IF;
			IF AV_REQUEST_SUBJECT IS NOT NULL  AND AV_REQUEST_SUBJECT <> '' THEN
				SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.SUBJECT LIKE ''%',AV_REQUEST_SUBJECT,'%'' AND ');
			END IF;
			IF AV_REQUEST_TYPE IS NOT NULL  AND AV_REQUEST_TYPE <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.TYPE_CODE IN (',AV_REQUEST_TYPE,') AND ');
            END IF;
			/*IF AV_PI_PERSON_ID IS NOT NULL  AND AV_PI_PERSON_ID <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.PI_PERSON_ID = ''',AV_PI_PERSON_ID,''' AND ');
			END IF;*/
            IF AV_MODULE_CODE = 1 THEN
					-- ---SATRTS MODIFICATION ON 29-07-2020-----------------
					IF (AV_ROLE_ID IS NOT NULL AND AV_ROLE_ID <> '') and (AV_RESEARCH_PERSON_ID IS NOT NULL AND AV_RESEARCH_PERSON_ID <> '') THEN
							-- SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,'T.PERSON_ROLE_ID IN (',AV_ROLE_ID,') AND ');
							SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.MODULE_ITEM_KEY IN (SELECT AWARD_ID
																								 FROM AWARD_PERSONS WHERE PERSON_ROLE_ID IN(
																						',AV_ROLE_ID,') AND PERSON_ID =''',AV_RESEARCH_PERSON_ID,''' ) AND ');
					END IF;
					IF (AV_ROLE_ID IS NOT NULL AND AV_ROLE_ID <> '') and (AV_RESEARCH_PERSON_ID IS NULL OR AV_RESEARCH_PERSON_ID = '') THEN
						SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.MODULE_ITEM_KEY IN (SELECT AWARD_ID
																								 FROM AWARD_PERSONS WHERE PERSON_ROLE_ID IN(
																						',AV_ROLE_ID,')) AND ');
					END IF;
					IF (AV_ROLE_ID is null OR AV_ROLE_ID = '') AND (AV_RESEARCH_PERSON_ID IS NOT NULL AND AV_RESEARCH_PERSON_ID <> '') THEN
						SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.MODULE_ITEM_KEY IN(SELECT AWARD_ID FROM AWARD_PERSONS
																							WHERE PERSON_ID =''',AV_RESEARCH_PERSON_ID,''' ) AND ' );
					END IF;
					-- --------ENDS MODIFICATION ON 29-07-2020--------------------
			END IF;
			IF AV_LEAD_UNIT_NUMBER IS NOT NULL  AND AV_LEAD_UNIT_NUMBER <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.LEAD_UNIT_NUMBER LIKE ''%',AV_LEAD_UNIT_NUMBER,'%'' AND ');
			END IF;
			IF AV_TITLE IS NOT NULL  AND AV_TITLE <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.TITLE LIKE ''%',AV_TITLE,'%'' AND ');
			END IF;
			IF AV_REQUEST_STATUS IS NOT NULL  AND AV_REQUEST_STATUS <> '' THEN
			 SET LS_FILTER_CONDITION = CONCAT(LS_FILTER_CONDITION,' T.STATUS_CODE IN (',AV_REQUEST_STATUS,')  AND ');
			END IF;
END IF;
IF 	AV_TAB_TYPE = 'ALL_REQUEST'	THEN
						 IF (SELECT COUNT(*)  FROM PERSON_ROLES WHERE PERSON_ID = AV_PERSON_ID AND ROLE_ID = 100) THEN
							SET TAB_QUERY = '';
						 ELSEIF (SELECT COUNT(*)  FROM PERSON_ROLES WHERE PERSON_ID = AV_PERSON_ID AND ROLE_ID IN(120,400)) THEN
							 SET TAB_QUERY = CONCAT(' WHERE ( T2.LEAD_UNIT_NUMBER IN(SELECT DISTINCT UNIT_NUMBER FROM PERSON_ROLES WHERE PERSON_ID = ''',AV_PERSON_ID,''' AND ROLE_ID IN(120,400) )  )');
						ELSE
							  SET TAB_QUERY = CONCAT(' WHERE (( T1.MODULE_ITEM_KEY IN(SELECT AWARD_ID FROM AWARD_PERSONS WHERE PERSON_ID=''',AV_PERSON_ID,''' AND PERSON_ROLE_ID IN (1,3,6) ) AND T1.MODULE_CODE = 1 )
																) ');
						END IF;
END IF;
IF AV_TAB_TYPE = 'MY_REQUEST' THEN
			SET TAB_QUERY = CONCAT(' WHERE ( T1.CREATE_USER = (SELECT USER_NAME FROM PERSON WHERE PERSON_ID = ''',AV_PERSON_ID,''')
											AND T1.STATUS_CODE NOT IN (4,8)
                                            OR ( T1.ASSIGNEE_PERSON_ID = ''',AV_PERSON_ID,''' )
											OR ( T1.MODULE_ITEM_KEY IN(SELECT AWARD_ID FROM AWARD_PERSONS WHERE PERSON_ID=''',AV_PERSON_ID,''' AND PERSON_ROLE_ID IN (1,3,6) ) AND T1.MODULE_CODE = 1 )
										      )' );
END IF;
IF AV_SORT_TYPE IS NULL or AV_SORT_TYPE ='' THEN
	SET AV_SORT_TYPE =  CONCAT(' ORDER BY T.UPDATE_TIMESTAMP DESC ');
ELSE
    SET AV_SORT_TYPE = CONCAT(' ORDER BY ',AV_SORT_TYPE);
END IF;
IF AV_UNLIMITED = TRUE THEN
	SET LS_OFFSET_CONDITION = '';
ELSE
	SET LS_OFFSET_CONDITION = CONCAT(' LIMIT ',AV_LIMIT,' OFFSET ',LS_OFFSET);
END IF;
IF LS_FILTER_CONDITION <>'' THEN
SET LS_FILTER_CONDITION = CONCAT(' WHERE  ',LS_FILTER_CONDITION);
SELECT TRIM(TRAILING 'AND ' FROM LS_FILTER_CONDITION) into LS_FILTER_CONDITION from dual;
END IF;
			SET LS_DYN_SQL =CONCAT('SELECT DISTINCT *  FROM(SELECT T1.SR_HEADER_ID,
																	T1.MODULE_ITEM_KEY,
                                                                    T1.MODULE_CODE,
																	T2.AWARD_NUMBER AS PROJECT_ID,
																	T2.TITLE AS TITLE,
																	T5.FULL_NAME AS PI_FULL_NAME,
                                                                    IFNULL(T5.PERSON_ID,T5.ROLODEX_ID) AS PI_PERSON_ID,
																	T8.DESCRIPTION AS REQUEST_TYPE,
																	T1.TYPE_CODE,
																	T1.STATUS_CODE,
																	T1.SUBJECT,
																	T2.LEAD_UNIT_NUMBER AS LEAD_UNIT_NUMBER,
                                                                    T10.UNIT_NAME,
																	T9.DESCRIPTION AS REQUEST_STATUS,
																	T1.UPDATE_TIMESTAMP
															FROM SR_HEADER T1
															INNER JOIN AWARD T2 ON T1.MODULE_ITEM_KEY = T2.AWARD_ID AND T1.MODULE_CODE = 1
															INNER JOIN AWARD_PERSONS T5 ON T5.AWARD_ID = T2.AWARD_ID AND T5.PERSON_ROLE_ID = 3
															INNER JOIN SR_TYPE T8 ON T8.TYPE_CODE = T1.TYPE_CODE
															INNER JOIN SR_STATUS T9 ON T9.STATUS_CODE = T1.STATUS_CODE
															INNER JOIN UNIT T10 ON T10.UNIT_NUMBER = T2.LEAD_UNIT_NUMBER  ',JOIN_CONDITION,TAB_QUERY,
									' GROUP BY T1.SR_HEADER_ID)T ',LS_FILTER_CONDITION,' ',AV_SORT_TYPE,' ',LS_OFFSET_CONDITION );
SET @QUERY_STATEMENT = LS_DYN_SQL;
PREPARE EXECUTABLE_STAEMENT FROM @QUERY_STATEMENT;
EXECUTE EXECUTABLE_STAEMENT;
 -- SELECT LS_DYN_SQL;
END
$$
