CREATE  FUNCTION `FN_CHK_AWARD_EXTENSION_ENDDATE`(
AV_AWARD_ID    varchar(12)
) RETURNS varchar(10) CHARSET utf8mb4
    DETERMINISTIC
BEGIN
	DECLARE LS_TOTAL_MONTHS VARCHAR(10);
	DECLARE LS_FINAL_EXPIRATION_DATE DATETIME;
    DECLARE LI_FLAG INT;
	DECLARE LS_AWARD_NUMBER VARCHAR(12);
	DECLARE LI_AWARD_ID DECIMAL(22,0);
	DECLARE LI_DAYS INT;
	DECLARE LS_VARIATION_END_DATE DATETIME;
	SELECT COUNT(1) INTO LI_FLAG FROM AWARD
	WHERE  award_id = AV_AWARD_ID and AWARD_VARIATION_TYPE_CODE = 1
    AND WORKFLOW_AWARD_STATUS_CODE IN (1,4);
	IF LI_FLAG > 0 THEN
		SELECT AWARD_NUMBER, FINAL_EXPIRATION_DATE
		INTO LS_AWARD_NUMBER, LS_VARIATION_END_DATE
		FROM AWARD
		WHERE AWARD_ID = AV_AWARD_ID;
		SELECT AWARD_ID INTO LI_AWARD_ID FROM AWARD
		WHERE AWARD_NUMBER = LS_AWARD_NUMBER
		AND AWARD_SEQUENCE_STATUS='ACTIVE';
		SELECT 	FINAL_EXPIRATION_DATE
		INTO LS_FINAL_EXPIRATION_DATE
		FROM AWARD
		WHERE AWARD_ID = LI_AWARD_ID;
	SELECT TIMESTAMPDIFF(DAY,DATE(NOW()),DATE(LS_FINAL_EXPIRATION_DATE)) INTO LI_DAYS FROM DUAL;
		IF LI_DAYS <  14 THEN -- Blocks submitting a variation request to extend the project at least 2 weeks before the current end date
			RETURN 'TRUE';
		END IF;
	/*
    SELECT 	SUBSTR(((DATEDIFF(FINAL_EXPIRATION_DATE,NOW())+1)/30),1,INSTR(((DATEDIFF(FINAL_EXPIRATION_DATE,NOW())+1)/30),'.')-1)
	INTO LS_TOTAL_MONTHS
	FROM AWARD
	WHERE AWARD_ID = LI_AWARD_ID;
		IF LS_TOTAL_MONTHS < 6 THEN
			RETURN 'TRUE';
		END IF;
	*/
	SELECT TIMESTAMPDIFF(DAY,DATE(LS_FINAL_EXPIRATION_DATE), DATE(LS_VARIATION_END_DATE)) INTO LI_DAYS FROM DUAL;
		IF  LI_DAYS  < 0 THEN -- blocks when variation_end_date < current_end_date
			RETURN 'TRUE';
		ELSE
			RETURN 'FALSE';
		END IF;
 ELSE
  RETURN 'FALSE';
	END IF;
END
$$
