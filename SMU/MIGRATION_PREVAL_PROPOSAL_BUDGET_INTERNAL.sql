DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PREVAL_PROPOSAL_BUDGET_INTERNAL`(
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID 			INT;
DECLARE LS_ERROR_MSG 					VARCHAR(1000);
DECLARE LS_APPLICATION_ID 				VARCHAR(50);
DECLARE LS_PROPOSED_BUDGET_TOTAL		VARCHAR(50);
DECLARE LS_PROPOSED_BUDGET_EOM 			VARCHAR(50);
DECLARE LS_PROPOSED_BUDGET_EQPT			VARCHAR(50);
DECLARE LS_PROPOSED_BUDGET_OOE			VARCHAR(50);
DECLARE LS_INDIRECT_COST				VARCHAR(50);
DECLARE LS_OVERSEAS_TRAVEL				VARCHAR(50);
DECLARE LS_RESEARCH_SCHOLARSHIP 		VARCHAR(50);
DECLARE LS_THIRD_STREAM_FUNDING 		VARCHAR(50);
DECLARE LS_DELIVERABLES 				VARCHAR(50);
DECLARE LS_TOTAL_LINE_ITEM_COST			DECIMAL(13,2);
DECLARE LI_FLAG 						INT;
BEGIN
		DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'EXCEPTION','PROPOSAL_BUDGET',LS_ERROR_MSG,'PRE_VALIDATION',NOW(),'quickstart');
			COMMIT;
		END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			APPLICATION_ID,
			PROPOSED_BUDGET_TOTAL,
			PROPOSED_BUDGET_EOM,
			PROPOSED_BUDGET_EQPT,
			PROPOSED_BUDGET_OOE,
			INDIRECT_COST
		FROM MIGRATION_PROPOSAL_BUDGET_INTERNAL_00_17;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_APPLICATION_ID,
		LS_PROPOSED_BUDGET_TOTAL,
		LS_PROPOSED_BUDGET_EOM,
		LS_PROPOSED_BUDGET_EQPT,
		LS_PROPOSED_BUDGET_OOE,
		LS_INDIRECT_COST;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
			SELECT COUNT(1) INTO LI_FLAG
			FROM MIGRATION_PROPOSAL_INTERNAL_00_17
			WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_APPLICATION_ID));
			IF LI_FLAG = 0 THEN
			select 1;
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_BUDGET, UPDATE_TIMESTAMP, UPDATE_USER)
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_BUDGET','APPLICATION ID DOES NOT EXISTS IN PROPOSAL FILE',LS_APPLICATION_ID,'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
			iterate INSERT_LOOP;
			END IF;
			SET LS_TOTAL_LINE_ITEM_COST = IFNULL(CAST(LS_PROPOSED_BUDGET_EOM AS DECIMAL(13,2)),0) + IFNULL(CAST(LS_PROPOSED_BUDGET_EQPT AS DECIMAL(13,2)),0) + IFNULL(CAST(LS_PROPOSED_BUDGET_OOE AS DECIMAL(13,2)),0) + IFNULL(CAST(LS_INDIRECT_COST AS DECIMAL(13,2)),0) + IFNULL(CAST(LS_OVERSEAS_TRAVEL AS DECIMAL(13,2)),0) +
			IFNULL(CAST(LS_RESEARCH_SCHOLARSHIP AS DECIMAL(13,2)),0) + IFNULL(CAST(LS_THIRD_STREAM_FUNDING AS DECIMAL(13,2)),0) + IFNULL(CAST(LS_DELIVERABLES AS DECIMAL(13,2)),0);
			IF IFNULL(CAST(LS_PROPOSED_BUDGET_TOTAL AS DECIMAL(13,2)),0)<> LS_TOTAL_LINE_ITEM_COST THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME, ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_BUDGET, UPDATE_TIMESTAMP, UPDATE_USER)
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'PROPOSAL_BUDGET','TOTAL BUDGET COST IS NOT EQUAL TO LINE ITEM COST',concat('TOTAL_COST=',LS_PROPOSED_BUDGET_TOTAL,',TOTAL_LINE_ITEM_COST=',LS_TOTAL_LINE_ITEM_COST),'PREVALIDATION','N',NOW(),'quickstart');
				COMMIT;
			iterate INSERT_LOOP;
			END IF;
		END LOOP;
		CLOSE CUR_SEL_DATA;
	END;
END;
END
$$
DELIMITER ;
