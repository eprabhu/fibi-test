DELIMITER $$
CREATE  PROCEDURE `MIGRATION_AWARD_INTERNAL`(
av_id int
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID INT;
DECLARE LS_ERROR_MSG 		VARCHAR(1000);
DECLARE LS_PROJECT_ID 				VARCHAR(200);
DECLARE LS_PROJECT_TYPE 			VARCHAR(50);
DECLARE LS_PROJECT_STATUS 			VARCHAR(50);
DECLARE LS_PROJECT_TITLE 			VARCHAR(1000);
DECLARE LS_PROJECT_START_DATE 		VARCHAR(50);
DECLARE LS_PROJECT_END_DATE 		VARCHAR(50);
DECLARE LS_PROJECT_DURATION 		VARCHAR(50);
DECLARE LS_PROJECT_LEAD_UNIT 		VARCHAR(600);
DECLARE LS_DATE_OF_AWARD 			VARCHAR(50);
DECLARE LS_PROJECT_FUND_CENTRE 		VARCHAR(200);
DECLARE LS_PROJECT_FUND_CODE 		VARCHAR(200);
DECLARE LI_FLAG						INT;
DECLARE LS_AWARD_NUMBER				VARCHAR(12);
DECLARE LI_VERSION_AWARD_ID 				DECIMAL(22,0);
DECLARE LI_MASTER_AWARD_ID 				DECIMAL(22,0);
DECLARE LS_UNIT_NUMBER				VARCHAR(8);
DECLARE LS_AWARD_TYPE_CODE			VARCHAR(3);
DECLARE LS_PROP_ACTIVITY_TYPE_CODE	VARCHAR(3);
DECLARE LS_PROP_SPONSOR_CODE		VARCHAR(6);
DECLARE LS_PROP_SPONSOR_NAME		VARCHAR(200);
DECLARE LS_AWARD_STATUS_CODE		VARCHAR(3);
DECLARE LI_GRANT_HEADER_ID			INT(11);
DECLARE LS_DIRECT_NAME_OF_FUNDING_AGENCY	VARCHAR(200);
DECLARE LS_IS_THIS_RESULT_OF_NEW_AWARD		VARCHAR(10);
DECLARE LI_AWARD_NUMBER				VARCHAR(12);
DECLARE LI_AWARD_NUMBER_EXIST INT;
DECLARE LS_PROJECT_SYNOPSYS					LONGTEXT;
DECLARE LS_IS_THIS_PROJECT					VARCHAR(10);
DECLARE LS_LINKED_PROJECT_TITLE				VARCHAR(1000);
DECLARE LS_LINKED_PROJECT_ID				VARCHAR(50);
DECLARE LS_LINKED_PROJECT_STATUS 			VARCHAR(50);
DECLARE LS_LINKED_FUNDING_AGENCY			VARCHAR(500);
DECLARE LS_LINKED_TYPE_OF_FUNDING_AGENCY 	VARCHAR(500);
DECLARE LS_LINKED_NAME_OF_FUNDING_AGENCY 	VARCHAR(500);
DECLARE LS_LINKED_NAME_OF_FUNDING_SCHEME 	VARCHAR(500);
DECLARE LS_LINKED_EXTERNAL_PROJECT_ID 		VARCHAR(200);
DECLARE LS_TOTAL_CASH 				   		VARCHAR(50);
DECLARE LS_CASH					   			VARCHAR(50);
DECLARE LS_CONTRIBUTIONS			   		VARCHAR(50);
DECLARE LI_CUSTOM_DATA_ELEMENTS_ID			INT(11);
DECLARE LI_COLUMN_ID						INT(11);
DECLARE LI_COLUMN_VERSION_NUMBER			INT(11);
DECLARE LI_CUSTOM_DATA_ID					INT(11);
declare LS_REVIEW_COMMENT varchar(255);
declare LI_REVIEW_COMMENT_ID int;
declare ls_spl_review_id int(3);
declare LS_HUMAN_SUB  int(3);
declare LS_IRB_APPROVAL_NUMBER varchar(500);
DECLARE LS_SOCIETAL_CHALLENGE_AREA VARCHAR(500);
declare ls_CHALLENGE_AREA_CODE varchar(500);
DECLARE LS_SPLITTED_SOCIETAL_CHALLENGE_AREA varchar(1000);
DECLARE LI_END_LENGTH int;
DECLARE LI_START_LENGTH int;
declare LI_RESRCH_AREA_ID int;
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'EXCEPTION','PROJECT',concat(LS_ERROR_MSG, STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y')),'CREATION',UTC_TIMESTAMP(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			PROJECT_ID,
			PROJECT_TYPE,
			PROJECT_STATUS,
			PROJECT_TITLE,
			PROJECT_START_DATE,
			PROJECT_END_DATE,
			PROJECT_DURATION,
			PROJECT_LEAD_UNIT,
			DATE_OF_AWARD,
			PROJECT_FUND_CENTRE,
			PROJECT_FUND_CODE,
			PROJECT_SYNOPSYS,
			IS_THIS_PROJECT,
			LINKED_PROJECT_TITLE,
			LINKED_PROJECT_ID,
			LINKED_PROJECT_STATUS,
			LINKED_FUNDING_AGENCY,
			LINKED_TYPE_OF_FUNDING_AGENCY,
			LINKED_NAME_OF_FUNDING_AGENCY,
			LINKED_NAME_OF_FUNDING_SCHEME,
			LINKED_EXTERNAL_PROJECT_ID,
			TOTAL_CASH,
			CASH,
			CONTRIBUTIONS,
			REVIEW_COMMENT,
			IRB_APPROVAL_NUMBER,
			SOCIETAL_CHALLENGE_AREA
			FROM MIGRATION_AWARD_INTERNAL_00_17
            where validation_status = 'VALID';
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
								LS_PROJECT_ID,
								LS_PROJECT_TYPE,
								LS_PROJECT_STATUS,
								LS_PROJECT_TITLE,
								LS_PROJECT_START_DATE,
								LS_PROJECT_END_DATE,
								LS_PROJECT_DURATION,
								LS_PROJECT_LEAD_UNIT,
								LS_DATE_OF_AWARD,
								LS_PROJECT_FUND_CENTRE,
								LS_PROJECT_FUND_CODE,
								LS_PROJECT_SYNOPSYS,
								LS_IS_THIS_PROJECT,
								LS_LINKED_PROJECT_TITLE,
								LS_LINKED_PROJECT_ID,
								LS_LINKED_PROJECT_STATUS,
								LS_LINKED_FUNDING_AGENCY,
								LS_LINKED_TYPE_OF_FUNDING_AGENCY,
								LS_LINKED_NAME_OF_FUNDING_AGENCY,
								LS_LINKED_NAME_OF_FUNDING_SCHEME,
								LS_LINKED_EXTERNAL_PROJECT_ID,
								LS_TOTAL_CASH,
								LS_CASH,
								LS_CONTRIBUTIONS,
								LS_REVIEW_COMMENT,
								LS_IRB_APPROVAL_NUMBER,
								LS_SOCIETAL_CHALLENGE_AREA;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		IF UPPER(TRIM(LS_PROJECT_TYPE)) = 'GRANT' THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM EPS_PROPOSAL
			WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_PROJECT_ID));
			IF LI_FLAG > 0 THEN
				SELECT ACTIVITY_TYPE_CODE,SPONSOR_CODE,GRANT_HEADER_ID
				INTO LS_PROP_ACTIVITY_TYPE_CODE,LS_PROP_SPONSOR_CODE,LI_GRANT_HEADER_ID
				FROM EPS_PROPOSAL
				WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_PROJECT_ID));
				SELECT SPONSOR_NAME INTO LS_PROP_SPONSOR_NAME FROM SPONSOR WHERE SPONSOR_CODE = LS_PROP_SPONSOR_CODE;
			ELSE
				SET LS_PROP_ACTIVITY_TYPE_CODE = 10;
				SELECT COUNT(1) INTO LI_FLAG
				FROM SPONSOR WHERE UPPER(TRIM(SPONSOR_NAME)) = UPPER(TRIM(LS_LINKED_NAME_OF_FUNDING_AGENCY));
				IF LI_FLAG > 0 THEN
					SELECT SPONSOR_CODE INTO LS_PROP_SPONSOR_CODE
					FROM SPONSOR WHERE UPPER(TRIM(SPONSOR_NAME)) = UPPER(TRIM(LS_LINKED_NAME_OF_FUNDING_AGENCY));
				END IF;
			END IF;
		ELSEIF UPPER(TRIM(LS_PROJECT_TYPE)) = 'DIRECT ENGAGEMENT' THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM SPONSOR WHERE UPPER(TRIM(SPONSOR_NAME)) = UPPER(TRIM(LS_LINKED_NAME_OF_FUNDING_AGENCY));
			IF LI_FLAG > 0 THEN
				SELECT SPONSOR_CODE INTO LS_PROP_SPONSOR_CODE
				FROM SPONSOR WHERE UPPER(TRIM(SPONSOR_NAME)) = UPPER(TRIM(LS_LINKED_NAME_OF_FUNDING_AGENCY));
			END IF;
			SET LS_PROP_ACTIVITY_TYPE_CODE = 10;
		END IF;
		IF LS_PROP_SPONSOR_CODE IS NULL THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','NAME_OF_FUNDING_AGENCY DOES NOT EXIST',LS_PROP_SPONSOR_CODE,'CREATION','N',UTC_TIMESTAMP(),'quickstart');
				COMMIT;
			ITERATE INSERT_LOOP;
		END IF;
		IF LS_PROJECT_TITLE IS NULL OR LS_PROJECT_TITLE = '' THEN
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','TITLE IS NULL',LS_PROJECT_TITLE,'CREATION','N',UTC_TIMESTAMP(),'quickstart');
				COMMIT;
			ITERATE INSERT_LOOP;
		END IF;
		IF LS_PROJECT_STATUS IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM AWARD_STATUS
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_STATUS));
			IF LI_FLAG > 0 THEN
				SELECT STATUS_CODE INTO LS_AWARD_STATUS_CODE
				FROM AWARD_STATUS
				WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_STATUS));
			ELSE
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT_STATUS DOES NOT EXIST',LS_PROJECT_STATUS,'CREATION','N',UTC_TIMESTAMP(),'quickstart');
				COMMIT;
				ITERATE INSERT_LOOP;
			END IF;
		ELSE
			ITERATE INSERT_LOOP;
		END IF;
		IF LS_PROJECT_LEAD_UNIT IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM UNIT
			WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROJECT_LEAD_UNIT));
			IF LI_FLAG > 0 THEN
				SELECT UNIT_NUMBER INTO LS_UNIT_NUMBER
				FROM UNIT
				WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROJECT_LEAD_UNIT));
			ELSE
				SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
				INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID, FILE_NAME,ERROR_MESSAGE,VALUE,
												VALIDATION_TYPE,CAN_CREATE_AWARD, UPDATE_TIMESTAMP, UPDATE_USER
											   )
				VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'PROJECT','PROJECT LEADUNIT DOES NOT EXIST',LS_PROJECT_LEAD_UNIT,'CREATION','N',UTC_TIMESTAMP(),'quickstart');
				COMMIT;
				ITERATE INSERT_LOOP;
			END IF;
		ELSE
			ITERATE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM AWARD_TYPE WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_TYPE));
		IF LI_FLAG > 0 THEN
			SELECT AWARD_TYPE_CODE INTO LS_AWARD_TYPE_CODE
			FROM AWARD_TYPE WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_TYPE));
		END IF;
		IF ( IFNULL(TRIM(LS_PROJECT_START_DATE),'')  = '' OR STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y') IS NULL ) THEN
			ITERATE INSERT_LOOP;
		END IF;
		IF ( IFNULL(TRIM(LS_PROJECT_END_DATE),'') = '' OR STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y') IS NULL ) THEN
			ITERATE INSERT_LOOP;
		END IF;
		IF (  STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y') IS NOT NULL AND TRIM(LS_PROJECT_START_DATE) <> ''
				      AND STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y') IS NOT NULL AND TRIM(LS_PROJECT_END_DATE) <> ''
					  AND STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y') > STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y') )THEN
			ITERATE INSERT_LOOP;
		END IF;
		SELECT AWARD_ID INTO LI_VERSION_AWARD_ID FROM MIGRATION_ID_GENERATOR;
		SELECT NEXT_VAL INTO LI_MASTER_AWARD_ID FROM AWARD_ID_GENERATOR;
		SELECT AWARD_NUMBER INTO LI_AWARD_NUMBER FROM MIGRATION_ID_GENERATOR;
		SELECT CONCAT(LPAD(AWARD_NUMBER, 6, "0"),'-00001') INTO LS_AWARD_NUMBER FROM MIGRATION_ID_GENERATOR;
		select COUNT(*) into LI_AWARD_NUMBER_EXIST from AWARD where AWARD_NUMBER in (LS_AWARD_NUMBER);
		IF LI_AWARD_NUMBER_EXIST > 0 THEN
			SELECT AWARD_NUMBER INTO LI_AWARD_NUMBER FROM AWARD_NEXTVALUE;
			SELECT CONCAT(LPAD((LI_AWARD_NUMBER), 6, "0"),'-00001') INTO LS_AWARD_NUMBER FROM DUAL;
			UPDATE AWARD_NEXTVALUE set AWARD_NUMBER = LI_AWARD_NUMBER+1;
		END IF;
		INSERT INTO AWARD
		(
		AWARD_ID,
		AWARD_NUMBER,
		SEQUENCE_NUMBER,
		ACCOUNT_NUMBER,
		LEAD_UNIT_NUMBER,
		TITLE,
		AWARD_TYPE_CODE,
		ACTIVITY_TYPE_CODE,
		ACCOUNT_TYPE_CODE,
		STATUS_CODE,
		SPONSOR_CODE,
		BEGIN_DATE,
		FINAL_EXPIRATION_DATE,
		AWARD_SEQUENCE_STATUS,
		AWARD_EFFECTIVE_DATE,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		IS_LATEST,
		CREATE_TIMESTAMP,
		CREATE_USER,
		WORKFLOW_AWARD_STATUS_CODE,
		AWARD_DOCUMENT_TYPE_CODE,
		GRANT_HEADER_ID,
		SUBMIT_USER,
		SUBMISSION_DATE,
		DURATION,
		FUND_CENTER	 ,
		FUND_CENTRE
		)
		VALUES
		(LI_VERSION_AWARD_ID,
		LS_AWARD_NUMBER,
		1,
		LS_PROJECT_FUND_CODE,
		LS_UNIT_NUMBER,
		TRIM(LS_PROJECT_TITLE),
		LS_AWARD_TYPE_CODE,
		LS_PROP_ACTIVITY_TYPE_CODE,
		NULL,
		LS_AWARD_STATUS_CODE,
		LS_PROP_SPONSOR_CODE,
		 STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y'),
		STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y'),
		'ARCHIVE',
		 STR_TO_DATE(LS_DATE_OF_AWARD,'%d/%m/%Y'),
		UTC_TIMESTAMP(),
		'quickstart',
		'N',
		UTC_TIMESTAMP(),
		'quickstart',
		3,
		1,
		LI_GRANT_HEADER_ID,
		'quickstart',
		UTC_TIMESTAMP(),
		LS_PROJECT_DURATION,
		LS_PROJECT_FUND_CENTRE,
		LS_PROJECT_FUND_CODE
		);
		INSERT INTO AWARD
		(
		AWARD_ID,
		AWARD_NUMBER,
		SEQUENCE_NUMBER,
		ACCOUNT_NUMBER,
		LEAD_UNIT_NUMBER,
		TITLE,
		AWARD_TYPE_CODE,
		ACTIVITY_TYPE_CODE,
		ACCOUNT_TYPE_CODE,
		STATUS_CODE,
		SPONSOR_CODE,
		BEGIN_DATE,
		FINAL_EXPIRATION_DATE,
		AWARD_SEQUENCE_STATUS,
		AWARD_EFFECTIVE_DATE,
		UPDATE_TIMESTAMP,
		UPDATE_USER,
		IS_LATEST,
		CREATE_TIMESTAMP,
		CREATE_USER,
		WORKFLOW_AWARD_STATUS_CODE,
		AWARD_DOCUMENT_TYPE_CODE,
		GRANT_HEADER_ID,
		SUBMIT_USER,
		SUBMISSION_DATE,
		DURATION,
		FUND_CENTER	 ,
		FUND_CENTRE
		)
		VALUES
		(LI_MASTER_AWARD_ID,
		LS_AWARD_NUMBER,
		0,
		LS_PROJECT_FUND_CODE,
		LS_UNIT_NUMBER,
		TRIM(LS_PROJECT_TITLE),
		LS_AWARD_TYPE_CODE,
		LS_PROP_ACTIVITY_TYPE_CODE,
		NULL,
		LS_AWARD_STATUS_CODE,
		LS_PROP_SPONSOR_CODE,
		 STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y'),
		 STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y'),
		'ACTIVE',
		  STR_TO_DATE(LS_DATE_OF_AWARD,'%d/%m/%Y'),
		UTC_TIMESTAMP(),
		'quickstart',
		'Y',
		NULL,
		NULL,
		3,
		0,
		LI_GRANT_HEADER_ID,
		'quickstart',
		UTC_TIMESTAMP(),
		LS_PROJECT_DURATION,
		LS_PROJECT_FUND_CENTRE,
		LS_PROJECT_FUND_CODE
		);
		UPDATE MIGRATION_AWARD_INTERNAL_00_17 SET VERSION_AWARD_ID = LI_VERSION_AWARD_ID, MASTER_AWARD_ID = LI_MASTER_AWARD_ID, AWARD_NUMBER = LS_AWARD_NUMBER, VALIDATION_STATUS = 'SUCCESS'
		WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID));
		UPDATE MIGRATION_AWARD_BUDGET_INTERNAL_00_17 SET VERSION_AWARD_ID = LI_VERSION_AWARD_ID, MASTER_AWARD_ID = LI_MASTER_AWARD_ID, AWARD_NUMBER = LS_AWARD_NUMBER
		WHERE UPPER(TRIM(PROJECT_ID)) = UPPER(TRIM(LS_PROJECT_ID));
		IF UPPER(TRIM(LS_PROJECT_TYPE)) = 'GRANT' THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM EPS_PROPOSAL
			WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_PROJECT_ID));
			IF LI_FLAG > 0 THEN
				UPDATE MIGRATION_AWARD_INTERNAL_00_17 SET CAN_CREATE_IP = 'Y'
				WHERE PROJECT_ID = LS_PROJECT_ID;
			END IF;
		END IF;
		UPDATE MIGRATION_ID_GENERATOR SET AWARD_NUMBER = CAST(LI_AWARD_NUMBER AS unsigned) +1;
		if length(trim(LS_IRB_APPROVAL_NUMBER)) > 0 then
				  SELECT COUNT(1) INTO LI_FLAG FROM special_review
					where upper(trim(DESCRIPTION)) = upper(trim('Human Subject'));
					if LI_FLAG = 1 then
				  select SPECIAL_REVIEW_CODE into LS_HUMAN_SUB from special_review
				  where upper(trim(DESCRIPTION)) = upper(trim('Human Subject'));
				SELECT IFNULL(MAX(AWARD_SPECIAL_REVIEW_ID),0)+1 INTO LS_SPL_REVIEW_ID FROM AWARD_SPECIAL_REVIEW;
					INSERT INTO AWARD_SPECIAL_REVIEW
					(
					AWARD_SPECIAL_REVIEW_ID,
					AWARD_ID,
					AWARD_NUMBER,
					SEQUENCE_NUMBER,
					 SPECIAL_REVIEW_CODE,
					 COMMENTS,
					 UPDATE_TIMESTAMP,
					 UPDATE_USER
					)
					VALUES
					(
					LS_SPL_REVIEW_ID,
					LI_VERSION_AWARD_ID,
					LS_AWARD_NUMBER,
					1,
					LS_HUMAN_SUB,
					LS_IRB_APPROVAL_NUMBER,
					UTC_TIMESTAMP(),
					'quickstart'
					);
					INSERT INTO AWARD_SPECIAL_REVIEW
					(
					AWARD_SPECIAL_REVIEW_ID,
					AWARD_ID,
					AWARD_NUMBER,
					SEQUENCE_NUMBER,
					 SPECIAL_REVIEW_CODE,
					 COMMENTS,
					 UPDATE_TIMESTAMP,
					 UPDATE_USER
					)
					VALUES
					(
					LS_SPL_REVIEW_ID + 1,
					LI_MASTER_AWARD_ID,
					LS_AWARD_NUMBER,
					0,
					LS_HUMAN_SUB,
					LS_IRB_APPROVAL_NUMBER,
					UTC_TIMESTAMP(),
					'quickstart'
					);
			end if;
		end if;
		IF LS_IS_THIS_PROJECT IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM CUSTOM_DATA_ELEMENTS
			WHERE TRIM(COLUMN_LABEL) = 'Is this project a result of a previously awarded research project?'
			AND IS_LATEST_VERSION = 'Y';
			IF LI_FLAG > 0 THEN
			SELECT CUSTOM_DATA_ELEMENTS_ID,COLUMN_ID,COLUMN_VERSION_NUMBER
			INTO LI_CUSTOM_DATA_ELEMENTS_ID,LI_COLUMN_ID,LI_COLUMN_VERSION_NUMBER
			FROM CUSTOM_DATA_ELEMENTS
			WHERE TRIM(COLUMN_LABEL) = 'Is this project a result of a previously awarded research project?'
			AND IS_LATEST_VERSION = 'Y';
			SELECT IFNULL(MAX(CUSTOM_DATA_ID),0)+1 INTO LI_CUSTOM_DATA_ID FROM CUSTOM_DATA;
			INSERT INTO CUSTOM_DATA
			(
			 CUSTOM_DATA_ID,
			 CUSTOM_DATA_ELEMENTS_ID,
			 MODULE_ITEM_CODE,
			 MODULE_ITEM_KEY,
			 MODULE_SUB_ITEM_CODE,
			 MODULE_SUB_ITEM_KEY,
			 UPDATE_TIMESTAMP,
			 UPDATE_USER,
			 VALUE,
			 COLUMN_ID,
			 COLUMN_VERSION_NUMBER
			 )
			 VALUES
			 (
			 LI_CUSTOM_DATA_ID,
			 LI_CUSTOM_DATA_ELEMENTS_ID,
			 1,
			 LI_VERSION_AWARD_ID,
			 0,
			 0,
			 UTC_TIMESTAMP(),
			 'quickstart',
			 LS_IS_THIS_PROJECT,
			 LI_COLUMN_ID,
			 LI_COLUMN_VERSION_NUMBER
			 );
			 INSERT INTO CUSTOM_DATA
			(
			 CUSTOM_DATA_ID,
			 CUSTOM_DATA_ELEMENTS_ID,
			 MODULE_ITEM_CODE,
			 MODULE_ITEM_KEY,
			 MODULE_SUB_ITEM_CODE,
			 MODULE_SUB_ITEM_KEY,
			 UPDATE_TIMESTAMP,
			 UPDATE_USER,
			 VALUE,
			 COLUMN_ID,
			 COLUMN_VERSION_NUMBER
			 )
			 VALUES
			 (
			 LI_CUSTOM_DATA_ID+1,
			 LI_CUSTOM_DATA_ELEMENTS_ID,
			 1,
			 LI_MASTER_AWARD_ID,
			 0,
			 0,
			 UTC_TIMESTAMP(),
			 'quickstart',
			 LS_IS_THIS_PROJECT,
			 LI_COLUMN_ID,
			 LI_COLUMN_VERSION_NUMBER
			 );
			END IF;
		 END IF;
		IF LS_LINKED_PROJECT_ID IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM CUSTOM_DATA_ELEMENTS
			WHERE TRIM(COLUMN_LABEL) = 'Project ID'
			AND IS_LATEST_VERSION = 'Y';
			IF LI_FLAG > 0 THEN
			SELECT CUSTOM_DATA_ELEMENTS_ID,COLUMN_ID,COLUMN_VERSION_NUMBER
			INTO LI_CUSTOM_DATA_ELEMENTS_ID,LI_COLUMN_ID,LI_COLUMN_VERSION_NUMBER
			FROM CUSTOM_DATA_ELEMENTS
			WHERE TRIM(COLUMN_LABEL) = 'Project ID'
			AND IS_LATEST_VERSION = 'Y';
			SELECT IFNULL(MAX(CUSTOM_DATA_ID),0)+1 INTO LI_CUSTOM_DATA_ID FROM CUSTOM_DATA;
			INSERT INTO CUSTOM_DATA
			(
			 CUSTOM_DATA_ID,
			 CUSTOM_DATA_ELEMENTS_ID,
			 MODULE_ITEM_CODE,
			 MODULE_ITEM_KEY,
			 MODULE_SUB_ITEM_CODE,
