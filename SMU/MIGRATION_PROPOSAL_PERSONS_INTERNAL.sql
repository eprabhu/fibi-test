DELIMITER $$
CREATE  PROCEDURE `MIGRATION_PROPOSAL_PERSONS_INTERNAL`(
av_id int
)
BEGIN
DECLARE LS_APPLICATION_ID 				VARCHAR(50);
DECLARE LS_PROJECT_TEAM_MEMBER_TYPE 	VARCHAR(50);
DECLARE LS_NT_LOGIN_ID 					VARCHAR(200);
DECLARE LS_PROJECT_TEAM_NAME 			VARCHAR(100);
DECLARE LS_PROJECT_TEAM_DESIGNATION 	VARCHAR(3000);
DECLARE LS_SEQUENCE_PROJECT_TEAM 		VARCHAR(100);
DECLARE LS_PROJECT_TEAM_ROLE 			VARCHAR(100);
DECLARE LS_PROJECT_TEAM_PERCENT_EFFORT 	VARCHAR(20);
DECLARE LS_PROJECT_TEAM_DEPARTMENT 		VARCHAR(1000);
DECLARE LS_PROJECT_TEAM_ORGANISATION 	VARCHAR(1000);
DECLARE LS_PROJECT_TEAM_COUNTRY 		VARCHAR(100);
DECLARE LS_PROJECT_TEAM_CV 				VARCHAR(100);
DECLARE LS_PROJECT_TEAM_TRACK 			VARCHAR(100);
DECLARE LI_FLAG							INT;
DECLARE LI_SEQ_ERROR_LOG_ID 			INT;
DECLARE LS_ERROR_MSG 					VARCHAR(1000);
DECLARE LI_PROPOSAL_PERSON_ID			INT;
DECLARE LS_PERSON_ID					VARCHAR(40);
DECLARE LI_ROLODEX_ID					INT(11);
DECLARE LI_PROP_PERSON_ROLE_ID			INT(3);
DECLARE LI_PROPOSAL_ID					INT(11);
DECLARE LS_EMAIL_ADDRESS				VARCHAR(200);
DECLARE LS_UNIT_NUMBER					VARCHAR(8);
DECLARE LS_UNIT_NAME					VARCHAR(500);
DECLARE LI_PROP_PERSON_UNIT_ID			INT;
DECLARE LS_FULL_NAME					VARCHAR(100);
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
	BEGIN
		GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
		 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
		SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
		SELECT @full_error INTO LS_ERROR_MSG;
		SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
		INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
		VALUES(LI_SEQ_ERROR_LOG_ID,LS_APPLICATION_ID,'EXCEPTION','PROPOSAL_PERSON',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
		COMMIT;
	END;
	BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT
			APPLICATION_ID,
			PROJECT_TEAM_MEMBER_TYPE,
			NT_LOGIN_ID,
			PROJECT_TEAM_NAME,
			PROJECT_TEAM_DESIGNATION,
			SEQUENCE_PROJECT_TEAM,
			PROJECT_TEAM_ROLE,
			PROJECT_TEAM_PERCENT_EFFORT,
			PROJECT_TEAM_DEPARTMENT,
			PROJECT_TEAM_ORGANISATION,
			PROJECT_TEAM_COUNTRY,
			PROJECT_TEAM_CV,
			PROJECT_TEAM_TRACK
		FROM MIGRATION_PROPOSAL_PERSONS_INTERNAL_00_17
		where validation_status = 'VALID'
		ORDER BY APPLICATION_ID,SEQUENCE_PROJECT_TEAM;
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP: LOOP
		FETCH CUR_SEL_DATA INTO
		LS_APPLICATION_ID,
		LS_PROJECT_TEAM_MEMBER_TYPE,
		LS_NT_LOGIN_ID,
		LS_PROJECT_TEAM_NAME,
		LS_PROJECT_TEAM_DESIGNATION,
		LS_SEQUENCE_PROJECT_TEAM,
		LS_PROJECT_TEAM_ROLE,
		LS_PROJECT_TEAM_PERCENT_EFFORT,
		LS_PROJECT_TEAM_DEPARTMENT,
		LS_PROJECT_TEAM_ORGANISATION,
		LS_PROJECT_TEAM_COUNTRY,
		LS_PROJECT_TEAM_CV,
		LS_PROJECT_TEAM_TRACK;
		IF DONE1 THEN
			LEAVE INSERT_LOOP;
		END IF;
		SELECT COUNT(1) INTO LI_FLAG
		FROM MIGRATION_PROPOSAL_INTERNAL_00_17
		WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_APPLICATION_ID));
		IF LI_FLAG = 0 THEN
			ITERATE INSERT_LOOP;
		ELSE
			SELECT PROPOSAL_ID INTO LI_PROPOSAL_ID FROM MIGRATION_PROPOSAL_INTERNAL_00_17
			WHERE UPPER(TRIM(APPLICATION_ID)) = UPPER(TRIM(LS_APPLICATION_ID));
		END IF;
		SELECT COUNT(1) INTO LI_FLAG FROM EPS_PROP_PERSON_ROLE
		WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_TEAM_ROLE));
		IF LI_FLAG > 0 THEN
			SELECT PROP_PERSON_ROLE_ID INTO LI_PROP_PERSON_ROLE_ID FROM EPS_PROP_PERSON_ROLE
			WHERE UPPER(TRIM(DESCRIPTION)) = UPPER(TRIM(LS_PROJECT_TEAM_ROLE));
			IF UPPER(TRIM(LS_PROJECT_TEAM_MEMBER_TYPE)) = 'SMU EMPLOYEE' THEN
				SELECT COUNT(1) INTO LI_FLAG
				FROM PERSON WHERE UPPER(TRIM(USER_NAME)) = UPPER(TRIM(LS_NT_LOGIN_ID));
				IF LI_FLAG > 0 THEN
					SELECT PERSON_ID,EMAIL_ADDRESS,FULL_NAME INTO LS_PERSON_ID,LS_EMAIL_ADDRESS, LS_FULL_NAME
					FROM PERSON WHERE UPPER(TRIM(USER_NAME)) = UPPER(TRIM(LS_NT_LOGIN_ID));
				END IF;
			ELSEIF UPPER(TRIM(LS_PROJECT_TEAM_MEMBER_TYPE)) = 'NON-SMU EMPLOYEE' THEN
				SELECT COUNT(1) INTO LI_FLAG FROM ROLODEX
				WHERE UPPER(TRIM(FULL_NAME))  COLLATE utf8mb4_general_ci  = UPPER(TRIM(LS_PROJECT_TEAM_NAME));
				IF LI_FLAG > 0 THEN
					SELECT ROLODEX_ID,EMAIL_ADDRESS,FULL_NAME INTO LI_ROLODEX_ID,LS_EMAIL_ADDRESS,LS_FULL_NAME FROM ROLODEX
					WHERE UPPER(TRIM(FULL_NAME)) = UPPER(TRIM(LS_PROJECT_TEAM_NAME));
				END IF;
			END IF;
			SELECT IFNULL(MAX(PROPOSAL_PERSON_ID),0)+1 INTO LI_PROPOSAL_PERSON_ID  FROM EPS_PROPOSAL_PERSONS;
			INSERT INTO EPS_PROPOSAL_PERSONS(
			PROPOSAL_PERSON_ID,
			FULL_NAME,
			PERSON_ID,
			PROP_PERSON_ROLE_ID,
			ROLODEX_ID,
			UPDATE_TIMESTAMP,
			UPDATE_USER,
			PROPOSAL_ID,
			PERCENTAGE_OF_EFFORT,
			EMAIL_ADDRESS,
			PI_FLAG,
			DESIGNATION,
			IS_MULTI_PI
			)
			VALUES
			(
			LI_PROPOSAL_PERSON_ID,
			LS_FULL_NAME,
			CASE WHEN UPPER(TRIM(LS_PROJECT_TEAM_MEMBER_TYPE)) = 'SMU EMPLOYEE' THEN LS_PERSON_ID
			ELSE NULL END,
			LI_PROP_PERSON_ROLE_ID,
			CASE WHEN UPPER(TRIM(LS_PROJECT_TEAM_MEMBER_TYPE)) = 'NON-SMU EMPLOYEE' THEN LI_ROLODEX_ID
			ELSE NULL END,
			NOW(),
			'quickstart',
			LI_PROPOSAL_ID,
			CAST(LS_PROJECT_TEAM_PERCENT_EFFORT AS DECIMAL(5,2)),
			LS_EMAIL_ADDRESS,
			CASE WHEN LI_PROP_PERSON_ROLE_ID = 3 THEN 'Y'
			ELSE
			'N'
			END,
			LS_PROJECT_TEAM_DESIGNATION,
			CASE WHEN LI_PROP_PERSON_ROLE_ID = 9 THEN 'Y'
			ELSE
			'N'
			END
			);
		IF UPPER(TRIM(LS_PROJECT_TEAM_MEMBER_TYPE)) = 'SMU EMPLOYEE' THEN
		IF LS_PROJECT_TEAM_DEPARTMENT IS NOT NULL THEN
			SELECT COUNT(1) INTO LI_FLAG
			FROM UNIT
			WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROJECT_TEAM_DEPARTMENT));
			IF LI_FLAG > 0 THEN
				SELECT UNIT_NUMBER,UNIT_NAME INTO LS_UNIT_NUMBER,LS_UNIT_NAME
				FROM UNIT
				WHERE UPPER(TRIM(UNIT_NAME)) = UPPER(TRIM(LS_PROJECT_TEAM_DEPARTMENT));
				SELECT IFNULL(MAX(PROP_PERSON_UNIT_ID),0)+1 INTO LI_PROP_PERSON_UNIT_ID FROM EPS_PROP_PERSON_UNITS;
				INSERT INTO EPS_PROP_PERSON_UNITS(
				PROP_PERSON_UNIT_ID,
				PROPOSAL_ID,
				PROPOSAL_PERSON_ID,
				LEAD_UNIT_FLAG,
				UNIT_NUMBER,
				UPDATE_TIMESTAMP, UPDATE_USER)
				VALUES(
				LI_PROP_PERSON_UNIT_ID,
				LI_PROPOSAL_ID,
				LI_PROPOSAL_PERSON_ID,
				CASE WHEN LI_PROP_PERSON_ROLE_ID = 3 THEN 'Y'
				ELSE
				'N'
				END,
				LS_UNIT_NUMBER,
				NOW(),
				'quickstart'
				);
			END IF;
	END IF;
   END IF;
END IF;
		SET LS_APPLICATION_ID 				= NULL;
		SET LS_PROJECT_TEAM_MEMBER_TYPE 	= NULL;
		SET LS_NT_LOGIN_ID 					= NULL;
		SET LS_PROJECT_TEAM_NAME 			= NULL;
		SET LS_PROJECT_TEAM_DESIGNATION 	= NULL;
		SET LS_SEQUENCE_PROJECT_TEAM 		= NULL;
		SET LS_PROJECT_TEAM_ROLE 			= NULL;
		SET LS_PROJECT_TEAM_PERCENT_EFFORT 	= NULL;
		SET LS_PROJECT_TEAM_DEPARTMENT 		= NULL;
		SET LS_PROJECT_TEAM_ORGANISATION 	= NULL;
		SET LS_PROJECT_TEAM_COUNTRY 		= NULL;
		SET LS_PROJECT_TEAM_CV 				= NULL;
		SET LS_PROJECT_TEAM_TRACK 			= NULL;
		SET LI_FLAG							= NULL;
		SET LS_ERROR_MSG 					= NULL;
		SET LI_PROPOSAL_PERSON_ID			= NULL;
		SET LS_PERSON_ID					= NULL;
		SET LI_ROLODEX_ID					= NULL;
		SET LI_PROP_PERSON_ROLE_ID			= NULL;
		SET LI_PROPOSAL_ID					= NULL;
		SET LS_EMAIL_ADDRESS				= NULL;
		SET LS_UNIT_NUMBER					= NULL;
		SET LS_UNIT_NAME					= NULL;
		SET LI_PROP_PERSON_UNIT_ID			= NULL;
		SET LS_FULL_NAME					= NULL;
		END LOOP;
		CLOSE CUR_SEL_DATA;
		COMMIT;
		SET SQL_SAFE_UPDATES = 0;
		UPDATE EPS_PROP_PERSON_ID_GENERATOR SET NEXT_VAL = (SELECT MAX(PROPOSAL_PERSON_ID)+1 FROM EPS_PROPOSAL_PERSONS);
		UPDATE EPS_PROP_PERSON_UNIT_ID_GENERATOR SET NEXT_VAL = (SELECT MAX(PROP_PERSON_UNIT_ID)+1 FROM EPS_PROP_PERSON_UNITS);
	END;
END;
END
$$
DELIMITER ;
