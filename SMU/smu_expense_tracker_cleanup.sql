CREATE  PROCEDURE `smu_expense_tracker_cleanup`()
BEGIN
	set sql_safe_updates = 0;
		DELETE FROM AWARD_EXPENSE_DETAILS_EXT EXT
		WHERE EXISTS(SELECT 1 FROM EXPENSE_TRACKER_RT ETRT
							WHERE IFNULL(TRIM(UPPER(EXT.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(CASE WHEN ETRT.FUND = '' THEN NULL ELSE ETRT.FUND END)),'0'))
		AND EXISTS(SELECT 1 FROM  AWARD_EXPENSE_TRANSACTIONS AET
							  WHERE IFNULL(TRIM(UPPER(AET.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(EXT.ACCOUNT_NUMBER)),'0'))
		AND EXT.IS_FROM_SAP = 'Y';
		DELETE FROM AWARD_EXPENSE_DETAILS EXD
		WHERE EXISTS(SELECT 1 FROM EXPENSE_TRACKER_RT ETRT
							WHERE IFNULL(TRIM(UPPER(EXD.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(CASE WHEN ETRT.FUND = '' THEN NULL ELSE ETRT.FUND END)),'0'))
		AND EXISTS(SELECT 1 FROM  AWARD_EXPENSE_TRANSACTIONS AET
							  WHERE IFNULL(TRIM(UPPER(AET.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(EXD.ACCOUNT_NUMBER)),'0'));
		DELETE FROM AWARD_EXPENSE_HEADER AEH
		WHERE EXISTS(SELECT 1 FROM EXPENSE_TRACKER_RT ETRT
							WHERE IFNULL(TRIM(UPPER(AEH.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(CASE WHEN ETRT.FUND = '' THEN NULL ELSE ETRT.FUND END)),'0'))
		AND EXISTS(SELECT 1 FROM  AWARD_EXPENSE_TRANSACTIONS AET
							  WHERE IFNULL(TRIM(UPPER(AET.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(AEH.ACCOUNT_NUMBER)),'0'))
		AND NOT EXISTS(SELECT 1 FROM AWARD_EXPENSE_DETAILS_EXT EXT
						WHERE IFNULL(TRIM(UPPER(EXT.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(AEH.ACCOUNT_NUMBER)),'0')
						AND EXT.IS_FROM_SAP = 'N');
		DELETE FROM AWARD_EXPENSE_TRANSACTIONS AEXT
		WHERE EXISTS(SELECT 1 FROM EXPENSE_TRACKER_RT ETRT
							WHERE IFNULL(TRIM(UPPER(AEXT.ACCOUNT_NUMBER)),'0') = IFNULL(TRIM(UPPER(CASE WHEN ETRT.FUND = '' THEN NULL ELSE ETRT.FUND END)),'0'));
	set sql_safe_updates = 1;
END
$$
DELIMITER ;
