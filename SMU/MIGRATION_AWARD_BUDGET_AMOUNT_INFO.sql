CREATE  PROCEDURE `MIGRATION_AWARD_BUDGET_AMOUNT_INFO`(av_id int
)
BEGIN
DECLARE LI_SEQ_ERROR_LOG_ID 			INT;
DECLARE LS_ERROR_MSG 					VARCHAR(1000);
DECLARE LI_FLAG 						INT;
DECLARE LS_PROJECT_ID 					VARCHAR(50);
DECLARE LS_FUND_CENTRE					VARCHAR(50);
DECLARE LS_FUND_CODE					VARCHAR(50);
DECLARE LS_BUDGET_CATEGORY				VARCHAR(50);
DECLARE LS_BUDGET_LINE_ITEM				VARCHAR(50);
DECLARE LS_QUANTITY						VARCHAR(50);
DECLARE LS_IO_CODE						VARCHAR(50);
DECLARE LS_ORIGINAL_APPROVED_BUDGET		VARCHAR(50);
DECLARE LS_CURRENT_APPROVED_BUDGET		VARCHAR(50);
DECLARE LS_EXPENDITURE_TO_DATE			VARCHAR(50);
DECLARE LS_AMOUNT_REMAIN_BAL			VARCHAR(50);
DECLARE LS_UTILIZATION_RATE				VARCHAR(50);
DECLARE LI_AWARD_AMOUNT_TRANSACTION_ID      DECIMAL(12,0);
DECLARE LS_TRANSACTION_ID                   VARCHAR(20);
DECLARE LI_AWARD_ID							DECIMAL(22,0);
DECLARE LS_AWARD_NUMBER						VARCHAR(12);
DECLARE LI_AWARD_AMOUNT_INFO_ID				DECIMAL(22,0);
DECLARE LI_BUDGET_HEADER_ID					INT;
DECLARE LS_PROJECT_START_DATE 		DATETIME;
DECLARE LS_PROJECT_END_DATE 		DATETIME;
DECLARE LI_BUDGET_PERIOD_ID 		INT(12);
DECLARE LI_BUDGET_DETAILS_ID 		INT(12);
DECLARE LI_LINE_ITEM_NUMBER			INT(3);
DECLARE LS_BUDGET_CATEGORY_CODE 	VARCHAR(3);
DECLARE LS_COST_ELEMENT 			VARCHAR(500);
DECLARE LI_TOTAL_COST 				DECIMAL(13,2);
DECLARE LS_TOTAL_CASH				VARCHAR(50);
DECLARE LS_CASH						VARCHAR(50);
DECLARE LS_CONTRIBUTIONS			VARCHAR(50);
DECLARE LI_AWARD_COST_SHARE_ID		INT(12);
DECLARE LI_TOTAL_DIRECT_COST		DECIMAL(13,2);
DECLARE LI_DIRECT_COST				DECIMAL(13,2);
BEGIN
	DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
		BEGIN
			GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
			 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
			SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
			SELECT @full_error INTO LS_ERROR_MSG;
			SELECT IFNULL(MAX(MIGRATION_ERROR_LOG_ID),0)+1 INTO LI_SEQ_ERROR_LOG_ID FROM MIGRATION_ERROR_LOG;
			INSERT INTO MIGRATION_ERROR_LOG(MIGRATION_ERROR_LOG_ID, LEGACY_PROJECT_ID,ERROR_TYPE, FILE_NAME, ERROR_MESSAGE, VALIDATION_TYPE, UPDATE_TIMESTAMP, UPDATE_USER)
			VALUES(LI_SEQ_ERROR_LOG_ID,LS_PROJECT_ID,'EXCEPTION','PROJECT_BUDGET',LS_ERROR_MSG,'CREATION',NOW(),'quickstart');
			COMMIT;
		END;
		BEGIN
		DECLARE DONE1 INT DEFAULT FALSE;
		DECLARE CUR_SEL_DATA CURSOR FOR
		SELECT AWARD_ID,AWARD_NUMBER,TOTAL_CASH FROM MIGRATION_AWARD
		WHERE TOTAL_CASH IS NOT NULL
		AND AWARD_ID NOT IN (SELECT AWARD_ID FROM AWARD_AMOUNT_INFO)
		AND PROJECT_ID NOT IN(258,193,267,266,265,263,260,161,8,
										280,209,208,201,200,163,261,431,419,294,292,285,210,204,310);
		DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
		OPEN CUR_SEL_DATA;
		INSERT_LOOP1: LOOP
		FETCH CUR_SEL_DATA INTO
		LI_AWARD_ID,
		LS_AWARD_NUMBER,
		LS_TOTAL_CASH;
		IF DONE1 THEN
			LEAVE INSERT_LOOP1;
		END IF;
				SELECT IFNULL(MAX(AWARD_AMOUNT_TRANSACTION_ID),0)+1 INTO LI_AWARD_AMOUNT_TRANSACTION_ID
				FROM AWARD_AMOUNT_TRANSACTION;
				SET LS_TRANSACTION_ID = CONCAT(DATE_FORMAT(NOW(),'%y%d%m'), SUBSTRING(DATE_FORMAT(NOW(2),'%h%m%s%f'),1,5),LI_AWARD_ID);
				INSERT INTO AWARD_AMOUNT_TRANSACTION
				(
				 AWARD_AMOUNT_TRANSACTION_ID,
				 AWARD_NUMBER,
				 TRANSACTION_ID,
				 TRANSACTION_TYPE_CODE,
				 COMMENTS,
				 SOURCE_AWARD_NUMBER,
				 DESTINATION_AWARD_NUMBER,
				 UPDATE_TIMESTAMP,
				 UPDATE_USER,
				 FUNDED_PROPOSAL_ID,
				 NOTICE_DATE
				)
				VALUES
				(
				LI_AWARD_AMOUNT_TRANSACTION_ID,
				LS_AWARD_NUMBER,
				LS_TRANSACTION_ID,
				17,
				'Migrated Award',
				'EXTERNAL',
				LS_AWARD_NUMBER,
				NOW(),
				'quickstart',
				NULL,
				NULL
				);
				COMMIT;
				SELECT IFNULL(MAX(AWARD_AMOUNT_INFO_ID),0)+1 INTO LI_AWARD_AMOUNT_INFO_ID
				FROM AWARD_AMOUNT_INFO;
				INSERT INTO AWARD_AMOUNT_INFO(
				AWARD_AMOUNT_INFO_ID,
				AWARD_ID,
				AWARD_NUMBER,
				SEQUENCE_NUMBER,
				TRANSACTION_ID,
				UPDATE_TIMESTAMP,
				UPDATE_USER,
				ANTICIPATED_CHANGE,
				ANTICIPATED_CHANGE_DIRECT,
				ANTICIPATED_CHANGE_INDIRECT,
				OBLIGATED_CHANGE,
				OBLIGATED_CHANGE_DIRECT,
				OBLIGATED_CHANGE_INDIRECT,
				ANTICIPATED_TOTAL_DIRECT,
				ANTICIPATED_TOTAL_INDIRECT,
				ANTICIPATED_TOTAL_AMOUNT,
				OBLIGATED_TOTAL_DIRECT,
				OBLIGATED_TOTAL_INDIRECT,
				AMOUNT_OBLIGATED_TO_DATE,
				ANT_DISTRIBUTABLE_AMOUNT,
				OBLI_DISTRIBUTABLE_AMOUNT,
				FINAL_EXPIRATION_DATE,
				CURRENT_FUND_EFFECTIVE_DATE,
				OBLIGATION_EXPIRATION_DATE,
				TOTAL_COST_IN_CURRENCY,
				CURRENCY_CODE
				)
				VALUES(
				LI_AWARD_AMOUNT_INFO_ID,
				LI_AWARD_ID,
				LS_AWARD_NUMBER,
				1,
				LS_TRANSACTION_ID,
				NOW(),
				'quickstart',
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				0,
				0,
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				0,
				0,
				0,
				0,
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				0,
				0,
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				IFNULL(CAST(LS_TOTAL_CASH AS DECIMAL(13,2)),0),
				NOW(), -- DATE_FORMAT(STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
				NOW(), -- DATE_FORMAT(STR_TO_DATE(LS_PROJECT_START_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
				NOW(), -- DATE_FORMAT(STR_TO_DATE(LS_PROJECT_END_DATE,'%d/%m/%Y'),'%Y/%m/%d %h:%i:%s'),
				0,
				'SGD'
				);
				COMMIT;
			SET LI_AWARD_ID = NULL;
			SET LS_AWARD_NUMBER = NULL;
			SET LS_PROJECT_START_DATE = NULL;
			SET LS_PROJECT_END_DATE = NULL;
			SET LS_CASH = NULL;
			SET LS_CONTRIBUTIONS = NULL;
			SET LS_TOTAL_CASH = NULL;
			SET LS_PROJECT_ID = NULL;
			SET LS_FUND_CENTRE = NULL;
			SET LS_FUND_CODE = NULL;
			END LOOP;
			CLOSE CUR_SEL_DATA;
			UPDATE AWARD_AMOUNT_INFO_ID_GENERATOR SET NEXT_VAL = LI_AWARD_AMOUNT_INFO_ID + 1;
			UPDATE AWARD_AMOUNT_TRANSACTION_ID_GENERATOR  SET NEXT_VAL = LI_AWARD_AMOUNT_TRANSACTION_ID + 1;
			COMMIT;
		END;
END;
END
$$
