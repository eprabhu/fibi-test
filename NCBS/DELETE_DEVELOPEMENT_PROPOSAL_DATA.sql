BEGIN
DECLARE LI_PROPOSAL_ID  VARCHAR(100);
DECLARE LS_ERROR_MSG	VARCHAR(1000);
DECLARE LS_ERROR_FLAG  VARCHAR(10);
DECLARE LS_PROPOSAL_NUMBER VARCHAR(100);
DECLARE LS_TITLE VARCHAR(1000);
DECLARE EXIT HANDLER FOR SQLEXCEPTION
				BEGIN
					GET DIAGNOSTICS CONDITION 1 @sqlstate = RETURNED_SQLSTATE,
					 @errno = MYSQL_ERRNO, @msg = MESSAGE_TEXT;
					SET @full_error = CONCAT("ERROR ", @errno, " (", @sqlstate, "): ", @msg);
					SELECT @full_error INTO LS_ERROR_MSG;
					 SELECT LS_ERROR_MSG;
				END;
				BEGIN
					DECLARE DONE1 INT DEFAULT FALSE;
					DECLARE CUR_PROPOSAL_DATA CURSOR FOR
					SELECT PROPOSAL_ID, TITLE FROM EPS_PROPOSAL  WHERE PROPOSAL_ID  BETWEEN AV_PROPOSAL_ID_1 and AV_PROPOSAL_ID_2
                        ;
					DECLARE CONTINUE HANDLER FOR NOT FOUND SET DONE1 = TRUE;
					OPEN CUR_PROPOSAL_DATA;
					INSERT_PROPOSAL_LOOP: LOOP
					FETCH CUR_PROPOSAL_DATA INTO
					 LI_PROPOSAL_ID, LS_TITLE;
					IF DONE1 THEN
						LEAVE INSERT_PROPOSAL_LOOP;
					END IF;
						 DELETE from inbox where MODULE_ITEM_KEY in (LI_PROPOSAL_ID);
						DELETE FROM eps_prop_evaluation_score WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE from eps_prop_evalpanel_persons where PROPOSAL_EVALUATION_ID
						IN( select PROPOSAL_EVALUATION_ID from eps_proposal_evaluation_panel WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID) );
