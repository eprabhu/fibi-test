						SELECT BUDGET_DETAILS_ID FROM budget_detail WHERE BUDGET_PERIOD_ID IN(
						SELECT BUDGET_PERIOD_ID FROM BUDGET_PERIOD WHERE BUDGET_HEADER_ID IN(
						SELECT BUDGET_HEADER_ID FROM budget_header WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID)
						)));
