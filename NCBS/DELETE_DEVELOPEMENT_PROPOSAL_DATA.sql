						SELECT BUDGET_HEADER_ID FROM budget_header WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM quest_answer_attachment WHERE QUESTIONNAIRE_ANSWER_ID IN(
						SELECT QUESTIONNAIRE_ANS_HEADER_ID FROM quest_answer WHERE QUESTIONNAIRE_ANS_HEADER_ID IN (
						SELECT QUESTIONNAIRE_ANS_HEADER_ID FROM quest_answer_header WHERE MODULE_ITEM_KEY IN (LI_PROPOSAL_ID)));
						DELETE FROM quest_answer WHERE QUESTIONNAIRE_ANS_HEADER_ID IN (
						SELECT QUESTIONNAIRE_ANS_HEADER_ID FROM quest_answer_header WHERE MODULE_ITEM_KEY IN (LI_PROPOSAL_ID));
						DELETE FROM quest_table_answer WHERE QUESTIONNAIRE_ANS_HEADER_ID IN (
						SELECT QUESTIONNAIRE_ANS_HEADER_ID FROM quest_answer_header WHERE MODULE_ITEM_KEY IN (LI_PROPOSAL_ID));
