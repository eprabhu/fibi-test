						SELECT PROPOSAL_ID FROM EPS_PROPOSAL WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM eps_proposal_irb_protocol WHERE PROTOCOL_ID IN (
						SELECT PROPOSAL_ID FROM EPS_PROPOSAL WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM eps_proposal_kpi_criteria WHERE PROPOSAL_KPI_ID IN (
						SELECT PROPOSAL_KPI_ID FROM eps_proposal_kpi WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM eps_proposal_person_attachmnt WHERE PROPOSAL_PERSON_ID IN (
						SELECT PROPOSAL_PERSON_ID FROM eps_proposal_persons WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM eps_proposal_person_degree WHERE PROPOSAL_PERSON_ID IN (
						SELECT PROPOSAL_PERSON_ID FROM eps_proposal_persons WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM eps_proposal_rates WHERE BUDGET_HEADER_ID IN (
						SELECT BUDGET_HEADER_ID FROM budget_header WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID));
						DELETE FROM eps_proposal_keywords WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_kpi WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_ext WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_evaluation_panel WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_organization WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_milestone WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_person_roles WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_persons WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_project_team WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_resrch_areas WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_special_review WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM eps_proposal_sponsors WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID);
						DELETE FROM custom_data  where MODULE_ITEM_KEY IN (LI_PROPOSAL_ID)	;
						DELETE FROM budget_persons WHERE BUDGET_HEADER_ID IN(
						SELECT BUDGET_HEADER_ID FROM budget_header WHERE PROPOSAL_ID IN (LI_PROPOSAL_ID) );
